def quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def main() -> None:
    out = [HEADER]

    for slug, name, synonyms, has_side in NEW:
        array = "ARRAY[" + ", ".join(quote(s) for s in synonyms) + "]"
        out.append(
            "INSERT INTO catalog.part_kind (category_id, name, synonyms, has_side)\n"
            f"SELECT c.id, {quote(name)}, {array}, {str(has_side).lower()}\n"
            "  FROM catalog.part_category c\n"
            f" WHERE c.slug = {quote(slug)}\n"
            "ON CONFLICT DO NOTHING;")

    out.append("\n-- Синонимы к существующим эталонам: только те, которых там ещё нет.")
    for name, synonyms in EXTRA:
        array = "ARRAY[" + ", ".join(quote(s) for s in synonyms) + "]"
        out.append(
            "UPDATE catalog.part_kind\n"
            f"   SET synonyms = synonyms || (SELECT coalesce(array_agg(s), ARRAY[]::text[])\n"
            f"                                 FROM unnest({array}) AS s\n"
            "                                WHERE s <> ALL (synonyms))\n"
            f" WHERE name = {quote(name)};")

    names = ", ".join(quote(name) for _, name, _, _ in NEW)
    out.append(f"\n--rollback DELETE FROM catalog.part_kind WHERE name IN ({names});")

    target = pathlib.Path(__file__).parent.parent / "changelog" / "catalog" / "013-part-kinds-live2.sql"
    target.write_text("\n".join(out) + "\n", encoding="utf-8")

    synonym_count = sum(len(s) for _, _, s, _ in NEW) + sum(len(s) for _, s in EXTRA)
    print(f"эталонов: {len(NEW)}, синонимов: {synonym_count}, "
          f"не взято намеренно: {len(SKIPPED)}")
    print(f"записано: {target}")


if __name__ == "__main__":
    main()
