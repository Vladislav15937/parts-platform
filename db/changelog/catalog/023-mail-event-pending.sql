--comment Буфер отчётов оператора писем, пришедших раньше записи номера задания (задача 0192). Служебное.
--comment
--comment Зачем он нужен. Отправка идёт вне транзакции, и отчёт оператора о
--comment доставке может обогнать запись результата отправки: номера задания
--comment (provider_id) в mail_message ещё нет, отчёту не к чему привязаться.
--comment Оператор при этом получил 200 и повторять не станет, так что без
--comment буфера такой отчёт терялся бы навсегда, а письмо оставалось SENT.
--comment Отчёт кладётся сюда, а после записи номера задания код применяет
--comment накопившееся и удаляет строки.
--comment
--comment Таблица в public по той же причине, что и mail_message: письмо
--comment не привязано к схеме арендатора. Записи не ключуются по письму,
--comment потому что письма, к которому они относятся, мы ещё не нашли.
--comment Дублей не отбиваем: отчёт применяется идемпотентно, а повтор
--comment оператора не вреден. Статус оператора хранится как пришёл, без CHECK:
--comment перечень значений принадлежит оператору и может расшириться, а отказ
--comment базы на новом значении потерял бы отчёт, ради которого буфер заведён.
--comment По received_at чистится старьё: отчёт, чьё письмо так и не нашлось,
--comment не должен копиться вечно. Триггеров и функций нет.
CREATE TABLE public.mail_event_pending (
    id              bigint      GENERATED BY DEFAULT AS IDENTITY,
    provider_id     text        NOT NULL,
    operator_status text        NOT NULL,
    detail          text,
    received_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT mail_event_pending_pk PRIMARY KEY (id)
);

CREATE INDEX mail_event_pending_provider_ix ON public.mail_event_pending (provider_id);
CREATE INDEX mail_event_pending_received_ix ON public.mail_event_pending (received_at);

--rollback DROP TABLE public.mail_event_pending;
