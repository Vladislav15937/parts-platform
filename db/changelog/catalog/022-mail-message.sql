--comment Очередь исходящих писем ячейки (задача 0192). Служебное, к данным склада не относится.
--comment
--comment Почему public, а не схема арендатора. Письмо уходит раньше, чем есть
--comment арендатор: сброс пароля просит человек, которого система ещё не
--comment привязала к схеме, а приглашение владельцу уходит при заведении
--comment компании, когда схемы может не быть вовсе. Очередь в схеме клиента
--comment заставила бы воркер обходить все схемы ради одного письма. Заодно
--comment восстановление одного клиента из бэкапа не воскрешает его старые
--comment письма: повторно отправленный сброс пароля — это вред, а не данные.
--comment
--comment Письмо хранится уже отрендеренным (тема, текст, HTML), а не как
--comment «шаблон плюс параметры». Повтор после сбоя обязан отправить ровно то
--comment же самое: перерисованное по новой версии шаблона письмо или по
--comment изменившимся данным — уже другое письмо, а ссылка в нём могла бы
--comment оказаться свежее той, что человек видел при первой попытке.
--comment
--comment Ключ идемпотентности — уникальный индекс, а не проверка в коде.
--comment Проверка чтением («нет ли уже такого письма») пропускает два
--comment одновременных запроса, и человек получил бы два письма на одно
--comment нажатие. Нарушение индекса вызывающий обязан перечитать и вернуть
--comment результат первой записи, как у приёмки и заказов с площадок.
--comment
--comment Статус ведёт код (QUEUED, SENT, DELIVERED, FAILED, BOUNCED), в базе
--comment только CHECK на допустимые значения. Триггеров и функций нет.
--comment provider_id — номер отправки у оператора (job_id), по нему приходят
--comment отчёты о доставке. Частичный индекс по next_attempt_at держит только
--comment ждущие письма: воркер спрашивает их каждые секунды, а отправленных
--comment со временем становится большинство.
CREATE TABLE public.mail_message (
    id              bigint      GENERATED BY DEFAULT AS IDENTITY,
    idempotency_key text        NOT NULL,
    template        text        NOT NULL,
    recipient       text        NOT NULL,
    subject         text        NOT NULL,
    body_text       text        NOT NULL,
    body_html       text        NOT NULL,
    status          text        NOT NULL DEFAULT 'QUEUED',
    attempts        int         NOT NULL DEFAULT 0,
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    provider_id     text,
    last_error      text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    sent_at         timestamptz,
    delivered_at    timestamptz,
    CONSTRAINT mail_message_pk PRIMARY KEY (id),
    CONSTRAINT mail_message_status_ck
        CHECK (status IN ('QUEUED', 'SENT', 'DELIVERED', 'FAILED', 'BOUNCED'))
);

CREATE UNIQUE INDEX mail_message_idem_uk ON public.mail_message (idempotency_key);
CREATE INDEX mail_message_provider_ix ON public.mail_message (provider_id);
CREATE INDEX mail_message_due_ix ON public.mail_message (next_attempt_at)
    WHERE status = 'QUEUED';

