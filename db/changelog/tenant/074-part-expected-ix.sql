--comment Частичный индекс ожидаемых позиций для поиска продавца — задача 0261
--
-- Поиск продавца отдаёт две вещи: то, что лежит на складе (строка part_stock
-- с остатком), и ожидаемые позиции (заведены из поставки, expected_origin,
-- пока DRAFT). Ожидаемых на складе единицы — сотни на пятьдесят тысяч, —
-- и без этого индекса вторая половина выдачи читает всю таблицу part
-- ради них: замерено на 50 300 позиций, узкий запрос «модель96» (503 находки)
-- 17 мс без индекса и 5 мс с ним, ветка ожидаемых идёт по индексу, а не
-- последовательным чтением part.
--
-- Предикат повторяет условие запроса дословно (p.expected_origin AND
-- p.status = 'DRAFT'): планировщик берёт частичный индекс, только если
-- условие запроса его влечёт. Сменит код условие — индекс перестанет
-- использоваться молча, и узнают об этом по времени ответа.
--
-- Индекс по id, а не по supply_id: ожидаемые соединяются с найденным по
-- id позиции, а поставка берётся по ключу. Форма данных, логики здесь нет.
CREATE INDEX part_expected_ix
    ON ${tenant.schema}.part (id)
    WHERE expected_origin AND status = 'DRAFT';

