--comment Метка «роль переноса у этого клиента заводилась»: отличает удалённого клиентом «Ревизора» от незаведённого (задача 0044)

-- Ответ владельца 24.10.2026 (tasks/0044, «Ответ владельца — 24 октября 2026
-- (после разбора PR 506, 508)», пункт 1б): удалённая клиентом роль «Ревизор» —
-- это отказ; журнал открыт сотруднику AUDITOR, только пока роль не заводили.
--
-- ПОЧЕМУ НУЖНА МЕТКА. tenant/101 заводит «Ревизора» только там, где был
-- сотрудник AUDITOR. Сотрудник AUDITOR без «Ревизора» поэтому бывает в двух
-- состояниях, которые по access_role неразличимы — строки нет в обоих:
--  - роль не заводили: на накате 101 ревизоров у клиента не было, сотрудника
--    завели позже (это делает нынешний образ из main — он пишет только
--    колонку role, — и любой прежний после отката приложения);
--  - роль завели и клиент её удалил.
-- Различает их факт «роль переноса здесь заводилась», и записан он отдельно
-- от самой роли, потому что должен пережить её удаление.
--
-- ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ МЯГКОЕ УДАЛЕНИЕ РОЛИ. Мягкое удаление (deleted_at
-- у access_role) заставило бы каждого читателя ролей отсеивать удалённые,
-- а access_role_name_uk и access_role_seeded_from_uk держали бы имя
-- и происхождение удалённой роли: клиент, удаливший «Ревизора», не смог бы
-- завести свою роль с тем же названием. Удаление остаётся обычным DELETE,
-- как сегодня, и метку не трогает.
--
-- БЕЗ ССЫЛКИ НА access_role. Внешний ключ с ON DELETE CASCADE унёс бы метку
-- вместе с ролью — ровно то, от чего она нужна; без ON DELETE он запретил бы
-- удалять роль вовсе. Связь — по значению seeded_from.
--
-- ПОЧЕМУ НА ВСЕ ШЕСТЬ ПРЕЖНИХ РОЛЕЙ, А НЕ ТОЛЬКО AUDITOR. Неоднозначен сегодня
-- один «Ревизор»: остальные пять 101 заводит всем. Но правило чтения одно на
-- всех — «роли с этим происхождением нет; метка есть — удалил клиент, метки
-- нет — не заводили», — и особого случая в схеме под одну роль не нужно.
--
-- ЭТО EXPAND. Прежние образы таблицу не знают. Метку пишет не удаление,
-- а заведение роли переноса — один раз, этим changeset'ом, — поэтому любой
-- образ, удаляющий роль (в том числе PR 506 без чтения метки), её
-- не разрушает. Пишет её заново только тот, кто заведёт роль с seeded_from:
-- сегодня это делает один tenant/101.
CREATE TABLE ${tenant.schema}.access_role_seeded (
    seeded_from text        PRIMARY KEY,
    seeded_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT access_role_seeded_from_key_ck CHECK (seeded_from IN
        ('OWNER','MANAGER','STOREKEEPER','SELLER','VIEWER','AUDITOR'))
);

COMMENT ON TABLE ${tenant.schema}.access_role_seeded IS
    'Какие роли переноса (access_role.seeded_from) у клиента заводились. Строка переживает удаление роли: роли с этим seeded_from нет, а метка есть — роль удалил клиент; нет и метки — роль не заводили. Задача 0044, ответ владельца 24.10.2026, 1б';

-- ЗАПОЛНЕНИЕ: метка у каждой роли переноса, которая сейчас есть, и только у неё.
-- Сотрудник AUDITOR без «Ревизора» на этом накате — «не заводили», и это
-- не догадка: удалить роль клиента не умеет ни один выпущенный образ — код
-- в main access_role не читает и не пишет вовсе, а удаление ролей приезжает
-- кодом 0044, которого в main нет. Значит отсутствие строки сегодня бывает
-- только у роли, которую не заводили (либо снесли прямым SQL — это не действие
-- клиента, и решать за него «удалил» было бы отказом без его решения).
-- Момент — когда роль завёл 101, а не день этого наката.
INSERT INTO ${tenant.schema}.access_role_seeded (seeded_from, seeded_at)
SELECT seeded_from, created_at
  FROM ${tenant.schema}.access_role
 WHERE seeded_from IS NOT NULL;

