-- Решение владельца продукта 19.10.2026 (tasks/0335, «Всё да, всё как
-- в базон»): название позиции в файле Дрома несёт поле «Год выпуска»
-- ЦЕЛИКОМ, как его хранит Bazon, — «2010» у б/у и «03-08», «04-09»
-- у новых. До этого changeset'а год у позиции был только числом
-- (donor.year, part.manual_year), а перенос разбирал «03-08»
-- BazonValueParser.parseYearRange и терял всё, кроме «от».
--
-- ТЕКСТ, А НЕ ПАРА ЧИСЕЛ. Задача требует слово «как оно хранится», а не
-- диапазон: «03-08» и «2003-2008» — разные написания одного периода,
-- и из пары чисел первое назад не собрать. Разбор периода в числа (для
-- отбора по году) остаётся там, где был; эта колонка его не заменяет.
--
-- NULL — «текста года нет» (поле в файле пусто или позиция заведена
-- не переносом). Пустую строку и строку из одних пробелов не пускает
-- CHECK, как у блоков карточки Дрома (tenant/080): пусто здесь только
-- NULL, иначе «нет года» читалось бы двумя способами.
--
-- Expand: прежний код колонки не знает, не читает и не пишет, она
-- допускает NULL, умолчания нет. Индекса нет: по тексту года ничего
-- не ищут и не сортируют — его только печатают в название.
ALTER TABLE ${tenant.schema}.part
    ADD COLUMN year_text text,
    ADD CONSTRAINT part_year_text_ck CHECK (year_text ~ '\S');

COMMENT ON COLUMN ${tenant.schema}.part.year_text IS
    'Поле «Год выпуска» позиции текстом, как в файле предыдущей системы: 2010, 03-08 (задача 0335). NULL — текста года нет';

--rollback-теряет текст поля «Год выпуска» у перенесённых позиций («03-08», «2010»): после отката год остаётся только числом у машины-донора и в своём значении позиции, диапазон новых деталей не восстановить без повторного переноса файла клиента
--rollback ALTER TABLE ${tenant.schema}.part DROP CONSTRAINT part_year_text_ck, DROP COLUMN year_text;
