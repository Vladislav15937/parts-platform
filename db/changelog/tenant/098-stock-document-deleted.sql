--comment Отметка «Удалён» у проведённого складского документа: кто и когда удалил (задача 0367)

-- Ответ владельца 23.10.2026 (tasks/0367, «Ответ владельца — 23 октября 2026»,
-- решения 1–5): проведённое поступление, списание и перемещение можно удалить;
-- удаление пишет встречное движение, документ помечается «Удалён», исходное
-- движение остаётся в журнале, а в «Движении товара» строка читается
-- «Выполнен (Удалён)» красным. «Отменить проводку» (0360) — другая операция.
--
-- ПОЧЕМУ ОТМЕТКА, А НЕ ЧЕТВЁРТЫЙ СТАТУС. Предлагалось завести DELETED
-- в stock_document_status_ck и переписать stock_document_completed_ck.
-- Отвергнуто по трём причинам.
--  1. «Выполнен (Удалён)» — это два факта: документ выполнен, и потом удалён.
--     Статус ведёт жизнь документа (черновик → выполнен, черновик → отменён,
--     а с 0360 и выполнен → черновик), удаление — отдельное событие поверх
--     выполненного. Склеенные в одно поле, они перестали бы читаться порознь.
--  2. Прежний образ читает статус через @Enumerated(STRING): незнакомое
--     DELETED роняло бы загрузку сущности (повтор приёмки по ключу клиента,
--     проведение и отмена по номеру) — откат приложения на сборку до 0367
--     получил бы пятисотки. Отметку прежний образ просто не видит.
--  3. Путь 0360 не трогается вовсе: stock_document_status_ck
--     и stock_document_completed_ck остаются как есть, «Отменить проводку»
--     ложится в них без нового changeset'а.
--
-- ЧЕГО ЗДЕСЬ НЕТ, И ПОЧЕМУ. «Удалённым бывает только выполненный» —
-- CHECK (deleted_at IS NULL OR status = 'DONE') — ограничение на старую
-- колонку status, и сторож совместимости (tools/migration-compat-guard.py)
-- отбивает его как новое ограничение на существующие данные; пометка
-- «--сужение» была бы ложью — сужения нет. Держит это код (тот же выбор,
-- что у строки администратора, tenant/076). Вернуть CHECK в схему можно
-- отдельным changeset'ом после релиза, где удаление уже стоит.
--
-- Автор обязателен вместе с моментом: удаление — действие человека
-- (только владелец до 0044, дальше — по праву сотрудника), и «кто удалил
-- проведённый документ» — ровно тот вопрос, ради которого отметку читают.
-- Ссылка на tenant_member без ON DELETE: сотрудники не удаляются
-- (MemberService.setActive), а администратор сервиса — тоже строка участника.
ALTER TABLE ${tenant.schema}.stock_document
    ADD COLUMN deleted_at timestamptz,
    ADD COLUMN deleted_by bigint REFERENCES ${tenant.schema}.tenant_member;

ALTER TABLE ${tenant.schema}.stock_document
    ADD CONSTRAINT stock_document_deleted_ck
        CHECK ((deleted_at IS NULL) = (deleted_by IS NULL));

COMMENT ON COLUMN ${tenant.schema}.stock_document.deleted_at IS
    'Момент удаления проведённого документа; NULL — не удалён. Статус остаётся DONE, встречное движение — в stock_movement. Задача 0367';
COMMENT ON COLUMN ${tenant.schema}.stock_document.deleted_by IS
    'Кто удалил проведённый документ; заполнен тогда и только тогда, когда deleted_at. Задача 0367';

