--comment «Прочие поля» объявления Дрома дословно — текстовая колонка в part_drom_card, задача 0292
--
-- Характеристики не-запчастей (магнитолы, усилители, регистраторы, шины) у объявления
-- Дрома лежат в «Прочих полях» файла переноса: строки «Подпись [ключ]: значение» —
-- модель магнитолы, размер DIN, каналы, мощность. Набор зависит от рубрики, полей под
-- них в схеме нет и заводить их по одному под каждую рубрику нельзя. Решение задачи
-- 0292 — хранить дословный текст, а не раскладывать его по колонкам; у шин и дисков
-- сюда попадает то, что не легло в поля колеса.
--
-- Колонка в боковой таблице, а не в part, как у 082: текст длинный, а part читают
-- продажа, резерв и пересчёт, и слушатель журнала кладёт в audit_log всю строку part
-- до и после каждой правки. Пусто — NULL; CHECK отбивает пустую строку и строку из
-- одних пробелов.
--
-- Expand: прежний код колонки не знает, не читает и не пишет. Индекса нет намеренно:
-- по характеристикам ничего не ищется.
ALTER TABLE ${tenant.schema}.part_drom_card
    ADD COLUMN characteristics text;

ALTER TABLE ${tenant.schema}.part_drom_card
    ADD CONSTRAINT part_drom_card_characteristics_ck CHECK (characteristics ~ '\S');

COMMENT ON COLUMN ${tenant.schema}.part_drom_card.characteristics IS
    'Характеристики объявления Дрома («Прочие поля» файла переноса) дословно: строки «Подпись [ключ]: значение» — модель магнитолы, размер DIN, каналы, мощность, у шин и дисков то, что не легло в поля колеса. Не в поиске. NULL — не заполнено';

