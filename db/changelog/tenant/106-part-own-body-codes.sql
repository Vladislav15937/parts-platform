--comment Коды кузова своей машины позиции без донора — part.own_body_codes, задача 0296
--
-- own_body_codes — коды кузова своей машины позиции без донора из применимости, весь список
-- через «, » — как их показывает колонка «Кузов» витрины (например «GRJ120, GRJ120W, KDJ120»).
-- Хранимое производное: пишет Java (OwnVehicleCodes) при разборе блока «Подходит», правке
-- применимости и смене наименования; руками не вводится.
--
-- NULL — кодов нет или ещё не считали.
--
-- CHECK отбивает пустую строку и строку из одних пробелов (так же, как у
-- part_applicability.other_bodies, tenant/104): пусто означает NULL, а не значение.
--
-- Существующие строки здесь не заполняются: колонку дополняет Java, логике в базе не место
-- (ни триггера, ни функции, ни UPDATE по данным). Индекса нет намеренно: отбор идёт по
-- членству кода в списке, а индекс по тексту целиком такому отбору не помогает.
--
-- Expand: прежний код колонки не знает, не читает и не пишет.
ALTER TABLE ${tenant.schema}.part
    ADD COLUMN own_body_codes text;

ALTER TABLE ${tenant.schema}.part
    ADD CONSTRAINT part_own_body_codes_ck CHECK (own_body_codes ~ '\S');

COMMENT ON COLUMN ${tenant.schema}.part.own_body_codes IS
    'Коды кузова своей машины позиции без донора из применимости, весь список через «, » — как их показывает колонка «Кузов» витрины. Хранимое производное: пишет Java (OwnVehicleCodes) при разборе блока «Подходит», правке применимости и смене наименования, руками не вводится. NULL — кодов нет или ещё не считали';

--rollback-теряет сохранённый список кодов кузова у позиций без донора: он производный и пересчитывается Java из применимости при её правке, разборе блока «Подходит» или смене наименования. Сами позиции и применимость остаются
--rollback ALTER TABLE ${tenant.schema}.part DROP CONSTRAINT part_own_body_codes_ck, DROP COLUMN own_body_codes;
