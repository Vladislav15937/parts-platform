--comment Признак «наименование вписано руками» у позиции — одна boolean-колонка part, задача 0303
--
-- Правка номера производителя пересобирает заголовок позиции (номер стоит в его конце), но
-- заголовок, вписанный руками в карточке, пересобирать нельзя: title_manual = true это запрещает.
-- Существующие строки не наполняются (остаются false): отличить ручную правку наименования
-- по audit_log нельзя, там же лежат правки пометки состояния и сопоставления написания.
--
-- Expand: прежний код колонки не знает, его INSERT получает умолчание false. Ни индекса
-- (по колонке не отбирают), ни CHECK, ни триггера.
ALTER TABLE ${tenant.schema}.part
    ADD COLUMN title_manual boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN ${tenant.schema}.part.title_manual IS
    'Наименование вписано руками в карточке (задача 0303): правка номера производителя такой заголовок не пересобирает. false — заголовок собран системой (приёмка, перенос) и номер производителя в его конце следует за правкой номера';

--rollback-теряет признак «наименование вписано руками»: после отката правка номера производителя снова может пересобрать и такой заголовок. Сами наименования и позиции остаются
--rollback ALTER TABLE ${tenant.schema}.part DROP COLUMN title_manual;
