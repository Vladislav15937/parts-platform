--comment Настройки компании: срок резерва по умолчанию — задача 0049

-- Срок, на который товар откладывается под клиента, до сих пор был зашит
-- в сборку (`SalesController.DEFAULT_RESERVATION = Duration.ofDays(3)`):
-- чтобы разборка держала резерв сутки, а не трое, нужен был релиз. Разборка
-- с ходовыми деталями держит сутки, иначе полка стоит; разборка на редкие
-- машины — неделю, потому что клиент едет из другого города.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ jsonb РЯДОМ С `member_setting` (tenant/065).
-- Там лежит состояние экрана одного человека — сортировка, отборы, колонки, —
-- и оно не касается никого, кроме него. Здесь настройка предприятия: её
-- ставит владелец, а последствие видит каждый продавец в каждой сделке. Это
-- данные, а не состояние экрана, и им положены типы, умолчание и `CHECK`,
-- видимые в схеме, — то самое, что база и обязана держать. Цена решения
-- названа честно: каждая следующая настройка компании — это колонка
-- и changeset, тогда как в jsonb она не стоила бы ничего.
--
-- ПОЧЕМУ ОДНА СТРОКА, А НЕ КЛЮЧ-ЗНАЧЕНИЕ. Ключ-значение снова отдаёт тип
-- и границы приложению: `reservation_days = 'позавчера'` такая таблица
-- примет. Строка одна на схему — схема и есть компания, — и это стережёт
-- `CHECK (id = 1)`, а не дисциплина запросов.
--
-- ПОЧЕМУ ОТ ОДНОГО ДНЯ, А НЕ ОТ НУЛЯ. Ноль в нашей системе не означает
-- «без резерва»: создание сделки резервирует товар всегда («Черновика без
-- резерва нет», SalesController), и автоснятия резерва нет как не было —
-- то есть ноль дал бы не сделку без резерва, а сделку, родившуюся
-- с красной пометкой «срок истёк». Расширить границу вниз позже безопасно,
-- сузить обратно — нет: `ALTER TABLE … ADD CONSTRAINT` у клиента, успевшего
-- поставить ноль, отвечает «check constraint is violated by some row»
-- (db/CLAUDE.md, откат tenant/062). Поэтому начинаем с узкого.
--
-- Верхняя граница — не вкус: `Instant.now().plus(Duration.ofDays(n))` при
-- большом n бросает `DateTimeException`, то есть пятисотку на оформлении
-- сделки. Года человеческого масштаба хватает с запасом: резерв на год —
-- это не резерв, а списание с полки.
CREATE TABLE ${tenant.schema}.company_setting
(
    id               smallint    NOT NULL DEFAULT 1
        CONSTRAINT company_setting_pk PRIMARY KEY
        CONSTRAINT company_setting_single CHECK (id = 1),

    reservation_days integer     NOT NULL DEFAULT 3
        CONSTRAINT company_setting_reservation_days
            CHECK (reservation_days BETWEEN 1 AND 365),

    updated_at       timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE ${tenant.schema}.company_setting IS
    'Настройки компании: одна строка на схему. Задача 0049';
COMMENT ON COLUMN ${tenant.schema}.company_setting.reservation_days IS
    'На сколько дней откладывается товар в новой сделке, если продавец не назвал свой срок';

-- Строка заводится здесь, а не провижинингом: провижининг заводит только
-- новых арендаторов, а три дня нужны и тем, кто уже работает. Умолчание
-- колонки повторено значением намеренно — changeset читают как ответ
-- на вопрос «что получит уже накатанный клиент».
INSERT INTO ${tenant.schema}.company_setting (id, reservation_days) VALUES (1, 3);

