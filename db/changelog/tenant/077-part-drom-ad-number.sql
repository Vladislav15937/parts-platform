--comment Номер объявления Дрома у позиции: связь перенесённой позиции с объявлением, которое уже висит у клиента на площадке — задача 0274
--
-- Номер приезжает файлом переноса с Дрома (docs/drom-transfer-file.md,
-- колонка «Номер объявления Дрома») и нужен затем, чтобы клиент мог ответить
-- «какое объявление — какая позиция» и сверить, что осталось ровно по одному.
-- Свой публичный код (part.public_code) для этого не годится: он случайный
-- и уходит в прайс как ordercode, а номера объявления Дрома в схеме не было
-- нигде.
--
-- Текст из одних цифр, а не число: так номер приходит в файле и так его
-- набирает человек в поиске; ведущий ноль и «1,26E+08» числом не пережить.
-- Пусто — NULL, а не пустая строка: CHECK не пускает пустую (она не цифры),
-- а NULL друг с другом в индексе не сталкиваются, поэтому индекс частичный.
--
-- Схема своя у каждого арендатора, так что уникальность «по клиенту» даёт
-- сам индекс: объявление № 125696381 у двух разных компаний — две разные
-- позиции в двух разных схемах.
--
-- Всё это expand: прежний код в колонку не пишет и не читает, вставка без неё
-- получает NULL.
ALTER TABLE ${tenant.schema}.part
    ADD COLUMN drom_ad_number text,
    ADD CONSTRAINT part_drom_ad_number_ck CHECK (drom_ad_number ~ '^[0-9]+$');
CREATE UNIQUE INDEX part_drom_ad_number_uk
    ON ${tenant.schema}.part (drom_ad_number)
    WHERE drom_ad_number IS NOT NULL;

COMMENT ON COLUMN ${tenant.schema}.part.drom_ad_number IS
    'Номер объявления Дрома, только цифры (№125696381 на карточке и в конце адреса страницы). Приезжает файлом переноса; NULL у позиций, у которых объявления на Дроме нет. Задача 0274';

