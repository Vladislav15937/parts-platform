--comment Сколько колёс в позиции, продаваемой одним комплектом — part_wheel.set_pieces, задача 0291
--
-- Число колёс (шин, дисков) в позиции, которая продаётся одним комплектом целиком: то число,
-- за которое названа цена. Нужна колесу, перенесённому с Дрома объявлением «комплект 4 шт»:
-- решение владельца от 14.10.2026 — комплект заводится ОДНОЙ позицией (остаток 1, цена из
-- файла, продаётся только целиком), и в колёсный прайс Дрома уходит inSet = это число.
--
-- NULL — колесо продаётся поштучно (прежнее поведение, inSet = 1). Так у всех колёс, заведённых
-- комплектом через WheelService.createSet: там каждое колесо — своя карточка.
-- Не путать с set_no — номером связки отдельных карточек, а не числом штук.
--
-- Существующие строки не заполняются: у всех NULL. Индекса нет: по колонке не ищут.
--
-- Expand: прежний код колонки не знает, не читает и не пишет.
ALTER TABLE ${tenant.schema}.part_wheel
    ADD COLUMN set_pieces integer;

ALTER TABLE ${tenant.schema}.part_wheel
    ADD CONSTRAINT part_wheel_set_pieces_ck CHECK (set_pieces IS NULL OR set_pieces > 0);

COMMENT ON COLUMN ${tenant.schema}.part_wheel.set_pieces IS
    'Сколько колёс в позиции, продаваемой одним комплектом, — число, за которое названа цена. В колёсный прайс Дрома уходит как inSet. NULL — колесо продаётся поштучно (inSet = 1). Не set_no: тот — номер связки отдельных карточек';

