--comment Память карточки выгрузки «часть изменений не ушла на Дром» — две колонки, а не settings и не журнал

-- Дельта, снятая с очереди и не ушедшая на Дром (сверх лимита пакета, отказ
-- «нужен человек» вроде неподключённого прайс-листа или неверного ключа,
-- пропуск в интервале после такого отказа), оставляла след только в
-- last_error, а его следующая малая дельта обнуляет. Карточка говорила
-- «принято», хотя цены и остатки на площадке устарели до ближайшего полного
-- забора прайса.
--
-- unsent_at — когда это случилось в последний раз. NULL — «неотправленного
-- нет». Признак гаснет на чтении, а не записью: покрыто, когда
-- last_feed_download_at позже unsent_at (Дром скачал полный прайс после
-- неотправки). Колонку при этом никто не обнуляет, поэтому гонки между
-- отправкой и забором прайса нет.
-- unsent_error — причина в том же виде, что last_error (метка вида
-- [TOO_BIG] или [HTTP 200] …), чтобы карточка назвала её даже тогда, когда
-- следующая малая дельта уже записала last_error = NULL.
--
-- Почему колонки, а не ключ в settings jsonb: тот же довод, что у
-- tenant/058 — это факт, его пишет отправка, и запись ключа гонялась бы
-- с сохранением настроек владельцем. Почему не publication_log: журнал
-- чистится через 90 дней, и карточка сказала бы «всё ушло» про то, что не ушло.
--
-- Без DEFAULT намеренно: NULL значит «нет неотправленного», старые строки
-- читаются так же, а прежний код колонок не знает и не пишет (expand,
-- накат без простоя).
ALTER TABLE ${tenant.schema}.marketplace_account
    ADD COLUMN unsent_at timestamptz,
    ADD COLUMN unsent_error text;

COMMENT ON COLUMN ${tenant.schema}.marketplace_account.unsent_at IS
    'Когда изменения этой выгрузки последний раз были сняты с очереди, не уйдя на Дром; NULL — неотправленного нет; покрыто, когда last_feed_download_at позже';
COMMENT ON COLUMN ${tenant.schema}.marketplace_account.unsent_error IS
    'Причина той неотправки в виде last_error (метка [TOO_BIG], [HTTP 200] …); читается вместе с unsent_at';

