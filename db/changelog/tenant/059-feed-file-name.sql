--comment Имя файла прайса — колонкой с уникальным индексом, а не ключом в settings

-- Ссылку на прайс прописывает в кабинете площадки её техспециалист, руками,
-- по переданному тексту. Кончалась она сорока случайными символами токена —
-- и переносили её с ошибками, а ошибку видно только по тому, что объявления
-- не появились: площадка о неверном адресе никому не сообщает. Отсюда
-- читаемый хвост «…/drom-yardt-parts.xml», который человек сверяет глазами.
-- Секрет при этом остаётся отдельной частью пути и никуда не девается:
-- имя файла — не пропуск, а подпись на нём.
--
-- Почему колонка, а не ключ в settings. Довод отбора (changeset 027 —
-- «колонками делается то, по чему фильтрует SQL прайса») сюда не подходит:
-- в отборе имя не участвует. Подходит другой: имя обязано быть уникальным,
-- а уникальный индекс по выражению из jsonb пишется хуже, читается хуже
-- и молчит там, где колонка отвечает.
--
-- Уникальность нужна не базе, а человеку. Два прайс-листа с именем
-- «drom-parts.xml» дают два адреса, различающихся только невидимым секретом
-- посередине: техспециалист площадки, получив оба, перепутает их, и склад
-- уедет в чужой прайс-лист по чужой цене размещения. То есть ровно то,
-- ради чего читаемое имя и заводится, без уникальности разрушается.
--
-- В пределах площадки, а не вообще, — как и название выгрузки
-- (marketplace_account_uk): у Дрома и у Авито свои адреса, и одно и то же
-- имя файла на разных площадках ничего не путает.
--
-- Незаданное имя — NULL, а не пустая строка, и это не мелочь: пустых строк
-- в уникальном индексе может быть только одна, и вторая выгрузка без имени
-- получила бы отказ на ровном месте. Ровно этим болел снятый штрихкод.
-- NULL же в Postgres друг с другом не сталкиваются, поэтому индекс частичный:
-- строки без имени в него не попадают вовсе.
--
-- CHECK повторяет то, что проверяет Java, и стоит здесь не ради вежливого
-- ответа (он приезжает отказом базы, то есть не для человека), а ради формы
-- данных: пустая строка и пробел в имени — это ссылка, которая не открывается,
-- и записать их не должно быть возможно даже запросом мимо приложения.
ALTER TABLE ${tenant.schema}.marketplace_account
    ADD COLUMN feed_file_name text;

CREATE UNIQUE INDEX marketplace_account_feed_file_uk
    ON ${tenant.schema}.marketplace_account (marketplace, feed_file_name)
    WHERE feed_file_name IS NOT NULL;

ALTER TABLE ${tenant.schema}.marketplace_account
    ADD CONSTRAINT marketplace_account_feed_file_ck
    CHECK (feed_file_name IS NULL
           OR feed_file_name ~ '^[a-z0-9][a-z0-9._-]{0,59}\.xml$');

COMMENT ON COLUMN ${tenant.schema}.marketplace_account.feed_file_name IS
    'Читаемое имя файла прайса в конце постоянной ссылки; NULL — имени не задавали, ссылка кончается токеном';

