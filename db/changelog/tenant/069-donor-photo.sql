--comment Снимки машины-донора: уезжают в объявление позиций с отмеченным наименованием — задача 0009

-- Снимков у донора в схеме не было ВОВСЕ: фотографии хранятся только у позиции
-- (part_photo, tenant/033). А продаётся с разборки не только деталь: покупатель
-- смотрит на машину, с которой её снимают, — целая ли сторона, бит ли зад,
-- какой пробег видно на панели, — и у ориентира снимки машины уходят
-- в объявления тех позиций, чьё наименование владелец отметил. Здесь только
-- форма данных; отбор наименований, порядок и запись в прайс — Java и TS
-- той же задачи.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ КОЛОНКА У donor И НЕ ЗАПИСИ В part_photo.
-- Снимков у машины столько же, сколько у позиции (шесть-девять), и у каждого
-- свой порядок, свой размер и своё состояние загрузки — это набор строк,
-- а не поле. В part_photo их класть нельзя: там `part_id NOT NULL`, то есть
-- снимок машины пришлось бы привязывать к какой-то одной позиции, и удаление
-- этой позиции (ON DELETE CASCADE) унесло бы фотографии машины, к которой она
-- отношения не имеет. Устройство повторяет part_photo намеренно: обе таблицы
-- читает один и тот же путь выгрузки, и расхождение в именах колонок
-- превратилось бы в два способа делать одно.
--
-- ПОЧЕМУ ЗДЕСЬ НЕТ variants. У part_photo такая колонка есть и её не отображает
-- даже сущность PartPhoto: читателя у неё нет ни одного. Повторять её значило бы
-- завести вторую мёртвую колонку и объявить её частью формы данных.
--
-- ПОЧЕМУ ГЛАВНЫЙ СНИМОК И ПОРЯДОК НЕ ВЕДЁТ ТРИГГЕР. Правило проекта: логика
-- живёт в Java, база хранит данные и связи (CLAUDE.md, db/CLAUDE.md —
-- двадцать три триггера и десять функций отсюда уже вынесены). «Снял отметку
-- с одного — поставь другому» это решение, и наблюдают его последствия
-- из сервиса, а не из схемы. Базе остаётся то, что видно в ней самой:
-- уникальность, умолчания и перечень допустимых состояний.
--
-- ПОЧЕМУ НАСТРОЙКИ ВЫГРУЗКИ ЗДЕСЬ НЕТ. «Для каких наименований дописывать
-- снимки донора» — настройка выгрузки, и живёт она в marketplace_account.settings
-- (jsonb): применяется при сборке файла, а не в WHERE прайса, и у каждой
-- выгрузки своя. Колонка в схеме арендатора дала бы второе место для того же
-- и changeset на каждую правку отбора.
CREATE TABLE ${tenant.schema}.donor_photo (
    id                bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    -- ON DELETE CASCADE: снимки списанной и удалённой машины не значат ничего
    -- и никем не читаются — ровно как у part_photo. Сами объекты в хранилище
    -- убирает приложение; строка без машины была бы ссылкой в никуда.
    donor_id          bigint      NOT NULL REFERENCES ${tenant.schema}.donor ON DELETE CASCADE,

    s3_key            text        NOT NULL,
    sort_order        int         NOT NULL DEFAULT 0,
    is_main           boolean     NOT NULL DEFAULT false,

    -- Размеры и вес знает тот, кто принял файл; NULL означает «ещё не считали»,
    -- а не ноль: снимок заводится до того, как телефон его залил.
    width             int,
    height            int,
    bytes             bigint,

    status            text        NOT NULL DEFAULT 'UPLOADED',

    -- Ключ запроса от клиента. Приёмка и запрос ссылки на снимок идут через
    -- офлайн-очередь: соединение обрывается до ответа, очередь повторяет, —
    -- и без ключа повтор заводит вторую запись и мусор в хранилище. Уникальность
    -- стережёт индекс, а не проверка «нет ли уже такого» в коде: та пропустит
    -- второй ОДНОВРЕМЕННЫЙ повтор, между её чтением и вставкой второй запрос
    -- ещё ничего не видит (tenant/016, та же правка у part_photo).
    client_request_id text,

    created_at        timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT donor_photo_status_ck CHECK (status IN ('UPLOADED','PROCESSED','FAILED'))
);

CREATE INDEX donor_photo_donor_ix ON ${tenant.schema}.donor_photo (donor_id, sort_order);

-- Главная на машину одна, и держит это индекс, а не дисциплина сервиса:
-- отметка решает, какой снимок уедет в объявление первым. Частичный — потому
-- что уникальна тут строка со `is_main`, а не пара (donor_id, is_main):
-- обычная уникальность разрешила бы ровно один НЕглавный снимок на машину.
CREATE UNIQUE INDEX donor_photo_main_uk ON ${tenant.schema}.donor_photo (donor_id) WHERE is_main;

-- Частичный и здесь, и это не украшение: NULL'ы в уникальном индексе Postgres
-- друг с другом не сталкиваются, а вот пустых строк он пускает только одну —
-- то есть незаданный ключ, записанный пустой строкой, отбил бы ВТОРОЙ снимок,
-- заведённый без ключа. Этим уже обожглись на снятом штрихкоде (CLAUDE.md):
-- пусто означает «не заполнено», а не значение. Условие `IS NOT NULL` заодно
-- оставляет индекс маленьким: ключ несут только записи из очереди.
CREATE UNIQUE INDEX donor_photo_client_request_uk
    ON ${tenant.schema}.donor_photo (client_request_id)
    WHERE client_request_id IS NOT NULL;

COMMENT ON TABLE ${tenant.schema}.donor_photo IS
    'Фотографии машины-донора. Уезжают в объявление позиций, чьё наименование отмечено в настройках выгрузки. Устройство повторяет part_photo. Задача 0009';
COMMENT ON COLUMN ${tenant.schema}.donor_photo.is_main IS
    'Главный снимок машины: уходит в объявление первым. Один на машину — держит частичный уникальный индекс donor_photo_main_uk; отметку переставляет приложение, а не триггер';
COMMENT ON COLUMN ${tenant.schema}.donor_photo.client_request_id IS
    'Ключ запроса от клиента для идемпотентности загрузки. NULL — ключа нет; пустой строкой не писать, в уникальном индексе она может быть только одна';

