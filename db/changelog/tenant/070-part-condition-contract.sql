-- Решение владельца продукта от 8 сентября 2026
-- (tasks/0039-sostoyanie-detali-kontraktnaya.md, раздел «Ответ владельца»):
-- значение «контрактная» заводится рядом с «новой», «б/у»
-- и «восстановленной».
--
-- ПОЧЕМУ ЭТО НЕ ЧАСТНЫЙ СЛУЧАЙ «Б/У», хотя выглядит им. Контрактная деталь
-- снята с целой машины, привезённой из Японии, и не ремонтировалась вовсе;
-- восстановленная — ремонтировалась. На разборке это разные товары и разная
-- цена, а у ориентира «Контракт» висит плашкой рядом с ценой в карточке
-- товара — то есть это маркировка для покупателя, а не служебное поле.
--
-- ЗДЕСЬ ТОЛЬКО ФОРМА ДАННЫХ, И ЭТО ВСЯ ДОЛЯ СХЕМЫ В ЗАДАЧЕ. Перечисление
-- PartCondition, слово на экране, разбор «Контракта» при переезде, пересборка
-- заголовка и дельта на площадку — Java и TS той же задачи. Новых колонок,
-- таблиц, индексов и данных здесь нет: значение никому не раздаётся,
-- умолчание колонки остаётся 'USED', уже лежащие строки не трогаются вовсе.
-- Здесь расширяются ровно два перечня — и оба обязательны.
--
-- И СТРОКА ВЫШЕ НЕ СЛУЧАЙНО НАЧИНАЕТСЯ НЕ С ТОГО СЛОВА. Первая редакция
-- этого пояснения начиналась словом «Changeset», и Liquibase прочитал
-- «-- Changeset расширяет…» как объявление changeset'а с неизвестным
-- форматом: ChangeLogParseException на весь файл, то есть набор арендатора
-- не разбирается вовсе и ни один клиент не заводится. Поймано накатом
-- (db/verify.sh, шаг 2); статические проверки файл приняли.
ALTER TABLE ${tenant.schema}.part
    DROP CONSTRAINT part_condition_ck;

ALTER TABLE ${tenant.schema}.part
    ADD CONSTRAINT part_condition_ck CHECK (condition IN
        ('NEW','USED','REFURBISHED','CONTRACT'));

-- ВТОРОЙ ПЕРЕЧЕНЬ — ОТБОР ВЫГРУЗКИ, И БЕЗ НЕГО ЗНАЧЕНИЕ ПОЛОВИНЧАТО.
-- `marketplace_account.conditions` ограничен теми же значениями, что и у
-- детали (tenant/027): контрактная деталь существовала бы на складе,
-- но владелец не смог бы собрать по ней прайс-лист — ограничение отбило бы
-- сохранение отбора отказом базы. Цена ошибки тут та же, что названа
-- в tenant/027: отбор выгрузки живёт рядом с ценой размещения, и разъехавшиеся
-- перечни означают либо отказ на сохранении, либо молча пустой прайс.
ALTER TABLE ${tenant.schema}.marketplace_account
    DROP CONSTRAINT marketplace_account_conditions_ck;

ALTER TABLE ${tenant.schema}.marketplace_account
    ADD CONSTRAINT marketplace_account_conditions_ck
    CHECK (conditions IS NULL OR conditions <@
        ARRAY['NEW','USED','REFURBISHED','CONTRACT']::text[]);

-- ОТКАТ ЗДЕСЬ НЕСИММЕТРИЧЕН, И ЭТО ГЛАВНОЕ, ЧТО НАДО ПРО НЕГО ЗНАТЬ.
-- Прямой ход расширяет перечень — он проходит при любых данных. Откат его
-- СУЖАЕТ, и сужающий `ADD CONSTRAINT` отвечает «check constraint is violated
-- by some row», если у клиента есть хоть одна контрактная позиция или хоть
-- одна выгрузка, отбирающая контрактные. На чистой базе (db/verify.sh, шаг 7)
-- строк нет, и разворот прошёл бы и без двух строк ниже: ровно та порода, что
-- у шестой роли (tenant/062) — полный разворот проверяют пустым, а выполняют
-- на живом. Поэтому данные уводятся из снимаемого значения ДО того, как
-- перечень сужается обратно.
--
-- КУДА УВОДИТСЯ ПОЗИЦИЯ: в 'USED', а не в 'NEW' или 'REFURBISHED'. Откат
-- обязан не переобещать покупателю: контрактная деталь снята с машины,
-- то есть она б/у и не ремонтировалась. 'NEW' соврал бы в объявлении,
-- 'REFURBISHED' приписал бы ремонт, которого не было. 'USED' — ещё
-- и умолчание самой колонки, то есть то значение, которое позиция получила бы,
-- не выбери приёмщик ничего.
--
-- КУДА УВОДИТСЯ ОТБОР ВЫГРУЗКИ: 'CONTRACT' вынимается из массива, а опустевший
-- отбор становится NULL. Пустой массив здесь завести нельзя — и это измерено,
-- а не выведено: приложение само пишет NULL на пустой список
-- (MarketplaceAccountService.updateFilter), а читает `{}` как «любое состояние»
-- (textList -> List.of(), дальше `?::text[] IS NULL OR p.condition = ANY (...)`).
-- То есть `{}` — значение, которого приложение не создаёт, а смысл его держится
-- на одной строке Java: прочитай её кто-нибудь как «отбор, которому ничего
-- не подходит», и выгрузка отдаст пустой прайс, то есть команду площадке снять
-- все объявления. NULL говорит «без ограничения по состоянию» самой схемой.
--
-- ЧТО ПРИ ЭТОМ ОСТАЁТСЯ РАЗОШЕДШИМСЯ — названо, а не умолчано. Заголовок
-- позиции собирается из вида детали, машины, сторон и состояния
-- (PartTitleGenerator), и пересобирает его Java, а не откат: у позиции,
-- уведённой в 'USED', заголовок останется прежним, с тем словом, которое
-- уже уехало в объявление.
--rollback-теряет состояние «контрактная» у позиций: откат уводит их в «б/у» (тем же словом в прайсе на площадку), и обратно это не восстановить — какие именно были контрактными, после отката не записано нигде; у выгрузок CONTRACT вынимается из отбора по состоянию, а выгрузка, отбиравшая ТОЛЬКО контрактные, остаётся вовсе без отбора по состоянию и начинает отдавать в прайс все состояния; заголовки позиций при этом остаются с прежним словом — их пересобирает Java, а не откат
