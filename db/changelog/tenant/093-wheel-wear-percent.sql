--comment Износ шины в процентах, как у Bazon (30%): колонка part_wheel.wear_percent и перевод уже лежащих миллиметров обратно в проценты, задача 0340

-- Решение владельца продукта 19.10.2026 (tasks/0340, раздел «Ответ
-- владельца», решение 3): износ хранится в процентах, как вписан у
-- клиента, — «30%» в файле Bazon уходит в наш файл ровно «30%». Решение
-- «износ в миллиметрах остатка протектора» (tenant/031, задача 0291)
-- отменено.
--
-- ЧТО ПРОИСХОДИТ С ТЕМ, ЧТО УЖЕ ЛЕЖИТ. Перенос из Bazon и с Дрома
-- переводил проценты в миллиметры от восьми мм новой шины
-- (8 × (100 − p) / 100, одна цифра после запятой), а прайс Дрома
-- переводил их обратно в проценты (100 × (8 − мм) / 8, округление
-- половины вверх, не меньше 0 и не больше 100). Здесь стоит ровно
-- второй пересчёт — тот же, что был у DromWheelGenerator.wearPercent.
-- Поэтому после наката площадка получает то же число, что получала
-- до него, у любой шины, и вписанной руками в мм тоже. У перенесённых
-- проценты кратные пяти возвращаются точно (5 → 7,6 мм → 5 и так до 95);
-- проценты вида 5k+2 из миллиметров не восстановить вовсе — 12 % и 13 %
-- оба лежат как 7,0 мм, — и такие вернутся на единицу больше (12 → 13).
-- Проверено тестом WheelWearPercentTest на непустой схеме.
--
-- Expand: колонка допускает NULL, умолчания нет; прежний код её
-- не знает. wear_mm остаётся до следующего релиза (contract): новый код
-- пишет обе колонки, чтобы прежний образ после отката приложения читал
-- износ, который успели завести. Индекса нет: колёс у клиента сотни.
ALTER TABLE ${tenant.schema}.part_wheel
    ADD COLUMN wear_percent smallint,
    ADD CONSTRAINT part_wheel_wear_percent_ck
        CHECK (wear_percent IS NULL OR wear_percent BETWEEN 0 AND 100);

UPDATE ${tenant.schema}.part_wheel
   SET wear_percent = LEAST(100, GREATEST(0, round((8 - wear_mm) * 100 / 8)))::smallint
 WHERE wear_mm IS NOT NULL;

COMMENT ON COLUMN ${tenant.schema}.part_wheel.wear_percent IS
    'Износ шины в процентах, как у клиента в Bazon: 30 значит «износ 30%» (задача 0340). NULL — износ не указан';

--rollback-теряет износ в процентах, как его вписал человек: после отката остаются миллиметры (8 мм за новую шину), и проценты вида 5k+2 при следующем накате вернутся на единицу больше (12 % → 7,0 мм → 13 %)
--rollback ALTER TABLE ${tenant.schema}.part_wheel DROP CONSTRAINT part_wheel_wear_percent_ck, DROP COLUMN wear_percent;
