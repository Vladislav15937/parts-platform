--comment «Применимость» («Подходит») как у клиента на Дроме — текстовая колонка в part_drom_card, задача 0287
--
-- Файл переноса с Дрома (docs/drom-transfer-file.md, колонка 17) несёт «Применимость»
-- блоками: строка на пункт, части через « | » («Toyota 4Runner | 5 поколение (2009–2013) |
-- TRN285, GRN285»), блоки «Другие кузова» и «Для двигателей». В справочную применимость
-- (part_applicability: марка/модель/поколение) строка клиента без потерь не ложится,
-- поэтому первично хранится дословный текст; разложение в справочник — отдельная,
-- необязательная работа (решение владельца 14.10.2026, tasks/0287).
--
-- Колонка в боковой таблице, а не в part: у отдельных позиций текст 34–42 тысячи знаков,
-- а part читают продажа, резерв и пересчёт, и слушатель журнала кладёт в audit_log всю
-- строку part до и после каждой правки. Пусто — NULL; CHECK отбивает пустую строку и
-- строку из одних пробелов.
--
-- Expand: прежний код колонки не знает, не читает и не пишет. Индекса нет намеренно:
-- по тексту ничего не ищется (поиск идёт по справочной применимости).
ALTER TABLE ${tenant.schema}.part_drom_card
    ADD COLUMN applicability text;

ALTER TABLE ${tenant.schema}.part_drom_card
    ADD CONSTRAINT part_drom_card_applicability_ck CHECK (applicability ~ '\S');

COMMENT ON COLUMN ${tenant.schema}.part_drom_card.applicability IS
    'Применимость («Подходит») как у клиента на Дроме, дословно, блоками: строка на пункт, части через « | ». Не part_applicability и не в поиске. NULL — не заполнено';

