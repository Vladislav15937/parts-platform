--comment Блоки карточки Дрома у позиции: гарантия, самовывоз, доставка и оплата — дословно, как у клиента, — задача 0285
--
-- Файл переноса с Дрома (docs/drom-transfer-file.md, колонки 19-21) несёт три
-- текста объявления, и клиент требует повторить объявление «на сто процентов»:
-- тексты хранятся так, как пришли, без чистки и без сопоставления со справочником.
-- Раньше им негде было лежать, и первая же загрузка файла потеряла бы их навсегда.
--
-- ПОЧЕМУ БОКОВАЯ ТАБЛИЦА 1:1, А НЕ КОЛОНКИ В part. «Доставка и оплата» это
-- около тысячи знаков на каждой из тысяч позиций, а следом идут применимость
-- (до 42 000 знаков) и остальное в том же роде. Колонкой в part они ехали бы
-- в каждую загрузку сущности Part (продажа, резерв, пересчёт — всё, что ходит
-- через Hibernate) и, главное, в снимок audit_log: слушатель кладёт в журнал всю
-- строку part до и после КАЖДОЙ правки, и три лишних текста раздули бы журнал
-- у каждой позиции. Читает таблицу только карточка и импорт.
--
-- Строки нет, пока у позиции ни разу не было блока (очищенные потом блоки оставляют
-- строку с NULL — правка видна в журнале): пусто здесь значит NULL
-- (а не пустая строка и не строка из одних пробелов — CHECK их не пускает;
-- та же природа, что у снятого штрихкода). Строку заводит и правит код приложения:
-- ни триггеров, ни вычисляемых колонок тут нет.
--
-- Всё это expand: прежний код таблицы не знает, не читает и не пишет в неё, а удаление
-- позиции убирает строку само (ON DELETE CASCADE).
CREATE TABLE ${tenant.schema}.part_drom_card (
    part_id          bigint PRIMARY KEY REFERENCES ${tenant.schema}.part (id) ON DELETE CASCADE,
    -- «Гарантия и условия возврата» на карточке Дрома.
    warranty         text,
    -- «Самовывоз» — адрес одной строкой.
    pickup           text,
    -- «Доставка и оплата» — весь текст с переводами строк.
    delivery_payment text,
    CONSTRAINT part_drom_card_warranty_ck CHECK (warranty ~ '\S'),
    CONSTRAINT part_drom_card_pickup_ck CHECK (pickup ~ '\S'),
    CONSTRAINT part_drom_card_delivery_payment_ck CHECK (delivery_payment ~ '\S')
);

COMMENT ON TABLE ${tenant.schema}.part_drom_card IS
    'Блоки карточки объявления Дрома, которые хранятся дословно и не нужны складу при каждом чтении позиции. Одна строка на позицию; строки нет — блоков не было. Задача 0285';
COMMENT ON COLUMN ${tenant.schema}.part_drom_card.warranty IS
    'Гарантия и условия возврата, как у клиента на Дроме («Обговаривается индивидуально»). NULL — не заполнено; пустой строкой не писать, CHECK не пустит';
COMMENT ON COLUMN ${tenant.schema}.part_drom_card.pickup IS
    'Самовывоз, как у клиента на Дроме («Самовывоз — улица Георгия Исакова 9»). NULL — не заполнено';
COMMENT ON COLUMN ${tenant.schema}.part_drom_card.delivery_payment IS
    'Доставка и оплата, весь текст с переводами строк и пустыми строками. NULL — не заполнено';

--rollback-теряет три блока карточки Дрома у каждой позиции (гарантия и условия возврата, самовывоз, доставка и оплата): тексты клиента, перенесённые файлом переноса или поправленные на карточке, из базы не восстановить, кроме повторной загрузки того же файла (она вернёт пустые блоки, но правки владельца на карточке пропадут). Сами позиции остаются
--rollback DROP TABLE ${tenant.schema}.part_drom_card;
