--comment Роль автора записывается вместе с правкой: подтянутая сегодня станет ложью

-- «Сотрудника переводят из продавцов в менеджеры, и запись „менеджер уронил
-- цену“ станет ложью задним числом, если роль подтягивать текущую»
-- (tasks/0043, раздел «Ответы владельца»). Роль сотрудника живёт одной
-- колонкой в tenant_member и переписывается на месте: истории у неё нет,
-- и восстановить её на момент правки нельзя ничем — tenant_member в список
-- отслеживаемых таблиц не входит, то есть даже смена роли в журнал
-- не попадает.
--
-- Отсюда единственный честный способ: записать роль тогда же, когда пишется
-- сама правка, — снимком рядом с автором, а не ссылкой. Тот же приём, что
-- у cost_price_snapshot в deal_item: переоценка задним числом не должна
-- переписывать прошлое.
--
-- ЗАПИСИ ДО ЭТОГО ЧИСЛА ОСТАЮТСЯ БЕЗ РОЛИ, И ЭТО ПРАВИЛЬНО. NULL здесь
-- означает «не знаем», и экран показывает прочерк. Подставить текущую роль
-- к старой записи значит выдать догадку за ответ — ровно то, за что задача
-- отдельно запрещает подставлять текущего пользователя вместо снятого
-- автора: «подставленный автор выглядит как ответ на вопрос „кто“, будучи
-- догадкой».
--
-- ТЕКСТ, А НЕ ССЫЛКА НА СПРАВОЧНИК. Роли — это шесть строк, перечисленных
-- CHECK'ом выше, а не таблица; и снимок обязан пережить исчезновение роли
-- из перечня, иначе он перестанет быть снимком.
ALTER TABLE ${tenant.schema}.audit_log
    ADD COLUMN changed_by_role text;

COMMENT ON COLUMN ${tenant.schema}.audit_log.changed_by_role IS
    'Роль автора на момент правки, снимком. NULL — правка сделана до 8 сентября 2026, приехала переносом или сделана фоновой задачей; текущую роль подставлять нельзя, она врёт задним числом';

