-- Решение владельца продукта от 8 сентября 2026
-- (tasks/0043-zhurnal-deystviy-organizatsii.md, раздел «Ответы владельца»):
-- на вопрос «новая роль или именное разрешение конкретному участнику»
-- ответ дословно — «роль». То есть шестое значение рядом с пятью
-- существующими, а не второй способ раздавать права.
--
-- ПОЧЕМУ НЕ ИМЕННОЕ РАЗРЕШЕНИЕ, хотя оно ближе к словам «тем, кому владелец
-- разрешил». Два способа раздавать права расходятся молча — в этом проекте
-- так уже случалось с белыми списками колонок и с копиями словарей, — и цена
-- расхождения тут не в неудобстве: разошедшись, они дадут журнал тому, кому
-- владелец его не открывал. Полномочия поштучно заводит задача 0044, и когда
-- она придёт, роль станет одним из них, а не третьим механизмом.
--
-- РОЛЬ ЧИТАЮЩАЯ, И ЭТО ДЕРЖИТСЯ САМО. Изменяющие методы в SecurityConfig
-- перечисляют разрешённые роли, а не запрещённую: AUDITOR, не внесённый
-- в этот список, не меняет ничего — ровно как «Просмотр». Обратная запись
-- («всем, кроме Просмотра») дала бы новой роли полные права молча.
ALTER TABLE ${tenant.schema}.tenant_member
    DROP CONSTRAINT tenant_member_role_ck;

ALTER TABLE ${tenant.schema}.tenant_member
    ADD CONSTRAINT tenant_member_role_ck CHECK (role IN
        ('OWNER','MANAGER','STOREKEEPER','SELLER','VIEWER','AUDITOR'));

-- Откат снимает роль, а не только разрешение на неё. Ограничение, суженное
-- обратно при живом сотруднике с ролью AUDITOR, не добавится вовсе — то есть
-- откат встанет на «check constraint is violated by some row», и увидеть это
-- можно будет только на схеме клиента, у которого такой сотрудник заведён.
-- На чистой базе (db/verify.sh, шаг 7) строк нет и разворот прошёл бы и без
-- этой строки — именно поэтому она здесь: полный разворот проверяют пустым,
-- а выполняют на живом.
--
-- Переводится сотрудник в «Просмотр», а не в «Менеджера»: откат обязан
-- двигать права вниз. Роль, которой после отката не существует, оставила бы
-- человека без входа вовсе, а повышение раздало бы ему то, чего владелец
-- не давал.
