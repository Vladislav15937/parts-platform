--changeset partsflow:tenant-058-feed-download-mark
--comment Отметка «площадка забрала прайс» — колонкой, а не в settings и не строкой журнала

-- Факт забора прайса по постоянной ссылке до сих пор никуда не сохранялся:
-- DromFeedController писал строку в лог, и на первый вопрос при подключении
-- клиента — «прайс вообще уехал?» — отвечал разработчик через docker logs.
-- То есть клиент ждал человека, чтобы узнать то, что система уже знала.
--
-- Соседняя last_sync_at занята другим фактом: её пишет отправка дельт
-- (DromDeltaSender), то есть «мы отправили», а не «у нас забрали». Это разные
-- события с разными причинами отсутствия, и путаница между ними как раз
-- и мешает ответить на вопрос клиента — поэтому отдельная колонка, а не
-- переиспользование существующей.
--
-- Почему колонка, а не ключ в settings jsonb. Отбор выгрузки лежит колонками
-- по доводу из changeset'а 027 — «по ним фильтрует SQL прайса»; здесь довод
-- другой, но к тому же выводу. settings — документ настроек, который владелец
-- сохраняет целиком, а это не настройка, а факт, и пишется он на каждый запрос
-- НЕаутентифицированного адреса. Запись ключа в settings означала бы
-- перезапись всего документа, гонящуюся с сохранением настроек владельцем:
-- настройки, сохранённые в ту же секунду, затёр бы забор прайса. UPDATE одной
-- колонки с этим не гонится и читается в списке выгрузок бесплатно.
--
-- Почему не строка в publication_log, где в CHECK уже есть FEED_BUILD:
-- журналу запланирована чистка старше 90 дней (docs/domain-model.md), и после
-- неё экран сказал бы «не забирали» про выгрузку, которую забирали, — ровно
-- та ложь, ради устранения которой всё и делается. Нужно одно текущее
-- значение, а не история.
--
-- Без DEFAULT намеренно: NULL здесь означает «не забирали ни разу», и экран
-- обязан показать это словами. Умолчание проставило бы всем существующим
-- выгрузкам время наката — отметку о заборе, которого не было.
ALTER TABLE ${tenant.schema}.marketplace_account
    ADD COLUMN last_feed_download_at timestamptz;

COMMENT ON COLUMN ${tenant.schema}.marketplace_account.last_feed_download_at IS
    'Когда площадка последний раз забрала прайс по постоянной ссылке; NULL — не забирала ни разу';

--rollback ALTER TABLE ${tenant.schema}.marketplace_account DROP COLUMN last_feed_download_at;
