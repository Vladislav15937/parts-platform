--comment Настройки экрана за сотрудником: сервер, а не браузер

-- Задача 0060, уточнения владельца продукта от 11 сентября 2026: «для каждого
-- отдельного пользователя всегда. Даже если он закрыл браузер, выключил
-- компьютер, открыл в другом браузере или из другого места» и «запоминать
-- всё, и должна быть кнопка сбросить фильтры, сбросить сортировку».
--
-- ПОЧЕМУ НЕ localStorage. Он не переживает ни другой браузер, ни другое
-- устройство, ни приватное окно, — то есть требование владельца им
-- не выполняется в трёх случаях из четырёх, им же названных. Состав колонок
-- витрины до сих пор хранился именно там (ключ `catalog-columns`) и переезжает
-- сюда вместе с остальным.
--
-- ПОЧЕМУ ОДНА ТАБЛИЦА С jsonb, А НЕ КОЛОНКИ ПОД КАЖДУЮ НАСТРОЙКУ. Здесь
-- лежит состояние экрана, а не данные предприятия: порядок сортировки, набор
-- отборов, состав колонок. Колонками это значило бы миграцию на каждую новую
-- колонку витрины (их сорок шесть) и на каждый новый экран, который захочет
-- что-то помнить, — то есть релиз ради настройки одного человека. Ничего,
-- кроме этого человека, содержимое не касается: оно не участвует ни в одном
-- запросе, кроме «отдай мне моё», и не связано ни с чем, кроме сотрудника.
--
-- Размер ограничивает приложение (MemberSettingsService), а не схема: предел
-- в схеме пришлось бы менять changeset'ом, а он тут произвольная величина,
-- защищающая от набитого мусора, — не форма данных.
CREATE TABLE ${tenant.schema}.member_setting
(
    -- ON DELETE CASCADE: настройка ушедшего сотрудника не значит ничего
    -- и никем не читается. Это ровно обратное решение тому, что принято
    -- у login_session (tenant/063), и разница по существу: журнал заводят,
    -- чтобы он пережил человека, а состояние его экрана — нет.
    member_id  bigint      NOT NULL
        REFERENCES ${tenant.schema}.tenant_member (id) ON DELETE CASCADE,

    -- Имя экрана, а не «настройки вообще»: витрина склада, колёса, сделки —
    -- разные наборы, и общая запись заставила бы читать чужое, чтобы записать
    -- своё.
    screen     text        NOT NULL,

    value      jsonb       NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT member_setting_pk PRIMARY KEY (member_id, screen)
);

COMMENT ON TABLE ${tenant.schema}.member_setting IS
    'Состояние экранов за сотрудником: сортировка, отборы, состав колонок. Переживает браузер и устройство — в этом вся причина держать его на сервере. Задача 0060';

--rollback DROP TABLE ${tenant.schema}.member_setting;
