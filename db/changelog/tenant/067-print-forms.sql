-- Товарного чека, накладной и счёта на юр. лицо в системе нет вовсе: печатает
-- только экран «Этикетки». Покупатель б/у запчасти уносит бумагу почти всегда —
-- по ней он через две недели приходит по гарантии, — то есть переход
-- с предыдущей системы без печати читается как «раньше бумагу давали, теперь
-- не даём». Здесь только форма данных; сами формы и экран настройки — Java и TS
-- той же задачи.
--
-- ПОЧЕМУ РЕКВИЗИТЫ ПРОДАВЦА — КОЛОНКА У СКЛАДА, А НЕ ОДНО ПОЛЕ НА КОМПАНИЮ.
-- Это главный довод задачи, и он от живого клиента: у него два склада
-- и в них РАЗНЫЕ ИП (§7 docs/bazon-parity.md, обход 29–30.07.2026). Чек
-- и накладная печатают того, кто продал, а продал — склад выдачи; одно поле
-- на компанию печатало бы на половине чеков чужое ИП, то есть документ
-- с неверным продавцом. NULL означает «не заполнено»: склад, которому
-- реквизиты не задали, печатает документ без блока продавца, а не пустые
-- строки с подписями.
--
-- ПОЧЕМУ ОСТАЛЬНОЕ — КОЛОНКИ В company_setting, А НЕ СВОЯ ТАБЛИЦА.
-- Правило уже записано (db/CLAUDE.md, «Настройка компании — колонка
-- в company_setting, а не ключ в jsonb», tenant/066): настройку ставит
-- владелец, а последствие видит каждый продавец в каждом документе, —
-- это данные предприятия, и им положены типы и умолчания, видимые в схеме.
-- Своя таблица печати дала бы ВТОРОЕ место для настроек компании, то есть
-- два способа решать одно; цена колонок названа там же честно — каждая
-- следующая настройка это changeset, и вот он.
--
-- ДВА УРОВНЯ РЕКВИЗИТОВ — РАЗНОГО НАЗНАЧЕНИЯ, И ОДИН НЕ ЗАМЕНЯЕТ ДРУГОЙ.
-- Блок склада (кто продал) идёт в товарный чек и накладную; реквизиты
-- организации (ИНН, КПП, банк, р/с, к/с, руководитель, главный бухгалтер)
-- идут в счёт на юр. лицо и в накладные поступлений. У клиента с двумя ИП
-- оба уровня нужны одновременно.
--
-- ПОЧЕМУ ИНН, КПП, БИК И СЧЕТА — text, А НЕ ЧИСЛА. Это идентификаторы,
-- а не величины: ведущий ноль значащий, арифметики над ними нет, а численный
-- тип молча съел бы ноль и выдал в счёте чужой банк. У клиента все десять
-- полей сейчас пустые — заполнять их он будет руками, с документов.
--
-- ПОЧЕМУ У РЕКВИЗИТОВ НЕТ CHECK НА ФОРМАТ. ИНН у ИП двенадцать знаков,
-- у организации десять; вставленное из письма приезжает с пробелами
-- и неразрывными пробелами. CHECK отбил бы это отказом базы — 409 без слов
-- о том, что не так, — на поле, которое владелец заполняет один раз в жизни
-- и с документа. Проверка формата и приведение — в Java, где они умеют
-- сказать словами; база держит форму данных.
ALTER TABLE ${tenant.schema}.warehouse
    ADD COLUMN print_details text;

COMMENT ON COLUMN ${tenant.schema}.warehouse.print_details IS
    'Реквизиты продавца этого склада для чека и накладной: название компании, адрес и контакты, многострочно. NULL — не заполнено, блок продавца не печатается. Задача 0051';

ALTER TABLE ${tenant.schema}.company_setting
    -- Условия возврата и гарантии. NULL и пустая строка здесь означают одно —
    -- «текста нет», и читателю положено спрашивать isBlank(), а не != null:
    -- владелец, вычистивший поле руками, пришлёт пустую строку, и печатать
    -- пустой абзац с заголовком было бы хуже, чем не печатать ничего.
    ADD COLUMN print_extra_text          text,

    -- Пометка об НДС вида «в том числе НДС 5% - ### руб.». Пусто означает,
    -- что строки в документе нет ВОВСЕ (пункт 6 критерия приёмки задачи),
    -- а не «НДС ноль»: та же природа, что у незаполненной цены установки —
    -- пусто это «услуги нет», а не значение.
    ADD COLUMN print_vat_note            text,

    -- Умолчания у обоих флагов — не вкус исполнителя: это значения, которые
    -- задача документирует у живого клиента дословно («Поле подписи для
    -- клиента: После дополнительного текста» — включено; «Поле подписи
    -- выдавшего товар: Выкл» — выключено). Переходящий клиент обязан получить
    -- свой чек, а не наш.
    ADD COLUMN print_client_signature    boolean NOT NULL DEFAULT true,
    ADD COLUMN print_issuer_signature    boolean NOT NULL DEFAULT false,

    -- Реквизиты организации для счёта на юр. лицо. Все NULL-уемые и все пустые
    -- у нового арендатора: у живого клиента они тоже пусты, и выдуманное
    -- умолчание уехало бы в счёт, который покупатель несёт в свою бухгалтерию.
    ADD COLUMN legal_name                text,
    ADD COLUMN legal_address             text,
    ADD COLUMN legal_inn                 text,
    ADD COLUMN legal_kpp                 text,
    ADD COLUMN legal_bank_name           text,
    ADD COLUMN legal_bank_bic            text,
    ADD COLUMN legal_bank_account        text,
    ADD COLUMN legal_bank_corr_account   text,
    ADD COLUMN legal_director            text,
    ADD COLUMN legal_chief_accountant    text;

COMMENT ON COLUMN ${tenant.schema}.company_setting.print_extra_text IS
    'Дополнительный текст чека и накладной: условия возврата, гарантии на товары. Пусто — строки в документе нет';
COMMENT ON COLUMN ${tenant.schema}.company_setting.print_vat_note IS
    'Пометка об НДС в документе. Пусто — строки нет вовсе, а не «НДС ноль»';
COMMENT ON COLUMN ${tenant.schema}.company_setting.print_client_signature IS
    'Печатать поле подписи клиента. Включено по умолчанию: так стоит у живого клиента';
COMMENT ON COLUMN ${tenant.schema}.company_setting.print_issuer_signature IS
    'Печатать поле подписи выдавшего товар. Выключено по умолчанию: так стоит у живого клиента';
COMMENT ON COLUMN ${tenant.schema}.company_setting.legal_inn IS
    'ИНН организации для счёта на юр. лицо; text, потому что это идентификатор с возможным ведущим нулём, а не число';
COMMENT ON COLUMN ${tenant.schema}.company_setting.legal_bank_account IS
    'Расчётный счёт организации; text по той же причине, что ИНН';

-- ЧТО ЭТИ КОЛОНКИ НЕ ПОКРЫВАЮТ — сказано здесь, чтобы следующий не считал
-- набор полным. У ориентира рядом с этими настройками живут ориентация печати,
-- размер шрифта доп. текста, печать по умолчанию, логотип и ОТДЕЛЬНЫЙ набор
-- тех же настроек для накладной в возврате. Их здесь нет намеренно: задача 0051
-- просит чек, накладную и счёт из сделки. Придут они своим changeset'ом,
-- и имена у них будут своими (print_return_extra_text и подобные) — нынешние
-- print_* относятся к чеку и накладной В СДЕЛКЕ.

