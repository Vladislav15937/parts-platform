--changeset partsflow:tenant-099-deal-item-added-at
--comment Момент, когда позиция попала в сделку: своя отметка у строки сделки (задача 0367)

-- Ответ владельца 23.10.2026 (tasks/0367, «Ответ владельца — 23 октября 2026»,
-- решение 8): «время у каждого товара своё» — время строки сделки в «Движении
-- товара» — момент, когда позиция попала в сделку, а не создание сделки.
-- До этого changeset'а своей отметки у deal_item не было, и лента брала
-- deal.created_at.
ALTER TABLE ${tenant.schema}.deal_item ADD COLUMN added_at timestamptz;

-- УЖЕ ЛЕЖАЩИМ СТРОКАМ — ИЗ ЖУРНАЛА ИЗМЕНЕНИЙ, А НЕ ДНЁМ НАКАТА. Настоящий
-- момент у большинства строк есть: deal_item в журнале изменений с самого
-- начала (сначала audit_trigger, tenant/008, с августа 2026 — AuditLogListener),
-- и запись INSERT несёт время вставки строки. Поэтому берётся она.
--
-- Где записи нет (строка вставлена мимо Hibernate: перенос резервов из Bazon
-- заводит сделку и её строки одной транзакцией), берётся заведение сделки —
-- то, что лента показывала до сих пор, то есть ничего не становится хуже.
--
-- greatest() с заведением сделки — не страховка, а смысл: позиция не могла
-- попасть в сделку раньше, чем сделка появилась. Это и есть случай переноса
-- позиций (Deal.transferTo): строка вставлена в прежнюю сделку и потом
-- переехала в новую, журнал хранит вставку в прежнюю, а «попала в эту
-- сделку» — не раньше её заведения. Перенос в сделку, заведённую задолго
-- до переноса, так получит момент её заведения, а не момент переноса: его
-- журнал хранит записью UPDATE, и разбирать снимки ради редкого случая
-- в changeset'е — догадка; названо в PR.
--
-- Новое умолчание now() не ставится до раздачи: ADD COLUMN ... DEFAULT now()
-- проставил бы день наката всем лежащим строкам — уверенный неверный ответ
-- на вопрос «когда». Тот же приём, что у part_applicability.set_at (tenant/094).
UPDATE ${tenant.schema}.deal_item i
   SET added_at = greatest(d.created_at, coalesce(
           (SELECT min(a.changed_at)
              FROM ${tenant.schema}.audit_log a
             WHERE a.table_name = 'deal_item'
               AND a.record_id = i.id
               AND a.operation = 'INSERT'),
           d.created_at))
  FROM ${tenant.schema}.deal d
 WHERE d.id = i.deal_id;

-- Умолчание раньше NOT NULL — это expand: прежний образ колонку не знает,
-- и вставленная им строка получает момент вставки, то есть ровно то, что
-- колонка и означает.
ALTER TABLE ${tenant.schema}.deal_item ALTER COLUMN added_at SET DEFAULT now();
ALTER TABLE ${tenant.schema}.deal_item ALTER COLUMN added_at SET NOT NULL;

COMMENT ON COLUMN ${tenant.schema}.deal_item.added_at IS
    'Момент, когда позиция попала в сделку. Строкам до задачи 0367 — из журнала изменений (вставка строки), без записи — заведение сделки; не раньше заведения сделки';

