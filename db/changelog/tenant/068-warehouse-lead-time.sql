--comment Срок поставки по складу: текст наличия и вилка дней заказа у каждого склада — задача 0008

-- В прайс Дрома уходит булево «доступна», и покупатель, приехавший за деталью
-- сегодня, узнаёт про срок уже по телефону. Склады у клиента в разных концах
-- города, и деталь с дальнего едет несколько дней — то есть «есть» означает
-- разное в зависимости от того, где позиция лежит. Здесь только форма данных;
-- подстановка текста в объявление, выбор лучшего срока у позиции на двух
-- складах и экран настройки — Java и TS той же задачи.
--
-- ПОЧЕМУ ЭТО КОЛОНКИ У СКЛАДА, А НЕ У ВЫГРУЗКИ И НЕ У КОМПАНИИ. Срок — свойство
-- места, где деталь физически лежит, а не прайс-листа и не предприятия: одна
-- и та же выгрузка отдаёт товар с обоих складов, и один текст на компанию
-- обещал бы покупателю срок ближнего склада для детали с дальнего. Это ровно
-- тот же довод, по которому реквизиты продавца стали колонкой у склада
-- в tenant/067: печатает и отдаёт тот, кто продал, а продал — склад.
--
-- ПОЧЕМУ ТЕКСТ НАЛИЧИЯ — СВОБОДНЫЙ, А НЕ СПРАВОЧНИК ИЗ ДВУХ ЗНАЧЕНИЙ. Слова
-- выбирает владелец и пишет их для покупателя на площадке («в наличии»,
-- «под заказ», «на складе в Японии»). Перечень с нашими формулировками уехал бы
-- покупателю от имени разборки, которая их не писала, и сузить его обратно
-- было бы уже нельзя — объявления с чужими словами площадка уже показала.
-- Проверка длины и приведение пробелов — в Java, где они умеют сказать словами.
--
-- ПОЧЕМУ ДНИ — int, А НЕ interval И НЕ ДАТА. Это срок доставки «через столько-то
-- дней», а не момент: даты пришлось бы двигать каждый день, а interval дал бы
-- точность, которой у человека нет — он называет «2–4 дня», а не часы.
--
-- ПОЧЕМУ NULL ВО ВСЕХ ТРЁХ. NULL означает «владелец не задавал», и выгрузка
-- на таком складе ведёт себя ровно как раньше — пункт 5 критерия приёмки
-- задачи: молча ничего не выдумываем. Выдуманное умолчание («под заказ»,
-- «1 день») уехало бы в объявление как обещание разборки, которого она
-- не давала, и у всех складов всех арендаторов разом — у клиента сегодня
-- все три колонки пусты.
--
-- А ВОТ НОЛЬ — ЗАКОННОЕ ЗНАЧЕНИЕ, И ЭТО НЕ ТОТ СЛУЧАЙ, ЧТО У ЦЕНЫ УСТАНОВКИ.
-- Ноль дней значит «сегодня, ждать не надо» (в критерии приёмки складу
-- «Ткацкая» ставят «в наличии», дней 0), то есть содержательный ответ
-- покупателю. У незаполненной цены установки пусто и ноль означают одно —
-- «услуги нет»; здесь отсутствие это NULL, и смешивать их нельзя: склад
-- со сроком 0 обязан отличаться от склада, которому срок не задавали.
ALTER TABLE ${tenant.schema}.warehouse
    -- Текст наличия этого склада, который покупатель читает в объявлении.
    ADD COLUMN availability_note text,

    -- Нижняя и верхняя границы вилки дней заказа: «2–4 дня». Заданная одна
    -- граница законна — «от 2 дней» и «до 4 дней» оба осмысленны для
    -- покупателя, и требовать обе значило бы заставлять владельца выдумывать
    -- вторую.
    ADD COLUMN order_days_from    int,
    ADD COLUMN order_days_to      int;

-- Отрицательных дней нет, и верхняя граница не меньше нижней, когда заданы обе.
-- Каждое условие прикрыто своим IS NULL намеренно: NULL'ы ограничение обязаны
-- проходить — у клиента сегодня все три колонки пусты, и накат не должен падать
-- ни на одной живой схеме. Предела «сверху» (разумного максимума дней) здесь
-- нет: числа в задаче не названы, а придумывать его за владельца нельзя —
-- расширить границу потом безопасно, сузить обратно уже нет (тот же довод,
-- что у срока резервирования в tenant/066).
ALTER TABLE ${tenant.schema}.warehouse
    ADD CONSTRAINT warehouse_order_days_ck CHECK (
        (order_days_from IS NULL OR order_days_from >= 0)
        AND (order_days_to IS NULL OR order_days_to >= 0)
        AND (order_days_from IS NULL OR order_days_to IS NULL
             OR order_days_to >= order_days_from)
    );

COMMENT ON COLUMN ${tenant.schema}.warehouse.availability_note IS
    'Текст наличия этого склада для объявления на площадке: «в наличии», «под заказ». Свободный текст — слова выбирает владелец, справочника нет. NULL — владелец не задавал, выгрузка ведёт себя как раньше. Задача 0008';
COMMENT ON COLUMN ${tenant.schema}.warehouse.order_days_from IS
    'Нижняя граница вилки дней заказа с этого склада. 0 — «сегодня, ждать не надо», это значение, а не пустота. NULL — владелец не задавал. Задача 0008';
COMMENT ON COLUMN ${tenant.schema}.warehouse.order_days_to IS
    'Верхняя граница вилки дней заказа с этого склада; не меньше нижней, когда заданы обе. NULL — владелец не задавал. Задача 0008';

-- ЧЕГО ЭТИ КОЛОНКИ НЕ ПОКРЫВАЮТ — сказано здесь, чтобы следующий не считал
-- набор полным. Срок задаётся складу целиком, а не отдельной позиции и не виду
-- детали: «эта фара под заказ, а та с полки» на одном складе этими колонками
-- не выражается. Задача 0008 просит срок по складу, и живой клиент держит его
-- именно так. Придёт позиционный срок — придёт своим changeset'ом и своими
-- именами; нынешние order_days_* относятся К СКЛАДУ.

