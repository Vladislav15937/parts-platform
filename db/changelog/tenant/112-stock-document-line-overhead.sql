-- Что человек сможет (tasks/0386, tasks/0361): в строке поступления рядом
-- с «Закупочной ценой» ввести «Накладные расходы» (доставка, таможня,
-- погрузка) и увидеть в плитке документа «Наклад. расх.» не нулём. Поле
-- и итог — работа 0361; здесь только колонка, без которой их некуда писать.
--
-- Номер 112, а не 111, названный в задаче: 111 занят changeset'ом задачи
-- 0343 (PR 541, part_applicability), который ещё не в main. Этот сливается
-- после него.
--
-- СУММА НА ВСЮ СТРОКУ, А НЕ ЦЕНА ЗА ШТУКУ. У Bazon в строке поступления
-- «Закупочная цена» — за штуку (сумма документа = Σ количество × цена),
-- а «Накладные расходы» — число на строку: в критерии 0361 «2 шт по 1 750
-- и накладными 100 → Наклад. расх. = 100». Итог документа — сумма колонки;
-- разнесения накладных шапки по строкам у Bazon не видели, поля «накладные
-- на документ» нет. Вывод разведки, а не наблюдение проводки (tasks/0386).
--
-- НОЛЬ ПО УМОЛЧАНИЮ И NOT NULL — В ОТЛИЧИЕ ОТ price. У price NULL значит
-- «цены нет». Накладные у Bazon в строке — «0», не пусто: это число, и сумма
-- по колонке не должна спотыкаться о NULL. Лежащие строки (старые документы
-- и переезд) получают 0 — накладных у них не было.
--
-- ОТРИЦАТЕЛЬНЫЕ ЗАПРЕЩЕНЫ (CHECK >= 0) — умолчание задачи при неотвеченном
-- вопросе владельцу (tasks/0386, «Вопрос владельцу продукта», пункт 1:
-- скидка или возврат поставщика минусом?). У Bazon отрицательных не видели.
-- Разрешить потом — расширение (снять CHECK), запретить после того, как
-- минусы записаны, — сужение с уводом данных; поэтому начинаем с узкого.
-- Текст отказа человеку — не здесь: слова при вводе даёт 0361.
--
-- Входят ли накладные в себестоимость карточки — решение 0361 и владельца,
-- схема хранит число и логики не несёт.
--
-- Expand: прежний образ колонку не знает, вставляет строку без неё
-- и получает 0. Журнал изменений (AuditLogListener.AUDITED) таблицу
-- stock_document_line не ведёт, вьюх на ней нет, права рабочей роли
-- ALTER колонки не меняет.
ALTER TABLE ${tenant.schema}.stock_document_line
    ADD COLUMN overhead numeric(14,2) NOT NULL DEFAULT 0;

ALTER TABLE ${tenant.schema}.stock_document_line
    ADD CONSTRAINT stock_document_line_overhead_ck CHECK (overhead >= 0);

COMMENT ON COLUMN ${tenant.schema}.stock_document_line.overhead IS
    'Накладные расходы на всю строку документа (не на штуку; цена price — за штуку). 0 — нет. Итог документа — сумма по строкам. Задача 0386';

