--comment Условия выгрузки задаются колонками витрины, а не набором полей схемы

-- Отбор прайса состоял из шести условий, зашитых колонками таблицы: цена
-- от и до, состояние, склады, виды деталей, марки. Каждое седьмое условие
-- означало миграцию, правку генератора, счётчика и экрана — то есть релиз,
-- и владелец ждал его вместо того, чтобы отобрать самому.
--
-- Витрина склада к этому времени уже умеет отбирать по двадцати девяти
-- колонкам: производитель, модель, секция, заметка, штрихкод, даты правок,
-- «пусто» и «не пусто», поиск вхождением. Механизм проверен, список
-- отбираемых колонок отдаётся клиенту сервером, и заводить рядом второй
-- значило бы получить две правды об одном и том же — ровно ту болезнь,
-- от которой в проекте уже лечили белые списки вида товара и свойств колеса.
--
-- Поэтому храним не новые поля под каждое условие, а те же две карты, что
-- у витрины: точное равенство (выбор из списка значений) и вхождение
-- (набранное руками). Ключ карты — имя колонки из белого списка сервера;
-- неизвестное имя отбор отвергает, так что jsonb здесь не дыра для
-- произвольного SQL, а способ не расширять схему на каждое новое условие.
ALTER TABLE ${tenant.schema}.marketplace_account
    ADD COLUMN filter_columns jsonb NOT NULL DEFAULT '{}'::jsonb,
    ADD COLUMN filter_words   jsonb NOT NULL DEFAULT '{}'::jsonb;

COMMENT ON COLUMN ${tenant.schema}.marketplace_account.filter_columns IS
    'Отбор по колонкам витрины: точное равенство, «колонка → значение»';
COMMENT ON COLUMN ${tenant.schema}.marketplace_account.filter_words IS
    'Отбор по колонкам витрины: вхождение, «колонка → часть значения»';

--rollback ALTER TABLE ${tenant.schema}.marketplace_account DROP COLUMN filter_columns, DROP COLUMN filter_words;
