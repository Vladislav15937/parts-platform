-- Решение владельца продукта от 18 октября 2026 (tasks/0322, ответ «8-а
-- с возможностью заводить без состояния»): ожидаемую позицию заводят
-- с вопросом о состоянии, «б/у» предложено на форме, и можно выбрать
-- «Не указано». До этого схема пустого состояния не допускала, и позиции,
-- о которой владелец ничего не знал, молча доставалось «б/у» — слово,
-- которое после 0318 видят продавец и покупатель предзаказа.
--
-- ЗДЕСЬ СНИМАЕТСЯ ТОЛЬКО NOT NULL. Умолчание 'USED' и part_condition_ck
-- не трогаются, и оба намеренно.
--
-- Умолчание остаётся, потому что требование 3 задачи прямо запрещает менять
-- его для других путей заведения без решения: вставка, не назвавшая
-- состояния (прежний образ, импорт, перенос), получает 'USED', как и вчера.
-- «Без состояния» — это явный NULL от того, кто спросил человека, а не
-- побочный эффект забытой колонки. Снять умолчание значило бы молча
-- превратить каждую такую вставку в позицию без состояния.
--
-- Перечень остаётся, потому что `condition IN (...)` на NULL даёт NULL,
-- а CHECK отбивает только false: пустое состояние ограничение пропускает
-- само, а незнакомое слово по-прежнему отбивает. Пересоздавать его ради
-- `IS NULL OR` незачем — смысл тот же, а сторож совместимости увидел бы
-- снятое и заведённое заново ограничение.
--
-- Вьюх и индексов на part.condition нет (перебор db/changelog 18.10.2026),
-- отбор выгрузки marketplace_account.conditions — отдельная колонка-массив,
-- её этот changeset не касается. Что в коде теперь видит NULL — в PR.
ALTER TABLE ${tenant.schema}.part
    ALTER COLUMN condition DROP NOT NULL;

COMMENT ON COLUMN ${tenant.schema}.part.condition IS 'Состояние позиции: NEW, USED, REFURBISHED, CONTRACT. NULL — не указано (задача 0322): владелец не знает состояния, и слово не печатается. Умолчание USED — для вставок, не назвавших состояние вовсе';

-- ОТКАТ СУЖАЕТ, И ПОЭТОМУ СНАЧАЛА УВОДИТ ДАННЫЕ. На чистой базе (db/verify.sh,
-- шаг 7) пустых нет, и SET NOT NULL проходит и без UPDATE; у клиента,
-- заведшего хоть одну позицию без состояния, он ответил бы «column contains
-- null values», и разворот встал бы. Та же порода, что у tenant/062 и 070.
--
-- КУДА УВОДИТСЯ: в 'USED'. Отказать словами — значит оставить откат, который
-- не откатывается. 'USED' — умолчание колонки, то есть ровно то, что
-- позиция получила бы до этого changeset'а, не выбери человек ничего; 'NEW'
-- переобещал бы покупателю, 'REFURBISHED' и 'CONTRACT' приписали бы
-- происхождение, которого никто не называл. Цена — то самое ложное «б/у»,
-- от которого задача уходит, и она названа в пометке ниже.
