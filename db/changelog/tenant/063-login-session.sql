--changeset partsflow:tenant-063-login-session
--comment Журнал сессий: вход, выход, устройство, длительность, неудачные попытки

-- Вторая половина задачи 0043 (решения владельца продукта от 8 и 9 сентября
-- 2026): «владелец мог видеть входы, выходы, с какого устройства, длительности
-- сессий и тд и тп». Вход — не изменение строки в базе, и audit_log его
-- не видит по природе: его пишет слушатель Hibernate. До этого changeset'а
-- о входах не оставалось ничего, кроме tenant_member.last_login_at, а та
-- перезаписывается — предыдущий вход не хранился нигде.
--
-- ОДНА ТАБЛИЦА НА ВХОДЫ И НА ОТКАЗЫ. «Пять отказов подряд ценнее ста успешных
-- входов» (docs/sessions.md, §3), и спрашивают о них тем же вопросом и в том
-- же списке: «кто заходил в кабинет». Разложенные по двум таблицам, они дали
-- бы два запроса, две страницы и разъезжающийся порядок строк. Отказ
-- отличается от входа тем, что у него нет сессии: session_key, last_seen_at
-- и ended_at у него пусты, и уборка зависших его не трогает.
--
-- ЭТА ТАБЛИЦА НЕ ЖУРНАЛ В СМЫСЛЕ SchemaGrants, и это осознанно. Три журнала
-- (stock_movement, audit_log, customer_account_entry) отданы рабочей роли
-- только на SELECT и INSERT — их нельзя переписать даже приложению. Запись
-- о сессии по своему устройству дописывается: активность отмечается по ходу
-- работы, конец — при выходе. Сделать её неизменяемой значит завести таблицу
-- событий и писать строку на каждую отметку активности: у десяти сотрудников
-- за смену это тысячи строк вместо десяти. Цена названа прямо: правку журнала
-- сессий прямым SQL не отбивает ничто — ровно как у трёх дыр из корневого
-- CLAUDE.md.
CREATE TABLE ${tenant.schema}.login_session
(
    id              bigserial PRIMARY KEY,

    -- Пусто у отказа с неизвестным логином: человека, которого нет, не на кого
    -- сослаться. Сам введённый логин при этом сохраняется — по нему и видно,
    -- что подбирают.
    member_id       bigint REFERENCES ${tenant.schema}.tenant_member (id),
    login_attempted text        NOT NULL,

    -- Роль снимком, тем же решением, что у audit_log.changed_by_role: роль
    -- живёт одной колонкой в tenant_member и переписывается на месте, поэтому
    -- подтянутая при чтении она соврала бы задним числом про человека,
    -- которого перевели.
    member_role     text,

    outcome         text        NOT NULL
        CONSTRAINT login_session_outcome_ck CHECK (outcome IN ('SUCCESS', 'FAILED')),
    -- Почему не пустили: BAD_CREDENTIALS или DISABLED. Наружу человеку эти два
    -- случая по-прежнему неразличимы (форма входа не должна работать
    -- справочником сотрудников) — а владельцу своей организации различимы,
    -- и «сотрудник ломится выключенной учётной записью» это другой разговор,
    -- чем «подбирают пароль».
    failure_reason  text,

    -- Суррогат сессии, а не сама её cookie: «журнал не должен становиться
    -- складом действующих ключей» (docs/sessions.md, §3). Пишется хеш
    -- идентификатора; по нему находят запись при выходе и при отзыве,
    -- а войти по нему нельзя.
    session_key     text,

    started_at      timestamptz NOT NULL DEFAULT now(),
    -- Последняя активность. Обновляется не чаще раза в несколько минут —
    -- запись в базу на каждый клик это и есть та единственная настоящая
    -- трудность, о которой предупреждает справка.
    last_seen_at    timestamptz,

    ended_at        timestamptz,
    end_reason      text
        CONSTRAINT login_session_end_reason_ck
            CHECK (end_reason IN ('LOGOUT', 'EXPIRED', 'REVOKED')),
    -- Чем именно отозвана: «смена пароля», «сотрудник выключен». Показывается
    -- рядом с «Завершена в 14:20» — без этого владелец видит, что сессию
    -- оборвали, и не видит, почему.
    end_detail      text,

    -- Адрес и строка браузера — сырыми и навсегда. Разбор («Chrome
    -- на Windows») делается на показе: библиотеки разбора обновляются,
    -- браузеры меняют формат строки, а Chrome с 2023 года отдаёт
    -- «замороженный» User-Agent. Разобрав при записи, через год получим
    -- журнал с неверными данными и без возможности переразобрать.
    -- Решение владельца продукта от 9 сентября 2026.
    ip              text,
    user_agent      text
);

COMMENT ON TABLE ${tenant.schema}.login_session IS
    'Журнал сессий: входы, выходы, устройство, длительность и неудачные попытки входа. Задача 0043';

COMMENT ON COLUMN ${tenant.schema}.login_session.last_seen_at IS
    'Последняя активность. Длительность работы считается по ней, а не по ended_at: закрыл ноутбук в 18:00, сессия истекла в 18:30 — «работал полчаса лишних» было бы ложью';

COMMENT ON COLUMN ${tenant.schema}.login_session.session_key IS
    'Хеш идентификатора сессии, не сам идентификатор: журнал не должен становиться складом действующих ключей';

-- Журнал открывают свежим сверху, и это его единственный порядок.
CREATE INDEX login_session_started_idx
    ON ${tenant.schema}.login_session (started_at DESC);

-- По нему ищут, кого отзывать при смене пароля, и кого закрывать уборкой
-- зависших. Частичный: закрытых сессий со временем станет на порядки больше,
-- чем открытых, и полный индекс рос бы вместе с историей.
CREATE INDEX login_session_open_idx
    ON ${tenant.schema}.login_session (member_id)
    WHERE ended_at IS NULL AND outcome = 'SUCCESS';

-- По ключу находят свою запись выход и отметка активности — то есть запрос
-- на каждые несколько минут работы каждого сотрудника.
CREATE INDEX login_session_key_idx
    ON ${tenant.schema}.login_session (session_key)
    WHERE session_key IS NOT NULL;

