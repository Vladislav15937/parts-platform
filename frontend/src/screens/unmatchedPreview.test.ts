import { describe, expect, it } from 'vitest';
import { preview } from './UnmatchedScreen';

describe('заголовок после сопоставления', () => {
  it('показывает подмену начала эталоном', () => {
    // Ради этого справочник и нужен: «мозги» становятся блоком управления.
    expect(preview(
      { name: 'мозги', sampleTitle: 'мозги Toyota Camry (б/у)' },
      'Блок управления двигателем',
    )).toBe('Блок управления двигателем Toyota Camry (б/у)');
  });

  // Разница между верным сопоставлением и ошибкой видна только здесь:
  // «Знак аварийной остановки» → «Набор инструментов» — это ложь в заголовке,
  // и увидеть её надо до нажатия. Кодом отличить нельзя, глазами — можно.
  it('показывает и то, что заголовок станет враньём', () => {
    expect(preview(
      { name: 'Знак аварийной остановки', sampleTitle: 'Знак аварийной остановки (б/у) F79' },
      'Набор инструментов',
    )).toBe('Набор инструментов (б/у) F79');
  });

  it('не меняет заголовок, который и есть само написание', () => {
    // Подмена стёрла бы сторону: левая фара слилась бы с правой.
    expect(preview({ name: 'Фара левая', sampleTitle: 'Фара левая' }, 'Фара'))
      .toBe('Фара левая');
  });

  it('не трогает чужой заголовок, в котором подменять нечего', () => {
    expect(preview({ name: 'фара', sampleTitle: 'Блок-фара Toyota (б/у)' }, 'Фара'))
      .toBe('Блок-фара Toyota (б/у)');
  });

  it('без карточек показывает сам эталон', () => {
    expect(preview({ name: 'запаска', sampleTitle: null }, 'Запасное колесо'))
      .toBe('Запасное колесо');
  });
});
