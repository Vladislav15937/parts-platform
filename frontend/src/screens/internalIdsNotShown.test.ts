import { describe, expect, it } from 'vitest';

/**
 * Экран не подставляет внутренний номер вместо имени (задача 0067).
 *
 * <p><b>Как это выглядело.</b> `деталь ${item.partId}`, `услуга
 * ${line.serviceId}`, `склад ${id}`, `· сделка ${p.dealId}` — запасной текст
 * там, где имя не приехало. Номер строки базы человеку не говорит ничего:
 * по нему не найти ни поиском, ни в разговоре, он меняется при переносе
 * и не переживает восстановления в другую схему, — а видит его продавец
 * ровно тогда, когда что-то пошло не так. Класс 3
 * `docs/defect-classes.md`: внутреннего представления на экране нет.
 *
 * <p><b>Почему перебор, а не проверка экранов по списку.</b> Та же причина,
 * что у `dealStatus.test.ts` (задачи 0062 и 0065): подстановку пишет каждый
 * экран **своим** `??`, и следующая заведётся снова — на экране, которого
 * в списке задачи не было. Ровно так 0062 нашла четыре написания пустого
 * клиента вместо двух названных, а 0065 — пятое, и пропустила бы его,
 * если бы искала по списку.
 *
 * <p><b>Кавычка считается и обратная.</b> На этом перебор задачи 0062
 * спотыкался: подстановка написана шаблонной строкой, а `OWN_WORD` искал
 * после `??` только `'` и `"`. Здесь шаблонная строка — основной случай,
 * и поэтому ищется именно она.
 *
 * <p><b>Запасной текст показывают не от хорошей жизни, и пустоту сюда
 * ставить нельзя.</b> `?? 'удалённая позиция'` стоит там, где карточку
 * удалили, а строка документа её пережила: строка без опознавательных
 * знаков вовсе была бы хуже номера. Поэтому перебор запрещает не запасной
 * текст, а **номер** в нём.
 */

const SOURCES = import.meta.glob('../**/*.{ts,tsx}', {
  query: '?raw', eager: true, import: 'default',
}) as Record<string, string>;

/**
 * Русское слово, за которым в текст подставляется значение с именем
 * внутреннего номера: `деталь ${item.partId}`, `склад ${id}`.
 *
 * <p>`${item.number}` под шаблон не подпадает намеренно — порядковый номер
 * позиции затем и заведён (задача 0060), чтобы его называли вслух. Ровно
 * так же законен `№${deal.number}`: номер документа человек и спрашивает.
 */
const GLUED_IN_TEMPLATE
  = /[А-Яа-яЁё]+[\s ]*\$\{[^}]*(?:[Ii]d|ID)\s*\}/;

/** Тот же номер, подставленный вместо имени: `?? \`склад ${id}\``. */
const FALLBACK_TO_ID = /\?\?[^\n]*\$\{[^}]*(?:[Ii]d|ID)\s*\}/;

/** `?? deal.id`, `number ?? created.id` — запасным значением внутренний номер. */
const FALLBACK_BARE_ID = /\?\?\s*[A-Za-z_][A-Za-z0-9_.]*\.id\b/;

/**
 * Номер пересчёта: его показывают человеку внутренним `id`, потому что
 * **своего номера у документа нет вовсе** — колонки `number` у
 * `inventory_session` в схеме не существует, а завести её может только
 * агент `migrator` (`db/changelog` правит он, по одному за раз).
 *
 * <p>Это **очередь работы, а не разрешение** — та же природа, что
 * у `KNOWN_WIDE` в `narrowViewport.test.tsx` и у пометки `ПРОБЕЛ`
 * в `tools/endpoint-coverage.py`. Поэтому список меряется наоборот:
 * пока колонки нет, эти места **обязаны** находиться, и появление номера
 * валит проверку с требованием убрать строку. Список, зеленеющий и после
 * починки, через месяц перестают читать.
 */
const QUEUE: { file: string; why: string }[] = [
  { file: './InventoryReconcile.tsx',
    why: 'номер пересчёта: колонки number у inventory_session нет, нужен migrator' },
  { file: './InventoryScreen.tsx',
    why: 'номер пересчёта на телефоне кладовщика: та же колонка' },
];

describe('внутренний номер не подставляется вместо имени', () => {
  it('перебор видит исходники', () => {
    // Перебор без файлов — зелёный тест ни о чём: промахнись glob мимо
    // каталога, и он молчал бы при любом коде.
    expect(Object.keys(SOURCES).length, 'перебор не нашёл ни одного исходника')
      .toBeGreaterThan(20);
  });

  it('номер строки базы не склеивается с текстом для человека', () => {
    const guilty: string[] = [];

    for (const [path, text] of Object.entries(SOURCES)) {
      // Фикстуры тестов законно собирают «деталь N» — они изображают
      // ответ сервера, а не экран.
      if (/\.test\.(ts|tsx)$/.test(path)) continue;
      if (QUEUE.some((q) => q.file === path)) continue;

      for (const line of text.split('\n')) {
        if (GLUED_IN_TEMPLATE.test(line) || FALLBACK_TO_ID.test(line)
            || FALLBACK_BARE_ID.test(line)) {
          guilty.push(`${path.replace('../', 'frontend/src/')}: ${line.trim()}`);
        }
      }
    }

    expect(
      guilty,
      'здесь человеку подставляется внутренний номер строки базы — по нему'
      + ' нельзя ни найти, ни спросить, ни позвонить. Назовите вещь словом'
      + ' («удалённая позиция», «неизвестный склад») либо попросите у сервера'
      + ' номер, которым её зовут люди (part.number, deal.number):',
    ).toEqual([]);
  });

  /**
   * Очередь работы меряется наоборот — см. комментарий у `QUEUE`.
   */
  it.each(QUEUE)('$file ещё показывает номер пересчёта ($why)', ({ file }) => {
    const text = SOURCES[file];
    expect(text, `${file} исчез — поправьте QUEUE`).toBeTypeOf('string');

    const shows = (text ?? '').split('\n').some((line) => /Сессия \{session\.id\}/.test(line)
      || /\{row\.id\}/.test(line));

    expect(
      shows,
      `${file} больше не показывает внутренний номер пересчёта — уберите его`
      + ' строку из QUEUE в этом тесте: список, зеленеющий и после починки,'
      + ' через месяц перестают читать',
    ).toBe(true);
  });
});
