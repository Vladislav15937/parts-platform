import { request } from '../api/client';
import { normalizeCode } from '../scan/codes';
import { conditionTitle } from '../inventory/catalog';
import { partNumber } from '../inventory/partNumber';

/**
 * Этикетки для термопринтера.
 *
 * <p>Печатаются браузером, а не отдаются драйверу принтера командами ZPL или
 * TSPL: у первых клиентов принтеры разные и заранее неизвестные, а печать
 * из браузера работает с любым, у которого есть драйвер в системе. Ценой
 * тому — необходимость выставить размер этикетки в диалоге печати один раз.
 */

export interface Cell {
  id: number;
  code: string;
  zone: string | null;
  active: boolean;
}

export function cellsOf(warehouseId: number): Promise<Cell[]> {
  return request<Cell[]>(`/api/organization/warehouses/${warehouseId}/cells`);
}

/**
 * Что печатается на этикетке ячейки.
 *
 * <p>Код приводится к латинице тем же {@link normalizeCode}, которым сканер
 * разбирает прочитанное. Иначе кириллическая «А», введённая человеком
 * в русской раскладке, вовсе не закодируется — Code128 её не знает, —
 * а напечатанная латинская `A` не совпала бы с базой при сверке глазами.
 */
export interface CellLabel {
  kind: 'cell';
  /** Что кодируется в штрихкод: только латиница и цифры. */
  code: string;
  /** Что печатается крупно: то же, что видит кладовщик в системе. */
  title: string;
  note: string | null;
}

export function cellLabel(cell: Cell, warehouseName: string): CellLabel {
  return {
    kind: 'cell',
    code: normalizeCode(cell.code),
    title: cell.code,
    note: cell.zone === null ? warehouseName : `${warehouseName} · ${cell.zone}`,
  };
}

export interface PartLabel {
  kind: 'part';
  /** Что кодируется в штрихкод: Номер товара цифрами, без пробелов разрядов. */
  code: string;
  /** Что печатается крупно: Номер товара так, как его видит человек, — «300 001». */
  number: string;
  /** Наименование детали — строкой под номером. */
  title: string;
  note: string | null;
}

/**
 * Этикетка детали.
 *
 * <p><b>Кодируется Номер товара</b> — порядковый номер позиции (задача 0366,
 * решение владельца продукта 19.10.2026 «Всё как у bazon», вариант «а»).
 * До неё кодировался неугадываемый публичный код: этикетка уезжает
 * к покупателю, и порядковый номер сказал бы ему, сколько позиций на складе.
 * Довод потерян сам после 0334 — номер и так стоит `id` каждого объявления
 * Дрома, — а клиент, переехавший с ориентира, сканирует свои наклейки
 * с Номером товара и обязан находить позицию. Прежние наклейки с публичным
 * кодом не умирают: сканер находит позицию по обоим (`resolvePartScan`).
 *
 * <p><b>Вёрстка до обхода ориентира — умолчание исполнителя</b> (задача 0366,
 * раздел «Ответ владельца»: что напечатано у ориентира, снаружи не видно):
 * Номер товара крупно сверху, под ним наименование, затем состояние с ценой
 * и штрихкод. Цифр под штрихкодом нет: крупный номер над ним — те же цифры,
 * и набирают их руками с него, а на 58×40 лишней строки нет.
 *
 * <p>Состояние — полным словом перед ценой, в той же строке: «контрактная ·
 * 12 500 ₽» (задача 0314). До неё его несла только пометка в наименовании,
 * а пометка из наименования уходит (0315, 0316) и после смены состояния
 * и сегодня врёт (0304).
 */
export function partLabel(
  number: number | string,
  title: string,
  // Числом или строкой: витрина склада отдаёт цену числом, поиск продавца —
  // строкой. Приводит её всё равно `Number`, и одна этикетка на оба места
  // дороже, чем один лишний тип в подписи.
  price: string | number | null,
  /** Код состояния (`PartCondition`); слово ставит {@link conditionTitle}. */
  condition: string | null | undefined,
): PartLabel {
  const parts = [
    conditionTitle(condition),
    price === null ? null : `${Math.round(Number(price)).toLocaleString('ru-RU')} ₽`,
  ].filter((part): part is string => part !== null);
  return {
    kind: 'part',
    code: String(number).replace(/\D/g, ''),
    number: partNumber(number),
    title,
    note: parts.length === 0 ? null : parts.join(' · '),
  };
}

export type Label = CellLabel | PartLabel;

/**
 * Сколько этикеток на позицию (задача 0371).
 *
 * <p>Три режима и их слова — с ориентира дословно: клиенты приходят оттуда
 * и узнают окно по ним. «По количеству товара в остатке» — пришло пять
 * одинаковых, и наклейка нужна на каждую штуку, а не на карточку.
 */
export type CopiesMode = 'one' | 'stock' | 'given';

export const COPIES_MODES: { mode: CopiesMode; title: string }[] = [
  { mode: 'one', title: 'По одной этикетке на товар' },
  { mode: 'stock', title: 'По количеству товара в остатке' },
  { mode: 'given', title: 'Указанное количество на товар' },
];

/**
 * Предел числа копий, набранного руками: этикетка — страница рулона, и лишний
 * ноль в поле («100» вместо «10») — это девяносто наклеек в корзину.
 */
export const COPIES_LIMIT = 100;

/**
 * Что не так с набранным числом копий; `null` — годится.
 *
 * <p>Одно выражение на кнопку и на подпись под полем: разойдясь, кнопка
 * гасла бы молча или подпись называла бы не ту причину.
 */
export function copiesProblem(typed: string, field: string): string | null {
  const text = typed.trim();
  if (text === '') return `Заполните «${field}».`;
  if (!/^\d+$/.test(text) || Number(text) < 1) {
    return `«${field}» — целое число от 1.`;
  }
  if (Number(text) > COPIES_LIMIT) {
    return `«${field}» — не больше ${COPIES_LIMIT}.`;
  }
  return null;
}

/**
 * Сколько этикеток у позиции в выбранном режиме.
 *
 * <p>Остаток — физический, вместе с отложенным под клиента: отложенная деталь
 * лежит на полке и подписана должна быть так же. Дробный остаток (метраж,
 * литры) округляется вверх — неподписанная половина хуже лишней наклейки.
 */
export function copiesOf(mode: CopiesMode, stock: number, given: number): number {
  if (mode === 'one') return 1;
  if (mode === 'given') return given;
  return Number.isFinite(stock) && stock > 0 ? Math.ceil(stock) : 0;
}

/** Каждая этикетка столько раз подряд, сколько копий ей назначено. */
export function repeated(items: { label: Label; copies: number }[]): Label[] {
  return items.flatMap(({ label, copies }) => Array.from({ length: copies }, () => label));
}

/**
 * Кодируется ли адрес штрихкодом.
 *
 * <p>Code128 не знает кириллицы вовсе. Часть букв это переживает: «А», «В»,
 * «Е», «К» и прочие неотличимы от латинских, и {@link normalizeCode} сводит
 * их к латинице — той самой, что напечатана на этикетке. А «Б», «Г», «Д»
 * двойника не имеют, и такой адрес не отсканируется никогда: ни с нашей
 * этикетки, ни с чужой.
 *
 * <p>Подменять их похожими нельзя ни в коем случае: «Б-02-1», напечатанная
 * как «B-02-1», сольётся с настоящей «В-02-1» — и кладовщик положит деталь
 * на другой стеллаж, ничего не заметив.
 */
export function scannable(code: string): boolean {
  const normalized = normalizeCode(code);
  for (const char of normalized) {
    const point = char.codePointAt(0) ?? 0;
    if (point < 32 || point > 126) {
      return false;
    }
  }
  return normalized.length > 0;
}

/**
 * Размер этикетки в миллиметрах.
 *
 * <p>58×40 — самый ходовой рулон у термопринтеров этой цены. Ширину модуля
 * штрихкода из неё и считаем: код должен уместиться с зонами покоя, иначе
 * сканер не найдёт его начало.
 */
export const LABEL_WIDTH_MM = 58;
export const LABEL_HEIGHT_MM = 40;

/** Поля этикетки: у термопринтеров край печати неточен на пару миллиметров. */
export const LABEL_PADDING_MM = 3;

/**
 * Подпись про размер этикетки — одна на все места печати.
 *
 * <p>Печатает браузер, а не драйвер принтера, поэтому размер выставляет
 * человек в диалоге печати: не выставит — принтер ужмёт штрихкод под лист A4,
 * и сканер перестанет его брать. Печатают этикетки из двух мест (экран
 * «Этикетки» пачкой и карточка позиции по одной), а подпись обязана быть
 * той же: разойдясь, вторая начала бы называть другой размер.
 */
export const LABEL_SIZE_NOTE =
  `Размер этикетки — ${LABEL_WIDTH_MM}×${LABEL_HEIGHT_MM} мм; выставьте его`
  + ' в диалоге печати и уберите поля, иначе принтер ужмёт штрихкод'
  + ' и сканер перестанет его брать.';
