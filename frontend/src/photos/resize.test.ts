import { describe, expect, it } from 'vitest';
import { fit } from './resize';

/**
 * Проверяется только расчёт размеров: сама перерисовка требует настоящего
 * холста, которого в jsdom нет. Это честная граница — расчёт ошибается тихо
 * и портит пропорции, а поломку холста видно сразу на первом же снимке.
 */
describe('вписывание снимка', () => {
  it('длинная сторона приводится к пределу, пропорции сохраняются', () => {
    // Типичный снимок телефона 4032×3024.
    expect(fit(4032, 3024)).toEqual({ width: 1600, height: 1200 });
  });

  it('вертикальный снимок уменьшается по высоте', () => {
    expect(fit(3024, 4032)).toEqual({ width: 1200, height: 1600 });
  });

  it('мелкое не растягивается', () => {
    // Растянутый снимок — это те же 300 КБ, но с потерей резкости.
    expect(fit(800, 600)).toEqual({ width: 800, height: 600 });
  });

  it('ровно по пределу остаётся как есть', () => {
    expect(fit(1600, 900)).toEqual({ width: 1600, height: 900 });
  });

  it('нулевой размер не делит на ноль', () => {
    expect(fit(0, 0)).toEqual({ width: 0, height: 0 });
  });
});
