/**
 * Часы, переведённые вперёд: тем же прогоном, но в другом месяце.
 *
 * <p><b>Зачем.</b> Календарная дата, зашитая в проверку, которая сравнивает
 * её с «сейчас», — это отложенное падение: зелёное сегодня, красное через
 * месяц, причём красное не там, где ошибка. Статический сторож
 * (`tools/date-mine-guard.py`) ловит литерал у поля, которое сравнивают
 * с «сейчас», но не ловит зависимость от дня недели, от месяца и от полуночи:
 * такую находит только прогон, у которого другое «сейчас».
 *
 * <p><b>Почему подменой `Date`, а не `faketime`.</b> `faketime` умеет сдвинуть
 * время и у node — проверено, — но не у всего: `/bin/date` и JVM на macOS
 * он не сдвигает вовсе (подпись мешает подгрузить его библиотеку), то есть
 * «прогон со сдвинутыми часами» получался бы разным на разных машинах,
 * а иногда и молча настоящим. Подмена `Date` в среде тестов работает
 * одинаково всюду, включая раннер.
 *
 * <p><b>Почему не `vi.useFakeTimers`.</b> Тот останавливает время и забирает
 * таймеры на себя, а здесь нужно живое время, но в другом месяце: половина
 * проверок ждёт `waitFor`, то есть настоящих таймеров. Здесь сдвинуто
 * показание и только оно.
 *
 * <p>Подключается не к обычному прогону, а к `vitest.shifted.config.ts`,
 * который зовёт `tools/clock-shift-run.sh`. Сдвиг — в `CLOCK_SHIFT_DAYS`,
 * по умолчанию 31 день.
 */
const days = Number(
  (globalThis as unknown as { process?: { env?: Record<string, string | undefined> } })
    .process?.env?.['CLOCK_SHIFT_DAYS'] ?? '31',
);

const SHIFT_MS = days * 24 * 60 * 60 * 1000;

const RealDate = Date;

/**
 * Дата со сдвинутым «сейчас».
 *
 * <p>Сдвигается только показание часов — `new Date()` без аргументов
 * и `Date.now()`. Разбор литерала не трогается: `new Date('2026-09-12')`
 * обязан остаться двенадцатым сентября, иначе сдвинулись бы обе стороны
 * сравнения сразу и прогон ничего бы не показал.
 */
class ShiftedDate extends RealDate {
  constructor(...args: ConstructorParameters<typeof Date> | []) {
    if (args.length === 0) {
      super(RealDate.now() + SHIFT_MS);
    } else {
      // @ts-expect-error — перенос аргументов как есть: любой из разрешённых
      // наборов конструктора Date, включая (год, месяц, …).
      super(...args);
    }
  }

  static override now(): number {
    return RealDate.now() + SHIFT_MS;
  }
}

globalThis.Date = ShiftedDate as unknown as DateConstructor;

// Строкой в прогоне: иначе «часы сдвинуты» остаётся утверждением о файле,
// а не о том, что случилось. Ровно та же причина, по которой возврат
// к моменту печатает, как он понял введённое время.
// eslint-disable-next-line no-console
console.log(
  `[часы сдвинуты на ${days} дн.] сейчас для проверок: ${new Date().toISOString()}`,
);
