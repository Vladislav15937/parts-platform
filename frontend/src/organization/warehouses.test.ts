import { describe, expect, it } from 'vitest';
import { unprintableCells } from './warehouses';

/**
 * Адреса ячеек, которые не напечатать штрихкодом.
 *
 * <p>Проверка стоит на заведении, а не на печати: переименовать десять полок
 * в первый день дешевле, чем через месяц объяснять кладовщику, почему сканер
 * их не видит.
 */
describe('печатаемость адреса ячейки', () => {
  it('пропускает латиницу и цифры', () => {
    expect(unprintableCells(['A-01-1', 'B-02-3', 'C10'])).toEqual([]);
  });

  // «А», «В», «Е», «К», «М», «Н», «О», «Р», «С», «Т», «Х» сканер сводит
  // к латинице — такие адреса читаются.
  it('пропускает кириллицу, у которой есть латинский двойник', () => {
    expect(unprintableCells(['А-01-1', 'В-02-1', 'Е-03-1', 'К-04-1'])).toEqual([]);
  });

  // А у «Б», «Г», «Д» двойника нет: подставить похожую нельзя — «Б-02-1»,
  // напечатанная как «B-02-1», сольётся с настоящей «В-02-1».
  it('находит кириллицу без двойника', () => {
    expect(unprintableCells(['А-01-1', 'Б-01-1', 'Г-02-1', 'B-03-1']))
      .toEqual(['Б-01-1', 'Г-02-1']);
  });

  it('находит строчные буквы: их в Code128 нет вовсе', () => {
    expect(unprintableCells(['стеллаж-1'])).toEqual(['стеллаж-1']);
  });
});
