import { describe, expect, it } from 'vitest';

import { goods, positions, plural } from './plural';

/**
 * Русское склонение при числе.
 *
 * <p>«Склад 1 товаров» и «Изменить 1 позиций» — то, что владелец видит
 * каждый раз, когда отбор сузился до одной строки. Помощник в проекте уже
 * был, но лежал внутри одного экрана и знал одно слово: соседние экраны
 * продолжали писать «товаров» при любом числе.
 */
describe('склонение при числе', () => {
  it('одна, две и пять склоняются по-разному', () => {
    expect(goods(1)).toBe('1 товар');
    expect(goods(2)).toBe('2 товара');
    expect(goods(5)).toBe('5 товаров');
  });

  /** Вторая десятка — исключение: «11 товаров», а не «11 товар». */
  it('вторая десятка не идёт по последней цифре', () => {
    expect(goods(11)).toBe('11 товаров');
    expect(goods(12)).toBe('12 товаров');
    expect(goods(14)).toBe('14 товаров');
    expect(goods(21)).toBe('21 товар');
  });

  /**
   * Разделитель разрядов неразрывный, и это не придирка: обычный пробел
   * позволяет строке переноситься посреди числа, и «35 844» превращается
   * в «35» на одной строке и «844» на другой.
   */
  it('разряды разделяются неразрывным пробелом', () => {
    expect(goods(35844)).toBe('35\u00a0844 товара');
    expect(positions(35844)).toBe('35\u00a0844 позиции');
  });

  it('слово задаётся вызывающим', () => {
    expect(plural(1, 'деталь', 'детали', 'деталей')).toBe('деталь');
    expect(plural(3, 'деталь', 'детали', 'деталей')).toBe('детали');
    expect(plural(0, 'деталь', 'детали', 'деталей')).toBe('деталей');
  });
});
