import { describe, expect, it } from 'vitest';
import { money, monthName, monthOf, shiftMonth,
  soldFooter,
  unknownShare,
} from './reports';

/**
 * Переключатель месяца в отчётах.
 *
 * <p>Ошибка здесь тихая и дорогая: отчёт покажет чужой месяц, а владелец
 * посчитает по нему зарплату. Наивное «прибавить месяц к сегодняшней дате»
 * на 31-м числе даёт 31 апреля, то есть первое мая, и апрель пропускается
 * целиком.
 */
describe('сдвиг месяца', () => {
  it('шаг назад и вперёд возвращает на место', () => {
    expect(shiftMonth(shiftMonth('2026-07', -1), 1)).toBe('2026-07');
  });

  it('через границу года', () => {
    expect(shiftMonth('2026-01', -1)).toBe('2025-12');
    expect(shiftMonth('2025-12', 1)).toBe('2026-01');
  });

  it('месяц с 31 днём не перескакивает через следующий', () => {
    // Март — 31 день, апреля 31-го не бывает. Отчёт за апрель обязан быть
    // достижим с обеих сторон.
    expect(shiftMonth('2026-03', 1)).toBe('2026-04');
    expect(shiftMonth('2026-05', -1)).toBe('2026-04');
  });

  it('месяц дня месяца не помнит', () => {
    // Отчёт всегда за месяц целиком: 31 января и 1 января дают один и тот же
    // период, иначе выборка зависит от того, когда её открыли.
    expect(monthOf(new Date(2026, 0, 31))).toBe('2026-01');
    expect(monthOf(new Date(2026, 0, 1))).toBe('2026-01');
  });
});

describe('подписи отчёта', () => {
  it('месяц называется по-русски', () => {
    expect(monthName('2026-07')).toBe('июль 2026');
  });

  it('пусто — это ноль, а не пустая клетка', () => {
    // У менеджера без наценки в отчёте должен стоять «0 ₽»: пустая клетка
    // читается как «неизвестно», и владелец пойдёт искать причину.
    expect(money(null)).toBe('0 ₽');
  });

  it('копейки в отчёте не показываются', () => {
    // Разряды toLocaleString разделяет неразрывным пробелом, и сравнивать
    // с обычным нельзя: тест падает на невидимой разнице.
    expect(money('9500.00').replace(/\u00a0/g, ' ')).toBe('9 500 ₽');
  });
});

/**
 * Доля выручки без указанного источника.
 *
 * <p>Пока она велика, сравнивать каналы нельзя: «Дром принёс мало» и «продавцы
 * не отмечают Дром» с экрана выглядят одинаково, а решение по ним разное —
 * снять размещение или поговорить с продавцами.
 */
describe('доля продаж без источника', () => {
  const report = (rows: Array<[number | null, string]>) => ({
    month: '2026-07',
    rows: rows.map(([sourceId, revenue]) => ({
      sourceId,
      sourceName: sourceId === null ? null : 'Канал',
      dealsCount: 1,
      revenue,
      margin: null,
      itemsWithoutCost: 0,
    })),
  });

  it('считает долю безымянной выручки, а не число сделок', () => {
    // Десять мелких продаж без источника и одна крупная с ним — это
    // хороший отчёт, а не плохой. Считать надо деньги.
    expect(unknownShare(report([[1, '9000'], [null, '1000']]))).toBeCloseTo(0.1);
  });

  it('всё без источника — единица', () => {
    expect(unknownShare(report([[null, '5000']]))).toBe(1);
  });

  it('пустой месяц не даёт деления на ноль', () => {
    expect(unknownShare(report([]))).toBe(0);
  });
});

/**
 * Подвал проданных позиций.
 *
 * <p>Ноль на месте себестоимости — утверждение о деньгах, которого никто
 * не проверял: у склада, приехавшего из чужой таблицы, закупок нет вовсе,
 * и «выгода 0» владелец читает как работу впустую. То же правило, что
 * у колонки «Наценка» в продажах по менеджерам.
 */
describe('подвал проданных позиций', () => {
  const totals = (items: number, withoutCost: number) => ({
    items, withoutCost, quantity: items, revenue: 800 * items, cost: 0, profit: 0,
  });

  it('без единой закупки себестоимость и выгода — прочерк, а не ноль', () => {
    const footer = soldFooter(totals(1, 1));
    expect(footer).toContain('себестоимость —');
    expect(footer).toContain('выгода —');
    // Выручка при этом настоящая: её знают все строки.
    expect(footer.replace(/\s/g, '')).toContain('проданона800');
  });

  it('когда закупка есть хоть у одной строки, суммы называются числами', () => {
    expect(soldFooter(totals(2, 1))).toContain('себестоимость 0');
  });
});
