import { describe, expect, it } from 'vitest';
import { money, monthName, monthOf, shiftMonth } from './reports';

/**
 * Переключатель месяца в отчётах.
 *
 * <p>Ошибка здесь тихая и дорогая: отчёт покажет чужой месяц, а владелец
 * посчитает по нему зарплату. Наивное «прибавить месяц к сегодняшней дате»
 * на 31-м числе даёт 31 апреля, то есть первое мая, и апрель пропускается
 * целиком.
 */
describe('сдвиг месяца', () => {
  it('шаг назад и вперёд возвращает на место', () => {
    expect(shiftMonth(shiftMonth('2026-07', -1), 1)).toBe('2026-07');
  });

  it('через границу года', () => {
    expect(shiftMonth('2026-01', -1)).toBe('2025-12');
    expect(shiftMonth('2025-12', 1)).toBe('2026-01');
  });

  it('месяц с 31 днём не перескакивает через следующий', () => {
    // Март — 31 день, апреля 31-го не бывает. Отчёт за апрель обязан быть
    // достижим с обеих сторон.
    expect(shiftMonth('2026-03', 1)).toBe('2026-04');
    expect(shiftMonth('2026-05', -1)).toBe('2026-04');
  });

  it('месяц дня месяца не помнит', () => {
    // Отчёт всегда за месяц целиком: 31 января и 1 января дают один и тот же
    // период, иначе выборка зависит от того, когда её открыли.
    expect(monthOf(new Date(2026, 0, 31))).toBe('2026-01');
    expect(monthOf(new Date(2026, 0, 1))).toBe('2026-01');
  });
});

describe('подписи отчёта', () => {
  it('месяц называется по-русски', () => {
    expect(monthName('2026-07')).toBe('июль 2026');
  });

  it('пусто — это ноль, а не пустая клетка', () => {
    // У менеджера без наценки в отчёте должен стоять «0 ₽»: пустая клетка
    // читается как «неизвестно», и владелец пойдёт искать причину.
    expect(money(null)).toBe('0 ₽');
  });

  it('копейки в отчёте не показываются', () => {
    // Разряды toLocaleString разделяет неразрывным пробелом, и сравнивать
    // с обычным нельзя: тест падает на невидимой разнице.
    expect(money('9500.00').replace(/\u00a0/g, ' ')).toBe('9 500 ₽');
  });
});
