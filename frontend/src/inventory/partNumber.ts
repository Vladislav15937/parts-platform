/**
 * Номер товара словами экрана — «300 001» (задача 0366).
 *
 * <p>Номер товара — порядковый номер позиции, как у ориентира: им деталь
 * называют вслух, он напечатан на этикетке и закодирован в её штрихкоде,
 * он же `id` объявления в прайсе Дрома (0334). Разряды через неразрывный
 * пробел — так пишет ориентир («300 001») и так ставит `toLocaleString`;
 * поиск на сервере понимает номер и с этим пробелом, и без него
 * (`PartNumberQuery`), поэтому скопированное с экрана находится.
 *
 * <p>Одно место на все экраны: склад, карточку, отчёты, журналы и отказы.
 * Две записи одного числа («300001» в списке и «300 001» в карточке)
 * заставляли бы сверять их глазами.
 */
export function partNumber(value: number | string | null | undefined): string {
  if (value === null || value === undefined || value === '') return '';
  const n = Number(value);
  return Number.isFinite(n) ? n.toLocaleString('ru-RU') : String(value);
}

