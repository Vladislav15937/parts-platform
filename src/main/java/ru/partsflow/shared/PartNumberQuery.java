package ru.partsflow.shared;

import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Номер позиции, набранный в строке поиска (задача 0064).
 *
 * <p><b>Зачем.</b> Номер завели затем, чтобы его произносили вслух:
 * «посмотри позицию 347». Второй собеседник обязан суметь его набрать —
 * иначе половина, ради которой номер и появился, не работает, и остаётся
 * только долистать тридцать пять тысяч строк.
 *
 * <p><b>Точное совпадение, а не подстрока.</b> Номер — это цифры, и цифры
 * есть во всех соседних полях: в номере производителя, в маркировке колеса,
 * в размере шины. Подстрочное {@code number::text ILIKE '%347%'} отдало бы
 * заодно позиции 1347, 3470 и 2347 — то есть добавило бы шум ровно того же
 * рода, от которого номер и должен спасать. Точное сравнение даёт из этой
 * ветки не больше одной строки: колонка уникальна.
 *
 * <p><b>Что считается номером.</b> Запрос целиком, без единого лишнего
 * слова: «347» — номер, «фара 347» — нет (там 347 это часть описания или
 * маркировки, и искать по нему позицию значит подменять вопрос). Знак
 * «№» (и «#») перед числом разрешён: на экране колонка так и подписана —
 * «№ позиции», — а в выдаче продавца строка начинается с «№ 347», и это
 * ровно то, что копируют и диктуют.
 *
 * <p><b>Лежит в {@code shared}, а не в {@code inventory}, и это про слои.</b>
 * Разбор читает ещё и журнал действий организации (задача 0168), а тот живёт
 * в {@code platform} — фундаменте, на который опираются остальные модули.
 * Ссылка оттуда на класс склада развернула бы зависимость задом наперёд,
 * а вторая копия регулярного выражения разошлась бы с первой на первой же
 * правке: тогда «№ 347» находило бы деталь на витрине и не находило её
 * в журнале. Та же причина, по которой здесь же лежат {@code AuditedColumns}
 * и {@code RetailCustomer}.
 *
 * <p><b>Разряды через пробел — тоже номер</b> (задача 0366): экраны пишут
 * Номер товара так, как его пишет ориентир, — «300 001», с пробелом тысяч
 * (неразрывным, как его ставит {@code toLocaleString('ru-RU')}), и именно эту
 * строку копируют и диктуют. Группы — строго по три цифры: «81170 33670»
 * (номер производителя из двух половин) номером не считается.
 *
 * <p><b>Длина ограничена</b> восемнадцатью цифрами: «12345678901234567890»
 * номером быть не может (номера идут подряд от единицы), а {@code Long}
 * на нём переполнится. Такой запрос остаётся обычным текстом.
 */
public final class PartNumberQuery {

    /** Весь запрос целиком — иначе это не «позиция 347», а слово в описании. */
    private static final Pattern NUMBER = Pattern.compile(
            "^[№#]?\\s*(\\d{1,18}|\\d{1,3}(?:[ \\u00A0\\u202F]\\d{3}){1,5})$");

    /** Пробелы разрядов: обычный, неразрывный и узкий неразрывный. */
    private static final Pattern GROUP_SPACE = Pattern.compile("[ \\u00A0\\u202F]");

    /**
     * Ветка `UNION` для витрины и для выдачи продавца — одна на обе.
     *
     * <p>Копия разошлась бы, и это уже случалось дважды: витрина искала
     * подстрокой там, где продавец искал морфологией, и «фара» отдавала
     * 521 позицию против 739. Правило записано в памятке модуля: **два
     * поиска по одному складу обязаны находить одно и то же**, а неправ
     * всегда тот, о ком не спрашивали.
     */
    public static final String UNION_BRANCH =
            "\n                          UNION SELECT id FROM part WHERE number = ?";

    /**
     * Ветка `UNION` по номеру объявления Дрома (задача 0274): запрос из одних
     * цифр может быть и номером позиции, и номером объявления, которое клиент
     * назвал по телефону («мне звонили по №125696381»). Сравнение точное —
     * подстрока притащила бы чужие объявления, — и ветка живёт там же, где
     * {@link #UNION_BRANCH}, у обоих поисков по складу сразу. Аргумент —
     * цифры запроса как есть ({@link #publicCodeArg}), а не {@code Long}:
     * в базе номер объявления лежит текстом.
     */
    public static final String DROM_AD_BRANCH =
            "\n                          UNION SELECT id FROM part WHERE drom_ad_number = ?";

    private PartNumberQuery() {
    }

    /**
     * Номер товара так, как его видит человек (задача 0366): «300 001»,
     * разряды неразрывным пробелом — тем же, что ставит экран
     * ({@code toLocaleString('ru-RU')}). Отказ, назвавший позицию иначе,
     * чем список, заставлял бы сверять две записи одного числа; а набранное
     * с этим пробелом находит {@link #parse}.
     */
    public static String format(long number) {
        String plain = Long.toString(number);
        StringBuilder out = new StringBuilder(plain.length() + plain.length() / 3);
        int head = plain.length() % 3 == 0 ? 3 : plain.length() % 3;
        out.append(plain, 0, head);
        for (int at = head; at < plain.length(); at += 3) {
            out.append('\u00A0').append(plain, at, at + 3);
        }
        return out.toString();
    }

    /**
     * Условие на публичный код позиции — одно место на все поиски (задача 0263).
     *
     * <p><b>Зачем.</b> Публичный код — двенадцать случайных шестнадцатеричных
     * знаков, и подстрока «347» встречается в нём примерно у каждой
     * четырёхсотой записи: на складе в 35 000 позиций запрос-номер приносил
     * десятки чужих строк рядом с одной настоящей. Когда весь запрос — номер,
     * код сравнивается точно (двенадцать цифр подряд — по-прежнему законный
     * запрос на код целиком); запрос с буквой («347A») номером не считается и
     * ищет по фрагменту, как раньше. Цена, решённая владельцем 10 октября
     * 2026: цифровой фрагмент кода больше не находится.
     *
     * <p>Условие и аргумент идут парой ({@link #publicCodeArg}): одно без
     * другого даёт либо {@code ILIKE} по голым цифрам, либо {@code =} по
     * строке с процентами — тихий ноль в выдаче.
     *
     * @param column колонка с кодом, с псевдонимом таблицы
     * @param byNumber запрос целиком является номером ({@link #parse} вернул не {@code null})
     */
    public static String publicCodeMatch(String column, boolean byNumber) {
        return column + (byNumber ? " = ?" : " ILIKE ?");
    }

    /**
     * Аргумент к {@link #publicCodeMatch}: цифры запроса как есть (с ведущими
     * нулями — они бывают в коде, а {@code Long} их съел бы) либо шаблон
     * вхождения.
     */
    public static String publicCodeArg(String raw, boolean byNumber) {
        String stripped = raw.strip();
        if (!byNumber) {
            return "%" + stripped + "%";
        }
        Matcher found = NUMBER.matcher(stripped);
        if (!found.matches()) {
            throw new IllegalArgumentException("Запрос не является номером");
        }
        return digits(found);
    }

    /** Цифры номера без пробелов разрядов: «300 001» → «300001». */
    private static String digits(Matcher found) {
        return GROUP_SPACE.matcher(found.group(1)).replaceAll("");
    }

    /**
     * Разбор открыт наружу: по номеру позиции ищут не только склад,
     * но и реестр сделок (задача 0069) — «мне звонили, позиция 347,
     * вы её вчера откладывали». Копия регулярного выражения в `sales`
     * разошлась бы с этой на первой правке, и тогда «№ 347» находило бы
     * деталь на витрине и не находило сделку с ней; класс лежит здесь,
     * потому что номер — свойство позиции, а не документа.
     *
     * @return номер позиции или {@code null}, если в строке не он —
     *         тогда поиск остаётся ровно таким, каким был
     */
    public static Long parse(String raw) {
        if (raw == null || raw.isBlank()) {
            return null;
        }
        Matcher found = NUMBER.matcher(raw.strip());
        return found.matches() ? Long.valueOf(digits(found)) : null;
    }
}
