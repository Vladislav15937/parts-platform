package ru.partsflow.shared;

/**
 * Контрагент розничной продажи: имя, по которому его узнаёт вся система.
 *
 * <p><b>Почему имя, а не колонка-признак.</b> Отдельного поля у {@code customer}
 * нет, а завести его может только {@code migrator} — отсюда и опознание
 * по имени, и запрет на переименование в {@code CustomerService.update}.
 * Появится колонка — это место исчезнет вместе с запретом.
 *
 * <p><b>Почему в {@code shared}, а не в {@code sales}.</b> Имя нужно двоим:
 * продажам, которые контрагента ищут и подставляют, и провижинингу, который
 * заводит его при создании арендатора. Провижининг живёт в {@code platform} —
 * фундаменте, на который опирается {@code sales}, а не наоборот, — и ссылка
 * оттуда на класс продаж развернула бы зависимость модулей задом наперёд.
 * Два написания рядом развернули бы её тоже, только молча: провижининг завёл
 * бы одно, экран продажи искал бы другое и завёл бы второго контрагента при
 * первой же продаже.
 */
public final class RetailCustomer {

    /**
     * «Частное лицо» — то, что стоит в поле клиента, пока покупатель
     * не назвался. Слово взято у ориентира, из которого приходят клиенты.
     */
    public static final String NAME = "Частное лицо";

    private RetailCustomer() {
    }
}
