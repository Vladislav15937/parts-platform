package ru.partsflow.shared;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Вещь, которой нет: как сказать об этом человеку и куда девать её номер.
 *
 * <p><b>Зачем отдельным перечислением.</b> Отказ «Сделка не найдена: 118»
 * называет человеку номер строки в базе. По нему нельзя ни найти, ни
 * спросить, ни позвонить: он ничего не значит для человека, меняется при
 * переносе и не переживает восстановления в другую схему, — а видит его
 * владелец ровно тогда, когда что-то пошло не так и надо понять, что делать.
 * Таких отказов в проекте было тридцать с лишним, в девяти файлах, и каждый
 * писал своё: двоеточие с номером, свой падеж, своё (или никакое)
 * продолжение.
 *
 * <p><b>Два края задачи 0067, и оба держит этот класс.</b> Первый: человеку
 * нужны слова, из которых понятно, <b>что делать</b>. Второй: номер нужен
 * разработчику — без него разбор жалобы невозможен, — и потому он не
 * исчезает, а уходит в лог. До этой правки было наоборот: номер ехал
 * человеку, а в логе не оставалось ничего, потому что
 * {@code ApiExceptionHandler.badRequest} ничего не пишет.
 *
 * <p><b>Почему фразы целиком, а не «вещь» плюс общий хвост.</b> Падежи:
 * «Склад не найден», «Поставка не найдена», «Наименование не найдено» —
 * из кусков это не собрать, не соврав. Тот же довод и то же устройство,
 * что у {@link ru.partsflow.inventory.MoneyField}, где падежи тоже стоят
 * прямо в перечислении.
 *
 * <p><b>Почему продолжение у всех одно.</b> «— обновите страницу, список
 * устарел» не выдумано здесь: так с задачи 0065 отвечают
 * {@code CustomerService}, {@code PaymentSourceService},
 * {@code DealSourceService} и {@code PrintSettingsService}. Это перенос уже
 * принятого в проекте решения, а не новая формулировка — выбирать слова
 * экрана исполнитель не вправе. И оно верно по существу: единственный
 * способ попасть в такой отказ через интерфейс — вещь убрали, пока список
 * был открыт.
 *
 * <p><b>Что этот класс не делает.</b> Он не превращает отказ в 404 и не
 * меняет классификацию: {@link IllegalArgumentException} по-прежнему уезжает
 * как 400 ({@code ApiExceptionHandler}), и офлайн-очередь приёмки по-прежнему
 * читает его как «требует внимания», а не «повторять вечно».
 *
 * <p><b>Цена, названная вслух.</b> В логе остаётся вещь и номер, но не
 * вызывающий: {@code Logger} здесь один на все места. Вызывающего в строке
 * нет намеренно — стек на каждую опечатку в номере это шум в логе, который
 * читают ровно тогда, когда ищут другое. Для разбора жалобы вещи и номера
 * хватает: субъекты узкие, и мест, бросающих каждый, единицы.
 */
public enum NotFound {

    PART("Запчасть не найдена"),

    PHOTO("Фотография не найдена"),

    WAREHOUSE("Склад не найден"),

    CELL("Ячейка не найдена"),

    /** Склад-приёмник перевозки: отказ обязан различать «откуда» и «куда». */
    DESTINATION_WAREHOUSE("Склад назначения не найден"),

    SUPPLY("Поставка не найдена"),

    DONOR("Донор не найден"),

    STOCK_DOCUMENT("Складской документ не найден"),

    /** Слово экрана, а не базы: вкладка везде говорит «Пересчёт». */
    INVENTORY_SESSION("Пересчёт не найден"),

    MEMBER("Сотрудник не найден"),

    BRANCH("Филиал не найден"),

    CUSTOMER("Клиент не найден"),

    DEAL("Сделка не найдена"),

    DEAL_ITEM("Позиция не найдена"),

    DEAL_RETURN("Возврат не найден"),

    SERVICE("Услуга не найдена"),

    DEAL_SOURCE("Источник сделки не найден"),

    PAYMENT_SOURCE("Источник платежа не найден"),

    /** Эталонный вид детали из справочника. */
    PART_KIND("Эталон не найден"),

    PART_NAME("Наименование не найдено"),

    /** Прайс-лист площадки. Владелец зовёт его выгрузкой. */
    FEED("Выгрузка не найдена"),

    MARKETPLACE_ACCOUNT("Кабинет не найден");

    private static final Logger log = LoggerFactory.getLogger(NotFound.class);

    /** Что делать человеку. Одно на все вещи — см. javadoc класса. */
    private static final String ADVICE = " — обновите страницу, список устарел";

    private final String subject;

    NotFound(String subject) {
        this.subject = subject;
    }

    /** «Сделка не найдена» — в нужном падеже и без номера. */
    public String subject() {
        return subject;
    }

    /** Полный текст для человека: вещь плюс что делать. */
    public String message() {
        return subject + ADVICE;
    }

    /**
     * Отказ человеку, номер — в лог.
     *
     * @param id внутренний номер, который человеку показывать нельзя,
     *           а разработчику без него не разобрать жалобу
     */
    public IllegalArgumentException error(Object id) {
        log.warn("Не найдено: {} (id={})", subject, id);
        return new IllegalArgumentException(message());
    }
}
