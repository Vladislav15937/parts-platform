package ru.partsflow.publishing;

import java.util.Locale;
import java.util.regex.Pattern;

/**
 * Имя файла прайса — читаемый хвост постоянной ссылки.
 *
 * <p>Ссылку прописывает в кабинете площадки её техспециалист, руками,
 * по переданному тексту. Пока она кончалась сорока случайными символами
 * токена, её переносили с ошибками — а ошибку видно только по тому,
 * что объявления не появились: о неверном адресе площадка не сообщает
 * никому. Отсюда «…/drom-yardt-parts.xml», который человек сверяет глазами.
 *
 * <p><b>Проверяется до сохранения и словами.</b> Имя уезжает в адрес,
 * и пробел или кириллица в нём — это ссылка, которая не открывается;
 * узнать об этом после сохранения можно было бы только от площадки,
 * то есть через дни и через объявления, которых нет. Тот же {@code CHECK}
 * стоит и в схеме ({@code tenant/059}), но его отказ — это ответ базы,
 * а не человеку.
 *
 * <p><b>Пусто — это {@code null}, а не пустая строка.</b> Пустых строк
 * в уникальном индексе может быть только одна, и вторая выгрузка без имени
 * получила бы отказ на ровном месте. Ровно этим болел снятый штрихкод.
 */
public final class FeedFileName {

    /** То же условие, что в {@code CHECK} схемы: разойтись они не должны. */
    private static final Pattern ALLOWED = Pattern.compile("^[a-z0-9][a-z0-9._-]{0,59}\\.xml$");

    private FeedFileName() {
    }

    /**
     * Годится ли имя для адреса и для заголовка ответа.
     *
     * <p>Отдельным методом, чтобы условие жило в одном месте: выдача прайса
     * берёт имя файла из адреса, то есть из того, что человек набрал в строке
     * браузера, — и второй такой же образец рядом разошёлся бы с этим
     * на первой правке.
     */
    public static boolean isValid(String name) {
        return name != null && ALLOWED.matcher(name).matches();
    }

    /**
     * Приводит набранное к тому, что можно поставить в адрес.
     *
     * <p>Регистр снимается намеренно: адрес переписывают руками, и разница
     * между {@code Drom-Parts.xml} и {@code drom-parts.xml} — это два разных
     * адреса, различающихся невидимо для того, кто их переносит.
     *
     * <p>Расширение дописывается, если его не набрали: файл прайса всегда
     * {@code .xml}, и требовать напечатать это ещё раз незачем.
     *
     * @return имя файла либо {@code null}, если имени не задавали
     * @throws IllegalArgumentException имя нельзя поставить в адрес — с текстом
     *                                  для человека
     */
    public static String normalize(String typed) {
        if (typed == null || typed.isBlank()) {
            return null;
        }
        String typedName = typed.strip();
        if (typedName.chars().anyMatch(Character::isWhitespace)) {
            throw new IllegalArgumentException(
                    "В имени файла нельзя пробелы: адрес с пробелом площадка не откроет. "
                            + "Слова разделяют дефисом — «drom-parts.xml»");
        }
        String name = typedName.toLowerCase(Locale.ROOT);
        if (!name.endsWith(".xml")) {
            name = name + ".xml";
        }
        if (!ALLOWED.matcher(name).matches()) {
            throw new IllegalArgumentException(
                    "Имя «%s» в адрес не поставить: можно латинские буквы, цифры, дефис, точку "
                            .formatted(typedName)
                            + "и подчёркивание — не больше 64 знаков вместе с «.xml». "
                            + "Кириллица и пробелы в ссылке ломаются — «drom-parts.xml»");
        }
        return name;
    }
}
