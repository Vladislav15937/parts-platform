package ru.partsflow.inventory;

/**
 * Сторона по поперечной оси.
 *
 * <p>Одного поля «сторона» не хватает: у детали независимо задаются левое-правое,
 * переднее-заднее и верхнее-нижнее — «стойка передняя левая нижняя». Так же
 * устроен и формат прайса Дрома (поля {@code lr}, {@code fr}, {@code ud}).
 */
public enum LateralSide {
    LEFT,
    RIGHT,
    /**
     * Подходит и слева, и справа — «Левая, Правая» на карточке Дрома
     * (амортизатор клиента «цена за пару», задача 0277). Третье значение,
     * а не две отметки: «ни одна» уже выражена отсутствием стороны.
     * Отбор продавца по левой или правой стороне такую деталь находит.
     */
    BOTH
}
