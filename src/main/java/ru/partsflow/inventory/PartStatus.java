package ru.partsflow.inventory;

/**
 * Состояние карточки запчасти.
 *
 * <p><b>Это производное поле.</b> Его ведёт триггер {@code stock_movement_apply}
 * по журналу движений, как и остаток. Писать статус из кода нельзя — разойдётся
 * с остатком, и проданная деталь останется в поиске продавца.
 *
 * <p>Резерва здесь нет намеренно. Зарезервированность — следствие
 * {@code part_stock.qty_reserved}, и как состояние карточки она неверна: у детали
 * количеством 3 может быть зарезервирована одна. Та же причина, по которой
 * в {@link ru.partsflow.sales.DealStatus} нет «частично оплачен».
 */
public enum PartStatus {

    /** Карточка заведена, на склад не приходовалась. */
    DRAFT,

    /** Есть остаток хотя бы на одном складе. */
    IN_STOCK,

    /** Остаток обнулён продажей. Возврат от клиента вернёт в {@link #IN_STOCK}. */
    SOLD,

    /** Остаток обнулён списанием. */
    WRITTEN_OFF
}
