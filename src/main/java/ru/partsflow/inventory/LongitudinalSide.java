package ru.partsflow.inventory;

/** Сторона по продольной оси: перед или зад. См. {@link LateralSide}. */
public enum LongitudinalSide {
    FRONT,
    REAR,
    /**
     * Подходит и спереди, и сзади — «Переднее, Заднее» на карточке Дрома
     * (задача 0283; 37 объявлений первого клиента). Третье значение, а не
     * две отметки: «ни одна» уже выражена отсутствием стороны, как у
     * {@link LateralSide#BOTH}. Отбор продавца по переднему или заднему
     * такую деталь находит.
     */
    BOTH
}
