package ru.partsflow.inventory;

import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Оценка состояния запчасти.
 *
 * <p>Значения фиксированы намеренно: оценка уходит в объявления на площадки,
 * и маппинг должен быть один в один. Свободный текст здесь означал бы, что
 * у каждого приёмщика своя шкала, а в фид уходит непереводимое.
 *
 * <p><b>Название человеку живёт здесь же, а не рядом.</b> До задачи 0033 их
 * было три и все разные: {@code CASE} витрины переводил
 * {@code EXCELLENT/GOOD/FAIR/POOR}, форма правки предлагала те же четыре
 * несуществующих значения, а карточка и колонка печатали {@code NO_DEFECTS}
 * как есть. Ни одно из четырёх слов того {@code CASE}'а в базе встретиться
 * не может — {@code part_quality_grade_ck} держит другие четыре, — то есть
 * колонка «Оценка состояния» всегда уходила в запасную ветку и показывала
 * состояние: владелец видел «б/у» там, где спрашивал про оценку, и отбор
 * предлагал ему то же самое.
 *
 * <p>Поэтому слово и код лежат в одном месте, а выражение для SQL собирается
 * из них же — как у {@code SupplyKinds}: список, написанный рядом руками,
 * расходится с перечислением на первой правке, и расходится молча.
 */
public enum QualityGrade {

    /** Полностью исправна, состояние близкое к новому. */
    AS_NEW("Как новая"),

    /** Отличное состояние, минимальный износ, большой остаточный ресурс. */
    NO_DEFECTS("Без дефектов"),

    /** Рабочая, но с заметным износом: люфты, потёртости, сколы. */
    WITH_DEFECTS("С дефектами"),

    /** Сломана или сильно повреждена: под ремонт или на запчасти. */
    NEEDS_REPAIR("Требует ремонт");

    private final String title;

    QualityGrade(String title) {
        this.title = title;
    }

    /**
     * Как оценка называется человеку.
     *
     * <p>Слова взяты из системы, из которой приходят клиенты: они их узнаю́т,
     * и переезд запчасти с оценкой «Без дефектов» не должен превращать её
     * в «отличное».
     */
    public String title() {
        return title;
    }

    /** Словарь целиком: по нему сверяются слова экрана и слова сервера. */
    public static Map<String, String> titles() {
        Map<String, String> titles = new LinkedHashMap<>();
        for (QualityGrade grade : values()) {
            titles.put(grade.name(), grade.title);
        }
        return titles;
    }

    /**
     * То же выражением SQL: {@code alias} — псевдоним таблицы {@code part}.
     *
     * <p><b>Запасной ветки по состоянию здесь нет и не должно быть.</b>
     * Пустая оценка — это «не оценена», а не «б/у»: подставив состояние,
     * список значений отбора предлагал выбрать «б/у» в колонке «Оценка
     * состояния», и по настоящей оценке склад было не отобрать ни одним
     * значением.
     *
     * <p>Незнакомый код тоже уходит в {@code NULL}, а не показывается как
     * есть: колонку держит {@code part_quality_grade_ck}, и появиться там
     * чужое значение может только правкой базы мимо приложения.
     */
    public static String sqlLabel(String alias) {
        StringBuilder sql = new StringBuilder("CASE ").append(alias).append(".quality_grade");
        for (QualityGrade grade : values()) {
            sql.append(" WHEN '").append(grade.name()).append("' THEN '")
                    .append(grade.title).append("'");
        }
        return sql.append(" END").toString();
    }
}
