package ru.partsflow.platform.outbox;

import java.util.List;

/**
 * Транспорт событий. Домен про него не знает — это единственный компонент,
 * который с наибольшей вероятностью придётся заменить (Kafka, NATS, что-то ещё),
 * поэтому он спрятан за интерфейсом.
 *
 * <p>Реализации: {@code InMemoryEventTransport} (по умолчанию и в тестах — даёт
 * быстрые интеграционные тесты без поднятия брокера) и {@code KafkaEventTransport}
 * (профиль {@code kafka}).
 *
 * <p>Контракт: доставка at-least-once. Дубликаты возможны при повторе после сбоя,
 * поэтому <b>все потребители обязаны быть идемпотентными</b>.
 */
public interface EventTransport {

    /**
     * Отправляет пачку записей. Должен бросить исключение при неуспехе —
     * релей пометит записи опубликованными только после успешного возврата.
     */
    void send(List<OutboxRecord> batch);
}
