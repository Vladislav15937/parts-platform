package ru.partsflow.platform.outbox;

import java.util.Set;

/**
 * Потребитель доменного события.
 *
 * <p>Реализации живут в своих модулях рядом с тем, что делают: обработчик
 * выдачи сделки — в {@code publishing}, потому что он про выгрузку, а не
 * про продажи. Модуль-издатель про своих потребителей не знает и знать
 * не должен — в этом весь смысл событий.
 *
 * <p><b>Про идемпотентность.</b> Обработчику не нужно проверять, не приходило
 * ли событие раньше: это делает {@link EventDispatcher} по журналу
 * {@code processed_event}. Но повтор всё равно возможен — если процесс упал
 * между обработкой и записью в журнал, — поэтому операция обработчика должна
 * переживать выполнение дважды. Дельта на Дром переживает, потому что несёт
 * состояние позиции, а не приращение; списание остатка не пережило бы.
 *
 * <p>Исключение из {@link #handle} означает, что событие не обработано:
 * оно попадёт в {@code event_dead_letter} и не будет помечено обработанным.
 */
public interface EventHandler {

    /**
     * Имя для журнала обработанных событий.
     *
     * <p>Переименование обработчика равносильно новому потребителю: старые
     * события он увидит необработанными. Поэтому имя фиксированное и не берётся
     * из имени класса.
     */
    String name();

    /** Типы событий с версией: {@code deal.issued.v1}. */
    Set<String> handles();

    void handle(ConsumedEvent event);
}
