package ru.partsflow.platform.health;

import io.micrometer.core.instrument.MeterRegistry;
import io.micrometer.core.instrument.binder.MeterBinder;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;
import ru.partsflow.platform.config.WriteFreeze;
import ru.partsflow.platform.tenant.TenantMigrations;

/**
 * Пройдёт ли в этой базе запись — спрошено у самой базы, попыткой.
 *
 * <p><b>Что наблюдали на ячейке (задача 0196).</b> Сборка {@code app-green}
 * работала на замороженной базе {@code parts_green_68a6d90d2720} и отвечала
 * на {@code /actuator/readiness} пятью зелёными строками и {@code ready:true}.
 * Записать в эту базу при этом не мог никто и ничего: тот же контейнер каждые
 * несколько секунд писал в лог {@code cannot execute UPDATE in a read-only
 * transaction} (SQLSTATE 25006) из планировщика релея. Готовность не врала
 * ни одной проверкой — <b>у неё просто не было вопроса о записи</b>: проверка
 * {@code database} это {@code SELECT 1}, а {@code journals} спрашивает
 * {@code has_table_privilege}, то есть <b>права</b>, а права заморозкой
 * не меняются. Брошенная сборка поэтому выглядела здоровой сколько угодно
 * долго: healthcheck боевого compose стоит на том же адресе, и docker считал
 * контейнер здоровым.
 *
 * <p><b>Спрашивается не настройка, а попытка.</b> Прочитать
 * {@code default_transaction_read_only} из {@code pg_db_role_setting} — это
 * вопрос о настройке, и он отвечает мимо цели сразу двумя способами:
 * настройка роли старше настройки базы и отменяет заморозку (ровно это
 * проверяет {@code freezable} в {@code ops/deploy.sh}), а база в режиме
 * восстановления не пишет вовсе, ничего такого не имея. Поэтому здесь
 * делается ровно то, что делает любая запись, — и отбивается она тем же
 * {@code PreventCommandIfReadOnly}, тем же кодом 25006, что и настоящий
 * {@code INSERT}.
 *
 * <p><b>Проба бесплатна, и это замерено, а не предположено.</b>
 * {@code WHERE false} не находит ни одной строки: данные не меняются,
 * блокировок на строках нет, каталог не растёт. Транзакционного номера она
 * тоже не тратит — три пробы подряд оставили {@code xmax} снапшота на 748,
 * то есть {@code UPDATE 0} идентификатор не назначает. Это и есть причина,
 * по которой пробу не жалко звать на каждый опрос готовности (healthcheck
 * раз в 15 секунд) и на каждый сбор метрик (раз в 30 секунд).
 *
 * <p><b>Почему первым кандидатом был не он.</b> Первой пробой был
 * {@code pg_current_xact_id()} — «пусть база назначит номер транзакции,
 * а на замороженной это откажет». Живой прогон показал обратное: на базе
 * с {@code default_transaction_read_only = on} он <b>успешно</b> вернул 746.
 * Запись запрещает не назначение номера, а проверка команды, и «похоже
 * на запись» здесь недостаточно — годится только сама запись.
 *
 * <p><b>Пишем в {@code public.shedlock} намеренно.</b> Это таблица, в которую
 * приложение пишет на каждой задаче планировщика: она лежит в {@code public}
 * (арендатор и его {@code search_path} не нужны, транзакция тоже),
 * существует с {@code catalog/007}, и права на неё рабочей роли выдаёт
 * {@code ops/create-roles.sh} при заведении ячейки. Ни данных клиента,
 * ни журналов, ни сессий проба не касается. Нет таблицы или нет прав —
 * ответ «не проверена» с причиной, а не тихое «проходит».
 *
 * <p><b>Считается один раз на две поверхности</b> — готовность и метрика, —
 * по той же причине, по которой защита журналов посчитана один раз
 * в {@code JournalProtection}: посчитанное дважды разъезжается, и тогда
 * строка ответа и число в наблюдении отвечают на один вопрос по-разному.
 */
@Component
public class DatabaseWriteProbe implements MeterBinder {

    /**
     * Сама проба: запись, которая ничего не записывает.
     *
     * <p>{@code SET lock_until = lock_until} при {@code WHERE false} —
     * законный {@code UPDATE}, который база обязана либо выполнить (0 строк),
     * либо отбить как запись. Третьего ответа у неё нет, и именно поэтому
     * проба отвечает на вопрос «пройдёт ли запись», а не «как настроено».
     */
    static final String PROBE =
            "UPDATE public.shedlock SET lock_until = lock_until WHERE false";

    /**
     * Метрика по ячейке: 1 — запись заморожена, 0 — проходит, {@code NaN} —
     * не проверена.
     *
     * <p>Именно число, а не только строка в готовности: брошенную сборку надо
     * уметь <b>назвать</b>. Метка сборки приезжает даром — {@code ops/prometheus.yml}
     * опрашивает обе сборки по DNS и ставит {@code build} из имени, по которому
     * нашёл. То есть «на замороженной базе стоит зелёная» — это
     * {@code partsflow_database_write_frozen{build="green"} == 1}, и у вопроса
     * «какая именно сборка виновата» впервые появляется ответ: правило
     * {@code РелейВстал} сворачивает свой {@code max()} по сборкам намеренно
     * и назвать виновную не может.
     *
     * <p>{@code NaN} для «не проверена» выбран вместо нуля сознательно: ноль
     * означал бы «запись проходит», то есть выдал бы незнание за здоровье,
     * и правило по такому ряду молчало бы там, где надо разбираться.
     */
    static final String FROZEN_GAUGE = "partsflow.database.write.frozen";

    private final JdbcTemplate jdbc;

    public DatabaseWriteProbe(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    /** Три состояния, и все три называются словами, а не выводятся читателем. */
    public enum State {

        /** Запись проходит — обычная работа. */
        PASSES,

        /** Запись отбита базой: заморожена. Законно, но должно быть названо. */
        FROZEN,

        /** Спросить не вышло: нет таблицы, нет прав, база не отвечает. */
        UNKNOWN
    }

    /**
     * @param state    что именно с записью
     * @param database имя базы — только когда она заморожена: «какая именно»
     *                 и есть первый вопрос того, кто пришёл разбираться
     *                 с брошенной сборкой
     * @param reason   почему не проверена, если не проверена
     */
    public record Answer(State state, String database, String reason) {

        /**
         * Что показать человеку.
         *
         * <p>Про заморозку сказано отдельно от прав журналов, и это требование,
         * а не вежливость: на замороженной базе {@code journals} честно зелёная
         * (права-то в порядке), и разница между «журналы заперты» и «писать
         * нельзя вообще» обязана быть видна из текста, а не достраиваться
         * читателем.
         */
        public String detail() {
            return switch (state) {
                case PASSES -> "Запись проходит: проба записи в public.shedlock прошла";
                case FROZEN -> ("Запись запрещена: база заморожена (%s). "
                        + "Сборка обслуживает только чтение — пишущее действие "
                        + "ответит человеку «Идёт обновление». Это законно на время "
                        + "выкладки и у прежней базы, оставшейся рядом; если так "
                        + "надолго — сборка брошена на слепке, и живут люди "
                        + "на другой. Права журналов тут не при чём: про них "
                        + "отвечает проверка journals, и заморозка их не меняет")
                        .formatted(database == null ? "имя не спросить" : database);
                case UNKNOWN -> "Запись не проверена: " + reason;
            };
        }
    }

    /**
     * Спрашивает базу и возвращает ответ.
     *
     * <p>Транзакция не нужна и не годится: запрос идёт в {@code public},
     * а не в схему арендатора, и оборачивать пробу в транзакцию значило бы
     * спрашивать про транзакцию, которую открыли мы, а не про ту, в которой
     * работают люди.
     */
    public Answer probe() {
        try {
            jdbc.update(PROBE);
            return new Answer(State.PASSES, null, null);
        } catch (RuntimeException e) {
            if (WriteFreeze.isFrozen(e)) {
                return new Answer(State.FROZEN, databaseName(), null);
            }
            // Причина — из самого глубокого исключения: обёртка Spring несёт
            // в сообщении весь текст запроса, и ответ готовности превращался
            // бы в простыню SQL вместо «нет прав» или «нет таблицы».
            return new Answer(State.UNKNOWN, null, TenantMigrations.rootMessage(e));
        }
    }

    /**
     * Имя замороженной базы.
     *
     * <p>Спрашивается отдельным запросом и уже после отказа: чтение
     * на замороженной базе работает — проверено живым прогоном, —
     * а до отказа имя никому не нужно.
     */
    private String databaseName() {
        try {
            return jdbc.queryForObject("SELECT current_database()", String.class);
        } catch (RuntimeException e) {
            // База перестала отвечать между пробой и вопросом об имени.
            // Про это скажет проверка database; здесь важно не подменить
            // ответ исключением.
            return null;
        }
    }

    @Override
    public void bindTo(MeterRegistry registry) {
        registry.gauge(FROZEN_GAUGE, this, probe -> switch (probe.probe().state()) {
            case FROZEN -> 1;
            case PASSES -> 0;
            case UNKNOWN -> Double.NaN;
        });
    }
}
