package ru.partsflow.platform.tenant;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.ApplicationRunner;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.stereotype.Component;
import ru.partsflow.platform.config.WriteFreeze;

/**
 * Накат общей схемы {@code catalog} при старте.
 *
 * <p>Схемы арендаторов мигрирует провижининг — каждая версионируется отдельно,
 * и трогать их на старте нельзя: пятьсот схем на подъёме приложения означают
 * минуты недоступности. А вот {@code catalog} и {@code public} общие на ячейку,
 * без них не поднимется ни один арендатор, и накатывать их руками — это ровно
 * тот забытый шаг, из-за которого схема нового клиента создаётся в пустоту.
 *
 * <p><b>Идёт до первого запроса, а не по расписанию.</b> Liquibase берёт
 * блокировку в {@code DATABASECHANGELOGLOCK}, поэтому несколько экземпляров
 * приложения, поднимающихся одновременно, не подерутся: первый мигрирует,
 * остальные ждут и видят, что делать нечего.
 *
 * <p><b>«До первого запроса» — не то же самое, что «до первого ответа».</b>
 * {@code ApplicationRunner} работает уже после того, как Tomcat принимает
 * подключения, то есть окно «порт отвечает, схема догоняется» настоящее.
 * Готовность приложения ({@code /actuator/readiness}) поэтому спрашивает
 * не этот класс и не факт его запуска, а состояние самой схемы —
 * {@link CatalogSchemaMigrator#pending()}.
 *
 * <p>Выключается свойством — на случай, когда миграциями управляет внешний
 * оркестратор и приложению туда лезть не надо. Проверка готовности при этом
 * остаётся: она спрашивает схему, а не того, кто её накатывает.
 *
 * <p><b>На замороженной базе оба шага пропускаются, а запуск продолжается
 * (задача 0122).</b> Выкладка морозит запись в базе работающей сборки
 * на полминуты ({@code default_transaction_read_only}, задача 0112), и всё
 * это время людей обслуживает как раз она. Перезапустись она в эти секунды —
 * упала по памяти, кто-то сделал {@code docker compose restart}, — и подняться
 * уже не могла: и накат ({@code UPDATE DATABASECHANGELOGLOCK}), и выдача прав
 * ({@code GRANT}) отбиваются кодом {@code 25006}, а падение здесь валит весь
 * запуск. Контейнер уходил в круг перезапусков, и «нельзя записать»
 * превращалось в <b>полный отказ ячейки, включая чтение</b>, — до отката
 * выкладки. Проверено живым прогоном: «Application run failed», причина —
 * {@code GRANT USAGE ON SCHEMA public}, SQLSTATE 25006.
 *
 * <p>Поэтому отказ замороженной базы — это {@code WARN} и продолженный старт:
 * сборка поднимается только на чтение (запись и без того отвечает 503,
 * {@code WriteFreeze}), а делать ей на этом старте всё равно нечего —
 * накатывать схему во время выкладки не нужно и нельзя. <b>Глотается ровно
 * заморозка:</b> любой другой отказ валит запуск, как и раньше, — без каталога
 * не заведётся ни один арендатор, а без прав на {@code public.spring_session}
 * вход отвечает пятисоткой всем.
 *
 * <p><b>Чем за это заплачено.</b> Пропущенное этим стартом никто не повторяет
 * сам: схему и права догонит следующий старт с открытой записью либо
 * {@code ops/schema-sync.sh}. Для непринятой общей схемы это видно машинно —
 * готовность спрашивает саму схему и такую сборку под трафик не пустит;
 * для невыданных прав отдельной проверки готовности пока нет (задача 0105),
 * и опереться тут можно только на то, что права на служебные таблицы ячейки
 * уже выданы: сборка перезапускается на своей базе, где она работала минуту
 * назад.
 */
@Component
@ConditionalOnProperty(name = "app.migrate-catalog-on-start", havingValue = "true",
        matchIfMissing = true)
public class CatalogMigrations implements ApplicationRunner {

    private static final Logger log = LoggerFactory.getLogger(CatalogMigrations.class);

    private final CatalogSchemaMigrator migrator;
    private final SchemaGrants grants;

    public CatalogMigrations(CatalogSchemaMigrator migrator, SchemaGrants grants) {
        this.migrator = migrator;
        this.grants = grants;
    }

    @Override
    public void run(org.springframework.boot.ApplicationArguments args) {
        try {
            migrator.migrate();
            log.info("Общая схема каталога актуальна");
        } catch (RuntimeException e) {
            // Падать намеренно: без каталога не заведётся ни один арендатор,
            // и приложение, поднявшееся без него, будет отвечать ошибками
            // на каждый вход — только не сразу и не понятно почему.
            // Кроме заморозки записи: там падение стоит дороже пропуска —
            // сборка, которая сейчас держит трафик, не поднялась бы вовсе.
            if (skippedWhileFrozen(e, "накат общей схемы каталога")) {
                return;
            }
            throw new IllegalStateException("Не удалось накатить общую схему каталога", e);
        }

        try {
            // Права на служебные таблицы ячейки — здесь же, по той же причине,
            // по которой их выдаёт накат схемы арендатора: новая таблица прав
            // не наследует, а ops/create-roles.sh на работающей ячейке после
            // выкладки никто не перезапускает. Цена пропуска — не «раздел
            // не работает», а «войти не может никто»: хранилище сессий лежит
            // в public, и без прав на него сессию некуда записать. Поэтому
            // падаем так же, как на каталоге, — и по тому же доводу.
            // В разработке разделения ролей нет, и метод не делает ничего.
            grants.applyCellTables();
        } catch (RuntimeException e) {
            if (skippedWhileFrozen(e, "выдача прав на служебные таблицы ячейки")) {
                return;
            }
            throw new IllegalStateException(
                    "Не удалось выдать права на служебные таблицы ячейки", e);
        }
    }

    /**
     * Отказ пришёл от замороженной на время выкладки базы — шаг пропущен,
     * запуск продолжается.
     *
     * <p>Распознаётся по SQLSTATE в цепочке причин, одним местом на всё
     * приложение ({@link WriteFreeze#isFrozen}): Liquibase, {@code JdbcTemplate}
     * и менеджер транзакций заворачивают отказ драйвера каждый по-своему,
     * и тип верхнего исключения не говорит ничего.
     *
     * <p>Уровень {@code WARN}, а не {@code INFO}: пропущенный шаг — это
     * состояние, из которого ячейка сама не выходит, и человек, разбирающийся
     * с ней через час, обязан увидеть, что схему не накатывали и прав
     * не выдавали. Строка называет и то, что делать: заморозка кончается
     * выкладкой, а догоняет пропущенное следующий старт или
     * {@code ops/schema-sync.sh}.
     *
     * @return {@code true} — отказ про заморозку, шаг пропущен;
     *         {@code false} — отказ другой, и его обязан увидеть запуск
     */
    private boolean skippedWhileFrozen(RuntimeException e, String step) {
        if (!WriteFreeze.isFrozen(e)) {
            return false;
        }
        log.warn("""
                Запись в базе заморожена — идёт выкладка (ops/deploy.sh). Шаг «{}» \
                пропущен, сборка поднимается только на чтение: чтение работает, \
                запись отвечает 503 «Идёт обновление». Пропущенное догонит \
                следующий старт с открытой записью либо ops/schema-sync.sh""", step);
        return true;
    }
}
