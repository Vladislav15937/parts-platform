package ru.partsflow.platform.config;

import java.sql.SQLException;

/**
 * Запись в базу заморожена на время выкладки (задача 0112).
 *
 * <p><b>Чем замораживают.</b> Шаг выкладки ставит базе
 * {@code default_transaction_read_only = on} и обрывает её соединения:
 * новые соединения пула открываются уже только на чтение, и любая запись —
 * вставка, правка, {@code nextval}, заведение схемы — отбивается самим
 * Postgres с кодом {@code 25006}. Замораживает база, а не приложение, и это
 * главное: забытый путь записи в коде (фоновый обход, отметка о заборе
 * прайса, провижининг) заморозку не обходит, а громко падает. Копия базы
 * снимается уже с замороженной, поэтому всё, что приняли до снятия, в ней
 * есть, а после — не принималось вовсе.
 *
 * <p>Здесь только распознавание: одно место, знающее код, на обработчик
 * ответов и на хранилище сессий.
 */
public final class WriteFreeze {

    /** {@code read_only_sql_transaction}: запись в транзакции только на чтение. */
    static final String READ_ONLY_SQL_STATE = "25006";

    /**
     * Что увидит человек.
     *
     * <p>«Не записано» сказано прямо: форма продавца после отказа остаётся
     * заполненной, и без этих слов «идёт обновление» читается как «сохранится
     * само». Офлайн-очередь приёмки текста не читает — ей хватает кода 503,
     * она повторит сама.
     */
    public static final String MESSAGE = "Идёт обновление, подождите: сохранение "
            + "приостановлено на несколько минут. Это действие не записано — "
            + "повторите его чуть позже";

    /** Сколько секунд советовать подождать до повтора. */
    public static final String RETRY_AFTER_SECONDS = "30";

    private WriteFreeze() {
    }

    /**
     * Отказ пришёл от замороженной базы.
     *
     * <p>Ищется по всей цепочке причин: Hibernate, {@code JdbcTemplate}
     * и менеджер транзакций заворачивают отказ драйвера каждый по-своему,
     * и тип верхнего исключения ничего не говорит.
     */
    public static boolean isFrozen(Throwable error) {
        for (Throwable cause = error; cause != null; cause = cause.getCause()) {
            if (cause instanceof SQLException sql && READ_ONLY_SQL_STATE.equals(sql.getSQLState())) {
                return true;
            }
            if (cause.getCause() == cause) {
                return false;
            }
        }
        return false;
    }
}
