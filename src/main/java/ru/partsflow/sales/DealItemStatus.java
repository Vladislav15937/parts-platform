package ru.partsflow.sales;

/**
 * Состояние позиции сделки.
 *
 * <p>Отдельно от статуса документа: часть сделки выдают, часть возвращают,
 * часть отменяют — и в разрезе «по товарам» продавец смотрит именно на позицию.
 */
public enum DealItemStatus {
    /**
     * Позиция в документе, но склад под неё ничего не откладывал.
     *
     * <p>Так лежит заказ с площадки, который нечем закрыть: он записан —
     * иначе о нём знала бы площадка и не знала разборка, — но резерв
     * не поставлен ни по одной позиции, потому что частичный держал бы
     * товар ради заказа, который всё равно придётся отклонить.
     *
     * <p><b>Отличать это от RESERVED обязательно.</b> Пока позиция врала,
     * что зарезервирована, отмена такого заказа шла снимать несуществующий
     * резерв и отвечала «нечего снимать» — то есть закрыть его было нельзя
     * вовсе, и он висел в очереди «ждут ответа» навсегда.
     */
    DRAFT,
    RESERVED,
    ISSUED,
    RETURNED,
    CANCELLED
}
