package ru.partsflow.sales;

/** Операция по лицевому счёту клиента. */
public enum AccountEntryType {

    /** Клиент положил деньги авансом. */
    TOP_UP,

    /** Вернули деньги со счёта. */
    WITHDRAW,

    /** Оплата сделки со счёта. */
    DEAL_PAYMENT,

    /** Возврат по сделке зачислен на счёт. */
    DEAL_REFUND,

    /** Ручная правка: всегда с комментарием, иначе разбирать нечего. */
    CORRECTION
}
