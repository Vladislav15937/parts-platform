package ru.partsflow.sales;

/**
 * Состояние сделки.
 *
 * <p>«Истёк срок» и «частично оплачен» сюда намеренно не входят: это не
 * состояния, а следствия срока резерва и суммы оплат. Хранить их значило бы
 * держать данные, которые разъедутся с источником при первом же продлении
 * резерва или доплате.
 */
public enum DealStatus {

    /** Собирается: позиции добавляют, склад ещё не тронут. */
    DRAFT,

    /** Товар отложен под клиента до {@code reserved_until}. */
    RESERVED,

    /** Собран и ждёт клиента на складе выдачи. */
    READY,

    /** Отдан клиенту. Списание со склада произошло здесь. */
    ISSUED,

    CANCELLED,

    RETURNED;

    /** Из этих состояний товар ещё можно вернуть на склад без возврата. */
    public boolean holdsStock() {
        return this == DRAFT || this == RESERVED || this == READY;
    }

    /**
     * Сделка закрыта: товара у клиента нет и денег он не должен.
     *
     * <p>Отменённая не состоялась вовсе, а возвращённая закрыта встречным
     * документом — деньги по ней либо вернули, либо не брали. Частичный
     * возврат сюда не попадает: там сделка остаётся {@code ISSUED}, потому
     * что часть товара клиент оставил себе и за неё должен.
     */
    public boolean isClosed() {
        return this == CANCELLED || this == RETURNED;
    }
}
