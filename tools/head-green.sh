#!/usr/bin/env bash
# Зелёная ли проверка кода на этой голове.
#
#   ./tools/head-green.sh <SHA|ветка>
#   ./tools/head-green.sh --selftest    # проверка самого сторожа, без сети
#
# Этот вопрос задают перед слиянием и сразу после догона `main` — «зелен ли
# прогон на ТЕКУЩЕЙ голове», — и до 26 сентября 2026 инструмента для него
# не было вовсе: каждый писал его на ходу из `gh` и `--jq` и ошибался
# по-разному. `gh pr checks --watch` выходит нулём, когда проверок ещё нет
# («no checks reported» — это не зелень, а «прогоны не начались»);
# `gh pr checks` первые секунд двадцать после догона отдаёт состояние
# прогона ПРОШЛОЙ головы и выглядит зелёным; `gh run list --branch <ветка>`
# отдаёт прогоны всех голов подряд, и какой из них про нужную — смотрят
# глазами.
#
# Три исхода, и различимы они КОДОМ ВОЗВРАТА, а не только словами:
#
#   0 — зелёная: все прогоны CI на этой голове завершены и успешны;
#   1 — красная: хотя бы один прогон CI на этой голове упал;
#   2 — ответа нет: прогон идёт, прогонов на этой голове нет вовсе, либо
#       их итог вердиктом не является (отменён, пропущен, сорван по времени).
#
# Третий код и есть смысл инструмента. «Ответа нет», выраженное нулём, —
# это слияние непроверенного, и именно так отвечают рукописные рецепты:
# у них два исхода, и «неизвестно» попадает в «можно».
#
# Почему отдельный инструмент, а не новый ответ `can-start.sh`: тот отвечает
# на другой вопрос — «не строим ли мы на сломанном», последним вердиктом CI
# на `main` безотносительно головы, — и отвечает верно, включая терпимость
# к идущему прогону («можно начинать, но дождитесь, прежде чем ветвиться»).
# Здесь идущий прогон, наоборот, ответ отменяет: сливают по конкретной
# голове, и «почти зелёная» голова — это красная.
#
# Прогонов на одной голове бывает ДВА — на `push` и на `pull_request`
# (в `ci.yml` стоят оба триггера), — поэтому считаются ВСЕ прогоны нужного
# процесса, а не первый совпавший: зелёный push при идущем pull_request
# ещё не зелёная голова.
set -u
cd "$(dirname "$0")/.."

say() { printf '  %s\n' "$*"; }

# Название рабочего процесса берём из самого файла: переименуют процесс —
# сторож поедет следом, а не начнёт молча искать несуществующий. Запасное
# значение — на случай чужого дерева (самопроверка гоняет копию скрипта
# во временном каталоге, где .github рядом нет).
wf_name() {
  awk 'NR <= 3 && /^name:[[:space:]]/ { sub(/^name:[[:space:]]*/, ""); print; exit }' "$1" 2>/dev/null
}
CI_WF=$(wf_name .github/workflows/ci.yml); [ -n "$CI_WF" ] || CI_WF="CI"

# Прогонов на одну голову больше нескольких не бывает; берём с запасом,
# чтобы перезапуски не вытеснили из выдачи первый прогон.
LIMIT=50

# Итог, который вердиктом не является: отмена, пропуск, срыв по времени.
# «Отменённый прогон не зелёный и не красный» — `docs/agent-workflow.md`.
# Правило одновременности в `ci.yml` (`cancel-in-progress: true`) отменяет
# прогон промежуточной головы ШТАТНО, то есть отменённые прогоны появляются
# сами собой, без чьей-либо ошибки.
NONVERDICT='c == "cancelled" || c == "skipped" || c == "timed_out" || c == "stale" || c == "neutral" || c == "action_required" || c == ""'
NONVERDICT_FN="function nonverdict(c) { return $NONVERDICT }"

# Голову спрашиваем у GitHub, а не у местного git: вопрос про то, что
# проверялось в прогоне, а местная копия ветки может отставать от
# отправленной — и тогда ответ был бы про голову, которой у GitHub нет.
resolve() {
  gh api "repos/{owner}/{repo}/commits/$1" --jq '.sha' 2>/dev/null
}

# Единственный источник списка прогонов. Подменяется файлом
# (HEAD_GREEN_RUNS) — этим самопроверка подкладывает состояния, которых
# живьём не дождёшься: идущий прогон рядом с зелёным живёт минуты.
# Подменять надо именно источник: проба, зеленеющая оттого, что gh
# не ответил (нет сети, нет входа на раннере), ничего не проверяет.
#
# Строка на прогон: состояние, процесс, итог, голова, заголовок — через табуляцию.
runs() {
  if [ -n "${HEAD_GREEN_RUNS:-}" ]; then
    cat "$HEAD_GREEN_RUNS"
    return
  fi
  gh run list --commit "$1" --limit "$LIMIT" \
    --json status,conclusion,headSha,displayTitle,workflowName \
    --jq '.[] | [.status, .workflowName, .conclusion, .headSha[0:7], .displayTitle] | @tsv' 2>/dev/null
}

# Разбор всех прогонов нужного процесса на нужной голове — одним проходом.
# Голова сверяется у каждой строки: выдача `gh` про соседние головы
# не должна попадать в ответ про эту.
classify() {
  awk -F'\t' -v w="$1" -v sha="$2" "$NONVERDICT_FN"'
$2 == w && $4 == sha {
  total++
  if ($1 != "completed") { running++; if (runTitle == "") runTitle = $5; next }
  if (nonverdict($3)) { nv++; if (nvConcl == "") nvConcl = $3; if (nvTitle == "") nvTitle = $5; next }
  if ($3 == "success") { green++; next }
  fail++; if (failConcl == "") failConcl = $3; if (failTitle == "") failTitle = $5
}
END {
  # Разделитель — \037 (US), а НЕ табуляция. Табуляция для `read` это
  # пробельный IFS: подряд идущие пустые поля она склеивает, и значения
  # съезжают влево — «красная: Склейка SQL развалилась ()» вместо
  # «красная: failure (Склейка SQL развалилась)». Живьём это видно только
  # когда пусто именно СРЕДНЕЕ поле, поэтому выдача с отменой и упавшим
  # разом печаталась верно, а выдача с одним упавшим — нет.
  printf "%d\037%d\037%d\037%d\037%d\037%s\037%s\037%s\037%s\n", \
    total + 0, running + 0, nv + 0, green + 0, fail + 0, nvConcl, failConcl, runTitle, failTitle
}'
}

# Ответ по разобранным числам. Порядок проверок — он же решение о том, что
# сильнее чего, и решение это названо в каждой ветке.
answer() {
  local sha7="$1" rows="$2"
  local total running nv green fail nvConcl failConcl runTitle failTitle
  IFS=$'\037' read -r total running nv green fail nvConcl failConcl runTitle failTitle \
    <<<"$(printf '%s\n' "$rows" | classify "$CI_WF" "$sha7")"

  if [ "$total" = 0 ]; then
    printf '  ? %s\n' "ответа нет: прогонов «${CI_WF}» на голове ${sha7} нет вовсе"
    say "  Это не зелёная голова: проверка кода по ней не выносилась."
    say "  Прогон мог не начаться (пуш не дошёл) или уже уехать из выдачи."
    return 2
  fi

  # Упавший прогон — вердикт, и он сильнее идущего рядом: код на этой голове
  # проверку уже не прошёл, а второй прогон этого не отменит.
  if [ "$fail" != 0 ]; then
    printf '  ✗ %s\n' "проверка кода на ${sha7} красная: ${failConcl} (${failTitle})"
    say "  прогонов «${CI_WF}» на голове: ${total}, из них упало ${fail}"
    [ "$running" = 0 ] || say "  ещё идёт ${running} — но упавшее уже вердикт, и он не отменится"
    return 1
  fi

  # Идущий прогон ответ отменяет: он может стать и зелёным, и красным.
  # Зелёный сосед тут ничего не решает — прогоны проверяют разное.
  if [ "$running" != 0 ]; then
    printf '  ? %s\n' "ответа нет: на ${sha7} идёт прогонов «${CI_WF}»: ${running} из ${total}"
    [ "$green" = 0 ] || say "  завершившихся зелёными: ${green} — это ещё не зелёная голова"
    say "  ${runTitle:-без заголовка}"
    return 2
  fi

  if [ "$nv" != 0 ]; then
    printf '  ? %s\n' "ответа нет: прогон «${CI_WF}» на ${sha7} — ${nvConcl}, а это не вердикт"
    say "  Отменённый прогон не зелёный и не красный: перезапустите его"
    say "  либо смотрите прогон той головы, которая осталась последней."
    return 2
  fi

  printf '  ✓ %s\n' "проверка кода на ${sha7} зелёная (прогонов «${CI_WF}»: ${green})"
  return 0
}

selftest() {
  local dir rc out forged ok_all=0
  dir=$(mktemp -d)
  trap 'rm -rf "$dir"' RETURN

  bad() { printf '  ✗ %s\n' "$*"; ok_all=1; }
  good() { printf '  ✓ %s\n' "$*"; }
  # Прогон сторожа на подложенном списке прогонов. Сеть не нужна вовсе:
  # источник подменён, gh не зовётся, голова не разрешается.
  run_on() {
    out=$(HEAD_GREEN_RUNS="$1" bash "${3:-$PWD/tools/head-green.sh}" "$2" 2>&1)
    rc=$?
  }

  echo "Самопроверка tools/head-green.sh"

  # 1. Зелёная голова: единственный прогон CI завершён успешно.
  cat > "$dir/zelenaya.tsv" <<'EOF'
completed	CI	success	aaaaaaa	Доска: 0158 слита
EOF
  run_on "$dir/zelenaya.tsv" aaaaaaa
  [ $rc = 0 ] && good "зелёная голова — код 0" || bad "зелёная голова дала код $rc: $out"
  case "$out" in
    *зелёная*) good "сказано словом «зелёная»" ;;
    *) bad "исход не назван словом: $out" ;;
  esac

  # 2. Красная: упавший прогон — это вердикт.
  cat > "$dir/krasnaya.tsv" <<'EOF'
completed	CI	failure	aaaaaaa	Склейка SQL развалилась
EOF
  run_on "$dir/krasnaya.tsv" aaaaaaa
  [ $rc = 1 ] && good "красная голова — код 1" || bad "красная голова дала код $rc: $out"
  # Кода мало: сообщение обязано назвать И итог, И заголовок прогона —
  # иначе человек не знает, что именно смотреть. На склеенных полях
  # (табуляция вместо \037) итог подменялся заголовком, а заголовок пустел.
  case "$out" in
    *failure*"Склейка SQL развалилась"*) good "красная называет итог и заголовок прогона" ;;
    *) bad "в сообщении о красной итог и заголовок разъехались: $out" ;;
  esac

  # 3. Тот самый случай: на одной голове ДВА прогона — зелёный push
  #    и идущий pull_request. «Первый совпавший» ответил бы «зелёная»,
  #    и по этому нулю слили бы непроверенное.
  cat > "$dir/dva-progona.tsv" <<'EOF'
completed	CI	success	aaaaaaa	Ветка 0194 (push)
in_progress	CI		aaaaaaa	Ветка 0194 (pull_request)
EOF
  run_on "$dir/dva-progona.tsv" aaaaaaa
  [ $rc = 2 ] \
    && good "зелёный прогон при идущем соседе — «ответа нет», а не зелень" \
    || bad "два прогона на одной голове (один идёт) дали код $rc: $out"
  case "$out" in
    *"ответа нет"*) good "сказано словами «ответа нет»" ;;
    *) bad "«ответа нет» не названо словами: $out" ;;
  esac
  case "$out" in
    *"Ветка 0194 (pull_request)"*) good "назван тот прогон, которого ждут" ;;
    *) bad "идущий прогон не назван заголовком: $out" ;;
  esac

  # 4. Прогонов на этой голове нет вовсе. Пустая выдача — это потеря
  #    доступа к GitHub либо не начавшийся прогон, но никак не зелень.
  : > "$dir/pusto.tsv"
  run_on "$dir/pusto.tsv" aaaaaaa
  [ $rc = 2 ] && good "пустая выдача — «ответа нет», а не зелёная голова" \
    || bad "пустая выдача дала код $rc: $out"

  # 4б. И то же, когда прогоны есть, но все они про ЧУЖУЮ голову: выдача
  #     `gh` соседние головы приносит, и зачесть их за свою — самый
  #     дешёвый способ соврать.
  cat > "$dir/chuzhaya-golova.tsv" <<'EOF'
completed	CI	success	bbbbbbb	Прошлая голова
completed	CI	success	ccccccc	Позапрошлая голова
EOF
  run_on "$dir/chuzhaya-golova.tsv" aaaaaaa
  [ $rc = 2 ] && good "зелёные прогоны чужих голов за свою не зачтены" \
    || bad "прогоны чужой головы приняты за ответ про свою (код $rc): $out"

  # 5. Отменённый прогон: не зелёный и не красный.
  cat > "$dir/otmenyon.tsv" <<'EOF'
completed	CI	cancelled	aaaaaaa	Слияние 285
EOF
  run_on "$dir/otmenyon.tsv" aaaaaaa
  [ $rc = 2 ] && good "отменённый прогон — «ответа нет»" \
    || bad "отменённый прогон дал код $rc (ни зелёным, ни красным он не является): $out"
  case "$out" in
    *cancelled*) good "отмена названа своим словом" ;;
    *) bad "отмена не названа: $out" ;;
  esac

  # 6. Прогоны на голове есть, но все чужого процесса: выкладка про код
  #    не говорит ничего — это та же находка, что у can-start.sh.
  cat > "$dir/tolko-vykladka.tsv" <<'EOF'
completed	Выкладка на стенд	success	aaaaaaa	Выкладка на стенд
EOF
  run_on "$dir/tolko-vykladka.tsv" aaaaaaa
  [ $rc = 2 ] && good "зелёная выкладка за проверку кода не зачтена" \
    || bad "зелёная выкладка принята за зелёную проверку кода (код $rc): $out"

  # 7. Упавший рядом с идущим — красная: вердикт уже вынесен и не отменится.
  #    Решение названо здесь, а не подразумевается.
  cat > "$dir/upal-i-idyot.tsv" <<'EOF'
completed	CI	failure	aaaaaaa	Ветка 0194 (push)
in_progress	CI		aaaaaaa	Ветка 0194 (pull_request)
EOF
  run_on "$dir/upal-i-idyot.tsv" aaaaaaa
  [ $rc = 1 ] && good "упавший прогон при идущем соседе — красная" \
    || bad "упавший прогон при идущем соседе дал код $rc: $out"

  # 8. Три исхода обязаны быть различимы кодом возврата, иначе весь
  #    инструмент не нужен: «ответа нет» под нулём — это и есть дефект,
  #    ради которого он написан.
  run_on "$dir/zelenaya.tsv" aaaaaaa;    local c_green=$rc
  run_on "$dir/krasnaya.tsv" aaaaaaa;    local c_red=$rc
  run_on "$dir/dva-progona.tsv" aaaaaaa; local c_none=$rc
  if [ "$c_green" != "$c_none" ] && [ "$c_red" != "$c_none" ] && [ "$c_green" != "$c_red" ]; then
    good "три исхода различимы кодом возврата ($c_green / $c_red / $c_none)"
  else
    bad "исходы не различимы кодом: зелёная=$c_green красная=$c_red ответа-нет=$c_none"
  fi

  # 9. Подделка первая: прежний рукописный рецепт — «первый совпавший
  #    прогон», то есть идущий сосед не считается вовсе. С ней случай 3
  #    обязан отдать зелень; не отдал — фикстура дефекта не различает,
  #    и все проверки выше ничего не утверждают.
  forged="$dir/pervyy-sovpavshiy.sh"
  sed 's/{ running++; if (runTitle == "") runTitle = $5; next }/{ next }/' \
    "$PWD/tools/head-green.sh" > "$forged"
  if cmp -s "$forged" "$PWD/tools/head-green.sh"; then
    bad "подделка «первый совпавший прогон» не применилась — проба ничего не утверждает"
  else
    run_on "$dir/dva-progona.tsv" aaaaaaa "$forged"
    [ $rc = 0 ] \
      && good "подделка «идущий не считается» отвечает зелёным на неготовой голове" \
      || bad "подделка «идущий не считается» дала код $rc — фикстура не различает дефект"
  fi

  # 10. Подделка вторая: отменённый прогон считается вердиктом — ровно то,
  #     чем can-start.sh объявлял main красной. С ней случай 5 обязан
  #     перестать быть «ответа нет».
  forged="$dir/otmena-verdikt.sh"
  sed "s/^NONVERDICT=.*/NONVERDICT='0'/" "$PWD/tools/head-green.sh" > "$forged"
  if cmp -s "$forged" "$PWD/tools/head-green.sh"; then
    bad "подделка «отмена — вердикт» не применилась — проба ничего не утверждает"
  else
    run_on "$dir/otmenyon.tsv" aaaaaaa "$forged"
    [ $rc != 2 ] \
      && good "подделка «отмена — вердикт» перестаёт отвечать «ответа нет» (код $rc)" \
      || bad "подделка «отмена — вердикт» дала тот же ответ — фикстура не различает дефект"
  fi

  # 11. Головы, которой GitHub не знает, быть не должно на экране чужим
  #     ответом. Поймано живым прогоном: `gh api` на 404 печатает тело
  #     отказа в stdout, и сообщение выходило «прогонов на голове {"messa
  #     нет вовсе» — то есть внутреннее представление показано человеку.
  run_unknown() {
    out=$(HEAD_GREEN_SHA='{"message":"No commit found for SHA: xyz","status":"422"' \
      HEAD_GREEN_RUNS="$dir/zelenaya.tsv" \
      bash "${1:-$PWD/tools/head-green.sh}" net-takoy-vetki 2>&1)
    rc=$?
  }
  run_unknown
  [ $rc = 2 ] && good "неизвестная голова — «ответа нет»" \
    || bad "неизвестная голова дала код $rc: $out"
  # Ищем именно `{"`, а не слово «message»: чужой ответ доезжает до экрана
  # обрезанным до семи знаков головы — `{"messa`, — и проба на целое слово
  # молчала бы на настоящем дефекте. Поймано этой же самопроверкой.
  case "$out" in
    *'{"'*) bad "тело отказа GitHub показано человеку: $out" ;;
    *) good "тело отказа GitHub человеку не показано" ;;
  esac
  case "$out" in
    *net-takoy-vetki*) good "названа та голова, которую не нашли" ;;
    *) bad "не сказано, какую голову не нашли: $out" ;;
  esac

  # 12. Подделка третья: проверки ответа о голове нет вовсе — ровно первая
  #     редакция. С ней случай 11 обязан показать человеку чужой JSON.
  forged="$dir/golova-bez-proverki.sh"
  sed 's/^head_looks_real() .*/head_looks_real() { return 0; }/' \
    "$PWD/tools/head-green.sh" > "$forged"
  if cmp -s "$forged" "$PWD/tools/head-green.sh"; then
    bad "подделка «голову не проверяем» не применилась — проба ничего не утверждает"
  else
    run_unknown "$forged"
    case "$out" in
      *'{"'*) good "подделка «голову не проверяем» показывает чужой JSON" ;;
      *) bad "подделка «голову не проверяем» ничего не изменила — фикстура не различает дефект" ;;
    esac
  fi

  # 13. Подделка четвёртая: разделитель полей — табуляция, как в первой
  #     редакции. Табуляция для `read` пробельная, подряд идущие пустые поля
  #     склеиваются, и «красная: failure (Склейка SQL развалилась)»
  #     превращается в «красная: Склейка SQL развалилась ()». Поймано живым
  #     прогоном, а не рассуждением: на выдаче с отменой и упавшим разом
  #     сообщение выходило верным, и проба на одном таком случае молчала бы.
  forged="$dir/tabulyatsiya.sh"
  sed 's/\\037/\\t/g' "$PWD/tools/head-green.sh" > "$forged"
  if cmp -s "$forged" "$PWD/tools/head-green.sh"; then
    bad "подделка «табуляция вместо \\037» не применилась — проба ничего не утверждает"
  else
    run_on "$dir/krasnaya.tsv" aaaaaaa "$forged"
    case "$out" in
      *failure*) bad "подделка «табуляция» ничего не изменила — фикстура не различает дефект" ;;
      *) good "подделка «табуляция вместо \\037» теряет итог прогона в сообщении" ;;
    esac
  fi

  echo
  if [ $ok_all = 0 ]; then
    echo "Самопроверка пройдена: зелёная, красная и «ответа нет» различимы кодом возврата."
  else
    echo "Самопроверка не прошла."
  fi
  return $ok_all
}

if [ "${1:-}" = "--selftest" ]; then
  selftest
  exit $?
fi

REF="${1:-}"
if [ -z "$REF" ]; then
  say "чья голова? ./tools/head-green.sh <SHA|ветка>"
  say "  (ответа нет — это код 2, а не 0: молчание за зелень не считается)"
  exit 2
fi

echo "Зелёная ли проверка кода на голове ${REF}"

# Похоже ли это на голову. `gh api` на неизвестной ссылке печатает тело
# отказа в stdout (а не только в stderr), и первая редакция подставляла его
# в сообщение: человек видел «прогонов на голове {"messa нет вовсе» вместо
# «GitHub не знает головы feature/0194». Внутреннего представления на экране
# нет — это правило проекта, и нарушить его проще всего чужим ответом.
head_looks_real() { printf '%s' "$1" | grep -Eq '^[0-9a-f]{7,40}$'; }

if [ -n "${HEAD_GREEN_SHA+x}" ]; then
  # Голову подменили (самопроверка): у инструмента два источника — голова
  # и прогоны, — и подменяются оба, иначе разбор ответа о голове не проверить.
  FULL="$HEAD_GREEN_SHA"
elif [ -n "${HEAD_GREEN_RUNS:-}" ]; then
  # Подменён только список прогонов — значит голову дали как есть.
  FULL="$REF"
else
  command -v gh >/dev/null 2>&1 || {
    say "gh не установлен — состояние головы не спросить"
    say "  (это «ответа нет», код 2, а не зелёная голова)"
    exit 2
  }
  FULL=$(resolve "$REF")
fi

if ! head_looks_real "$FULL"; then
  printf '  ? %s\n' "ответа нет: GitHub не знает головы «${REF}»"
  say "  Ветка не отправлена, имя набрано иначе или пропал доступ к GitHub."
  exit 2
fi

SHA7=$(printf '%s' "$FULL" | cut -c1-7)
[ "$SHA7" = "$REF" ] || say "голова ${REF} — это ${SHA7}"

answer "$SHA7" "$(runs "$FULL")"
exit $?
