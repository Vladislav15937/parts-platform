# --- 4. договор не противоречит себе ------------------------------------------

def договор_не_противоречит(root, агент):
    """«Ничего не меняет» рядом с «ломайте код» — и ни слова про возврат."""
    rel = os.path.join(".claude", "agents", "%s.md" % агент)
