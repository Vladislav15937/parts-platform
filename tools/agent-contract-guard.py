        положить(os.path.join(".claude", "agents", "conductor.md"),
                 ДИРИЖЁР_ОК + ПУСКАТЕЛЬ_ОК)
        положить(os.path.join(".claude", "agents", "reviewer.md"), РАЗБОР_ОК)
