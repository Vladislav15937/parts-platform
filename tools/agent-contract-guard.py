def возврат_дефекта():
    """Копия сторожа со снятой проверкой обязана валить самопроверку.

    Копия кладётся в `.scratch/` — место подделок (`docs/agent-workflow.md`,
    «Подделки доказательства живут в одном месте»). Не в `/tmp`: копия считает
    корень репозитория от своего каталога, и из `/tmp` ушла бы в корень
    файловой системы (урок 0151). У `.scratch/` глубина та же, что у `tools/`,
    и при этом он игнорируется git. Рекурсию обрывает `AGENT_CONTRACT_FAKE`.
    Целость копии проверяется ДО запуска: красное от сломанного синтаксиса
    говорило бы о копии, а не о стороже (урок 0198).
    """
    import py_compile
    import subprocess

    if os.environ.get("AGENT_CONTRACT_FAKE"):
        return []
    me = os.path.abspath(__file__)
    текст = open(me, encoding="utf-8").read()
    место = os.path.join(os.path.dirname(os.path.dirname(me)), ".scratch")
    try:
        os.makedirs(место, exist_ok=True)
    except OSError as e:
        return ["подделку некуда положить (%s): возврат дефекта не проверен" % e]
    копия = os.path.join(место, "agent-contract-guard-fake.py")
    сбои = []
    окружение = dict(os.environ, AGENT_CONTRACT_FAKE="1")
    try:
        for имя, было, стало, ждём in ПОДДЕЛКИ:
            if было not in текст:
                сбои.append(
                    "подделку «%s» некуда поставить — место в стороже "
                    "изменилось, и возврат дефекта не проверяет ничего" % имя)
                continue
            with open(копия, "w", encoding="utf-8") as handle:
                handle.write(текст.replace(было, стало, 1))
            try:
                py_compile.compile(копия, doraise=True)
            except py_compile.PyCompileError:
                сбои.append("подделка «%s» не компилируется — её красное "
                            "говорило бы о копии, а не о стороже" % имя)
                continue
            done = subprocess.run([sys.executable, копия, "--selftest"],
                                  capture_output=True, text=True,
                                  env=окружение)
            вывод = done.stdout + done.stderr
            if done.returncode == 0:
                сбои.append(
                    "подделка «%s» прошла самопроверку зелёной: проверка, "
                    "которую можно снять незаметно, не стережёт ничего" % имя)
            elif ждём and ждём not in вывод:
                сбои.append(
                    "подделка «%s» покраснела не тем: в выводе нет «%s», "
                    "то есть красное говорит о чём-то другом" % (имя, ждём))
    finally:
        for мусор in (копия, копия + "c"):
            if os.path.exists(мусор):
                os.remove(мусор)
        кэш = os.path.join(место, "__pycache__")
        if os.path.isdir(кэш):
            shutil.rmtree(кэш, ignore_errors=True)
    return сбои


