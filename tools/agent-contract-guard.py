class Unknown(RuntimeError):
    """Спросить не вышло: файл не прочитан.

    Это не «нарушений нет»: первое означает, что сторож ничего не проверил,
    второе — что проверил и не нашёл. Сведение их в один исход и есть дефект,
    которым оплачена задача 0241.
    """


def red(msg):
    print(RED % msg, file=sys.stderr)


def читать(root, rel):
    path = os.path.join(root, rel)
    try:
        with open(path, encoding="utf-8") as handle:
            return handle.read()
    except OSError as e:
        raise Unknown("%s не прочитан (%s)" % (rel, e.strerror or e))


def абзацы(text):
    """Абзацы без строк таблиц.

    Строки таблицы выброшены намеренно: иначе строка таблицы «Что
    параллелится», где изоляция и имя агента стоят рядом по построению,
    удовлетворяла бы и пункт 1, и пункт 2 — то есть два вопроса слились бы
    в один, а правило снова держалось бы одним местом.
    """
    out = []
    for кусок in re.split(r"\n\s*\n", text):
        строки = [s for s in кусок.splitlines()
                  if not s.lstrip().startswith("|")]
        if строки:
            out.append("\n".join(строки))
    return out


def номер_строки(text, подстрока):
    for number, line in enumerate(text.splitlines(), start=1):
        if подстрока in line:
            return number
    return None


def назван(текст, имена):
    низ = текст.lower()
    return any(имя.lower() in низ for имя in имена)


def причина(агент):
    for имя, _, _, зачем in ОБЯЗАНЫ:
        if имя == агент:
            return зачем
    return "причина не записана"


# --- 1. пускатель называет ----------------------------------------------------

def пускатель_называет(root, агент, имена, файл):
    """Есть ли абзац, где стоят и изоляция, и имя агента."""
    text = читать(root, файл)
    с_изоляцией = [a for a in абзацы(text) if ИЗОЛЯЦИЯ in a]
    if not с_изоляцией:
        return ["%s: про `%s` не сказано вовсе — передавать изоляцию некому.\n"
                "      Это договор того, кто запускает «%s»."
                % (файл, ИЗОЛЯЦИЯ, агент)]
    if any(назван(a, имена) for a in с_изоляцией):
        return []
    строка = номер_строки(text, ИЗОЛЯЦИЯ)
    return [
        "%s:%s — правило про `%s` есть, а «%s» в нём не назван.\n"
        "      Запускающий, исполняющий свой договор ДОСЛОВНО, запустит его\n"
        "      без изоляции: правило, написанное про исполнителя, на разбор\n"
        "      не распространяется — его там нет ни одним словом.\n"
        "      Почему этот агент назван: %s."
        % (файл, строка or "?", ИЗОЛЯЦИЯ, агент, причина(агент))]


# --- 2. таблица называет ------------------------------------------------------

def таблица(text):
    """Строки таблицы «Что параллелится» — от её заголовка до конца таблицы."""
    строки = text.splitlines()
    начало = None
    for number, line in enumerate(строки):
        if line.startswith("#") and ЗАГОЛОВОК_ТАБЛИЦЫ in line:
            начало = number
            break
    if начало is None:
        return None
    out, видели = [], False
    for line in строки[начало + 1:]:
        if line.lstrip().startswith("|"):
            видели = True
            out.append(line)
            continue
        if видели and line.strip():
            break
    return out


def таблица_называет(root, агент, имена):
    text = читать(root, ДОКУМЕНТ)
    rows = таблица(text)
    if rows is None:
        return ["%s: таблицы «%s» нет — проверить нечем.\n"
                "      Это не «строка на месте», а «спросить не вышло»."
                % (ДОКУМЕНТ, ЗАГОЛОВОК_ТАБЛИЦЫ)]
    свои = [r for r in rows if назван(r, имена)]
    if not свои:
        return [
            "%s, таблица «%s»: строки про «%s» нет.\n"
            "      Таблицу читают те, кто договор этого агента не открывает\n"
            "      вовсе, — а разборов на волне идёт три-пять разом.\n"
            "      Строка обязана называть и `%s`."
            % (ДОКУМЕНТ, ЗАГОЛОВОК_ТАБЛИЦЫ, агент, ИЗОЛЯЦИЯ)]
    if not any(ИЗОЛЯЦИЯ in r for r in свои):
        return [
            "%s, таблица «%s»: строка про «%s» есть, а `%s` в ней не названа.\n"
            "      «Параллелится» без своей копии — это и есть тот случай,\n"
            "      ради которого изоляцию заводили: один видит в своём\n"
            "      `git status` чужое, и `git add -A` увозит это в его ветку."
            % (ДОКУМЕНТ, ЗАГОЛОВОК_ТАБЛИЦЫ, агент, ИЗОЛЯЦИЯ)]
    return []


