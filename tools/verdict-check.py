#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Вердикт разбора оставляет след отката — или слиянию не служит.

    ./tools/verdict-check.py <PR> [<полный SHA головы>]   последний вердикт в PR
    ./tools/verdict-check.py --file <путь> [<SHA>]         вердикт из файла
    ./tools/verdict-check.py --selftest                    самопроверка

ЗАЧЕМ (задача 0176). Весь порядок слияния держится на вердикте разбора,
а до этой задачи работа разбора не оставляла следа: в PR приезжала строка
«Разбор: МОЖНО», и отличить сделанный откат от несделанного было нечем.
Исполнитель при этом доказывает письменно — «что именно вы ломали и что
тест ответил» (`coder.md`). Вердикт, который не краснеет на недоказанной
правке, — тот же зелёный тест, не падающий от поломки, только ценой
в слияние.

Формат вердикта записан ОДИН РАЗ — в `.claude/agents/reviewer.md`, между
метками `<!-- вердикт:начало/конец -->`, — и самопроверка берёт оттуда
образец и требует, чтобы он проходил. Поменяли формат там и забыли здесь —
краснеет самопроверка, а не первый настоящий вердикт.

ЧТО ПРОВЕРЯЕТСЯ — у последнего комментария PR, начинающегося
с «Разбор (reviewer»:

  1. ВЕРДИКТ «МОЖНО». «Нельзя» и «доказательство не получено» — возврат
     исполнителю, а не слияние с оговоркой.
  2. ГОЛОВА — строка `Голова:` с полным SHA, и он тот, что спросили (или
     нынешняя голова PR). Вердикт про прежнюю голову про эту не говорит.
  3. ДЕРЕВО — строка `Дерево:` с замером своей копии (`…/.git/worktrees/…`)
     и словом «пусто» про `git status --porcelain`. Это не новое требование:
     `reviewer.md` велел печатать оба ответа замера и до задачи 0176.
  4. ОТКАТ — хотя бы одна строка `Откат: <файл — что сломано> → <чем
     прогнали>: <что ответил>`. Слева обязан стоять файл (имя с расширением
     или путь): «сделал откат» без предмета — то же слово вместо следа.

ТРИ ИСХОДА: 0 — вердикт «можно» и след на месте; 1 — слиянию не служит
(вердикта нет, не «можно», не та голова, следа нет); 2 — спросить не вышло
(`gh` не ответил, файл не прочитан). «Не проверил» и «проверил и чисто» —
разные утверждения, и склеив их, проверка зеленеет там, где перестала
работать (урок `tasks/0241`).

ЧЕГО НЕ ЛОВИТ. Перечень — часть договора, а не оговорка.

  * **Правду следа.** Разбор, вписавший откат, которого не делал, проходит.
    Сторож меряет не честность, а проверяемость: названы файл, команда
    и ответ — значит любой повторит это одной командой, а одно слово
    «можно» повторить нельзя ничем. Это и есть разница, ради которой
    задача заведена.
  * **Полноту.** Одного отката достаточно, хотя тестов в правке бывает семь.
    Требовать отката на каждый тест значит требовать работы, а задача 0176
    запрещает разбору второй прогон: след — запись того, что он и так
    делает.
  * **Правки без разбора** (файлы задач, памятки, документы — «Чего разбор
    не касается»). Вердикта у них нет, и сторож к ним не зовётся вовсе.

ПОЧЕМУ НЕ ЗАДАЧА CI. Тормоз в прогоне PR не стоит на пути слияния: прогон
идёт по пушу, а вердикт приходит после зелёного прогона — проверка краснела
бы на каждом PR до разбора; а волна приземляется пушем сводной ветки,
и PR закрываются сами. Поэтому сторож зовёт тот, кто вердикт принимает:
дирижёр — прежде чем внести PR в таблицу для сессии, сессия — прежде чем
сливать (`conductor.md`, `docs/agent-workflow.md`, «Кто и что может слить»).
В CI идёт только самопроверка.
"""
import json
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

GOOD, FOUND, UNKNOWN = 0, 1, 2

ЗАГОЛОВОК = re.compile(
    r"^Разбор \(reviewer[^)]*\)\s*:\s*"
    r"(МОЖНО|НЕЛЬЗЯ|ДОКАЗАТЕЛЬСТВО НЕ ПОЛУЧЕНО)", re.IGNORECASE)
SHA = re.compile(r"\b[0-9a-f]{40}\b")
# Файл: имя с расширением или путь. Список расширений — то, что в дереве
# бывает предметом отката; не попавшее сюда ловит путь со слешем.
ФАЙЛ = re.compile(
    r"[\w.\-]+\.(java|py|sh|ts|tsx|js|yml|yaml|xml|sql|json|properties|md|"
    r"conf|css|html|toml)\b|\w/\w")

МЕТКА_НАЧАЛА = "<!-- вердикт:начало -->"
МЕТКА_КОНЦА = "<!-- вердикт:конец -->"
REVIEWER = os.path.join(".claude", "agents", "reviewer.md")
CONDUCTOR = os.path.join(".claude", "agents", "conductor.md")
WORKFLOW = os.path.join(".github", "workflows", "ci.yml")
SELF = "tools/verdict-check.py"


class Unknown(RuntimeError):
    """Спросить не вышло — это не «вердикт плохой» и не «вердикт хороший»."""


def строки(текст):
    """Строки без разметки, которой вердикт обрастает в комментарии."""
    out = []
    for s in текст.splitlines():
        s = s.strip()
        if s.startswith("```"):
            continue
        s = re.sub(r"^[-*•>]\s*", "", s)
        s = s.replace("**", "").strip()
        if s:
            out.append(s)
    return out


def поле(строки_, имя):
    префикс = имя + ":"
    return [s[len(префикс):].strip() for s in строки_
            if s.lower().startswith(префикс.lower())]


def это_вердикт(текст):
    сс = строки(текст)
    return bool(сс) and bool(ЗАГОЛОВОК.match(сс[0]))


def разобрать(текст, ждём_sha=None):
    """Список отказов; пустой — вердикт служит слиянию."""
    сс = строки(текст)
    if not сс or not ЗАГОЛОВОК.match(сс[0]):
        return ["первая строка — не «Разбор (reviewer…): МОЖНО|НЕЛЬЗЯ|"
                "ДОКАЗАТЕЛЬСТВО НЕ ПОЛУЧЕНО»"]
    отказы = []
    решение = ЗАГОЛОВОК.match(сс[0]).group(1).upper()
    if решение != "МОЖНО":
        отказы.append("вердикт «%s»: это возврат исполнителю, а не слияние"
                      % решение.lower())

    головы = поле(сс, "Голова")
    if not головы or not SHA.search(головы[0]):
        отказы.append("нет строки «Голова:» с полным SHA — неизвестно, про "
                      "какую голову вердикт")
    elif ждём_sha and SHA.search(головы[0]).group(0) != ждём_sha:
        отказы.append("вердикт про голову %s, а спрошена %s — про эту голову "
                      "разбора нет" % (SHA.search(головы[0]).group(0), ждём_sha))

    деревья = поле(сс, "Дерево")
    if not деревья:
        отказы.append("нет строки «Дерево:» — замер своей копии не напечатан")
    elif "/worktrees/" not in деревья[0] or "пусто" not in деревья[0].lower():
        отказы.append("в «Дерево:» нет замера своей копии (…/.git/worktrees/…) "
                      "или «пусто» про git status --porcelain")

    откаты = поле(сс, "Откат")
    if not откаты:
        отказы.append("нет ни одной строки «Откат:» — следа отката нет, "
                      "вердикт держится на слове")
    for н, о in enumerate(откаты, start=1):
        if "→" not in о:
            отказы.append("откат %d: нет «→» между тем, что сломано, и тем, "
                          "что ответило" % н)
            continue
        что, ответ = (ч.strip() for ч in о.split("→", 1))
        if not ФАЙЛ.search(что):
            отказы.append("откат %d: не назван файл, который ломали" % н)
        if ":" not in ответ or not all(ч.strip() for ч in ответ.split(":", 1)):
            отказы.append("откат %d: нет «<чем прогнали>: <что ответил>»" % н)
    return отказы


def gh_pr(номер):
    gh = os.environ.get("VERDICT_CHECK_GH", "gh")
    try:
        р = subprocess.run(
            [gh, "pr", "view", str(номер), "--json", "headRefOid,comments"],
            capture_output=True, text=True, timeout=60)
    except (OSError, subprocess.TimeoutExpired) as e:
        raise Unknown("gh не запустился: %s" % e)
    if р.returncode != 0:
        raise Unknown("gh pr view %s ответил %d: %s"
                      % (номер, р.returncode, р.stderr.strip()[:300]))
    try:
        данные = json.loads(р.stdout)
        return данные["headRefOid"], [к["body"] for к in данные["comments"]]
    except (ValueError, KeyError, TypeError) as e:
        raise Unknown("gh ответил не тем: %s" % e)


def проверить_pr(номер, sha=None):
    голова, комментарии = gh_pr(номер)
    вердикты = [к for к in комментарии if это_вердикт(к)]
    if not вердикты:
        return ["в PR %s нет комментария «Разбор (reviewer…)» — вердикта нет"
                % номер]
    return разобрать(вердикты[-1], sha or голова)


def отчёт(отказы, о_чём):
    if отказы:
        print("\033[1;31mВердикт не принимается\033[0m (%s):" % о_чём)
        for о in отказы:
            print("  ✗ " + о)
        return FOUND
    print("\033[1;32m✓ вердикт «можно», след отката на месте\033[0m (%s)"
          % о_чём)
    return GOOD


# --- самопроверка --------------------------------------------------------------

def читать(rel):
    try:
        with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
            return f.read()
    except OSError as e:
        raise Unknown("%s не прочитан (%s)" % (rel, e))


def образец():
    текст = читать(REVIEWER)
    if МЕТКА_НАЧАЛА not in текст or МЕТКА_КОНЦА not in текст:
        raise AssertionError("в %s нет меток образца вердикта" % REVIEWER)
    return текст.split(МЕТКА_НАЧАЛА, 1)[1].split(МЕТКА_КОНЦА, 1)[0]


def selftest():
    провалы = []

    def ждать(имя, отказы, должно_пройти, слово=None):
        if должно_пройти and отказы:
            провалы.append("%s: должен пройти, а отказ: %s" % (имя, отказы))
        elif not должно_пройти and not отказы:
            провалы.append("%s: должен краснеть, а прошёл" % имя)
        elif слово and not any(слово in о for о in отказы):
            провалы.append("%s: краснеет не тем (%s), ждали «%s»"
                           % (имя, отказы, слово))
        else:
            print("  ✓ " + имя)

    try:
        хорош = образец()
    except AssertionError as e:
        print("\033[1;31m✗ %s\033[0m" % e)
        return FOUND
    sha = SHA.search(хорош).group(0)
    ждать("образец из reviewer.md проходит", разобрать(хорош, sha), True)

    def без(префикс):
        return "\n".join(s for s in хорош.splitlines()
                         if not строки(s) or not строки(s)[0].startswith(префикс))

    def заменить(старое, новое):
        assert старое in хорош, старое
        return хорош.replace(старое, новое)

    первый_откат = next(s for s in строки(хорош) if s.startswith("Откат:"))
    ждать("одна строка «можно сливать» (как до 0176)",
          разобрать("Разбор (reviewer, Sonnet): МОЖНО. Подделки краснеют.",
                    sha), False, "Откат")
    ждать("след снят: без строк «Откат:»", разобрать(без("Откат:"), sha),
          False, "следа отката нет")
    ждать("откат без «→»",
          разобрать(заменить(первый_откат, первый_откат.replace("→", "и")),
                    sha), False, "нет «→»")
    ждать("откат без файла",
          разобрать(заменить(первый_откат,
                             "Откат: снята проверка → тесты: красные"), sha),
          False, "не назван файл")
    ждать("откат без ответа",
          разобрать(заменить(первый_откат,
                             "Откат: PartService.java — снята проверка → "
                             "прогнал"), sha), False, "что ответил")
    ждать("без «Голова:»", разобрать(без("Голова:"), sha), False, "Голова")
    ждать("вердикт про другую голову", разобрать(хорош, "0" * 40), False,
          "про эту голову разбора нет")
    ждать("без «Дерево:»", разобрать(без("Дерево:"), sha), False, "Дерево")
    ждать("общее дерево вместо своей копии",
          разобрать(заменить("/.git/worktrees/", "/.git/"), sha), False,
          "замера своей копии")
    ждать("вердикт «нельзя»",
          разобрать(заменить("МОЖНО", "НЕЛЬЗЯ"), sha), False, "возврат")
    ждать("разметка markdown не мешает",
          разобрать("```\n" + хорош.replace("Откат:", "- **Откат:**")
                    + "\n```", sha), True)

    # Путь через gh: подложенный gh вместо настоящего, сети нет.
    with tempfile.TemporaryDirectory() as tmp:
        def pr(комментарии, код=0, голова=sha):
            данные = os.path.join(tmp, "pr.json")
            with open(данные, "w", encoding="utf-8") as f:
                json.dump({"headRefOid": голова,
                           "comments": [{"body": к} for к in комментарии]}, f)
            скрипт = os.path.join(tmp, "gh")
            with open(скрипт, "w", encoding="utf-8") as f:
                f.write("#!/bin/sh\n%s\n" % (
                    "cat '%s'" % данные if код == 0
                    else "echo 'HTTP 502' >&2; exit %d" % код))
            os.chmod(скрипт, 0o755)
            os.environ["VERDICT_CHECK_GH"] = скрипт
            try:
                return проверить_pr(1)
            finally:
                del os.environ["VERDICT_CHECK_GH"]

        ждать("PR: последний вердикт хорош, прежний плох",
              pr(["Разбор (reviewer): МОЖНО", хорош]), True)
        ждать("PR: прежний хорош, последний без следа",
              pr([хорош, без("Откат:")]), False, "следа отката нет")
        ждать("PR: вердикта нет вовсе", pr(["LGTM", "готово"]), False,
              "вердикта нет")
        ждать("PR: голова сдвинулась после разбора",
              pr([хорош], голова="1" * 40), False, "про эту голову")
        try:
            pr([хорош], код=1)
            провалы.append("PR: gh не ответил — ждали «спросить не вышло», "
                           "а получили вердикт")
        except Unknown:
            print("  ✓ PR: gh не ответил → «спросить не вышло», не вердикт")

    # Обвязка: сторожа не надо ломать, достаточно не позвать.
    try:
        if "./%s --selftest" % SELF not in читать(WORKFLOW):
            провалы.append("%s не зовёт ./%s --selftest" % (WORKFLOW, SELF))
        else:
            print("  ✓ самопроверку зовёт CI")
        if SELF not in читать(CONDUCTOR):
            провалы.append("%s не зовёт %s перед таблицей для сессии"
                           % (CONDUCTOR, SELF))
        else:
            print("  ✓ дирижёр зовёт сторожа")
    except Unknown as e:
        print("\033[1;33m? %s\033[0m" % e)
        return UNKNOWN

    if провалы:
        for п in провалы:
            print("\033[1;31m✗ %s\033[0m" % п)
        return FOUND
    print("\033[1;32m✓ самопроверка: образец проходит, каждая подделка "
          "краснеет своим\033[0m")
    return GOOD


def main(argv):
    if argv[:1] == ["--selftest"]:
        return selftest()
    try:
        if argv[:1] == ["--file"] and len(argv) in (2, 3):
            try:
                with open(argv[1], encoding="utf-8") as f:
                    текст = f.read()
            except OSError as e:
                raise Unknown("%s не прочитан (%s)" % (argv[1], e))
            return отчёт(разобрать(текст, argv[2] if len(argv) == 3 else None),
                         argv[1])
        if len(argv) in (1, 2) and argv[0].isdigit():
            sha = argv[1] if len(argv) == 2 else None
            if sha and not re.fullmatch(r"[0-9a-f]{40}", sha):
                raise Unknown("SHA нужен полный, 40 знаков: %s" % sha)
            return отчёт(проверить_pr(argv[0], sha), "PR %s" % argv[0])
    except Unknown as e:
        print("\033[1;33m? спросить не вышло: %s\033[0m" % e)
        return UNKNOWN
    print(__doc__.split("ЗАЧЕМ")[0].strip())
    return UNKNOWN


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
