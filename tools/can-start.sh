#!/usr/bin/env bash
# Можно ли начинать работу.
#
#   ./tools/can-start.sh
#   ./tools/can-start.sh --selftest    # проверка самого сторожа, без сети
#
# Запускается первым делом, до правок. Отвечает на один вопрос: не строим ли мы
# на сломанном. Красная main — это стоп для всех: следующая правка ляжет поверх
# поломки, её тесты пройдут на сломанном основании, и разбирать придётся
# две ошибки вместо одной. Ночью, когда никто не смотрит, так теряется вся смена.
#
# Отвечает он про ПРОВЕРКИ КОДА, а не про любой прогон на main. До 20 сентября
# 2026 сторож брал последний завершённый прогон какого угодно рабочего процесса
# — а нажатие кнопки выкладки тоже прогон, и падает выкладка в том числе
# от внешнего: нет секретов стенда, кончилась квота копий, недоступен реестр
# образов. Упавшая выкладка при целом коде объявляла main красной ДЛЯ ВСЕХ
# исполнителей, и 18 сентября 2026 сторож соврал именно так. Ложная тревога
# здесь дороже пропуска: правило «красная main — стоп для всех» работает,
# только пока сторож не врёт, а соврав, он получает то же, что любая ложная
# тревога, — его начинают обходить. Следующая красная будет настоящей.
#
# Поэтому прогоны различаются по НАЗВАНИЮ рабочего процесса, а не по порядку:
# итог выносит CI, а упавшая выкладка называется отдельной строкой — «CI на
# main зелёный, последняя выкладка упала» это другое сообщение, чем «main
# красная», и человеку нужны оба.
#
# Код возврата 0 — можно начинать; 1 — нельзя, и написано почему.
set -u
cd "$(dirname "$0")/.."

BAD=0
say()  { printf '  %s\n' "$*"; }
ok()   { printf '  ✓ %s\n' "$*"; }
stop() { printf '  ✗ %s\n' "$*"; BAD=1; }

# Названия рабочих процессов берём из самих файлов: переименуют процесс —
# сторож поедет следом, а не начнёт молча искать несуществующий. Запасные
# значения — на случай чужого дерева (самопроверка гоняет копию скрипта
# во временном каталоге, где .github рядом нет).
wf_name() {
  awk 'NR <= 3 && /^name:[[:space:]]/ { sub(/^name:[[:space:]]*/, ""); print; exit }' "$1" 2>/dev/null
}
CI_WF=$(wf_name .github/workflows/ci.yml);         [ -n "$CI_WF" ]     || CI_WF="CI"
DEPLOY_WF=$(wf_name .github/workflows/deploy.yml); [ -n "$DEPLOY_WF" ] || DEPLOY_WF="Выкладка на стенд"

# Смотрим двадцать последних, а не десять: несколько выкладок подряд
# (а их нажимают пачкой, когда стенд чинят) вытеснили бы из выдачи все
# прогоны CI, и сторож остался бы без ответа про код.
LIMIT=20

# Единственный источник списка прогонов. Подменяется файлом (CAN_START_RUNS) —
# этим самопроверка подкладывает состояние, которого живьём не дождёшься:
# к следующему часу упавшая выкладка уезжает вниз выдачи, и дефект
# перестаёт воспроизводиться. Подменять надо именно источник: проба,
# зеленеющая оттого, что gh не ответил (нет сети, нет входа на раннере),
# ничего не проверяет — она засчитывает молчание за работу сторожа.
#
# Строка на прогон: состояние, процесс, итог, голова, заголовок — через табуляцию.
runs() {
  if [ -n "${CAN_START_RUNS:-}" ]; then
    cat "$CAN_START_RUNS"
    return
  fi
  gh run list --branch main --limit "$LIMIT" \
    --json status,conclusion,headSha,displayTitle,workflowName \
    --jq '.[] | [.status, .workflowName, .conclusion, .headSha[0:7], .displayTitle] | @tsv' 2>/dev/null
}

# Последний ЗАВЕРШЁННЫЙ прогон названного процесса. Идущий сейчас ничего
# не говорит: он может стать и зелёным, и красным.
pick() {
  awk -F'\t' -v w="$1" '$1 == "completed" && $2 == w { print; exit }'
}

selftest() {
  local dir rc out forged ok_all=0
  dir=$(mktemp -d)
  trap 'rm -rf "$dir"' RETURN

  bad() { printf '  ✗ %s\n' "$*"; ok_all=1; }
  good() { printf '  ✓ %s\n' "$*"; }
  # Прогон сторожа на подложенном списке прогонов. Сеть не нужна вовсе:
  # источник подменён, gh не зовётся.
  run_on() {
    out=$(CAN_START_RUNS="$1" bash "${2:-$PWD/tools/can-start.sh}" 2>&1)
    rc=$?
  }

  echo "Самопроверка tools/can-start.sh"

  # 1. Тот самый случай: упавшая выкладка поверх зелёного CI. Списано
  #    с живой main 19 сентября 2026 (прогон 35453785036, голова 1a8573d:
  #    выкладка красная, CI по той же голове зелёный).
  cat > "$dir/vykladka-upala.tsv" <<'EOF'
completed	Выкладка на стенд	failure	1a8573d	Выкладка на стенд
completed	CI	success	1a8573d	Тестовая компания пересоздана, наполнена, вход открыт (#266)
completed	CI	success	fa835d5	Доска: 0145 слита (PR #265)
EOF
  run_on "$dir/vykladka-upala.tsv"
  [ $rc = 0 ] \
    && good "упавшая выкладка при зелёном CI не запрещает работу" \
    || bad "упавшая выкладка при зелёном CI объявила main красной: $out"
  case "$out" in
    *"CI на main зелёный"*) good "сказано, что именно смотрит сторож" ;;
    *) bad "не сказано, что зелёным признан именно CI: $out" ;;
  esac
  # Промолчать о ней нельзя: выкладка упала по-настоящему, и знать об этом надо.
  case "$out" in
    *"выкладка"*) good "упавшая выкладка названа отдельной строкой" ;;
    *) bad "упавшая выкладка не названа вовсе: $out" ;;
  esac

  # 2. Обратная сторона: красный CI под зелёной выкладкой — это стоп.
  #    Сторож, который молчит здесь, хуже отсутствующего.
  cat > "$dir/ci-krasnyy.tsv" <<'EOF'
completed	Выкладка на стенд	success	aaaaaaa	Выкладка на стенд
completed	CI	failure	bbbbbbb	Склейка SQL развалилась
EOF
  run_on "$dir/ci-krasnyy.tsv"
  [ $rc = 1 ] \
    && good "красный CI под зелёной выкладкой — стоп" \
    || bad "красный CI не остановил работу (код $rc): $out"

  # 3. Прогонов CI не видно вовсе (одни выкладки). Это не «зелено»,
  #    а «неизвестно», и разрешать работу на неизвестном нельзя.
  cat > "$dir/tolko-vykladki.tsv" <<'EOF'
completed	Выкладка на стенд	failure	aaaaaaa	Выкладка на стенд
completed	Выкладка на стенд	success	bbbbbbb	Выкладка на стенд
EOF
  run_on "$dir/tolko-vykladki.tsv"
  [ $rc = 1 ] \
    && good "без прогонов CI сторож не разрешает работу" \
    || bad "без единого прогона CI сторож ответил «можно» (код $rc): $out"

  # 4. Пустая выдача — это потеря доступа к GitHub, а не зелёная main.
  : > "$dir/pusto.tsv"
  run_on "$dir/pusto.tsv"
  [ $rc = 1 ] \
    && good "пустая выдача — отказ, а не зелёная main" \
    || bad "пустая выдача принята за зелёную main: $out"

  # 5. Идущая выкладка не повод ждать: ветвиться она не мешает. А идущий
  #    прогон CI — повод, и он назван.
  cat > "$dir/vykladka-idyot.tsv" <<'EOF'
in_progress	Выкладка на стенд		ccccccc	Выкладка на стенд
completed	CI	success	bbbbbbb	Зелёный
EOF
  run_on "$dir/vykladka-idyot.tsv"
  case "$out" in
    *"идёт прогон"*) bad "идущая выкладка выдана за идущую проверку кода: $out" ;;
    *) good "идущая выкладка не просит подождать" ;;
  esac
  cat > "$dir/ci-idyot.tsv" <<'EOF'
in_progress	CI		ccccccc	Идёт
completed	CI	success	bbbbbbb	Зелёный
EOF
  run_on "$dir/ci-idyot.tsv"
  case "$out" in
    *"идёт прогон"*) good "идущий прогон CI назван" ;;
    *) bad "идущий прогон CI не назван: $out" ;;
  esac

  # 6. И главное: подделка, возвращающая прежнюю логику, обязана покраснеть
  #    на случае 1. Без этой половины первая ничего не утверждает — проба,
  #    не краснеющая от возвращённого дефекта, засчитывает саму себя.
  forged="$dir/prezhnyaya-logika.sh"
  sed 's/\$1 == "completed" \&\& \$2 == w { print; exit }/$1 == "completed" { print; exit }/' \
    "$PWD/tools/can-start.sh" > "$forged"
  if cmp -s "$forged" "$PWD/tools/can-start.sh"; then
    bad "подделка прежней логики не применилась — проба ничего не утверждает"
  else
    run_on "$dir/vykladka-upala.tsv" "$forged"
    [ $rc = 1 ] \
      && good "прежняя логика (первый завершённый прогон любого типа) краснеет" \
      || bad "прежняя логика не покраснела на упавшей выкладке — фикстура не различает дефект"
  fi

  echo
  if [ $ok_all = 0 ]; then
    echo "Самопроверка пройдена: итог выносит CI, упавшая выкладка названа и не запрещает работу."
  else
    echo "Самопроверка не прошла."
  fi
  return $ok_all
}

if [ "${1:-}" = "--selftest" ]; then
  selftest
  exit $?
fi

# Источник подменён — gh не нужен вовсе; иначе без него состояние main
# не спросить.
[ -n "${CAN_START_RUNS:-}" ] || command -v gh >/dev/null 2>&1 \
  || { say "gh не установлен — состояние main не спросить"; exit 1; }

echo "Можно ли начинать"

RUNS=$(runs)

# 1. Итог про КОД — у последнего завершённого прогона CI. Выкладка сюда
#    не входит намеренно: её отказ важен, но он не запрещает писать код.
IFS=$'\t' read -r _ _ CONCLUSION SHA TITLE <<<"$(printf '%s\n' "$RUNS" | pick "$CI_WF")"

if [ -z "$(printf '%s' "$RUNS" | tr -d '[:space:]')" ]; then
  stop "прогонов main не видно — проверьте доступ к GitHub"
elif [ -z "${CONCLUSION:-}" ]; then
  # Прогоны есть, а проверок кода среди них нет: это «неизвестно»,
  # а не «зелено», и разрешать работу на неизвестном нельзя.
  stop "завершённых прогонов «${CI_WF}» на main не видно среди последних ${LIMIT}"
  say "  Состояние кода неизвестно — посмотрите прогоны на GitHub глазами."
elif [ "$CONCLUSION" = "success" ]; then
  ok "CI на main зелёный (${SHA}: ${TITLE})"
else
  stop "CI на main ${CONCLUSION} на ${SHA}: ${TITLE}"
  say "  Чинить это — первая задача, а не своя. Красную main не обходят:"
  say "  либо починка, либо откат слияния, которое её уронило."
fi

# 2. Упавшая выкладка — событие операционное: стенд не раскатан, а код цел.
#    Молчать о ней тоже нельзя: она упала по-настоящему.
IFS=$'\t' read -r _ _ DCONCLUSION DSHA _ <<<"$(printf '%s\n' "$RUNS" | pick "$DEPLOY_WF")"
if [ -n "${DCONCLUSION:-}" ] && [ "$DCONCLUSION" != "success" ]; then
  say "последняя выкладка на стенд: ${DCONCLUSION} (${DSHA}) — на код это не влияет"
  say "  (выкладка падает и от внешнего: секреты стенда, квота копий, реестр образов),"
  say "  но стенд сейчас не раскатан — если работа на него опиралась, начните с неё."
fi

# 3. Идущий прогон CI — не поломка, но начинать поверх него не стоит: если он
#    покраснеет, работа окажется на сломанном основании и об этом узнают позже.
#    Идущая выкладка так не мешает: она ничего не говорит про код.
RUNNING=$(printf '%s\n' "$RUNS" | awk -F'\t' -v w="$CI_WF" \
  '$1 != "completed" && $2 == w { n++ } END { print n + 0 }')
[ "${RUNNING:-0}" = "0" ] || say "на main идёт прогон CI (${RUNNING}) — дождитесь, прежде чем ветвиться"

# 4. Своё дерево. Незакоммиченное чужой правки не переживёт, а ветка
#    от устаревшей main даёт конфликт там, где его могло не быть.
#    В самопроверке этот блок пропускается: дерево и origin/main к решению
#    про прогоны отношения не имеют, а `git fetch` — это сеть.
if [ -z "${CAN_START_RUNS:-}" ]; then
  DIRTY=$(git status --porcelain | wc -l | tr -d ' ')
  [ "$DIRTY" = "0" ] && ok "рабочее дерево чистое" || say "незакоммиченных файлов: ${DIRTY}"

  git fetch -q origin main 2>/dev/null || true
  BEHIND=$(git rev-list --count HEAD..origin/main 2>/dev/null || echo 0)
  [ "${BEHIND:-0}" = "0" ] && ok "не отстаём от origin/main" \
    || say "отстаём от origin/main на ${BEHIND} — ветвитесь от свежей"
fi

echo
if [ $BAD -eq 0 ]; then
  echo "Можно начинать."
else
  echo "Начинать нельзя. Сначала — зелёная main."
fi
exit $BAD
