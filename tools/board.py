ШАПКА = ("---\nid: {id}\ntitle: {title}\nstatus: {status}\n"
         "assignee: {who}\nsource: проба\npr: {pr}\n---\n")

ПОЛНЫЙ = ("## Что человек сможет\nтекст\n\n## Почему это важно\nтекст\n\n"
          "## Как проверить, что сделано\nтекст\n\n## Что известно\nтекст\n")


def файл(**kw):
    kw.setdefault("title", "проба")
    kw.setdefault("status", "новая")
    kw.setdefault("who", "—")
    kw.setdefault("pr", "—")
    body = kw.pop("body", ПОЛНЫЙ)
    return ШАПКА.format(**kw) + body


