def дерево_selftest():
    """Сверка дерева с origin/main — на настоящем репозитории (задача 0199).

    Безусловно, при каждом запуске, по тому же доводу, что `git_selftest()`:
    логика вся про то, какое дерево с каким сравнивается, и на словах её
    не установить. Оба края обязательны: отставание названо, а опережение
    (своя правка в своём файле, неотправленная отметка, местный `main`
    впереди `origin/main`) — нет.
    """
    import shutil
    import tempfile

    repo = tempfile.mkdtemp(prefix="board-guard-tree-")
    tasks_dir = os.path.join(repo, "tasks")
    os.makedirs(tasks_dir)

    def run(*args):
        subprocess.run(["git", "-C", repo] + list(args),
                       check=True, capture_output=True)

    def задача(номер, **kw):
        open(os.path.join(tasks_dir, f"{номер}-proba.md"), "w",
             encoding="utf-8").write(файл(id=номер, **kw))

    def commit(message):
        run("add", "-A")
        run("-c", "user.email=guard@example", "-c", "user.name=guard",
            "-c", "commit.gpgsign=false",
            "commit", "-q", "--no-verify", "-m", message)

    def совпало(что):
        итог, причина = сверка_дерева(repo=repo)
        if итог is None or причина or итог["нет"] or итог["отстали"]:
            сбои.append(f"{что}: названо отставанием (итог {итог}, причина "
                        f"«{причина}») — ложная тревога на каждом запуске, "
                        f"и вывод доски перестанут читать")

    сбои = []
    try:
        run("init", "-q")
        run("symbolic-ref", "HEAD", "refs/heads/main")
        open(os.path.join(tasks_dir, "README.md"), "w").write("правила\n")
        for номер in ("0501", "0502", "0503"):
            задача(номер)
        commit("основа")
        run("update-ref", "refs/remotes/origin/main", "HEAD")

        # Совпавшее дерево — ни строки.
        совпало("копия, совпавшая с origin/main")

        # Ветка исполнителя: своя правка в своём файле и неотправленная
        # новая задача в каталоге — это опережение, а не отставание.
        run("checkout", "-q", "-b", "feature/0501")
        задача("0501", status="в работе", who="coder")
        commit("0501: в работе")
        задача("0504")
        совпало("своя правка своего файла задачи на ветке")
        os.remove(os.path.join(tasks_dir, "0504-proba.md"))

        # main уехал вперёд: новая задача и чужая отметка статуса. Главный
        # случай — ради него задача 0199 и заведена.
        run("checkout", "-q", "main")
        задача("0505")
        задача("0502", status="в работе", who="coder")
        commit("доска: 0505 заведена, 0502 в работе")
        run("update-ref", "refs/remotes/origin/main", "HEAD")
        run("checkout", "-q", "feature/0501")
        итог, причина = сверка_дерева(repo=repo)
        if итог is None or итог["нет"] != ["0505-proba.md"]:
            сбои.append(f"задача, заведённая в main после ответвления копии, "
                        f"не названа отсутствующей — это дефект 0199 целиком: "
                        f"доска печатает «Всего N» по отставшей копии и молчит "
                        f"(итог {итог}, причина «{причина}»)")
        if итог is None or итог["отстали"] != ["0502-proba.md"]:
            сбои.append(f"задача, чей статус main сменил после ответвления, "
                        f"не названа отставшей — а раздают как раз по статусу "
                        f"(итог {итог}, причина «{причина}»)")
        if итог is not None and итог["в_main"] != 4:
            сбои.append(f"число задач в origin/main посчитано {итог['в_main']} "
                        f"вместо 4 — README задачей не считается")

        # Местный main впереди origin/main (отметка не отправлена) — молчит.
        run("checkout", "-q", "main")
        задача("0506")
        commit("доска: 0506 заведена")
        совпало("местный main впереди origin/main")

        # Файл, снятый в копии руками, для доски так же невидим, как
        # не подтянутый: каталог, а не HEAD.
        os.remove(os.path.join(tasks_dir, "0503-proba.md"))
        итог, причина = сверка_дерева(repo=repo)
        if итог is None or "0503-proba.md" not in итог["нет"]:
            сбои.append(f"файл задачи, снятый в копии, не назван — доска "
                        f"читает каталог, и его в ней нет (итог {итог})")
        run("checkout", "-q", "--", "tasks/0503-proba.md")

        # Без ссылки origin/main — не падает и не молчит.
        run("update-ref", "-d", "refs/remotes/origin/main")
        итог, причина = сверка_дерева(repo=repo)
        if итог is not None or not причина or "git fetch" not in причина:
            сбои.append(f"без ссылки origin/main сверка дерева не объявила себя "
                        f"невыполненной с командой подтягивания — молчание "
                        f"читается как «копия свежая» (итог {итог}, причина "
                        f"«{причина}»)")
        return сбои
    except (OSError, subprocess.SubprocessError) as e:
        if isinstance(e, FileNotFoundError):
            return []
        return [f"репозиторий для сверки дерева не завёлся ({e}) — эта "
                f"половина сторожа ничего не доказывает"]
    finally:
        shutil.rmtree(repo, ignore_errors=True)


def ветки():
    """Имена всех известных ветвей и видно ли их вообще.

    На мелкой копии CI (`actions/checkout` тянет одну ссылку) ветвей нет,
    и проверка «в работе без ветки» покраснела бы на каждой живой задаче —
    то есть ложной тревогой на том самом месте, где сторож обязан молчать.
    Поэтому у неё есть условие: сверка ветвей выполняется, только если
    ветвей задач видно хотя бы несколько. Молчание называется словами,
    а не выдаётся за проверенное, — как это делает сверка с origin/main
    у tools/test-schema-guard.py.
    """
    try:
        out = git("branch", "-a", "--format=%(refname:short)")
    except (OSError, subprocess.SubprocessError):
        return set(), False
    names = {b.strip() for b in out.splitlines() if b.strip()}
    задачные = [b for b in names if re.search(r"/\d{4}(-|$)|^\d{4}(-|$)", b)]
    return names, len(задачные) >= 3


def слитое(repo=None):
    """(номер задачи -> (sha, заголовок), причина пустой карты).

    Карта работы, уехавшей в `main`. Ищется по первой линии `origin/main`
    и только по заголовкам вида «0140: …»: так подписаны слияния через кнопку
    GitHub («0140: доступ кнопки к стендам… (#253)»). Именно origin/main,
    а не HEAD: на своей ветке коммит «0165: …» есть у самого исполнителя,
    и сторож объявил бы слитой работу, которая ещё идёт. Отметки доски
    («Доска: 0205 слита — PR 303») сюда не попадают: они начинаются
    не с номера.

    **Вторая половина — причина, и без неё карта врала молча** (задача 0253).
    Отказ git глотался (`except … return {}`), и пустая карта значила разом
    «ничего не уехало» и «спросить не удалось»: ни функция, ни её вызов,
    ни выдача человеку этих двух случаев не различали. Соседи в этом же файле
    молчание называют словами — `ветки()` отдаёт флаг, `сверка_с_main()` пару
    «вклад, причина», — а `слитое()` в периметр задачи 0241 не вошла.

    Исходов три, как и у них: карта с находками (причина `None`), «git
    не ответил» и «git ответил, а коммитов вида „NNNN: …“ не видно» — второе
    на мелкой копии CI обычное дело, и это не повод краснеть. Прогона причина
    не красит; на её словах стоит критерий 6 задачи 0251 («пустая карта
    означает „сверить не с чем“, а не „ничего не уехало“»), и теперь он
    обеспечен кодом, а не докстрингом.
    """
    ок, out = git_ok("log", "--first-parent", "--name-only",
                     "--format=%x1e%H%x1f%s", "origin/main",
                     repo=repo, timeout=20)
    if not ок:
        return {}, ("git не ответил про историю origin/main — карту слитого "
                    "собрать не удалось, и это не «ничего не уехало». Если "
                    "ссылки нет, подтяните её: git fetch --no-tags origin "
                    "main:refs/remotes/origin/main")
    found = {}
    for rec in out.split("\x1e"):
        if "\x1f" not in rec:
            continue
        head, _, tail = rec.partition("\n")
        sha, subject = head.split("\x1f", 1)
        m = re.match(r"(\d{4}):\s*(.+)", subject)
        if not m:
            continue
        # Заголовок «NNNN: …» носит и коммит, который только завёл файл
        # задачи (так 0141 попал в main коммитом #254 при статусе `новая`),
        # и тот, что принёс работу. Работой считается коммит, тронувший
        # хоть один файл вне `tasks/` (задача 0251): иначе обратная пара
        # краснела бы на каждой свежезаведённой задаче.
        if not any(f.strip() and not f.startswith("tasks/")
                   for f in tail.split("\n")):
            continue
        found.setdefault(m.group(1), (sha, m.group(2)))
    if not found:
        return {}, ("в первой линии origin/main не видно ни одного коммита "
                    "вида «NNNN: …» (мелкая копия?) — сверить не с чем")
    return found, None


def задачный(путь):
    """Файл задачи по пути внутри дерева: `tasks/0199-….md`, не README."""
    имя = os.path.basename(путь)
    return имя.endswith(".md") and имя != "README.md"


def сверка_дерева(repo=None):
    """(отставание, причина) — по какому дереву доска отвечает (задача 0199).

    Доска читает `tasks/` **своего** рабочего дерева и объявляет итог
    «Всего N» без оговорок. Запущенная в отставшей копии, она отвечает
    про отставшую копию — теми же словами, каким отвечает про `main`:
    27 сентября 2026 первый взгляд дирижёра дал «192 задачи» при 195
    в `main`. Ошибается такая картина в самую дорогую сторону — задача,
    заведённая после ответвления копии, не видна вовсе, и её выдадут
    второму исполнителю.

    Отставание — это то, что в `origin/main` есть, а здесь нет, и только
    это. Две части:

    * `нет` — файлы задач `origin/main`, которых в каталоге нет. Сверяется
      с каталогом, а не с `HEAD`: доска читает каталог, и снятый в копии
      файл для неё так же невидим, как не подтянутый.
    * `отстали` — файлы, которые `main` изменил **после точки расхождения**
      и которые здесь до сих пор не такие, как в `main`: статус, исполнитель,
      номер PR. Трёхточечный дифф, как у `вклад_ветки()`, и не просто
      «отличается от main»: своя правка исполнителя в своём файле задачи
      и неотправленная отметка дирижёра — это опережение, а не отставание,
      и тревога на них была бы на каждом запуске.

    Исходов три, как у соседей. Отставание найдено — строка с командой
    обновления. Совпало — **ни строки**: на лишнюю натыкается каждый запуск,
    а кончается это тем, что вывод перестают читать. Сверить не вышло
    (ссылки `origin/main` нет, git не ответил) — `None` и причина словами,
    как у `tools/test-schema-guard.py`. Код возврата не меняется ни в одном:
    отставшая копия — это не «доска врёт». `git fetch` сторож не делает:
    у себя видно ровно то, что подтянуто последним `git fetch`.

    Причина может прийти и вместе с найденным: на мелкой копии точки
    расхождения не видно, и тогда `отстали` — `None` («не сверено»),
    а `нет` посчитано.
    """
    есть, _ = git_ok("rev-parse", "--verify", "--quiet", "origin/main^{commit}",
                     repo=repo)
    if not есть:
        return None, ("ссылки origin/main нет — подтяните её: "
                      "git fetch --no-tags origin main:refs/remotes/origin/main")
    ок, out = git_ok("ls-tree", "-z", "--name-only", "origin/main", "tasks/",
                     repo=repo, timeout=20)
    if not ок:
        return None, "git не ответил, какие задачи лежат в origin/main"
    в_main = {os.path.basename(f) for f in out.split("\0") if задачный(f)}

    каталог = os.path.join(repo or ROOT, "tasks")
    здесь = ({f for f in os.listdir(каталог) if задачный(f)}
             if os.path.isdir(каталог) else set())
    итог = {"нет": sorted(в_main - здесь), "отстали": None,
            "в_main": len(в_main)}

    ок, base = git_ok("merge-base", "HEAD", "origin/main", repo=repo)
    if not ок or not base.strip():
        return итог, ("точки расхождения с origin/main не видно (мелкая "
                      "копия?) — изменённые в main задачи не сверены")
    ок1, сменил_main = git_ok("diff", "--name-only", "-z", base.strip(),
                              "origin/main", "--", "tasks/", repo=repo, timeout=20)
    ок2, иначе_здесь = git_ok("diff", "--name-only", "-z", "origin/main",
                              "--", "tasks/", repo=repo, timeout=20)
    if not (ок1 and ок2):
        return итог, ("git не ответил, что изменилось в tasks/ origin/main — "
                      "изменённые в main задачи не сверены")
    сменил_main = {os.path.basename(f) for f in сменил_main.split("\0")
                   if задачный(f)}
    иначе_здесь = {os.path.basename(f) for f in иначе_здесь.split("\0")
                   if задачный(f)}
    итог["отстали"] = sorted((сменил_main & иначе_здесь & здесь))
    return итог, None


def номера(файлы, сколько=8):
    """«0201, 0202 и ещё 5» — номера задач для строки человеку."""
    nn = [f[:4] for f in файлы]
    хвост = f" и ещё {len(nn) - сколько}" if len(nn) > сколько else ""
    return ", ".join(nn[:сколько]) + хвост


def только_доска(tasks, repo=None):
    """(находки, причина невыполненной сверки). Задача, закрытая PR без кода.

    Задача 0029 стояла `слита` с номером PR, где лежал только файл самой
    задачи, — а три пути сделки как читались любым вошедшим, так и читались.
    Это худший вид лжи доски: она закрывает работу, которой не было, и такая
    задача не всплывёт больше никогда — её не раздадут и о ней не спросят.
    Механизм, похоже, тот же, что и у приписанного решения владельца:
    PR упоминал номер задачи в заголовке, и упоминание стало отметкой.

    Проверяем не «сделано ли», а куда именно этот PR писал: слияние,
    тронувшее только `tasks/`, задачу закрыть не могло.

    **Вторая половина пары — причина, и без неё проверка врала молча**
    (задача 0241). Отказ git глотался `pass`, и функция отдавала пустой
    список — ответ, неотличимый от «нарушений нет», то есть непроверенное
    выдавалось за проверенное. Замерено на живой доске: 155 слитых задач
    с номером PR, ROOT уведён в каталог, который не репозиторий, — ответ
    `[]` и ни строчки человеку. Теперь git спрашивается через `git_ok()`
    (он различает отказ и пустоту), а «спросить не удалось» уезжает
    причиной и называется словами — как это делают соседи `ветки()`
    и `сверка_с_main()`.

    **И мерить вклад надо от точки расхождения** (задача 0253). Прежняя
    редакция спрашивала `diff-tree --no-commit-id --name-only -r -m
    --first-parent <слияние>` — величину, в которую попадает и то, чем уехал
    вперёд сам `main`: `-m` печатает разницу с обоими родителями, а
    `--first-parent` её не ограничивает. Значит условие «файлы есть, и все
    они в `tasks/`» выполнялось только у слияния, между ответвлением
    и которым в `main` не легло ни одного коммита, — то есть проверка,
    написанная против лжи доски, в обычном случае не работала вовсе
    и молчала об этом. Теперь зовётся `вклад_слияния()`, и он мерит тем же
    трёхточечным диффом, которым блок «Доска не знает» мерит ветку.

    Второй исход того же свойства — слияний не видно НИ ПО ОДНОЙ слитой
    задаче: git ответил, а истории нет (мелкая копия CI тянет одну ссылку).
    Проверка тогда не проверяет ни одного PR и прежде молчала об этом.
    Называется он только когда проверять было что и не нашлось ничего:
    на полной копии видны 96 слияний из 155, и строки быть не должно —
    ложная тревога здесь дороже пропуска.

    `repo` — чтобы случаи гонялись на настоящем временном репозитории,
    как у `сверка_с_main()` и `вклад_ветки()`.
    """
    out = []
    проверяемые = найдено = 0
    for t in tasks:
        pr = t.get("pr", "—")
        if t.get("status") != "слита" or pr in ("—", ""):
            continue
        проверяемые += 1
        # Ищем именно коммит слияния — «Слияние #64: …», как принято
        # здесь во всех слияниях. Просто «#64» в тексте не годится:
        # первым найдётся отметка на доске, ссылающаяся на тот же PR,
        # и проверка станет ловить сама себя. И `--fixed-strings`,
        # а не `-E`: `\b` в регулярках git не работает — из-за этого
        # проверка молча не находила ничего и зеленела на подделке.
        ок, слияние = git_ok("log", "--all", "--format=%H", "-1",
                             "--fixed-strings", "--grep", f"Слияние #{pr}:",
                             repo=repo)
        if not ок:
            return out, (f"git не ответил про слияние по PR #{pr} "
                         f"({t['file']}) — «спросить не удалось» это "
                         f"не «нарушений нет»")
        слияние = слияние.strip()
        if not слияние:
            continue                  # слияния не видно — не наше дело
        найдено += 1
        # `git show` на коммите слияния не печатает файлов вовсе, и
        # проверка молча зеленела на подделке — поймано пробой, а не
        # чтением. Нужен вклад ветки, и мерится он от точки расхождения
        # (задача 0253): `diff-tree -m --first-parent`, стоявший здесь
        # прежде, подмешивал к вкладу ветки файлы, которыми уехал вперёд
        # сам `main`, — и проверка гасла в обычном случае.
        ок, files = вклад_слияния(слияние, repo=repo)
        if not ок:
            return out, (f"git не ответил, какие файлы тронул PR #{pr} "
                         f"({t['file']}) — куда писало слияние, осталось "
                         f"неизвестным")
        touched = [f for f in files if not f.startswith("tasks/")]
        if files and not touched:
            out.append(f"{t['file']}: помечена слитой по PR #{pr}, "
                       f"а тот PR тронул только tasks/")
    if проверяемые and not найдено:
        return out, (f"коммитов слияния в этой копии не видно ни по одной "
                     f"из {проверяемые} слитых задач (мелкая копия?) — "
                     f"проверка не проверила ни одного PR")
    return out, None


