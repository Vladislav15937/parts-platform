#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Доска задач одним взглядом — и сверка её с собственным договором.

    ./tools/board.py              всё
    ./tools/board.py новая        только с этим статусом
    ./tools/board.py --свободные  что можно раздавать прямо сейчас
    ./tools/board.py --selftest   прогнать сторожа по подделкам и выйти

Читает `tasks/*.md`. Одна задача — один файл: пять агентов, правящих общий
список параллельно, дерутся на слиянии, а свой файл каждый трогает один.

Отдельно проверяет то, из-за чего доска начинает врать. Проверок было пять,
и блок «Доска врёт» был пуст при доске, расходившейся с `main` в двух местах:
пустой блок читается как «сверено», а сверена была половина договора
(задача 0165). Теперь их десять, и у каждой в комментарии написано, какой
случай её завёл.

**Откуда берутся требования к файлу задачи — и почему это сказано вслух.**
Сегодня они записаны в `tasks/README.md`, и этот сторож повторяет их здесь
кодом. Это **вторая копия правила**, то есть ровно та болезнь, из-за которой
заведена `tasks/0177`: правило, записанное дважды, расходится не от
небрежности, а по построению. Решением владельца продукта от 26 сентября
2026 (вариант «б», записано дословно в `tasks/0190-skill-kanon-zadachi.md`,
раздел «Решение владельца — 26 сентября 2026») канон задачи обязан жить
**в одном месте — в скилле**, а этот сторож обязан сверять по нему.
Скилла на 27 сентября 2026 нет (`.claude/skills` не существует), `0190`
в состоянии `новая`, и привязка к канону — **следующий шаг, а не сделанное
здесь**. Связь пока односторонняя и правится руками: дописав требование
в канон, его придётся дописать и сюда. Это названо в `tasks/0165`
и не выдаётся за единый источник.

  ./tools/board.py --selftest — сторож, не краснеющий на дефекте, хуже
  отсутствующего, и установить это можно только попыткой.
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TASKS = os.path.join(ROOT, "tasks")
ORDER = ["новая", "назначена", "в работе", "готово", "ждёт решения",
         "слита", "отклонена"]

# «готово» и «ждёт решения» — разные вещи, и путать их дорого. «Готово»
# означает: работа сделана, PR зелёный, открыта только кнопка слияния.
# «Ждёт решения» означает: открыт вопрос, ответить на который может
# только владелец продукта, и до ответа делать нечего. Пока статус был
# один, четверо в одинаковом положении написали разное — трое «ждёт
# решения», один «в работе», — и по доске нельзя было отличить очередь
# на кнопку от очереди на ответ.

# Задача, которую ещё предстоит делать. У закрытой (`слита`, `отклонена`)
# часть требований договора уже ничего не решает: дописанный сегодня
# критерий приёмки к слитой год назад работе — правка ради зелёного цвета.
ОТКРЫТЫЕ = ("новая", "назначена", "в работе", "готово", "ждёт решения")

# Номер PR — число, и только число. Два номера через запятую законны
# (`0019` → «45, 47», `0082` → «198, 200»: работа шла двумя PR), решётка
# внутри значения — нет: доска печатает значение как есть, и получается
# «PR ##219» и «PR #"#221"». Коммит `c435d97` это уже запрещал, и три
# задачи всё равно написали решётку — значит держать правило должна
# проверка, а не внимательность заводящего.
НОМЕР_PR = re.compile(r"\d+(?:\s*,\s*\d+)*")

# Раздел, который и есть критерий приёмки. Заголовки по доске разные
# («Как проверить, что сделано» у большинства, «Приёмка одна, и она
# жёсткая» у 0158), поэтому сверяется вхождение, а не дословное имя:
# сторож, краснеющий на своём же живом файле, будет отключён в первый день.
КРИТЕРИЙ = ("как проверить", "как проверяется", "приёмка", "критерий")

# Разделы шаблона `tasks/README.md`, по роли, а не по дословному имени.
# Синонимы взяты с самой доски: «Зачем» вместо «Почему это важно»,
# «Что нашли» и «Что не так» вместо «Что человек сможет». Требовать
# дословных заголовков значило бы краснеть на двух сотнях живых файлов,
# написанных до появления сторожа.
# Первый элемент — как раздел называется человеку (он попадёт в сообщение
# сторожа), второй — по каким вхождениям он узнаётся в заголовках файла.
# Сверка идёт по нижнему регистру, а печатать надо то, что человек станет
# искать в `tasks/README.md`: несовпадение регистра в сообщении заставляет
# искать раздел, которого «нет».
РАЗДЕЛЫ = (
    ("Почему это важно", ("почему", "зачем")),
    ("Что человек сможет", ("что человек", "что сделано", "что не так",
                            "что найдено", "что случилось", "что это меняет",
                            "что делает", "что получ")),
    ("Что известно", ("что известно", "что уже известно")),
)

# С какого номера действует требование разделов — и это **решение
# исполнителя, названное вслух** (задача 0165, критерий 4: «решить и назвать,
# с какого номера или статуса правило действует»).
#
# Довод. Без разделов шаблона на 27 сентября 2026 — 39 файлов доски, и
# 30 из них `слита`: разделы дописывались по ходу, а история не правится
# задним числом. Проверка, краснеющая на всей истории, будет отключена
# в первый же день — а отключённый сторож не ловит и новое. Порог по статусу
# («открытые задачи обязаны иметь разделы») тоже не годится: под него
# попадают 12 живых `новая`, то есть исполнитель, взявший чужую задачу,
# получил бы красное на файле, которого он не писал.
#
# Поэтому граница — номер: 0206 это следующий свободный номер на день
# заведения сторожа (последняя заведённая — 0205). Правило действует
# на то, что пишут **после** него, и растёт вместе с доской само.
# Цена названа: 39 прежних файлов сторож не починит никогда, и починить
# их можно только руками, задачей про разделы. Сузить границу вверх легко,
# опустить вниз — значит разом покраснеть на истории.
РАЗДЕЛЫ_С_НОМЕРА = "0206"

# Ветка задачи: `feature/0165`, `feature/0069-sdelka-po-nomeru-pozitsii`,
# `tasks/0140-dostup-knopki-k-stendam`. Сверялся только последний сегмент,
# **равный** номеру, — то есть ветка с именем задачи в хвосте (а так названа
# половина ветвей проекта) не считалась веткой задачи вовсе. Из-за этого
# и осталось невидимым расхождение 0140: статус «в работе», номера PR нет,
# ветки `tasks/0140-…` сторож не видел, а PR #253 был слит неделю назад.
def ветка_задачи(number, branches):
    """Имя ветки, которую сторож считает веткой этой задачи, либо None."""
    for b in branches:
        tail = b.strip().split("/")[-1]
        # Только точный номер с нулями: «0002» и «0002-что-то». «feature/2»
        # — старая ветка обычной работы, и без этого совпадали все подряд,
        # превращая предупреждение в шум, который перестают читать.
        if tail == number or tail.startswith(number + "-"):
            return b.strip()
    return None


def read(path):
    text = open(path, encoding="utf-8").read()
    head = re.match(r"---\n(.*?)\n---", text, re.S)
    if not head:
        return None
    fields = dict(re.findall(r"^([a-z]+): (.*)$", head.group(1), re.M))
    fields["file"] = os.path.basename(path)
    fields["sections"] = [s.strip().lower()
                          for s in re.findall(r"^#{2,3} (.+)$", text, re.M)]
    return fields


def задачи(tasks_dir):
    tasks, broken = [], []
    for name in sorted(os.listdir(tasks_dir)):
        if not name.endswith(".md") or name == "README.md":
            continue
        t = read(os.path.join(tasks_dir, name))
        if t is None:
            broken.append(f"{name}: нет заголовка")
            continue
        tasks.append(t)
    return tasks, broken


def есть_раздел(t, ключи):
    return any(any(k in s for k in ключи) for s in t.get("sections", ()))


def проверить(tasks, branches=(), merged=None, ветки_видны=True):
    """Сверка доски с её договором. Чистая функция — её и гоняет самопроверка.

    merged: номер задачи -> (sha, заголовок коммита) для работы, уехавшей
    в `main`. Пустой словарь значит «сверить не с чем», а не «ничего
    не уехало»: на мелкой копии CI истории нет вовсе.
    """
    merged = merged or {}
    broken, warnings = [], []

    for t in tasks:
        name, status = t["file"], t.get("status")
        pr = t.get("pr", "—")
        number = t.get("id", "")
        есть_pr = pr not in ("—", "")

        if status == "слита" and not есть_pr:
            broken.append(f"{name}: помечена слитой, а номера PR нет")
        # «Готово» без номера PR — та же ложь, что и «слита» без него:
        # статус обещает зелёный PR, по которому человеку осталось нажать
        # кнопку, а нажимать нечего.
        if status == "готово" and not есть_pr:
            broken.append(f"{name}: помечена готовой, а номера PR нет")
        if status in ("назначена", "в работе", "готово") and t.get("assignee", "—") == "—":
            broken.append(f"{name}: {status}, а исполнитель не назван")
        if status not in ORDER:
            broken.append(f"{name}: неизвестный статус «{status}»")

        # 1. Значение `pr` — номер, а не «#219» и не «"#221"».
        if есть_pr and not НОМЕР_PR.fullmatch(pr.strip()):
            broken.append(f"{name}: значение pr «{pr}» — не номер. Доска печатает "
                          f"его как есть, и выходит «PR #{pr}»: решётку и кавычки "
                          f"в значение не пишут (пишите 219, два PR — «219, 221»)")

        # 2. «В работе» без живой ветки и без номера PR. Работа, которой
        #    негде идти: либо статус отстал от слитого PR (так и вышло
        #    с 0140 — PR #253 слит 19 сентября, ветки нет, статус «в работе»
        #    остался), либо взявший не отметился, и задачу выдадут второму.
        if status == "в работе" and not есть_pr:
            if number in merged:
                sha, subject = merged[number]
                broken.append(f"{name}: на доске «в работе», а работа уехала "
                              f"в main коммитом {sha[:7]} «{subject}» — "
                              f"статус и номер PR отстали")
            elif ветки_видны and not ветка_задачи(number, branches):
                broken.append(f"{name}: «в работе», а ни ветки задачи, ни номера "
                              f"PR нет — работа либо не начата, либо потеряна")

        # 3. Критерий приёмки. `tasks/README.md`: «задач без критерия приёмки
        #    не бывает» — по нему нельзя понять, сделано или нет, и спор
        #    об этом всплывёт на слиянии. Спрашивается только у открытых:
        #    у слитой задачи критерий уже ничего не решает, и дописанный
        #    задним числом он был бы правкой ради зелёного цвета.
        if status in ОТКРЫТЫЕ and not есть_раздел(t, КРИТЕРИЙ):
            broken.append(f"{name}: нет раздела с критерием приёмки "
                          f"(«Как проверить, что сделано»). По такой задаче "
                          f"нельзя понять, сделано или нет")

        # 4. Разделы шаблона — с номера РАЗДЕЛЫ_С_НОМЕРА и выше, довод
        #    у самой постоянной.
        if number >= РАЗДЕЛЫ_С_НОМЕРА:
            нет = [имя for имя, ключи in РАЗДЕЛЫ if not есть_раздел(t, ключи)]
            if нет:
                broken.append(f"{name}: нет разделов шаблона: "
                              f"{', '.join('«' + n + '»' for n in нет)} "
                              f"(правило действует с номера {РАЗДЕЛЫ_С_НОМЕРА})")

    # Два файла с одним номером.
    #
    # 9 сентября 2026 на доске оказалось два файла с id 0049: задача
    # про срок резервирования и задача про выгрузку склада. Второй завёл
    # я, не проверив, занят ли номер, — и заметил это не я, а исполнитель,
    # которому задачу раздали. По такому номеру раздача даёт не ту работу:
    # дирижёр говорит «возьми 0049», исполнитель открывает первый
    # попавшийся файл, и делается не то, что просили.
    #
    # Молчала при этом доска, чья работа — не давать себе врать. Значит
    # проверка тут и нужна, а не внимательность заводящего.
    seen = {}
    for t in tasks:
        seen.setdefault(t.get("id"), []).append(t["file"])
    for number, files in sorted(seen.items()):
        if len(files) > 1:
            broken.append(f"номер {number} занят дважды: {', '.join(sorted(files))}")

    # Работа, которой нет на доске. Ветка `feature/0002` при задаче 0002
    # в состоянии «новая» означает одно из двух: исполнитель ещё не отметился
    # (тогда это вопрос времени) или задачу взяли мимо дирижёра (тогда её
    # выдадут второму). Отличить снаружи нельзя, поэтому предупреждение,
    # а не ошибка: доска не врёт, но и не знает.
    if ветки_видны:
        for t in tasks:
            if t.get("status") != "новая":
                continue
            b = ветка_задачи(t.get("id", ""), branches)
            if b:
                warnings.append(f"{t['id']}: на доске «новая», "
                                f"а ветка «{b}» уже есть")

    return broken, warnings


def git(*args, timeout=10):
    return subprocess.run(["git", "-C", ROOT] + list(args),
                          capture_output=True, text=True, timeout=timeout).stdout


def ветки():
    """Имена всех известных ветвей и видно ли их вообще.

    На мелкой копии CI (`actions/checkout` тянет одну ссылку) ветвей нет,
    и проверка «в работе без ветки» покраснела бы на каждой живой задаче —
    то есть ложной тревогой на том самом месте, где сторож обязан молчать.
    Поэтому у неё есть условие: сверка ветвей выполняется, только если
    ветвей задач видно хотя бы несколько. Молчание называется словами,
    а не выдаётся за проверенное, — как это делает сверка с origin/main
    у tools/test-schema-guard.py.
    """
    try:
        out = git("branch", "-a", "--format=%(refname:short)")
    except (OSError, subprocess.SubprocessError):
        return set(), False
    names = {b.strip() for b in out.splitlines() if b.strip()}
    задачные = [b for b in names if re.search(r"/\d{4}(-|$)|^\d{4}(-|$)", b)]
    return names, len(задачные) >= 3


def слитое():
    """Номер задачи -> (sha, заголовок) для работы, уехавшей в `main`.

    Ищется по первой линии `origin/main` и только по заголовкам вида
    «0140: …»: так подписаны слияния через кнопку GitHub («0140: доступ
    кнопки к стендам… (#253)»). Именно origin/main, а не HEAD: на своей
    ветке коммит «0165: …» есть у самого исполнителя, и сторож объявил бы
    слитой работу, которая ещё идёт. Отметки доски («Доска: 0205 слита —
    PR 303») сюда не попадают: они начинаются не с номера.
    """
    try:
        out = git("log", "--first-parent", "--format=%H%x1f%s", "origin/main",
                  timeout=20)
    except (OSError, subprocess.SubprocessError):
        return {}
    found = {}
    for line in out.splitlines():
        if "\x1f" not in line:
            continue
        sha, subject = line.split("\x1f", 1)
        m = re.match(r"(\d{4}):\s*(.+)", subject)
        if m:
            found.setdefault(m.group(1), (sha, m.group(2)))
    return found


def только_доска(tasks):
    """Задача, закрытая PR, в котором не было кода.

    Задача 0029 стояла `слита` с номером PR, где лежал только файл самой
    задачи, — а три пути сделки как читались любым вошедшим, так и читались.
    Это худший вид лжи доски: она закрывает работу, которой не было, и такая
    задача не всплывёт больше никогда — её не раздадут и о ней не спросят.
    Механизм, похоже, тот же, что и у приписанного решения владельца:
    PR упоминал номер задачи в заголовке, и упоминание стало отметкой.

    Проверяем не «сделано ли», а куда именно этот PR писал: слияние,
    тронувшее только `tasks/`, задачу закрыть не могло.
    """
    out = []
    try:
        for t in tasks:
            pr = t.get("pr", "—")
            if t.get("status") != "слита" or pr in ("—", ""):
                continue
            # Ищем именно коммит слияния — «Слияние #64: …», как принято
            # здесь во всех слияниях. Просто «#64» в тексте не годится:
            # первым найдётся отметка на доске, ссылающаяся на тот же PR,
            # и проверка станет ловить сама себя. И `--fixed-strings`,
            # а не `-E`: `\b` в регулярках git не работает — из-за этого
            # проверка молча не находила ничего и зеленела на подделке.
            found = git("log", "--all", "--format=%H", "-1",
                        "--fixed-strings", "--grep", f"Слияние #{pr}:").strip()
            if not found:
                continue                  # слияния не видно — не наше дело
            # `git show` на коммите слияния не печатает файлов вовсе, и
            # проверка молча зеленела на подделке — поймано пробой, а не
            # чтением. Нужна разница с первым родителем.
            files = git("diff-tree", "--no-commit-id", "--name-only", "-r",
                        "-m", "--first-parent", found).split()
            touched = [f for f in files if not f.startswith("tasks/")]
            if files and not touched:
                out.append(f"{t['file']}: помечена слитой по PR #{pr}, "
                           f"а тот PR тронул только tasks/")
    except (OSError, subprocess.SubprocessError):
        pass                              # без git обходимся: доска важнее
    return out


