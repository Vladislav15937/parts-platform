ФЛАГИ = ("--свободные", "--selftest")


def разобрать(args):
    """(всё в порядке, разбор). Неизвестный флаг — отказ, а не тишина.

    `board.py --selftest` до 27 сентября 2026 печатал доску и выходил
    нулём: флаги отбирались по префиксу `--` и выбрасывались. То есть
    на вопрос «а сторож себя проверяет?» инструмент отвечал «да» видом
    успешной работы — та же порода, что и пустой блок «Доска врёт».
    """
    неизвестные = [a for a in args if a.startswith("--") and a not in ФЛАГИ]
    if неизвестные:
        return False, ("флаг", неизвестные)
    # Неизвестный статус — та же ложь, только тише: `board.py "ждет решения"`
    # без «ё» печатало «Подходящих задач нет», то есть доска отвечала «таких
    # задач нет» на опечатку. Спрашивают её ровно затем, чтобы узнать, есть
    # ли такие, — и получали «нет» вместо «я не знаю такого статуса».
    чужие = [a for a in args if not a.startswith("--") and a not in ORDER]
    if чужие:
        return False, ("статус", чужие)
    return True, {
        "free_only": "--свободные" in args,
        "selftest": "--selftest" in args,
        "wanted": [a for a in args if not a.startswith("--")],
    }


