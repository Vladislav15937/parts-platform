#!/usr/bin/env bash
# Счёт выкинутых голов на текущей волне.
#
#   ./tools/wave-discards.sh note  <волна> <голова> <причина>   # записать одно
#   ./tools/wave-discards.sh count <волна>                      # прочитать счёт
#   ./tools/wave-discards.sh --selftest                         # без сети, без push
#
# Задача 3 октября 2026: правило «предел — два выкидывания на волну»
# (`.claude/agents/conductor.md`, «Красная сводная ветка») держалось ровно
# тем, что ОДИН запуск дирижёра помнил его весь заход. Дирижёра дважды обрывало
# в тот же день (лимит сессии, спящий компьютер) и дважды возобновляло — и, если
# обрыв случится посреди третьего выкидывания, счёт нечем прочитать: предел
# перестаёт действовать молча, тот же класс, что мы чинили весь день (правило
# есть, а того, по чему его читают, — нет).
#
# ГДЕ ЖИВЁТ СЧЁТ И ПОЧЕМУ ИМЕННО ТАК. Запись — файл `.claude/wave-discards/
# <волна>.log`, по строке на выкидывание, который пишется ПРЯМО В `main` тем же
# способом, что отметки доски (`conductor.md`, «Как отметки доски попадают
# в main»): коммит плюс `git push`, без ветки и PR. Рассмотрены и отклонены:
#
#   * файл в самой ветке свода (`wave/<дата>`) — она пушится по SSH и это
#     решило бы задачу не хуже, но ветка свода участвует в прогоне CI
#     и в финальном приземлении «одним коммитом» (`tasks/0211`): файл уехал бы
#     в `main` вместе с остальным содержимым волны либо требовал бы отдельного
#     коммита-уборки перед приземлением — лишний шаг именно там, где решение
#     владельца требует «один догон, один прогон, одно слияние»;
#   * запись в сообщении коммита свода — читается `git log`, но разбор счёта
#     требует парсить текст коммита, а не одну строку файла, и ничего не даёт
#     взамен: коммит всё равно уезжает в тот же `main`;
#   * комментарий в PR задачи, чью голову выкинули — виден людям, но у волны
#     несколько PR одновременно, и команда чтения была бы «найди тот самый
#     PR», а не одна и та же для любой волны;
#   * файл вне репозитория — не едет с проектом и не переживает смену машины,
#     на которой работает дирижёр; собственно `deploy-history.log` живёт так
#     осознанно, потому что он про КОНКРЕТНУЮ ячейку, а счёт волны ни к какой
#     ячейке не привязан.
#
# Запись на `main` безопасна ровно потому, что это уже установленный в проекте
# путь — отметки доски делают то же самое, минуя ветку и PR, в любой момент
# волны. Утечки счёта в следующую волну не происходит: у каждой волны своё
# имя и свой файл, и дирижёр, начав новую волну, спрашивает счёт по НОВОМУ
# имени — у него файла с таким путём ещё нет, и это легитимный ноль, а не
# остаток чужой волны. Файлы прежних волн остаются в `main` навсегда тем же
# способом, что `deploy-history.log` на ячейке, — это журнал, а не кеш,
# и нулю следующей волны он не мешает: она читает только свой путь.
#
# ТРИ ИСХОДА У `count`, А НЕ ДВА. «Файла нет» — это легитимный ноль: git
# отличает его собственной ошибкой («path ... does not exist in»), и это
# проверено самопроверкой ниже. Любая ДРУГАЯ причина неудачи — испорченный
# объект, недоступный `origin`, нет прав, не настроен remote вовсе — это
# «СЧЁТ НЕ ПРОЧИТАН», отдельная строка и код возврата 2; подмена этого исхода
# нулём была бы ровно тем дефектом, который чинили в задаче 0148 («дамп
# открылся» ≠ «клиента можно вернуть»). Код возврата: 0 — счёт известен
# (печатается число, включая 0), 2 — счёт не прочитан.
#
# ПОЧЕМУ ПЛАМБИНГ, А НЕ `git checkout` + правка файла. Дирижёр в момент записи
# может стоять на ветке свода волны, а не на `main`, и переключать рабочую
# копию ради одной строки в журнале — лишний риск унести туда что-то чужое.
# `read-tree` / `update-index` / `write-tree` / `commit-tree` строят новый
# коммит поверх `FETCH_HEAD` в объектной базе, не трогая ни индекс, ни ветку,
# на которой стоит дирижёр, — ровно как отметки доски делают это сейчас
# обычным `git commit`, только без переключения веток вовсе.
#
# СКРИПТ НЕ ДЕЛАЕТ `cd` В СВОЙ КАТАЛОГ. Конвенция `cd "$(dirname "$0")/.."`
# верна у `head-green.sh`, который всегда про репозиторий, в котором лежит
# сам сторож; этот скрипт обязан работать в репозитории ВЫЗЫВАЮЩЕГО — рабочей
# копии дирижёра или временном репозитории самопроверки, — и copy-paste той
# строки увёл его в собственный репозиторий: `git fetch`/`git push` внутри
# ушли не туда, куда звал вызывающий, а туда, куда смотрит `$0`. Самопроверка
# в тот вечер (3 октября 2026) приняла это за «работает» и толкнула четыре
# тестовых коммита прямо в настоящий `origin/main` этого проекта — возврат
# дефекта сохранён в этом же файле ниже (`selftest`, случай «вызывающий, а не
# свой путь»). Разные скрипты — разная конвенция, и копировать её не читая
# нельзя.
#
# САМОПРОВЕРКЕ ЗАПРЕЩЁН `git push` ЛЮБЫМ УСТРОЙСТВОМ — решение владельца
# от 3 октября 2026, после находки выше. `--selftest` строит и читает
# состояние волны через `git init` (без единого `remote`) и прямую запись
# в объектную базу (`update-ref`, минуя push и минуя сеть); единственный
# код, который умеет `git push`, — `cmd_note`, и самопроверка его не зовёт
# вовсе. Это осознанный пробел: ретрай-петля `cmd_note` при отвергнутом push
# (не-fast-forward между fetch и push) проверена вручную во время разработки
# задачи, но не покрыта автоматическим `--selftest` и не прогоняется в CI —
# дешевле потерять эту проверку, чем держать в самопроверке хотя бы один
# код, способный дотянуться до настоящего адреса. Доказательство внутри
# `selftest()` одно — живое: канарейка, временно переопределённый `git`,
# кричащая и возвращающая отказ, если СРЕДИ ЛЮБЫХ аргументов любого вызова
# встретится `push` — не только первым словом, но и спрятанный за `-C`,
# `--git-dir` или чем угодно ещё. Текстовый поиск литерала «git push»
# по исходнику здесь стоял первой редакцией и был снят: подделка
# `git -C "$store" push origin main` проходила его беспрепятственно
# («git push» рядом не стоит, между ними `-C "$store"`), а искать по тексту
# саму себя, не находя, — отдельная хрупкость: сообщение канарейки обязано
# называть слово `push`, и любая правка формулировки грозила заставить
# проверку находить саму себя. Единственное, что действительно доказывает
# отсутствие push, — попытка его позвать, а не чтение текста о нём.
set -u

say() { printf '  %s\n' "$*"; }

REMOTE="${WAVE_DISCARDS_REMOTE:-origin}"
BRANCH="${WAVE_DISCARDS_BRANCH:-main}"

path_for() { printf '.claude/wave-discards/%s.log' "$1"; }

usage() {
  say "./tools/wave-discards.sh note  <волна> <голова> <причина>"
  say "./tools/wave-discards.sh count <волна>"
  say "./tools/wave-discards.sh --selftest"
}

# --- сборка коммита: чистая работа с объектной базой, без сети ----------------

build_note_commit() {
  # Ни fetch, ни push здесь нет — поэтому и самопроверка, и cmd_note могут
  # звать эту функцию, не нарушая запрет на push в самопроверке.
  local wave="$1" base="$2" path="$3" head="$4" reason="$5"
  local old line new tmp_index blob tree
  old=$(git show "$base:$path" 2>/dev/null) || old=""
  line="$(date -u +%Y-%m-%dT%H:%M:%SZ) голова=$head причина=$reason"
  if [ -n "$old" ]; then new="$old
$line"; else new="$line"; fi

  tmp_index=$(mktemp)
  blob=$(printf '%s\n' "$new" | git hash-object -w --stdin)
  GIT_INDEX_FILE="$tmp_index" git read-tree "$base"
  GIT_INDEX_FILE="$tmp_index" git update-index --add --cacheinfo 100644,"$blob","$path"
  tree=$(GIT_INDEX_FILE="$tmp_index" git write-tree)
  rm -f "$tmp_index"
  git commit-tree "$tree" -p "$base" -m "Волна $wave: выкидывание головы $head ($reason)"
}

# --- запись (единственное место, где этот скрипт зовёт `git push`) ------------

cmd_note() {
  local wave="$1" head="$2" reason="$3" path attempt=0 max=6
  path=$(path_for "$wave")
  while :; do
    attempt=$((attempt + 1))
    local ferr; ferr=$(mktemp)
    if ! git fetch --quiet "$REMOTE" "$BRANCH" 2>"$ferr"; then
      say "ЗАПИСЬ НЕ УДАЛАСЬ: git fetch $REMOTE $BRANCH не отвечает"
      cat "$ferr" >&2; rm -f "$ferr"
      return 2
    fi
    local base
    if ! base=$(git rev-parse FETCH_HEAD 2>"$ferr"); then
      say "ЗАПИСЬ НЕ УДАЛАСЬ: после fetch FETCH_HEAD не разрешается"
      cat "$ferr" >&2; rm -f "$ferr"
      return 2
    fi
    rm -f "$ferr"

    local commit
    commit=$(build_note_commit "$wave" "$base" "$path" "$head" "$reason")

    local perr; perr=$(mktemp)
    if git push "$REMOTE" "$commit:refs/heads/$BRANCH" 2>"$perr"; then
      rm -f "$perr"
      say "записано: $path"
      return 0
    fi
    if [ "$attempt" -ge "$max" ]; then
      say "ЗАПИСЬ НЕ УДАЛАСЬ: push отвергнут $max раз подряд"
      cat "$perr" >&2; rm -f "$perr"
      return 2
    fi
    rm -f "$perr"
    # $BRANCH ушёл вперёд между fetch и push — повторяем с начала цикла
    # на свежей базе; потерянного обновления здесь нет, потому что каждая
    # попытка перечитывает "old" заново из уже обновлённого FETCH_HEAD.
  done
}

# --- чтение: только fetch (без push) -------------------------------------------

cmd_count() {
  local wave="$1" path errfile
  path=$(path_for "$wave")
  errfile=$(mktemp)

  if ! git fetch --quiet "$REMOTE" "$BRANCH" 2>"$errfile"; then
    printf 'СЧЁТ НЕ ПРОЧИТАН: git fetch %s %s не отвечает: %s\n' \
      "$REMOTE" "$BRANCH" "$(tr '\n' ' ' < "$errfile")"
    rm -f "$errfile"; return 2
  fi

  local base
  if ! base=$(git rev-parse FETCH_HEAD 2>"$errfile"); then
    printf 'СЧЁТ НЕ ПРОЧИТАН: после fetch FETCH_HEAD не разрешается: %s\n' \
      "$(tr '\n' ' ' < "$errfile")"
    rm -f "$errfile"; return 2
  fi

  local content rc
  content=$(git show "$base:$path" 2>"$errfile"); rc=$?
  if [ "$rc" -ne 0 ]; then
    # Этой и только этой ошибкой git отличает «пути нет» от всего остального —
    # повреждённого объекта, недостающих прав, оборванной сети, незаведённого
    # remote. Первое — легитимный ноль (волна ни разу не выкидывала голову),
    # второе — «спросить не вышло», и склеивать их в одно и есть тот дефект,
    # ради которого написана эта проверка.
    if grep -q "does not exist in\|exists on disk, but not in" "$errfile"; then
      echo 0
      rm -f "$errfile"; return 0
    fi
    printf 'СЧЁТ НЕ ПРОЧИТАН: %s\n' "$(tr '\n' ' ' < "$errfile")"
    rm -f "$errfile"; return 2
  fi
  rm -f "$errfile"
  printf '%s\n' "$content" | grep -c '.'
  return 0
}

# --- самопроверка: без сети, без push, без единого configured remote ----------

selftest() {
  local dir ok_all=0
  dir=$(mktemp -d)
  trap 'rm -rf "$dir"' RETURN

  bad() { printf '  ✗ %s\n' "$*"; ok_all=1; }
  good() { printf '  ✓ %s\n' "$*"; }

  echo "Самопроверка tools/wave-discards.sh"

  # Канарейка, а не текстовый поиск по исходнику. Первая редакция искала
  # литерал «git push» в тексте функции — и прошла даже на подделке,
  # вызвавшей `git -C "$store" push origin main`: подстрока «git push»
  # там просто не стоит рядом, `-C "$store"` встаёт между словами. Текстовый
  # поиск по живому коду в принципе не ловит переписанный порядок аргументов,
  # а самоссылочный (проверка ищет себя же в собственном тексте) оказался
  # вдобавок хрупким: сообщение самой проверки обязано называть слово
  # «push», и малейшая правка формулировки могла заставить её находить
  # самоё себя. Поэтому единственное доказательство здесь — исполнение:
  # на всё время самопроверки `git` подменён функцией, которая кричит
  # и отказывает, если СРЕДИ ЛЮБЫХ аргументов вызова встретился `push` —
  # не только первым словом, но и после `-C`, `--git-dir` или чего угодно
  # ещё. `export -f` доезжает до дочерних `bash`, то есть и до подпроцессов,
  # которыми самопроверка запускает сам сторож (`run_count` ниже): они тоже
  # не смогут дотянуться до push, будь он там.
  git() {
    local a
    for a in "$@"; do
      if [ "$a" = push ]; then
        echo "КАНАРЕЙКА: среди аргументов git() встретился push — этого не может быть в самопроверке" >&2
        return 99
      fi
    done
    command git "$@"
  }
  export -f git

  SELF="$(cd "$(dirname "$0")" && pwd)/$(basename "$0")"

  # "Хранилище" волны — обычный `git init`, ни одного `remote` не заведено
  # ни разу: пункт задачи «работает в репозитории без remote вовсе»
  # выполняется не отдельным тестом, а всем устройством пробы.
  store="$dir/store"
  git init -q "$store"
  (cd "$store" && git config user.email t@t.t && git config user.name t \
    && echo init > a.txt && git add a.txt && git commit -q -m init)

  # "Читатель" — отдельный каталог, тоже без единого remote; адрес
  # хранилища передаётся КАЖДЫЙ раз аргументом через переменную окружения
  # (путь в файловой системе), а не записью в `.git/config`.
  reader="$dir/reader"
  git init -q "$reader"

  run_count() {
    (cd "$reader" && WAVE_DISCARDS_REMOTE="$1" WAVE_DISCARDS_BRANCH=main \
      bash "$SELF" count "$2")
  }

  # Симулирует «кто-то записал выкидывание» — строит коммит той же функцией,
  # что и настоящий `note`, и приземляет его в хранилище `update-ref`'ом:
  # это прямая локальная правка СВОЕГО объектного хранилища, а не push
  # куда-то наружу. Разницу стоит проверить глазами: `update-ref` меняет
  # ссылку репозитория, в котором и так сидишь, `push` — ссылку в чужом.
  land() {
    local wave="$1" head="$2" reason="$3" base path commit
    base=$(git -C "$store" rev-parse main)
    path=$(path_for "$wave")
    commit=$(cd "$store" && build_note_commit "$wave" "$base" "$path" "$head" "$reason")
    git -C "$store" update-ref refs/heads/main "$commit"
  }

  local out rc

  # 1. Волна, которая ни разу не выкидывала голову: легитимный ноль.
  out=$(run_count "$store" wave/test-1); rc=$?
  [ "$rc" = 0 ] && [ "$out" = "0" ] \
    && good "свежая волна — счёт 0, код 0" \
    || bad "свежая волна дала «${out}» (код $rc), ожидался 0"

  # 2. Запись и чтение ДРУГИМ ПРОЦЕССОМ — буквально: отдельный `bash`,
  #    своя среда, без общего состояния с записавшим. Это и есть
  #    «переживает перезапуск», проверенное, а не заявленное.
  land wave/test-1 aaa1111 "red: db/changelog conflict"
  out=$(run_count "$store" wave/test-1); rc=$?
  [ "$rc" = 0 ] && [ "$out" = "1" ] \
    && good "одна запись — счёт 1 из нового процесса" \
    || bad "после одной записи счёт «${out}» (код $rc), ожидался 1"

  land wave/test-1 bbb2222 "shows green on its own head"
  out=$(run_count "$store" wave/test-1); rc=$?
  [ "$rc" = 0 ] && [ "$out" = "2" ] \
    && good "две записи — счёт 2" \
    || bad "после двух записей счёт «${out}» (код $rc), ожидался 2"

  # 3. Привязка к волне: вторая волна в том же хранилище не видит счёт первой.
  out=$(run_count "$store" wave/test-2); rc=$?
  [ "$rc" = 0 ] && [ "$out" = "0" ] \
    && good "счёт не утекает в другую волну (своя — 0 при чужой 2)" \
    || bad "счёт утёк в другую волну: «${out}» (код $rc), ожидался 0"

  # 4. Свежий, ранее не спрашивавший читатель — доказательство того же
  #    самого с другой стороны: число лежит в хранилище, а не в кеше
  #    первого читателя.
  reader2="$dir/reader2"
  git init -q "$reader2"
  out=$(cd "$reader2" && WAVE_DISCARDS_REMOTE="$store" WAVE_DISCARDS_BRANCH=main \
    bash "$SELF" count wave/test-1)
  rc=$?
  [ "$rc" = 0 ] && [ "$out" = "2" ] \
    && good "счёт виден свежему читателю без памяти о записавшем" \
    || bad "свежий читатель дал «${out}» (код $rc), ожидался 2"

  # 5. Ломаем место: испорченный объект git — это НЕ «пути нет», и подмена
  #    нулём здесь была бы ровно тем дефектом, который чинили в задаче 0148.
  #    Ломаем КОПИЮ хранилища (простое копирование файлов, без единой
  #    git-команды над оригиналом): порча объекта обязана остаться местной,
  #    а не отравить $store, которым пользуются сценарии после этого.
  local store_corrupt wave3_sha blob objpath path commit
  store_corrupt="$dir/store-corrupt"
  cp -R "$store" "$store_corrupt"
  wave3_sha=$(git -C "$store_corrupt" rev-parse main)
  path=$(path_for wave/test-3)
  commit=$(cd "$store_corrupt" && build_note_commit wave/test-3 "$wave3_sha" "$path" ccc3333 "перед поломкой")
  git -C "$store_corrupt" update-ref refs/heads/main "$commit"
  wave3_sha="$commit"
  blob=$(git -C "$store_corrupt" ls-tree -r "$wave3_sha" -- "$path" | awk '{print $3}')
  objpath="$store_corrupt/.git/objects/${blob:0:2}/${blob:2}"
  if [ ! -f "$objpath" ]; then
    bad "не нашли объект блоба $blob в хранилище — проба ничего не утверждает"
  else
    chmod u+w "$objpath"
    echo "испорчено" > "$objpath"
    out=$(run_count "$store_corrupt" wave/test-3); rc=$?
    case "$out" in
      *"СЧЁТ НЕ ПРОЧИТАН"*)
        [ "$rc" = 2 ] \
          && good "испорченный объект — «СЧЁТ НЕ ПРОЧИТАН», код 2, а не ноль" \
          || bad "испорченный объект назван словами, но код $rc (ожидался 2)" ;;
      *) bad "испорченный объект дал «${out}» (код $rc) — принят за ноль, а не назван отказом" ;;
    esac
  fi

  # 6. Ломаем место вторым способом: адрес хранилища не существует вовсе
  #    (опечатка, сорванный путь) — тот же класс отказа, другая причина.
  out=$(run_count "$dir/нет-такого-пути" wave/test-1); rc=$?
  case "$out" in
    *"СЧЁТ НЕ ПРОЧИТАН"*)
      [ "$rc" = 2 ] \
        && good "недоступный адрес — «СЧЁТ НЕ ПРОЧИТАН», код 2, а не ноль" \
        || bad "недоступный адрес назван словами, но код $rc (ожидался 2)" ;;
    *) bad "недоступный адрес дал «${out}» (код $rc) — принят за ноль, а не назван отказом" ;;
  esac

  # 7. Третий способ сломать место — буквально то, что требует задача:
  #    переменная окружения с адресом снята, а в репозитории вызывающего
  #    `remote` не настроен ВООБЩЕ (у `reader` их нет ни одного с самого
  #    `git init`). Умолчание REMOTE="origin" в таком репозитории не находит
  #    ничего, и это тоже обязано назваться словами, а не нулём.
  out=$(cd "$reader" && env -u WAVE_DISCARDS_REMOTE WAVE_DISCARDS_BRANCH=main \
    bash "$SELF" count wave/test-1)
  rc=$?
  case "$out" in
    *"СЧЁТ НЕ ПРОЧИТАН"*)
      [ "$rc" = 2 ] \
        && good "без переменной окружения и без remote — «СЧЁТ НЕ ПРОЧИТАН», код 2" \
        || bad "без remote назван словами, но код $rc (ожидался 2)" ;;
    *) bad "без переменной окружения и remote дало «${out}» (код $rc) — принято за ноль" ;;
  esac

  # 8. Обратный край: исправное место при наличии ЧУЖОЙ записи в main между
  #    чтением и записью своей — ровно та гонка, которую в бою создают
  #    отметки доски, пишущие в main тем же способом в любой момент волны.
  #    Чужая запись — тоже через `build_note_commit`, в другую волну: так
  #    гонка моделируется тем же механизмом, что и настоящий `note`,
  #    а не смешением пламбинга с обычным `git commit` по рабочему индексу
  #    (смешение один раз уже дало ложный провал — `land` строит коммит
  #    мимо индекса `$store`, и обычный `git commit` следом видит устаревший
  #    индекс и откатывает дерево, теряя записи; оба пишущих пути обязаны
  #    быть пламбингом, если делят один нерабочий репозиторий).
  land wave/other-conductor-activity xxx0000 "параллельная запись, не наша"
  land wave/test-1 ddd4444 "третья, после чужой записи в main"
  out=$(run_count "$store" wave/test-1); rc=$?
  [ "$rc" = 0 ] && [ "$out" = "3" ] \
    && good "запись верна и после чужой записи в main (нет гонки)" \
    || bad "после чужой записи счёт «${out}» (код $rc), ожидался 3"

  echo
  if [ "$ok_all" = 0 ]; then
    echo "Самопроверка пройдена: ноль, счёт, отказ чтения и привязка к волне различимы — без единого push."
  else
    echo "Самопроверка не прошла."
  fi
  return "$ok_all"
}

if [ "${1:-}" = "--selftest" ]; then
  selftest
  exit $?
fi

case "${1:-}" in
  note)
    [ $# -ge 4 ] || { usage; exit 2; }
    cmd_note "$2" "$3" "${*:4}"
    ;;
  count)
    [ $# -ge 2 ] || { usage; exit 2; }
    cmd_count "$2"
    ;;
  *)
    usage
    exit 2
    ;;
esac
