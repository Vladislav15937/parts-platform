#!/usr/bin/env bash
# Тот же прогон, но с часами, переведёнными вперёд.
#
# Зачем. Календарная дата, зашитая в проверку, которая сравнивает её
# с «сейчас», — отложенное падение: 18 сентября 2026 тест ждал «до 15
# сентября», пятнадцатое стало позади, и красной стала `main` — то есть любой
# PR любой ветки, через четыре дня после того, как мину поставили.
# Литерал у поля, сравниваемого с «сейчас», ловит перебором
# `tools/date-mine-guard.py`. Но он ловит только литерал: зависимость
# от дня недели, от месяца и от полуночи по исходникам не видна вовсе,
# и установить её можно единственным способом — прогнать то же самое
# в другой день.
#
#   ./tools/clock-shift-run.sh                # +31 день, фронтенд и проверки
#   ./tools/clock-shift-run.sh --days 400     # и другой год заодно
#   ./tools/clock-shift-run.sh --java         # и бэкенд, если часы у JVM сдвигаются
#   ./tools/clock-shift-run.sh --selftest     # сверить шим со статическим сторожом
#
# Задачей CI этот прогон заведён — ЦЕЛИКОМ, вместе с бэкендом: задача
# «Часы вперёд» в .github/workflows/ci.yml. Это решение владельца продукта
# от 27 сентября 2026, дословно «1-целиком» (задача 0206), и рекомендация
# исполнителя 0125 — «хотя бы дешёвую половину, без --java» — им отклонена:
# цена полного прогона на каждый PR принята сознательно. Сокращать объём
# «чтобы было дешевле» значит отменять это решение, а не исполнять его.
#
# Замеры: статический сторож tools/date-mine-guard.py — секунды; фронтенд
# со сдвигом — 14 с, столько же, сколько обычный прогон; удвоенные
# самопроверки ops/, tools/, db/ — около двух минут; бэкенд — 4 мин 09 с
# на 1101 тест локально, а на раннере дольше: холодные ~/.m2 и выкачка
# образов. Сколько задача занимает на раннере — печатает сама задача, своим
# последним шагом, и то же число стоит у неё в комментарии; переписанное
# локальное число тут не годится, машины разные.
#
# Три исхода, различимые кодом, — как у tools/head-green.sh:
#   0 — сдвиг ничего не поменял: всё, что прогнано, ответило как и без сдвига;
#   1 — исход поменялся: названо, что именно;
#   2 — часть не проверена. Это НЕ зелёный: «проверить не вышло» и «всё хорошо»
#       обязаны различаться, иначе отсутствие тревоги начнут читать как её
#       отсутствие по существу.
#
# Чего этот прогон не сдвигает, и знать это надо заранее:
#   • времена файлов. `touch -t` в фикстурах и `find -mtime` смотрят
#     на настоящую файловую систему;
#   • JVM на macOS: `faketime` подгружает свою библиотеку через
#     DYLD_INSERT_LIBRARIES, а подписанный java её не берёт — время остаётся
#     настоящим. Проверено тремя формами вызова; поэтому прогон бэкенда
#     не «пропускается молча», а называется непроверенным;
#   • `/bin/date` — по той же причине. Шеллу время подменяется своим `date`
#     в PATH, а не faketime;
#   • сеть, и она под сдвинутыми часами просто не работает: у сервера
#     проверяется срок сертификата, а к будущей дате он просрочен. Поэтому
#     бэкенд идёт офлайном (`-o`), а maven обязан быть прогрет НАСТОЯЩИМИ
#     часами — так его и зовёт CI отдельным шагом. Правило общее: сеть —
#     настоящими часами, сдвинутыми — только наш код;
#   • подписанные запросы к хранилищу. MinIO в тестах поднимается контейнером
#     и живёт по настоящим часам, а подпись S3 несёт отметку времени: клиент
#     на месяц вперёд получает 403. Поэтому PhotoServiceTest
#     и PhotoArchiveStreamTest из сдвинутого прогона исключены по имени —
#     их зависимость от календаря не проверена, и прогон это называет.
set -u

DAYS=31
WITH_JAVA=0
SELFTEST=0
while [ $# -gt 0 ]; do
    case "$1" in
        --days) DAYS="$2"; shift 2 ;;
        --java) WITH_JAVA=1; shift ;;
        --selftest) SELFTEST=1; shift ;;
        # Предел строкой не ставится, и это не мелочь: шапка растёт, а помощь,
        # обрезанная посередине абзаца, обещает список и не показывает его.
        # Ровно так и было — `sed -n '2,36p'` кончался на заголовке «Чего этот
        # прогон не сдвигает», а все три пункта под ним в помощь не попадали.
        # Печатаем шапку целиком: до первой строки, которая не комментарий.
        -h|--help)
            awk 'NR > 1 && /^#/ { sub(/^# ?/, ""); print; next }
                 NR > 1 { exit }' "$0"
            exit 0 ;;
        *) printf 'Не знаю аргумента: %s\n' "$1" >&2; exit 2 ;;
    esac
done

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

green() { printf '\033[1;32m%s\033[0m\n' "$1"; }
red()   { printf '\033[1;31m%s\033[0m\n' "$1"; }
warn()  { printf '\033[1;33m%s\033[0m\n' "$1"; }
step()  { printf '\n\033[1;34m==> %s\033[0m\n' "$1"; }

CHANGED=0
UNCHECKED=0
SHIFT_SECONDS=$(( DAYS * 86400 ))

printf 'Сдвиг: +%s дн. (%s с)\n' "$DAYS" "$SHIFT_SECONDS"

# ──────────────────────────── подменный `date` ───────────────────────────────
#
# Шелл спрашивает время у `/bin/date`, а его faketime не сдвигает. Поэтому
# в PATH кладётся свой: спросили «сейчас» — отдаёт сдвинутое, спросили
# названный момент — отдаёт как есть. Второе обязательно: сдвинув ОБЕ стороны
# сравнения, прогон не показал бы ничего.
#
# Одно от другого шим отличает по АРГУМЕНТУ, а не по наличию флага, и правило
# это слово в слово то же, что у tools/date-mine-guard.py (SHELL_DATE_ARG,
# SHELL_CLOCK_WORD, asks_now): `date -d now`, `-d yesterday`, `-d '+1 day'`,
# `-d '2 days ago'` — часы; `-d "@$epoch"`, `-d '2026-09-12 13:59:00'`, `-r`,
# `-j -f` — названный момент.
#
# До задачи 0206 шим решал по флагу, то есть стоял на той самой ослабленной
# редакции, которую сторож у себя уже починил. Цена была не косметическая:
# проверка, спрашивающая часы через `date -d now`, в сдвинутом прогоне видела
# НАСТОЯЩЕЕ «сейчас», литерал рядом был сдвинут, исход не менялся — и мина
# оставалась невидимой ровно в том прогоне, который её ищет. Правила два, живут
# они в разных файлах и разойтись могут снова, поэтому сверяются теперь
# прогоном, а не чтением: `--selftest` ниже.
make_shim() {
    dir="$1"
    seconds="$2"
    cat > "$dir/date" <<SHIM_END
#!/bin/sh
# Подменный date (tools/clock-shift-run.sh): сдвигает ответ на вопрос
# «сейчас» и не трогает ответ про названный момент. Решает по аргументу,
# тем же правилом, что tools/date-mine-guard.py; сверяются они прогоном —
# ./tools/clock-shift-run.sh --selftest.
real=/bin/date
seconds=$seconds

# Первый проход — только классификация: аргументы не расходуются, потому что
# названный момент уходит настоящему date ИСХОДНОЙ строкой вызова.
moment=0
have_d=0
darg=""
prev=""
for a in "\$@"; do
    [ "\$prev" = "-d" ] && { darg="\$a"; have_d=1; }
    case "\$a" in
        -r|-j|--reference=*) moment=1 ;;
        --date=*) darg="\${a#--date=}"; have_d=1 ;;
    esac
    prev="\$a"
done

# Слово часов в аргументе -d: now, today, yesterday, tomorrow, ±N, next, last,
# «… ago». Всё прочее в -d — названный момент: эпоха или дата строкой.
if [ "\$have_d" = 1 ] && [ "\$moment" = 0 ]; then
    printf '%s' "\$darg" | grep -Eqi \
        '^[[:space:]]*(now|today|yesterday|tomorrow|[-+][0-9]|next|last)|(^|[^[:alnum:]])ago([^[:alnum:]]|\$)' \
        || moment=1
fi

[ "\$moment" = 1 ] && exec "\$real" "\$@"

# Часы. Относительное выражение считает сам date — от настоящего «сейчас», —
# и сдвиг прибавляется к результату: иначе -d '+1 day' дал бы завтрашний день
# настоящего месяца, то есть ответ, не сдвинутый вовсе.
if [ "\$have_d" = 1 ]; then
    base=\$("\$real" -d "\$darg" +%s 2>/dev/null) || base=""
    # Выражения, которого этот date не понимает (у BSD -d нет вовсе), шим
    # не подменяет тихо: пусть отказ будет виден там, где его написали.
    [ -n "\$base" ] || exec "\$real" "\$@"
else
    base=\$("\$real" +%s)
fi
now=\$(( base + seconds ))

utc=""
fmt=""
for a in "\$@"; do
    case "\$a" in
        -u) utc="-u" ;;
        +*) fmt="\$a" ;;
    esac
done
if [ -n "\$fmt" ]; then
    "\$real" \$utc -r "\$now" "\$fmt" 2>/dev/null || "\$real" \$utc -d "@\$now" "\$fmt"
else
    "\$real" \$utc -r "\$now" 2>/dev/null || "\$real" \$utc -d "@\$now"
fi
SHIM_END
    chmod +x "$dir/date"
}

# Сам шим обязан работать, иначе «проверки прошли» означало бы, что часы
# никуда не двигались. Ровно та же болезнь, что у пробы, зеленеющей оттого,
# что сеть не ответила.
check_shim() {
    before="$(/bin/date -u +%Y-%m-%d)"
    after="$(PATH="$1:$PATH" date -u +%Y-%m-%d)"
    if [ "$before" = "$after" ]; then
        red "Подменный date не сдвигает время ($before): проверки шли бы по настоящим часам."
        return 1
    fi
    printf 'Шеллу «сегодня» показывается как %s вместо %s\n' "$after" "$before"
    return 0
}

# ─────────────────────────────── самопроверка ────────────────────────────────
#
# Шим и статический сторож обязаны понимать «сейчас» ОДИНАКОВО: что сторож
# считает вопросом о часах, то шим сдвигает; что названным моментом — отдаёт
# как есть. Иначе одно из двух. Шим слабее сторожа — мина, спрашивающая часы
# через `date -d now`, невидима в прогоне, который её ищет (так и было
# до задачи 0206). Шим сильнее — сдвигаются обе стороны сравнения разом,
# и прогон не показывает ничего.
#
# Поэтому сверка идёт ПРОГОНОМ: каждый вызов задаётся обоим — сторожу через
# `--classify`, шиму по-настоящему, — и расхождение красит проверку. Чтением
# такое не устанавливается: правила живут в двух файлах и однажды уже
# разъехались, причём молча.
#
# Литерал даты в вызовах ниже разобран в ALLOWED сторожа с причиной: здесь
# он оракул, а не мина — момент зашит с обеих сторон и от сегодняшнего числа
# ответ не зависит вовсе.
selftest() {
    dir="$(mktemp -d)"
    trap 'rm -rf "$dir"' EXIT
    make_shim "$dir" "$SHIFT_SECONDS"

    printf 'Сверяются подменный date и tools/date-mine-guard.py --classify\n'
    check_shim "$dir" || return 2
    printf '\n'

    bad=0
    unchecked=""
    while IFS= read -r call; do
        [ -n "$call" ] || continue
        verdict="$(./tools/date-mine-guard.py --classify "$call" 2>&1 | tail -1)"
        plain="$(eval "$call" 2>/dev/null)"; plain_rc=$?
        shifted="$(PATH="$dir:$PATH"; export PATH; eval "$call" 2>/dev/null)"; shifted_rc=$?
        case "$verdict" in
            часы)
                if [ "$plain_rc" != 0 ] || [ -z "$plain" ]; then
                    unchecked="$unchecked
  ~ $call — этот /bin/date такой формы не понимает, сдвиг не наблюдаем"
                elif [ "$plain" = "$shifted" ]; then
                    red "  ✗ $call"
                    red "      сторож: это вопрос «сейчас»; шим ответ НЕ сдвинул ($shifted)."
                    red "      Значит мина, спрашивающая часы этой формой, в сдвинутом"
                    red "      прогоне невидима — ровно то, что закрывала задача 0206."
                    bad=1
                else
                    green "  ✓ $call — часы: $plain → $shifted"
                fi ;;
            момент)
                if [ "$plain" = "$shifted" ] && [ "$plain_rc" = "$shifted_rc" ]; then
                    green "  ✓ $call — названный момент, не сдвинут: $plain"
                else
                    red "  ✗ $call"
                    red "      сторож: это названный момент; шим его сдвинул ($plain → $shifted)."
                    red "      Сдвинув обе стороны сравнения, прогон не покажет ничего."
                    bad=1
                fi ;;
            *)
                red "  ✗ $call — сторож не сказал, часы это или момент: «$verdict»"
                bad=1 ;;
        esac
    done <<CASES
date -u +%s
date -u -d now +%F
date -u -d yesterday +%F
date -u -d '+1 day' +%F
date -u -d '@0' +%F
date -u -d '2026-09-12 13:59:00' +%s
date -u -r 0 +%F
date -u -j -f '%F %T' '2026-09-12 13:59:00' +%s
CASES

    if [ "$bad" = 1 ]; then
        printf '\n'
        red "Шим и сторож отвечают по-разному (см. выше): у сдвинутого прогона"
        red "и у статического сторожа разошлось само понятие «сейчас»."
        return 1
    fi
    if [ -n "$unchecked" ]; then
        printf '%s\n\n' "$unchecked"
        warn "Часть вызовов не проверена (названа выше) — это не зелёный ответ."
        warn "GNU date понимает их все: такой ответ даёт прогон CI, а на macOS"
        warn "/bin/date не знает -d вовсе."
        return 2
    fi
    printf '\n'
    green "Шим и сторож понимают «сейчас» одинаково: восемь вызовов date"
    green "(семь случаев критерия; последний — в двух формах, -r и -j -f)."
    return 0
}

if [ "$SELFTEST" = 1 ]; then
    selftest
    exit $?
fi

SHIM="$(mktemp -d)"
trap 'rm -rf "$SHIM"' EXIT
make_shim "$SHIM" "$SHIFT_SECONDS"
check_shim "$SHIM" || exit 2

# ───────────────────────────────── фронтенд ──────────────────────────────────
#
# node в PATH есть не всегда: локально он из nvm, а версия закреплена
# в `frontend/.nvmrc` — той же, которую берёт CI. Не нашёлся — прогон
# называется непроверенным, а не пропускается молча.
if ! command -v node > /dev/null 2>&1; then
    want="$(cat frontend/.nvmrc 2>/dev/null || true)"
    for dir in "$HOME/.nvm/versions/node/v${want}"* "$HOME/.nvm/versions/node"/*; do
        if [ -x "$dir/bin/node" ]; then
            PATH="$dir/bin:$PATH"
            export PATH
            break
        fi
    done
fi

step "Фронтенд: тот же набор со сдвинутыми часами"
if ! command -v node > /dev/null 2>&1; then
    warn "  НЕ ПРОВЕРЕНО: node не найден ни в PATH, ни в nvm"
    UNCHECKED=1
elif [ ! -x "$ROOT/frontend/node_modules/.bin/vitest" ]; then
    warn "  НЕ ПРОВЕРЕНО: нет frontend/node_modules — сделайте npm ci"
    UNCHECKED=1
elif (
        cd frontend \
        && CLOCK_SHIFT_DAYS="$DAYS" ./node_modules/.bin/vitest run \
            --config vitest.shifted.config.ts > "$SHIM/front.log" 2>&1
    ); then
    green "  ✓ исход не поменялся: $(grep -oE 'Tests +[0-9]+ passed' "$SHIM/front.log" | tail -1)"
else
    red "  ✗ со сдвинутыми часами прогон падает — значит какая-то проверка"
    red "    держится на календаре. Упавшее:"
    grep -E '^ *(FAIL|✗|×)' "$SHIM/front.log" | head -20 | sed 's/^/      /'
    CHANGED=1
fi

# ────────────────────────── проверки ячейки и сторожа ────────────────────────
#
# Список не переписывается рядом, а собирается: сторож, заведённый после
# правки этого файла, иначе остался бы непроверенным — и молча.
#
# Пропуск — по имени и с причиной, как разрешённые пары у сторожа схем.
# Молчаливый пропуск съел бы и настоящую проверку, а пустой список сделал бы
# прогон многоминутным: самопроверка, поднимающая Postgres, идёт здесь дважды.
skip_why() {
    case "$1" in
        db/verify-rollback.py)
            printf 'поднимает Postgres и гоняет Liquibase по одному changeset’у — минуты, и дважды; календарных дат в нём нет' ;;
        *) printf '' ;;
    esac
}

# Предел на одну самопроверку: зависшая не должна вешать весь прогон, и «висит»
# обязано отличаться от «прошла». На ubuntu это `timeout`, на macOS —
# `gtimeout` из coreutils; нет ни того, ни другого — гоняем без предела
# и говорим об этом.
LIMIT=""
for candidate in timeout gtimeout; do
    command -v "$candidate" > /dev/null 2>&1 && LIMIT="$candidate 180" && break
done
[ -n "$LIMIT" ] || warn "ни timeout, ни gtimeout — самопроверки идут без предела по времени"

step "Проверки и сторожа: свои самопроверки со сдвинутыми часами"
for file in ops/*.sh tools/*.sh tools/*.py db/*.py; do
    [ -f "$file" ] || continue
    [ "$file" = "tools/clock-shift-run.sh" ] && continue
    why="$(skip_why "$file")"
    if [ -n "$why" ]; then
        warn "  ~ $file — пропущено: $why"
        continue
    fi
    flag=""
    grep -q -- '--selftest' "$file" && flag="--selftest"
    grep -q -- '--самопроверка' "$file" && flag="--самопроверка"
    [ -n "$flag" ] || continue
    [ -x "$file" ] || continue

    $LIMIT "./$file" "$flag" > "$SHIM/plain.log" 2>&1; plain=$?
    PATH="$SHIM:$PATH" $LIMIT "./$file" "$flag" > "$SHIM/shifted.log" 2>&1; shifted=$?

    if [ "$plain" = "$shifted" ]; then
        if [ "$plain" = 0 ]; then
            green "  ✓ $file — исход тот же"
        else
            warn  "  ~ $file — падает и без сдвига (код $plain), к часам отношения не имеет"
        fi
        continue
    fi
    red "  ✗ $file — исход поменялся: без сдвига $plain, со сдвигом $shifted"
    diff "$SHIM/plain.log" "$SHIM/shifted.log" | head -12 | sed 's/^/      /'
    CHANGED=1
done

# ────────────────────────────────── бэкенд ──────────────────────────────────
step "Бэкенд"
JVM_SHIFTS=0
if command -v faketime > /dev/null 2>&1; then
    probe="$(mktemp -d)"
    printf 'public class T { public static void main(String[] a){ System.out.println(java.time.LocalDate.now()); } }\n' \
        > "$probe/T.java"
    real_day="$(java "$probe/T.java" 2>/dev/null)"
    fake_day="$(faketime -f "+${DAYS}d" java "$probe/T.java" 2>/dev/null)"
    rm -rf "$probe"
    [ -n "$fake_day" ] && [ "$real_day" != "$fake_day" ] && JVM_SHIFTS=1
fi

if [ "$JVM_SHIFTS" = 0 ]; then
    warn "  НЕ ПРОВЕРЕНО: часы этой JVM не сдвигаются (faketime до неё не доходит)."
    warn "  На macOS подписанный java не подгружает библиотеку faketime — это"
    warn "  свойство машины, а не прогона; на linux-раннере сдвиг работает."
    warn "  Статически бэкенд проверен: ./tools/date-mine-guard.py."
    UNCHECKED=1
elif [ "$WITH_JAVA" = 0 ]; then
    warn "  не запускалось: нужен --java (полный прогон это ~20 минут)"
    UNCHECKED=1
else
    # Офлайн здесь обязателен, и это замер, а не вкус: под сдвинутыми часами
    # выкачка не проходит вовсе — обёртка тянет сам maven по HTTPS, а к дате
    # на месяц вперёд сертификат сервера просрочен, и `wget` отвечает «Failed
    # to fetch». Прогон бэкенда умирал на этом за полсекунды, к часам
    # отношения не имея: на раннере обычный «Бэкенд» был зелёный, а сдвинутый
    # падал на выкачке (прогоны 36396852635 и 36399889628). Значит maven
    # обязан быть прогрет настоящими часами ДО этого места — шагом CI либо
    # руками.
    # Два теста с настоящим хранилищем исключены по имени и с причиной — как
    # тяжёлые самопроверки выше. MinIO поднимается контейнером и живёт
    # по НАСТОЯЩИМ часам, а подпись S3 несёт отметку времени: клиент, ушедший
    # на месяц вперёд, получает 403 и не загружает ничего. Замерено
    # на раннере: 12 падений в PhotoServiceTest и PhotoArchiveStreamTest
    # («хранилище отвергло подписанную ссылку», ожидалось 200, пришло 403)
    # при зелёном обычном «Бэкенде» в том же прогоне (36402641773). Это
    # свойство подписи, а не календарная мина, и чинить тут нечего — но
    # и молчать нельзя: их календарная зависимость этим прогоном НЕ проверена,
    # и прогон говорит это вслух, а не пропускает молча.
    S3_EXCLUDE='!PhotoServiceTest,!PhotoArchiveStreamTest'
    warn "  ~ из сдвинутого прогона исключены: $S3_EXCLUDE"
    warn "    хранилище живёт по настоящим часам, и подписанный запрос"
    warn "    от сдвинутого клиента отвергается (403) — это подпись,"
    warn "    а не календарь. Их зависимость от календаря не проверена."
    if faketime -f "+${DAYS}d" ./mvnw -o -B -ntp test -Dtest="$S3_EXCLUDE" \
            > "$SHIM/back.log" 2>&1; then
        green "  ✓ исход не поменялся"
    else
        mvn_rc=$?
        # Выжимка по тестам — и то, что делать, когда она пуста. Пустая
        # выжимка на красном означает «упало, а что упало, не сказано»:
        # ровно та проверка, которая отсылает человека к логу, которого
        # он не увидит (лог живёт во временном каталоге прогона CI).
        # Выжимка ищет ПАДЕНИЯ, а не слово «тест». Первая редакция брала
        # `Tests run`, то есть совпадала с успешными строками `[INFO] Tests
        # run: 2, Failures: 0` — их сотни, и `head` обрезал вывод задолго
        # до настоящего отказа: на раннере в выжимку попали двадцать зелёных
        # строк, а имя упавшего теста не попало вовсе. Красное, которое
        # не называет упавшего, — это тот же «упало, а что упало, не сказано».
        named="$(grep -E '<<< (FAILURE|ERROR)!|Tests run:.*(Failures: [1-9]|Errors: [1-9])|^\[ERROR\]   [A-Za-z]|^\[ERROR\] BUILD FAILURE|^\[ERROR\] Failed to execute goal' \
            "$SHIM/back.log" 2>/dev/null | head -20)"
        if [ -n "$named" ]; then
            red "  ✗ со сдвинутыми часами падает (maven вышел с кодом $mvn_rc):"
            printf '%s\n' "$named" | sed 's/^/      /'
            # И хвост лога рядом с выжимкой — всегда, а не вместо неё. Выжимка
            # отвечает «что упало», хвост — «почему», а сам лог живёт
            # во временном каталоге прогона и человеку не достаётся: разбирать
            # придётся по тому, что напечатано здесь и сейчас.
            red "  Последние строки прогона:"
            tail -30 "$SHIM/back.log" | sed 's/^/      /'
            CHANGED=1
        else
            # Ни один тест не назвался — значит упал не тест, а сам прогон:
            # maven не начался, JVM не поднялась, зависимости не приехали.
            # Это «не проверено», а не «нашли мину»: назвать миной отказ,
            # к часам отношения не имеющий, значит соврать в ту же сторону,
            # в которую врал бы молчаливый зелёный.
            warn "  НЕ ПРОВЕРЕНО: прогон бэкенда не состоялся — maven вышел"
            warn "  с кодом $mvn_rc, и ни одного теста не назвалось. Последние строки:"
            tail -25 "$SHIM/back.log" | sed 's/^/      /'
            warn "  Если это отказ выкачки — так и задумано: сеть под сдвинутыми"
            warn "  часами не работает. Прогрейте maven настоящими часами"
            warn "  и повторите: ./mvnw -B -ntp -DskipTests=true test-compile"
            UNCHECKED=1
        fi
    fi
fi

step "Итог"
if [ "$CHANGED" = 1 ]; then
    red "Сдвиг часов поменял исход: в проверках есть календарная мина (см. выше)."
    exit 1
fi
if [ "$UNCHECKED" = 1 ]; then
    warn "Прогнанное сдвиг не поменял, но часть не проверена (названа выше)."
    warn "Это не зелёный: «проверить не вышло» и «всё хорошо» — разные ответы."
    exit 2
fi
green "Часы вперёд на $DAYS дн. — ни одна проверка не поменяла исход."
exit 0
