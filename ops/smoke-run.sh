#     делается на машине;
#   • признак в реестре арендаторов — честнее по смыслу, но это changeset,
#     то есть `migrator` и отдельная ветка;
#   • отдельная переменная окружения — НЕ ГОДИТСЯ ВОВСЕ: ровно от забытой
