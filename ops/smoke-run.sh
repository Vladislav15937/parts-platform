# ─────────────────────── своя компания прогона (0144) ────────────────────────
#
# ЧЕМ ПОМЕЧАЕТСЯ ТЕСТОВАЯ КОМПАНИЯ — белым списком прямо здесь, и это
# РЕШЕНИЕ ИСПОЛНИТЕЛЯ. Путей было три, у каждого цена:
#   • список в скрипте — видно при чтении, едет тем же SHA, что и образ,
