# ───────────────────────────── разбор ответов ────────────────────────────────
#
# Тело и код приезжают одной строкой-ответом: код последней строкой (curl -w).
body_of() { printf '%s' "$1" | sed '$d'; }
code_of() { printf '%s' "$1" | tail -n 1 | tr -dc '0-9' | tail -c 3; }

# Значение из тела ответа: val "$body" "d['items'][0]['status']".
# Пусто — если тело не разобралось или ключа нет. Пустое значение и есть
# признак «ответ не тот», и обрабатывают его вердикты, а не эта функция.
val() {
    printf '%s' "$1" | python3 -c "
import json, sys
try:
    d = json.load(sys.stdin)
except ValueError:
    sys.exit(1)
try:
    v = eval(sys.argv[1])
except Exception:
    sys.exit(1)
print('' if v is None else v)
" "$2" 2>/dev/null
}

# Деньги приезжают числом JSON: «5000.0» и «5000.00» — одно и то же,
# и сравнивать их текстом значит ловить собственное написание.
same_money() { python3 -c "
import sys
try:
    sys.exit(0 if float(sys.argv[1]) == float(sys.argv[2]) else 1)
except ValueError:
    sys.exit(1)" "$1" "$2"; }

# ─────────────────────────── как ходить за ответом ───────────────────────────
#
# Изнутри контейнера терминатора: порты сборок наружу не опубликованы,
# у caddy есть curl, и он в той же сети — тем же доводом живёт
# ops/deploy-checks.sh. С хоста ходят там, где прогон нацелили на чужую
# машину или на свой подъём.
run_there() {
    if [ "$ROUTE" = host ]; then "$@"; else $COMPOSE exec -T caddy "$@"; fi
}

# МЕТОД ПУТЬ [ТЕЛО] → тело ответа, последней строкой код.
#
# Тело уезжает потоком, а не аргументом: в нём пароль, а аргументы команды
# видит в `ps` любой, у кого есть учётка на машине (тем же доводом живёт
# ops/migrate-tenants.sh).
request() {
    local method="$1" path="$2" body="${3-}"
    set -- -sS -m "$TIMEOUT" -X "$method" -b "$JAR" -c "$JAR" \
           -H 'Content-Type: application/json' -w '\n%{http_code}'
    [ -n "$CSRF" ] && set -- "$@" -H "X-XSRF-TOKEN: $CSRF"
    [ -n "$RESOLVE_HOST" ] && set -- "$@" --resolve "$RESOLVE_HOST:443:127.0.0.1"
    # Заголовки ответа — в файл рядом с банкой, и только когда их спросили.
    # По ним вход отличает «cookie не доехала» от «пароль не тот»: это
    # единственное наблюдаемое, которое их различает (задача 0147).
    [ -n "$DUMP_HEADERS" ] && set -- "$@" -D "$DUMP_HEADERS"
    # А трасса — про ЗАПРОС, и это другой вопрос: заголовки ответа говорят,
    # что сервер сделал, а «ушла ли cookie» по ним не узнать вовсе (0149).
    [ -n "$DUMP_TRACE" ] && set -- "$@" -v --stderr "$DUMP_TRACE"
    if [ -n "$body" ]; then
        printf '%s' "$body" | run_there curl "$@" --data-binary @- "$BASE$path" 2>&1
    else
        run_there curl "$@" "$BASE$path" 2>&1
    fi
}

# Токен CSRF приложение кладёт в cookie, а в заголовок его перекладывает
# клиент. Здесь клиент — мы, и банка лежит там же, откуда ходит curl.
read_csrf() { run_there awk '/XSRF-TOKEN/ {print $7}' "$JAR" 2>/dev/null | tail -n 1; }

# Заголовки последнего ответа и строка банки с токеном — свидетельства,
# по которым вход называет причину отказа (задача 0147). Отдельными
# функциями, а не строками в шаге, по той же причине, что и read_csrf:
# их подменяет самопроверка, иначе проверен был бы вердикт, а не путь.
read_headers() { run_there cat "${JAR}-headers" 2>/dev/null; }
# Вся строка банки, а не только значение: в ней видны и хозяин cookie
# (домен), и флаг Secure — четвёртым полем. Cookie, помеченная Secure,
# в банке ЛЕЖИТ и читается awk'ом, а по http не отправляется вовсе:
# «токен получен» и «токен доехал» — разные утверждения.
read_jar_line() { run_there awk '/XSRF-TOKEN/ {print}' "$JAR" 2>/dev/null | tail -n 1; }
# Трасса запроса — единственное место, где видно, что curl ПОЛОЖИЛ В ЗАПРОС.
# «Токен в банке есть» и «cookie ушла» — разные утверждения, и до 0149
# второе не измерял никто: отказ говорил о нём, не спросив.
read_trace() { run_there cat "${JAR}-trace" 2>/dev/null; }

# Значение XSRF-TOKEN из заголовка Cookie ЗАПРОСА (строки «> Cookie:»),
# а не из Set-Cookie ответа: в трассе лежит и то, и другое.
sent_cookie_of() {
    printf '%s' "$1" | awk '
        /^> [Cc]ookie:/ {
            if (match($0, /XSRF-TOKEN=[^;[:space:]]+/)) {
                print substr($0, RSTART + 11, RLENGTH - 11); exit
            }
        }'
}

# Токен, который сервер завёл в ответе: до 0149 его печатали как «отправленный».
fresh_token_of() {
    printf '%s' "$1" | awk '
        /XSRF-TOKEN=/ {
            if (match($0, /XSRF-TOKEN=[^;[:space:]]+/)) {
                print substr($0, RSTART + 11, RLENGTH - 11); exit
            }
        }'
}

# ───────────────────────────── куда и в каком режиме ─────────────────────────
#
# Метка хоста сильнее переменной намеренно: DEPLOY_STAND передаёт кнопка,
# а переменную однажды забудут или передадут не ту — и тогда «дымовой прогон»
# оформит сделку в учёте живого клиента. Обратной ошибки (лишнее чтение
# на ИФТ) не существует.
host_label() {  # адрес → prom, ift, psi, local либо пусто
    printf '%s' "$1" | python3 -c "
import re, sys, urllib.parse
host = (urllib.parse.urlsplit(sys.stdin.read().strip()).hostname or '').lower()
if host in ('localhost', '127.0.0.1', '::1'):
    print('local')
else:
    labels = set(re.split(r'[.\-]', host))
    for label, name in (('prom', 'prom'), ('prod', 'prom'), ('psi', 'psi'), ('ift', 'ift')):
        if label in labels:
            print(name)
            break
" 2>/dev/null
}

# стенд, метка хоста, затребованный флаг, «своя ли компания» → «write»,
# «write-if-confirmed», «read-only» либо отказ строкой, начинающейся
# с «отказ:».
#
# Четвёртый аргумент необязателен и по умолчанию пуст — то есть компания
# считается ЧУЖОЙ, пока не доказано обратное. Направление отказа здесь
# единственно верное: забыли передать признак — получили лишнее чтение.
mode_of() {
    local stand="$1" label="$2" want="$3" test_company="${4-}" allowed
    # Своя компания прогона — единственное, что открывает запись на ПРОМ,
    # и открывает НЕ ДО КОНЦА: «write-if-confirmed» значит «писать можно,
    # когда вход подтвердит, что попали именно в неё» (0144).
    local prom_mode="read-only"
    [ "$test_company" = yes ] && prom_mode="write-if-confirmed"

    case "$label" in
        prom) allowed="$prom_mode" ;;
        *)
            case "$stand" in
                prom) allowed="$prom_mode" ;;
                ift|psi) allowed="write" ;;
                *)
                    # Локальный подъём — это машина разработчика, а не стенд:
                    # там писать можно, не называя стенда.
                    if [ "$label" = local ]; then allowed="write"
                    else allowed="отказ: стенд не назван (DEPLOY_STAND=ift|psi|prom) и по имени хоста не узнаётся — не зная, ПРОМ это или нет, прогон не пишет ничего"; fi ;;
            esac ;;
    esac

    case "$want" in
        # Просить меньше можно всегда: лишнее чтение не портит ничего.
        read-only) [ "${allowed#отказ:}" = "$allowed" ] && echo "read-only" || echo "$allowed" ;;
        write)
            if [ "$allowed" = write ]; then echo write
            elif [ "$allowed" = write-if-confirmed ]; then echo write-if-confirmed
            elif [ "$allowed" = read-only ]; then
                echo "отказ: это ПРОМ, а компания прогона не значится тестовой — там живые данные клиента, и дымовая сделка была бы сделкой в его учёте. Писать на ПРОМ можно только в свою тестовую компанию (белый список TEST_TENANTS)"
            else echo "$allowed"; fi ;;
        *) echo "$allowed" ;;
    esac
}

# Стенд, адрес и затребованный флаг → MODE, TEST_TENANT, CONFIRM_FOR_WRITE.
#
# Отдельной функцией, а не строками в хвосте: самопроверка обязана считать
# режим ТЕМ ЖЕ путём, которым его считает живой прогон. Проба, решающая
# за него, проверяет себя, а не выкладку.
decide_mode() {  # стенд, адрес, затребованный режим
    TEST_TENANT=$(test_tenant_of "$SMOKE_COMPANY")
    local is_test=""
    [ -n "$TEST_TENANT" ] && is_test=yes
    MODE=$(mode_of "$1" "$(host_label "$2")" "$3" "$is_test")
    CONFIRM_FOR_WRITE=""
    # Умолчание — «нельзя»: до подтверждения входом прогон идёт читающим.
    # Ошибка в эту сторону стоит лишнего чтения, в обратную — сделки
    # в учёте живого клиента.
    if [ "$MODE" = write-if-confirmed ]; then
        MODE="read-only"
        CONFIRM_FOR_WRITE=yes
    fi
}

# ─────────────────────────────── вердикты ────────────────────────────────────
#
# Разбор отделён от запроса намеренно: краснеть проверка обязана на дефекте,
# а установить это можно, только подсунув ей ответ. Ниже так у всех шагов.

# ТОКЕН CSRF — ОТДЕЛЬНЫЙ ВЕРДИКТ, И ЭТО НЕ ПЕДАНТИЗМ (задача 0146).
#
# Вход без токена отбивается фильтром CSRF, а пользователь в этот момент ещё
# анонимный — Spring переводит отказ в ТОЧКУ ВХОДА аутентификации, то есть
# наружу выходит 401 с пустым телом. Ровно такой же 401 с пустым телом
# приходит на неверный пароль: проверено опытом, ответы неразличимы
# до буквы (то же записано в javadoc AuthController.csrf()).
#
# Пока этого вердикта не было, прогон на любой отказ входа говорил
# «проверьте SMOKE_COMPANY/SMOKE_LOGIN/SMOKE_PASSWORD» — то есть НАЗЫВАЛ
# ПРИЧИНУ, КОТОРОЙ НЕ ПРОВЕРЯЛ. Красная выкладка кнопкой на ПРОМ
# (прогон 35453785036) из-за этого разбиралась по неверной версии: секрет
# был верен, минутой раньше тот же пароль дал 200 через терминатор.
#
# Поэтому токен спрашивается ДО входа и отдельно: ответ /api/auth/csrf
# и сам токен. Пустая банка — это не «неверный пароль», и сказать об этом
# надо тем, кто будет читать лог выкладки.
verdict_csrf() {  # код ответа /api/auth/csrf, прочитанный токен
    case "$1" in
        200|204) ;;
        000|"")
            bad "токен CSRF не получить: GET /api/auth/csrf не ответил вовсе (${BASE}) — вход без токена отвечает 401, как на неверный пароль" "токен CSRF"
            return 1 ;;
        *)
            bad "токен CSRF не получить: GET /api/auth/csrf ответил $1, а не 204 — вход без токена отвечает 401, как на неверный пароль" "токен CSRF"
            return 1 ;;
    esac
    if [ -z "$2" ]; then
        # Главный случай: ответ годный, а в банке пусто. Так ведёт себя curl,
        # получив по http cookie с флагом Secure, — он её не сохраняет вовсе.
        bad "GET /api/auth/csrf ответил $1, а токена в банке нет (${JAR}): вход уйдёт без заголовка X-XSRF-TOKEN и получит 401 — неотличимо от неверного пароля" "токен CSRF"
        return 1
    fi
    ok "токен CSRF получен"
}

# ЧТО ИМЕННО РАЗЛИЧАЕТ ПРИЧИНЫ 401 — ИЗМЕРЕНО, А НЕ ВЫВЕДЕНО (задача 0147).
#
# 0146 научила прогон спрашивать токен до входа; получив его, он стал
# утверждать «значит дело в учётной записи» — и снова назвал причину,
# которой не проверял: учётная запись на ПРОМ была верна, вход снаружи
# в ту же минуту давал 200. Одна неверная подсказка сменилась другой.
#
# Живой прогон настоящего образа (того самого, c250226) даёт таблицу:
#
#   случай                          код  новая XSRF-TOKEN   журнал входов
#   верный пароль                   200  нет                +1
#   НЕВЕРНЫЙ ПАРОЛЬ                 401  нет                +1 (FAILED)
#   нет такой компании              401  нет                без изменений
#   cookie CSRF не доехала          401  ДА                 без изменений
#
# То есть «новая XSRF-TOKEN в ответе» — ЕДИНСТВЕННОЕ наблюдаемое, которое
# отделяет «сервер не увидел cookie» от «сервер проверил пароль»: тела у всех
# трёх отказов нет вовсе (Content-Length: 0), и по коду они неразличимы.
# Сервер заводит новый токен ровно тогда, когда присланного не было.
#
# Поэтому заголовки ответа входа снимаются всегда, и вердикт называет только
# то, что в них увидел. Свидетельств нет — причина НЕ УСТАНОВЛЕНА, и так
# и говорится: инструмент, уверенно называющий не ту причину, дороже
# молчащего — молчащий отправляет смотреть, уверенный чинить не то.
# И ОДНО ИЗ ЭТИХ СВИДЕТЕЛЬСТВ САМО ОКАЗАЛОСЬ НЕИЗМЕРЕННЫМ (задача 0149).
#
# Пятая красная выкладка на ПРОМ (прогон 35465647129) показала «Отправляли
# токен «a354d337…», банка: «…2ee85b2e…»» — два РАЗНЫХ значения, отчего
# и родилась версия «прогон шлёт не то, что лежит в банке». Версия неверна,
# и это установлено живым прогоном того же образа: строку «отправляли»
# печатал CSRF, перечитанный ПОСЛЕ запроса, а банку к этой минуте переписал
# `curl -c` ответом. То есть «отправленным» назывался токен ИЗ ОТВЕТА —
# тот самый новый, по которому вердикт и опознаёт непришедшую cookie.
# Расходились они ВСЕГДА, когда сервер заводил новый токен, и о том,
# что ушло, не говорили ничего.
#
# Поэтому теперь: отправленный токен снимается ДО запроса (SENT_CSRF),
# новый токен из ответа называется новым, а «ушла ли cookie» спрашивается
# у трассы запроса — единственного места, где это видно.
verdict_login() {  # код, тело, заголовки ответа, строка банки ДО запроса, трасса
    local heads="${3-}" jarline="${4-}" trace="${5-}"
    case "$1" in
        200) ;;
        401|403)
            if [ -z "$heads" ]; then
                bad "вход не прошёл ($1), а свидетельств нет: заголовки ответа не сняты (${JAR}-headers). ПРИЧИНА НЕ УСТАНОВЛЕНА — ни токен, ни учётная запись здесь не проверены" "вход"
                return 1
            fi
            case "$heads" in
                *XSRF-TOKEN*|*xsrf-token*)
                    # Измеренное: сервер завёл НОВЫЙ токен, то есть присланной
                    # cookie он не видел. До проверки пароля дело не дошло.
                    local secure why fresh jar_token sent_said sent_cookie cookie_said
                    secure=$(printf '%s' "$jarline" | awk '{print $4}')
                    fresh=$(fresh_token_of "$heads")
                    why="в ответе стоит НОВАЯ XSRF-TOKEN «$(printf '%s' "${fresh:-—}" | cut -c1-8)…»"
                    if [ "$secure" = TRUE ] && [ "${BASE#http://}" != "$BASE" ]; then
                        # Тот случай, когда «токен получен» и «токен доехал»
                        # расходятся: в банке он есть и читается, а curl
                        # не отправляет его по незащищённому адресу.
                        why="${why}, а в банке она помечена Secure — по http curl её не отправляет вовсе"
                    fi
                    # ЧТО УШЛО — снято ДО запроса. Взять это у CSRF нельзя:
                    # он перечитан из банки, а банку переписал ответ (0149).
                    jar_token=$(printf '%s' "$jarline" | awk '{print $7}')
                    if [ -z "${SENT_CSRF:-}" ]; then
                        sent_said="Отправлять было нечего: заголовок X-XSRF-TOKEN не уходил."
                    elif [ -n "${jar_token}" ] && [ "${jar_token}" != "${SENT_CSRF}" ]; then
                        sent_said="Отправляли токен «$(printf '%s' "${SENT_CSRF}" | cut -c1-8)…», а в банке до запроса лежал «$(printf '%s' "${jar_token}" | cut -c1-8)…» — РАЗОШЛИСЬ."
                    else
                        sent_said="Отправляли токен «$(printf '%s' "${SENT_CSRF}" | cut -c1-8)…» — тот самый, что лежал в банке до запроса."
                    fi
                    # И то, чего не видно ни в банке, ни в заголовках ответа:
                    # положил ли curl cookie В САМ ЗАПРОС. Без этого «сервер
                    # не получил» и «клиент не отправил» неразличимы.
                    if [ -z "${trace}" ]; then
                        cookie_said="Ушла ли cookie в запросе — НЕ ИЗМЕРЕНО: трассы запроса нет (${JAR}-trace)."
                    else
                        sent_cookie=$(sent_cookie_of "${trace}")
                        if [ -n "${sent_cookie}" ]; then
                            cookie_said="Cookie XSRF-TOKEN=«$(printf '%s' "${sent_cookie}" | cut -c1-8)…» в запросе БЫЛА — curl её отправил, значит до сервера она не дошла либо он её не принял."
                        else
                            cookie_said="Заголовка Cookie в запросе НЕ БЫЛО — curl не отправил cookie из банки."
                        fi
                    fi
                    bad "вход отбит ДО проверки учётных данных ($1): сервер НЕ ПОЛУЧИЛ cookie CSRF — ${why}. ${sent_said} ${cookie_said} Банка ${JAR}: «${jarline:-пусто}», адрес ${BASE}. Учётной записи это не касается: такой попытки не будет и в журнале входов" "токен CSRF"
                    return 1 ;;
                *)
                    bad "вход не прошёл ($1): cookie CSRF до сервера ДОЕХАЛА — новой XSRF-TOKEN в ответе нет, значит отказ на проверке учётных данных. Проверьте SMOKE_COMPANY/SMOKE_LOGIN/SMOKE_PASSWORD (в журнале входов компании будет FAILED; при неизвестном коде компании — ни одной записи)" "вход"
                    return 1 ;;
            esac ;;
        *)
            # `--stderr` уводит в файл и собственные жалобы curl, поэтому
            # при «не ответил вовсе» причина лежит не в теле, а в трассе.
            local extra=""
            [ -n "${trace}" ] && extra=" Трасса: $(printf '%s' "${trace}" | tr '\n' ' ' | cut -c1-200)"
            bad "вход отвечает $1, а не 200: $(printf '%s' "$2" | tr '\n' ' ' | cut -c1-120).${extra}" "вход"
            return 1 ;;
    esac
    local role
    role=$(val "$2" "d['role']")
    if [ -z "$role" ]; then
        bad "вход ответил 200, но без роли — это не ответ входа: $(printf '%s' "$2" | tr '\n' ' ' | cut -c1-120)" "вход"
        return 1
    fi
    ok "вошли: $(val "$2" "d['displayName']") ($role)"
}

# КУДА ВХОД ПРИВЁЛ НА САМОМ ДЕЛЕ (0144). Ответ входа и «кто я» несут
# companySchema; секрет говорит, куда собирались, и писать можно только
# туда, куда попали. Несовпадение — отказ словами и ни одной записи:
# это главный случай задачи, он отличает намерение от факта.
verdict_tenant() {  # тело ответа, чем получено
    local schema
    schema=$(val "$1" "d['companySchema']")
    if [ -z "$schema" ]; then
        bad "${2} не назвал компанию (companySchema пусто) — куда попали, неизвестно, и записи не будет" "компания"
        return 1
    fi
    if [ "$schema" != "$TEST_TENANT" ]; then
        bad "секрет называет «${SMOKE_COMPANY}» (${TEST_TENANT}), а вход привёл в «${schema}» — записи не будет" "компания"
        return 1
    fi
    if [ -n "$CONFIRM_FOR_WRITE" ]; then
        MODE="write"
        ok "компания прогона подтверждена входом: ${schema} — продажу оформляем здесь"
    else
        ok "компания прогона подтверждена входом: ${schema}"
    fi
}

verdict_catalog() {  # код, тело
    if [ "$1" != 200 ]; then
        bad "витрина отвечает $1, а не 200 — склад не открывается вовсе" "витрина"
        return 1
    fi
    local total rows
    total=$(val "$2" "d['total']")
    rows=$(val "$2" "len(d['rows'])")
    if [ -z "$total" ] || [ -z "$rows" ]; then
        bad "витрина ответила 200, но это не страница склада: $(printf '%s' "$2" | tr '\n' ' ' | cut -c1-120)" "витрина"
        return 1
    fi
    # Пустая страница при непустом складе — то самое «200 с нулём байт»:
    # ответ есть, товара на экране нет.
    if [ "$total" -gt 0 ] && [ "$rows" = 0 ]; then
        bad "витрина говорит «позиций ${total}», а строк не отдала ни одной" "витрина"
        return 1
    fi
    ok "витрина отдаёт страницу: позиций $total, строк на странице $rows"
}

verdict_number_search() {  # номер, ожидаемый partId, код, тело
    if [ "$3" != 200 ]; then
        bad "поиск по номеру отвечает $3, а не 200" "поиск по номеру"
        return 1
    fi
    local found
    found=$(val "$4" "[r['partId'] for r in d['rows'] if str(r.get('number')) == '$1']")
    if [ -z "$found" ] || [ "$found" = "[]" ]; then
        bad "по номеру $1 не находится ничего — а позиция с этим номером на складе есть" "поиск по номеру"
        return 1
    fi
    case "$found" in
        *"$2"*) ok "поиск по номеру $1 находит свою позицию" ;;
        *) bad "по номеру $1 нашлась чужая позиция ($found вместо $2)" "поиск по номеру"; return 1 ;;
    esac
}

verdict_card() {  # код, тело
    if [ "$1" != 200 ]; then
        bad "карточка позиции отвечает $1, а не 200" "карточка"
        return 1
    fi
    if [ -z "$(val "$2" "1")" ]; then
        bad "карточка ответила 200, но тело не разобралось: $(printf '%s' "$2" | tr '\n' ' ' | cut -c1-120)" "карточка"
        return 1
    fi
    ok "карточка открывается"
}

verdict_intake() {  # код, тело
    if [ "$1" != 201 ]; then
        bad "приёмка отвечает $1, а не 201: $(printf '%s' "$2" | tr '\n' ' ' | cut -c1-140)" "приёмка"
        return 1
    fi
    if [ -z "$(val "$2" "d['parts'][0]['id']")" ]; then
        bad "приёмка ответила 201, но позиции в ответе нет — принимать было нечего" "приёмка"
        return 1
    fi
    ok "приёмка завела позицию $(val "$2" "d['parts'][0]['publicCode']")"
}

verdict_reserved() {  # код, тело сделки, свободный остаток после
    if [ "$1" != 201 ]; then
        bad "оформление сделки отвечает $1, а не 201: $(printf '%s' "$2" | tr '\n' ' ' | cut -c1-140)" "оформление сделки"
        return 1
    fi
    local status
    status=$(val "$2" "d['items'][0]['status']")
    if [ "$status" != RESERVED ]; then
        bad "сделка создана, но позиция в ней не отложена (статус «${status}», ждали RESERVED)" "оформление сделки"
        return 1
    fi
    # Главное здесь: не ответ, а полка. Сделка, не снявшая свободный остаток,
    # обещает одну деталь двум покупателям — и отвечает при этом 201.
    if [ "$3" != 0 ]; then
        bad "сделка оформлена, а деталь не отложена: свободный остаток $3 вместо 0" "оформление сделки"
        return 1
    fi
    ok "сделка $(val "$2" "d['number']") оформлена, деталь отложена (свободный остаток 0)"
}

verdict_paid() {  # код оплаты, тело сделки после оплаты
    if [ "$1" != 201 ]; then
        bad "оплата отвечает $1, а не 201: $(printf '%s' "$2" | tr '\n' ' ' | cut -c1-140)" "оплата"
        return 1
    fi
    local paid total debt
    paid=$(val "$2" "d['paidAmount']"); total=$(val "$2" "d['totalAmount']"); debt=$(val "$2" "d['debt']")
    if [ -z "$paid" ] || [ -z "$total" ]; then
        bad "после оплаты сделка не читается: $(printf '%s' "$2" | tr '\n' ' ' | cut -c1-120)" "оплата"
        return 1
    fi
    if ! same_money "$paid" "$total"; then
        bad "оплата принята, а долг не закрылся: оплачено $paid из $total" "оплата"
        return 1
    fi
    ok "оплата принята полностью: $paid из $total, долг $debt"
}

verdict_issued() {  # код выдачи, тело сделки, остаток после
    if [ "$1" != 200 ]; then
        bad "выдача отвечает $1, а не 200: $(printf '%s' "$2" | tr '\n' ' ' | cut -c1-140)" "выдача"
        return 1
    fi
    local status
    status=$(val "$2" "d['status']")
    if [ "$status" != ISSUED ]; then
        bad "выдача прошла, а сделка осталась в статусе «${status}» вместо ISSUED" "выдача"
        return 1
    fi
    # Выданное — это списанное с полки. Выдача, ответившая 200 и не тронувшая
    # остаток, оставляет проданную деталь в продаже.
    if [ "$3" != 0 ]; then
        bad "сделка выдана, а остаток не списан: на складе осталось $3" "выдача"
        return 1
    fi
    ok "выдача закрыла сделку и списала остаток"
}

verdict_cleanup() {  # код возврата, тело, остаток после
    if [ "$1" != 201 ]; then
        bad "убрать за собой не вышло: возврат отвечает $1 — на стенде осталась дымовая продажа" "уборка"
        return 1
    fi
    local status
    status=$(val "$2" "d['status']")
    if [ "$status" != DONE ]; then
        bad "возврат создан в статусе «${status}» вместо DONE — дымовая продажа осталась на стенде" "уборка"
        return 1
    fi
    if [ "$3" != 0 ]; then
        bad "уборка вернула дымовую деталь на полку (остаток $3) — она будет продаваться людям" "уборка"
        return 1
    fi
    ok "убрано за собой: остаток и касса вернулись к прежним"
}

# ─────────────────────────────── шаги ────────────────────────────────────────

step_login() {
    # Ответ csrf больше не выбрасывается: без токена вход обречён на 401,
    # и назвать это надо токеном, а не паролем (0146).
    local csrf_answer
    csrf_answer=$(request GET /api/auth/csrf)
    CSRF=$(read_csrf)
    verdict_csrf "$(code_of "$csrf_answer")" "$CSRF" || return 1
    local answer heads jarline trace
    # Строка банки читается ДО запроса: `curl -c` переписывает файл ответом,
    # и после входа в нём лежит уже НОВАЯ cookie — то есть не та, что ушла.
    # Свидетельство, снятое после, отвечало бы на другой вопрос.
    jarline=$(read_jar_line)
    # По той же причине здесь запоминается и ОТПРАВЛЯЕМЫЙ токен: ниже CSRF
    # перечитывается из переписанной банки, и отказ, называвший его
    # отправленным, называл токен из ответа (задача 0149).
    SENT_CSRF="$CSRF"
    DUMP_HEADERS="${JAR}-headers"
    DUMP_TRACE="${JAR}-trace"
    answer=$(request POST /api/auth/login \
        "{\"company\":\"$SMOKE_COMPANY\",\"login\":\"$SMOKE_LOGIN\",\"password\":\"$SMOKE_PASSWORD\"}")
    DUMP_HEADERS=""
    DUMP_TRACE=""
    # Заголовки снимаются всегда, а не только при отказе: задним числом
    # их не взять — второй запрос будет уже другим (задача 0147).
    heads=$(read_headers)
    # И трасса — тем же доводом: «ушла ли cookie» у второго запроса
    # спрашивать бессмысленно, он уйдёт с другой банкой (задача 0149).
    trace=$(read_trace)
    # Вход меняет токен: после него CSRF старой сессии уже не годится.
    CSRF=$(read_csrf)
    verdict_login "$(code_of "$answer")" "$(body_of "$answer")" "$heads" "$jarline" "$trace" || return 1
    # Своя ли это компания — спрашивается у ОТВЕТА, а не у секрета.
    [ -n "$TEST_TENANT" ] || return 0
    verdict_tenant "$(body_of "$answer")" "вход"
}

step_catalog() {
    local answer body
    answer=$(request GET '/api/parts/catalog?size=1')
    body=$(body_of "$answer")
    verdict_catalog "$(code_of "$answer")" "$body" || return 1
    # Позиция, на которой дальше проверяются поиск и карточка. В режиме
    # записи её подменит только что принятая — своя, а не чужая.
    PART_ID=$(val "$body" "d['rows'][0]['id']")
    PART_NUMBER=$(val "$body" "d['rows'][0]['number']")
}

step_warehouse() {
    local answer
    answer=$(request GET /api/organization/warehouses)
    WAREHOUSE_ID=$(val "$(body_of "$answer")" "d[0]['id']")
    if [ -z "$WAREHOUSE_ID" ]; then
        bad "складов у компании нет — принимать некуда" "приёмка"
        return 1
    fi
}

step_intake() {
    local answer body
    # Ключ запроса свой у каждого прогона: повтор тем же ключом вернул бы
    # позицию прошлой выкладки, и прогон проверял бы вчерашний день.
    answer=$(request POST /api/intake/receipts "{\"warehouseId\":$WAREHOUSE_ID,
        \"requestId\":\"smoke-$RUN_ID\",
        \"items\":[{\"rawName\":\"дымовой прогон выкладки\",\"quantity\":1,
                    \"price\":1000,\"costPrice\":100,\"condition\":\"USED\"}]}")
    body=$(body_of "$answer")
    verdict_intake "$(code_of "$answer")" "$body" || return 1
    PART_ID=$(val "$body" "d['parts'][0]['id']")
    PART_CODE=$(val "$body" "d['parts'][0]['publicCode']")
    # Номер позиции приёмка не отдаёт — его показывают витрина и выдача
    # продавцу. Спрашиваем тем же путём, которым его узнаёт человек.
    local found
    found=$(body_of "$(request GET "/api/parts/stock?q=$PART_CODE")")
    PART_NUMBER=$(val "$found" "[r['number'] for r in d['rows'] if r['partId'] == $PART_ID][0]")
    if [ -z "$PART_NUMBER" ]; then
        bad "принятая позиция $PART_CODE не находится по своему коду — продавать её нечем" "поиск по номеру"
        return 1
    fi
}

step_number_search() {
    if [ -z "$PART_NUMBER" ]; then
        note "на складе нет ни одной позиции — искать нечего (пустой стенд)"
        return 0
    fi
    local answer
    answer=$(request GET "/api/parts/stock?q=$PART_NUMBER")
    verdict_number_search "$PART_NUMBER" "$PART_ID" "$(code_of "$answer")" "$(body_of "$answer")"
}

step_card() {
    if [ -z "$PART_ID" ]; then
        note "на складе нет ни одной позиции — карточку открывать нечем (пустой стенд)"
        return 0
    fi
    local answer
    answer=$(request GET "/api/parts/$PART_ID/history")
    verdict_card "$(code_of "$answer")" "$(body_of "$answer")"
}

# Свободный остаток позиции по её номеру: 0, если строки нет вовсе
# (выданная деталь с полки уходит).
available_now() {
    local found
    found=$(body_of "$(request GET "/api/parts/stock?q=$PART_NUMBER")")
    val "$found" "([r['$1'] for r in d['rows'] if r['partId'] == $PART_ID] or [0])[0]" | sed 's/\.0*$//'
}

step_deal() {
    local answer body
    answer=$(request POST /api/deals "{\"items\":[{\"partId\":$PART_ID,\"quantity\":1,
        \"warehouseId\":$WAREHOUSE_ID}]}")
    body=$(body_of "$answer")
    DEAL_ID=$(val "$body" "d['id']")
    ITEM_ID=$(val "$body" "d['items'][0]['id']")
    DEAL_TOTAL=$(val "$body" "d['totalAmount']")
    verdict_reserved "$(code_of "$answer")" "$body" "$(available_now qtyAvailable)"
}

step_pay() {
    [ -n "$DEAL_ID" ] || return 1
    local answer code
    answer=$(request POST "/api/deals/$DEAL_ID/payments" "{\"amount\":$DEAL_TOTAL}")
    code=$(code_of "$answer")
    verdict_paid "$code" "$(body_of "$(request GET "/api/deals/$DEAL_ID")")"
}

step_issue() {
    [ -n "$DEAL_ID" ] || return 1
    local answer
    answer=$(request POST "/api/deals/$DEAL_ID/issue")
    verdict_issued "$(code_of "$answer")" "$(body_of "$answer")" "$(available_now qty)"
}

step_cleanup() {
    [ -n "$DEAL_ID" ] && [ -n "$ITEM_ID" ] || return 1
    # Возврат БЕЗ постановки на полку и деньгами из кассы: остаток стенда
    # и лицевой счёт клиента возвращаются к тому, что было до прогона.
    # Полностью стереть след нельзя и не нужно: документы и журналы
    # неизменяемы по построению — на них стоит вся доказательность склада.
    local answer
    answer=$(request POST "/api/deals/$DEAL_ID/returns" "{\"warehouseId\":$WAREHOUSE_ID,
        \"reason\":\"дымовой прогон выкладки — уборка за собой\",
        \"refundToAccount\":false,
        \"items\":[{\"dealItemId\":$ITEM_ID,\"quantity\":1,\"restocked\":false}]}")
    verdict_cleanup "$(code_of "$answer")" "$(body_of "$answer")" "$(available_now qty)"
}

step_logout() {
    request POST /api/auth/logout >/dev/null 2>&1
}

# С ГОТОВОЙ СЕССИЕЙ ответа входа у нас нет: вход случился в другом запуске,
# до заморозки (0142). «Куда попали» спрашиваем у «кто я» — это GET, внутри
# окна заморозки он законен, и отвечает та же MeView с companySchema.
# Без этого шага прогон на ПРОМ не писал бы никогда: настоящая выкладка идёт
# ровно этим путём.
step_whoami() {
    local answer code
    answer=$(request GET /api/auth/me)
    code=$(code_of "$answer")
    if [ "$code" != 200 ]; then
        bad "«кто я» отвечает ${code}, а не 200 — готовая сессия не годится" "компания"
        return 1
    fi
    verdict_tenant "$(body_of "$answer")" "«кто я»"
}

scenario() {
    # Вход — это ЗАПИСЬ: он заводит серверную сессию в public.spring_session
    # (0080). Внутри окна заморозки выкладки (0112) запись отбита, и вход
    # отвечает 503 — то есть пятая самопроверка не могла пройти там НИКОГДА,
    # ни на каком стенде и ни при каком пароле. Первая же выкладка кнопкой
    # на ПРОМ упала именно так (задача 0142). Поэтому вход умеет случиться
    # заранее, ДО заморозки: выкладка зовёт `--login-only`, банка cookie
    # остаётся в контейнере терминатора, и сюда приходит готовая сессия.
    if [ -n "${SMOKE_SESSION_READY:-}" ]; then
        # Токен CSRF живёт в той же банке. Без него первый же POST уйдёт без
        # заголовка и получит отказ — «готовая сессия» без токена хуже
        # отсутствующей, потому что выглядит рабочей.
        CSRF=$(read_csrf)
        if [ -z "$CSRF" ]; then
            red "Сессия объявлена готовой, а токена CSRF в банке нет: $JAR"
            FAILED="вход"
            return 1
        fi
        note "вход не повторяем: сессия получена до заморозки записи"
        # Куда привела ГОТОВАЯ сессия — тем же вопросом и по тому же правилу.
        if [ -n "$TEST_TENANT" ]; then
            step_whoami || return 1
        fi
    else
        step_login || return 1
    fi
    step_catalog
    if [ "$MODE" = write ]; then
        step_warehouse && step_intake
    fi
    step_number_search
    step_card
    if [ "$MODE" = write ]; then
        step_deal && step_pay && step_issue
        # Уборка идёт даже если продажа сломалась на середине: оставленная
        # на стенде дымовая сделка — это работа для человека.
        [ -n "$DEAL_ID" ] && step_cleanup
    else
        note "продажу не оформляем: на ПРОМ дымовая сделка была бы сделкой в учёте клиента"
    fi
    step_logout
    [ -z "$FAILED" ]
}

# Только вход, без сценария (0142). Выкладка зовёт его ДО заморозки записи:
# внутри окна вход отвечает 503, потому что заводит серверную сессию.
#
# Отдельной функцией, а не строками в хвосте, — чтобы её могла позвать
# самопроверка на подставных ответах. Путь, который нельзя прогнать, проверен
# не будет: разбор PR #256 нашёл, что `--login-only`, рапортующий успех
# без единого запроса, самопроверка пропускала молча.
login_only() {
    printf 'Дымовой прогон: вход заранее, %s (банка %s)\n' "$BASE" "$JAR"
    if step_login; then
        green "Вход выполнен до заморозки: сессия готова"
        return 0
    fi
    red "Вход до заморозки не прошёл: ${FAILED%, }"
    return 1
}

# ────────────────────────────── самопроверка ─────────────────────────────────
#
# Без ячейки и без docker. Проверяется три вещи, и третья — главная:
#   1. каждый вердикт краснеет на своём дефекте и называет свой шаг;
#   2. режим считается по стенду и по имени хоста, а ПРОМ не пишет;
#   3. В РЕЖИМЕ ЧТЕНИЯ НИ ОДНОГО ПИШУЩЕГО ЗАПРОСА НЕ УХОДИТ ВОВСЕ —
#      перебором отправленного, а не чтением кода.
selftest() {
    local broken=0
    expect() {  # имя, ожидаемый исход (ok|fail), шаг в списке упавших
        local name="$1" want="$2" mark="$3"
        shift 3
        FAILED=""
        # Через файл, а не $(...): подстановка команды — подоболочка,
        # и список упавших до нас бы не доехал. Самопроверка при этом молча
        # зеленела бы — ровно тот изъян, который она и ловит.
        local tmp="${TMPDIR:-/tmp}/smoke-selftest.$$"
        "$@" > "$tmp" 2>&1; local code=$?
        local out; out=$(cat "$tmp"); rm -f "$tmp"
        if [ "$want" = ok ] && [ $code != 0 ]; then
            red "  ✗ $name: ожидалось «проходит», а проверка покраснела: $out"
            broken=$((broken + 1)); return
        fi
        if [ "$want" = fail ]; then
            if [ $code = 0 ]; then
                red "  ✗ $name: ожидалось «краснеет», а проверка промолчала: $out"
                broken=$((broken + 1)); return
            fi
            case "$FAILED" in
                *"$mark"*) ;;
                *) red "  ✗ $name: покраснела, но не назвала «${mark}» (назвала «${FAILED}»)"
                   broken=$((broken + 1)); return ;;
            esac
        fi
        printf '  ✓ %s\n' "$name"
    }

    same() {  # имя, получилось, ожидалось
        if [ "$2" = "$3" ]; then printf '  ✓ %s\n' "$1"
        else red "  ✗ $1: получилось «$2», ждали «$3»"; broken=$((broken + 1)); fi
    }

    # Что проверка СКАЗАЛА, а не только на чём покраснела. Без этого пробу
    # проходит «косметическая починка»: имя упавшего шага то же, а человеку
    # по-прежнему называют причину, которой не измеряли (задача 0147).
    says() {  # имя случая, обязательный кусок текста, команда...
        local name="$1" want="$2"
        shift 2
        FAILED=""
        local tmp="${TMPDIR:-/tmp}/smoke-selftest-says.$$"
        "$@" > "$tmp" 2>&1
        local out; out=$(cat "$tmp"); rm -f "$tmp"
        case "$out" in
            *"$want"*) printf '  ✓ %s\n' "$name" ;;
            *) red "  ✗ ${name}: нет слов «${want}» — сказано «$(printf '%s' "$out" | tr '\n' ' ')»"
               broken=$((broken + 1)) ;;
        esac
    }

    echo "Самопроверка ops/smoke-run.sh"

    # 1. Режим: стенд, имя хоста и явный флаг.
    same "режим: ИФТ пишет" "$(mode_of ift ift '')" "write"
    same "режим: ПСИ пишет" "$(mode_of psi psi '')" "write"
    same "режим: ПРОМ только читает" "$(mode_of prom prom '')" "read-only"
    same "режим: свой подъём пишет" "$(mode_of '' local '')" "write"
    same "режим: ХОСТ ПРОМА СИЛЬНЕЕ ПЕРЕМЕННОЙ" "$(mode_of ift prom '')" "read-only"
    # Приставку проверяем образцом, а не срезом: `cut -c` на macOS считает
    # символы, а на Linux байты, и «отказ:» превращается там в «отк» —
    # самопроверка краснела бы только на CI и только на кириллице.
    refuses() {  # имя случая, ответ mode_of
        case "$2" in
            "отказ:"*) printf '  ✓ %s\n' "$1" ;;
            *) red "  ✗ $1: ожидался отказ, получилось «${2}»"; broken=$((broken + 1)) ;;
        esac
    }
    refuses "режим: безымянный стенд — отказ" "$(mode_of '' '' '')"
    refuses "режим: --write на ПРОМ — отказ" "$(mode_of prom prom write)"
    refuses "режим: --write на хосте прома — отказ" "$(mode_of ift prom write)"
    same "режим: --read-only на ИФТ разрешён" "$(mode_of ift ift read-only)" "read-only"
    same "метка хоста: prom.example.ru" "$(host_label https://prom.example.ru/)" "prom"
    same "метка хоста: parts-prod.example.ru" "$(host_label https://parts-prod.example.ru/)" "prom"
    same "метка хоста: ift.example.ru" "$(host_label https://ift.example.ru/)" "ift"
    same "метка хоста: свой подъём" "$(host_label http://localhost:8080)" "local"

    # Тестовая компания (0144): на ПРОМ запись открывается только ей и только
    # после подтверждения входом. Чужой компании там по-прежнему нельзя
    # ничего, а метка хоста остаётся сильнее переменной для обеих.
    same "режим: ПРОМ + СВОЯ компания — запись после подтверждения" \
        "$(mode_of prom prom '' yes)" "write-if-confirmed"
    same "режим: ПРОМ + компания клиента — только чтение" \
        "$(mode_of prom prom '' '')" "read-only"
    same "режим: признак не передан — компания считается чужой" \
        "$(mode_of prom prom '')" "read-only"
    refuses "режим: --write на ПРОМ в компании клиента — отказ" "$(mode_of prom prom write '')"
    same "режим: --write на ПРОМ в своей компании — после подтверждения" \
        "$(mode_of prom prom write yes)" "write-if-confirmed"
    same "режим: ЗАБЫТЫЙ СТЕНД на хосте прома — чужой компании чтение" \
        "$(mode_of '' prom '' '')" "read-only"
    same "режим: забытый стенд на хосте прома — своей нужно подтверждение" \
        "$(mode_of '' prom '' yes)" "write-if-confirmed"
    same "режим: метка прома сильнее переменной и для своей компании" \
        "$(mode_of ift prom '' yes)" "write-if-confirmed"
    same "белый список: smoke — тестовая" "$(test_tenant_of smoke)" "t_1000002"
    same "белый список: yardt (клиент) — не тестовая" "$(test_tenant_of yardt)" ""

    # 2. Вердикты: годный ответ и сломанный. Сломанные — не выдуманные:
    #    это «200, а дела не сделано», то есть ровно то, чего не видят
    #    четыре инфраструктурные проверки.
    expect "вход: 200 с ролью проходит" ok "" \
        verdict_login 200 '{"login":"prodavec","displayName":"Продавец","role":"SELLER"}' '' ''
    expect "вход: 200 без роли краснеет" fail "вход" verdict_login 200 '{"ok":true}' '' ''

    # ОТКАЗ ВХОДА РАЗЛИЧАЕТСЯ ТОЛЬКО ЗАГОЛОВКАМИ ОТВЕТА (задача 0147).
    # Тела нет ни у одного из отказов, код у всех один; измеренная на живом
    # образе таблица — в комментарии к verdict_login выше.
    says_not() {  # имя случая, запрещённый кусок текста, команда...
        local name="$1" forbidden="$2"
        shift 2
        FAILED=""
        local tmp="${TMPDIR:-/tmp}/smoke-selftest-saysnot.$$"
        "$@" > "$tmp" 2>&1
        local out; out=$(cat "$tmp"); rm -f "$tmp"
        case "$out" in
            *"$forbidden"*) red "  ✗ ${name}: сказано «${forbidden}» там, где это НЕ измерено — «$(printf '%s' "$out" | tr '\n' ' ')»"
                            broken=$((broken + 1)) ;;
            *) printf '  ✓ %s\n' "$name" ;;
        esac
    }
    local heads_new='HTTP/1.1 401
Set-Cookie: XSRF-TOKEN=novyy; Path=/
Content-Length: 0'
    local heads_plain='HTTP/1.1 401
Content-Length: 0'
    local jar_plain='app-blue	FALSE	/	FALSE	0	XSRF-TOKEN	staryy'
    local jar_secure='app-blue	FALSE	/	TRUE	0	XSRF-TOKEN	staryy'
    expect "вход: 401 БЕЗ новой cookie — краснеет и названа учётная запись" fail "вход" \
        verdict_login 401 '' "$heads_plain" "$jar_plain"
    expect "вход: 401 С НОВОЙ cookie — краснеет и назван ТОКЕН, а не пароль" fail "токен CSRF" \
        verdict_login 401 '' "$heads_new" "$jar_plain"
    expect "вход: 401 БЕЗ свидетельств — краснеет" fail "вход" \
        verdict_login 401 '' '' ''
    # Имени упавшего шага мало: проверяем САМИ СЛОВА. Иначе пробу проходит
    # «косметическая починка» — та, что переписала текст, ничего не измерив.
    says "вход: без свидетельств сказано «причина не установлена»" \
        "ПРИЧИНА НЕ УСТАНОВЛЕНА" verdict_login 401 '' '' ''
    says_not "вход: без свидетельств про учётную запись НЕ сказано" \
        "SMOKE_PASSWORD" verdict_login 401 '' '' ''
    says "вход: с новой cookie названа непришедшая cookie" \
        "НЕ ПОЛУЧИЛ cookie CSRF" verdict_login 401 '' "$heads_new" "$jar_plain"
    says_not "вход: с новой cookie учётная запись НЕ обвиняется" \
        "SMOKE_PASSWORD" verdict_login 401 '' "$heads_new" "$jar_plain"
    says "вход: доехавшая cookie названа доехавшей" \
        "ДОЕХАЛА" verdict_login 401 '' "$heads_plain" "$jar_plain"
    # Банка с Secure-cookie при запросе по http: токен в ней ЕСТЬ и читается
    # awk'ом («токен получен»), а curl его не отправляет — то есть «получен»
    # и «доехал» расходятся. Это ровно тот случай, который сходится со всеми
    # четырьмя признаками замеров на ПРОМ, и назвать его надо отдельно.
    local real_base="$BASE"
    BASE=http://app-blue:8080
    says "вход: Secure-cookie в банке при http названа отдельной причиной" \
        "помечена Secure" verdict_login 401 '' "$heads_new" "$jar_secure"
    # И обратный край: по https Secure-cookie — обычное дело, приписки быть
    # не должно. Без этого случая «причина» печаталась бы всегда, то есть
    # снова называлась бы неизмеренной.
    BASE=https://parts.example.ru
    says_not "вход: по https про Secure не говорится" \
        "помечена Secure" verdict_login 401 '' "$heads_new" "$jar_secure"
    BASE="$real_base"

    # ─── УШЛА ЛИ COOKIE В ЗАПРОСЕ — отдельное свидетельство (задача 0149) ───
    #
    # Заголовки ответа говорят, что сделал СЕРВЕР; отправил ли что-нибудь
    # КЛИЕНТ, по ним не узнать вовсе — а пятая красная выкладка на ПРОМ
    # упёрлась ровно в этот вопрос. Видно это только в трассе запроса.
    local trace_with='> POST /api/auth/login HTTP/1.1
> Cookie: XSRF-TOKEN=staryy
> X-XSRF-TOKEN: staryy
< HTTP/1.1 401
< Set-Cookie: XSRF-TOKEN=novyy; Path=/'
    local trace_without='> POST /api/auth/login HTTP/1.1
> X-XSRF-TOKEN: staryy
< HTTP/1.1 401'
    local real_sent="${SENT_CSRF}"
    SENT_CSRF=staryy
    says "вход: cookie в запросе БЫЛА — так и сказано" \
        "curl её отправил" verdict_login 401 '' "$heads_new" "$jar_plain" "$trace_with"
    says "вход: заголовка Cookie в запросе НЕ БЫЛО — так и сказано" \
        "curl не отправил cookie из банки" verdict_login 401 '' "$heads_new" "$jar_plain" "$trace_without"
    says "вход: трассы нет — про отправку cookie сказано «не измерено»" \
        "НЕ ИЗМЕРЕНО" verdict_login 401 '' "$heads_new" "$jar_plain" ''
    # Обратный край: без трассы утверждать, что cookie ушла, нельзя —
    # иначе причина снова называлась бы неизмеренной.
    says_not "вход: без трассы не утверждается, что cookie ушла" \
        "curl её отправил" verdict_login 401 '' "$heads_new" "$jar_plain" ''
    # Отправленный токен против банки: оба значения сняты ДО запроса,
    # и сказать про них можно ровно то, что измерено.
    says "вход: отправленный токен и банка сошлись — сказано, что это он" \
        "тот самый, что лежал в банке" verdict_login 401 '' "$heads_new" "$jar_plain" "$trace_with"
    SENT_CSRF=drugoy
    says "вход: отправленный и лежавший в банке РАЗОШЛИСЬ — это названо" \
        "РАЗОШЛИСЬ" verdict_login 401 '' "$heads_new" "$jar_plain" "$trace_with"
    # А токен из ответа называется НОВЫМ. До 0149 ровно он и стоял в строке
    # «отправляли токен», из-за чего два значения в одной строке выглядели
    # доказательством того, что прогон шлёт не то.
    says "вход: токен из ответа назван новым, а не отправленным" \
        "НОВАЯ XSRF-TOKEN «novyy" verdict_login 401 '' "$heads_new" "$jar_plain" "$trace_with"
    SENT_CSRF="${real_sent}"

    # Токен CSRF (0146). Вход без токена и вход с неверным паролем отвечают
    # ОДИНАКОВО — 401 с пустым телом, — поэтому сказать, что именно случилось,
    # можно только спросив токен отдельно. Красная выкладка на ПРОМ
    # разбиралась по неверной версии ровно потому, что прогон называл пароль,
    # не проверив токен.
    expect "токен CSRF: получен — проходит" ok "" verdict_csrf 204 "токен"
    expect "токен CSRF: 204, А БАНКА ПУСТА — краснеет и назван токен" fail "токен CSRF" \
        verdict_csrf 204 ""
    expect "токен CSRF: csrf не ответил вовсе — краснеет" fail "токен CSRF" verdict_csrf 000 ""
    expect "токен CSRF: csrf отвечает 502 — краснеет" fail "токен CSRF" verdict_csrf 502 ""

    expect "витрина: страница проходит" ok "" \
        verdict_catalog 200 '{"total":2,"rows":[{"id":7,"number":347}]}'
    expect "витрина: 500 краснеет" fail "витрина" verdict_catalog 500 'Internal Server Error'
    expect "витрина: ПОЗИЦИИ ЕСТЬ, СТРОК НЕТ — краснеет" fail "витрина" \
        verdict_catalog 200 '{"total":2,"rows":[]}'
    expect "витрина: пустой склад проходит" ok "" verdict_catalog 200 '{"total":0,"rows":[]}'

    expect "поиск по номеру: своя позиция проходит" ok "" \
        verdict_number_search 347 7 200 '{"rows":[{"partId":7,"number":347}]}'
    expect "поиск по номеру: не нашлось — краснеет" fail "поиск по номеру" \
        verdict_number_search 347 7 200 '{"rows":[]}'
    expect "поиск по номеру: нашлась чужая — краснеет" fail "поиск по номеру" \
        verdict_number_search 347 7 200 '{"rows":[{"partId":9,"number":347}]}'

    expect "карточка: открывается" ok "" verdict_card 200 '{"changes":[],"movements":[]}'
    expect "карточка: 500 краснеет" fail "карточка" verdict_card 500 'oops'
    expect "карточка: 200 не-JSON краснеет" fail "карточка" verdict_card 200 '<html>Ошибка</html>'

    expect "приёмка: позиция заведена" ok "" \
        verdict_intake 201 '{"documentId":1,"parts":[{"id":9,"publicCode":"AB12"}]}'
    expect "приёмка: 409 краснеет" fail "приёмка" verdict_intake 409 '{"message":"конфликт"}'
    expect "приёмка: 201 без позиции краснеет" fail "приёмка" verdict_intake 201 '{"parts":[]}'

    expect "сделка: деталь отложена" ok "" \
        verdict_reserved 201 '{"number":5,"items":[{"id":11,"status":"RESERVED"}]}' 0
    expect "сделка: 500 краснеет" fail "оформление сделки" verdict_reserved 500 'oops' 1
    expect "сделка: СТАТУС НЕ RESERVED — краснеет" fail "оформление сделки" \
        verdict_reserved 201 '{"number":5,"items":[{"id":11,"status":"DRAFT"}]}' 0
    expect "сделка: 201, А ОСТАТОК НЕ ОТЛОЖЕН — краснеет" fail "оформление сделки" \
        verdict_reserved 201 '{"number":5,"items":[{"id":11,"status":"RESERVED"}]}' 1

    expect "оплата: долг закрыт" ok "" \
        verdict_paid 201 '{"totalAmount":1000.0,"paidAmount":1000.00,"debt":0}'
    expect "оплата: 500 краснеет" fail "оплата" verdict_paid 500 'oops'
    expect "оплата: ПРИНЯТА, А ДОЛГ ОСТАЛСЯ — краснеет" fail "оплата" \
        verdict_paid 201 '{"totalAmount":1000,"paidAmount":0,"debt":1000}'

    expect "выдача: закрыла сделку и списала остаток" ok "" \
        verdict_issued 200 '{"status":"ISSUED"}' 0
    expect "выдача: 500 краснеет" fail "выдача" verdict_issued 500 'oops' 1
    expect "выдача: СТАТУС НЕ ИЗМЕНИЛСЯ — краснеет" fail "выдача" \
        verdict_issued 200 '{"status":"RESERVED"}' 0
    expect "выдача: 200, А ОСТАТОК НЕ СПИСАН — краснеет" fail "выдача" \
        verdict_issued 200 '{"status":"ISSUED"}' 1

    expect "уборка: за собой убрано" ok "" verdict_cleanup 201 '{"status":"DONE"}' 0
    expect "уборка: отказ краснеет" fail "уборка" verdict_cleanup 409 '{"message":"нельзя"}' 0
    expect "уборка: ДЕТАЛЬ ОСТАЛАСЬ НА ПОЛКЕ — краснеет" fail "уборка" \
        verdict_cleanup 201 '{"status":"DONE"}' 1

    # 3. Сценарий целиком на подставных ответах — и перебор отправленного.
    #    Тело check_* можно было бы заменить на `return 0`, и вердикты выше
    #    остались бы зелёными: подсовывая ответ прямо в verdict_*, мы минуем
    #    то, что этот ответ добывает.
    local real_request; real_request=$(declare -f request)
    STUB_LOG="${TMPDIR:-/tmp}/smoke-selftest-log.$$"
    request() {
        printf '%s %s\n' "$1" "${2%%\?*}" >> "$STUB_LOG"
        stub_answer "$1" "$2"
    }
    read_csrf() { echo "токен"; }
    # Свидетельства входа тоже подменяются: без этого сценарий самопроверки
    # полез бы за ними в контейнер терминатора, то есть в docker.
    read_headers() { printf ''; }
    read_jar_line() { printf ''; }
    read_trace() { printf ''; }

    local writes
    for want_mode in read-only write; do
        : > "$STUB_LOG"
        FAILED=""; MODE="$want_mode"; PART_ID=""; PART_NUMBER=""; DEAL_ID=""; ITEM_ID=""
        STUB_BREAK="" scenario > "$STUB_LOG.out" 2>&1
        [ -z "$FAILED" ] || {
            red "  ✗ сценарий ($want_mode) покраснел на исправных ответах: ${FAILED}"
            red "    $(tr '\n' ' ' < "$STUB_LOG.out" | cut -c1-200)"
            broken=$((broken + 1)); }
        # Пишущим считается всё, кроме GET и входа-выхода: вход оставляет
        # запись в журнале входов, и это ровно то, что о прогоне должно
        # быть видно. Сделок, платежей и позиций он на ПРОМ не создаёт.
        writes=$(grep -v '^GET ' "$STUB_LOG" | grep -v '^POST /api/auth/' | sort -u)
        if [ "$want_mode" = read-only ]; then
            if [ -n "$writes" ]; then
                red "  ✗ НА ПРОМ УШЛА ЗАПИСЬ: $(printf '%s' "$writes" | tr '\n' ' ')"
                broken=$((broken + 1))
            else
                printf '  ✓ режим чтения: пишущих запросов не ушло ни одного\n'
            fi
        else
            case "$writes" in
                *"POST /api/deals"*) printf '  ✓ режим записи: сделка всё-таки оформляется (проверка не пустая)\n' ;;
                *) red "  ✗ режим записи не оформил сделки — перебор запросов ничего не доказывает"
                   broken=$((broken + 1)) ;;
            esac
        fi
    done

    # Готовая сессия (0142): выкладка входит ДО заморозки и передаёт банку,
    # поэтому внутри окна вход повторяться не должен вовсе. Проверяется
    # перебором отправленного — обеими сторонами, иначе проба не утверждает
    # ничего: без второй половины её прошёл бы и сценарий, разучившийся
    # входить совсем.
    : > "$STUB_LOG"
    FAILED=""; MODE=read-only; PART_ID=""; PART_NUMBER=""; DEAL_ID=""; ITEM_ID=""
    SMOKE_SESSION_READY=yes STUB_BREAK="" scenario >/dev/null 2>&1
    if grep -q '^POST /api/auth/login' "$STUB_LOG"; then
        red "  ✗ с готовой сессией прогон ВСЁ РАВНО входит — внутри заморозки это 503"
        broken=$((broken + 1))
    else
        printf '  ✓ готовая сессия: повторного входа не уходит\n'
    fi
    [ -z "$FAILED" ] || {
        red "  ✗ с готовой сессией сценарий покраснел на исправных ответах: ${FAILED}"
        broken=$((broken + 1)); }

    : > "$STUB_LOG"
    FAILED=""; MODE=read-only; PART_ID=""; PART_NUMBER=""; DEAL_ID=""; ITEM_ID=""
    STUB_BREAK="" scenario >/dev/null 2>&1
    if grep -q '^POST /api/auth/login' "$STUB_LOG"; then
        printf '  ✓ без готовой сессии вход по-прежнему уходит (проверка не пустая)\n'
    else
        red "  ✗ без готовой сессии вход не ушёл — прогон разучился входить сам"
        broken=$((broken + 1))
    fi

    # Режим «только вход» (0142): он обязан ДЕЙСТВИТЕЛЬНО входить. Разбор
    # PR #256 нашёл, что рапорт об успехе без единого запроса проходил молча —
    # а это дефект 0142 целиком: выкладка считает сессию готовой, внутри окна
    # проверки идут без неё и краснеют на 503.
    : > "$STUB_LOG"
    FAILED=""; MODE=read-only
    login_only >/dev/null 2>&1
    if grep -q '^POST /api/auth/login' "$STUB_LOG"; then
        printf '  ✓ --login-only действительно входит\n'
    else
        red "  ✗ --login-only отрапортовал успех, не входя: выкладка сочтёт сессию готовой"
        broken=$((broken + 1))
    fi

    # Пустой токен при «готовой сессии». Ветка отказа не исполнялась ни разу:
    # заглушка read_csrf выше всегда отдаёт токен, поэтому подменяем её здесь
    # пустым ответом — иначе проверка утверждала бы, что путь безопасен,
    # ни разу по нему не пройдя.
    : > "$STUB_LOG"
    FAILED=""; MODE=read-only; PART_ID=""; PART_NUMBER=""; DEAL_ID=""; ITEM_ID=""
    read_csrf() { echo ""; }
    SMOKE_SESSION_READY=yes scenario >/dev/null 2>&1
    case "$FAILED" in
        *вход*) printf '  ✓ готовая сессия без токена CSRF — отказ, а не тихий проход\n' ;;
        *) red "  ✗ пустой токен при готовой сессии прошёл молча: первый же POST уйдёт без заголовка"
           broken=$((broken + 1)) ;;
    esac
    read_csrf() { echo "токен"; }

    # И ТО ЖЕ САМОЕ НА СВЕЖЕМ ВХОДЕ (задача 0146) — через обвязку, а не
    # вызовом вердикта: проба, зовущая функцию, не проверяет того, что делает
    # сам шаг. Банка пуста — так ведёт себя curl, получив по http cookie
    # с флагом Secure (проверено живым прогоном: на не-localhost хосте банка
    # остаётся пустой, и вход уходит без заголовка).
    : > "$STUB_LOG"
    FAILED=""; MODE=read-only; PART_ID=""; PART_NUMBER=""; DEAL_ID=""; ITEM_ID=""
    read_csrf() { echo ""; }
    step_login >/dev/null 2>&1
    case "$FAILED" in
        *"токен CSRF"*) printf '  ✓ свежий вход без токена: назван ТОКЕН, а не учётная запись\n' ;;
        *) red "  ✗ свежий вход без токена: прогон назвал «${FAILED:-ничего — шаг прошёл молча}» — именно так красная выкладка на ПРОМ разбиралась по неверной версии"
           broken=$((broken + 1)) ;;
    esac
    # Вторая половина, без которой первая ничего не стоит: без токена вход
    # отправлять НЕЛЬЗЯ ВОВСЕ. Иначе пробу прошла бы «починка», переписавшая
    # одни слова: запрос ушёл бы, получил 401 и снова был бы неотличим
    # от неверного пароля.
    if grep -q '^POST /api/auth/login' "$STUB_LOG"; then
        red "  ✗ без токена CSRF прогон ВСЁ РАВНО шлёт вход — ответ 401 неотличим от неверного пароля"
        broken=$((broken + 1))
    else
        printf '  ✓ без токена CSRF вход не отправляется вовсе\n'
    fi
    read_csrf() { echo "токен"; }

    # И обвязка шагов: подделанный ответ обязан доехать до вердикта через
    # тот же путь, которым идёт живой прогон.
    for break_at in deal issue; do
        : > "$STUB_LOG"
        FAILED=""; MODE=write; PART_ID=""; PART_NUMBER=""; DEAL_ID=""; ITEM_ID=""
        STUB_BREAK="$break_at" scenario >/dev/null 2>&1
        local mark="оформление сделки"; [ "$break_at" = issue ] && mark="выдача"
        case "$FAILED" in
            *"$mark"*) printf '  ✓ обвязка: молча сломанный шаг «%s» краснеет и назван\n' "$mark" ;;
            *) red "  ✗ обвязка: сломанный «${break_at}» не назван (назвала «${FAILED}»)"
               broken=$((broken + 1)) ;;
        esac
    done
    # ─── ПРОМ и своя тестовая компания (0144) ───────────────────────────────
    #
    # Проверяется ПЕРЕБОРОМ ОТПРАВЛЕННОГО и тем же путём, которым идёт живой
    # прогон: режим считает decide_mode, а не проба. Каждый случай — целый
    # сценарий на подставных ответах, а не вызов mode_of: выше уже видно,
    # что «режим посчитан верно» и «запись не ушла» — разные утверждения.
    prom_case() {  # имя, компания, стенд, адрес, флаг, схема входа, готовая сессия, ожидание
        local name="$1" company="$2" stand="$3" base="$4" want="$5"
        local schema="$6" ready="$7" expect_what="$8"
        : > "$STUB_LOG"
        FAILED=""; PART_ID=""; PART_NUMBER=""; DEAL_ID=""; ITEM_ID=""
        SMOKE_COMPANY="$company"
        decide_mode "$stand" "$base" "$want"
        case "$MODE" in
            "отказ:"*)
                # Отказ до первого запроса — законный способ не написать
                # ничего, но только там, где мы его и ждём.
                if [ "$expect_what" = refuse ]; then printf '  ✓ %s\n' "$name"
                else red "  ✗ ${name}: прогон отказался нацеливаться — «${MODE}»"
                     broken=$((broken + 1)); fi
                return ;;
        esac
        STUB_SCHEMA="$schema" SMOKE_SESSION_READY="$ready" STUB_BREAK="" \
            scenario > "$STUB_LOG.out" 2>&1
        local writes
        writes=$(grep -v '^GET ' "$STUB_LOG" | grep -v '^POST /api/auth/' | sort -u)
        case "$expect_what" in
            write)
                if [ -n "$FAILED" ]; then
                    red "  ✗ ${name}: сценарий покраснел на исправных ответах — «${FAILED}»"
                    broken=$((broken + 1)); return
                fi
                case "$writes" in
                    *"POST /api/deals"*) printf '  ✓ %s\n' "$name" ;;
                    *) red "  ✗ ${name}: сделка НЕ оформлена — проверка пуста и ничего не утверждает"
                       broken=$((broken + 1)) ;;
                esac ;;
            read)
                if [ -n "$writes" ]; then
                    red "  ✗ ${name}: НА ПРОМ УШЛА ЗАПИСЬ: $(printf '%s' "$writes" | tr '\n' ' ')"
                    broken=$((broken + 1))
                elif [ -n "$FAILED" ]; then
                    # Иначе «записи нет» выполнялось бы и сценарием, упавшим
                    # на первом шаге, — то есть проба ничего не значила бы.
                    red "  ✗ ${name}: записи нет, но сценарий покраснел — «${FAILED}»"
                    broken=$((broken + 1))
                else printf '  ✓ %s\n' "$name"; fi ;;
            refuse)
                if [ -n "$writes" ]; then
                    red "  ✗ ${name}: НА ПРОМ УШЛА ЗАПИСЬ: $(printf '%s' "$writes" | tr '\n' ' ')"
                    broken=$((broken + 1))
                elif [ -z "$FAILED" ]; then
                    red "  ✗ ${name}: записи нет, но и отказа нет — прогон промолчал о чужой компании"
                    broken=$((broken + 1))
                else printf '  ✓ %s\n' "$name"; fi ;;
        esac
    }

    local prom_url=https://prom.example.ru/
    prom_case "ПРОМ + СВОЯ компания: сделка ОФОРМЛЯЕТСЯ" \
        smoke prom "$prom_url" '' t_1000002 '' write
    prom_case "ПРОМ + своя компания, ГОТОВАЯ СЕССИЯ (путь выкладки): сделка оформляется" \
        smoke prom "$prom_url" '' t_1000002 yes write
    prom_case "ПРОМ + компания клиента: пишущих не ушло ни одного" \
        yardt prom "$prom_url" '' t_1000001 '' read
    prom_case "ПРОМ + компания клиента и явный --write: отказ до первого запроса" \
        yardt prom "$prom_url" write t_1000001 '' refuse
    prom_case "ПРОМ: в секрете своя, а вход привёл в ЧУЖУЮ — отказ, записи нет" \
        smoke prom "$prom_url" '' t_1000001 '' refuse
    prom_case "ПРОМ: готовая сессия привела в ЧУЖУЮ — отказ, записи нет" \
        smoke prom "$prom_url" '' t_1000001 yes refuse
    prom_case "ПРОМ: забытый DEPLOY_STAND, компания клиента — только чтение" \
        yardt '' "$prom_url" '' t_1000001 '' read
    prom_case "ПРОМ: забытый DEPLOY_STAND, своя компания — пишет после подтверждения" \
        smoke '' "$prom_url" '' t_1000002 '' write
    prom_case "ИФТ: компания не из списка — пишет как раньше" \
        etalon ift https://ift.example.ru/ '' t_000042 '' write
    SMOKE_COMPANY=""; TEST_TENANT=""; CONFIRM_FOR_WRITE=""

    # ─── .env ячейки не подменяет белый список (разбор PR #262) ─────────────
    #
    # Ни один случай выше .env не трогает вовсе: они зовут функции, а .env
    # читает ПУТЬ ЗАПУСКА — `set -a; . "./$ENV_FILE"` идёт ПОСЛЕ объявления
    # списка. То есть для самопроверки дыра была невидима, а строка
    # `TEST_TENANTS=…` в .env молча открывала запись в кабинет клиента:
    # отказ «это ПРОМ» исчезал, а сверка «куда попали» проходила честно,
    # потому что вход в компанию клиента законно отдаёт t_1000001.
    #
    # Поэтому здесь запускается САМ скрипт, целиком, с подложенным .env.
    # В сеть он при этом не ходит: `--mode` только печатает решение.
    local env_file=".smoke-selftest-env.$$"
    local mode_out mode_code
    printf 'APP_DOMAIN=prom.example.ru\n' > "$env_file"
    mode_out=$(ENV_FILE="$env_file" DEPLOY_STAND=prom SMOKE_URL=https://prom.example.ru/ \
        SMOKE_COMPANY=smoke SMOKE_LOGIN=x SMOKE_PASSWORD=y bash "$0" --mode 2>&1)
    mode_code=$?
    case "$mode_out" in
        *"smoke:t_1000002"*)
            if [ "$mode_code" = 0 ]; then
                printf '  ✓ чистый .env: путь запуска доходит до режима, список свой\n'
            else
                red "  ✗ чистый .env: путь запуска не отработал (код ${mode_code})"
                broken=$((broken + 1))
            fi ;;
        *) red "  ✗ чистый .env: --mode не назвал своего списка: $(printf '%s' "$mode_out" | tr '\n' ' ')"
           broken=$((broken + 1)) ;;
    esac

    printf 'APP_DOMAIN=prom.example.ru\nTEST_TENANTS="yardt:t_1000001"\n' > "$env_file"
    mode_out=$(ENV_FILE="$env_file" DEPLOY_STAND=prom SMOKE_URL=https://prom.example.ru/ \
        SMOKE_COMPANY=yardt SMOKE_LOGIN=x SMOKE_PASSWORD=y bash "$0" --mode 2>&1)
    mode_code=$?
    if [ "$mode_code" = 0 ]; then
        red "  ✗ СТРОКА TEST_TENANTS В .env ПРОШЛА МОЛЧА — так открывают запись в кабинет клиента: $(printf '%s' "$mode_out" | tr '\n' ' ')"
        broken=$((broken + 1))
    else
        case "$mode_out" in
            *TEST_TENANTS*) printf '  ✓ .env со строкой TEST_TENANTS — прогон падает словами, а не пишет на ПРОМ\n' ;;
            *) red "  ✗ .env со строкой TEST_TENANTS: упал, но причину не назвал: $(printf '%s' "$mode_out" | tr '\n' ' ')"
               broken=$((broken + 1)) ;;
        esac
    fi
    # ─── прямо в сборку: адрес запроса сменился, СТЕНД — нет (0145) ─────────
    #
    # В окне выкладки прогон ходит не через терминатор — там отвечает ещё
    # СТАРАЯ сборка, — а прямо в выкладываемую: SMOKE_BUILD=app-green.
    # Метка стенда при этом обязана считаться по публичному адресу: в имени
    # «app-green» меток prom/ift нет вовсе, host_label вернул бы пусто,
    # и решение осталось бы за переменной DEPLOY_STAND — то есть забытая
    # или неверная переменная снова открывала бы запись в кабинете живого
    # клиента. Случай подобран так, что два ответа РАЗНЫЕ: стенд назван
    # «ift» (как при забытой переменной), а публичный адрес — промовский.
    printf 'APP_DOMAIN=prom.example.ru\n' > "$env_file"
    build_mode() {  # компания, DEPLOY_STAND → вывод --mode
        ENV_FILE="$env_file" DEPLOY_STAND="$2" SMOKE_URL=https://prom.example.ru/ \
            SMOKE_BUILD=app-green SMOKE_COMPANY="$1" SMOKE_LOGIN=x SMOKE_PASSWORD=y \
            bash "$0" --mode 2>&1
    }
    mode_out=$(build_mode yardt ift)
    case "$mode_out" in
        *"режим: read-only"*)
            printf '  ✓ прямо в сборку: ПРОМ узнан по публичному адресу, а не по имени сборки\n' ;;
        *) red "  ✗ ПРЯМО В СБОРКУ: ПРОМ НЕ УЗНАН — режим посчитан по «app-green», и DEPLOY_STAND=ift открыл запись в кабинете клиента: $(printf '%s' "$mode_out" | tr '\n' ' ')"
           broken=$((broken + 1)) ;;
    esac
    # Обе половины сразу, иначе проба выше проходит и у «починки», которая
    # SMOKE_BUILD просто не выполняет: не ходя в сборку, прогон в окне
    # проверял бы старую версию — молча и с зелёным исходом.
    case "$mode_out" in
        *"нацелен: http://app-green:8080"*)
            case "$mode_out" in
                *"стенд определяется по адресу: https://prom.example.ru"*)
                    printf '  ✓ прямо в сборку: запрос уходит в сборку, стенд считается по стенду\n' ;;
                *) red "  ✗ прямо в сборку: стенд считается не по публичному адресу: $(printf '%s' "$mode_out" | tr '\n' ' ')"
                   broken=$((broken + 1)) ;;
            esac ;;
        *) red "  ✗ прямо в сборку: запрос НЕ нацелен на сборку — в окне выкладки проверялась бы старая версия: $(printf '%s' "$mode_out" | tr '\n' ' ')"
           broken=$((broken + 1)) ;;
    esac
    mode_out=$(build_mode smoke prom)
    case "$mode_out" in
        *"запись откроется после подтверждения входом: да"*)
            printf '  ✓ прямо в сборку: своя компания по-прежнему пишет после подтверждения\n' ;;
        *) red "  ✗ прямо в сборку: своя компания потеряла право писать — продажу в окне выкладки не проверит никто: $(printf '%s' "$mode_out" | tr '\n' ' ')"
           broken=$((broken + 1)) ;;
    esac
    # Без публичного адреса стенд определять не по чему, и молчать об этом
    # нельзя: «не знаю, ПРОМ ли это» обязано быть отказом, а не записью.
    printf '\n' > "$env_file"
    mode_out=$(ENV_FILE="$env_file" DEPLOY_STAND=prom SMOKE_BUILD=app-green \
        SMOKE_COMPANY=smoke SMOKE_LOGIN=x SMOKE_PASSWORD=y bash "$0" --mode 2>&1)
    mode_code=$?
    if [ "$mode_code" = 0 ]; then
        red "  ✗ прямо в сборку без публичного адреса стенда прошло молча: стенд определять не по чему"
        broken=$((broken + 1))
    else
        printf '  ✓ прямо в сборку без адреса стенда — отказ словами\n'
    fi
    rm -f "$env_file"

    # ─── обвязка входа: свидетельства обязаны ДОЕХАТЬ до вердикта (0147) ────
    #
    # Пробы выше зовут verdict_login напрямую — то есть проверяют вердикт,
    # а не шаг. Шаг, разучившийся снимать заголовки ответа, оставил бы их
    # зелёными и на живой выкладке снова обвинил бы учётную запись: ровно
    # это и случилось на ПРОМ после 0146. Поэтому здесь подменяются ОТВЕТЫ,
    # а step_login проходится целиком.
    : > "$STUB_LOG"
    FAILED=""; MODE=read-only
    request() {
        printf '%s %s\n' "$1" "${2%%\?*}" >> "$STUB_LOG"
        case "$1 $2" in
            "GET /api/auth/csrf") printf '\n204' ;;
            *) printf '\n401' ;;
        esac
    }
    read_headers() { printf 'HTTP/1.1 401\nSet-Cookie: XSRF-TOKEN=novyy; Path=/\nContent-Length: 0\n'; }
    read_jar_line() { printf 'app-blue\tFALSE\t/\tFALSE\t0\tXSRF-TOKEN\tstaryy'; }
    step_login >/dev/null 2>&1
    case "$FAILED" in
        *"токен CSRF"*) printf '  ✓ обвязка входа: заголовки ответа доезжают до вердикта\n' ;;
        *) red "  ✗ обвязка входа: 401 с новой cookie назван «${FAILED:-ничем}» — значит шаг не снимает заголовков, и на выкладке снова обвинят пароль"
           broken=$((broken + 1)) ;;
    esac
    # Обратная половина: та же обвязка при ДОЕХАВШЕЙ cookie обязана называть
    # учётную запись. Без неё пробу прошла бы «починка», отвечающая одним
    # и тем же словом на любой отказ.
    : > "$STUB_LOG"
    FAILED=""; MODE=read-only
    read_headers() { printf 'HTTP/1.1 401\nContent-Length: 0\n'; }
    step_login >/dev/null 2>&1
    case "$FAILED" in
        *вход*) printf '  ✓ обвязка входа: без новой cookie названа учётная запись\n' ;;
        *) red "  ✗ обвязка входа: 401 без новой cookie назван «${FAILED:-ничем}»"
           broken=$((broken + 1)) ;;
    esac

    # ─── ОТПРАВЛЕННЫМ НАЗЫВАЕТСЯ ТО, ЧТО УШЛО (задача 0149) ─────────────────
    #
    # Пятая красная выкладка на ПРОМ показала в одной строке два разных
    # токена, и отсюда родилась версия «прогон шлёт не то, что лежит
    # в банке». Живой прогон того же образа показал обратное: банку
    # переписывает ОТВЕТ (`curl -c`), и CSRF, перечитанный после запроса, —
    # это НОВЫЙ токен сервера. Проба возвращает ровно этот дефект: банка
    # до запроса и после него разные, и в строке отказа обязана стоять
    # первая. Через обвязку, а не вызовом вердикта: подменой аргументов
    # проверялся бы вердикт, а ошибка была в шаге.
    : > "$STUB_LOG"
    FAILED=""; MODE=read-only
    # Банка «переписывается» ответом входа: до запроса она отдаёт один токен,
    # после — другой. Считается это ПО ФАЙЛУ, а не счётчиком в переменной:
    # `CSRF=$(read_csrf)` — подстановка команды, то есть подоболочка, и
    # счётчик из неё не доезжает. Со счётчиком обе стороны отдавали один
    # токен, и проба ЗЕЛЕНЕЛА НА ДЕФЕКТЕ — поймано возвратом подделки.
    read_csrf() {
        if grep -q '^POST /api/auth/login' "$STUB_LOG" 2>/dev/null
        then echo "novyy-token"
        else echo "staryy-token"; fi
    }
    read_headers() { printf 'HTTP/1.1 401\nSet-Cookie: XSRF-TOKEN=novyy-token; Path=/\nContent-Length: 0\n'; }
    read_jar_line() { printf 'app-blue\tFALSE\t/\tFALSE\t0\tXSRF-TOKEN\tstaryy-token'; }
    read_trace() { printf '> POST /api/auth/login HTTP/1.1\n> Cookie: XSRF-TOKEN=staryy-token\n> X-XSRF-TOKEN: staryy-token\n'; }
    local login_out
    login_out=$(step_login 2>&1)
    case "$login_out" in
        *"Отправляли токен «staryy-t"*)
            printf '  ✓ отправленным назван ТОТ ТОКЕН, ЧТО УШЁЛ\n' ;;
        *) red "  ✗ отправленным назван не тот токен, что ушёл: «$(printf '%s' "$login_out" | tr '\n' ' ')»"
           broken=$((broken + 1)) ;;
    esac
    case "$login_out" in
        *"Отправляли токен «novyy-to"*)
            red "  ✗ ОТПРАВЛЕННЫМ НАЗВАН ТОКЕН ИЗ ОТВЕТА — банку переписал curl -c, и строка отказа врёт о том, что ушло: именно так разбиралась пятая красная выкладка на ПРОМ"
            broken=$((broken + 1)) ;;
        *) printf '  ✓ токен из ответа отправленным не называется\n' ;;
    esac
    case "$login_out" in
        *"curl её отправил"*)
            printf '  ✓ обвязка входа: трасса запроса доезжает до вердикта\n' ;;
        *) red "  ✗ обвязка входа: про отправленную cookie не сказано ничего — трасса до вердикта не доехала, и «ушла ли она» снова никем не измерено"
           broken=$((broken + 1)) ;;
    esac

    # И сами флаги: свидетельства берутся только потому, что их ПРОСИТ запрос.
    # Здесь подменяется отправка, а не ответы, и смотрится argv — иначе
    # «починка», переставшая просить -D и --stderr, прошла бы молча:
    # заглушки выше отдают свидетельства сами.
    local real_run_there argv_log login_argv
    real_run_there=$(declare -f run_there)
    argv_log="${TMPDIR:-/tmp}/smoke-selftest-argv.$$"
    : > "$argv_log"
    run_there() {
        printf '%s\n' "$*" >> "$argv_log"
        case "$*" in
            *"/api/auth/csrf"*) printf '\n204' ;;
            *) printf '\n401' ;;
        esac
    }
    eval "$real_request"
    FAILED=""; MODE=read-only
    step_login >/dev/null 2>&1
    login_argv=$(grep '/api/auth/login' "$argv_log" | tail -n 1)
    case "$login_argv" in
        *"-D "*) printf '  ✓ запрос входа просит заголовки ответа (-D)\n' ;;
        *) red "  ✗ запрос входа не просит заголовков ответа: вердикт останется без свидетельств и снова обвинит пароль (0147)"
           broken=$((broken + 1)) ;;
    esac
    case "$login_argv" in
        *"--stderr "*) printf '  ✓ запрос входа просит трассу (--stderr): «ушла ли cookie» измеряется\n' ;;
        *) red "  ✗ запрос входа не просит трассы — «ушла ли cookie» снова не измеряет никто (0149)"
           broken=$((broken + 1)) ;;
    esac
    rm -f "$argv_log"
    eval "$real_run_there"

    rm -f "$STUB_LOG" "$STUB_LOG.out"
    eval "$real_request"

    if [ "$broken" != 0 ]; then
        red "Самопроверка не прошла: $broken"
        return 1
    fi
    green "Самопроверка пройдена"
    return 0
}

# Подставные ответы ячейки. Состояние берётся из перебора уже отправленного:
# после оформления сделки свободный остаток ноль, после выдачи полка пуста.
# STUB_BREAK подделывает МОЛЧА сломанный шаг — тот, что отвечает успехом
# и не делает дела.
stub_answer() {
    local method="$1" path="$2"
    case "$method $path" in
        "GET /api/auth/csrf") printf '\n204' ;;
        # Схема в ответе входа — то, «куда попали». Подставная по умолчанию
        # своя; случай «секрет называл свою, а привело в чужую» подменяет
        # её через STUB_SCHEMA.
        "POST /api/auth/login") printf '{"role":"SELLER","displayName":"Продавец","companySchema":"%s"}\n200' "${STUB_SCHEMA:-t_1000002}" ;;
        "GET /api/auth/me") printf '{"role":"SELLER","displayName":"Продавец","companySchema":"%s"}\n200' "${STUB_SCHEMA:-t_1000002}" ;;
        "POST /api/auth/logout") printf '\n204' ;;
        "GET /api/organization/warehouses") printf '[{"id":1,"name":"Основной"}]\n200' ;;
        # Строка витрины — та же позиция, что отдаёт поиск ниже: в режиме
        # чтения прогон берёт её с витрины и ищет по её же номеру.
        "GET /api/parts/catalog"*) printf '{"total":1,"rows":[{"id":9,"number":348}]}\n200' ;;
        "POST /api/intake/receipts") printf '{"parts":[{"id":9,"publicCode":"AB12"}]}\n201' ;;
        "GET /api/parts/stock"*)
            local qty=1 free=1
            grep -q '^POST /api/deals$' "$STUB_LOG" && free=0
            [ "${STUB_BREAK:-}" = deal ] && free=1
            if grep -q '/issue$' "$STUB_LOG"; then
                qty=0; free=0
                [ "${STUB_BREAK:-}" = issue ] && qty=1
            fi
            printf '{"rows":[{"partId":9,"number":348,"publicCode":"AB12","qty":%s,"qtyAvailable":%s}],"total":1}\n200' "$qty" "$free" ;;
        "GET /api/parts/"*"/history") printf '{"changes":[],"movements":[]}\n200' ;;
        "POST /api/deals") printf '{"id":5,"number":5,"totalAmount":1000,"items":[{"id":11,"status":"RESERVED"}]}\n201' ;;
        "POST /api/deals/5/payments") printf '{"id":3,"amount":1000}\n201' ;;
        "GET /api/deals/5") printf '{"id":5,"totalAmount":1000,"paidAmount":1000,"debt":0}\n200' ;;
        "POST /api/deals/5/issue")
            if [ "${STUB_BREAK:-}" = issue ]; then printf '{"id":5,"status":"ISSUED"}\n200'
            else printf '{"id":5,"status":"ISSUED"}\n200'; fi ;;
        "POST /api/deals/5/returns") printf '{"id":2,"number":2,"status":"DONE"}\n201' ;;
        *) printf '{"message":"подставного ответа на %s %s нет"}\n404' "$method" "$path" ;;
    esac
}

# ─────────────────────────────── запуск ──────────────────────────────────────
WANT=""
case "${1:-}" in
    --selftest) selftest; exit $? ;;
    --read-only) WANT=read-only ;;
    --write) WANT=write ;;
    # Только вход, без сценария. Зовёт выкладка ДО заморозки записи: внутри
    # окна вход отвечает 503, потому что заводит серверную сессию (0142).
    # Режим чтения намеренно: сам по себе вход оставляет запись только
    # в журнале входов, и это ровно то, что о прогоне должно быть видно.
    --login-only) WANT=read-only; LOGIN_ONLY=yes ;;
    # Куда нацелен, в каком режиме и с каким списком тестовых компаний —
    # без единого запроса. Спрашивают этим ПЕРЕД тем, как нажать кнопку.
    --mode) WANT=""; PRINT_MODE=yes ;;
    -h|--help) sed -n '2,72p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    "") ;;
    *) red "Непонятный аргумент: $1"; exit 2 ;;
esac

# Окружение ячейки — оттуда APP_DOMAIN. Нет файла — значит прогон нацелили
# переменными снаружи, и это законно.
if [ -f "$ENV_FILE" ]; then
    set -a; . "./$ENV_FILE"; set +a
fi

# СПИСОК ТЕСТОВЫХ КОМПАНИЙ ЗАДАЁТСЯ КОДОМ И ТОЛЬКО ИМ. Строка
# `TEST_TENANTS=…` в .env (или экспортированная переменная) — это попытка
# открыть запись на ПРОМ мимо разбора, и отвечать на неё тишиной нельзя:
# молча она СРАБОТАЛА БЫ, потому что .env сорсится после объявления списка.
# Падаем словами, своего значения не отдав; readonly ниже закрывает и всё
# остальное, что могло бы его переписать.
if [ "${TEST_TENANTS:-}" != "$TEST_TENANTS_BUILTIN" ]; then
    red "Список тестовых компаний задан снаружи: TEST_TENANTS=«${TEST_TENANTS:-}». Он задаётся только кодом (ops/smoke-run.sh) — уберите строку TEST_TENANTS из ${ENV_FILE} и из окружения. Так открывают запись на ПРОМ мимо разбора."
    exit 1
fi
readonly TEST_TENANTS TEST_TENANTS_BUILTIN

# Куда ходить — и ОТДЕЛЬНО от этого: по какому адресу считается стенд.
#
# STAND_BASE — публичный адрес стенда. По нему host_label решает, ПРОМ это
# или нет, и на этом решении стоит вся защита 0085 и 0144: «метка хоста
# сильнее переменной». BASE — куда запрос уходит на самом деле. Обычно это
# одно и то же, и расходятся они ровно в одном случае — когда прогон нацелен
# ПРЯМО В СБОРКУ (SMOKE_BUILD, задача 0145).
RESOLVE_HOST=""
STAND_BASE=""
if [ -n "${SMOKE_URL:-}" ]; then
    STAND_BASE="${SMOKE_URL%/}"
    BASE="$STAND_BASE"
    ROUTE="${DEPLOY_CURL:-host}"
elif [ -n "${APP_DOMAIN:-}" ]; then
    STAND_BASE="https://$APP_DOMAIN"
    BASE="$STAND_BASE"
    # Адрес разрешаем сами: снаружи домен может указывать куда угодно,
    # а проверяем мы ЭТУ машину. То же делает первая самопроверка.
    RESOLVE_HOST="$APP_DOMAIN"
    ROUTE="${DEPLOY_CURL:-caddy}"
fi

# Прямо в сборку, минуя терминатор (задача 0145). Так прогон ходит в окне
# выкладки: копия уже поднята под НОВОЙ сборкой, а трафик ещё на старой —
# то есть через терминатор в эту минуту отвечает та версия, которую как раз
# заменяют, и прогон проверял бы не то.
#
# СТЕНД ПРИ ЭТОМ СЧИТАЕТСЯ ПО-ПРЕЖНЕМУ — по публичному адресу. Считай мы его
# по «app-green», метки «prom» в имени не было бы вовсе, host_label вернул бы
# пусто, и решение осталось бы за переменной DEPLOY_STAND — то есть забытая
# или неверная переменная снова открывала бы запись в кабинете живого
# клиента. Ровно от этого 0085 и защищается, и защита обязана пережить смену
# адреса запроса.
if [ -n "${SMOKE_BUILD:-}" ]; then
    if [ -z "$STAND_BASE" ]; then
        red "Прогон нацелен прямо в сборку ${SMOKE_BUILD}, но публичный адрес стенда неизвестен: нет ни SMOKE_URL, ни APP_DOMAIN в $ENV_FILE. По нему определяется стенд — не зная, ПРОМ это или нет, прогон не пишет ничего."
        exit 1
    fi
    BASE="http://${SMOKE_BUILD}:8080"
    # Разрешать нечего: имя сборки живёт в DNS сети compose.
    RESOLVE_HOST=""
    ROUTE="${DEPLOY_CURL:-caddy}"
fi

if [ -z "$BASE" ]; then
    red "Дымовой прогон не нацелен: нет ни SMOKE_URL, ни APP_DOMAIN в $ENV_FILE"
    exit 1
fi

# Чем входить. Файл — по той же причине, что и ссылки на прайсы: пароль,
# отданный аргументом команды, виден в `ps` любому на машине.
if [ -z "${SMOKE_LOGIN:-}" ] && [ -f "$CRED_FILE" ]; then
    SMOKE_COMPANY=$(sed -n '1p' "$CRED_FILE" | tr -d '\r')
    SMOKE_LOGIN=$(sed -n '2p' "$CRED_FILE" | tr -d '\r')
    SMOKE_PASSWORD=$(sed -n '3p' "$CRED_FILE" | tr -d '\r')
fi
SMOKE_COMPANY="${SMOKE_COMPANY:-}"; SMOKE_LOGIN="${SMOKE_LOGIN:-}"; SMOKE_PASSWORD="${SMOKE_PASSWORD:-}"
if [ -z "$SMOKE_COMPANY" ] || [ -z "$SMOKE_LOGIN" ] || [ -z "$SMOKE_PASSWORD" ]; then
    # Не «пропускаем»: прогон, молча не выполняющийся, хуже отсутствующего —
    # выкладку зеленят, ни разу не пройдя сценарий.
    red "Дымовой прогон некем пройти: не задан вход ($CRED_FILE — три строки: компания, логин, пароль продавца; либо SMOKE_COMPANY/SMOKE_LOGIN/SMOKE_PASSWORD)"
    exit 1
fi

# Режим считается по адресу СТЕНДА, а не по тому, куда уходит запрос.
decide_mode "${DEPLOY_STAND:-}" "$STAND_BASE" "$WANT"
case "$MODE" in
    "отказ:"*) red "Дымовой прогон ${MODE}"; exit 1 ;;
esac

# Только сказать, что будет, и выйти. Ни одного запроса отсюда не уходит.
if [ -n "$PRINT_MODE" ]; then
    printf 'Дымовой прогон нацелен: %s\n' "$BASE"
    # Два адреса печатаются раздельно намеренно: разойдясь, они отвечают
    # на разные вопросы — «куда уйдёт запрос» и «по чему решили, что это
    # за стенд». Второй и есть то, чем открывается или закрывается запись.
    printf 'стенд определяется по адресу: %s\n' "$STAND_BASE"
    printf 'компания из секрета: %s\n' "$SMOKE_COMPANY"
    printf 'список тестовых компаний: %s\n' "$TEST_TENANTS"
    printf 'режим: %s\n' "$MODE"
    printf 'запись откроется после подтверждения входом: %s\n' \
        "$([ -n "$CONFIRM_FOR_WRITE" ] && echo "да, если вход приведёт в ${TEST_TENANT}" || echo нет)"
    exit 0
fi

RUN_ID="$(date +%Y%m%d-%H%M%S)-$$"

# Только вход и выход из скрипта: банка cookie остаётся, сценарий не идёт.
# Зовётся выкладкой ДО заморозки записи — сессия ложится в исходную базу
# и уезжает в копию, которая снимается следом, поэтому переключённая
# на копию сборка эту же сессию и видит (0142).
if [ -n "$LOGIN_ONLY" ]; then
    login_only
    exit $?
fi

printf 'Дымовой прогон сценарием: %s, режим \033[1m%s\033[0m\n' "$BASE" \
    "$([ "$MODE" = write ] && echo 'продажа целиком' || echo 'только чтение')"

scenario
if [ -n "$FAILED" ]; then
    red "Дымовой прогон не прошёл: ${FAILED%, }"
    exit 1
fi
green "Дымовой прогон пройден: сценарий доезжает до конца"
