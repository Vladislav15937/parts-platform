#     на ПРОМ можно было бы одной строкой в .env, и молча.
#
# Пара «код: схема», а не один код: секрет говорит, КУДА СОБИРАЛИСЬ, а ответ
# входа — КУДА ПОПАЛИ, и сверять надо второе с первым.
#
# ОБЪЯВЛЕН ЗДЕСЬ, А СТЕРЕЖЁТСЯ НИЖЕ — и вот почему. Файл ячейки .env
# сорсится ПОЗЖЕ (`set -a; . "./$ENV_FILE"`), то есть строка `TEST_TENANTS=…`
# в нём переписывала бы этот список уже после объявления — молча и с полным
# эффектом: разбор PR #262 воспроизвёл это живьём, отказ «это ПРОМ» исчезал
