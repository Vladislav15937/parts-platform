step "Общие схемы: реестр арендаторов и справочники (база $DB_NAME)"
# --schema, а не весь кластер: роли и настройки сервера восстанавливает
# провижининг ячейки, а не бэкап данных.
$COMPOSE exec -T postgres pg_dump -U "$DB_USER" -d "$DB_NAME" \
    --format=custom --schema=public --schema=catalog \
    > "$OUT/shared.dump"
# Код возврата pg_dump говорит «вышел без ошибки», а не «получился дамп»:
# пустой файл нужного имени проходил зелёным. Спрашиваем оглавление (задача 0237).
dump_check "$OUT/shared.dump" || fail "shared.dump негоден: $DUMP_WHY"
ok "shared.dump — $(du -h "$OUT/shared.dump" | cut -f1), таблиц в оглавлении: $DUMP_TABLES"

step "Арендаторы"
# Берём из реестра, а не перечисляем схемы: схема без записи в реестре —
# это мусор от сорвавшегося провижининга, и восстанавливать его незачем.
TENANTS=$(psql_ -tAc "SELECT schema_name FROM public.tenant_registry
                      WHERE status IN ('ACTIVE','SUSPENDED') ORDER BY tenant_id")

if [ -z "$TENANTS" ]; then
    ok "арендаторов нет"
else
    for schema in $TENANTS; do
        # Числа для сверки снимаются ВОКРУГ дампа — до и после (задача 0244).
        # Проверка бэкапа сверяет развёрнутую копию с ними, а не с живой базой:
        # живая база к утру понедельника уже другая, и её движение красило
        # проверку на годной копии. Два замера, а не один, потому что pg_dump
        # держит свой снимок: запись между замером и снимком дала бы то же
        # ложное красное, только окном в секунды. Годным считается любое число
        # между замерами; на спокойной ячейке они равны.
        AGG_BEFORE=""
        AGG_AFTER=""
        AGG_BEFORE=$(agg_snap "$schema") || AGG_BEFORE=""

        # Каждый дамп согласован сам по себе: pg_dump держит снимок на время
        # одного вызова. Между арендаторами согласованности нет и не нужно —
        # их данные не пересекаются.
        $COMPOSE exec -T postgres pg_dump -U "$DB_USER" -d "$DB_NAME" \
            --format=custom --schema="$schema" > "$OUT/$schema.dump"
        dump_check "$OUT/$schema.dump" || fail "$schema.dump негоден: $DUMP_WHY"

        [ -z "$AGG_BEFORE" ] || AGG_AFTER=$(agg_snap "$schema") || AGG_AFTER=""
        if [ -n "$AGG_BEFORE" ] && [ -n "$AGG_AFTER" ]; then
            for metric in $(agg_names); do
                value_before=$(printf '%s\n' "$AGG_BEFORE" \
                    | awk -v m="$metric" '$1 == m { print $2; exit }')
                value_after=$(printf '%s\n' "$AGG_AFTER" \
                    | awk -v m="$metric" '$1 == m { print $2; exit }')
                [ -n "$value_before" ] && [ -n "$value_after" ] || continue
                AGG_LINES="$AGG_LINES$(agg_line "$schema" "$metric" "$value_before" "$value_after")
"
            done
        else
            # Громко: без чисел проверка бэкапа сверить копию не сможет
            # и честно скажет «не сверено». Бэкап при этом снят и лежит —
            # валить его из-за ненайденной таблицы значило бы терять данные
            # ради оракула.
            AGG_MISSING="$AGG_MISSING $schema"
            printf '\033[1;33m    числа для сверки по %s НЕ записаны — проверка бэкапа сверить копию не сможет\033[0m\n' \
                "$schema"
        fi
        ok "$schema — $(du -h "$OUT/$schema.dump" | cut -f1)"
    done
fi

step "Опись"
# Числа на момент снятия стоят ПОСЛЕ строк реестра, и это не вкусовщина:
# первые три строки описи ops/restore-cell.sh печатает человеку, а
# «арендаторов: N» читает оттуда же sed'ом — формат начала файла трогать нельзя.
{
    echo "снято: $STAMP"
    echo "база: $DB_NAME"
    echo "арендаторов: $(echo "$TENANTS" | grep -c . || true)"
    psql_ -tAc "SELECT tenant_id||' '||schema_name||' '||code||' '||status
                  FROM public.tenant_registry ORDER BY tenant_id"
    printf '%s' "$AGG_LINES"
} > "$OUT/manifest.txt"
if [ -n "$AGG_MISSING" ]; then
    printf '\033[1;33m    manifest.txt — БЕЗ чисел для сверки по схемам:%s\033[0m\n' "$AGG_MISSING"
else
    ok "manifest.txt — с числами на момент снятия ($(printf '%s' "$AGG_LINES" | grep -c . || true) строк)"
fi

step "Уборка старше $KEEP_DAYS дней"
# Отказ уборки глушился ЦЕЛИКОМ — и сообщение (`2>/dev/null`), и код возврата
# (`|| true`). Уборка, переставшая работать (сменились права на каталоге, том
# только на чтение), не оставляла ни строки: рядом печаталось только число
# оставшихся наборов, а порога у этого числа нет — то есть «14 наборов»
# и «140 наборов» читаются одинаково.
#
# Цена та же, что у непрокрученного журнала (0154): заполненный диск ячейки
# останавливает Postgres, а с ним архив WAL и точку возврата ВСЕХ её
# арендаторов. Поэтому отказ называется словами и меняет код возврата —
# но не валит бэкап здесь же: дампы уже сняты, а ниже остались снимки
# и офсайт, терять которые из-за неубранного старья нельзя.
CLEANUP_FAILED=0
UBORKA_ERR=$(find "$BACKUPS" -maxdepth 1 -type d -name '20*' -mtime "+$KEEP_DAYS" \
    -exec rm -rf {} + 2>&1) || CLEANUP_FAILED=1
# Непустой вывод считается отказом наравне с кодом: `find` печатает
# «Permission denied» по отдельному каталогу и выходит нулём.
if [ "$CLEANUP_FAILED" = 1 ] || [ -n "$UBORKA_ERR" ]; then
    CLEANUP_FAILED=1
    printf '\033[1;31m    Уборка старых наборов НЕ прошла — старое остаётся на диске\033[0m\n'
    [ -z "$UBORKA_ERR" ] || printf '%s\n' "$UBORKA_ERR" | head -5 | sed 's/^/      /'
    printf '\033[1;31m    заполненный диск ячейки останавливает Postgres, а с ним архив WAL\033[0m\n'
fi
ok "осталось наборов: $(find "$BACKUPS" -maxdepth 1 -type d -name '20*' | wc -l | tr -d ' ')"

mark_success partsflow_backup_success_timestamp_seconds "{db=\"$DB_NAME\"}"

# Фотографии — ПОСЛЕ отметки о дампах, и это не небрежность. Отметка означает
# ровно то, что за ней стоит: дампы сняты и лежат. Сорвавшееся зеркало
# не должно делать это утверждение ложным, а своя отметка у него отдельная —
# «дамп снялся» и «снимки скопировались» проверяются разными тревогами,
# по той же причине, по которой у бэкапа и у его проверки отметки разные.
step "Фотографии"
# Зеркалом, а не полной копией на каждую ночь. У одного переехавшего клиента
# снимков под сотню тысяч и десятки гигабайт; датированный слепок каждые сутки
# забьёт диск за неделю. Объекты неизменяемы — ключ содержит uuid, — поэтому
# инкремент здесь честен: что появилось, то и доедет.
#
# Без --remove намеренно. Удаление в живом хранилище доезжать до копии
# не должно: иначе стёртая по ошибке папка клиента исчезает и из бэкапа
# в ту же ночь — то есть ровно тогда, когда бэкап и понадобился. Плата —
# мусор в копии, и она несопоставимо меньше.
#
# Префикс арендатора сохраняется (t_000042/parts/…), как схема в базе:
# вернуть одного клиента — это скопировать обратно одну папку.
PHOTOS="$BACKUPS/photos"
mkdir -p "$PHOTOS"
# Сколько объектов в хранилище ДО зеркала (задача 0237): число файлов в копии
# без этого ни с чем не сверялось, и «снимков: 0» читалось одинаково для пустой
# ячейки, неподключённого тома и опечатанного пути. Считаем ДО, а не после:
# снимок, загруженный во время зеркала, не должен краснить копию.
PHOTO_SRC=$($COMPOSE run --rm mc ls --recursive "cell/${S3_BUCKET:-parts-photos}" 2>/dev/null \
    | wc -l | tr -d ' ') || PHOTO_SRC=""
$COMPOSE run --rm -v "$(cd "$PHOTOS" && pwd):/backup" mc \
    mirror --overwrite --quiet "cell/${S3_BUCKET:-parts-photos}" /backup > /dev/null
PHOTO_LOCAL=$(find "$PHOTOS" -type f | wc -l | tr -d ' ')
# Красное здесь не валит скрипт на месте: ниже офсайт, терять который из-за
# зеркала нельзя (та же логика, что у уборки). Но отметка снимков НЕ ставится,
# а код возврата в конце ненулевой.
PHOTO_FAILED=0
if photo_check "$PHOTO_SRC" "$PHOTO_LOCAL"; then
    ok "снимков: $PHOTO_LOCAL (в хранилище до зеркала $PHOTO_SRC), $(du -sh "$PHOTOS" | cut -f1)"
    mark_success partsflow_photo_backup_success_timestamp_seconds
else
    PHOTO_FAILED=1
    printf '\033[1;31m    Зеркало снимков НЕ подтверждено: %s\033[0m\n' "$PHOTO_WHY"
    printf '\033[1;31m    отметка снимков не ставится — тревога по её возрасту сработает\033[0m\n'
fi

# Офсайт — ПОСЛЕ обеих локальных отметок, и своя отметка у него отдельная.
# «Дамп снялся» и «копия уехала наружу» — разные утверждения, и следят
# за ними разные тревоги, как у дампов и снимков между собой. Копия наружу
# закрывает единственное, чего локальный бэкап не закрывает, — гибель диска:
# и дампы, и зеркало снимков живут на той же машине, что и ячейка.
#
# Включается заданием OFFSITE_REMOTE — путь rclone, покрывающий и другой хост
# (SFTP), и другой бакет (S3, B2) одним инструментом. Пусто — шаг пропускается
# с ГРОМКИМ предупреждением, а не тихо: ячейка без офсайта отличается от ячейки
# с офсайтом лишь тем, что о потере диска на ней узнают в день потери. Своей
# отметки при пропуске нет — absent() в тревогах поймает ячейку, которой офсайт
# положен, но на которой его забыли.
#
# rclone copy, а не sync: наружная копия только пополняется и никогда не удаляет.
# Иначе локальная уборка старых наборов — или, хуже, пустой диск после аварии
# плюс один прогон крона — стёрла бы наружную копию под ноль, то есть ровно
# тогда, когда она и нужна. Та же причина, по которой зеркало снимков идёт
# без --remove. Плата — рост наружного хранилища; его подрезка независимо
# от локальной остаётся отдельным шагом, как и раньше сам офсайт.
step "Офсайт"
if [ -z "${OFFSITE_REMOTE:-}" ]; then
    printf '\033[1;33m    OFFSITE_REMOTE не задан — копия остаётся только на этой машине.\033[0m\n'
    printf '\033[1;33m    Потеря диска уносит и клиента, и его бэкап. Задайте OFFSITE_REMOTE.\033[0m\n'
else
    command -v rclone > /dev/null || fail "OFFSITE_REMOTE задан, а rclone не установлен"
    # Весь каталог ячейки разом: и датированные дампы, и зеркало снимков.
    # Инкрементально — rclone пропускает то, что уже уехало (снимки неизменяемы
    # по ключу, дампы датированы), так что за ночь наружу едет только новое.
    rclone copy "$BACKUPS" "$OFFSITE_REMOTE" --transfers 8 --quiet
    # «Уехало» проверяется присутствием файла на той стороне, а не кодом
    # возврата: rclone отдаёт ноль и когда копировать было нечего. Ищем
    # сегодняшний общий дамп — без него ни один набор не развернуть.
    #
    # Спрашивает ops/offsite-confirm.sh, и исходов у него три (задача 0148):
    # «файл есть», «файла нет» и «спросить не вышло». Прежняя редакция
    # глушила отказ самого `lsf` и печатала «на той стороне нет» на оба
    # последних — то есть посылала искать пропавший файл там, где вопрос
    # не был задан.
    OFFSITE_RC=0
    offsite_confirm "$OFFSITE_REMOTE/$STAMP/" 'shared.dump' || OFFSITE_RC=$?
    case "$OFFSITE_RC" in
        0)
            ok "уехало наружу: $OFFSITE_REMOTE"
            mark_success partsflow_offsite_backup_success_timestamp_seconds ;;
        2)
            # Скрипт не валим: локальная копия снята и лежит, терять её из-за
            # недоступного офсайта нельзя — та же логика, что у отметки
            # в наблюдение. Но отметку офсайта НЕ ставим ни здесь, ни ниже:
            # тревога по её возрасту обязана сработать в обоих случаях.
            printf '\033[1;31m    Офсайт НЕ ПРОВЕРЕН: спросить ту сторону не удалось (%s)\033[0m\n' \
                "$OFFSITE_WHY"
            printf '\033[1;31m    Это НЕ «файла там нет»: %s мог уехать. Проверьте удалёнку rclone и сеть.\033[0m\n' \
                "$STAMP/shared.dump" ;;
        *)
            printf '\033[1;31m    Офсайт не подтверждён: %s на той стороне нет\033[0m\n' \
                "$STAMP/shared.dump" ;;
    esac
fi

if [ "$PHOTO_FAILED" != 0 ]; then
    printf '\n\033[1;33m    Дампы сняты, но зеркало снимков НЕ подтверждено — прогон завершится с кодом 1\033[0m\n'
fi
printf '\n\033[1;32mБэкап снят: %s\033[0m\n' "$OUT"
printf 'Фотографии: %s (зеркало, общее на все наборы)\n' "$PHOTOS"
[ -n "${OFFSITE_REMOTE:-}" ] && printf 'Офсайт: %s\n' "$OFFSITE_REMOTE"
printf 'Проверить восстановлением: ops/verify-backup.sh %s\n' "$OUT"
# Зеркало снимков не подтверждено — прогон не «зелёный», хотя дампы лежат.
[ "$PHOTO_FAILED" = 0 ] || exit 1
