#!/usr/bin/env bash
# Постановка бэкапов на расписание.
#
#   ops/install-cron.sh            # поставить
#   ops/install-cron.sh --show     # что стоит сейчас — и запустится ли оно
#   ops/install-cron.sh --remove   # снять
#   ops/install-cron.sh --selftest # проверить самого сторожа на подделках
#
# Отдельным скриптом, а не строчками в документации: строчки, которые надо
# скопировать руками, однажды копируют с опечаткой в пути или не копируют
# вовсе. Ошибиться при этом можно молча — до того дня, когда бэкап нужен.
#
# Сама забытая установка тоже видна: тревога «БэкапНеСнимался» срабатывает
# на отсутствие отметки, а не только на её возраст. То есть ячейка,
# на которой этот скрипт не запускали, сообщит об этом сама.
#
# ПОЧЕМУ ПУТЬ ЖУРНАЛА ПРОВЕРЯЕТСЯ ДО ПОСТАНОВКИ (задача 0152). Все пять задач
# кончаются перенаправлением `>> ЖУРНАЛ 2>&1`, а шелл создаёт файл
# перенаправления ДО запуска команды. Нет прав — он не запускает команду
# вовсе: `crontab -l` показывает пять задач, а не выполняется ни одна,
# и следов тоже никаких — ни строки в журнале, ни отметки в наблюдении.
# Так боевая ячейка прожила С САМОГО ЗАВЕДЕНИЯ расписания: умолчанием стоял
# `/var/log/parts-backup.log`, а `/var/log` пользователю `deploy` на запись
# недоступен (`drwxr-xr-x root:syslog`). Цена — ни одного логического дампа,
# ни одной офсайт-копии и ни одной репетиции возврата; данные клиента
# держались на одном `archive_command` самого Postgres, который ведёт база,
# а не cron.
#
# Отсюда два изменения, и оба нужны вместе. Первое: умолчание журнала — это
# каталог ячейки, куда `deploy` пишет по построению (ячейка живёт в его
# домашнем каталоге), а не системный `/var/log`, доступ к которому зависит
# от прав, выданных кем-то другим. Второе: перед постановкой путь ПРОБУЕТСЯ
# тем же действием, которым его тронет cron, и при отказе расписание
# не ставится вовсе — с объяснением, что делать. Молча поставленное мёртвое
# расписание хуже непоставленного: оно выглядит работающей защитой.
set -euo pipefail
cd "$(dirname "$0")/.."

ROOT="$(pwd)"
MARK="# parts-platform: бэкапы ячейки"
# Умолчание — каталог ячейки. `/var/log` оставлен возможным (`BACKUP_LOG=`),
# но не умолчанием: там запись зависит от прав на системном каталоге, а здесь
# от того, что ячейка вообще развёрнута. Файл попадает под `*.log`
# в `.gitignore`, а `logs/` лежит ВНЕ `ops/` — кнопка выкладки синхронизирует
# `ops/` с `--delete`, и журнал внутри неё уезжал бы при каждой выкладке.
LOG="${BACKUP_LOG:-$ROOT/logs/parts-backup.log}"
# Чем ставить. Переопределяет только самопроверка: настоящий crontab трогать
# нельзя — на машине ячейки в нём живое расписание.
CRONTAB="${CRONTAB_CMD:-crontab}"
SELF="$(cd "$(dirname "$0")" && pwd)/$(basename "$0")"

red()   { printf '\033[1;31m%s\033[0m\n' "$1" >&2; }
green() { printf '\033[1;32m%s\033[0m\n' "$1"; }

# Проверка идёт через два часа после снятия: длинный дамп большой ячейки
# не должен встретиться со своей же проверкой на одной базе.
#
# Пять задач вместо двух — потому что защит две, и они про разное.
# Дампы по схемам возвращают ОДНОГО клиента (ночью, ежедневно), архив WAL
# даёт точку возврата до минуты. У второй свои задачи:
#
#   каждые 5 минут — сторож архива: цела ли цепочка и уехала ли наружу.
#     Часто, потому что разрыв обесценивает всё, что случилось после него:
#     замеченный через сутки, он стоит суток, к которым уже не вернуться.
#     Заодно это единственный шаг, увозящий сегменты наружу чаще раза
#     в сутки, — без него гибель диска по-прежнему стоила бы смены.
#   по воскресеньям — базовая копия кластера: то, на что накатывается архив.
#     Ночью в воскресенье и до ночного дампа, чтобы две тяжёлые задачи
#     не читали базу одновременно.
#   по понедельникам в 6:00 — репетиция возврата к моменту: та же логика,
#     что у проверки дампов разворотом. «Архив непрерывен» и «к моменту можно
#     вернуться» — разные утверждения, и второе проверяется только накатом.
#
# ШЕСТАЯ ЗАДАЧА — прокрутка журнала, и она не защита данных, а условие того,
# что защита продолжит работать (задача 0154). В журнал пишут все пять задач
# выше, а первая из них идёт каждые пять минут: 288 запусков в сутки,
# ~4,7 МиБ в месяц по замеру. Расти ему некуда — заполненный диск ячейки
# останавливает Postgres, а с ним и архив WAL, то есть ту самую точку
# возврата. Каждый час, а не раз в сутки: час — это окно, за которое журнал
# успевает перерасти предел. При сегодняшнем поведении задач это 6 КиБ
# (замер), но величина эта НЕ ограничена: задача, вылившая всплеск вывода,
# даст ровно такую копию, какой успела вырасти, — прокрутка режет в момент
# запуска, а не управляет потоком записи.
# Минута 7 выбрана, чтобы не приходиться на :00 и :05, когда идёт архив.
ENTRIES="$MARK
*/5 * * * * cd $ROOT && ops/wal-archive.sh >> $LOG 2>&1
0 1 * * 0 cd $ROOT && ops/basebackup.sh >> $LOG 2>&1
0 3 * * * cd $ROOT && ops/backup.sh >> $LOG 2>&1
0 5 * * 1 cd $ROOT && ops/verify-backup.sh >> $LOG 2>&1
0 6 * * 1 cd $ROOT && ops/restore-pitr.sh --verify >> $LOG 2>&1
7 * * * * cd $ROOT && ops/rotate-log.sh $LOG >> $LOG 2>&1
# конец parts-platform"

current() { $CRONTAB -l 2>/dev/null || true; }
without_ours() { current | sed "/^$MARK\$/,/^# конец parts-platform\$/d"; }

# Предел журнала и глубина хранения живут в ops/rotate-log.sh — ОДНИМ местом
# на оба скрипта. Второе место с тем же числом разъезжается с первым молча,
# и разъехалось бы ровно в тот день, когда предел решат поменять.
read -r ROT_LIMIT ROT_KEEP <<< "$(bash "$ROOT/ops/rotate-log.sh" --limit)"

hsize() {  # человекочитаемый размер: МиБ у больших, КиБ у маленьких
    if [ "$1" -ge 1048576 ]; then printf '%s МиБ' "$(( ( $1 + 524288 ) / 1048576 ))"
    else printf '%s КиБ' "$(( ( $1 + 512 ) / 1024 ))"; fi
}
jsize() { if [ -f "$1" ]; then wc -c < "$1" | tr -d ' '; else printf '0'; fi; }

# --- сторож пути журнала ----------------------------------------------------

LOG_REASON=""
log_writable() {  # $1 — путь журнала; причина отказа остаётся в LOG_REASON
    local path="$1" dir
    LOG_REASON=""
    dir=$(dirname "$path")
    [ -d "$dir" ] || mkdir -p "$dir" 2>/dev/null || true
    if [ ! -d "$dir" ]; then
        LOG_REASON="каталога $dir нет, и завести его не вышло"
        return 1
    fi
    # Пробуем ТЕМ ЖЕ действием, которым путь тронет cron, — `>> файл`.
    # Спрашивать `test -w` у каталога мало: на ответ влияют и ACL, и точка
    # монтирования только на чтение, и уже лежащий там файл чужого владельца.
    # Сторож, отвечающий на соседний вопрос, — это ровно то, чем 0152
    # и стоила ячейке всех пяти защит.
    if ( exec >>"$path" ) 2>/dev/null; then
        return 0
    fi
    # `|| true` внутри подстановки не для красоты: без него отсутствующий
    # awk (урезанный образ, чужой PATH) уронил бы сторожа под `set -e` ровно
    # там, где он обязан объяснять. Сторож, падающий вместо объяснения, —
    # это снова молчаливо непоставленное расписание.
    if [ -e "$path" ]; then
        LOG_REASON="файл есть, а записи в него нет ($(ls -ld "$path" 2>/dev/null | awk '{print $1, $3, $4}' || true))"
    else
        LOG_REASON="файла нет, и создать его в $dir нельзя ($(ls -ld "$dir" 2>/dev/null | awk '{print $1, $3, $4}' || true))"
    fi
    return 1
}

otkaz_log() {  # $1 — путь журнала
    red "  ✗ журнал расписания недоступен на запись: $1"
    red "      $LOG_REASON"
    cat >&2 <<TXT

      Шелл создаёт файл перенаправления ДО запуска команды: получив отказ,
      он не запускает команду вовсе. Расписание стояло бы в crontab целиком
      и не выполнялось НИ РАЗУ — молча, все пять задач сразу: ни дампа,
      ни офсайт-копии, ни репетиции возврата. Так и было на боевой ячейке
      с самого заведения расписания (задача 0152).

      Расписание НЕ ТРОНУТО. Два выхода:

        1) писать журнал туда, куда пишет сам владелец ячейки (умолчание):
             BACKUP_LOG=$ROOT/logs/parts-backup.log ops/install-cron.sh

        2) выдать права на этот путь — это правка прав на системном каталоге,
           и делает её тот, у кого есть root:
             sudo install -o "$(id -un)" -g "$(id -gn)" -m 640 /dev/null "$1"
             BACKUP_LOG="$1" ops/install-cron.sh

TXT
}

# --- проверка самого сторожа ------------------------------------------------
#
# Сторож, не краснеющий на дефекте, хуже отсутствующего, и установить это
# можно только попыткой. Случаи — ровно те, которыми эта защита перестаёт
# работать: неписучий путь проходит молча; отказ всё-таки трогает crontab;
# `--show` называет расписание стоящим, когда оно не запустится; и сама
# проверка снята из скрипта. Настоящий crontab при этом не трогается вовсе.
selftest() {
    local bad=0 tmp out rc entries n
    echo "Самопроверка ops/install-cron.sh"

    tmp=$(mktemp -d)
    # shellcheck disable=SC2064
    trap "rm -rf '$tmp'" EXIT

    cat > "$tmp/crontab" <<'SH'
#!/usr/bin/env bash
# Подделка crontab: настоящий трогать нельзя — на машине ячейки в нём живое
# расписание, и самопроверка, сносящая его, была бы хуже отсутствующей.
f="$FAKE_CRONTAB"
case "${1:-}" in
    -l) [ -s "$f" ] || exit 1; cat "$f" ;;
    -)  cat > "$f" ;;
    *)  echo "подделка crontab: не умеет $*" >&2; exit 2 ;;
esac
SH
    chmod +x "$tmp/crontab"

    probe() {  # $1 — путь журнала, дальше — аргументы скрипта
        local log="$1"; shift
        set +e
        out=$(BACKUP_LOG="$log" CRONTAB_CMD="$tmp/crontab" FAKE_CRONTAB="$tmp/cron-file" \
              bash "$SELF" "$@" 2>&1); rc=$?
        set -e
    }

    # Случай 1: путь, куда писать можно, — расписание встаёт целиком.
    # Сторож, краснеющий на исправном пути, отключили бы в первый же день
    # вместе с защитой.
    rm -f "$tmp/cron-file"
    probe "$tmp/zhurnal/parts-backup.log"
    entries=$(grep -c '^[0-9*]' "$tmp/cron-file" 2>/dev/null || true)
    if [ "$rc" = 0 ] && [ "${entries:-0}" = 6 ] \
       && grep -q "$tmp/zhurnal/parts-backup.log" "$tmp/cron-file" 2>/dev/null \
       && grep -q 'rotate-log.sh' "$tmp/cron-file" 2>/dev/null; then
        printf '  ✓ писучий путь — все шесть задач встали, прокрутка среди них, журнал назван\n'
    else
        red "  ✗ на писучем пути расписание обязано вставать целиком (код $rc, задач ${entries:-0})"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=1
    fi

    # Случай 2: неписучий путь — тот самый дефект. Каталогом журнала объявлен
    # обычный файл: так отказ воспроизводится и под root, у которого биты
    # прав не спрашивают.
    printf 'ya fayl, a ne katalog\n' > "$tmp/fayl"
    rm -f "$tmp/cron-file"
    probe "$tmp/fayl/parts-backup.log"
    if [ "$rc" != 0 ] \
       && grep -q 'недоступен на запись' <<<"$out" \
       && grep -q "$tmp/fayl/parts-backup.log" <<<"$out" \
       && grep -q 'ДО запуска команды' <<<"$out" \
       && [ ! -e "$tmp/cron-file" ]; then
        printf '  ✓ неписучий путь — красное, названы путь и цена, crontab не тронут\n'
    else
        red "  ✗ неписучий путь обязан валить установку, называть путь и НЕ трогать crontab"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        [ -e "$tmp/cron-file" ] && red "      а расписание всё-таки поставлено"
        bad=1
    fi

    # Случай 3: то же самое правами, а не подменой каталога, — как на боевой
    # машине. Под root биты прав не действуют, и случай честно пропускается:
    # молчаливое «зелено» здесь было бы хуже пропуска.
    mkdir -p "$tmp/tolko-chtenie"
    chmod 500 "$tmp/tolko-chtenie"
    if [ "$(id -u)" = 0 ]; then
        printf '  · случай «каталог без права записи» пропущен: под root права не спрашивают\n'
    else
        rm -f "$tmp/cron-file"
        probe "$tmp/tolko-chtenie/parts-backup.log"
        if [ "$rc" != 0 ] && grep -q 'создать его в' <<<"$out" && [ ! -e "$tmp/cron-file" ]; then
            printf '  ✓ каталог без права записи — красное (это и есть боевой случай)\n'
        else
            red "  ✗ каталог без права записи обязан валить установку"
            printf '%s\n' "$out" | sed 's/^/      /' >&2
            bad=1
        fi
    fi

    # Случай 4: расписание уже стоит, а путь в нём неписучий. «Задача стоит
    # в cron» и «задача отработает» — разные утверждения, и на этой разнице
    # ячейка и погорела: `--show` показывал пять строк мёртвого расписания
    # и молчал.
    printf '%s\n%s\n%s\n' "$MARK" \
        "0 3 * * * cd $ROOT && ops/backup.sh >> $tmp/fayl/parts-backup.log 2>&1" \
        "# конец parts-platform" > "$tmp/cron-file"
    probe "$LOG" --show
    if [ "$rc" != 0 ] && grep -q "$tmp/fayl/parts-backup.log" <<<"$out"; then
        printf '  ✓ --show краснеет на стоящем, но неработающем расписании\n'
    else
        red "  ✗ --show обязан сказать, что стоящее расписание не запустится"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=1
    fi

    # Случай 5: возврат дефекта — копия скрипта со снятой проверкой. Без него
    # нельзя утверждать, что краснеет именно сторож, а не что-нибудь соседнее:
    # эта копия обязана молча поставить расписание на тот же неписучий путь.
    sed 's/^\( *\)if ! log_writable "\$LOG"; then$/\1if false; then/' "$SELF" > "$tmp/bez-storozha.sh"
    if cmp -s "$SELF" "$tmp/bez-storozha.sh"; then
        red "  ✗ подделку собрать не удалось — строка проверки в скрипте изменилась"
        bad=1
    else
        rm -f "$tmp/cron-file"
        set +e
        out=$(BACKUP_LOG="$tmp/fayl/parts-backup.log" CRONTAB_CMD="$tmp/crontab" \
              FAKE_CRONTAB="$tmp/cron-file" bash "$tmp/bez-storozha.sh" 2>&1); rc=$?
        set -e
        entries=$(grep -c '^[0-9*]' "$tmp/cron-file" 2>/dev/null || true)
        if [ "$rc" = 0 ] && [ "${entries:-0}" = 6 ]; then
            printf '  ✓ со снятой проверкой мёртвое расписание встаёт молча — краснеет именно сторож\n'
        else
            red "  ✗ без проверки установка обязана проходить: иначе случай 2 краснеет не из-за сторожа"
            printf '%s\n' "$out" | sed 's/^/      /' >&2
            bad=1
        fi
    fi

    # Случай 6 (задача 0154): журнал перерос предел ВДВОЕ — `--show` обязан
    # это назвать. Расписание при этом стоит целиком и выглядит работающим,
    # то есть снаружи всё в порядке: ровно та болезнь, которой 0152 обошлась
    # ячейке в девять дней без бэкапов.
    rm -f "$tmp/cron-file"
    probe "$tmp/zhurnal/parts-backup.log"
    : > "$tmp/zhurnal/parts-backup.log"
    n=0
    while [ "$n" -lt 400 ]; do
        printf 'строка вывода задачи расписания %s\n' "$n" >> "$tmp/zhurnal/parts-backup.log"
        n=$(( n + 1 ))
    done
    set +e
    out=$(ROTATE_LIMIT_BYTES=8192 BACKUP_LOG="$tmp/zhurnal/parts-backup.log" \
          CRONTAB_CMD="$tmp/crontab" FAKE_CRONTAB="$tmp/cron-file" \
          bash "$SELF" --show 2>&1); rc=$?
    set -e
    if [ "$rc" != 0 ] && grep -q 'прокрутка НЕ РАБОТАЕТ' <<<"$out"; then
        printf '  ✓ переросший журнал назван: --show краснеет, хотя расписание стоит\n'
    else
        red "  ✗ --show обязан заметить журнал, переросший предел вдвое (код $rc)"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=1
    fi

    # Случай 7 — возврат дефекта прокрутки: копия скрипта БЕЗ её строки ставит
    # пять задач, как было до 0154, и `--show` настоящего скрипта обязан это
    # назвать. Без этого случая «прокрутка стоит в расписании» проверялось бы
    # только на исправном дереве — то есть сторож не предъявлялся бы на дефекте.
    sed '/rotate-log.sh \$LOG >> \$LOG/d' "$SELF" > "$tmp/bez-rotatsii.sh"
    if cmp -s "$SELF" "$tmp/bez-rotatsii.sh"; then
        red "  ✗ подделку собрать не удалось — строка прокрутки в расписании изменилась"
        bad=1
    else
        rm -f "$tmp/cron-file"
        set +e
        out=$(BACKUP_LOG="$tmp/zhurnal/parts-backup.log" CRONTAB_CMD="$tmp/crontab" \
              FAKE_CRONTAB="$tmp/cron-file" bash "$tmp/bez-rotatsii.sh" 2>&1); rc=$?
        entries=$(grep -c '^[0-9*]' "$tmp/cron-file" 2>/dev/null || true)
        out=$(BACKUP_LOG="$tmp/zhurnal/parts-backup.log" CRONTAB_CMD="$tmp/crontab" \
              FAKE_CRONTAB="$tmp/cron-file" bash "$SELF" --show 2>&1); rc=$?
        set -e
        if [ "${entries:-0}" = 5 ] && [ "$rc" != 0 ] \
           && grep -q 'прокрутки журнала в расписании НЕТ' <<<"$out"; then
            printf '  ✓ расписание без прокрутки названо словами — краснеет именно её отсутствие\n'
        else
            red "  ✗ расписание без прокрутки обязано краснеть на --show (задач ${entries:-0}, код $rc)"
            printf '%s\n' "$out" | sed 's/^/      /' >&2
            bad=1
        fi
    fi

    [ $bad = 0 ] || { red "Самопроверка не прошла"; exit 1; }
    green "Самопроверка пройдена"
}

case "${1:-install}" in
    --selftest)
        selftest
        ;;
    --show)
        printf 'Расписание ячейки:\n'
        ours=$(current | sed -n "/^$MARK\$/,/^# конец parts-platform\$/p")
        if [ -z "$ours" ]; then
            red '  не установлено'
            exit 1
        fi
        printf '%s\n' "$ours" | grep -v '^#' || true
        # «Задача стоит в crontab» и «задача отработает» — разные утверждения,
        # и это ровно та разница, на которой ячейка простояла без бэкапов.
        # Поэтому у каждого журнала, названного в расписании, спрашивается
        # право записи — тем же действием, которым его тронет cron.
        bad=0
        # Прокрутка журнала (задача 0154) спрашивается ДВУМЯ вопросами, потому
        # что это два разных утверждения — ровно как «стоит в cron» и
        # «отработает». Первый: стоит ли она в расписании вообще. Второй:
        # не перерос ли журнал предел ВДВОЕ — при сегодняшнем поведении задач
        # (6 КиБ в час) это означает, что прокрутка не работает, какой бы
        # ни была причина. У вопроса есть честный ложноположительный край:
        # задача, вылившая всплеск вывода до планового часа, даст ту же
        # красную строку при исправной прокрутке — поэтому строка называет
        # оба случая, а не один. Ложная тревога здесь дешевле пропуска:
        # переросший журнал стоит посмотреть в любом случае. Без второго вопроса
        # получилась бы ротация, о которой никто не узнает, если она перестанет
        # работать, — та же болезнь, из-за которой ячейка девять дней стояла
        # без бэкапов.
        if printf '%s\n' "$ours" | grep -q 'rotate-log.sh'; then
            printf '  ✓ прокрутка журнала в расписании: предел %s, копий %s\n' \
                "$(hsize "$ROT_LIMIT")" "$ROT_KEEP"
        else
            red '  ✗ прокрутки журнала в расписании НЕТ — он растёт без предела'
            red '      задача архива идёт каждые 5 минут (~4,7 МиБ в месяц), и остановить рост некому'
            red '      заполненный диск ячейки останавливает Postgres, а с ним и архив WAL'
            red "      чинится повторной установкой: BACKUP_LOG=$LOG ops/install-cron.sh"
            bad=1
        fi
        for path in $(printf '%s\n' "$ours" | sed -n 's/.*>> \([^ ]*\) 2>&1.*/\1/p' | sort -u); do
            if log_writable "$path"; then
                size=$(jsize "$path")
                if [ "$size" -gt $(( ROT_LIMIT * 2 )) ]; then
                    red "  ✗ журнал $path вырос до $(hsize "$size") при пределе $(hsize "$ROT_LIMIT")"
                    red "      либо прокрутка НЕ РАБОТАЕТ, либо задача вылила всплеск вывода до планового часа"
                    red "      прокрутка режет журнал в момент запуска и потоком записи не управляет"
                    red "      проверить прямо сейчас: ops/rotate-log.sh $path"
                    bad=1
                else
                    printf '  ✓ журнал %s — запись есть, задачи запускаются; размер %s\n' \
                        "$path" "$(hsize "$size")"
                fi
            else
                red "  ✗ журнал $path — записи нет: $LOG_REASON"
                red "      задачи НЕ ЗАПУСКАЮТСЯ вовсе: шелл создаёт файл перенаправления до команды"
                red "      чинится повторной установкой: BACKUP_LOG=$ROOT/logs/parts-backup.log ops/install-cron.sh"
                bad=1
            fi
        done
        exit $bad
        ;;
    --remove)
        without_ours | $CRONTAB -
        printf '\033[1;32mРасписание снято. Тревога «БэкапНеСнимался» придёт через сутки.\033[0m\n'
        ;;
    install)
        # Путь журнала — ДО постановки. Поставленное и не запускающееся
        # расписание выглядит защитой, которой нет, и узнают об этом
        # в тот единственный день, когда бэкап нужен.
        if ! log_writable "$LOG"; then
            otkaz_log "$LOG"
            exit 1
        fi
        # Проверка восстановлением еженедельная, а не ежедневная: она поднимает
        # весь набор в отдельную базу, и на ячейке с двумя сотнями арендаторов
        # это часы диска и процессора. Раз в неделю отвечает на тот же вопрос —
        # «получится ли вернуть клиента», — не мешая работать.
        printf '%s\n' "$(without_ours)" "$ENTRIES" | grep -v '^$' | $CRONTAB -
        printf '\033[1;32mРасписание установлено:\033[0m\n'
        printf '  архив WAL   — каждые 5 минут (цепочка и офсайт)\n'
        printf '  базовая     — по воскресеньям в 1:00\n'
        printf '  бэкап       — каждый день в 3:00\n'
        printf '  проверка    — по понедельникам в 5:00\n'
        printf '  возврат     — по понедельникам в 6:00 (репетиция на момент)\n'
        printf '  прокрутка   — каждый час: предел %s, копий %s\n' \
            "$(hsize "$ROT_LIMIT")" "$ROT_KEEP"
        printf '  журнал      — %s (запись проверена)\n' "$LOG"
        printf '\nОтметки об успехе уходят в pushgateway, тревоги — в Telegram.\n'
        printf 'Проверить прямо сейчас:\n'
        printf '  ops/backup.sh && ops/verify-backup.sh        — дампы по схемам\n'
        printf '  ops/basebackup.sh                            — базовая копия кластера\n'
        printf '  ops/wal-archive.sh && ops/restore-pitr.sh --verify   — точка возврата\n'
        printf 'Базовую копию снимите СЕЙЧАС: до неё архив WAL накатывать не на что.\n'
        printf '\n\033[1;33mСтоит в crontab — ещё не значит отработало.\033[0m Через пять минут\n'
        printf 'спросите следы, а не расписание:\n'
        printf '  tail -n 20 %s\n' "$LOG"
        printf '  curl -s localhost:9091/metrics | grep partsflow_wal_offsite_success\n'
        ;;
    *)
        printf 'Использование: %s [--show|--remove|--selftest]\n' "$0" >&2
        exit 2
        ;;
esac
