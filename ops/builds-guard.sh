#!/usr/bin/env bash
# Какие сборки поднимет ячейка при таком .env — сторож боевого compose.
#
#   ./ops/builds-guard.sh             # проверить docker-compose.prod.yml
#   ./ops/builds-guard.sh --selftest  # проверить самого сторожа на подделках
#
# Почему это сторож, а не строка в документе. Сборок две, они стоят под
# профилями compose (0079), и какие из них работают, говорит COMPOSE_PROFILES
# в .env. Пока этой строки в .env не было, `docker compose up -d` не поднимал
# НИ ОДНОЙ сборки — ячейка вставала терминатором, за которым нет приложения,
# и это простой живого клиента из-за строчки в файле, о которой обновляющийся
# по прежней инструкции не знал. Решение владельца от 18 сентября 2026:
# нет строки про сборки — поднимать прежнюю версию, как было.
#
# У правки два края, и оба обязаны стеречься. Забыть первый — вернуть простой.
# Забыть второй (сделать синюю сборку беспрофильной) — вернуть воскресающую
# сборку: погашенная старая поднималась бы первым же `up -d` без имени сервиса,
# ради чего профили и заводились. Поэтому проверяются пять случаев, а не один.
#
# Спрашиваем сам compose, а не читаем YAML глазами: «какие сервисы включены»
# считает он, по своим правилам профилей, и правило это менялось между
# версиями. Замерено на v2.29.7 и v5.0.0-desktop.1 — совпали.

set -euo pipefail
cd "$(dirname "$0")/.."

COMPOSE_FILE="${COMPOSE_FILE:-docker-compose.prod.yml}"
EXAMPLE="${EXAMPLE:-.env.example}"
# Чем спрашивать. Переопределяют, когда надо перепроверить ответ другой
# версией compose: правило профилей — её правило, а не наше, и «у меня
# работает» про чужую версию не говорит ничего.
DC="${DC:-docker compose}"

red()   { printf '\033[1;31m%s\033[0m\n' "$1" >&2; }
green() { printf '\033[1;32m%s\033[0m\n' "$1"; }

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# Заглушки вместо секретов — ровно как в задаче CI «Боевой compose»:
# обязательные переменные валят разбор, а нам нужен ответ про профили.
stub_env() {  # $1 — строка COMPOSE_PROFILES или слово НЕТ
    sed -E 's/^([A-Z0-9_]+)=$/\1=ci-placeholder/' "$EXAMPLE" \
        | grep -v '^COMPOSE_PROFILES=' > "$TMP/env"
    [ "$1" = "НЕТ" ] || printf 'COMPOSE_PROFILES=%s\n' "$1" >> "$TMP/env"
}

# Какие сборки включены при таком .env. `env -u` обязателен: переменная
# оболочки у compose старше файла, и унаследованная от вызывающего она
# подменила бы ответ на вопрос, который мы задаём.
builds() {  # $1 — строка COMPOSE_PROFILES или слово НЕТ
    stub_env "$1"
    env -u COMPOSE_PROFILES $DC -f "$COMPOSE_FILE" \
        --project-directory . --env-file "$TMP/env" config --services 2>/dev/null \
        | grep '^app-' | sort | tr '\n' ' ' | sed 's/ $//'
}

# Случаи. Первый — тот, ради которого сторож написан; четвёртый — обратный
# край, и без него «починка» удалением профилей прошла бы проверку.
check() {  # $1 — что в .env, $2 — ожидание, $3 — чем это важно человеку
    local got
    got=$(builds "$1")
    if [ "$got" = "$2" ]; then
        printf '  ✓ %s → %s\n' "$3" "${got:-ничего}"
        return 0
    fi
    red "  ✗ $3: ожидались «$2», поднимутся «${got:-ничего}»"
    return 1
}

run_checks() {
    local bad=0
    check "НЕТ"        "app-blue"           "без строки COMPOSE_PROFILES поднимается прежняя сборка" || bad=1
    check ""           "app-blue"           "пустая строка — то же самое, а не «ни одной»"           || bad=1
    check "blue"       "app-blue"           "COMPOSE_PROFILES=blue"                                  || bad=1
    check "green"      "app-green"          "COMPOSE_PROFILES=green — синяя НЕ воскресает"           || bad=1
    check "blue,green" "app-blue app-green" "COMPOSE_PROFILES=blue,green — окно выкладки"            || bad=1
    return $bad
}

# --- проверка самого сторожа ------------------------------------------------
#
# Проверка, которая не краснеет на дефекте, хуже отсутствующей, и установить
# это можно только попыткой. Подделки — ровно два способа сделать неправильно:
# вернуть как было (простой ячейки) и «починить» снятием профиля (воскресающая
# сборка). Каждая обязана валить сторожа, и каждая — своим случаем.
selftest() {
    local ok=0
    echo "Самопроверка ops/builds-guard.sh"

    if COMPOSE_FILE="$COMPOSE_FILE" run_checks >/dev/null 2>&1; then
        printf '  ✓ настоящий %s проходит\n' "$COMPOSE_FILE"
    else
        red "  ✗ настоящий $COMPOSE_FILE не проходит — смотрите прогон без --selftest"; ok=1
    fi

    # Подделка 1: как было до 0110 — синяя только под своим профилем.
    sed 's/^    profiles: \[blue, ""\]$/    profiles: [blue]/' "$COMPOSE_FILE" > "$TMP/kak-bylo.yml"
    cmp -s "$COMPOSE_FILE" "$TMP/kak-bylo.yml" \
        && { red "  ✗ подделку «как было» не удалось собрать — строка профилей изменилась"; ok=1; }
    if COMPOSE_FILE="$TMP/kak-bylo.yml" run_checks >/dev/null 2>&1; then
        red "  ✗ «как было» (profiles: [blue]) обязано валить сторожа: ячейка не поднимается"; ok=1
    else
        printf '  ✓ «как было» — красное: без строки не поднимается ни одной сборки\n'
    fi

    # Подделка 2: наивная починка — снять профиль вовсе. Без строки ячейка
    # поднимется, зато погашенная синяя воскреснет при COMPOSE_PROFILES=green.
    sed 's/^    profiles: \[blue, ""\]$/    labels: [snyali-profil=da]/' "$COMPOSE_FILE" > "$TMP/bez-profilya.yml"
    if COMPOSE_FILE="$TMP/bez-profilya.yml" run_checks >/dev/null 2>&1; then
        red "  ✗ снятый профиль обязан валить сторожа: погашенная сборка воскресает"; ok=1
    else
        printf '  ✓ снятый профиль — красное: при COMPOSE_PROFILES=green поднималась бы и синяя\n'
    fi

    [ $ok = 0 ] || { red "Самопроверка не прошла"; exit 1; }
    green "Самопроверка пройдена"
}

case "${1:-}" in
    --selftest) selftest; exit 0 ;;
    "") ;;
    *) red "Непонятный аргумент: $1"; exit 2 ;;
esac

echo "Какие сборки поднимет ячейка ($COMPOSE_FILE)"
if run_checks; then
    green "Ячейка поднимается при любом из пяти .env, и погашенная сборка не воскресает"
else
    red "Правка профилей меняет то, что поднимется у клиента, — смотрите строки выше"
    exit 1
fi
