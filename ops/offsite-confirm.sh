#!/usr/bin/env bash
# Подтверждение офсайта: лежит ли НАЗВАННЫЙ файл на той стороне.
#
# Сорсится ops/backup.sh и ops/wal-archive.sh; по пути не зовётся, поэтому
# в индексе лежит 100644 — как ops/moment.sh, и это законное исключение
# из правила «новый ops/*.sh обязан быть 100755» (урок 0197).
#
# ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ (задача 0148). Оба зовущих спрашивали одинаково —
# `rclone lsf … 2>/dev/null | grep -q <файл>` — и ОТСУТСТВИЕ строки объявляли
# отсутствием файла на той стороне: «офсайт не подтверждён: shared.dump на той
# стороне нет». Пустым ответ становится не только от этого: в конфигурации
# rclone нет такой удалёнки, нет сети, нет прав, опечатка в OFFSITE_REMOTE —
# всё это даёт ту же пустоту и тот же вердикт. Человек идёт искать пропавший
# файл там, где не удалось задать вопрос, а отметка офсайта не ставится
# в обоих случаях одинаково — то есть по следам в наблюдении эти две беды
# неразличимы тоже.
#
# САМ ЗАПРОС ЖИВЁТ ЗДЕСЬ, а не у зовущего, и это защита по построению: терять
# код возврата негде, потому что ловить его зовущему не нужно. Та же форма,
# что у адреса образа в одном месте (ops/images.yml) и у единственного хука
# ui/useMounted.ts: нечего стеречь — нечего обойти.
#
# Исходов три, кодом возврата:
#   0 — спросили, файл на той стороне есть;
#   1 — спросили, файла там нет (это и есть «офсайт не уехал»);
#   2 — СПРОСИТЬ НЕ ВЫШЛО, и это не «нет файла»; причина в OFFSITE_WHY.
OFFSITE_WHY=""

offsite_confirm() {   # $1 — путь rclone, $2 — имя файла на той стороне
    local where="$1" name="$2" out rc=0 errf
    OFFSITE_WHY=""
    errf="$(mktemp)"
    out=$(rclone lsf "$where" 2>"$errf") || rc=$?
    # Первые две строки отказа в одну: `cut -c` на не-ASCII режет байты
    # на Linux и символы на macOS (урок 0085), а rclone говорит и по-русски.
    OFFSITE_WHY=$(sed -n '1,2p' "$errf" | tr '\n' ' ')
    rm -f "$errf"
    # Признак «ответ получен» — одной строкой: возврат дефекта ставится ровно
    # сюда, одной заменой, и подделке не нужно переписывать два условия
    # (урок 0198: красное от сломанной копии не говорит ни о чём).
    local asked=yes   # 0148-офсайт
    [ "$rc" = 0 ] || asked=no
    if [ "$asked" = no ]; then
        OFFSITE_WHY="rclone вышел кодом ${rc}${OFFSITE_WHY:+ — }${OFFSITE_WHY}"
        return 2
    fi
    if printf '%s\n' "$out" | grep -q "^${name}$"; then
        return 0
    fi
    OFFSITE_WHY=""
    return 1
}
