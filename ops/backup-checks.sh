#!/usr/bin/env bash
# Проверки по СЛЕДУ для ops/backup.sh и ops/basebackup.sh (задача 0237).
#
# Этот файл только сорсят — у него нет своего запуска (поэтому в индексе
# 100644, как у ops/backup-aggregates.sh и ops/offsite-confirm.sh):
#
#   . ops/backup-checks.sh
#
# ЗАЧЕМ. Обе крон-задачи снятия копий доказывали работу кодом возврата
# `pg_dump`/`pg_basebackup` и печатали числа, которые ни с чем не сверялись.
# Негодный дамп выглядит точно так же, как годный — файл на диске есть, размер
# напечатан, — и разница выясняется в аварию. Правило то же, что у 0157 и 0235:
# у операции спрашивают не «вышла ли без ошибки», а «что от неё осталось».
#
# Здесь только вопросы, без побочных действий: каждая функция возвращает 0
# или 1 и кладёт причину в одну переменную, а решает зовущий (валить прогон или
# нет). Так их можно прогнать самопроверкой на подложенных файлах без docker.

# --- Дамп: это дамп или мусор ------------------------------------------------
#
# Чем читается оглавление, задаёт зовущий: DUMP_TOC_CMD читает дамп со stdin
# и печатает `pg_restore -l`. На ячейке это `pg_restore -l` ВНУТРИ контейнера
# postgres (на хосте клиентских утилит нет и версия обязана совпадать с
# сервером); самопроверка подменяет его заглушкой.
#
# Оглавление, а не разворот: формат `custom` читается одной командой, не занимая
# ни места, ни секунды диска, а вопрос здесь «это дамп или мусор». Разворот
# делает ops/verify-backup.sh раз в неделю — это другой вопрос.
DUMP_WHY=""

dump_check() {   # $1 — файл дампа
    local file="$1" toc errf tables rc=0
    DUMP_WHY=""
    if [ ! -f "$file" ]; then
        DUMP_WHY="файла нет"
        return 1
    fi
    if [ ! -s "$file" ]; then
        DUMP_WHY="файл пуст (0 байт)"
        return 1
    fi
    errf="$(mktemp)"
    toc=$($DUMP_TOC_CMD < "$file" 2>"$errf") || rc=$?
    if [ "$rc" != 0 ]; then
        DUMP_WHY="не открывается как дамп: $(sed -n '1p' "$errf" | tr -d '\r')"
        rm -f "$errf"
        return 1
    fi
    rm -f "$errf"
    # Строка оглавления: «216; 1259 16385 TABLE s1 t owner». Считаем объявления
    # таблиц (а не данных): дамп схемы без единой таблицы — пустая схема,
    # то есть восстанавливать из него нечего.
    tables=$(printf '%s\n' "$toc" | grep -E '^[0-9]+; [0-9]+ [0-9]+ TABLE ' \
        | grep -vc ' TABLE DATA ' || true)
    if [ "${tables:-0}" -lt 1 ]; then
        DUMP_WHY="в дампе нет таблиц (оглавление открылось, объявлений TABLE — 0)"
        return 1
    fi
    DUMP_TABLES="$tables"
    return 0
}
DUMP_TABLES=0

# --- Снимки: ноль не выдаётся за успех ---------------------------------------
#
# Числа два: сколько объектов было в хранилище ДО зеркала и сколько файлов
# лежит в копии ПОСЛЕ. Копия не может быть меньше хранилища на момент до
# зеркала: зеркало идёт без --remove и только пополняет. Снимок, загруженный
# во время зеркала, в хранилище-до не входит и ложного красного не даёт —
# поэтому считаем ДО, а не после.
#
# Ноль в копии при нуле в хранилище — законная пустая ячейка; ноль в копии при
# непустом хранилище — каталог не смонтировался или путь опечатан, и это ровно
# то, чем «снимков: 0» зелёным отличалось от здоровой ячейки.
PHOTO_WHY=""

photo_check() {   # $1 — объектов в хранилище до зеркала, $2 — файлов в копии
    local source="$1" local_n="$2"
    PHOTO_WHY=""
    case "$source" in
        ''|*[!0-9]*)
            PHOTO_WHY="хранилище не ответило, сколько в нём снимков (получено «${source}») — сверить копию не с чем"
            return 1 ;;
    esac
    case "$local_n" in
        ''|*[!0-9]*)
            PHOTO_WHY="число файлов в копии не прочитано (получено «${local_n}»)"
            return 1 ;;
    esac
    if [ "$local_n" -lt "$source" ]; then
        if [ "$local_n" = 0 ]; then
            PHOTO_WHY="в копии 0 файлов при $source объектах в хранилище — каталог копии не смонтирован или путь опечатан"
        else
            PHOTO_WHY="в копии $local_n файлов, в хранилище до зеркала было $source — зеркало недокопировало"
        fi
        return 1
    fi
    return 0
}

# --- Базовая копия: нижняя граница размера -----------------------------------
#
# Граница выбрана НЕ от размера базы живого клиента (398 МБ — он растёт, и
# граница от него краснела бы на молодой ячейке), а от «копия пустой быть не
# может». Замер 15 октября 2026: пустой кластер postgres:16-alpine, поток
# `pg_basebackup -Ft -X fetch | gzip -1`, — 3 666 141 байт. Граница 1 МиБ
# в три с половиной раза ниже этого пола: ложное красное на маленькой базе
# невозможно, а «пустой файл», «обрыв на первых килобайтах» и «заголовок gzip
# без тела» отбиваются. Обрыв позже порога ловит gzip -t в самом скрипте;
# вопрос «разворачивается ли» — недельная проверка (ops/restore-pitr.sh --verify).
BASE_MIN_BYTES="${BASE_MIN_BYTES:-1048576}"
BASE_WHY=""

base_size_check() {   # $1 — размер base.tar.gz в байтах
    local bytes="$1"
    BASE_WHY=""
    case "$bytes" in
        ''|*[!0-9]*) BASE_WHY="размер копии не прочитан (получено «${bytes}»)"; return 1 ;;
    esac
    if [ "$bytes" -lt "$BASE_MIN_BYTES" ]; then
        BASE_WHY="base.tar.gz — $bytes байт, меньше $BASE_MIN_BYTES: даже пустой кластер даёт около 3,5 МБ"
        return 1
    fi
    return 0
}

# --- Уборка архива WAL: граница утверждается, а не печатается ----------------
#
# Имена сегментов — 24 шестнадцатеричных знака ФИКСИРОВАННОЙ ширины, поэтому
# сравнение строк в локали C совпадает с порядком в журнале. Файлы истории
# (`.history`, `.backup`) в счёт не идут: pg_archivecleanup с `-x .gz` их
# трогает по своим правилам, а границу о них никто не спрашивает.
WAL_WHY=""

wal_names() {   # $1 — каталог архива; имена сегментов без .gz, по порядку
    find "$1" -maxdepth 1 -type f -name '*.gz' 2>/dev/null \
        | sed 's|.*/||; s/\.gz$//' | grep -E '^[0-9A-F]{24}$' | LC_ALL=C sort || true
}

wal_lt() {   # $1 < $2 по порядку журнала
    [ "$1" != "$2" ] && [ "$(printf '%s\n%s\n' "$1" "$2" | LC_ALL=C sort | head -1)" = "$1" ]
}

# ДО уборки: граница не должна быть выше начала НИ ОДНОЙ хранимой копии.
# Выше — значит убрать сегмент, без которого копия не накатывается, то есть
# снести точку возврата всех арендаторов ячейки. Проверка стоит до удаления,
# потому что после неё возвращать нечего.
wal_boundary_check() {   # $1 — граница, остальное — START_WAL хранимых копий
    local boundary="$1" s
    shift
    WAL_WHY=""
    if ! printf '%s' "$boundary" | grep -Eq '^[0-9A-F]{24}$'; then
        WAL_WHY="граница уборки «${boundary}» не похожа на имя сегмента WAL (24 знака 0-9A-F)"
        return 1
    fi
    for s in "$@"; do
        if wal_lt "$s" "$boundary"; then
            WAL_WHY="граница $boundary выше начала хранимой копии ($s) — уборка снесла бы сегменты, без которых она не накатывается"
            return 1
        fi
    done
    return 0
}

# ПОСЛЕ уборки: из списков, снятых до и после. Утверждаются три вещи:
#   1) всё, что было не ниже границы, на месте — иначе убрано нужное;
#   2) ниже границы не осталось ничего — иначе уборка не сработала и архив
#      растёт до конца диска (а кончившийся диск останавливает запись в базу);
#   3) архив не опустел.
# Сравнение числа «было/стало» (AFTER <= BEFORE) не взято намеренно: пока идёт
# уборка, база кладёт новый сегмент, и после может быть законно БОЛЬШЕ. Факты
# о множествах такой гонки не боятся.
wal_after_check() {   # $1 — граница, $2 — имена до (по строке), $3 — имена после
    local boundary="$1" before="$2" after="$3" lost left n
    WAL_WHY=""
    lost=$(comm -23 \
        <(printf '%s\n' "$before" | grep -E '^[0-9A-F]{24}$' | LC_ALL=C sort \
            | LC_ALL=C awk -v b="$boundary" '$0 >= b') \
        <(printf '%s\n' "$after" | grep -E '^[0-9A-F]{24}$' | LC_ALL=C sort) || true)
    if [ -n "$lost" ]; then
        n=$(printf '%s\n' "$lost" | grep -c .)
        WAL_WHY="убрано нужное: $n сегм. не ниже границы $boundary (первый $(printf '%s\n' "$lost" | head -1))"
        return 1
    fi
    left=$(printf '%s\n' "$after" | grep -E '^[0-9A-F]{24}$' | LC_ALL=C sort \
        | LC_ALL=C awk -v b="$boundary" '$0 < b' || true)
    if [ -n "$left" ]; then
        n=$(printf '%s\n' "$left" | grep -c .)
        WAL_WHY="уборка не сработала: осталось $n сегм. ниже границы $boundary (первый $(printf '%s\n' "$left" | head -1))"
        return 1
    fi
    if [ -n "$(printf '%s' "$before" | tr -d '[:space:]')" ] \
        && [ -z "$(printf '%s' "$after" | tr -d '[:space:]')" ]; then
        WAL_WHY="архив WAL после уборки пуст — а до неё в нём были сегменты"
        return 1
    fi
    return 0
}
