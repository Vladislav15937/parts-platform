#!/usr/bin/env bash
# Момент возврата: разбор «когда» с ОБЯЗАТЕЛЬНЫМ часовым поясом.
#
# Общий код двух входов — ops/restore-pitr.sh (--to) и ops/wal-archive.sh
# (--chain). «К какому моменту возвращаемся» и «до какого момента вернуться
# можно» обязаны понимать введённое одинаково: разойдясь, они разойдутся
# молча, и сторож разрешит возврат не туда.
#
# ПОЧЕМУ ПОЯС ОБЯЗАТЕЛЕН. Архив WAL живёт в UTC, а время, которое называет
# человек, — чьё-то местное: он прочитал его в журнале контейнера (UTC),
# услышал по телефону от клиента (MSK) или взял с часов своей машины. Разница
# в три часа не видна НИЧЕМ: восстановление проходит успешно, кластер
# поднимается, данные на месте — просто не те. Проверить результат оператору
# нечем, а стоит ошибка либо потерянной смены, либо возвращённой поломки.
# Раньше момент молча толковался в поясе машины, и на этом ошибся не оператор
# в четыре утра, а разбор задачи 0083 — человек, читавший код целиком
# и специально проверявший работу (задача 0087).
#
# Поэтому пояс не угадывается, а называется. Пять видов, все равноправные:
#
#   2026-09-12 13:59:00 MSK              — как называет клиент
#   2026-09-12 13:59:00 +03:00           — смещением
#   2026-09-12 10:59:00 UTC              — как пишет журнал контейнера
#   2026-09-12 13:59:00 local            — пояс ЭТОЙ машины, названный явно
#   2026-09-12 13:59:00 Asia/Novosibirsk — любой пояс из базы
#
# «local» здесь — не умолчание, а такой же явный ответ, как остальные четыре:
# разница в том, что его написали, а не подставили за человека.
#
# И разобранное печатается ОБОИМИ представлениями (moment_report): «13:59 MSK
# = 10:59 UTC», плюс третья строка, если пояс машины отличается от названного.
# Эхо здесь не вежливость — это единственное место, где ошибку в поясе видно
# до того, как она стала успешным возвратом не туда.
#
# ПОРТИРУЕМОСТЬ. Хост ячейки — Linux (bash 5, GNU date), машина разработчика —
# macOS (bash 3.2, BSD date), и разбирают аварию там, где сидят. Отсюда: ни
# ${x,,}, ни mapfile, ни `date -d` в одиночку. Зато `TZ=… date` понимают обе,
# и разбор в названном поясе идёт именно так, а не таблицей сокращений внутри
# date — она у GNU и BSD разная.

# Значения последнего разобранного момента. Инициализированы: скрипты работают
# под `set -u`.
MOMENT_EPOCH=0      # сам момент, секунды от эпохи
MOMENT_TZ="-"       # пояс: имя из базы, «-» (пояс машины) или «@СМЕЩЕНИЕ»
MOMENT_LABEL=""     # как назвать пояс человеку
MOMENT_RAW=""       # что ввели, дословно
MOMENT_FLAG="--to"  # каким флагом ввели: сообщение об отказе называет его

_m_date() {
    local tz="$1"; shift
    if [ "$tz" = "-" ]; then
        date "$@"
    else
        TZ="$tz" date "$@"
    fi
}

# Разбор и печать: сначала GNU, следом BSD. Порядок именно такой — на macOS
# `date -d` это флаг перевода на летнее время, он падает с «illegal option»
# и уводит во вторую ветку; на Linux первая отвечает сразу.
_m_to_epoch() {
    _m_date "$1" -d "$2" +%s 2>/dev/null \
        || _m_date "$1" -j -f '%Y-%m-%d %H:%M:%S' "$2" +%s 2>/dev/null
}
_m_from_epoch() {
    _m_date "$1" -d "@$2" "$3" 2>/dev/null \
        || _m_date "$1" -r "$2" "$3" 2>/dev/null
}

_m_offset_text() {          # секунды -> «+03:00»
    local s="$1" sign="+"
    if [ "$s" -lt 0 ]; then sign="-"; s=$(( 0 - s )); fi
    printf '%s%02d:%02d\n' "$sign" "$(( s / 3600 ))" "$(( s % 3600 / 60 ))"
}
_m_offset_at() {            # смещение пояса В ЭТОТ момент, а не сейчас: зимой
    local z                 # и летом оно разное, и возврат бывает через границу
    z=$(_m_from_epoch "$1" "$2" '+%z')
    printf '%s:%s\n' "${z:0:3}" "${z:3:2}"
}

moment_offset()     { _m_offset_at "$MOMENT_TZ" "$MOMENT_EPOCH"; }
moment_utc_text()   { _m_from_epoch UTC "$MOMENT_EPOCH" '+%Y-%m-%d %H:%M:%S'; }
moment_local_text() {       # момент так, как его назвали
    case "$MOMENT_TZ" in
        # Смещение числом пояса не называет: печатаем UTC, сдвинутый на него.
        @*) _m_from_epoch UTC "$(( MOMENT_EPOCH + ${MOMENT_TZ#@} ))" '+%Y-%m-%d %H:%M:%S' ;;
        *)  _m_from_epoch "$MOMENT_TZ" "$MOMENT_EPOCH" '+%Y-%m-%d %H:%M:%S' ;;
    esac
}

# Строка для recovery_target_time. Смещение в ней обязательно: без него
# Postgres толкует момент в поясе СЕРВЕРА (в контейнере это UTC), и «вернуться
# к 13:59» молча становится «к 16:59».
moment_pg() {
    case "$MOMENT_TZ" in
        @*) printf '%s%s\n' "$(moment_local_text)" "$(_m_offset_text "${MOMENT_TZ#@}")" ;;
        *)  printf '%s%s\n' "$(moment_local_text)" "$(moment_offset)" ;;
    esac
}

# Эхо разобранного: оба представления и предупреждение о чужом поясе машины.
moment_report() {
    local off here_off here_text
    off=$(moment_offset)
    here_off=$(_m_offset_at - "$MOMENT_EPOCH")
    here_text=$(_m_from_epoch - "$MOMENT_EPOCH" '+%Y-%m-%d %H:%M:%S')
    printf '    введено:  %s\n' "$MOMENT_RAW"
    printf '    это:      %s %s (%s)  =  %s UTC\n' \
        "$(moment_local_text)" "$MOMENT_LABEL" "$off" "$(moment_utc_text)"
    if [ "$here_off" = "$off" ]; then
        printf '    пояс этой машины тот же (%s)\n' "$here_off"
    else
        # Та самая ошибка, ради которой всё написано: человек называет время
        # клиента, а смотрит на часы машины — и не замечает, что они разные.
        printf '    на ЭТОЙ машине это %s (%s) — пояс машины ДРУГОЙ, сверьте\n' \
            "$here_text" "$here_off"
    fi
}

_m_here_offset_now() { _m_offset_at - "$(date +%s)"; }

# База часовых поясов. Без неё `TZ=Europe/Moscow date` МОЛЧА считает время
# в UTC — и «13:59 MSK» становится «13:59 UTC», то есть ровно та ошибка,
# от которой написан весь файл. Голый образ Linux (ubuntu:24.04) приезжает
# без tzdata, и обнаружилось это прогоном в нём, а не рассуждением.
_m_zone_missing() {
    local tz="$1"
    [ ! -f "/usr/share/zoneinfo/$tz" ]
}
_m_no_tzdb() {
    cat >&2 <<EOF
ОШИБКА: в системе нет базы часовых поясов — пояса «${1}» не существует
        в /usr/share/zoneinfo.

        Без неё TZ=${1} молча считается за UTC, то есть возврат ушёл бы
        не туда и отчитался успехом. Поставьте tzdata (apt install tzdata)
        либо назовите момент смещением: '+03:00' или 'UTC'.
EOF
}

_m_no_zone() {
    local dt="$1"
    cat >&2 <<EOF
ОШИБКА: в моменте «${dt}» не указан часовой пояс.

        Архив WAL живёт в UTC, а названное время — чьё-то местное: журнал
        контейнера пишет UTC, клиент по телефону называет своё, часы этой
        машины показывают третье. Ошибка в три часа не видна ничем —
        восстановление пройдёт успешно и вернёт НЕ ТОТ момент.

        Напишите пояс явно, любым из видов:
            $MOMENT_FLAG '$dt MSK'               время клиента, Москва
            $MOMENT_FLAG '$dt +03:00'            смещением
            $MOMENT_FLAG '$dt UTC'               время из журнала контейнера
            $MOMENT_FLAG '$dt local'             пояс ЭТОЙ машины (сейчас $(_m_here_offset_now))
            $MOMENT_FLAG '$dt Asia/Novosibirsk'  любой пояс из базы
EOF
}

_m_bad_shape() {
    cat >&2 <<EOF
ОШИБКА: не разобрал момент «${1}».

        Нужно «ГГГГ-ММ-ДД ЧЧ:ММ[:СС] ПОЯС», например:
            $MOMENT_FLAG '2026-09-12 13:59:00 MSK'
        Дата обязательна целиком: «13:59» без неё — это ещё одна догадка
        за человека, и ошибиться в ней на сутки так же легко, как в поясе
        на три часа.
EOF
}

_m_bad_zone() {
    cat >&2 <<EOF
ОШИБКА: не знаю часового пояса «${1}».

        Понимаю: MSK, UTC (он же Z), local (пояс этой машины, сейчас
        $(_m_here_offset_now)), смещение числом (+03:00, +03, +0300)
        и любое имя из базы поясов (Asia/Novosibirsk, Europe/Moscow).
EOF
}

# Разбирает момент. Успех — 0 и заполненные MOMENT_*; отказ — 1 и объяснение
# словами в stderr.
moment_parse() {
    local raw="$1"
    MOMENT_RAW="$raw"

    # Пробелы по краям — без внешних утилит: функцию зовут и из cron.
    while [ "${raw# }" != "$raw" ]; do raw="${raw# }"; done
    while [ "${raw% }" != "$raw" ]; do raw="${raw% }"; done

    # Регулярное выражение отдельной переменной: в bash 3.2 записанное
    # в [[ ]] кавычками оно сравнивается как строка.
    local re='^([0-9]{4}-[0-9]{2}-[0-9]{2})[ T]+([0-9]{2}:[0-9]{2})(:[0-9]{2})?[ ]*(.*)$'
    if ! [[ "$raw" =~ $re ]]; then
        _m_bad_shape "$raw"
        return 1
    fi
    local d="${BASH_REMATCH[1]}" hm="${BASH_REMATCH[2]}"
    local sec="${BASH_REMATCH[3]}" zone="${BASH_REMATCH[4]}"
    [ -n "$sec" ] || sec=":00"
    local dt="$d $hm$sec"

    local up
    up=$(printf '%s' "$zone" | tr 'a-z' 'A-Z')
    case "$up" in
        "")
            _m_no_zone "$dt"; return 1 ;;
        Z|UTC|GMT|UT)
            MOMENT_TZ="UTC"; MOMENT_LABEL="UTC" ;;
        LOCAL|МЕСТНОЕ|местное)
            MOMENT_TZ="-";   MOMENT_LABEL="пояс этой машины" ;;
        MSK|МСК|мск)
            # Единственное сокращение в таблице, и намеренно: клиенты
            # в Москве, а прочие сокращения у GNU и BSD толкуются по-разному
            # либо не толкуются вовсе. Всё остальное — именем из базы поясов
            # или смещением, они однозначны везде.
            if _m_zone_missing "Europe/Moscow"; then
                _m_no_tzdb "Europe/Moscow"; return 1
            fi
            MOMENT_TZ="Europe/Moscow"; MOMENT_LABEL="MSK" ;;
        [+-][0-9][0-9]|[+-][0-9][0-9][0-9][0-9]|[+-][0-9][0-9]:[0-9][0-9])
            local sign hh mm off
            sign="${up:0:1}"; hh="${up:1:2}"; mm="${up:3}"; mm="${mm#:}"
            [ -n "$mm" ] || mm="00"
            # 10# обязательно: «08» и «09» без него читаются восьмеричными
            # и валят арифметику.
            off=$(( 10#$hh * 3600 + 10#$mm * 60 ))
            if [ "$sign" = "-" ]; then off=$(( 0 - off )); fi
            MOMENT_TZ="@$off"; MOMENT_LABEL=$(_m_offset_text "$off") ;;
        */*)
            # Неверно названный пояс BSD и GNU date считают UTC МОЛЧА: опечатка
            # в «Europe/Moscov» дала бы ровно ту ошибку, от которой вся эта
            # проверка и заведена. Поэтому спрашиваем базу поясов файлом.
            if _m_zone_missing "$zone"; then
                if [ -d /usr/share/zoneinfo ]; then
                    _m_bad_zone "$zone"
                else
                    _m_no_tzdb "$zone"
                fi
                return 1
            fi
            MOMENT_TZ="$zone"; MOMENT_LABEL="$zone" ;;
        *)
            _m_bad_zone "$zone"; return 1 ;;
    esac

    local epoch
    case "$MOMENT_TZ" in
        @*) local base
            base=$(_m_to_epoch UTC "$dt")
            [ -n "$base" ] || { _m_bad_shape "$raw"; return 1; }
            epoch=$(( base - ${MOMENT_TZ#@} )) ;;
        *)  epoch=$(_m_to_epoch "$MOMENT_TZ" "$dt") ;;
    esac
    [ -n "$epoch" ] || { _m_bad_shape "$raw"; return 1; }
    MOMENT_EPOCH="$epoch"

    # Обратная сверка: «2026-02-30» BSD date не отвергает, а переносит на 2 марта
    # — то есть отдаёт МОЛЧА другой момент. Это та же болезнь, что и пояс
    # по умолчанию, и лечится так же: разобранное сверяется с введённым.
    if [ "$(moment_local_text)" != "$dt" ]; then
        cat >&2 <<EOF
ОШИБКА: такого момента нет: «${dt}» — это $(moment_local_text).
        Проверьте число и время.
EOF
        return 1
    fi
    return 0
}

# --- Самопроверка -----------------------------------------------------------
#
# Проверка, не краснеющая на дефекте, хуже отсутствующей, и установить это
# можно только попыткой. Здесь это особенно верно: разбор момента ошибается
# ТИХО — неправильно понятое время выглядит как правильно понятое.
moment_selftest() {
    local bad=0 mark=0
    _t_ok()   { printf '\033[1;32m    %s\033[0m\n' "$1"; }
    # Счётчик, а не флаг: с флагом второй упавший случай не отличался бы
    # от первого, и «получилось» печаталось бы рядом с красным. Поймано
    # прогоном в голом ubuntu — то есть не рассуждением.
    _t_bad()  { printf '\033[1;31m    САМОПРОВЕРКА: %s\033[0m\n' "$1"; bad=$(( bad + 1 )); }
    # Закрывает случай и открывает следующий. Зелёная строка рядом с красной —
    # худшее, что может сказать самопроверка: по ней читают, что случай пройден.
    # Поэтому «получилось» печатается, только если с конца прошлого случая
    # ничего не упало.
    _t_done() { if [ "$bad" = "$mark" ]; then _t_ok "$1"; fi; mark=$bad; }
    # Разбор, который обязан получиться: отказ здесь — тоже находка, а не
    # повод уронить самопроверку молча на set -e.
    _t_parse() { moment_parse "$1" > /dev/null 2>&1 || _t_bad "«${1}» не разобран"; }

    # Считаем в поясе, отличном от UTC, ВСЕГДА: на CI машина живёт в UTC,
    # и там разница между «местным» и «UTC» равна нулю — то есть именно тот
    # случай, ради которого задача заведена, на CI не проверялся бы вовсе.
    export TZ="Asia/Novosibirsk"      # +07, без перевода часов

    # Но без базы поясов этот TZ молча станет UTC, и вся самопроверка
    # превратится в проверку UTC против UTC — зелёную и ничего не значащую.
    # Поэтому условие проверяется первым и называется прямо.
    if _m_zone_missing "$TZ" || _m_zone_missing "Europe/Moscow"; then
        printf '\033[1;31m    САМОПРОВЕРКА: нет базы часовых поясов (/usr/share/zoneinfo)\033[0m\n'
        printf '    Без неё TZ молча считается за UTC, и проверять нечего: поставьте tzdata.\n'
        unset TZ
        return 1
    fi

    # Эталон: один и тот же момент, с которым сверяются все написания.
    local utc_epoch
    _t_parse '2026-09-12 10:59:00 UTC'
    utc_epoch=$MOMENT_EPOCH

    local form
    for form in \
        '2026-09-12 13:59:00 MSK' \
        '2026-09-12 13:59:00 +03:00' \
        '2026-09-12 13:59:00 +0300' \
        '2026-09-12 13:59:00 +03' \
        '2026-09-12 13:59 MSK' \
        '2026-09-12T13:59:00 Europe/Moscow' \
        '2026-09-12 10:59:00 Z'
    do
        if moment_parse "$form" > /dev/null 2>&1 && [ "$MOMENT_EPOCH" = "$utc_epoch" ]; then
            :
        else
            _t_bad "«${form}» разобран не тем моментом: $MOMENT_EPOCH против $utc_epoch"
        fi
    done
    _t_done 'семь написаний одного момента дают один момент'

    # Пояс машины — отдельный ответ, и он ОТЛИЧАЕТСЯ от UTC: ради этого
    # различия всё и написано.
    _t_parse '2026-09-12 17:59:00 local'
    [ "$MOMENT_EPOCH" = "$utc_epoch" ] \
        || _t_bad "local (+07) разобран не тем моментом: $MOMENT_EPOCH против $utc_epoch"
    _t_parse '2026-09-12 13:59:00 local'
    [ "$MOMENT_EPOCH" != "$utc_epoch" ] \
        || _t_bad 'пояс машины совпал с UTC — самопроверка идёт не в том поясе'
    _t_done 'пояс машины разбирается как свой, а не как UTC'

    # Эхо: оба представления обязаны быть названы. Это единственное место,
    # где человек видит ошибку в поясе до того, как она стала возвратом не туда.
    local out
    _t_parse '2026-09-12 13:59:00 MSK'
    out=$(moment_report)
    case "$out" in
        *'13:59:00 MSK'*) : ;;
        *) _t_bad "эхо не называет введённого: $out" ;;
    esac
    case "$out" in
        *'10:59:00 UTC'*) : ;;
        *) _t_bad "эхо не называет UTC: $out" ;;
    esac
    case "$out" in
        *'ДРУГОЙ'*) : ;;
        *) _t_bad "эхо молчит о чужом поясе машины: $out" ;;
    esac
    _t_done 'эхо называет оба представления и чужой пояс машины'

    # Строка для Postgres обязана нести смещение — без него сервер толкует
    # её в своём поясе.
    _t_parse '2026-09-12 13:59:00 MSK'
    [ "$(moment_pg)" = '2026-09-12 13:59:00+03:00' ] \
        || _t_bad "строка для Postgres без смещения: $(moment_pg)"
    _t_parse '2026-09-12 10:59:00 UTC'
    [ "$(moment_pg)" = '2026-09-12 10:59:00+00:00' ] \
        || _t_bad "строка для Postgres без смещения: $(moment_pg)"
    _t_done 'строка для Postgres несёт смещение'

    # Отказы. Каждый обязан быть словами, а не пустотой: молчащий отказ
    # в аварию читается как «инструмент сломан», и его обходят.
    local rc
    set +e
    out=$(moment_parse '2026-09-12 13:59:00' 2>&1); rc=$?
    set -e
    [ "$rc" != 0 ] || _t_bad 'момент без пояса принят'
    case "$out" in
        *'не указан часовой пояс'*) : ;;
        *) _t_bad "отказ без пояса не объяснён словами: $out" ;;
    esac
    case "$out" in
        *MSK*UTC*) : ;;
        *) _t_bad "отказ не показывает, что писать: $out" ;;
    esac
    _t_done 'момент без пояса отбит словами и с примерами'

    set +e
    out=$(moment_parse '2026-09-12 13:59:00 ЧАС' 2>&1); rc=$?
    set -e
    [ "$rc" != 0 ] || _t_bad 'незнакомый пояс принят'
    _t_done 'незнакомый пояс отбит'

    # Опечатка в имени пояса — тот же тихий сдвиг: date молча считает такой
    # пояс за UTC.
    set +e
    out=$(moment_parse '2026-09-12 13:59:00 Europe/Moscov' 2>&1); rc=$?
    set -e
    [ "$rc" != 0 ] || _t_bad 'опечатка в имени пояса принята (молча стала бы UTC)'
    _t_done 'опечатка в имени пояса отбита'

    set +e
    out=$(moment_parse '13:59 MSK' 2>&1); rc=$?
    set -e
    [ "$rc" != 0 ] || _t_bad 'момент без даты принят'
    _t_done 'момент без даты отбит'

    set +e
    out=$(moment_parse '2026-02-30 13:59:00 MSK' 2>&1); rc=$?
    set -e
    [ "$rc" != 0 ] || _t_bad 'несуществующее число принято (тихо стало бы 2 марта)'
    _t_done 'несуществующее число отбито'

    unset TZ
    [ "$bad" = 0 ] || return 1
    return 0
}
