#!/usr/bin/env sh
# Файл окружения ячейки: разрешение пути и три состояния. ОДНО МЕСТО НА ПРОЕКТ.
#
#   . ops/env-file.sh                  # после cd в корень репозитория
#   env_file_source "$ENV_FILE" || exit 1
#
# ЗАЧЕМ ОБЩЕЕ МЕСТО. Правило тут ровно одно — «абсолютный путь берём как есть,
# относительный разрешаем от корня репозитория», — и записанное в каждом
# скрипте отдельно оно разъезжается молча. К 2 октября 2026 копий было четыре
# (задачи 0243 и 0250): рабочая в ops/migrate-tenants.sh, своя в
# ops/control-plane.sh, своя в ops/create-roles.sh и ТРИ ПОЛОМАННЫХ — у шести
# самопроверок выкладки, у дымового прогона и у сторожа канала тревог.
# Правило, переписанное руками в пятый раз, ошибётся в пятый раз.
#
# ДЕФЕКТ, КОТОРЫЙ ЗДЕСЬ ПОЧИНЕН РАЗ И НАВСЕГДА. Проверка шла по
# НЕПРЕФИКСОВАННОМУ пути (`[ -f "$ENV_FILE" ]`), а чтение — по пути с «./»
# впереди (`. "./$ENV_FILE"`), при том что скрипт выше уже сделал cd в корень
# репозитория. Поэтому ENV_FILE=/srv/parts/.env — то есть ровно так, как файл
# лежит на ячейке, — проверку ПРОХОДИЛ и источался как «.//srv/parts/.env».
# Под `set -e` это шумное падение; а у трёх мест задачи 0250 стоит `set -uo
# pipefail` БЕЗ `-e`, поэтому отказ чтения печатал одну строку в stderr
# и прогон продолжался с умолчаниями — как если бы файла не было вовсе.
#
# ПОЧЕМУ «./» ВООБЩЕ НУЖНО. Точка-источник без слэша ищет файл в PATH, а не
# в текущем каталоге: `. .env` в строгом sh открывает не тот файл, который
# человек имел в виду, либо не открывает ничего. Значит простому имени «./»
# необходимо, а пути со слэшем — вредно.
#
# ТОЧКА ОТСЧЁТА ОТНОСИТЕЛЬНОГО ПУТИ — КОРЕНЬ РЕПОЗИТОРИЯ, и это не оплошность.
# Умолчание «.env» — файл ячейки рядом с docker-compose.prod.yml, и запуск
# из ops/ обязан находить его, как находил раньше. Сменить точку отсчёта
# значило бы сломать работающий путь ради неработающего (довод записан
# в задаче 0243 и перепроверен 0250).
#
# ЧИСТЫЙ sh, А НЕ bash: сторож канала тревог работает в контейнере
# curlimages/curl, где bash'а нет вовсе, и compose зовёт его через /bin/sh.
# Отсюда ни ${x,,}, ни mapfile, ни [[ ]].

# Путь, которым файл можно открыть: абсолютный как есть, остальное от «./».
resolve_env_file() {
    case "$1" in
        /*) printf '%s\n' "$1" ;;
        *)  printf './%s\n' "$1" ;;
    esac
}

# Три состояния, и сводить их нельзя: «файла нет», «файл есть, а прочитать
# не удалось» и «файл прочитан». Прежние редакции сводили первые два
# к третьему с пустыми переменными — и человек читал «нет такой переменной
# в файле» про файл, в котором она записана.
#
# Проверяется -e, а не -f, НАМЕРЕННО: docker на месте пропавшего файла
# bind-mount'а создаёт пустой КАТАЛОГ (задача 0101), и такой каталог обязан
# стать «есть, а прочитать не удалось», а не «файла нет». Под -f он тоже
# не прошёл бы, но ответ был бы не про то.
env_file_state() {
    src=$(resolve_env_file "$1")
    if [ ! -e "$src" ]; then printf 'нет\n';         return 0; fi
    if [ ! -r "$src" ]; then printf 'не-читается\n'; return 0; fi
    printf 'годен\n'
}

# Совет человеку: откуда считается относительный путь и как назвать свой файл.
# Отдельной функцией потому, что эту строку печатают все отказы, и разойдясь,
# они начали бы учить разному.
env_file_hint() {
    printf 'Относительный путь разрешается от корня репозитория (%s), а не от каталога,\n' "$(pwd)"
    printf 'где вы стоите; абсолютный берётся как есть. Назовите файл явно: ENV_FILE=/путь/к/.env\n'
}

# Прочитать файл окружения в ТЕКУЩУЮ оболочку. Коды: 0 — прочитан или законно
# отсутствует, 1 — есть, а прочитать не удалось (сказано словами в stderr).
#
# ОТСУТСТВИЕ ФАЙЛА — ЗАКОННОЕ СОСТОЯНИЕ, и это не поблажка: самопроверки,
# контейнеры и прогон CI нацеливают скрипты переменными снаружи, и файла
# ячейки там нет вовсе. А вот «файл есть, и он не прочитался» законным
# состоянием не является ни у одного из зовущих: дальше пошли бы умолчания
# вместо настроек ячейки, то есть ответ про чужую машину.
#
# Сорсится в текущую оболочку с `set -a`, как было у всех зовущих до этого:
# подоболочка, читающая одну переменную, отменила бы остальные молча.
# ЗНАЧИТ .env СТАРШЕ ОКРУЖЕНИЯ, переданного вызывающим, — поведение прежнее
# и на нём стоит случай 10 самопроверки сторожа канала.
env_file_source() {  # путь к файлу окружения
    env_file_path=$(resolve_env_file "$1")
    case "$(env_file_state "$1")" in
        годен)
            set -a
            # shellcheck source=/dev/null
            if . "$env_file_path"; then
                set +a
                ENV_FILE_READ=да
                return 0
            fi
            set +a
            printf 'Файл окружения %s есть, а прочитать его не удалось.\n' "$env_file_path" >&2
            printf '    Это НЕ «переменной в нём нет»: проверьте сам файл (кавычки, перевод строки).\n' >&2
            ENV_FILE_READ=нет
            return 1 ;;
        не-читается)
            printf 'Файл окружения есть, а прочитать его нечем: %s — нет прав на чтение.\n' "$env_file_path" >&2
            printf '    Это НЕ «переменной в нём нет» — она там может быть записана, её просто не видно.\n' >&2
            printf '    Кем читать: тем пользователем, которому принадлежит ячейка (.env лежит с правами 600).\n' >&2
            ENV_FILE_READ=нет
            return 1 ;;
        *)
            # Файла нет — нацелили переменными снаружи. Молчим: строка про
            # отсутствующий .env на каждом запуске из контейнера и из прогона
            # приучила бы не читать вывод.
            ENV_FILE_READ=нет
            return 0 ;;
    esac
}
