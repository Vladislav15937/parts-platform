#!/usr/bin/env bash
# Пять самопроверок выкладки — то, без чего переключение трафика
# не считается удачным.
#
#   ops/deploy-checks.sh              # прогнать все пять на сборке под трафиком
#   ops/deploy-checks.sh --selftest   # проверка самих проверок, без ячейки
#
# Делались они глазами (docs/pilot-server.md, «Повседневные команды»), то есть
# не делались в половине случаев. Каждая отвечает на свой вопрос, и каждая
# КРАСИТ ВЫКЛАДКУ: молча зелёный деплой, после которого прайс пуст, хуже
# упавшего.
#
#   1. приложение отвечает   — GET / через терминатор, 200. Не «порт открыт»:
#      путь тот же, которым ходит человек, и он же доказывает, что трафик
#      действительно переключился на новую сборку.
#   2. журналы защищены      — рабочая роль не может править stock_movement,
#      audit_log и customer_account_entry. Запуск без переменных окружения
#      поднимает приложение владельцем схем, всё работает одинаково,
#      и разница видна в тот день, когда журнал предъявляют как доказательство.
#   3. отставших схем ноль   — код, рассчитывающий на миграцию, которой
#      у арендаторов нет, поднимается молча, а первой про это узнаёт площадка,
#      забравшая пустой прайс.
#   4. прайс не пуст         — число <offer> в выгрузке не упало до нуля.
#      Пустой прайс площадка читает как «снять всё», и это худший исход
#      выкладки: объявления пропадают у всех разом, а вернуть их стоит суток.
#   5. сценарий доезжает     — дымовой прогон (ops/smoke-run.sh): вход
#      продавцом, поиск детали по номеру, карточка, а на ИФТ и ПСИ ещё
#      и продажа целиком — приёмка, сделка с резервом, оплата, выдача
#      и уборка за собой. Первые четыре отвечают на вопрос «поднялось ли»,
#      и выкладка может быть зелёной при сломанной продаже: сторож
#      размонтирования убил экран пересчёта целиком и сутки прожил в main,
#      не тронув ни одной из них.
#
# И ШЕСТАЯ СТРОКА — СООБЩЕНИЕ, А НЕ ПРОВЕРКА: включён ли управляющий контур
# (ops/control-plane.sh, задача 0197). Выкладку она не красит намеренно —
# во время подключения клиента контур включён законно, и красное здесь
# остановило бы ровно ту работу, ради которой он включён. Обязан ли включённый
# контур красить выкладку — вопрос владельцу продукта, названный в задаче.
# Стоит она тут потому, что это единственное место, где состояние ячейки
# читает человек по расписанию: секрет на боевой ячейке простоял включённым
# трое суток, и спросить о нём было некому.
#
# ЧЕМ СПРАШИВАЕТСЯ. Проверки 2 и 3 не читают лог: он ротируется, и через сутки
# ответа в нём нет вовсе. Обе спрашивают готовность ВЫКЛАДЫВАЕМОЙ сборки
# (/actuator/readiness, задача 0078) — той самой, что сейчас обслуживает людей.
#
# И У ТРЕТЬЕЙ ЭТО РАЗМЕН, НАЗВАННЫЙ ВСЛУХ (задача 0202, 27 сентября 2026).
# До неё она звала ops/migrate-tenants.sh, то есть спрашивала каждую схему
# у самого Liquibase (deep=true) — но через управляющий контур, секретом
# провижининга, который docs/onboarding.md (раздел 2) велит выключать сразу
# после подключения. Выполненное правило красило следующую выкладку: скрипт
# падает на пустом APP_PROVISIONING_TOKEN раньше, чем успевает что-нибудь
# спросить. 27 сентября это остановило выкладку на ПРОМ, продержав запись
# замороженной 37 секунд у живого клиента, — при схемах, которые были
# на версии.
#
# ЧЕГО ГОТОВНОСТЬ НЕ ЗАМЕЧАЕТ — два состояния, и знать их надо оба:
#   * схему, в которую лазили руками: ответ идёт по отметке schema_version
#     в реестре, а отметка врёт — объекта нет, а версия в ней нужная;
#   * схему ВПЕРЕДИ версии сборки: ответ несимметричен намеренно («впереди —
#     норма», TenantMigrations.lag()), и такую схему он не назовёт по имени,
#     только посчитает.
#
# ОБА ЭТИХ СОСТОЯНИЯ ЛОВИТ ШАГ 3 ТОЙ ЖЕ ВЫКЛАДКИ — ops/schema-sync.sh без
# --apply: он спрашивает каждую схему у Liquibase (режим CHECK ничего
# не пишет), сверяет на РАВЕНСТВО с версией образа, называет по имени и схему
# впереди, и секрета не требует. Значит глубокая проверка из выкладки
# не ушла — она стоит раньше, до подъёма новой сборки, и её код возврата
# выкладку так же красит. Третья самопроверка после переключения трафика
# подтверждает то же глазами сборки, которая теперь под трафиком.
# ЗАПУСКАЯ ЭТОТ СКРИПТ РУКАМИ, помните: глубокий вопрос — ops/schema-sync.sh,
# а не эта проверка.
#
# Второго места, знающего, как спросить «кто отстал», от этого не появилось:
# готовность у нас уже спрашивает проверка 2, а глубокий вопрос остался
# у ops/schema-sync.sh — оба инструмента были и раньше.
#
# КУДА НАЦЕЛЕНО. Ни одного зашитого адреса: стендов три (ИФТ, ПСИ, ПРОМ),
# и все на разных машинах. Умолчания — боевая ячейка на этой же машине,
# переменные ниже переносят проверку на любую другую.
#
#   DEPLOY_BUILD=app-green     какую сборку спрашивать (по умолчанию — под трафиком)
#   DEPLOY_HTTP_URL=…          что открыть проверкой 1 (по умолчанию https://$APP_DOMAIN/)
#   DEPLOY_FEED_URLS="u1 u2"   постоянные ссылки на прайсы, которые забирает площадка
#   DEPLOY_CURL=host           ходить с хоста, а не изнутри контейнера терминатора
#   DEPLOY_STAND=ift|psi|prom  какой это стенд: на ПРОМ пятая ничего не пишет

set -uo pipefail

# Путь к самому скрипту, снятый ДО смены каталога: его читает проверка
# итоговой строки (случай 8 самопроверки), а относительный $0 после `cd`
# уже не разрешается.
SELF="$(cd "$(dirname "$0")" && pwd)/$(basename "$0")"

cd "$(dirname "$0")/.."

COMPOSE="${COMPOSE:-docker compose -f docker-compose.prod.yml}"
ENV_FILE="${ENV_FILE:-.env}"
TIMEOUT="${DEPLOY_CHECK_TIMEOUT:-20}"

# Подменяется в самопроверке дымовой прогон: проверять надо разбор его
# ответа, а не гонять сценарий внутри самопроверки второй раз.
SMOKE="${SMOKE_RUN:-ops/smoke-run.sh}"
# И тем же — признак управляющего контура: сам он проверяет себя отдельно
# (ops/control-plane.sh --selftest, та же задача CI), здесь проверяется, что
# его ответ доезжает до человека и НЕ красит выкладку.
CONTROL_PLANE="${CONTROL_PLANE_SH:-ops/control-plane.sh}"

red()   { printf '\033[1;31m%s\033[0m\n' "$1" >&2; }
green() { printf '\033[1;32m%s\033[0m\n' "$1"; }

FAILED=""
ok()  { printf '  \033[1;32m✓\033[0m %s\n' "$1"; }
bad() { printf '  \033[1;31m✗ %s\033[0m\n' "$1" >&2; FAILED="$FAILED$2, "; }

# ─────────────────────────── как ходить за ответом ───────────────────────────
#
# Изнутри контейнера терминатора: порты сборок ячейки наружу не опубликованы,
# у caddy есть curl, и он в той же сети. С хоста ходят там, где проверку
# нацелили на чужую машину (DEPLOY_CURL=host).
fetch() {
    if [ "${DEPLOY_CURL:-}" = host ]; then
        curl -sS -m "$TIMEOUT" "$@" 2>&1
    else
        $COMPOSE exec -T caddy curl -sS -m "$TIMEOUT" "$@" 2>&1
    fi
}

# ──────────────────────────── 1. приложение отвечает ─────────────────────────
#
# Разбор отделён от запроса намеренно: краснеть проверка обязана на дефекте,
# а проверить это можно только подсунув ей ответ. Ниже так у всех пяти.
verdict_http() {  # код ответа
    case "$1" in
        200) ok "приложение отвечает 200"; return 0 ;;
        000|"") bad "приложение не отвечает вовсе (ответа нет)" "приложение отвечает"; return 1 ;;
        *) bad "приложение отвечает $1, а не 200" "приложение отвечает"; return 1 ;;
    esac
}

check_http() {
    local url code
    url="${DEPLOY_HTTP_URL:-}"
    if [ -z "$url" ]; then
        # Через терминатор и по настоящему домену: так ходит человек, и так
        # видно, что трафик переключился. Адрес разрешаем сами — снаружи
        # домен может указывать ещё куда угодно, а проверяем мы ЭТУ машину.
        [ -n "${APP_DOMAIN:-}" ] || {
            bad "проверка 1 не нацелена: нет ни DEPLOY_HTTP_URL, ни APP_DOMAIN в $ENV_FILE" \
                "приложение отвечает"
            return 1
        }
        code=$(fetch -o /dev/null -w '%{http_code}' \
            --resolve "$APP_DOMAIN:443:127.0.0.1" "https://$APP_DOMAIN/")
    else
        code=$(fetch -o /dev/null -w '%{http_code}' "$url")
    fi
    # curl при отказе печатает свою строку вместо кода — оставляем только код.
    verdict_http "$(printf '%s' "$code" | tr -dc '0-9' | tail -c 3)"
}

# ─────────────────────────── 2. журналы защищены ─────────────────────────────
#
# Ответ готовности (задача 0078) несёт проверку journals — ту же, что пишет
# в лог «Журналы защищены». Спрашиваем её, а не лог: лог ротируется, и через
# сутки ответа в нём нет вовсе.
verdict_journals() {  # тело ответа /actuator/readiness
    local answer verdict
    answer="$1"
    verdict=$(printf '%s' "$answer" | python3 -c "
import json, sys
raw = sys.stdin.read()
try:
    body = json.loads(raw)
except ValueError:
    # Сам ответ, а не «не разобралось»: на месте готовности обычно лежит
    # либо отказ curl'а, либо страница ошибки терминатора — и по ней сразу
    # видно, чинить приложение или сеть.
    sys.exit('вместо ответа готовности пришло: ' + ' '.join(raw.split())[:160])
checks = body.get('checks')
if not isinstance(checks, list):
    sys.exit('в ответе готовности нет списка checks')
for check in checks:
    if check.get('check') == 'journals':
        print(('да' if check.get('ok') else 'нет') + ' ' + str(check.get('detail', '')))
        break
else:
    sys.exit('в ответе готовности нет проверки journals')
" 2>&1)
    case "$verdict" in
        "да "*) ok "журналы защищены: ${verdict#да }"; return 0 ;;
        "нет "*) bad "журналы НЕ защищены: ${verdict#нет }" "журналы защищены"; return 1 ;;
        *) bad "защиту журналов спросить не вышло: $verdict" "журналы защищены"; return 1 ;;
    esac
}

check_journals() {
    verdict_journals "$(fetch "http://$BUILD:8080/actuator/readiness")"
}

# ─────────────────────────── 3. отставших схем ноль ──────────────────────────
#
# Своего запроса тут нет: ответ несёт готовность выкладываемой сборки, ту же,
# что спрашивает проверка 2. Что она замечает, а что нет — в шапке, «ЧЕМ
# СПРАШИВАЕТСЯ»: размен на отметку в реестре сделан осознанно, а глубокий
# вопрос стоит шагом 3 выкладки (ops/schema-sync.sh). Второго места,
# знающего, как спросить «кто отстал», заводить нельзя — оно разъехалось бы
# с первым.
#
# ТРИ ИСХОДА, И РАЗЛИЧИМЫ ОНИ КОДОМ ВОЗВРАТА, а не только словами (образец —
# tools/head-green.sh, задача 0194):
#
#   0 — схем позади поставляемой версии нет;
#   1 — есть отставшие: код, рассчитывающий на новую схему, выкладывать нельзя;
#   2 — СПРОСИТЬ НЕ ВЫШЛО: ответа нет, он не разобрался, в нём нет проверки
#       schemas, либо сама готовность говорит «версии схем не проверены».
#
# До 27 сентября 2026 второго и третьего не различало ничто: любой ненулевой
# код печатался как «схемы отстали (или спросить не вышло)» — то есть проверка
# утверждала ХУДШЕЕ ИЗ ДВУХ, а истинным бывало «я не спросил». В тот день это
# стоило разбора живой выкладки на ПРОМ: схемы были на версии (их привёл шаг 3
# той же выкладки), а проверка объявила их отставшими, потому что упёрлась
# в выключенный управляющий контур.
#
# Красит выкладку и второе, и третье — проверка, не выполнившаяся и не
# сказавшая об этом, хуже отсутствующей (тот же довод, что в check_feeds).
# Но след у них РАЗНЫЙ: человек, разбирающий красную выкладку, по итоговой
# строке обязан понять, накатывать ему схемы или чинить доступ к ответу.
#
# И РАЗЛИЧАЕТ ИХ МАШИННЫЙ ПРИЗНАК, А НЕ СЛОВО (задача 0204). Поле known
# в ответе готовности — «удалось ли узнать состояние», ReadinessEndpoint.Check —
# единственный договор между Java и этим скриптом. До 0204 исход узнавался
# по вхождению фразы «не проверены» в текст, и пиннящего теста у фразы не было
# ни с одной стороны: переименование её в Java — скажем, в единственное число,
# как у соседних проверок ТОГО ЖЕ ответа («Общая схема catalog не проверена»,
# «Защита журналов не проверена», «Запись не проверена») — молча возвращало
# дефект 0202. Проверено живым прогоном на настоящих строках: нынешняя фраза
# давала код 2, та же в единственном числе — код 1 и слова «СХЕМЫ ОТСТАЛИ»,
# то есть проверка снова утверждала ХУДШЕЕ ИЗ ДВУХ. Косметическое приведение
# формулировок к одному виду ломало выкладку.
#
# ФРАЗА ОСТАЛАСЬ ЗАПАСНЫМ ПУТЁМ и только для сборок старше признака: база
# может быть новее кода, то есть откат приложения законен (задача 0112), —
# а у откаченной сборки фраза заморожена в её jar и разойтись не может.
# Значит переименование слова в нынешней Java исхода больше не меняет вовсе.
#
# ДЕРЖИТСЯ ДОГОВОР С ДВУХ СТОРОН: ReadinessContractTest читает ЭТОТ файл,
# достаёт из него имя поля и имя проверки и требует их у самого ответа
# готовности — краснеет и Java, перестав отдавать поле, и этот скрипт,
# вернувшийся к узнаванию исхода по слову.
verdict_schemas() {  # тело ответа /actuator/readiness
    local answer verdict
    answer="$1"
    verdict=$(printf '%s' "$answer" | python3 -c "
import json, sys
raw = sys.stdin.read()
try:
    body = json.loads(raw)
except ValueError:
    sys.exit('вместо ответа готовности пришло: ' + ' '.join(raw.split())[:160])
checks = body.get('checks')
if not isinstance(checks, list):
    sys.exit('в ответе готовности нет списка checks')
for check in checks:
    if check.get('check') == 'schemas':
        detail = str(check.get('detail', ''))
        # Машинный признак исхода. Его отсутствие в ответе — это сборка
        # старше признака (откат приложения законен), и только для неё
        # исход узнаётся по фразе.
        known = check.get('known')
        if check.get('ok'):
            print('да ' + detail)
        elif known is False or (known is None and 'не проверены' in detail):
            # Готовность САМА признаётся, что не спросила: реестра нет, база
            # не отвечает (ReadinessEndpoint.schemas()). Это не «схемы
            # отстали», и выдать одно за другое — ровно дефект 0202.
            print('нескажу ' + detail)
        else:
            print('нет ' + detail)
        break
else:
    sys.exit('в ответе готовности нет проверки schemas')
" 2>&1)
    case "$verdict" in
        # «По отметке реестра» стоит в самой строке, а не отдельной
        # припиской: постоянную приписку приучаются не читать, а обещание
        # проверки и её поведение расходиться не должны.
        "да "*) ok "отставших схем нет по отметке реестра: ${verdict#да }"; return 0 ;;
        "нет "*) bad "СХЕМЫ ОТСТАЛИ: ${verdict#нет }" "отставших схем ноль"; return 1 ;;
        "нескажу "*)
            bad "СПРОСИТЬ НЕ ВЫШЛО — неизвестно, на версии схемы или нет: ${verdict#нескажу }" \
                "схемы спросить не вышло"
            return 2 ;;
        *)
            bad "СПРОСИТЬ НЕ ВЫШЛО — неизвестно, на версии схемы или нет: ${verdict}" \
                "схемы спросить не вышло"
            return 2 ;;
    esac
}

check_schemas() {
    verdict_schemas "$(fetch "http://$BUILD:8080/actuator/readiness")"
}

# ───────────────────────────── 4. прайс не пуст ──────────────────────────────
verdict_feed() {  # ссылка, тело прайса
    local offers
    offers=$(printf '%s' "$2" | grep -o '<offer>' | wc -l | tr -d ' ')
    if [ "${offers:-0}" -gt 0 ]; then
        ok "прайс не пуст: объявлений $offers ($1)"
        return 0
    fi
    # «Пустой» и «не приехал» — разные беды, и лечатся они по-разному.
    # Первое — отбор выгрузки: файл целый, товаров в нём нет, площадка
    # снимает объявления. Второе — сеть или упавшее приложение. Красит
    # выкладку и то, и другое, но человеку нельзя говорить «прайс пуст»
    # там, где прайса не было вовсе.
    case "$2" in
        *"<offers"*)
            bad "прайс ПУСТ: ни одного <offer> ($1). Площадка читает это как «снять всё»" \
                "прайс не пуст" ;;
        *)
            bad "прайс не приехал ($1): $(printf '%s' "$2" | tr '\n' ' ' | cut -c1-160)" \
                "прайс не пуст" ;;
    esac
    return 1
}

check_feeds() {
    local url body rc=0
    if [ -z "${DEPLOY_FEED_URLS:-}" ]; then
        # Не «пропускаем»: худший исход выкладки — пустой прайс, и проверка,
        # молча не выполняющаяся, хуже отсутствующей. Стенду без выгрузок
        # это говорят вслух, значением «нет».
        bad "прайс проверить нечем: не задан DEPLOY_FEED_URLS (постоянные ссылки выгрузок). Стенду без выгрузок поставьте DEPLOY_FEED_URLS=нет" \
            "прайс не пуст"
        return 1
    fi
    if [ "$DEPLOY_FEED_URLS" = "нет" ]; then
        printf '  \033[1;33m—\033[0m прайсов на этом стенде нет (DEPLOY_FEED_URLS=нет) — проверять нечего\n'
        return 0
    fi
    for url in $DEPLOY_FEED_URLS; do
        body=$(fetch "$url")
        verdict_feed "$url" "$body" || rc=1
    done
    return $rc
}

# ─────────────────── 5. сценарий доезжает до конца ───────────────────────────
#
# Своего сценария здесь нет: его ведёт ops/smoke-run.sh — он же знает, на каком
# стенде можно писать, а на каком нельзя. Здесь только вердикт по его коду
# возврата, ровно как у проверки 3 с ops/migrate-tenants.sh: второе место,
# умеющее продавать по HTTP, разошлось бы с первым.
verdict_smoke() {  # код возврата дымового прогона, его вывод
    # Вывод печатается целиком и всегда, а не только при отказе: это
    # единственное место выкладки, где видно, что человек сможет продать.
    # Десять строк в логе против получаса разбора «а что именно проверяли».
    printf '%s\n' "$2" | sed 's/^/    /'
    if [ "$1" = 0 ]; then
        ok "сценарий доезжает до конца"
        return 0
    fi
    # Последняя непустая строка без раскраски: у ops/smoke-run.sh это перечень
    # упавших шагов — то, ради чего проверка и заведена.
    bad "сценарий не доезжает: $(printf '%s\n' "$2" \
            | sed $'s/\033\\[[0-9;]*m//g' | grep -v '^[[:space:]]*$' | tail -n 1)" \
        "сценарий продажи"
    return 1
}

check_smoke() {
    local out code
    if [ -n "${DEPLOY_WRITE_FROZEN:-}" ]; then
        # Внутри окна выкладки (задача 0145). Запись в базе заморожена
        # целиком — ALTER DATABASE схем не различает, — поэтому пишущие шаги
        # здесь отбиты у всех одинаково, включая свою тестовую компанию
        # прогона. Продажу в этом случае проводит сама выкладка, ДО заморозки
        # копии и до переключения трафика; здесь остаётся то, что внутри окна
        # законно и чего больше нигде не видно: чтение через терминатор,
        # на уже переключённой сборке и с сессией, добытой до заморозки.
        printf '  \033[1;33m—\033[0m запись заморожена: продажу прогнали до окна, здесь только чтение\n'
        out=$(bash "$SMOKE" --read-only 2>&1)
        code=$?
    else
        out=$(bash "$SMOKE" 2>&1)
        code=$?
    fi
    verdict_smoke "$code" "$out"
}

# ────────── 6. состояние управляющего контура (сообщение, не проверка) ───────
#
# Своего запроса здесь нет: спрашивает ops/control-plane.sh — он же знает, как
# сверить ответ сборки с .env и чем секрет отзывается. Второе место, знающее
# это, разошлось бы с первым, а цена расхождения — человек, считающий контур
# закрытым.
#
# Код возврата намеренно НЕ красит выкладку и НЕ попадает в FAILED.
report_control_plane() {
    local out code
    out=$(CONTROL_PLANE_BUILD="$BUILD" bash "$CONTROL_PLANE" 2>&1); code=$?
    printf '%s\n' "$out"
    if [ "$code" != 0 ]; then
        printf '  \033[1;33m—\033[0m состояние контура выкладку не красит: во время подключения\n'
        printf '      клиента он включён законно. Красить ли — вопрос владельцу (задача 0197).\n'
    fi
    return 0
}

# ───────── итог выкладки: число в последней строке против напечатанного ──────
#
# Расхождение «шесть напечатанных строк против „пяти“ в итоге» поймало ПРОБНОЕ
# СЛИЯНИЕ (разбор PR #290), а не самопроверка: случай ниже есть у каждой
# check_* и у каждого verdict_*, а у последней строки — той, по которой человек
# решает, гасить ли старую сборку, — не было ни одного. Допиши седьмую
# печатающую проверку, и итог разойдётся снова, а скажет об этом опять человек.
#
# Считается по самому файлу: сколько строк печатает блок запуска, из них
# сколько КРАСЯТ выкладку (check_*) и сколько только сообщают (report_*).
# Ни ячейки, ни docker для этого не нужно — расхождение видно из текста.
word_for() {  # число → слово, которым его называет итоговая строка
    case "$1" in
        1) printf 'одна' ;;   2) printf 'две' ;;     3) printf 'три' ;;
        4) printf 'четыре' ;; 5) printf 'пять' ;;    6) printf 'шесть' ;;
        7) printf 'семь' ;;   8) printf 'восемь' ;;  9) printf 'девять' ;;
        *) printf '' ;;
    esac
}

verdict_summary() {  # сколько красят выкладку, сколько только сообщают, итоговая строка
    local gating="$1" reports="$2" line="$3" want
    if [ "$gating" = 0 ]; then
        bad "блок запуска не зовёт ни одной проверки: выкладка зеленеет, не спросив ячейку" \
            "итог выкладки"
        return 1
    fi
    want=$(word_for "$gating")
    if [ -z "$want" ]; then
        bad "красят выкладку ${gating} проверок, а слова для этого числа в word_for нет — итог назвать нечем" \
            "итог выкладки"
        return 1
    fi
    case "$line" in
        *"$want"*) ;;
        *) bad "итог говорит не про ${gating} самопроверок (ждали «${want}»), а краснят выкладку ровно они: ${line}" \
               "итог выкладки"
           return 1 ;;
    esac
    # Напечатанное сообщение, не названное в итоге (и обещанное, которого нет):
    # человек читает N+1 строк, а итог отвечает про N — и не понять, о чём
    # он умолчал. Это и есть находка PR #290, только теперь с этой стороны.
    case "${reports}:${line}" in
        0:*сообщени*)
            bad "итог обещает сообщение, а печатать его некому: строк report_* в блоке запуска нет" \
                "итог выкладки"
            return 1 ;;
        0:*) ;;
        *:*сообщени*) ;;
        *) bad "напечатанных сообщений ${reports}, а итог про них молчит: ${line}" \
               "итог выкладки"
           return 1 ;;
    esac
    ok "итог сходится с напечатанным: краснят выкладку ${want}, сообщений ${reports}"
    return 0
}

check_summary() {  # файл со скриптом (по умолчанию — этот)
    local file="${1:-$SELF}" block gating reports line
    block=$(awk 'index($0, "Самопроверки выкладки:") { inside = 1; next }
                 index($0, "if [ -n \"$FAILED\" ]") == 1 { inside = 0 }
                 inside' "$file")
    gating=$(printf '%s\n' "$block" | grep -c '^check_[a-z_]*$')
    reports=$(printf '%s\n' "$block" | grep -c '^report_[a-z_]*$')
    # Итог — последняя строка, которую скрипт печатает зелёным: та самая,
    # по которой человек решает, гасить ли старую сборку.
    line=$(grep '^green "' "$file" | tail -n 1)
    verdict_summary "$(printf '%s' "$gating" | tr -dc '0-9')" \
        "$(printf '%s' "$reports" | tr -dc '0-9')" "$line"
}

# ────────────────────────────── самопроверка ─────────────────────────────────
#
# Без ячейки и без docker: каждой проверке подсовывается ответ — годный
# и сломанный, — и сверяется, что на сломанном она краснеет и НАЗЫВАЕТ,
# что именно упало. Живой прогон это дополняет, а не заменяет: там ломают
# по-настоящему.
selftest() {
    local bad_count=0
    local out

    expect() {  # имя, ожидаемый исход (ok|fail), имя проверки в списке упавших
        local name="$1" want="$2" mark="$3"
        shift 3
        FAILED=""
        # Через файл, а не `out=$(...)`: подстановка команды — это подоболочка,
        # и список упавших, который проверка дописывает в FAILED, до нас бы
        # не доехал. Самопроверка при этом молча зеленела бы на половине
        # случаев — ровно тот изъян, который она и должна ловить.
        local tmp="${TMPDIR:-/tmp}/deploy-checks-selftest.$$"
        "$@" > "$tmp" 2>&1; local code=$?
        out=$(cat "$tmp"); rm -f "$tmp"
        if [ "$want" = ok ] && [ $code != 0 ]; then
            red "  ✗ $name: ожидалось «проходит», а проверка покраснела: $out"
            bad_count=$((bad_count + 1)); return
        fi
        if [ "$want" = fail ]; then
            if [ $code = 0 ]; then
                red "  ✗ $name: ожидалось «краснеет», а проверка промолчала: $out"
                bad_count=$((bad_count + 1)); return
            fi
            case "$FAILED" in
                *"$mark"*) ;;
                # В фигурных скобках намеренно: bash 3.2 (macOS) берёт байты
                # «»» в имя переменной, и «$mark» становится неизвестным
                # именем — падение самопроверки на своём же сообщении.
                *) red "  ✗ $name: покраснела, но не назвала «${mark}» (назвала «${FAILED}»)"
                   bad_count=$((bad_count + 1)); return ;;
            esac
        fi
        printf '  ✓ %s\n' "$name"
    }

    echo "Самопроверка ops/deploy-checks.sh"

    # 1. Приложение отвечает.
    expect "1. 200 — проходит" ok "" verdict_http 200
    expect "1. 502 краснеет и названа" fail "приложение отвечает" verdict_http 502
    expect "1. нет ответа краснеет" fail "приложение отвечает" verdict_http 000
    expect "1. 200 с приставкой не принимается" fail "приложение отвечает" verdict_http 2001

    # 2. Журналы защищены. Сломанный ответ — тот самый, что приходит с ячейки,
    #    поднятой одной ролью: приложение работает, а журналы изменяемы.
    local ready broken nojournals
    ready='{"ready":true,"checks":[{"check":"database","ok":true,"detail":"База отвечает"},
        {"check":"journals","ok":true,"detail":"Журналы защищены: роль partsflow_app не может править"}]}'
    broken='{"ready":false,"checks":[{"check":"journals","ok":false,
        "detail":"Журналы правятся прямым SQL: audit_log доступны на UPDATE роли app"}]}'
    nojournals='{"ready":true,"checks":[{"check":"database","ok":true,"detail":"База отвечает"}]}'
    expect "2. защищены — проходит" ok "" verdict_journals "$ready"
    expect "2. правятся прямым SQL краснеет" fail "журналы защищены" verdict_journals "$broken"
    expect "2. ответ без journals краснеет" fail "журналы защищены" verdict_journals "$nojournals"
    expect "2. не-JSON краснеет" fail "журналы защищены" verdict_journals "502 Bad Gateway"

    # 3. Отставшие схемы. Спрашивается та же готовность, что и проверкой 2
    #    (задача 0202): управляющий контур и его секрет для этого больше
    #    не нужны. Ответы — настоящие строки ReadinessEndpoint.schemas().
    local schemas_ok schemas_ahead schemas_behind schemas_unknown
    schemas_ok='{"ready":true,"checks":[{"check":"schemas","ok":true,
        "detail":"Схем позади версии 138/tenant-096-part-number нет (арендаторов 3)"}]}'
    schemas_ahead='{"ready":true,"checks":[{"check":"schemas","ok":true,
        "detail":"Схем позади версии 138/tenant-096 нет; впереди 1 из 3 — это норма между накатом и подъёмом новой сборки"}]}'
    schemas_behind='{"ready":false,"checks":[{"check":"schemas","ok":false,
        "detail":"Схемы арендаторов позади версии 138/tenant-096: 2 из 3 (t_000042, t_000106)"}]}'
    schemas_unknown='{"ready":false,"checks":[{"check":"schemas","ok":false,
        "detail":"Версии схем арендаторов не проверены: отношение public.tenant_registry не существует"}]}'
    expect "3. ноль отставших — проходит" ok "" verdict_schemas "$schemas_ok"
    expect "3. схема впереди — норма, проходит" ok "" verdict_schemas "$schemas_ahead"
    expect "3. отставшие краснеют" fail "отставших схем ноль" verdict_schemas "$schemas_behind"

    # 3. И ТРЕТИЙ ИСХОД, которого до 27 сентября 2026 не было вовсе: спросить
    #    не удалось. Тогда это был упавший на секрете ops/migrate-tenants.sh;
    #    теперь — готовность, которая сама говорит «не проверены», ответ без
    #    проверки schemas и ответ, который не разобрался. След у всех свой:
    #    человек, читающий «схемы отстали» при схемах на версии, чинит не то.
    expect "3. готовность сама не спросила — свой след" fail "схемы спросить не вышло" \
        verdict_schemas "$schemas_unknown"
    expect "3. ответ без schemas — СПРОСИТЬ НЕ ВЫШЛО" fail "схемы спросить не вышло" \
        verdict_schemas "$nojournals"
    expect "3. не-JSON — СПРОСИТЬ НЕ ВЫШЛО" fail "схемы спросить не вышло" \
        verdict_schemas "502 Bad Gateway"

    # 3. И ГЛАВНОЕ: исход решает ПРИЗНАК, а не слово (задача 0204). У ответов
    #    ниже поле known стоит, а фраза переименована в единственное число —
    #    ровно та косметика, которая до 0204 молча возвращала дефект 0202.
    #    Ответы — настоящие строки ReadinessEndpoint с настоящим полем.
    local schemas_ok_flag schemas_behind_flag schemas_unknown_flag
    schemas_ok_flag='{"ready":true,"checks":[{"check":"schemas","ok":true,"known":true,
        "detail":"Схем позади версии 138/tenant-096 нет (арендаторов 3)"}]}'
    schemas_behind_flag='{"ready":false,"checks":[{"check":"schemas","ok":false,"known":true,
        "detail":"Схемы арендаторов позади версии 138/tenant-096: 2 из 3 (t_000042, t_000106). Приведите их к версии образа: ops/schema-sync.sh --apply"}]}'
    schemas_unknown_flag='{"ready":false,"checks":[{"check":"schemas","ok":false,"known":false,
        "detail":"Версия схем арендаторов НЕ ПРОВЕРЕНА: отношение public.tenant_registry не существует"}]}'
    expect "3. признак: ноль отставших — проходит" ok "" verdict_schemas "$schemas_ok_flag"
    expect "3. признак: отставшие краснеют" fail "отставших схем ноль" \
        verdict_schemas "$schemas_behind_flag"
    expect "3. признак: «спросить не вышло» при ПЕРЕИМЕНОВАННОЙ фразе — свой след" \
        fail "схемы спросить не вышло" verdict_schemas "$schemas_unknown_flag"

    # 3. Слова, а не только след: по этой строке решают, накатывать схемы или
    #    чинить доступ. Формулировки «отстали (или спросить не вышло)»
    #    не должно остаться ни одной — она утверждает худшее из двух.
    FAILED=""
    out=$( { verdict_schemas "$schemas_behind"; } 2>&1 )
    case "$out" in
        *"СХЕМЫ ОТСТАЛИ"*)
            case "$out" in
                *"НЕ ВЫШЛО"*)
                    red "  ✗ 3. отставшие названы ещё и «не вышло» — прежнее слияние состояний"
                    bad_count=$((bad_count + 1)) ;;
                *) printf '  ✓ 3. отставшие названы отставшими и только\n' ;;
            esac ;;
        *) red "  ✗ 3. отставание не названо словом: ${out}"; bad_count=$((bad_count + 1)) ;;
    esac
    FAILED=""
    out=$( { verdict_schemas "$schemas_unknown"; } 2>&1 )
    case "$out" in
        *"НЕ ВЫШЛО"*)
            case "$out" in
                *ОТСТАЛИ*)
                    red "  ✗ 3. «спросить не вышло» утверждает отставание — это и есть дефект 0202"
                    bad_count=$((bad_count + 1)) ;;
                *) printf '  ✓ 3. «спросить не вышло» отставания не утверждает\n' ;;
            esac ;;
        *) red "  ✗ 3. «спросить не вышло» не названо словами: ${out}"; bad_count=$((bad_count + 1)) ;;
    esac
    FAILED=""

    # 3. И кодом возврата — иначе различие живёт только в строке, а по коду
    #    зовущий по-прежнему не отличит «накатите схемы» от «я не спросил».
    ( verdict_schemas "$schemas_ok" ) >/dev/null 2>&1; c_ok=$?
    ( verdict_schemas "$schemas_behind" ) >/dev/null 2>&1; c_behind=$?
    ( verdict_schemas "$schemas_unknown" ) >/dev/null 2>&1; c_unknown=$?
    FAILED=""
    if [ "$c_ok" != "$c_behind" ] && [ "$c_ok" != "$c_unknown" ] \
        && [ "$c_behind" != "$c_unknown" ]; then
        printf '  ✓ 3. три исхода различимы кодом возврата (%s / %s / %s)\n' \
            "$c_ok" "$c_behind" "$c_unknown"
    else
        red "  ✗ 3. исходы не различимы кодом: нет=${c_ok} отстали=${c_behind} не-спросили=${c_unknown}"
        bad_count=$((bad_count + 1))
    fi

    # 3. И признак даёт РОВНО ТЕ ЖЕ три кода, что фраза: иначе «исход не зависит
    #    от слова» выполнялось бы наполовину — по признаку выходил бы свой набор
    #    исходов, и зовущий отличал бы их иначе, чем у прежних сборок.
    ( verdict_schemas "$schemas_ok_flag" ) >/dev/null 2>&1; f_ok=$?
    ( verdict_schemas "$schemas_behind_flag" ) >/dev/null 2>&1; f_behind=$?
    ( verdict_schemas "$schemas_unknown_flag" ) >/dev/null 2>&1; f_unknown=$?
    FAILED=""
    if [ "$f_ok" = "$c_ok" ] && [ "$f_behind" = "$c_behind" ] \
        && [ "$f_unknown" = "$c_unknown" ]; then
        printf '  ✓ 3. признак даёт те же три исхода, что и фраза (%s / %s / %s)\n' \
            "$f_ok" "$f_behind" "$f_unknown"
    else
        red "  ✗ 3. по признаку исходы другие: нет=${f_ok} отстали=${f_behind} не-спросили=${f_unknown} (по фразе ${c_ok} / ${c_behind} / ${c_unknown})"
        bad_count=$((bad_count + 1))
    fi

    # 4. Прайс. «Пустой» — это не ошибка сети: файл приезжает целым и годным,
    #    в нём просто ноль объявлений, и именно так площадка снимает всё.
    expect "4. три объявления — проходит" ok "" verdict_feed "https://п/прайс.xml" \
        '<offers><offer><id>1</id></offer><offer/><offer></offer></offers>'
    expect "4. пустой прайс краснеет" fail "прайс не пуст" verdict_feed "https://п/прайс.xml" \
        '<?xml version="1.0"?><catalog><offers></offers></catalog>'
    expect "4. отказ вместо прайса краснеет" fail "прайс не пуст" verdict_feed \
        "https://п/прайс.xml" 'curl: (7) Failed to connect'

    # 5. Ненацеленная проверка прайса — отказ, а не тишина. Это ровно тот
    #    случай, ради которого проверка и написана: не настроив ссылку,
    #    выкладку зеленят, не посмотрев в прайс ни разу.
    FAILED=""
    if (DEPLOY_FEED_URLS= check_feeds >/dev/null 2>&1); then
        red "  ✗ 4. без DEPLOY_FEED_URLS проверка обязана краснеть"
        bad_count=$((bad_count + 1))
    else
        printf '  ✓ 4. без DEPLOY_FEED_URLS — отказ\n'
    fi
    FAILED=""
    if (DEPLOY_FEED_URLS=нет check_feeds >/dev/null 2>&1); then
        printf '  ✓ 4. DEPLOY_FEED_URLS=нет — сказано вслух и пропущено\n'
    else
        red "  ✗ 4. стенд без выгрузок обязан проходить при DEPLOY_FEED_URLS=нет"
        bad_count=$((bad_count + 1))
    fi

    # 6. Обвязка проверок, а не только их разбор. Тело check_http,
    #    check_journals и check_schemas можно было заменить на `return 0`,
    #    и самопроверка оставалась зелёной: подсовывали ответ прямо в
    #    verdict_*, минуя то, что этот ответ добывает. То есть нацеливание —
    #    ровно то, чем проверка отличается от заглушки, — не проверялось
    #    ничем, и выкладка зеленела бы, не спросив ячейку ни разу.
    #    Ячейка для этого не нужна: подменяются `fetch` и скрипт опроса схем,
    #    а обвязка проходится целиком, от нацеливания до вердикта.
    local real_fetch stub
    real_fetch=$(declare -f fetch)
    # BUILD присваивается уже после самопроверки, а check_journals его читает
    # при `set -u`: без этого обвязка упала бы не на том, что проверяют.
    BUILD="app-green"
    STUB_ANSWER=""
    # Аргументы запоминаются В ФАЙЛ, а не в переменную: ответ добывается
    # подстановкой команды — $(fetch …), — то есть в ПОДОБОЛОЧКЕ, и присвоенное
    # там до нас не доезжает. Проверка нацеливания читала бы пустую строку
    # и краснела на исправном коде; поймано ею же. Тот же приём, что
    # у аргументов дымового прогона ниже.
    FETCH_ARGS_FILE="${TMPDIR:-/tmp}/deploy-checks-fetch.$$"
    : > "$FETCH_ARGS_FILE"
    fetch() { printf '%s\n' "$*" > "$FETCH_ARGS_FILE"; printf '%s' "$STUB_ANSWER"; }

    DEPLOY_HTTP_URL="https://стенд/"
    STUB_ANSWER="200"
    expect "1. обвязка: ответ 200 доезжает до вердикта" ok "" check_http
    STUB_ANSWER="502"
    expect "1. обвязка: 502 доезжает и краснеет" fail "приложение отвечает" check_http
    unset DEPLOY_HTTP_URL
    APP_DOMAIN=""
    expect "1. обвязка: ненацеленная проверка — отказ" fail "приложение отвечает" check_http

    STUB_ANSWER="$ready"
    expect "2. обвязка: готовность доезжает до вердикта" ok "" check_journals
    STUB_ANSWER="$broken"
    expect "2. обвязка: незащищённые журналы доезжают и краснеют" \
        fail "журналы защищены" check_journals

    STUB_ANSWER="$schemas_ok"
    expect "3. обвязка: готовность доезжает до вердикта" ok "" check_schemas
    STUB_ANSWER="$schemas_behind"
    expect "3. обвязка: отставшие доезжают и краснеют" \
        fail "отставших схем ноль" check_schemas
    # Ответа нет вовсе — то самое состояние, которое до 0202 печаталось
    # как «схемы отстали».
    STUB_ANSWER=""
    expect "3. обвязка: пустой ответ — СПРОСИТЬ НЕ ВЫШЛО" \
        fail "схемы спросить не вышло" check_schemas

    # И КОГО СПРАШИВАЮТ: ответ обязан браться у ВЫКЛАДЫВАЕМОЙ сборки. Проверка,
    # ушедшая к соседней, ответила бы про чужую пару кода и схемы — молча
    # и с зелёным исходом (та же ловушка, из-за которой дымовой прогон ходит
    # прямо в сборку, задача 0145). Спрашивается это у АРГУМЕНТОВ запроса:
    # подмены ответа тут мало, она про разбор, а не про нацеливание.
    STUB_ANSWER="$schemas_ok"
    : > "$FETCH_ARGS_FILE"
    FAILED=""
    check_schemas >/dev/null 2>&1
    asked=$(cat "$FETCH_ARGS_FILE")
    case "$asked" in
        *"$BUILD"*readiness*)
            printf '  ✓ 3. обвязка: спрашивается готовность выкладываемой сборки\n' ;;
        *) red "  ✗ 3. обвязка: спросили не ту сборку или не готовность: ${asked}"
           bad_count=$((bad_count + 1)) ;;
    esac
    FAILED=""

    # 5. Дымовой прогон. Сам сценарий проверяет себя сам
    #    (ops/smoke-run.sh --selftest, та же задача CI); здесь — что его отказ
    #    доезжает до выкладки и НАЗЫВАЕТ шаг, а не теряется по дороге.
    expect "5. прогон доехал — проходит" ok "" \
        verdict_smoke 0 "  ✓ выдача закрыла сделку и списала остаток
Дымовой прогон пройден: сценарий доезжает до конца"
    expect "5. сломанный шаг краснеет и назван" fail "сценарий продажи" \
        verdict_smoke 1 "  ✗ сделка оформлена, а деталь не отложена: свободный остаток 1
Дымовой прогон не прошёл: оформление сделки"

    local real_smoke="$SMOKE"
    stub="${TMPDIR:-/tmp}/deploy-checks-smoke.$$"
    printf '#!/usr/bin/env bash\necho "Дымовой прогон пройден"\nexit 0\n' > "$stub"
    SMOKE="$stub"
    expect "5. обвязка: пройденный прогон доезжает до вердикта" ok "" check_smoke
    printf '#!/usr/bin/env bash\necho "Дымовой прогон не прошёл: выдача"\nexit 1\n' > "$stub"
    expect "5. обвязка: непройденный доезжает и краснеет" fail "сценарий продажи" check_smoke

    # 5. И главное — С ЧЕМ прогон зовут внутри окна выкладки (задача 0145).
    #    Там запись в базе заморожена, а заморозка ставится на базу целиком
    #    и схем не различает: пишущие шаги отбиты у всех одинаково, включая
    #    свою тестовую компанию прогона. Поэтому внутри окна он обязан идти
    #    только на чтение — продажу выкладка проводит раньше, по ещё открытой
    #    копии. Спрашивается это у АРГУМЕНТОВ, с которыми его позвали, и
    #    обеими сторонами: без признака он обязан идти целиком, иначе продажа
    #    не проверялась бы нигде и проба ничего не утверждала бы.
    cat > "$stub" <<EOF
#!/usr/bin/env bash
printf '%s\n' "\$@" > "$stub.args"
echo "Дымовой прогон пройден"
exit 0
EOF
    : > "$stub.args"
    ( DEPLOY_WRITE_FROZEN=yes check_smoke ) >/dev/null 2>&1
    if grep -qx -- '--read-only' "$stub.args"; then
        printf '  ✓ 5. ВНУТРИ ОКНА ЗАМОРОЗКИ прогон зовут только на чтение\n'
    else
        red "  ✗ 5. внутри окна прогон зовут с продажей — запись там отбита, и покраснеет ИСПРАВНАЯ сборка"
        bad_count=$((bad_count + 1))
    fi
    : > "$stub.args"
    ( check_smoke ) >/dev/null 2>&1
    if grep -qx -- '--read-only' "$stub.args"; then
        red "  ✗ 5. вне окна прогон тоже только читает — тогда продажу не проверяет никто"
        bad_count=$((bad_count + 1))
    else
        printf '  ✓ 5. вне окна (руками, без выкладки) прогон идёт целиком\n'
    fi
    rm -f "$stub.args"

    rm -f "$stub"
    SMOKE="$real_smoke"

    eval "$real_fetch"
    rm -f "$FETCH_ARGS_FILE"
    unset STUB_ANSWER FETCH_ARGS_FILE APP_DOMAIN

    # 6. Состояние управляющего контура — сообщение, а не проверка (0197).
    #    Проверяются три вещи, и каждая ловит свой способ сломать замысел:
    #    ответ доезжает до человека; выкладку он НЕ красит (иначе включённый
    #    во время подключения контур останавливал бы ту самую работу);
    #    и спрашивается ТА сборка, которую выкладывают, — без этого признак
    #    отвечал бы про соседнюю и молча.
    local real_cp="$CONTROL_PLANE"
    stub="${TMPDIR:-/tmp}/deploy-checks-control-plane.$$"
    cat > "$stub" <<'EOF'
#!/usr/bin/env bash
echo "  ! контур ВКЛЮЧЁН — с запуска сборки, 3 дня"
echo "спрошенная-сборка: ${CONTROL_PLANE_BUILD:-НЕ ПЕРЕДАНА}"
exit 1
EOF
    CONTROL_PLANE="$stub"
    BUILD="app-green"
    FAILED=""
    # Без подстановки команды: она подоболочка, и FAILED из неё не доехал бы —
    # то есть главное утверждение («выкладку не красит») не проверялось бы.
    report_control_plane > "$stub.out" 2>&1; local cp_rc=$?
    out=$(cat "$stub.out")
    if [ "$cp_rc" != 0 ]; then
        red "  ✗ 6. включённый контур обязан НЕ красить выкладку, а код возврата ${cp_rc}"
        bad_count=$((bad_count + 1))
    elif [ -n "$FAILED" ]; then
        red "  ✗ 6. контур попал в список упавших (${FAILED}) — выкладка покраснеет на законном состоянии"
        bad_count=$((bad_count + 1))
    else
        case "$out" in
            *ВКЛЮЧЁН*) printf '  ✓ 6. ответ про контур доезжает и выкладку не красит\n' ;;
            *) red "  ✗ 6. ответ про контур до человека не доехал: ${out}"
               bad_count=$((bad_count + 1)) ;;
        esac
    fi
    case "$out" in
        *"спрошенная-сборка: app-green"*)
            printf '  ✓ 6. спрашивается выкладываемая сборка, а не соседняя\n' ;;
        *) red "  ✗ 6. имя сборки не уехало в признак — он ответит про другую сборку"
           printf '%s\n' "$out" | sed 's/^/      /' >&2
           bad_count=$((bad_count + 1)) ;;
    esac
    # Выключенный контур лишней строки не печатает: постоянная приписка
    # «не красит» приучила бы её не читать.
    printf '#!/usr/bin/env bash\necho "  ✓ контур выключен"\nexit 0\n' > "$stub"
    FAILED=""
    report_control_plane > "$stub.out" 2>&1
    out=$(cat "$stub.out")
    case "$out" in
        *"не красит"*)
            red "  ✗ 6. у выключенного контура приписки про выкладку быть не должно"
            bad_count=$((bad_count + 1)) ;;
        *) printf '  ✓ 6. выключенный контур — одна строка без оговорок\n' ;;
    esac
    rm -f "$stub" "$stub.out"
    CONTROL_PLANE="$real_cp"

    # 7. И сам список упавших: выкладка обязана называть, ЧТО именно упало,
    #    а не «проверки не прошли». Разбирают её по этой строке.
    FAILED=""
    verdict_http 502 >/dev/null 2>&1
    verdict_feed "u" "" >/dev/null 2>&1
    case "$FAILED" in
        *"приложение отвечает"*)
            case "$FAILED" in
                *"прайс не пуст"*) printf '  ✓ упавшие перечисляются все, а не первая\n' ;;
                *) red "  ✗ в списке упавших нет второй"; bad_count=$((bad_count + 1)) ;;
            esac ;;
        *) red "  ✗ в списке упавших нет первой"; bad_count=$((bad_count + 1)) ;;
    esac

    # 8. Итоговая строка. Её читает человек, решающий, гасить ли старую сборку,
    #    и разойтись с напечатанным она уже успела: шесть строк против «пяти»
    #    в итоге поймал разбор PR #290 пробным слиянием. Сперва вердикт
    #    на подложенных числах — обе стороны, потому что соврать он может
    #    в две: назвать не то число и умолчать про напечатанное сообщение.
    expect "8. итог сходится с напечатанным" ok "" verdict_summary 5 1 \
        "Все пять самопроверок пройдены — и рядом сообщение об управляющем контуре: оно выкладку не красит"
    expect "8. шестая красящая проверка краснеет" fail "итог выкладки" \
        verdict_summary 6 1 "Все пять самопроверок пройдены — и рядом сообщение об управляющем контуре"
    expect "8. переписанное число в итоге краснеет" fail "итог выкладки" \
        verdict_summary 5 1 "Все шесть самопроверок пройдены — и рядом сообщение об управляющем контуре"
    expect "8. напечатанное сообщение, не названное в итоге, краснеет" fail "итог выкладки" \
        verdict_summary 5 1 "Все пять самопроверок пройдены"
    expect "8. обещанное сообщение, которого не печатают, краснеет" fail "итог выкладки" \
        verdict_summary 5 0 "Все пять самопроверок пройдены — и рядом сообщение об управляющем контуре"
    expect "8. блок запуска без проверок краснеет" fail "итог выкладки" \
        verdict_summary 0 1 "Все пять самопроверок пройдены — и рядом сообщение"

    # 8. И обвязка: сам файл против своего итога. Числа выше проверяют вердикт,
    #    а это — что их БЕРУТ из блока запуска, а не придумывают: без обвязки
    #    check_summary можно было бы заменить на `verdict_summary 5 1 …`
    #    литералами, и проверка осталась бы зелёной на разошедшемся файле.
    #    Копия только читается, не запускается, поэтому лежит в /tmp: правило
    #    «копию класть в ops/» (задача 0151) про запуск, а не про чтение.
    expect "8. обвязка: настоящий файл сходится со своим итогом" ok "" check_summary
    stub="${TMPDIR:-/tmp}/deploy-checks-summary.$$"
    awk '$0 == "report_control_plane" { print "check_sixth" } { print }' "$SELF" > "$stub"
    expect "8. обвязка: дописанная красящая проверка ломает итог" fail "итог выкладки" \
        check_summary "$stub"
    sed 's/Все пять самопроверок/Все шесть самопроверок/' "$SELF" > "$stub"
    expect "8. обвязка: переписанное в итоге число ломает итог" fail "итог выкладки" \
        check_summary "$stub"
    rm -f "$stub"

    # 3. ВОЗВРАТ ДЕФЕКТА. Случаи выше не утверждают ничего, пока не показано,
    #    что на возвращённом слиянии состояний они краснеют: проверка,
    #    не краснеющая на дефекте, хуже отсутствующей. Подделка — ровно
    #    прежнее поведение: ответ «версии схем не проверены» зовётся
    #    отставанием, как звался им упавший на секрете инструмент.
    #
    #    Копия кладётся в ops/, а не в /tmp: скрипт делает cd в корень
    #    репозитория от своего каталога, и копия в /tmp ушла бы в корень
    #    файловой системы (урок задачи 0151). Рекурсию обрывает DEPLOY_CHECKS_FAKE.
    if [ -z "${DEPLOY_CHECKS_FAKE:-}" ]; then
        local fake="ops/deploy-checks-fake-0202.sh"
        sed 's/^\( *\)elif known is False or.*/\1elif False:/' "$SELF" > "$fake"
        if cmp -s "$fake" "$SELF"; then
            red "  ✗ 3. подделку слияния состояний негде поставить — проба ничего не утверждает"
            bad_count=$((bad_count + 1))
        elif ! bash -n "$fake" 2>/dev/null; then
            # Иначе красное придёт от сломанного синтаксиса, а не от дефекта,
            # и проба снова ничего не скажет (урок задачи 0198).
            red "  ✗ 3. подделка сломала синтаксис — красное придёт не от слияния состояний"
            bad_count=$((bad_count + 1))
        elif DEPLOY_CHECKS_FAKE=yes bash "$fake" --selftest >/dev/null 2>&1; then
            red "  ✗ 3. слияние «отстали» и «спросить не вышло» самопроверку НЕ валит"
            bad_count=$((bad_count + 1))
        else
            printf '  ✓ 3. возврат дефекта: слияние состояний валит самопроверку\n'
        fi
        rm -f "$fake"

        # 3. И ВТОРОЙ ВОЗВРАТ — дефекта 0204: скрипт перестаёт читать признак
        #    и снова узнаёт исход по слову. Данные при этом целы, а выкладка
        #    у сборки с переименованной фразой объявляет схемы отставшими —
        #    то есть самопроверка обязана покраснеть именно на этом.
        local blind="ops/deploy-checks-fake-0204.sh"
        sed "s/known = check.get('known')/known = None/" "$SELF" > "$blind"
        if cmp -s "$blind" "$SELF"; then
            red "  ✗ 3. подделку «исход по слову» негде поставить — признак нигде не читается"
            bad_count=$((bad_count + 1))
        elif ! bash -n "$blind" 2>/dev/null; then
            red "  ✗ 3. подделка сломала синтаксис — красное придёт не от узнавания по слову"
            bad_count=$((bad_count + 1))
        elif DEPLOY_CHECKS_FAKE=yes bash "$blind" --selftest >/dev/null 2>&1; then
            red "  ✗ 3. узнавание исхода по СЛОВУ вместо признака самопроверку НЕ валит"
            bad_count=$((bad_count + 1))
        else
            printf '  ✓ 3. возврат дефекта: исход по слову вместо признака валит самопроверку\n'
        fi
        rm -f "$blind"
    fi

    if [ "$bad_count" != 0 ]; then
        red "Самопроверка не прошла: $bad_count"
        return 1
    fi
    green "Самопроверка пройдена"
    return 0
}

