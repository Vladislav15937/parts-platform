# его шестой самопроверкой значило бы обещать запрет, которого нет.
# Но и молчать про него в итоге нельзя: человек прочитал шесть строк, а итог
# говорил про пять — сообщение, которому нельзя верить, хуже отсутствующего
# (находка разбора PR #290).
# Сходится ли эта строка с тем, что напечатано выше, сверяет теперь
# --selftest (случай 8), а не человек на пробном слиянии: седьмая печатающая
# проверка либо переписанное здесь число валят самопроверку по имени.
green "Все пять самопроверок пройдены — и рядом сообщение об управляющем контуре: оно выкладку не красит"
