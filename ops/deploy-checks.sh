               bad_count=$((bad_count + 1)) ;;
        esac
    fi
    FAILED=""

    # 6. Слова: по этой строке решают, чинить сборку образа или искать,
    #    что подняли. Смешать их — то же, чем болела третья проверка (0202).
    FAILED=""
    out=$( { verdict_version "$ver_other" "$ver_ok"; } 2>&1 )
    case "$out" in
        *"ПОДНЯЛИ НЕ ТО"*)
            case "$out" in
                *"НЕ НАЗВАЛ"*)
                    red "  ✗ 6. несовпадение названо ещё и «не назвал версию» — слияние состояний"
                    bad_count=$((bad_count + 1)) ;;
                *) printf '  ✓ 6. несовпадение названо несовпадением и только\n' ;;
            esac ;;
        *) red "  ✗ 6. несовпадение версий не названо словом: ${out}"; bad_count=$((bad_count + 1)) ;;
    esac
    FAILED=""
    out=$( { verdict_version "$ver_sha" "$ver_unnamed"; } 2>&1 )
    case "$out" in
        *"НЕ НАЗВАЛ"*)
            case "$out" in
                *"ПОДНЯЛИ НЕ ТО"*)
                    red "  ✗ 6. «образ не назвал версию» утверждает, что подняли не то"
                    bad_count=$((bad_count + 1)) ;;
                *) printf '  ✓ 6. безымянный образ назван дефектом сборки, а не подменой\n' ;;
            esac ;;
        *) red "  ✗ 6. безымянная версия не названа словами: ${out}"; bad_count=$((bad_count + 1)) ;;
    esac
    FAILED=""

    # 6. И кодом возврата — четыре исхода, иначе зовущий их не различит.
    ( verdict_version "$ver_sha" "$ver_ok" ) >/dev/null 2>&1; v_ok=$?
    ( verdict_version "$ver_other" "$ver_ok" ) >/dev/null 2>&1; v_other=$?
    ( verdict_version "$ver_sha" "502" ) >/dev/null 2>&1; v_mute=$?
    ( verdict_version "$ver_sha" "$ver_old" ) >/dev/null 2>&1; v_old=$?
    FAILED=""
    if [ "$v_ok" = 0 ] && [ "$v_other" = 1 ] && [ "$v_mute" = 2 ] && [ "$v_old" = 3 ]; then
        printf '  ✓ 6. четыре исхода различимы кодом возврата (%s / %s / %s / %s)\n' \
            "$v_ok" "$v_other" "$v_mute" "$v_old"
    else
        red "  ✗ 6. исходы не различимы кодом: совпало=${v_ok} разошлось=${v_other} не-спросили=${v_mute} старая=${v_old}"
        bad_count=$((bad_count + 1))
    fi

    # 6. Обвязка: ответ берётся у ВЫКЛАДЫВАЕМОЙ сборки, а ожидание — у того,
    #    кто выкладывает. Подмены ответа тут мало: она про разбор.
    STUB_ANSWER="$ver_ok"
    DEPLOY_EXPECT_VERSION="$ver_sha"
    expect "6. обвязка: ожидание выкладки доезжает до вердикта" ok "" check_version
    DEPLOY_EXPECT_VERSION="$ver_other"
    expect "6. обвязка: чужая версия доезжает и краснеет" \
        fail "версия та, что выкладывали" check_version
    unset DEPLOY_EXPECT_VERSION
    # Запуск руками: ожидание берётся из тега ИМЕННО ЭТОЙ сборки, а не
    # из общего. Взяв чужой ключ, проверка сверяла бы соседнюю версию.
    APP_IMAGE_TAG="$ver_other"
    APP_IMAGE_TAG_GREEN="$ver_sha"
    expect "6. обвязка: без выкладки ожидание берётся из тега этой сборки" ok "" check_version
    APP_IMAGE_TAG_GREEN="$ver_other"
    expect "6. обвязка: чужой тег в .env краснеет" \
        fail "версия та, что выкладывали" check_version
    unset APP_IMAGE_TAG APP_IMAGE_TAG_GREEN
    STUB_ANSWER="$ver_ok"
    DEPLOY_EXPECT_VERSION="$ver_sha"
    : > "$FETCH_ARGS_FILE"
    FAILED=""
    check_version >/dev/null 2>&1
    asked=$(cat "$FETCH_ARGS_FILE")
    case "$asked" in
        *"$BUILD"*readiness*)
            printf '  ✓ 6. обвязка: спрашивается готовность выкладываемой сборки\n' ;;
        *) red "  ✗ 6. обвязка: спросили не ту сборку или не готовность: ${asked}"
           bad_count=$((bad_count + 1)) ;;
    esac
    unset DEPLOY_EXPECT_VERSION
    FAILED=""

    # 5. Дымовой прогон. Сам сценарий проверяет себя сам
    #    (ops/smoke-run.sh --selftest, та же задача CI); здесь — что его отказ
    #    доезжает до выкладки и НАЗЫВАЕТ шаг, а не теряется по дороге.
    expect "5. прогон доехал — проходит" ok "" \
        verdict_smoke 0 "  ✓ выдача закрыла сделку и списала остаток
Дымовой прогон пройден: сценарий доезжает до конца"
    expect "5. сломанный шаг краснеет и назван" fail "сценарий продажи" \
        verdict_smoke 1 "  ✗ сделка оформлена, а деталь не отложена: свободный остаток 1
Дымовой прогон не прошёл: оформление сделки"

    # 5. ПРОГОН МОГ ПРОЙТИ, НЕ ИСПОЛНИВ ЧАСТИ ШАГОВ (задача 0239). Второй
    #    уровень той же правки: прогон теперь называет пропущенное словом
    #    ЧАСТИЧНО, и выкладка обязана это донести, а не сказать «сценарий
    #    доезжает до конца». Красить при этом нельзя — пустой стенд законен.
    FAILED=""
    out=$( { verdict_smoke 0 "  — поиск по номеру — пропущено: на складе нет ни одной позиции (пустой стенд)
Дымовой прогон пройден ЧАСТИЧНО: не исполнялись шаги — поиск по номеру, карточка. Сценарий до конца НЕ доехал."; } 2>&1 )
    case "$out" in
        *"НЕ ЦЕЛИКОМ"*)
            case "$out" in
                *"доезжает до конца"*)
                    red "  ✗ 5. пропуски названы, а рядом осталось «доезжает до конца»"
                    bad_count=$((bad_count + 1)) ;;
                *) printf '  ✓ 5. ПРОПУЩЕННЫЕ ШАГИ: итог не утверждает «сценарий доезжает до конца»\n' ;;
            esac ;;
        *) red "  ✗ 5. про пропущенные шаги выкладка молчит: $(printf '%s' "$out" | tr '\n' ' ')"
           bad_count=$((bad_count + 1)) ;;
    esac
    if [ -n "$FAILED" ]; then
        red "  ✗ 5. пропущенные шаги покрасили выкладку — пустой стенд законен, краснеть нечему"
        bad_count=$((bad_count + 1))
    fi
    FAILED=""

    local real_smoke="$SMOKE"
    stub="${TMPDIR:-/tmp}/deploy-checks-smoke.$$"
    printf '#!/usr/bin/env bash\necho "Дымовой прогон пройден"\nexit 0\n' > "$stub"
    SMOKE="$stub"
    expect "5. обвязка: пройденный прогон доезжает до вердикта" ok "" check_smoke
    printf '#!/usr/bin/env bash\necho "Дымовой прогон не прошёл: выдача"\nexit 1\n' > "$stub"
    expect "5. обвязка: непройденный доезжает и краснеет" fail "сценарий продажи" check_smoke

    # 5. И главное — С ЧЕМ прогон зовут внутри окна выкладки (задача 0145).
    #    Там запись в базе заморожена, а заморозка ставится на базу целиком
    #    и схем не различает: пишущие шаги отбиты у всех одинаково, включая
    #    свою тестовую компанию прогона. Поэтому внутри окна он обязан идти
    #    только на чтение — продажу выкладка проводит раньше, по ещё открытой
    #    копии. Спрашивается это у АРГУМЕНТОВ, с которыми его позвали, и
    #    обеими сторонами: без признака он обязан идти целиком, иначе продажа
    #    не проверялась бы нигде и проба ничего не утверждала бы.
    cat > "$stub" <<EOF
#!/usr/bin/env bash
printf '%s\n' "\$@" > "$stub.args"
echo "Дымовой прогон пройден"
exit 0
EOF
    : > "$stub.args"
    ( DEPLOY_WRITE_FROZEN=yes check_smoke ) >/dev/null 2>&1
    if grep -qx -- '--read-only' "$stub.args"; then
        printf '  ✓ 5. ВНУТРИ ОКНА ЗАМОРОЗКИ прогон зовут только на чтение\n'
    else
        red "  ✗ 5. внутри окна прогон зовут с продажей — запись там отбита, и покраснеет ИСПРАВНАЯ сборка"
        bad_count=$((bad_count + 1))
    fi
    : > "$stub.args"
    ( check_smoke ) >/dev/null 2>&1
    if grep -qx -- '--read-only' "$stub.args"; then
        red "  ✗ 5. вне окна прогон тоже только читает — тогда продажу не проверяет никто"
        bad_count=$((bad_count + 1))
    else
        printf '  ✓ 5. вне окна (руками, без выкладки) прогон идёт целиком\n'
    fi
    rm -f "$stub.args"

    rm -f "$stub"
    SMOKE="$real_smoke"

    eval "$real_fetch"
    rm -f "$FETCH_ARGS_FILE"
    unset STUB_ANSWER FETCH_ARGS_FILE APP_DOMAIN

    # 6. Состояние управляющего контура — сообщение, а не проверка (0197).
    #    Проверяются три вещи, и каждая ловит свой способ сломать замысел:
    #    ответ доезжает до человека; выкладку он НЕ красит (иначе включённый
    #    во время подключения контур останавливал бы ту самую работу);
    #    и спрашивается ТА сборка, которую выкладывают, — без этого признак
    #    отвечал бы про соседнюю и молча.
    local real_cp="$CONTROL_PLANE"
    stub="${TMPDIR:-/tmp}/deploy-checks-control-plane.$$"
    cat > "$stub" <<'EOF'
#!/usr/bin/env bash
echo "  ! контур ВКЛЮЧЁН — с запуска сборки, 3 дня"
echo "спрошенная-сборка: ${CONTROL_PLANE_BUILD:-НЕ ПЕРЕДАНА}"
exit 1
EOF
    CONTROL_PLANE="$stub"
    BUILD="app-green"
    FAILED=""
    # Без подстановки команды: она подоболочка, и FAILED из неё не доехал бы —
    # то есть главное утверждение («выкладку не красит») не проверялось бы.
    report_control_plane > "$stub.out" 2>&1; local cp_rc=$?
    out=$(cat "$stub.out")
    if [ "$cp_rc" != 0 ]; then
        red "  ✗ 6. включённый контур обязан НЕ красить выкладку, а код возврата ${cp_rc}"
        bad_count=$((bad_count + 1))
    elif [ -n "$FAILED" ]; then
        red "  ✗ 6. контур попал в список упавших (${FAILED}) — выкладка покраснеет на законном состоянии"
        bad_count=$((bad_count + 1))
    else
        case "$out" in
            *ВКЛЮЧЁН*) printf '  ✓ 6. ответ про контур доезжает и выкладку не красит\n' ;;
            *) red "  ✗ 6. ответ про контур до человека не доехал: ${out}"
               bad_count=$((bad_count + 1)) ;;
        esac
    fi
    case "$out" in
        *"спрошенная-сборка: app-green"*)
            printf '  ✓ 6. спрашивается выкладываемая сборка, а не соседняя\n' ;;
        *) red "  ✗ 6. имя сборки не уехало в признак — он ответит про другую сборку"
           printf '%s\n' "$out" | sed 's/^/      /' >&2
           bad_count=$((bad_count + 1)) ;;
    esac
    # Выключенный контур лишней строки не печатает: постоянная приписка
    # «не красит» приучила бы её не читать.
    printf '#!/usr/bin/env bash\necho "  ✓ контур выключен"\nexit 0\n' > "$stub"
    FAILED=""
    report_control_plane > "$stub.out" 2>&1
    out=$(cat "$stub.out")
    case "$out" in
        *"не красит"*)
            red "  ✗ 6. у выключенного контура приписки про выкладку быть не должно"
            bad_count=$((bad_count + 1)) ;;
        *) printf '  ✓ 6. выключенный контур — одна строка без оговорок\n' ;;
    esac
    rm -f "$stub" "$stub.out"
    CONTROL_PLANE="$real_cp"

    # 7. И сам список упавших: выкладка обязана называть, ЧТО именно упало,
    #    а не «проверки не прошли». Разбирают её по этой строке.
    FAILED=""
    verdict_http 502 >/dev/null 2>&1
    verdict_feed "u" "" >/dev/null 2>&1
    case "$FAILED" in
        *"приложение отвечает"*)
            case "$FAILED" in
                *"прайс не пуст"*) printf '  ✓ упавшие перечисляются все, а не первая\n' ;;
                *) red "  ✗ в списке упавших нет второй"; bad_count=$((bad_count + 1)) ;;
            esac ;;
        *) red "  ✗ в списке упавших нет первой"; bad_count=$((bad_count + 1)) ;;
    esac

    # 8. Итоговая строка. Её читает человек, решающий, гасить ли старую сборку,
    #    и разойтись с напечатанным она уже успела: шесть строк против «пяти»
    #    в итоге поймал разбор PR #290 пробным слиянием. Сперва вердикт
    #    на подложенных числах — обе стороны, потому что соврать он может
    #    в две: назвать не то число и умолчать про напечатанное сообщение.
    expect "8. итог сходится с напечатанным" ok "" verdict_summary 6 1 \
        "Все шесть самопроверок пройдены — и рядом сообщение об управляющем контуре: оно выкладку не красит"
    expect "8. седьмая красящая проверка краснеет" fail "итог выкладки" \
        verdict_summary 7 1 "Все шесть самопроверок пройдены — и рядом сообщение об управляющем контуре"
    expect "8. переписанное число в итоге краснеет" fail "итог выкладки" \
        verdict_summary 6 1 "Все семь самопроверок пройдены — и рядом сообщение об управляющем контуре"
    expect "8. напечатанное сообщение, не названное в итоге, краснеет" fail "итог выкладки" \
        verdict_summary 6 1 "Все шесть самопроверок пройдены"
    expect "8. обещанное сообщение, которого не печатают, краснеет" fail "итог выкладки" \
        verdict_summary 6 0 "Все шесть самопроверок пройдены — и рядом сообщение об управляющем контуре"
    expect "8. блок запуска без проверок краснеет" fail "итог выкладки" \
        verdict_summary 0 1 "Все шесть самопроверок пройдены — и рядом сообщение"

    # 8. И обвязка: сам файл против своего итога. Числа выше проверяют вердикт,
    #    а это — что их БЕРУТ из блока запуска, а не придумывают: без обвязки
    #    check_summary можно было бы заменить на `verdict_summary 5 1 …`
    #    литералами, и проверка осталась бы зелёной на разошедшемся файле.
    #    Копия только читается, не запускается, поэтому лежит в /tmp: правило
    #    «копию класть в ops/» (задача 0151) про запуск, а не про чтение.
    expect "8. обвязка: настоящий файл сходится со своим итогом" ok "" check_summary
    stub="${TMPDIR:-/tmp}/deploy-checks-summary.$$"
    awk '$0 == "report_control_plane" { print "check_seventh" } { print }' "$SELF" > "$stub"
    expect "8. обвязка: дописанная красящая проверка ломает итог" fail "итог выкладки" \
        check_summary "$stub"
    sed 's/Все шесть самопроверок/Все семь самопроверок/' "$SELF" > "$stub"
    expect "8. обвязка: переписанное в итоге число ломает итог" fail "итог выкладки" \
        check_summary "$stub"
    rm -f "$stub"

    # 3. ВОЗВРАТ ДЕФЕКТА. Случаи выше не утверждают ничего, пока не показано,
    #    что на возвращённом слиянии состояний они краснеют: проверка,
    #    не краснеющая на дефекте, хуже отсутствующей. Подделка — ровно
    #    прежнее поведение: ответ «версии схем не проверены» зовётся
    #    отставанием, как звался им упавший на секрете инструмент.
    #
    #    Копия кладётся в ops/, а не в /tmp: скрипт делает cd в корень
    #    репозитория от своего каталога, и копия в /tmp ушла бы в корень
    #    файловой системы (урок задачи 0151). Рекурсию обрывает DEPLOY_CHECKS_FAKE.
    if [ -z "${DEPLOY_CHECKS_FAKE:-}" ]; then
        local fake="ops/deploy-checks-fake-0202.sh"
        sed 's/^\( *\)elif known is False or.*/\1elif False:/' "$SELF" > "$fake"
        if cmp -s "$fake" "$SELF"; then
            red "  ✗ 3. подделку слияния состояний негде поставить — проба ничего не утверждает"
            bad_count=$((bad_count + 1))
        elif ! bash -n "$fake" 2>/dev/null; then
            # Иначе красное придёт от сломанного синтаксиса, а не от дефекта,
            # и проба снова ничего не скажет (урок задачи 0198).
            red "  ✗ 3. подделка сломала синтаксис — красное придёт не от слияния состояний"
            bad_count=$((bad_count + 1))
        elif DEPLOY_CHECKS_FAKE=yes bash "$fake" --selftest >/dev/null 2>&1; then
            red "  ✗ 3. слияние «отстали» и «спросить не вышло» самопроверку НЕ валит"
            bad_count=$((bad_count + 1))
        else
            printf '  ✓ 3. возврат дефекта: слияние состояний валит самопроверку\n'
        fi
        rm -f "$fake"

        # 3. И ВТОРОЙ ВОЗВРАТ — дефекта 0204: скрипт перестаёт читать признак
        #    и снова узнаёт исход по слову. Данные при этом целы, а выкладка
        #    у сборки с переименованной фразой объявляет схемы отставшими —
        #    то есть самопроверка обязана покраснеть именно на этом.
        local blind="ops/deploy-checks-fake-0204.sh"
        sed "s/known = check.get('known')/known = None/" "$SELF" > "$blind"
        if cmp -s "$blind" "$SELF"; then
            red "  ✗ 3. подделку «исход по слову» негде поставить — признак нигде не читается"
            bad_count=$((bad_count + 1))
        elif ! bash -n "$blind" 2>/dev/null; then
            red "  ✗ 3. подделка сломала синтаксис — красное придёт не от узнавания по слову"
            bad_count=$((bad_count + 1))
        elif DEPLOY_CHECKS_FAKE=yes bash "$blind" --selftest >/dev/null 2>&1; then
            red "  ✗ 3. узнавание исхода по СЛОВУ вместо признака самопроверку НЕ валит"
            bad_count=$((bad_count + 1))
        else
            printf '  ✓ 3. возврат дефекта: исход по слову вместо признака валит самопроверку\n'
        fi
        rm -f "$blind"

        # 6. ВОЗВРАТ ДЕФЕКТА задачи 0130, две подделки. Первая — ровно то,
        #    что требует критерий приёмки: «убрать передачу SHA в сборку
        #    образа — проверка обязана упасть на пустой версии, а не
        #    промолчать». Здесь она выражена со стороны проверки: безымянная
        #    версия объявляется совпадением.
        local blind_version="ops/deploy-checks-fake-0130.sh"
        # Образец ПРИВЯЗАН К НАЧАЛУ СТРОКИ намеренно: без якоря он совпадает
        # и со своей же строкой в этой самопроверке — подделка правит
        # собственный генератор вместо разбора ответа (урок 0195: проба
        # находила свой текст и утверждала не то).
        sed "s/^    print('безымянная ' + detail)\$/    print('да ' + detail)/" \
            "$SELF" > "$blind_version"
        if cmp -s "$blind_version" "$SELF"; then
            red "  ✗ 6. подделку «безымянная сойдёт за совпадение» негде поставить — проба ничего не утверждает"
            bad_count=$((bad_count + 1))
        elif ! bash -n "$blind_version" 2>/dev/null; then
            red "  ✗ 6. подделка сломала синтаксис — красное придёт не от безымянной версии"
            bad_count=$((bad_count + 1))
        elif DEPLOY_CHECKS_FAKE=yes bash "$blind_version" --selftest >/dev/null 2>&1; then
            red "  ✗ 6. образ БЕЗ переданного SHA самопроверку НЕ валит — проверка молчит на пустой версии"
            bad_count=$((bad_count + 1))
        else
            printf '  ✓ 6. возврат дефекта: пустая версия валит самопроверку, а не проходит молча\n'
        fi
        rm -f "$blind_version"

        # 6. Вторая — сверка снята начисто: любая версия объявляется той,
        #    которую выкладывали. Без неё первая подделка не отличала бы
        #    «проверка есть» от «проверка есть только у безымянных».
        local blind_match="ops/deploy-checks-fake-0130-match.sh"
        # И здесь якорь обязателен: без него образец совпал со своей же
        # строкой генератора, кавычка осталась незакрытой, и копия падала
        # «syntax error» — то есть красное приходило от сломанного файла,
        # а не от снятой сверки. Поймано прогоном самопроверки (урок 0198).
        sed 's/^    same = n.*$/    same = True/' "$SELF" > "$blind_match"
        if cmp -s "$blind_match" "$SELF"; then
            red "  ✗ 6. подделку «всё совпадает» негде поставить — сверки версий нет вовсе"
            bad_count=$((bad_count + 1))
        elif ! bash -n "$blind_match" 2>/dev/null; then
            red "  ✗ 6. подделка сломала синтаксис — красное придёт не от снятой сверки"
            bad_count=$((bad_count + 1))
        elif DEPLOY_CHECKS_FAKE=yes bash "$blind_match" --selftest >/dev/null 2>&1; then
            red "  ✗ 6. снятая сверка версий самопроверку НЕ валит: подняли что угодно — «совпало»"
            bad_count=$((bad_count + 1))
        else
            printf '  ✓ 6. возврат дефекта: снятая сверка версий валит самопроверку\n'
        fi
        rm -f "$blind_match"
    fi

    # 9. ПОДМЕНА ТЕЛА ПРОВЕРКИ (задача 0239). `check_summary` считает ИМЕНА
    #    строк вызова, поэтому `check_http() { return 0; }` для него неотличим
    #    от настоящей проверки — и увидеть это он не может по построению, он
    #    считает вызовы. Увидеть может самопроверка ЦЕЛИКОМ: у каждой из шести
    #    есть случай обвязки с подменённым `fetch`, и выпотрошенная проверка
    #    на сломанном ответе не краснеет.
    #
    #    Так и было записано в ops/CLAUDE.md — «выпотрошенный в return 0
    #    check_http валит самопроверку двумя случаями», — но ПРОВЕРЕНО это
    #    не было ничем: подделки такого вида не существовало. Теперь она есть
    #    и идёт ПЕРЕБОРОМ, а имена берутся из блока запуска, а не списком:
    #    седьмая проверка, заведённая завтра, попадает в перебор сама. Цена
    #    названа: шесть детских прогонов самопроверки, по ~1,1 с каждый.
    if [ -n "${DEPLOY_CHECKS_FAKE:-}" ]; then
        printf '  ✓ 9. подделок тела не заводим — рекурсии нет\n'
    else
        local gutted name names
        names=$(gating_names)
        if [ -z "$names" ]; then
            red "  ✗ 9. имён гейтящих проверок не нашлось — перебор подмены тела пуст"
            bad_count=$((bad_count + 1))
        fi
        for name in $names; do
            gutted="ops/deploy-checks-fake-0239-${name}.sh"
            awk -v fn="$name" '
                $0 == fn "() {" { print fn "() { return 0; }"; skip = 1; next }
                skip && $0 == "}" { skip = 0; next }
                !skip { print }
            ' "$SELF" > "$gutted"
            if ! grep -q "^${name}() { return 0; }\$" "$gutted"; then
                red "  ✗ 9. тело ${name} подменить не удалось — перебор про неё ничего не утверждает"
                bad_count=$((bad_count + 1))
            elif ! bash -n "$gutted" 2>/dev/null; then
                # Иначе красное придёт от сломанного синтаксиса, а не
                # от подменённого тела (урок 0198).
                red "  ✗ 9. подделка ${name} сломала синтаксис — красное скажет не о том"
                bad_count=$((bad_count + 1))
            elif DEPLOY_CHECKS_FAKE=yes bash "$gutted" --selftest >/dev/null 2>&1; then
                red "  ✗ 9. ${name} с телом «return 0» самопроверку НЕ валит: выкладка зеленеет, не спросив ячейку"
                bad_count=$((bad_count + 1))
            else
                printf '  ✓ 9. подмена тела: %s с «return 0» валит самопроверку\n' "$name"
            fi
            rm -f "$gutted"
        done

        # 1 и 5. ВОЗВРАТ ДЕФЕКТА на обе починки этой задачи: без них случаи
        #        выше не утверждают, что краснеет именно сторож.
        local fake0239
        fake0239="ops/deploy-checks-fake-0239.sh"
        sed 's|^    seen=$(printf.*|    seen=podelka|' "$SELF" > "$fake0239"
        if ! grep -q '^    seen=podelka$' "$fake0239"; then
            red "  ✗ 1. подделку «тело не смотрим» негде поставить"
            bad_count=$((bad_count + 1))
        elif ! bash -n "$fake0239" 2>/dev/null; then
            red "  ✗ 1. подделка «тело не смотрим» сломала синтаксис"
            bad_count=$((bad_count + 1))
        elif DEPLOY_CHECKS_FAKE=yes bash "$fake0239" --selftest >/dev/null 2>&1; then
            red "  ✗ 1. ВОЗВРАТ ДЕФЕКТА: «200 с нулём байт» снова проходит, а самопроверка молчит"
            bad_count=$((bad_count + 1))
        else
            printf '  ✓ 1. возврат дефекта: непросмотренное тело валит самопроверку\n'
        fi
        sed 's|\*ЧАСТИЧНО\*)|*NIKOGDA-podelka*)|' "$SELF" > "$fake0239"
        if ! grep -q 'NIKOGDA-podelka' "$fake0239"; then
            red "  ✗ 5. подделку «пропуски не замечаем» негде поставить"
            bad_count=$((bad_count + 1))
        elif ! bash -n "$fake0239" 2>/dev/null; then
            red "  ✗ 5. подделка «пропуски не замечаем» сломала синтаксис"
            bad_count=$((bad_count + 1))
        elif DEPLOY_CHECKS_FAKE=yes bash "$fake0239" --selftest >/dev/null 2>&1; then
            red "  ✗ 5. ВОЗВРАТ ДЕФЕКТА: пропущенные шаги снова объявляются «доездом до конца»"
            bad_count=$((bad_count + 1))
        else
            printf '  ✓ 5. возврат дефекта: незамеченные пропуски валят самопроверку\n'
        fi
        rm -f "$fake0239"
    fi

    if [ "$bad_count" != 0 ]; then
        red "Самопроверка не прошла: $bad_count"
        return 1
    fi
    green "Самопроверка пройдена"
    return 0
}

