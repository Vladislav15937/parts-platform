#!/usr/bin/env bash
# Включён ли управляющий контур ячейки — и сходится ли это с .env.
#
#   ops/control-plane.sh             # спросить работающую сборку и сверить с файлом
#   ops/control-plane.sh --selftest  # проверить самого сторожа на подделках
#
# ЗАЧЕМ ОН ЕСТЬ. 26 сентября 2026 на боевой ячейке у сборки, поднятой трое
# суток назад, в окружении лежал непустой APP_PROVISIONING_TOKEN. Утечки
# не было — снаружи контур закрыт по адресам, POST /api/provisioning/tenants
# через терминатор отвечает 404, — но правило «секрет выключается сразу после
# подключения» (docs/onboarding.md, раздел 2) не выполнялось трое суток,
# и УЗНАТЬ ОБ ЭТОМ БЫЛО НЕЧЕМ: готовность задаёт пять вопросов и ни одного
# про контур, ops/config-guard.sh смотрит только монтирования, в ops/alerts.yml
# про провижининг нет ни одного правила. Правило, выполняемое руками
# и проверяемое памятью, не выполняют — и это не видно.
#
# Цена невыполнения не абстрактная: секрет — ЕДИНСТВЕННАЯ преграда перед
# провижинингом (ограничений частоты и числа схем нет вовсе, задача 0183),
# а кончившийся диск ячейки останавливает Postgres, а с ним архив WAL
# и точку возврата ВСЕХ арендаторов.
#
# ПОЧЕМУ СПРАШИВАЕМ РАБОТАЮЩУЮ СБОРКУ, А НЕ ФАЙЛ. Это главное свойство
# проверки, и взято оно прямо из наблюдавшегося случая: окружение контейнера
# читается ПРИ ЕГО СОЗДАНИИ, поэтому вычищенный .env при живом секрете внутри
# — состояние совершенно обычное. Признак, читающий только .env, соврал бы
# ровно там, где он нужен. Спрашивается /actuator/provisioning, а он отвечает
# тем же методом, которым контур решает, пускать ли запрос.
#
# А .env читается ВТОРЫМ вопросом, не вместо: разрыв между файлом и
# контейнером — это и есть наблюдавшийся дефект, и назвать его надо словами.
# Догадываться, что `docker compose restart` окружение не перечитывает,
# человек не должен — он и не догадался.
#
# ЗАМЕРЕНО (27 сентября 2026, docker 29.1.3, compose v5.0.0-desktop.1):
#   .env вычищен, `docker compose restart`  → тот же контейнер, СЕКРЕТ ЖИВОЙ
#   .env вычищен, `docker compose up -d`    → новый контейнер, секрет отозван
# То есть инструкция «пустое значение в .env, перезапуск приложения»
# выполнялась буквально и цели не достигала.
#
# КРАСНЫМ ЭТО НИЧЕГО НЕ КРАСИТ — решение не исполнителя. Во время подключения
# клиента контур включён законно, и запрет остановил бы ровно ту работу, ради
# которой он включён. Здесь сообщение: состояние, с какого момента и чем
# секрет отзывается. Обязан ли включённый контур красить выкладку или
# готовность — вопрос владельцу продукта (задача 0197).
#
# Код возврата при этом честный: 1 на РАЗРЫВЕ (файл и сборка не сходятся)
# и когда ответа не получили вовсе. «Спросить некого» — это не «выключено».
#
# КУДА НАЦЕЛЕНО. Умолчание — сборка под трафиком этой ячейки, изнутри сети
# compose: порт приложения наружу не опубликован (у caddy есть curl,
# в образе приложения его нет).
#
#   CONTROL_PLANE_BUILD=app-green   какую сборку спрашивать (умолчание — под трафиком)
#   CONTROL_PLANE_URL=…             спросить по адресу с хоста, а не изнутри ячейки
#   ENV_FILE=…                      файл окружения ячейки (умолчание .env)

set -uo pipefail
cd "$(dirname "$0")/.."

SELF="ops/$(basename "$0")"
COMPOSE="${COMPOSE:-docker compose -f docker-compose.prod.yml}"
ENV_FILE="${ENV_FILE:-.env}"
TIMEOUT="${CONTROL_PLANE_TIMEOUT:-20}"

red()   { printf '\033[1;31m%s\033[0m\n' "$1" >&2; }
green() { printf '\033[1;32m%s\033[0m\n' "$1"; }
warn()  { printf '\033[1;33m%s\033[0m\n' "$1"; }

# Как отзывается секрет — одной строкой на весь скрипт: два написания
# разъехались бы, а цена ошибки здесь — человек, считающий контур закрытым.
KAK_OTOZVAT="Отзывается так: пустой APP_PROVISIONING_TOKEN в ${ENV_FILE}, затем
      ops/config-guard.sh && ${COMPOSE} up -d <сборка>
    ПЕРЕСОЗДАНИЕ, а не restart: restart оставляет контейнер прежним вместе
    с его окружением — замерено. Пересоздание сборки под трафиком — это её
    перезапуск: секунды, пока она поднимается, ячейка отвечает 502. На ячейке
    с двумя сборками дешевле дождаться следующей выкладки: она пересоздаёт
    сборку сама, то есть отзывает секрет попутно."

# ─────────────────────── разбор ответа признака ──────────────────────────────
#
# Разбор отделён от запроса намеренно, как у ops/deploy-checks.sh: краснеть
# проверка обязана на дефекте, а проверить это можно только подсунув ей ответ.
verdict_state() {  # тело ответа, код ответа, секрет в файле (да|нет)
    local body="$1" code="$2" v_file="$3" state detail

    case "$code" in
        200) ;;
        404)
            # Не «выключено»: сборка старше этой проверки либо адрес не
            # перечислен в management.endpoints. Выдать это за «выключено»
            # значило бы сказать «всё в порядке», ничего не спросив.
            red "  ✗ признака нет: сборка отвечает 404 на /actuator/provisioning"
            red "      Это НЕ «контур выключен», а «спросить нечем»: сборка старше"
            red "      задачи 0197 либо адрес убран из management.endpoints.web.exposure."
            red "      Состояние контура на такой сборке снаружи не видно вовсе."
            return 1 ;;
        000|"")
            red "  ✗ сборка не отвечает вовсе — состояние контура неизвестно"
            red "      Это НЕ «контур выключен». Поднята ли сборка: ${COMPOSE} ps"
            return 1 ;;
        *)
            red "  ✗ на /actuator/provisioning ответ ${code}, а не 200"
            red "      $(printf '%s' "$body" | tr '\n' ' ' | cut -c1-160)"
            return 1 ;;
    esac

    # Ответ разбирается python'ом, а не grep'ом: ключа нет — это чужой ответ,
    # а не «выключено» (та же ловушка, что у ops/migrate-tenants.sh, где
    # отсутствие ключа читалось как «отставших нет»).
    state=$(printf '%s' "$body" | python3 -c '
import json, sys
raw = sys.stdin.read()
try:
    answer = json.loads(raw)
except ValueError:
    sys.exit("вместо признака пришло: " + " ".join(raw.split())[:160])
if not isinstance(answer, dict) or "enabled" not in answer:
    sys.exit("в ответе нет ключа enabled: " + " ".join(raw.split())[:160])
print(("да" if answer["enabled"] else "нет") + "\t"
      + str(answer.get("forHuman", "?")) + "\t" + str(answer.get("detail", "")))
' 2>&1) || { red "  ✗ признак не разобран: ${state}"; return 1; }

    local v_build for_human
    v_build=$(printf '%s' "$state" | cut -f1)
    for_human=$(printf '%s' "$state" | cut -f2)
    detail=$(printf '%s' "$state" | cut -f3)

    # ── четыре сочетания, и два из них — разрыв ──────────────────────────────
    if [ "$v_build" = да ] && [ "$v_file" = нет ]; then
        # Ровно то, что наблюдали на боевой ячейке.
        red "  ✗ РАЗРЫВ: в ${ENV_FILE} секрет пуст, а сборка работает с прежним — он ЖИВОЙ"
        red "      Включён с запуска сборки: ${for_human}."
        red "      Файл вычистили, а контейнер его не перечитывал: окружение читается"
        red "      при создании контейнера. Контур закрытым только КАЖЕТСЯ."
        red "      ${KAK_OTOZVAT}"
        return 1
    fi
    if [ "$v_build" = нет ] && [ "$v_file" = да ]; then
        # Обратный разрыв, и он тоже стоит времени: человек задал секрет,
        # пошёл заводить клиента и получил «Управляющий контур выключен».
        red "  ✗ РАЗРЫВ: секрет задан в ${ENV_FILE}, а сборка его не читала"
        red "      Контур выключен с запуска сборки: ${for_human}."
        red "      Провижининг ответит «${detail%% —*}»."
        red "      Чтобы ВКЛЮЧИТЬ: ${COMPOSE} up -d <сборка> — пересоздание, не restart."
        return 1
    fi
    if [ "$v_build" = да ]; then
        # Законное состояние в день подключения клиента и незаконное на третьи
        # сутки. Отличить их можно только по «с какого момента», поэтому оно
        # стоит в самой строке, а не в подробностях.
        local pro_fayl=" (и в ${ENV_FILE} секрет задан)"
        [ "$v_file" = да ] || pro_fayl=" (файл окружения не смотрели)"
        warn "  ! контур ВКЛЮЧЁН — с запуска сборки, ${for_human}${pro_fayl}"
        printf '      %s\n' "Во время подключения клиента это законно, после — нет."
        printf '      %s\n' "${KAK_OTOZVAT}"
        return 0
    fi
    green "  ✓ контур выключен — и в ${ENV_FILE} пусто: файл и сборка сходятся"
    return 0
}

# ─────────────────────────── чем спрашиваем ──────────────────────────────────
fetch() {
    # Подменяется самопроверкой: проба, зовущая только функцию разбора,
    # не проверяет ПУТЬ ЗАПУСКА — а именно он читает .env и окружение
    # (урок задачи 0144). Со стендом ответ приезжает из файла, и обвязка
    # проходится целиком, от чтения файла до вердикта.
    if [ -n "${CONTROL_PLANE_STUB:-}" ]; then
        cat "$CONTROL_PLANE_STUB"
        return 0
    fi
    if [ -n "${CONTROL_PLANE_URL:-}" ]; then
        curl -sS -m "$TIMEOUT" -w '\n%{http_code}' "$@" 2>&1
    else
        $COMPOSE exec -T caddy curl -sS -m "$TIMEOUT" -w '\n%{http_code}' "$@" 2>&1
    fi
}

# Есть ли секрет в файле окружения. Значение НЕ печатается и наружу не уходит
# ни в каком виде — только «да» или «нет».
secret_in_file() {
    [ -f "$ENV_FILE" ] || { echo "файла-нет"; return; }
    local value src
    # Путь абсолютный оставляем как есть: «./» перед ним даёт несуществующий
    # файл, sourcing молча не срабатывает, и заданный секрет читается как
    # ПУСТОЙ — то есть проверка объявила бы разрыв там, где всё сходится.
    # Поймано своей же самопроверкой, а не глазами.
    case "$ENV_FILE" in
        /*) src="$ENV_FILE" ;;
        *)  src="./$ENV_FILE" ;;
    esac
    # Своей подоболочкой: sourcing файла ячейки в текущую втянул бы в окружение
    # скрипта десятки чужих переменных, включая секреты, — а дальше они уехали
    # бы детям (и в ps их аргументов).
    value=$(set -a; . "$src" >/dev/null 2>&1; printf '%s' "${APP_PROVISIONING_TOKEN:-}")
    if [ -n "$(printf '%s' "$value" | tr -d '[:space:]')" ]; then echo да; else echo нет; fi
}

check_control_plane() {
    local url build answer body code v_file

    if ! command -v python3 >/dev/null 2>&1; then
        # Молча отдавать «выключено» без разбора ответа нельзя: это тот самый
        # тихий успех, которым проверка перестаёт что-либо утверждать (0151).
        red "  ✗ нечем разобрать ответ: нет python3"
        return 1
    fi

    v_file=$(secret_in_file)
    if [ "$v_file" = "файла-нет" ]; then
        # Законно, когда проверку нацелили переменными на чужую машину.
        warn "  ! ${ENV_FILE} рядом нет — сверяю только то, что отвечает сборка"
        v_file=неизвестно
    fi

    if [ -n "${CONTROL_PLANE_URL:-}" ]; then
        url="$CONTROL_PLANE_URL"
    else
        build="${CONTROL_PLANE_BUILD:-}"
        if [ -z "$build" ]; then
            # Имя активной сборки живёт в одном месте на всю ячейку
            # (ops/active-build.caddy через switch-build.sh): второе место,
            # знающее его, однажды спросило бы не ту сборку.
            build=$(ops/switch-build.sh --current) || {
                red "  ✗ не удалось узнать сборку под трафиком — назовите её:"
                red "      CONTROL_PLANE_BUILD=app-green $SELF"
                return 1
            }
        fi
        url="http://$build:8080/actuator/provisioning"
        printf 'Управляющий контур: сборка \033[1m%s\033[0m\n' "$build"
    fi

    answer=$(fetch "$url")
    body=$(printf '%s\n' "$answer" | sed '$d')
    code=$(printf '%s\n' "$answer" | tail -n1 | tr -dc '0-9' | tail -c 3)

    # Значение «неизвестно» доезжает до вердикта как есть: без файла разрыв
    # объявлять не из чего, и придумывать за него «пусто» нельзя — вышла бы
    # ложная тревога о разрыве на всякой машине без .env рядом.
    verdict_state "$body" "$code" "$v_file"
}

# ───────────────────────────── самопроверка ──────────────────────────────────
#
# Без ячейки и без docker: вердикту подсовываются ответы — годные и сломанные,
# — и сверяется, что на дефекте он краснеет и НАЗЫВАЕТ, что именно не так.
# Последний случай — возврат дефекта: копия скрипта, объявляющая всё
# сходящимся, обязана валить самопроверку. Без него остальные не утверждали
# бы ничего.
selftest() {
    local bad=0 out rc tmp
    tmp="${TMPDIR:-/tmp}/control-plane-selftest.$$"
    echo "Самопроверка ops/control-plane.sh"

    local on off
    on='{"enabled":true,"since":"2026-09-23T14:02:11Z","forSeconds":259200,"forHuman":"3 дня","detail":"Управляющий контур ВКЛЮЧЁН — с запуска этой сборки, 3 дня. Отзывается пустым APP_PROVISIONING_TOKEN в .env и ПЕРЕСОЗДАНИЕМ сборки (docker compose up -d <сборка>)"}'
    off='{"enabled":false,"since":"2026-09-23T14:02:11Z","forSeconds":259200,"forHuman":"3 дня","detail":"Управляющий контур выключен: app.provisioning-token не задан — и не задан с запуска этой сборки"}'

    probe() {  # имя, ожидаемый исход (ok|fail), обязательные слова…
        local name="$1" want="$2"; shift 2
        local body="$1" code="$2" file="$3"; shift 3
        set +e
        out=$(verdict_state "$body" "$code" "$file" 2>&1); rc=$?
        set -e
        if [ "$want" = ok ] && [ "$rc" != 0 ]; then
            red "  ✗ ${name}: ожидалось «проходит», а покраснело:"; printf '%s\n' "$out" | sed 's/^/      /' >&2
            bad=$((bad + 1)); return
        fi
        if [ "$want" = fail ] && [ "$rc" = 0 ]; then
            red "  ✗ ${name}: ожидалось «краснеет», а промолчало:"; printf '%s\n' "$out" | sed 's/^/      /' >&2
            bad=$((bad + 1)); return
        fi
        local word
        for word in "$@"; do
            case "$out" in
                *"$word"*) ;;
                *) red "  ✗ ${name}: в ответе нет «${word}»"
                   printf '%s\n' "$out" | sed 's/^/      /' >&2
                   bad=$((bad + 1)); return ;;
            esac
        done
        printf '  ✓ %s\n' "$name"
    }

    # 1. Наблюдавшийся случай: файл вычищен, сборка работает с секретом.
    #    Красное, назван разрыв и названо ПЕРЕСОЗДАНИЕ — иначе человек снова
    #    сделает restart и снова решит, что закрыл контур.
    probe "файл пуст, сборка со секретом — РАЗРЫВ назван" fail "$on" 200 нет \
        РАЗРЫВ "3 дня" "up -d" "ПЕРЕСОЗДАНИЕ, а не restart"
    # 2. Обратный разрыв: секрет задан, сборка его не читала.
    probe "секрет задан, сборка не читала — назван обратный разрыв" fail "$off" 200 да \
        РАЗРЫВ "up -d"
    # 3. Законное состояние дня подключения: включён и в файле задан.
    probe "оба включены — проходит и сказано, сколько" ok "$on" 200 да \
        ВКЛЮЧЁН "3 дня" "up -d"
    # 4. Всё закрыто.
    probe "оба выключены — проходит" ok "$off" 200 нет сходятся
    # 5. Ответа нет вовсе: это не «выключено».
    probe "нет ответа — красное и НЕ «выключено»" fail "" 000 нет \
        "не отвечает" "НЕ «контур выключен»"
    # 6. Сборка старше проверки: тоже не «выключено».
    probe "404 — красное и названо «спросить нечем»" fail "" 404 нет \
        "спросить нечем" "НЕ «контур выключен»"
    # 7. Чужой ответ вместо признака.
    probe "не-JSON — красное, ответ показан" fail "502 Bad Gateway" 200 нет "не разобран"
    # 8. Ответ без ключа: длина ноль — это не «выключено».
    probe "ответ без enabled — красное" fail '{"status":"UP"}' 200 нет "нет ключа enabled"

    # 9. ОБВЯЗКА целиком, настоящим запуском скрипта: путь запуска читает .env,
    #    и проба, зовущая только verdict_state, этого не проверяет вовсе
    #    (урок задачи 0144). Здесь же — что секрет не попадает в вывод.
    local fakeenv="$tmp.env" stub="$tmp.stub"
    printf 'APP_PROVISIONING_TOKEN=sekret-kotoryy-nelzya-pechatat\nAPP_DOMAIN=stend\n' > "$fakeenv"
    printf '%s\n200\n' "$on" > "$stub"

    set +e
    out=$(ENV_FILE="$fakeenv" CONTROL_PLANE_URL=http://stend \
          CONTROL_PLANE_STUB="$stub" bash "$SELF" 2>&1); rc=$?
    set -e
    case "$out" in
        *sekret-kotoryy-nelzya-pechatat*)
            red "  ✗ СЕКРЕТ НАПЕЧАТАН в выводе — этого нельзя ни в каком виде"
            printf '%s\n' "$out" | sed 's/^/      /' >&2
            bad=$((bad + 1)) ;;
        *ВКЛЮЧЁН*)
            if [ "$rc" = 0 ]; then
                printf '  ✓ обвязка: запуск читает .env, доходит до вердикта и НЕ печатает секрет\n'
            else
                red "  ✗ обвязка: «оба включены» обязано проходить, а код возврата ${rc}"
                bad=$((bad + 1))
            fi ;;
        *) red "  ✗ обвязка не дошла до вердикта:"
           printf '%s\n' "$out" | sed 's/^/      /' >&2
           bad=$((bad + 1)) ;;
    esac

    # 9б. И тот же запуск с ПУСТЫМ .env обязан назвать разрыв. Без этого случая
    #     «сверка с .env» могла бы не читать файл вовсе: ответ сборки один и тот
    #     же, разными обязаны быть вердикты.
    printf 'APP_PROVISIONING_TOKEN=\nAPP_DOMAIN=stend\n' > "$tmp.cleared"
    set +e
    out=$(ENV_FILE="$tmp.cleared" CONTROL_PLANE_URL=http://stend \
          CONTROL_PLANE_STUB="$stub" bash "$SELF" 2>&1); rc=$?
    set -e
    if [ "$rc" != 0 ] && [ -n "$(printf '%s' "$out" | grep -F 'РАЗРЫВ')" ]; then
        printf '  ✓ обвязка: вычищенный .env при живом секрете в сборке — РАЗРЫВ и код 1\n'
    else
        red "  ✗ обвязка: вычищенный .env обязан дать РАЗРЫВ и ненулевой код (код ${rc})"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=$((bad + 1))
    fi

    # 10. Файл читается на самом деле: заданный секрет и пустой обязаны давать
    #     разные ответы. Иначе «сверка с .env» была бы украшением.
    local seen_yes seen_no
    seen_yes=$(ENV_FILE="$fakeenv" secret_in_file)
    printf 'APP_PROVISIONING_TOKEN=\n' > "$tmp.empty"
    seen_no=$(ENV_FILE="$tmp.empty" secret_in_file)
    printf 'APP_PROVISIONING_TOKEN="   "\n' > "$tmp.blank"
    local seen_blank
    seen_blank=$(ENV_FILE="$tmp.blank" secret_in_file)
    if [ "$seen_yes" = да ] && [ "$seen_no" = нет ] && [ "$seen_blank" = нет ]; then
        printf '  ✓ .env разбирается: заданный — да, пустой и из пробелов — нет\n'
    else
        red "  ✗ .env разобран неверно: задан=${seen_yes}, пуст=${seen_no}, пробелы=${seen_blank}"
        bad=$((bad + 1))
    fi

    # 11. ВОЗВРАТ ДЕФЕКТА. Копия скрипта, объявляющая всё сходящимся (то есть
    #     проверка, снятая начисто), обязана валить самопроверку. Копия лежит
    #     в ops/: скрипт делает cd в корень репозитория от своего каталога,
    #     и копия в /tmp ушла бы в корень файловой системы (урок задачи 0151).
    local fake="ops/.control-plane-bez-proverki.$$.sh"
    python3 - "$SELF" "$fake" <<'PY'
import sys
src, dst = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()
# Снимаем ровно проверку: вердикт всегда «сходится и выключено».
text = text.replace(
    'verdict_state() {  # тело ответа, код ответа, секрет в файле (да|нет)',
    'verdict_state() {  # ПОДДЕЛКА: проверка снята\n'
    '    green "  ✓ контур выключен — и в .env пусто: файл и сборка сходятся"\n'
    '    return 0\n'
    '_nedostupno() {', 1)
open(dst, "w", encoding="utf-8").write(text)
PY
    chmod +x "$fake"
    set +e
    out=$(bash "$fake" --selftest 2>&1); rc=$?
    set -e
    rm -f "$fake"
    if [ "$rc" != 0 ]; then
        printf '  ✓ возврат дефекта: копия со снятой проверкой валит самопроверку\n'
    else
        red "  ✗ копия со СНЯТОЙ проверкой прошла самопроверку — значит проверка ничего не утверждает"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=$((bad + 1))
    fi

    rm -f "$tmp.env" "$tmp.empty" "$tmp.blank"
    if [ "$bad" != 0 ]; then
        red "Самопроверка не прошла: $bad"
        return 1
    fi
    green "Самопроверка пройдена"
    return 0
}

