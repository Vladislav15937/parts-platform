#!/usr/bin/env bash
# Проверка бэкапа восстановлением.
#
#   ops/verify-backup.sh [каталог-набора] [файл-окружения]
#   ops/verify-backup.sh --selftest        # проверка самой проверки, без docker
#
# «Дамп снялся» — это не бэкап. Бэкап — это когда из него поднялся арендатор
# и в нём тот же склад. Проверяется именно это: набор разворачивается
# в отдельную базу, и агрегаты сверяются с живой.
#
# Вместе с базой проверяются фотографии: каждая карточка ссылается на объект
# в хранилище, и восстановленный склад без снимков — это не восстановленный
# клиент, а список наименований. Сверяются не количества файлов, а сами
# ключи: совпадение чисел ничего не значит, если файлы другие.
#
# Восстановление идёт в ОТДЕЛЬНУЮ базу, а не в ту же под другим именем схемы:
# pg_restore кладёт схему туда, откуда её сняли, переименовать на лету нечем.
# Заодно это ближе к настоящему восстановлению — на чистый кластер.
#
# ОТКАЗ ВОССТАНОВЛЕНИЯ НЕ ГЛУШИТСЯ (задача 0157). До неё обе строки разворота
# кончались `>/dev/null 2>&1 || true`, и проверка жаловалась на СЛЕДСТВИЕ —
# «relation "t_000042.part" does not exist», — потому что таблиц не было вовсе.
# Человек из-за этого полчаса искал не там. Инструмент, называющий причину,
# которой он не проверял, хуже молчащего: настоящая причина лежала в выводе
# pg_restore, который выбрасывался.
#
# Файл окружения выбирается переменной ENV_FILE — одинаково у всех трёх
# скриптов. Позиция аргумента у них разная (набор, схема), и запоминать,
# какой по счёту здесь env, — ровно тот способ однажды снять бэкап одной
# ячейки, а проверить другой:
#
#   ENV_FILE=.env.cell02 ops/backup.sh
#   ENV_FILE=.env.cell02 ops/verify-backup.sh
#
set -euo pipefail
# Путь к себе снимается ДО cd: ниже скрипт уходит в корень репозитория,
# и относительный $0 после этого не разрешается вовсе (урок задачи 0200).
# Самопроверка читает себя этим путём и этим же путём кладёт подделки.
case "$0" in
    /*) SELF="$0" ;;
    *)  SELF="$PWD/$0" ;;
esac
cd "$(dirname "$0")/.."

# Список расширений — один на восстановление ячейки, восстановление одного
# клиента и эту проверку. Почему их ставит восстанавливающий, а не дамп
# и не приложение — в самом файле.
EXT_SQL="ops/restore-extensions.sql"

# Числа для сверки: список агрегатов, слово-метка описи и SQL — один список
# на два файла (задача 0244). Пишет их ops/backup.sh вокруг самого дампа,
# читает эта проверка. Довод, почему оракул берётся из описи набора, а не
# у живой базы, — в самом ops/backup-aggregates.sh.
. ops/backup-aggregates.sh

step() { printf '\n\033[1;34m==> %s\033[0m\n' "$1"; }
ok()   { printf '\033[1;32m    OK: %s\033[0m\n' "$1"; }
fail() { printf '\033[1;31m    ПРОВАЛ: %s\033[0m\n' "$1"; exit 1; }

# --- разбор вывода pg_restore ------------------------------------------------
#
# Вынесено отдельными функциями не ради красоты: так их можно прогнать
# на подложенных выводах без docker, базы и набора (--selftest ниже).
# Проверка, которая не краснеет на дефекте, хуже отсутствующей, а установить
# это можно только попыткой.

# Настоящие ошибки разворота. Безобидна ровно одна: схема public есть в любой
# базе с рождения, и pg_restore спотыкается о неё при развороте shared.dump
# в чистую базу. Так же её отбрасывает ops/restore-cell.sh.
restore_errors() {
    grep -E 'error:|ERROR:' "$1" 2>/dev/null \
        | grep -v 'schema "public" already exists' \
        | grep -v 'CREATE SCHEMA public' || true
}

# Годен ли разворот: код возврата, файл с выводом, что разворачивали.
# Печатает НАСТОЯЩУЮ причину и сам вывод pg_restore — то, что раньше
# выбрасывалось в /dev/null.
restore_verdict() {
    local rc="$1" out="$2" what="$3" errs total
    # «Ошибок не нашлось» и «искать было негде» — разные утверждения, а сходились
    # они в одно: `restore_errors` глушит отказ чтения (`2>/dev/null … || true`),
    # и непрочитанный файл вывода давал пустой список, то есть вердикт «годен».
    # Именно этим путём проверка бэкапа объявила бы набор развёрнутым, ничего
    # не прочитав, — а её зелёная строка и есть еженедельное «клиента можно
    # вернуть».
    if [ ! -r "$out" ]; then
        printf 'ВЫВОД pg_restore НЕ ПРОЧИТАТЬ: %s (код pg_restore: %s)\n' "${out}" "${rc}"
        printf '      Развёрнутым такой набор объявлять нельзя: ошибок не искали.\n'
        return 1
    fi
    errs="$(restore_errors "$out")"
    # Ненулевой код при отсутствии настоящих ошибок — это «schema public
    # already exists» и ничего больше. Красить проверку этим значило бы
    # краснеть каждую неделю на безобидном, а такую проверку отключают.
    if [ -z "${errs}" ]; then
        return 0
    fi
    total="$(printf '%s\n' "${errs}" | grep -c . || true)"
    printf 'ОТКАЗ ВОССТАНОВЛЕНИЯ: %s (код pg_restore: %s, ошибок: %s)\n' \
        "${what}" "${rc}" "${total}"
    printf '%s\n' "${errs}" | head -8 | sed 's/^/      /'
    [ "${total}" -gt 8 ] && printf '      … и ещё %s\n' "$(( total - 8 ))"
    # Причина называется только тогда, когда она ВИДНА в выводе. Иначе
    # повторилась бы та самая болезнь: подсказка про то, чего не проверяли.
    if printf '%s' "${errs}" | grep -qE 'gen_random_bytes|gin_trgm_ops|ltree|pg_trgm|pgcrypto'; then
        printf 'ПРИЧИНА: в базе нет расширений Postgres.\n'
        printf '      gen_random_bytes — это pgcrypto, gin_trgm_ops — pg_trgm, тип ltree — ltree.\n'
        printf '      В дампах схем их нет по построению; ставит их %s.\n' "${EXT_SQL}"
    fi
    return 1
}

# Расширения, которые ставит восстанавливающий.
ours_extensions() {
    grep -oE 'CREATE EXTENSION IF NOT EXISTS [a-z_0-9]+' "$EXT_SQL" \
        | awk '{print $NF}' | sort
}

# Дрейф: в живой базе завелось расширение, которого путь восстановления
# не знает. Список лежит в ops/, а схемы растут в db/changelog — разойтись
# они могут молча, и узнать об этом в день аварии дороже всего. plpgsql
# не считается: он есть в любой базе с рождения, и красное на нём означало бы
# красную проверку на исправной ячейке каждую неделю.
extensions_verdict() {
    local live="$1" ours="$2" missing
    missing="$(comm -23 \
        <(printf '%s\n' "${live}" | sed 's/[[:space:]]//g' | grep -v '^plpgsql$' | grep -v '^$' | sort) \
        <(printf '%s\n' "${ours}" | sed 's/[[:space:]]//g' | grep -v '^$' | sort) || true)"
    [ -z "${missing}" ] && return 0
    printf 'РАСШИРЕНИЯ РАЗОШЛИСЬ: в живой базе есть то, чего путь восстановления не ставит: %s\n' \
        "$(printf '%s' "${missing}" | tr '\n' ' ')"
    printf '      Восстановленный клиент будет без них. Впишите их в %s.\n' "${EXT_SQL}"
    return 1
}

# Вердикт по одному агрегату набора. Чистая функция — её и гоняет самопроверка
# на подложенных числах, без docker, базы и набора.
#
# Исходов три, и сводить их к двум нельзя: 0 — сошлось, 1 — расхождение
# (копия негодна), 2 — сверить не с чем. Третье означает набор, снятый сборкой
# до задачи 0244: чисел в его описи нет, и выдать это за «сошлось» значило бы
# повторить дефект 0157, где «бэкап проверен» выносилось, ничего не проверив.
aggregate_verdict() {   # схема метрика замер-до замер-после фактическое
    local schema="$1" metric="$2" before="$3" after="$4" actual="$5"
    if [ -z "$before" ] || [ -z "$after" ]; then
        printf 'НЕ СВЕРЕНО: %s.%s — в описи набора нет числа на момент снятия\n' \
            "$schema" "$metric"
        printf 'Набор снят сборкой до задачи 0244; следующий ночной дамп числа запишет.\n'
        return 2
    fi
    if ! agg_numeric "$before" || ! agg_numeric "$after" || ! agg_numeric "$actual"; then
        printf 'НЕ СВЕРЕНО: %s.%s — числа не разобрать (опись «%s»/«%s», копия «%s»)\n' \
            "$schema" "$metric" "$before" "$after" "$actual"
        return 2
    fi
    agg_in_range "$actual" "$before" "$after" && return 0
    printf 'РАСХОЖДЕНИЕ: %s.%s (%s) — в развёрнутой копии %s, а на момент снятия набора %s\n' \
        "$schema" "$metric" "$(agg_title "$metric")" "$actual" "$before"
    if [ "$before" != "$after" ]; then
        printf 'Замеры вокруг дампа: %s и %s — годным было любое число между ними.\n' \
            "$before" "$after"
    fi
    # Это важно сказать прямо: до задачи 0244 такое красное приходило и от
    # законной записи в живую базу после снятия набора, и человек привык
    # читать его как ложное. Теперь сверка идёт с описью набора — значит
    # в наборе ДЕЙСТВИТЕЛЬНО не те данные.
    printf 'Живая база тут не участвует: в наборе не то, что в него снимали.\n'
    return 1
}

# Сверка обязана идти с описью набора, а не с живой базой, и обращение
# к живой базе в этом файле остаётся ровно одно — запрос к pg_extension
# (на него опирается задача 0238, второй копии не заводить). Проверяется
# это по самому тексту скрипта: вернувшийся live-оракул иначе не виден —
# на подложенных числах он выглядит исправным.
oracle_verdict() {   # $1 — файл скрипта
    local file="$1" needle calls
    # Образец собирается на ходу: написанный литералом, он нашёлся бы в этом
    # же файле, и сторож краснел бы на собственном тексте (урок задач 0195
    # и 0214 — проба, находящая свою же строку).
    needle="$(printf '(%s "' live)"
    calls=$(grep -cF -- "$needle" "$file" || true)
    if [ "$calls" -gt 1 ]; then
        printf 'ОРАКУЛ: обращений к живой базе %s вместо одного — сверка снова идёт с движущейся целью\n' \
            "$calls"
        return 1
    fi
    if [ "$calls" = 0 ] || ! grep -F -- "$needle" "$file" | grep -q 'pg_extension'; then
        printf 'ОРАКУЛ: единственное обращение к живой базе должно быть запросом к pg_extension\n'
        return 1
    fi
    return 0
}

# Уходит ли отметка в наблюдение — и почему, если не уходит (задача 0245).
#
# Отдельной функцией, потому что иначе условие отметки проверяется только живым
# pushgateway: на подложенных числах его не видно вовсе. Отправка стоит ВНУТРИ
# этой функции, и это стережёт mark_gate_verdict ниже — безусловная отправка,
# вернувшаяся рядом, выглядела бы исправной.
#
# УСЛОВИЕ: набор, по которому сверить агрегаты было нечем, отметки НЕ СТАВИТ.
# Довод не новый, он уже написан над самой отметкой ниже: «дамп открылся»
# и «клиента можно вернуть» — разные утверждения, и тревога следит за вторым,
# а сверка агрегатов и есть второе. Значит правильно не заводить вторую отметку
# рядом с существующей, а ЗАДЕРЖАТЬ существующую: тогда находку накрывает уже
# работающее правило `БэкапНеПроверялся` (ops/alerts.yml), и ни новой метрики,
# ни семнадцатого правила, ни нового числа называть не нужно.
#
# РЕШЕНИЕ 0244 ЭТИМ НЕ ОТМЕНЯЕТСЯ НИ В ЧЁМ: код возврата проверки на таком
# наборе остаётся нулевым, жёлтая строка «Агрегаты НЕ сверены» остаётся,
# проверка не краснеет. Меняется ровно одно — уходит ли отметка.
#
# ЦЕНА НАЗВАНА И ПРИНЯТА (решение владельца продукта от 1 октября 2026,
# tasks/0245): одна тревога на два смысла — «разворот не прошёл» и
# «развернулось, но числа сверить было нечем», — человек пойдёт искать упавший
# разворот, которого не было. Разводится это текстом тревоги и жёлтой строкой
# в выводе, а принято потому, что оба состояния означают одно: утверждать,
# что клиента можно вернуть, нечем.
#
# Код возврата: 0 — отметка ушла, 1 — не ушла (наблюдение не ответило),
# 2 — не ставили вовсе. Третье отдельно от второго намеренно: «решили
# не ставить» и «ставили, да не доехало» чинят разные люди.
send_mark() {   # признак-«агрегаты-не-сверены» адрес-pushgateway команда-отправки…
    local unverified="$1" url="$2"
    shift 2
    if [ "$unverified" != 0 ]; then
        printf 'ОТМЕТКА В НАБЛЮДЕНИЕ НЕ СТАВИТСЯ: сверить агрегаты было нечем,\n'
        printf 'то есть подтвердить «клиента можно вернуть» эта проверка не может.\n'
        printf 'Без отметки через девять суток загорится тревога БэкапНеПроверялся.\n'
        return 2
    fi
    if printf '# TYPE partsflow_backup_verified_timestamp_seconds gauge\npartsflow_backup_verified_timestamp_seconds %s\n' \
        "$(date -u +%s)" | "$@" "${url%/}/metrics/job/backup" > /dev/null
    then
        return 0
    fi
    printf 'Отметка в наблюдение не ушла — проверьте pushgateway\n'
    return 1
}

# Отметку ставит ровно одно место — send_mark (задача 0245). Проверяется
# по тексту скрипта: отправка, вернувшаяся безусловной строкой рядом, на
# подложенных признаках выглядит исправной, и увидеть её можно только так.
# Образец собирается на ходу — написанный литералом, он нашёлся бы в самой
# самопроверке, и сторож краснел бы на собственном тексте (урок задач 0195
# и 0214, и то же у оракула выше).
mark_gate_verdict() {   # $1 — файл скрипта
    local file="$1" needle from to n found=0
    needle="$(printf 'metrics/job/%s' backup)"
    from=$(grep -n '^send_mark() {' "$file" | head -1 | cut -d: -f1)
    if [ -z "$from" ]; then
        printf 'ОТМЕТКА: функции send_mark в файле нет — отправку никто не накрывает условием\n'
        return 1
    fi
    to=$(awk -v s="$from" 'NR > s && $0 == "}" { print NR; exit }' "$file")
    for n in $(grep -nF -- "$needle" "$file" | cut -d: -f1); do
        found=1
        if [ "$n" -lt "$from" ] || [ "$n" -gt "$to" ]; then
            printf 'ОТМЕТКА: отправка стоит вне send_mark (строка %s) — условие её не накрывает\n' "$n"
            return 1
        fi
    done
    if [ "$found" = 0 ]; then
        printf 'ОТМЕТКА: отправки в наблюдение в файле нет вовсе\n'
        return 1
    fi
    return 0
}

# --- проверка самой проверки -------------------------------------------------
selftest() {
    local bad=0 out rc pair urlneedle
    # tmp НЕ local: ловушка EXIT срабатывает, когда функция уже завершилась,
    # и локальной переменной к этому моменту нет — под `set -u` это
    # «tmp: unbound variable» и код возврата 1 на ПРОЙДЕННОЙ самопроверке.
    # Своя же ловушка красила бы CI и обесценивала случай 9: ребёнок падал бы
    # по ней, а не из-за подделки.
    tmp="$(mktemp -d)"
    # FAKE не local по той же причине, и пустой — чтобы ловушка не упала
    # под `set -u`, когда до подделок дело не дошло.
    FAKE=""
    trap 'rm -rf "${tmp:-}"; rm -f "${FAKE:-}"' EXIT
    echo "Самопроверка ops/verify-backup.sh"

    says()     { printf '%s' "$1" | grep -qF -- "$2"; }
    says_not() { ! printf '%s' "$1" | grep -qF -- "$2"; }
    verdict() { set +e; out="$(restore_verdict "$1" "$2" "$3")"; rc=$?; set -e; }
    agg()     { set +e; out="$(aggregate_verdict "$1" "$2" "$3" "$4" "$5")"; rc=$?; set -e; }

    # Подделка кладётся в ops/, а не в /tmp, и это не вкусовщина: скрипт уходит
    # в корень репозитория от СВОЕГО каталога (`cd "$(dirname "$0")/.."`)
    # и сорсит ops/backup-aggregates.sh относительным путём. Копия из /tmp ушла
    # бы в чужой каталог и умерла бы НЕ от подделки, а от ненайденного файла
    # (урок задачи 0151) — красное от такой копии не утверждает ничего.
    plant() {   # $1 — что заменить, $2 — на что
        FAKE="ops/.verify-backup-fake.sh"
        python3 - "$SELF" "$FAKE" "$1" "$2" <<'PY'
import sys
src, dst, old, new = sys.argv[1:5]
t = open(src, encoding="utf-8").read()
assert old in t, "подделка не легла — изменилось место: " + old[:60]
open(dst, "w", encoding="utf-8").write(t.replace(old, new, 1))
PY
        # Целость копии проверяется ДО запуска: красное от сломанного синтаксиса
        # говорит о подделке, а не о стороже (урок задачи 0198).
        bash -n "$FAKE"
    }
    child() {
        set +e
        VERIFY_BACKUP_SELFTEST_CHILD=1 ENV_FILE=/dev/null bash "$FAKE" --selftest \
            >"$tmp/fake.log" 2>&1
        rc=$?
        set -e
    }

    # 1. Главный случай задачи: разворот упал на расширениях. Проверка обязана
    #    назвать РАСШИРЕНИЯ и показать вывод pg_restore, а не молчать и не
    #    жаловаться на отсутствующую таблицу — это следствие, и именно оно
    #    увело человека на полчаса.
    cat > "$tmp/ext.out" <<'EOF'
pg_restore: error: could not execute query: ERROR:  function public.gen_random_bytes(integer) does not exist
pg_restore: error: could not execute query: ERROR:  relation "t_000042.donor" does not exist
EOF
    verdict 1 "$tmp/ext.out" "t_000042"
    if [ "$rc" != 0 ] && says "$out" 'gen_random_bytes' && says "$out" 'ПРИЧИНА' \
       && says "$out" 'pgcrypto' && says "$out" 'ОТКАЗ ВОССТАНОВЛЕНИЯ'; then
        printf '  ✓ отказ по pgcrypto назван расширениями, вывод pg_restore показан\n'
    else
        printf '\033[1;31m  ✗ отказ по gen_random_bytes обязан называть расширения и показывать вывод\033[0m\n'
        printf '%s\n' "$out" | sed 's/^/      /'; bad=1
    fi

    # 2. Второй замер задачи: расширения частично есть (pgcrypto поставили,
    #    pg_trgm нет) — падают индексы.
    cat > "$tmp/trgm.out" <<'EOF'
pg_restore: error: could not execute query: ERROR:  operator class "public.gin_trgm_ops" does not exist for access method "gin"
EOF
    verdict 1 "$tmp/trgm.out" "t_000042"
    if [ "$rc" != 0 ] && says "$out" 'gin_trgm_ops' && says "$out" 'pg_trgm'; then
        printf '  ✓ отказ по gin_trgm_ops назван расширениями\n'
    else
        printf '\033[1;31m  ✗ отказ по gin_trgm_ops обязан называть pg_trgm\033[0m\n'
        printf '%s\n' "$out" | sed 's/^/      /'; bad=1
    fi

    # 3. Обратный край: «schema public already exists» — единственный
    #    безобидный отказ разворота в чистую базу. Проверка, краснеющая
    #    на нём, будет краснеть каждую неделю, и её отключат вместе с защитой.
    cat > "$tmp/benign.out" <<'EOF'
pg_restore: error: could not execute query: ERROR:  schema "public" already exists
Command was: CREATE SCHEMA public;
EOF
    verdict 1 "$tmp/benign.out" "общие схемы"
    if [ "$rc" = 0 ]; then
        printf '  ✓ «schema public already exists» проверку не красит\n'
    else
        printf '\033[1;31m  ✗ безобидный отказ обязан проходить\033[0m\n'; bad=1
    fi

    # 4. Чистый разворот.
    : > "$tmp/clean.out"
    verdict 0 "$tmp/clean.out" "t_000042"
    [ "$rc" = 0 ] && printf '  ✓ чистый разворот проходит\n' \
        || { printf '\033[1;31m  ✗ чистый разворот обязан проходить\033[0m\n'; bad=1; }

    # 4б. «Ошибок не нашлось» против «искать было негде» (задача 0235, класс 16).
    #     `restore_errors` глушит отказ чтения, поэтому НЕПРОЧИТАННЫЙ файл вывода
    #     давал пустой список — и вердикт «годен», то есть еженедельное
    #     «клиента можно вернуть» выносилось, ничего не прочитав. Случай 4 выше
    #     (пустой файл при коде 0) — законный чистый разворот, и он обязан
    #     проходить; отсутствующий файл — не то же самое.
    verdict 1 "$tmp/net-takogo-fayla.out" "t_000042"
    if [ "$rc" != 0 ] && says "$out" 'НЕ ПРОЧИТАТЬ'; then
        printf '  ✓ вывод pg_restore не прочитать — набор развёрнутым не объявляется\n'
    else
        printf '\033[1;31m  ✗ непрочитанный вывод обязан краснеть, а не читаться как «ошибок нет»\033[0m\n'
        printf '%s\n' "$out" | sed 's/^/      /'; bad=1
    fi

    # 5. Незнакомая беда. Причину выдумывать нельзя, но вывод обязан доехать
    #    до человека — иначе он опять останется с одним следствием.
    cat > "$tmp/other.out" <<'EOF'
pg_restore: error: could not open input file "/backups/t_000042.dump": No such file or directory
EOF
    verdict 1 "$tmp/other.out" "t_000042"
    if [ "$rc" != 0 ] && says "$out" 'could not open input file' && says_not "$out" 'ПРИЧИНА'; then
        printf '  ✓ незнакомый отказ показан дословно и причина не выдумана\n'
    else
        printf '\033[1;31m  ✗ незнакомый отказ обязан доезжать выводом и без выдуманной причины\033[0m\n'
        printf '%s\n' "$out" | sed 's/^/      /'; bad=1
    fi

    # 6. Дрейф списка расширений.
    set +e
    out="$(extensions_verdict "ltree
pg_trgm
pgcrypto
plpgsql
postgis" "$(ours_extensions)")"; rc=$?
    set -e
    if [ "$rc" != 0 ] && says "$out" 'postgis'; then
        printf '  ✓ незнакомое расширение живой базы названо по имени\n'
    else
        printf '\033[1;31m  ✗ расширение живой базы, которого нет в списке, обязано красить проверку\033[0m\n'
        printf '%s\n' "$out" | sed 's/^/      /'; bad=1
    fi

    # 7. Обратный край дрейфа: ровно наши три плюс plpgsql — молчит.
    set +e
    out="$(extensions_verdict "$(ours_extensions)
plpgsql" "$(ours_extensions)")"; rc=$?
    set -e
    [ "$rc" = 0 ] && printf '  ✓ исправная ячейка (наши три плюс plpgsql) не краснеет\n' \
        || { printf '\033[1;31m  ✗ исправная ячейка обязана проходить молча\033[0m\n'
             printf '%s\n' "$out" | sed 's/^/      /'; bad=1; }

    # 8. Список не пуст. Потерянный или переименованный файл расширений — это
    #    молча вернувшаяся дыра задачи 0157.
    if [ "$(ours_extensions | grep -c .)" -ge 3 ]; then
        printf '  ✓ список расширений читается: %s\n' "$(ours_extensions | tr '\n' ' ')"
    else
        printf '\033[1;31m  ✗ %s не читается или пуст\033[0m\n' "$EXT_SQL"; bad=1
    fi

    # 9. ВОЗВРАТ ДЕФЕКТА. Копия проверки, где вердикт всегда «годен», — это
    #    ровно прежняя редакция с `|| true`. Её самопроверка ОБЯЗАНА упасть:
    #    иначе краснеет не сторож, а что-то другое, и все восемь случаев выше
    #    ничего не утверждают. Ребёнку случай 9 выключен, иначе рекурсия.
    if [ -z "${VERIFY_BACKUP_SELFTEST_CHILD:-}" ]; then
        plant 'restore_verdict() {
    local rc="$1"' 'restore_verdict() {
    return 0
    local rc="$1"'
        child
        if [ "$rc" != 0 ] && grep -q 'gen_random_bytes' "$tmp/fake.log"; then
            printf '  ✓ возврат дефекта: с заглушённым вердиктом самопроверка падает\n'
        else
            printf '\033[1;31m  ✗ подделка «вердикт всегда годен» обязана валить самопроверку\033[0m\n'
            sed 's/^/      /' "$tmp/fake.log"; bad=1
        fi
    fi

    # --- сверка агрегатов: с описью набора, а не с живой базой (задача 0244) --

    # 10. ГЛАВНЫЙ СЛУЧАЙ, И ОН ОБРАТНЫЙ: ложное красное. Копия годна, в описи
    #     набора стоит 10, в копии 10 — а живая база к утру понедельника уехала
    #     вперёд. Живой базы в вердикте нет вовсе, поэтому её движение проверку
    #     больше не красит.
    agg t_000042 part 10 10 10
    if [ "$rc" = 0 ] && [ -z "$out" ]; then
        printf '  ✓ годная копия не краснеет, что бы ни записали в живую базу после снятия\n'
    else
        printf '\033[1;31m  ✗ сошедшийся с описью агрегат обязан проходить молча\033[0m\n'
        printf '%s\n' "$out" | sed 's/^/      /'; bad=1
    fi

    # 10б. На подложенных числах вернувшийся live-оракул выглядел бы исправным —
    #      видно его только по тексту скрипта. Заодно это стережёт единственный
    #      в проекте запрос к pg_extension: на него опирается задача 0238.
    set +e; out="$(oracle_verdict "$SELF")"; rc=$?; set -e
    if [ "$rc" = 0 ]; then
        printf '  ✓ оракул — опись набора; к живой базе остался один запрос, про расширения\n'
    else
        printf '\033[1;31m  ✗ %s\033[0m\n' "$out"; bad=1
    fi

    # 10в. Возврат дефекта оракула: дописанная сверка по живой базе обязана
    #      краснеть. Строка собирается из кусков — написанная литералом, она
    #      нашлась бы в этом же файле и покрасила случай 10б на исправном коде.
    cat "$SELF" > "$tmp/oracle.sh"
    printf 'expected=$%s%s "$query")\n' '(' 'live' >> "$tmp/oracle.sh"
    set +e; out="$(oracle_verdict "$tmp/oracle.sh")"; rc=$?; set -e
    if [ "$rc" != 0 ] && says "$out" 'ОРАКУЛ'; then
        printf '  ✓ возврат дефекта: вернувшаяся сверка с живой базой краснеет\n'
    else
        printf '\033[1;31m  ✗ сверка с живой базой обязана краснеть — это дефект 0244\033[0m\n'
        printf '%s\n' "$out" | sed 's/^/      /'; bad=1
    fi

    # 11. НАСТОЯЩЕЕ КРАСНОЕ СОХРАНЕНО, и этот край важнее первого: дамп без
    #     движений склада. Проверка, переставшая краснеть на негодной копии,
    #     хуже отсутствующей — в 0157 за это уже заплачено.
    agg t_000042 stock_movement 5 5 0
    if [ "$rc" = 1 ] && says "$out" 'РАСХОЖДЕНИЕ' && says "$out" 'stock_movement' \
       && says "$out" 'журнале движений'; then
        printf '  ✓ набор без движений склада краснеет и называет, чего в нём нет\n'
    else
        printf '\033[1;31m  ✗ набор без движений склада обязан краснеть\033[0m\n'
        printf '%s\n' "$out" | sed 's/^/      /'; bad=1
    fi

    # 12. Урезанная таблица: позиций в копии меньше, чем снимали.
    agg t_000042 part 120 120 97
    if [ "$rc" = 1 ] && says "$out" '97' && says "$out" '120'; then
        printf '  ✓ урезанная таблица краснеет, оба числа названы\n'
    else
        printf '\033[1;31m  ✗ урезанная таблица обязана краснеть с обоими числами\033[0m\n'
        printf '%s\n' "$out" | sed 's/^/      /'; bad=1
    fi

    # 13. Остаток приезжает numeric(12,3): «12.000» и «12» — одно число.
    #     Строковое сравнение красило бы проверку на годной копии каждую неделю.
    agg t_000042 part_stock_qty 12.000 12.000 12
    [ "$rc" = 0 ] && printf '  ✓ «12.000» и «12» — одно и то же число\n' \
        || { printf '\033[1;31m  ✗ дробное представление остатка не должно краснеть\033[0m\n'; bad=1; }

    # 13б. А настоящая недостача остатка краснеет и на дробных.
    agg t_000042 part_stock_qty 12.000 12.000 11.000
    [ "$rc" = 1 ] && printf '  ✓ недостача остатка краснеет и на дробных числах\n' \
        || { printf '\033[1;31m  ✗ 11.000 против 12.000 обязано краснеть\033[0m\n'; bad=1; }

    # 14. В эти секунды писали: замеры вокруг дампа разошлись. Годным считается
    #     любое число между ними — и только между ними.
    agg t_000042 deal 5 7 6
    [ "$rc" = 0 ] && printf '  ✓ число между замерами вокруг дампа проходит\n' \
        || { printf '\033[1;31m  ✗ число между замерами обязано проходить\033[0m\n'; bad=1; }
    agg t_000042 deal 5 7 8
    if [ "$rc" = 1 ] && says "$out" 'Замеры вокруг дампа'; then
        printf '  ✓ число вне замеров краснеет и границы названы\n'
    else
        printf '\033[1;31m  ✗ число вне замеров обязано краснеть с названными границами\033[0m\n'
        printf '%s\n' "$out" | sed 's/^/      /'; bad=1
    fi
    agg t_000042 deal 5 7 4
    [ "$rc" = 1 ] && printf '  ✓ недостача ниже обоих замеров краснеет\n' \
        || { printf '\033[1;31m  ✗ 4 при замерах 5 и 7 обязано краснеть\033[0m\n'; bad=1; }

    # 15. Набор прежней сборки: чисел в описи нет. Это «НЕ СВЕРЕНО» словами,
    #     а не тихое «сошлось»: выдать одно за другое — дефект 0157.
    agg t_000042 part "" "" 10
    if [ "$rc" = 2 ] && says "$out" 'НЕ СВЕРЕНО'; then
        printf '  ✓ набор без чисел в описи назван не сверенным, а не зелёным\n'
    else
        printf '\033[1;31m  ✗ отсутствие чисел в описи обязано называться словами\033[0m\n'
        printf '%s\n' "$out" | sed 's/^/      /'; bad=1
    fi

    # 16. Круг «записали → прочитали» на настоящем файле описи: читается то же,
    #     что пишет бэкап, своя схема не подменяется чужой, а ненаписанная
    #     метрика отдаёт пусто (то есть «не сверено», а не ноль).
    {
        echo "снято: 20260101T030000Z"
        echo "база: parts_blue_0123456789ab"
        echo "арендаторов: 2"
        echo "42 t_000042 yardt ACTIVE"
        agg_line t_000042 part 10 11
        agg_line t_000099 part 7 7
    } > "$tmp/manifest.txt"
    pair="$(agg_pair "$tmp/manifest.txt" t_000042 part)"
    if [ "$pair" = "10 11" ] \
       && [ "$(agg_pair "$tmp/manifest.txt" t_000099 part)" = "7 7" ] \
       && [ -z "$(agg_pair "$tmp/manifest.txt" t_000042 deal)" ] \
       && [ "$(sed -n 's/^арендаторов: \([0-9]\{1,\}\)$/\1/p' "$tmp/manifest.txt")" = "2" ]; then
        printf '  ✓ опись: числа читаются по схеме и метрике, начало файла не тронуто\n'
    else
        printf '\033[1;31m  ✗ круг «записали → прочитали» в описи не сошёлся: «%s»\033[0m\n' "$pair"
        bad=1
    fi

    # 16б. И бэкап обязан их писать: оракул, который перестали записывать, —
    #      это та же проверка без сверки, только молча.
    if grep -q 'backup-aggregates.sh' ops/backup.sh && grep -q 'agg_line' ops/backup.sh; then
        printf '  ✓ ops/backup.sh пишет числа тем же списком, что читает проверка\n'
    else
        printf '\033[1;31m  ✗ ops/backup.sh перестал писать числа в опись — сверять будет нечем\033[0m\n'
        bad=1
    fi

    # 17. ВОЗВРАТ ДЕФЕКТА №2: вердикт агрегата, всегда отвечающий «годно», —
    #     это проверка, не сверяющая ничего. Самопроверка обязана упасть,
    #     и упасть именно на негодной копии. Ребёнку случай выключен — рекурсия.
    if [ -z "${VERIFY_BACKUP_SELFTEST_CHILD:-}" ]; then
        plant '    local schema="$1" metric="$2"' '    return 0
    local schema="$1" metric="$2"'
        child
        if [ "$rc" != 0 ] && grep -q 'без движений склада' "$tmp/fake.log"; then
            printf '  ✓ возврат дефекта: с всегда годным вердиктом самопроверка падает\n'
        else
            printf '\033[1;31m  ✗ подделка «агрегат всегда сходится» обязана валить самопроверку\033[0m\n'
            sed 's/^/      /' "$tmp/fake.log"; bad=1
        fi
    fi

    # --- отметка в наблюдении: задержана на несверенном наборе (задача 0245) --

    # 18. ГЛАВНЫЙ СЛУЧАЙ. Отметка была одна на оба исхода, то есть «агрегаты
    #     НЕ сверены» видел только человек, читающий вывод: в наблюдении такой
    #     набор выглядел проверенным, и правило БэкапНеПроверялся молчало.
    #     Проверяется ПЕРЕБОРОМ ОТПРАВЛЕННОГО, а не кодом возврата: «решили
    #     не ставить» и «ничего не ушло» — разные утверждения.
    cat > "$tmp/push" <<'EOF'
#!/bin/sh
printf '%s\n' "$*" > "$PUSH_ARGV"
cat > "$PUSH_BODY"
EOF
    chmod +x "$tmp/push"
    # Образец адреса собирается на ходу по той же причине, что в mark_gate_verdict:
    # литерал в этом файле сторож нашёл бы ВНЕ send_mark и покраснел бы
    # на исправном коде.
    urlneedle="$(printf 'metrics/job/%s' backup)"

    rm -f "$tmp/argv" "$tmp/body"
    set +e
    out="$(PUSH_ARGV="$tmp/argv" PUSH_BODY="$tmp/body" \
        send_mark 1 http://pushgateway:9091 "$tmp/push")"
    rc=$?
    set -e
    if [ "$rc" = 2 ] && says "$out" 'НЕ СТАВИТСЯ' && says "$out" 'БэкапНеПроверялся' \
       && [ ! -f "$tmp/argv" ]; then
        printf '  ✓ несверенный набор: отметка не уходит вовсе, и названа тревога, которая загорится\n'
    else
        printf '\033[1;31m  ✗ на несверенном наборе отметка обязана НЕ уходить и называть тревогу\033[0m\n'
        printf '%s\n' "$out" | sed 's/^/      /'; bad=1
    fi

    # 18б. ОБРАТНЫЙ КРАЙ, и он важнее первого: сверенный набор отметку СТАВИТ.
    #      Проверка, не ставящая её никогда, тушит тревогу насовсем — «бэкап
    #      не проверялся» перестало бы приходить и тогда, когда проверка вообще
    #      не идёт, то есть дыра 0157 вернулась бы с другой стороны.
    rm -f "$tmp/argv" "$tmp/body"
    set +e
    out="$(PUSH_ARGV="$tmp/argv" PUSH_BODY="$tmp/body" \
        send_mark 0 http://pushgateway:9091 "$tmp/push")"
    rc=$?
    set -e
    if [ "$rc" = 0 ] && [ -f "$tmp/argv" ] \
       && says "$(cat "$tmp/argv")" "$urlneedle" \
       && says "$(cat "$tmp/body")" 'partsflow_backup_verified_timestamp_seconds'; then
        printf '  ✓ сверенный набор: отметка уходит в pushgateway\n'
    else
        printf '\033[1;31m  ✗ сверенный набор обязан ставить отметку\033[0m\n'
        printf '%s\n' "$out" | sed 's/^/      /'; bad=1
    fi

    # 18в. Отметку ставит ровно одно место. Безусловная отправка, вернувшаяся
    #      рядом, на подложенных признаках выглядела бы исправной — видна она
    #      только по тексту скрипта.
    set +e; out="$(mark_gate_verdict "$SELF")"; rc=$?; set -e
    if [ "$rc" = 0 ]; then
        printf '  ✓ отправка отметки стоит только внутри send_mark\n'
    else
        printf '\033[1;31m  ✗ %s\033[0m\n' "$out"; bad=1
    fi

    # 19. ВОЗВРАТ ДЕФЕКТА №3: отметка, уходящая и без сверки, — это прежняя
    #     редакция. Её самопроверка обязана упасть, иначе случай 18 ничего
    #     не утверждает. Ребёнку случай выключен — рекурсия.
    if [ -z "${VERIFY_BACKUP_SELFTEST_CHILD:-}" ]; then
        plant '    if [ "$unverified" != 0 ]; then' '    if false; then'
        child
        if [ "$rc" != 0 ] && grep -q 'обязана НЕ уходить' "$tmp/fake.log"; then
            printf '  ✓ возврат дефекта: отметка, уходящая без сверки, валит самопроверку\n'
        else
            printf '\033[1;31m  ✗ подделка «ставим отметку всегда» обязана валить самопроверку\033[0m\n'
            sed 's/^/      /' "$tmp/fake.log"; bad=1
        fi

        # 19б. ВОЗВРАТ ДЕФЕКТА №4: отправка, дописанная ВНЕ send_mark, — то есть
        #      условие, которое обходится одной строкой рядом. Строка собирается
        #      на ходу: написанная литералом, она нашлась бы в этом же файле
        #      и покрасила случай 18в на исправном коде.
        plant 'step "Готовим чистую базу для проверки"' \
            "curl -sf --data-binary @- \"http://x/${urlneedle}\" > /dev/null
step \"Готовим чистую базу для проверки\""
        child
        if [ "$rc" != 0 ] && grep -q 'вне send_mark' "$tmp/fake.log"; then
            printf '  ✓ возврат дефекта: отправка вне send_mark краснеет\n'
        else
            printf '\033[1;31m  ✗ отправка вне send_mark обязана валить самопроверку\033[0m\n'
            sed 's/^/      /' "$tmp/fake.log"; bad=1
        fi
    fi

    [ $bad = 0 ] || { printf '\033[1;31mСамопроверка не прошла\033[0m\n'; exit 1; }
    printf '\033[1;32mСамопроверка пройдена: вердикты на подложенных выводах. Набор не разворачивался, бэкап не проверен.\033[0m\n'
}

