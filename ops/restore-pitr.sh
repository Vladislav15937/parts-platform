#!/usr/bin/env bash
# Возврат к моменту времени: базовая копия + накат архива WAL.
#
#   ops/restore-pitr.sh --to '2026-09-12 13:59:00 MSK'          # поднять состояние на 13:59 по Москве
#   ops/restore-pitr.sh --to '...' --tenant t_000042            # и вынуть одного клиента
#   ops/restore-pitr.sh --to latest                             # до конца архива
#   ops/restore-pitr.sh --verify                                # репетиция, так зовёт cron
#   ops/restore-pitr.sh --selftest                              # проверка разбора момента
#
# ЧАСОВОЙ ПОЯС В --to ОБЯЗАТЕЛЕН, и это половина цены ошибки здесь. Архив WAL
# живёт в UTC, а время, которое называет человек, — чьё-то местное: журнал
# контейнера пишет UTC, клиент по телефону называет своё, часы этой машины
# показывают третье. Возврат на три часа мимо проходит УСПЕШНО — кластер
# поднимается, данные на месте, просто не те, — и проверить это оператору
# нечем. До 13 сентября 2026 момент молча толковался в поясе машины, и на этом
# ошибся не оператор в четыре утра, а разбор задачи 0083: человек, читавший
# код целиком и специально проверявший работу. Разбор момента и его эхо —
# в ops/moment.sh.
#
# Ключевое решение: разворот идёт в ОТДЕЛЬНЫЙ временный кластер, а не поверх
# живого. Причин две, и обе про схему-на-арендатора.
#
# Первая: накат WAL возвращает кластер ЦЕЛИКОМ, то есть всех арендаторов
# на один момент. Если у одного клиента авария, а остальные работают, возврат
# поверх живой базы отнял бы у остальных всё, что они наработали с этого
# момента, — и именно от этого schema-per-tenant защищает. Во временном
# кластере состояние на нужный момент есть у всех, а забрать из него можно
# ОДНОГО: pg_dump одной схемы, дальше обычный ops/restore-tenant.sh.
#
# Вторая: разворот поверх живого невозвратим. Ошибся с моментом — второй
# попытки нет, потому что то, чем ты пользовался, уже перезаписано.
# Во временном кластере ошибка с моментом стоит повторного прогона.
#
# Что делать, когда погиб весь кластер, а не один клиент: поднять временный
# так же, убедиться, что момент тот, и переключить ячейку на его каталог
# данных (порядок — в docs/deployment.md, «Возврат к моменту времени»).
#
# ОТКАЗ ВМЕСТО ТИХОГО ВОССТАНОВЛЕНИЯ. Разрыв в архиве Postgres переживает
# молча: накат останавливается на пропавшем сегменте, и — если момент
# не задан — кластер поднимается на том, что успел накатить. Снаружи это
# выглядит успехом: база работает, данные есть, просто не все. Поэтому
# цепочка проверяется ДО разворота (ops/wal-archive.sh --chain), а после
# разворота сверяется, что накат дошёл до запрошенного момента, а не
# остановился раньше. Оба сторожа нужны: первый называет доступный момент
# заранее, второй ловит то, чего в именах файлов не видно.
set -euo pipefail
cd "$(dirname "$0")/.."
# Разбор момента общий с ops/wal-archive.sh: «к какому моменту возвращаемся»
# и «до какого можно вернуться» обязаны понимать введённое одинаково.
. ops/moment.sh

TARGET=""
TENANT=""
BASE_DIR=""
KEEP=0
VERIFY=0
SELFTEST=0
PITR_DB=""

while [ $# -gt 0 ]; do
    case "$1" in
        --to)       TARGET="${2:?укажите момент или latest}"; shift 2 ;;
        --tenant)   TENANT="${2:?укажите схему, например t_000042}"; shift 2 ;;
        --base)     BASE_DIR="${2:?укажите каталог базовой копии}"; shift 2 ;;
        --keep)     KEEP=1; shift ;;
        --db)       PITR_DB="${2:?укажите имя базы, например parts_green_1a2b3c4d5e6f}"; shift 2 ;;
        --verify)   VERIFY=1; shift ;;
        --selftest) SELFTEST=1; shift ;;
        *)          printf 'Использование: %s --to "МОМЕНТ ПОЯС"|latest [--tenant СХЕМА] [--base КАТАЛОГ] [--db БАЗА] [--keep]\n' "$0" >&2
                    printf '               %s --verify | --selftest\n' "$0" >&2
                    exit 2 ;;
    esac
done

# --- Времена в сообщениях ----------------------------------------------------
#
# Стоят ДО окружения и docker намеренно: сообщения не зависят ни от того,
# ни от другого, а самопроверка ниже смотрит на них и обязана идти в CI.
#
# ПОЯС НАЗЫВАЕТСЯ ВСЕГДА — молчащее время читается как время читающего. Но
# этого мало, и задача 0096 ровно про это: момент, который назвал ОПЕРАТОР,
# обязан вернуться к нему тем же числом, каким он его назвал. Он сверяет ответ
# с тем, что записал у себя или услышал по телефону, а не с часами машины
# возврата, — и «13:59 MSK», приехавшее как «17:59 +07», это третье число
# вместо его собственного. Данные при этом верны, и тем хуже: человек
# сравнивает два числа, думая, что они об одном. А читают это сообщение ровно
# тогда, когда возврат НЕ получился, то есть при разборе аварии в четыре утра.
#
# У времён, которых никто не называл (мтайм сегмента, «сейчас» у --to latest
# и --verify), своего пояса нет вовсе, и пояс машины — единственный честный
# ответ. Поэтому ветку решает moment_named, а не флаг вызова.
human() {
    if moment_named; then
        moment_named_text "$1"
    else
        date -d "@$1" '+%Y-%m-%d %H:%M:%S %Z' 2>/dev/null \
            || date -r "$1" '+%Y-%m-%d %H:%M:%S %Z'
    fi
}
# Метка набора: 20260912T162000Z.
stamp_epoch() {
    local s="$1"
    date -u -d "${s:0:4}-${s:4:2}-${s:6:2} ${s:9:2}:${s:11:2}:${s:13:2}" +%s 2>/dev/null \
        || date -u -j -f '%Y%m%dT%H%M%SZ' "$s" +%s
}
# Метка — это UTC, а сверяют её с названным моментом: «есть ли копия не позже
# 13:59 MSK». Поэтому время снятия печатается тем же способом, что и отказ
# ниже, — иначе одна и та же сверка читается в двух разных поясах.
stamp_human() {
    local s="$1" e
    case "$s" in
        # Каталог, названный руками через --base, меткой может и не быть:
        # времени в нём тогда нет, и выдумывать его нельзя.
        20[0-9][0-9][01][0-9][0-3][0-9]T[0-2][0-9][0-5][0-9][0-5][0-9]Z) ;;
        *) return 1 ;;
    esac
    e=$(stamp_epoch "$s") || return 1
    [ -n "$e" ] || return 1
    human "$e"
}
# Отказ, ради которого задача 0096 и заведена: момент в нём — тот самый,
# который назвал оператор. Отдельной функцией, чтобы самопроверка смотрела
# на само сообщение, а не на его половину.
no_base_text() {
    printf 'нет базовой копии не позже %s — проверьте %s и ops/basebackup.sh\n' \
        "$(human "$1")" "$2"
}

# Каталог базовых копий: «его нет вовсе», «он не читается» и «копии в нём
# не нашлось» — три разные беды (задача 0148), и первые две прежняя редакция
# называла третьей. `find "$BASES" … 2>/dev/null` на недоступном каталоге
# отдаёт пустой список, и возврат отвечал `no_base_text` — то есть объявлял
# отсутствие копии, не сумев её поискать. Это та же ложь, которую у архива WAL
# чинила 0137 («в архиве нет ни одного сегмента» при полном архиве), и читают
# её в аварию: человек идёт снимать новую копию вместо того, чтобы вернуть
# права, — а снять её в аварию может быть уже не с чего.
bases_verdict() {   # $1 — каталог базовых копий
    local asked=yes   # 0148-каталог
    { [ -d "$1" ] && [ -r "$1" ] && [ -x "$1" ]; } || asked=no
    [ "$asked" = no ] || return 0
    if [ ! -d "$1" ]; then
        printf 'каталога базовых копий нет вовсе: %s — ЕСТЬ ли копия, не проверено\n' "$1"
    else
        printf 'каталог базовых копий не читается этим пользователем: %s — ЕСТЬ ли копия, не проверено\n' "$1"
    fi
    return 2
}

# Немой psql отдаёт ПУСТУЮ строку с НУЛЕВЫМ кодом, и дальше эта пустота
# читается как данные (задача 0148): «базы $PITR_DB нет; есть: ‹пусто›»
# и «накат встал на ‹пусто›, а в архиве есть …». Красные оба вердикта
# правильно — а причина в них подменена: спросить у копии не вышло, и ни
# «базы нет», ни «восстановлено не всё» этим не установлено.
#
# Ответ отдаётся в stdout, отказ — в stderr и ненулевым кодом: функцию зовут
# из `$( )`, то есть из подоболочки, откуда ни `fail`, ни переменная наружу
# не доезжают (тот же урок, что в 0151 у банки cookie).
PITR_DOCKER="${PITR_DOCKER:-docker}"
qc_asked() {   # $1 — запрос, $2 — что спрашиваем словами
    local out rc=0 why errf
    errf="$(mktemp)"
    out=$($PITR_DOCKER exec "$CNAME" psql -U "$DB_USER" -d postgres -tAqc "$1" 2>"$errf") || rc=$?
    why=$(sed -n '1,2p' "$errf" | tr '\n' ' ')
    rm -f "$errf"
    local asked=yes   # 0148-psql
    { [ "$rc" = 0 ] && [ -n "$out" ]; } || asked=no
    if [ "$asked" = no ]; then
        printf '\033[1;31m    ОШИБКА: %s — СПРОСИТЬ У КОПИИ НЕ ВЫШЛО: psql вышел кодом %s%s\033[0m\n' \
            "$2" "$rc" "${why:+ — $why}" >&2
        printf '\033[1;31m    Пустой ответ здесь НЕ данные: этим не установлено ни «базы нет», ни «восстановлено не всё».\033[0m\n' >&2
        return 1
    fi
    printf '%s\n' "$out"
}

# --- Самопроверка времён в сообщениях ----------------------------------------
#
# Пояс в сообщении ошибается ТИХО: неверный выглядит ровно как верный, а числа
# при этом правильные. Установить, что сообщение говорит поясом оператора,
# можно только попыткой.
pitr_selftest() {
    local bad=0 mark=0 out want here
    _p_ok()   { printf '\033[1;32m    %s\033[0m\n' "$1"; }
    _p_bad()  { printf '\033[1;31m    САМОПРОВЕРКА: %s\033[0m\n' "$1"; bad=$(( bad + 1 )); }
    _p_done() { if [ "$bad" = "$mark" ]; then _p_ok "$1"; fi; mark=$bad; }

    # Пояс машины отличается и от UTC, и от московского: на раннере машина
    # живёт в UTC, и там «пояс машины» совпал бы с UTC — то есть разница, ради
    # которой задача заведена, не проверялась бы вовсе.
    export TZ="Asia/Novosibirsk"      # +07, без перевода часов
    if [ ! -f "/usr/share/zoneinfo/$TZ" ] || [ ! -f /usr/share/zoneinfo/Europe/Moscow ]
    then
        _p_bad 'нет базы часовых поясов (/usr/share/zoneinfo) — TZ молча стал бы UTC'
        unset TZ
        return 1
    fi

    moment_parse '2026-09-12 13:59:00 MSK' > /dev/null 2>&1 \
        || _p_bad 'момент не разобран — дальше проверять нечего'
    want="$(moment_local_text) ${MOMENT_LABEL}"
    here=$(date -d "@${MOMENT_EPOCH}" '+%H:%M:%S' 2>/dev/null \
           || date -r "${MOMENT_EPOCH}" '+%H:%M:%S')

    out=$(no_base_text "${MOMENT_EPOCH}" './backups/cell01/base')
    case "$out" in
        *"${want}"*) : ;;
        *) _p_bad "отказ называет момент не так, как его назвали (${want}): ${out}" ;;
    esac
    case "$out" in
        # Часы машины на месте названного момента — это и есть дефект 0096.
        *"${here}"*) _p_bad "отказ печатает момент по часам машины (${here}): ${out}" ;;
    esac
    case "$out" in
        *"$(moment_utc_text) UTC"*) : ;;
        *) _p_bad "отказ не называет UTC, в котором живёт архив: ${out}" ;;
    esac
    case "$out" in
        *'нет базовой копии не позже'*) : ;;
        *) _p_bad "это перестало быть тем сообщением: ${out}" ;;
    esac
    _p_done 'отказ «нет базовой копии» называет момент поясом, которым его назвали'

    # Обратный край: момента никто не называл (--to latest, --verify). Своего
    # пояса у «сейчас» нет, и пояс машины тут единственный честный ответ —
    # без этого случая «починку», печатающую всё в UTC, проверка приняла бы.
    MOMENT_NAMED=0
    out=$(no_base_text "${MOMENT_EPOCH}" './backups/cell01/base')
    case "$out" in
        *"${here}"*) : ;;
        *) _p_bad "без названного момента время идёт не по часам машины (${here}): ${out}" ;;
    esac
    case "$out" in
        *'+07'*|*NOVT*) : ;;
        *) _p_bad "время без пояса — читается как время читающего: ${out}" ;;
    esac
    _p_done 'без названного момента время идёт по часам машины, и пояс назван'

    # Время снятия копии — та же сверка, что и в отказе, значит тот же пояс.
    moment_parse '2026-09-12 13:59:00 MSK' > /dev/null 2>&1 \
        || _p_bad 'момент не разобран'
    out=$(stamp_human 20260912T162000Z)
    case "$out" in
        *'2026-09-12 19:20:00 MSK'*) : ;;
        *) _p_bad "время снятия копии напечатано не поясом момента: ${out}" ;;
    esac
    case "$out" in
        *'16:20:00 UTC'*) : ;;
        *) _p_bad "время снятия копии не названо в UTC: ${out}" ;;
    esac
    if stamp_human 'svoy-katalog' > /dev/null 2>&1; then
        _p_bad 'из каталога без метки достали время — такое время выдумано'
    fi
    _p_done 'время снятия копии названо тем же поясом, а каталог без метки — нет'

    # КАТАЛОГ БАЗОВЫХ КОПИЙ: «нет вовсе», «не читается» и «копии не нашлось» —
    # три разных ответа (задача 0148), и первые два прежняя редакция называла
    # третьим, потому что `find … 2>/dev/null` на недоступном каталоге отдаёт
    # пустой список.
    local bdir
    bdir="$(mktemp -d)"
    mkdir -p "$bdir/backups/base"
    local bv_out bv_rc
    set +e
    bv_out=$(bases_verdict "$bdir/backups/base" 2>&1); bv_rc=$?
    set -e
    [ "$bv_rc" = 0 ] || _p_bad "целый каталог копий объявлен недоступным: ${bv_out}"
    set +e
    bv_out=$(bases_verdict "$bdir/net-takogo" 2>&1); bv_rc=$?
    set -e
    [ "$bv_rc" != 0 ] || _p_bad 'пропавший каталог копий объявлен целым'
    case "$bv_out" in
        *'нет вовсе'*) : ;;
        *) _p_bad "пропавший каталог назван не тем: ${bv_out}" ;;
    esac
    case "$bv_out" in
        *'нет базовой копии не позже'*)
            _p_bad "НЕИЗМЕРЕННОЕ: пропавший каталог назван отсутствием копии: ${bv_out}" ;;
    esac
    _p_done 'пропавший каталог базовых копий назван пропавшим, а не «копии нет»'

    if [ "$(id -u)" = 0 ]; then
        # Честнее сказать, чем промолчать: под root права не отбиваются никому,
        # и случай прошёл бы «зелёным» ни о чём (приём ops/install-cron.sh).
        printf '    прогон под root — случаи про права каталога копий не проверены\n'
    else
        chmod 000 "$bdir/backups/base"
        set +e
        bv_out=$(bases_verdict "$bdir/backups/base" 2>&1); bv_rc=$?
        set -e
        [ "$bv_rc" != 0 ] || _p_bad 'нечитаемый каталог копий объявлен целым'
        case "$bv_out" in
            *'не читается'*) : ;;
            *) _p_bad "нечитаемый каталог назван не тем: ${bv_out}" ;;
        esac
        case "$bv_out" in
            *'нет базовой копии не позже'*)
                _p_bad "НЕИЗМЕРЕННОЕ: нечитаемый каталог назван отсутствием копии: ${bv_out}" ;;
        esac
        _p_done 'нечитаемый каталог базовых копий назван нечитаемым'

        # И то же — ПРОГОНОМ ВСЕГО ПУТИ: вердикт надо ещё позвать, а прежняя
        # редакция до него не доходила вовсе (урок 0144: проба, зовущая
        # функцию, не проверяет того, что делает запуск). docker здесь
        # не нужен — отказ приходит раньше разворота.
        local rp_out rp_rc
        set +e
        rp_out=$(ENV_FILE=/dev/null DB_USER=app BACKUP_DIR="$bdir/backups" \
            bash "$0" --to '2026-09-12 13:59:00 MSK' 2>&1); rp_rc=$?
        set -e
        [ "$rp_rc" != 0 ] || _p_bad 'возврат на нечитаемом каталоге копий вышел нулём'
        case "$rp_out" in
            *'не читается'*) : ;;
            *) _p_bad "путь запуска не называет нечитаемый каталог: $(printf '%s' "${rp_out}" | tr '\n' ' ')" ;;
        esac
        case "$rp_out" in
            *'нет базовой копии не позже'*)
                _p_bad 'НЕИЗМЕРЕННОЕ: путь запуска назвал это отсутствием копии' ;;
        esac
        _p_done 'путь запуска на нечитаемом каталоге говорит про права, а не про отсутствие копии'
        chmod 755 "$bdir/backups/base"
    fi

    # НЕМОЙ psql: пустая строка с нулевым кодом — это не данные (задача 0148).
    # `docker` подменяется заглушкой: предмет здесь — что делает qc_asked
    # с ответом, а не живой кластер.
    mkdir -p "$bdir/bin"
    cat > "$bdir/bin/docker" <<'DOCKER'
#!/bin/sh
case "${STUB_PSQL:-ответ}" in
    ответ)  printf '000000010000000000000099\n'; exit 0 ;;
    немой)  exit 0 ;;
    отказ)  printf 'psql: error: connection to server failed\n' >&2; exit 2 ;;
esac
DOCKER
    chmod +x "$bdir/bin/docker"
    CNAME=zaglushka
    DB_USER=app
    PITR_DOCKER="$bdir/bin/docker"
    qa() {   # режим заглушки → «код|ответ|слова»
        local out rc=0 err
        err="$(mktemp)"
        out=$(STUB_PSQL="$1" qc_asked 'SELECT 1' 'до какого сегмента дошёл накат' 2>"$err") || rc=$?
        printf '%s|%s|%s\n' "$rc" "$out" "$(tr '\n' ' ' < "$err")"
        rm -f "$err"
    }
    local qa_out
    qa_out=$(qa ответ)
    case "$qa_out" in
        "0|000000010000000000000099|"*) : ;;
        *) _p_bad "ответ psql не доехал: ${qa_out}" ;;
    esac
    qa_out=$(qa немой)
    case "$qa_out" in
        0\|*) _p_bad "пустой ответ немого psql принят за данные: ${qa_out}" ;;
        *'СПРОСИТЬ У КОПИИ НЕ ВЫШЛО'*) : ;;
        *) _p_bad "пустой ответ назван не тем: ${qa_out}" ;;
    esac
    qa_out=$(qa отказ)
    case "$qa_out" in
        *'кодом 2'*'connection to server failed'*) : ;;
        *) _p_bad "отказ psql не назван своим кодом и словами: ${qa_out}" ;;
    esac
    _p_done 'немой и отказавший psql названы неотвеченным вопросом, а не данными'

    # ВОЗВРАТ ДЕФЕКТА, две подделки — по одной на находку. Копии лежат
    # в `.scratch/`: каталог игнорируется git и стоит на той же глубине,
    # что `ops/`, то есть корень репозитория разрешается туда же (0151, 0248).
    if [ -n "${PITR_SELFTEST_FAKE:-}" ]; then
        printf '    подделки своей копии не заводим — рекурсии нет\n'
    else
        mkdir -p .scratch
        local fake rcf
        for fake in каталог psql; do
            rcf=".scratch/restore-pitr-${fake}-fake-0148.sh"
            case "$fake" in
                каталог) sed 's|^    local asked=yes   # 0148-каталог$|    local asked=yes; set -- "."|' "$0" > "$rcf" ;;
                psql)    sed 's|^    local asked=yes   # 0148-psql$|    local asked=yes; out="${out:-0}"|' "$0" > "$rcf" ;;
            esac
            if ! grep -q 'local asked=yes; ' "$rcf"; then
                _p_bad "подделку «${fake}» негде поставить — случаи выше ничего не утверждают"
            elif ! bash -n "$rcf" 2>/dev/null; then
                _p_bad "подделка «${fake}» сломала синтаксис — её красное скажет не о том"
            elif PITR_SELFTEST_FAKE=yes bash "$rcf" --selftest >/dev/null 2>&1; then
                _p_bad "ВОЗВРАТ ДЕФЕКТА «${fake}»: прежнее поведение самопроверку НЕ валит"
            fi
            rm -f "$rcf"
        done
        _p_done 'возврат дефекта: обе прежние редакции валят самопроверку'
    fi
    rm -rf "$bdir"

    unset TZ
    [ "$bad" = 0 ] || return 1
    return 0
}

