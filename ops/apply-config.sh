MOUNTS_FILE="${APPLY_CONFIG_MOUNTS:-}"   # подложенные монтирования
PS_FILE="${APPLY_CONFIG_PS:-}"           # подложенный список работающих
SEEN_SH="${APPLY_CONFIG_SEEN_SH:-}"      # подложенное «что видит контейнер»
DO_FILE="${APPLY_CONFIG_DO:-}"           # куда писать команды вместо выполнения

