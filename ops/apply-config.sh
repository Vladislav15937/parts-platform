#!/usr/bin/env bash
# Привезённая настройка начинает действовать — или названа поимённо.
#
#   ops/apply-config.sh             # читающий отчёт: что требует применения
#   ops/apply-config.sh --apply     # применить дешёвое, дорогое НАЗВАТЬ
#   ops/apply-config.sh --selftest  # проверить самого сторожа на подделках
#
# ЗАЧЕМ ОН ЕСТЬ. Выкладка кладёт `ops/` целиком (rsync, задача 0111)
# и не применяет НИЧЕГО: из десяти файлов со шагом применения она делала один —
# перечитку терминатора при переводе трафика. Правило существовало только
# в прозе (`ops/CLAUDE.md`: «подменив ops/*.sh, смонтированный в контейнер
# отдельным файлом, пересоздай контейнер»), и слово `force-recreate`
# встречалось во всём дереве ровно в одной памятке — ни в одном скрипте,
# ни в одном шаге выкладки, ни в одном шаге CI.
#
# Стоило это трёх случаев на живой ячейке, и все три молчали:
#
#   19 сентября 2026 — ops/archive-wal.sh. Новый файл лёг на хост, а Postgres
#     продолжал исполнять старый: bind-mount ОДНОГО файла разрешается в inode
#     один раз, при старте контейнера, а rsync подменяет файл новым (inode
#     на хосте 537925, внутри контейнера 537927). Снаружи всё исправно — база
#     здорова, архивация пишет, отказов ноль, — а сегменты ложились с правами
#     600 и наружу НЕ УЕЗЖАЛИ: точки возврата не было при исправной с виду
#     ячейке. Это единственный живой выстрел класса, и он один стоит всей
#     задачи.
#   ops/alerts.yml — правило в файле ещё не тревога: `ФотоНеБэкапились`
#     неделю не знала ячейка, шесть правил в файле против пяти в памяти.
#   20–28 сентября 2026 — ops/install-cron.sh. Прокрутка журнала (0154) лежала
#     в main с 20 сентября, файл приехал, расписание никто не переустановил:
#     восемь дней журнал рос без предела.
#
# РЕШЕНИЕ ВЛАДЕЛЬЦА от 28 сентября 2026, дословно: «расхождение красит,
# выкладка применяет». Вторая половина — про этот скрипт: привезённое
# применяет САМА ВЫКЛАДКА, а не человек отдельным шагом. Порядок «человек
# применит» отклонён замером: ровно он подвёл 20 сентября — шаг, который
# делают по памяти, однажды не сделают, и узнают об этом через неделю.
#
# ЧЕМ ПЛАТИМ — РЕШЕНИЕ ИСПОЛНИТЕЛЯ, И ОНО ЖДЁТ ВЛАДЕЛЬЦА. Решение отвечает
# на вопрос «кто применяет», а не «чем платим», и прочтённое буквально внесло
# бы простой базы в выкладку, которая этого файла не касалась вовсе. Поэтому
# шаги разведены на два разряда, и разряд у каждого назван в таблице ниже:
#
#   сама    — клиента не видно: наблюдение (prometheus, alertmanager,
#             alert-watch) и расписание. Замерено 0,5–0,8 с на контейнер,
#             трафика и базы не касается.
#   человек — клиента ВИДНО: postgres (простой записи И чтения) и caddy (вход
#             в ячейку). Выкладка их не трогает, называет поимённо, печатает
#             цену и готовую команду. Вопрос владельцу назван в tasks/0216:
#             разрешать ли выкладке пересоздавать postgres и caddy — и красить
#             ли выкладку, у которой дорогой шаг остался несделанным.
#
# И ПРИМЕНЯЕТСЯ ТОЛЬКО ТО, ЧТО ДЕЙСТВИТЕЛЬНО РАЗОШЛОСЬ. Это не экономия
# секунд: пересоздание prometheus СБРАСЫВАЕТ отсчёт `for:` у горящих тревог
# (замер задачи 0158 — тревога, горевшая шесть минут, вернулась в `pending`),
# а у трёх правил `for: 1h`. Пересоздавай его каждая выкладка — доставка
# накопленного отодвигалась бы на срок до часа, и выглядело бы это как
# «тревоги не работают». Поэтому сперва сверка, потом шаг.
#
# СВЕРЯЕТСЯ СОДЕРЖИМОЕ, А НЕ INODE — и сверяется ТО, ЧТО ВИДИТ КОНТЕЙНЕР.
# Первое: привезённый файл получает новый inode ВСЕГДА, на каждой выкладке
# и при полностью исправной ячейке, — сторож на inode краснел бы каждый раз
# и был бы отключён в первый день (тот же довод, что «ложная тревога дороже
# пропуска»). Inode доказывает «не тот объект», содержимое доказывает «другой
# текст», и нужно второе (задача 0215). Второе: спрашивать хост бессмысленно —
# 19 сентября на хосте лежал ПРАВИЛЬНЫЙ файл, и именно поэтому всё выглядело
# исправным. Вопрос задаётся контейнеру: `exec -T <сервис> cat <путь>`.
#
# ПЕРЕЧИТКА НА МЕСТЕ НЕ ГОДИТСЯ ПОСЛЕ RSYNC'А, и это следствие того же
# пиннинга inode: `/-/reload` у Prometheus перечитает файл ПО ТОМУ ЖЕ
# СМОНТИРОВАННОМУ ПУТИ, то есть прежний inode с прежним текстом. Команда
# из `docs/deployment.md` («Правило в файле — ещё не тревога») верна для
# РУЧНОГО пути, где файл приезжает `git show <SHA>:<файл> > <файл>`:
# перенаправление `>` пишет в существующий inode и сохраняет его. После
# rsync'а кнопки — нет. Поэтому у обоих файлов наблюдения шаг применения
# один и тот же: пересоздание контейнера.
#
# И ФЛАГ ОБЯЗАТЕЛЕН. `docker compose up -d <сервис>` сравнивает РЕЗОЛВНУТУЮ
# конфигурацию сервиса, а не содержимое смонтированного в него файла:
# поменялось только содержимое — команда печатает «Running» и не делает
# ничего. Замерено живым прогоном (задача 0158 и повторно этой задачей).
# `restart` не годится тем же: он сохраняет прежние монтирования.
#
# ЧТО СЧИТАЕТСЯ МОНТИРОВАНИЕМ — спрашиваем сам compose (`config --format
# json`), как это делает ops/config-guard.sh, а не читаем YAML глазами:
# какие пути монтируются и во что разворачиваются, считает он, по своим
# правилам интерполяции и `extends`. Отсюда же свойство, которого просила
# задача: ВОСЬМОЕ МОНТИРОВАНИЕ НЕЛЬЗЯ ЗАВЕСТИ МОЛЧА — у пути либо есть шаг
# применения, либо написано, почему его нет, иначе сторож краснеет.
#
# ГДЕ ЕГО ЗОВУТ: шагом ops/deploy.sh — сразу после ops/config-guard.sh
# и ДО заморозки записи. Порядок не случаен: состав настроек проверяется
# раньше их применения («файл на месте» — другой вопрос, чем «той ли он
# редакции»), а пересоздание контейнеров наблюдения не касается ни трафика,
# ни базы, и делать его внутри окна заморозки значило бы удлинять окно
# без нужды. Дежурный зовёт его читающим — без --apply.
#
#   COMPOSE_FILE=…            какой compose спрашивать (умолчание docker-compose.prod.yml)
#   ENV_FILE=…                файл окружения ячейки (умолчание .env)
#   DC=…                      чем спрашивать compose (умолчание docker compose)
#
# Коды возврата — четыре, и они различимы намеренно (образец — три исхода
# tools/head-green.sh): 0 применять нечего либо всё применено, 1 осталось
# названное человеку, 2 СПРОСИТЬ НЕ УДАЛОСЬ (это не «сходится»), 3 дешёвый
# шаг отказал или не подействовал.
set -uo pipefail

SELF="$(cd "$(dirname "$0")" && pwd)/$(basename "$0")"
# Корень переопределяет только самопроверка: ей нужно прогнать сторожа
# по подделанному дереву, не трогая настоящее.
ROOT="${APPLY_CONFIG_ROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
cd "$ROOT"

COMPOSE_FILE="${COMPOSE_FILE:-docker-compose.prod.yml}"
DC="${DC:-docker compose}"
ENV_FILE="${ENV_FILE:-.env}"
# Расписание знает про себя само: состав задач, маркеры и способ спросить
# crontab живут в одном файле, и второе место с тем же знанием разъехалось бы
# с первым молча.
