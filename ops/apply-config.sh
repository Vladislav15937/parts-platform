# ─────────────────────── таблица шагов применения ───────────────────────────
#
# Ключ — сервис и путь ВНУТРИ контейнера: путь на хосте зависит от каталога
# и от .env, а этот не зависит ни от чего и читается человеком. Тот же ключ,
# что у ops/config-guard.sh, — и это не совпадение: оба отвечают про одни
# и те же монтирования, только первый про «файл на месте», а этот про «та ли
# редакция действует».
#
# ЦЕНА У КАЖДОГО ШАГА НАЗВАНА ЧИСЛОМ ИЛИ СЛОВОМ «ПРОСТОЙ». Человек, читающий
# «нужно пересоздать postgres», обязан видеть, что это простой клиента, а не
# 0,8 секунды: иначе он выполнит дорогой шаг в середине рабочего дня.
TIER=""    # сама | человек | нет
STEP=""    # чем применяется
PRICE=""   # чем платим
WHY=""     # почему шага нет (только при TIER=нет)
rule() {  # сервис:путь-в-контейнере
    TIER=неизвестно
    STEP=""
    PRICE=""
    WHY=""
    case "$1" in
        # ── терминатор ──────────────────────────────────────────────────────
        caddy:/etc/caddy/Caddyfile)
            # ЧЕЛОВЕК, и это решение исполнителя. Терминатор — вход в ячейку:
            # его пересоздание означает секунды, в которые снаружи отвечает
            # 502 всем, а выкладка обещает, что простоя нет. Перечитка
            # на месте (`caddy reload`) после rsync'а не годится по той же
            # причине, что и у Prometheus: reload читает файл по
            # смонтированному пути, то есть прежний inode.
            TIER=человек
            STEP="$DC -f $COMPOSE_FILE up -d --force-recreate caddy"
            PRICE="ВХОД В ЯЧЕЙКУ: секунды, в которые снаружи 502 всем. Выкладка обещает, что простоя нет" ;;
        caddy:/etc/caddy/active-build.caddy)
            # СОСТОЯНИЕ, а не настройка: имя сборки под трафиком. Из репозитория
            # его не привозят вовсе (rsync исключает), пишет его на месте
            # ops/switch-build.sh — `>` в существующий inode, намеренно, — и
            # потому в исправной ячейке содержимое внутри и снаружи совпадает
            # само. Расхождение здесь означает ПОДМЕНЁННЫЙ INODE, то есть
            # следующее переключение сборок «пройдёт» и не случится.
            TIER=человек
            STEP="$DC -f $COMPOSE_FILE up -d --force-recreate caddy"
            PRICE="СОСТОЯНИЕ ЯЧЕЙКИ: inode подменён, и следующее переключение сборок пройдёт, не случившись. Вход в ячейку — секунды 502" ;;
        # ── база ────────────────────────────────────────────────────────────
        postgres:/usr/local/bin/archive-wal.sh)
            # ЧЕЛОВЕК, и это прямой запрет задачи: пересоздание postgres —
            # простой клиента, а выкладка обещает, что простоя нет (запись
            # мёрзнет 32–33 с, чтение работает). Тот самый файл, на котором
            # 19 сентября 2026 ячейка осталась без точки возврата.
            TIER=человек
            STEP="$DC -f $COMPOSE_FILE up -d --force-recreate postgres"
            PRICE="ПРОСТОЙ КЛИЕНТА: база встанет на секунды-десятки секунд — не только запись, но и чтение. Пока шаг не сделан, archive_command исполняет ПРЕЖНЮЮ редакцию: так 19 сентября 2026 сегменты WAL ложились с правами 600 и наружу не уезжали при здоровой с виду базе" ;;
        # ── наблюдение ──────────────────────────────────────────────────────
        prometheus:/etc/prometheus/prometheus.yml)
            TIER=сама
            STEP="$DC -f $COMPOSE_FILE up -d --force-recreate prometheus"
            PRICE="0,8 с. Сбрасывает отсчёт for: у горящих тревог — поэтому пересоздаётся ТОЛЬКО при настоящем расхождении" ;;
        prometheus:/etc/prometheus/alerts.yml)
            # Тот же шаг, что и у prometheus.yml, — и это не небрежность:
            # конфигурацию Prometheus генерирует `sed` в точке входа, поэтому
            # /-/reload перечитал бы сгенерированную копию, а не привезённый
            # файл; да и читал бы он прежний inode.
            TIER=сама
            STEP="$DC -f $COMPOSE_FILE up -d --force-recreate prometheus"
            PRICE="0,8 с. Правило в файле — ещё не тревога: до пересоздания в памяти живут прежние правила (так ФотоНеБэкапились неделю не знала ячейка)" ;;
        alertmanager:/etc/alertmanager/alertmanager.yml)
            TIER=сама
            STEP="$DC -f $COMPOSE_FILE up -d --force-recreate alertmanager"
            PRICE="0,5 с. До пересоздания тревоги считаются и уходят по ПРЕЖНЕЙ настройке доставки" ;;
        alertmanager:/etc/alertmanager/telegram-token)
            # Секрет, и в репозитории его нет — привезти его выкладка не может
            # (rsync исключает ops/secrets/). Расходится он, когда токен
            # заменил человек, и тогда шаг тот же и такой же дешёвый.
            # Сверяется СУММА, а не текст: сам токен наружу не печатается.
            TIER=сама
            STEP="$DC -f $COMPOSE_FILE up -d --force-recreate alertmanager"
            PRICE="0,5 с. До пересоздания диспетчер шлёт ПРЕЖНИМ токеном — молча, и механизм при этом выглядит работающим" ;;
        alert-watch:/usr/local/bin/alert-channel-check.sh)
            TIER=сама
            STEP="$DC -f $COMPOSE_FILE up -d --force-recreate alert-watch"
            PRICE="0,8 с. Сторож канала тревог — второй путь: до пересоздания в петле работает ПРЕЖНЯЯ редакция" ;;
        alert-watch:/etc/alert-channel/telegram-token)
            TIER=сама
            STEP="$DC -f $COMPOSE_FILE up -d --force-recreate alert-watch"
            PRICE="0,8 с. Второму пути нечем слать прежним токеном — молча" ;;
        # ── законный каталог ────────────────────────────────────────────────
        *:/wal-archive)
            # Каталог архива WAL: его готовит разовый wal-archive-init, а не
            # выкладка. Применять тут нечего — содержимое каталога и есть
            # данные, а не настройка.
            TIER=нет
            WHY="каталог архива WAL: данные, а не настройка — применять нечего" ;;
    esac
}

# ─────────────────────────── чем считать суммы ──────────────────────────────
#
# Два имени, потому что инструмент разный на ячейке (Linux, sha256sum)
# и у разработчика (macOS, shasum). Не нашлось ни одного — это «спросить
# не удалось», а не «сходится».
hash_stdin() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum | cut -d' ' -f1
    elif command -v shasum >/dev/null 2>&1; then
        shasum -a 256 | cut -d' ' -f1
    else
        return 1
    fi
}

# ─────────────────── монтирования: спрашиваем сам compose ───────────────────
#
# Профили названы все до одного по тому же доводу, что у ops/config-guard.sh:
# `config` печатает только сервисы включённых профилей, а сборки и служебные
# контейнеры стоят под своими — без этого половина монтирований
# не проверялась бы вовсе.
mounts() {
    if [ -n "$MOUNTS_FILE" ]; then
        cat "$MOUNTS_FILE"
        return $?
    fi
    $DC -f "$COMPOSE_FILE" --project-directory . --env-file "$ENV_FILE" \
        --profile blue --profile green --profile kafka --profile backup \
        config --format json 2>"$TMP/err" | python3 -c '
import json, sys
d = json.load(sys.stdin)
for name, svc in sorted((d.get("services") or {}).items()):
    for v in svc.get("volumes") or []:
        if v.get("type") != "bind":
            continue
        print("\t".join([name, v.get("target", ""), v.get("source", "")]))
'
}

# Какие сервисы РАБОТАЮТ. Погашенная сборка и разовый `mc` стоят под профилями
# законно, и краснеть на них значило бы краснеть на исправной ячейке. Сервис,
# контейнера у которого нет, новую редакцию прочитает при старте сам — это
# «применять нечего», а не «не спросить».
running() {
    if [ -n "$PS_FILE" ]; then
        cat "$PS_FILE"
        return $?
    fi
    $DC -f "$COMPOSE_FILE" --project-directory . --env-file "$ENV_FILE" \
        --profile blue --profile green --profile kafka --profile backup \
        ps --format json 2>"$TMP/err" | python3 -c '
import json, sys
raw = sys.stdin.read().strip()
rows = []
if raw:
    try:
        # Compose v2 отдаёт массив, v5 — по объекту на строку. Обе формы живые:
        # у разработчика одна версия, на ячейке другая.
        doc = json.loads(raw)
        rows = doc if isinstance(doc, list) else [doc]
    except ValueError:
        for line in raw.splitlines():
            line = line.strip()
            if line:
                rows.append(json.loads(line))
for r in rows:
    if (r.get("State") or "") != "running":
        continue
    print(r.get("Service") or "")
'
}

# Что видит КОНТЕЙНЕР по этому пути. Не хост: 19 сентября на хосте лежал
# правильный файл, и ровно поэтому всё выглядело исправным.
seen_sha() {  # сервис, путь в контейнере → сумма или пусто
    if [ -n "$SEEN_SH" ]; then
        "$SEEN_SH" "$1" "$2" 2>/dev/null
        return $?
    fi
    # `</dev/null` не для красоты: сверка идёт в цикле `while read`, который
    # читает список монтирований со стандартного ввода, а `compose exec`
    # свой стандартный ввод ЧИТАЕТ — и съедает остаток списка вместе с ним.
    # Поймано живым прогоном на настоящем docker: из трёх монтирований
    # проверялось ПЕРВОЕ, а две оставшиеся пары исчезали молча — то есть
    # сторож отчитывался зелёным, не посмотрев на две трети того, ради чего
    # написан. На заглушках этого не видно вовсе.
    $DC -f "$COMPOSE_FILE" --project-directory . --env-file "$ENV_FILE" \
        exec -T "$1" cat "$2" </dev/null 2>"$TMP/err" | hash_stdin
}

# Выполнить шаг — или записать его, если сторожа гоняет самопроверка.
do_step() {  # команда строкой
    if [ -n "$DO_FILE" ]; then
        printf '%s\n' "$1" >> "$DO_FILE"
        return 0
    fi
    # shellcheck disable=SC2086
    $1
}

# ───────────────────────────── сама сверка ──────────────────────────────────
#
# Копится три списка, и они про разное: применённое, оставшееся человеку
# и то, чего не спросить. Смешать их нельзя — «не спросить» и «сходится»
# выдавать одно за другое значит соврать про то, чего не измеряли (урок 0151).
CHEAP=""        # шаг<TAB>что за ним стоит
HUMAN=""        # шаг<TAB>цена<TAB>что за ним стоит
UNKNOWN=0       # не спросить
BADLIST=0       # монтирование без описанного шага

check_mounts() {
    local list svc target source host seen run_list rc=0

    if ! command -v python3 >/dev/null 2>&1; then
        red "  ✗ нечем разобрать ответ compose: нет python3"
        UNKNOWN=$((UNKNOWN + 1))
        return 0
    fi

    list=$(mounts) || {
        red "Не удалось спросить compose про монтирования:"
        sed 's/^/    /' "$TMP/err" >&2
        UNKNOWN=$((UNKNOWN + 1))
        return 0
    }
    run_list=$(running) || {
        red "Не удалось спросить ячейку про работающие контейнеры:"
        sed 's/^/    /' "$TMP/err" >&2
        UNKNOWN=$((UNKNOWN + 1))
        return 0
    }

    while IFS=$'\t' read -r svc target source; do
        [ -n "$svc" ] || continue
        rule "$svc:$target"

        if [ "$TIER" = нет ]; then
            printf '  · %s:%s — %s\n' "$svc" "$target" "$WHY"
            continue
        fi
        if [ "$TIER" = неизвестно ]; then
            # Восьмое монтирование, заведённое молча. Краснеем, а не
            # догадываемся: у пути либо есть шаг применения, либо написано,
            # почему его нет.
            red "  ✗ $svc монтирует $target, а шага применения для него не описано"
            red "      Впишите его в ops/apply-config.sh: чем применяется, чем платим и кто делает —"
            red "      выкладка или человек. Иначе привезённая правка этого файла не подействует молча."
            BADLIST=$((BADLIST + 1))
            continue
        fi

        # Пропажу файла ловит ops/config-guard.sh, и он же краснеет на ней
        # раньше — шагом выкладки перед этим. Здесь молчим, чтобы два сторожа
        # не говорили человеку одно и то же разными словами.
        if [ ! -f "$source" ]; then
            printf '  · %s:%s — на хосте файла нет; это вопрос ops/config-guard.sh\n' "$svc" "$target"
            continue
        fi

        case "
$run_list
" in
            *"
$svc
"*) : ;;
            *)  printf '  · %s не запущен — новую редакцию %s он прочитает при старте\n' "$svc" "$target"
                continue ;;
        esac

        host=$(hash_stdin < "$source") || {
            red "  ✗ $source — нечем посчитать сумму (нет ни sha256sum, ни shasum)"
            UNKNOWN=$((UNKNOWN + 1))
            continue
        }
        seen=$(seen_sha "$svc" "$target")
        if [ -z "$seen" ]; then
            red "  ✗ ${svc}: не прочитать $target ВНУТРИ контейнера — сверка НЕ ВЫПОЛНЕНА"
            red "      Это НЕ «редакция совпадает»: ответа нет вовсе."
            [ -s "$TMP/err" ] && sed 's/^/      /' "$TMP/err" >&2
            UNKNOWN=$((UNKNOWN + 1))
            continue
        fi

        if [ "$host" = "$seen" ]; then
            printf '  ✓ %s:%s — в контейнере та же редакция\n' "$svc" "$target"
            continue
        fi

        # Разошлось. Именно этот случай 19 сентября выглядел исправной ячейкой.
        red "  ✗ ${svc}: $target В КОНТЕЙНЕРЕ ДРУГОЙ РЕДАКЦИИ, чем на хосте"
        red "      на хосте $source — $(printf '%.12s' "$host")…, в контейнере — $(printf '%.12s' "$seen")…"
        red "      $PRICE"
        if [ "$TIER" = сама ]; then
            CHEAP="$CHEAP$STEP	$svc:$target
"
        else
            HUMAN="$HUMAN$STEP	$PRICE	$svc:$target
"
        fi
        rc=1
    done <<EOF
$list
EOF
    return $rc
}

# ─────────────────── шаги с внешним побочным действием ──────────────────────
#
# Их три, и в compose их нет вовсе: они меняют не контейнер, а мир вокруг —
# crontab машины, роли в базе, образы в реестре. Названы поимённо, потому что
# «в перечне нет» и «шага применения нет» — разные утверждения.
CRON_DIFFERS=""
check_external() {
    local out rc

    # 1. Расписание. Тот самый случай, с которого завелась задача: файл
    #    приехал, задачи в crontab остались прежние, и прокрутки журнала
    #    не было восемь дней. Спрашивает про себя сам install-cron.sh —
    #    состав задач и маркеры живут там, и второе место с тем же знанием
    #    разъехалось бы с первым молча.
    if [ -x "$CRON_SH" ]; then
        out=$("$CRON_SH" --diff 2>&1); rc=$?
        case "$rc" in
            0)  printf '  ✓ расписание ячейки: в crontab стоят те задачи, что в %s\n' "$CRON_SH" ;;
            1)  red "  ✗ РАСПИСАНИЕ РАСХОДИТСЯ с $CRON_SH — привезённая редакция не переустановлена"
                printf '%s\n' "$out" | sed 's/^/      /' >&2
                red "      Так прокрутки журнала не было в crontab восемь дней (20–28 сентября 2026),"
                red "      и журнал рос без предела: заполненный диск останавливает Postgres, а с ним архив WAL."
                CRON_DIFFERS=yes ;;
            *)  red "  ✗ расписание: спросить не удалось — сверка НЕ ВЫПОЛНЕНА"
                printf '%s\n' "$out" | sed 's/^/      /' >&2
                UNKNOWN=$((UNKNOWN + 1)) ;;
        esac
    else
        printf '  · %s рядом нет — расписание не сверялось\n' "$CRON_SH"
    fi

    # 2. Роли ячейки. Сверять НЕЧЕГО: применённые права живут в базе, а
    #    отметки «какой редакцией скрипта их выдали» нет нигде — сравнивать
    #    файл не с чем. Признак, который это утверждал бы, был бы
    #    неизмеренным утверждением (та же ошибка, что дважды сделала памятка
    #    ячейки с origin/main). Зато СЛЕДСТВИЕ проверяется: `journals`
    #    в /actuator/readiness спрашивает у базы попыткой, защищены ли
    #    журналы, и это вторая самопроверка выкладки.
    printf '  · ops/create-roles.sh — не сверяется: отметки «какой редакцией выданы права» нет нигде.\n'
    printf '      Следствие проверяет вторая самопроверка выкладки (journals в /actuator/readiness);\n'
    printf '      правили роли — применяет человек: ops/create-roles.sh, затем restart сборки под трафиком.\n'

    # 3. Адреса образов. Спрашивает ops/image-state.sh (задача 0198) —
    #    и спрашивает лучше, чем сверка файла: он сверяет СУММУ образа,
    #    в которую адрес разрешается на этой машине сейчас. Второй механизм
    #    про то же был бы вторым местом с одним знанием.
    printf '  · ops/images.yml — сверяет ops/image-state.sh (он зовётся из ops/config-guard.sh шагом раньше)\n'
}

# ──────────────────────────── применение ────────────────────────────────────
#
# Дешёвое применяется, дорогое называется. И применённое ПРОВЕРЯЕТСЯ ПОВТОРНО:
# шаг, отчитавшийся успехом и не сделавший дела, — самый частый класс в этом
# проекте (0152, 0101, 0158, 0198, 0202), и `up -d` без флага ведёт себя ровно
# так. Поэтому после пересоздания сумма спрашивается у контейнера ещё раз.
FAILED=0
apply_cheap() {
    local step what seen host source svc target
    [ -n "$CHEAP" ] || return 0

    # По одному разу на команду: prometheus.yml и alerts.yml живут в одном
    # контейнере, и пересоздавать его дважды значило бы сбросить отсчёт `for:`
    # два раза подряд.
    while IFS=$'\t' read -r step what; do
        [ -n "$step" ] || continue
        printf '\n  → %s\n' "$step"
        printf '     ради: %s\n' "$what"
        if do_step "$step"; then
            :
        else
            red "  ✗ шаг не прошёл: $step"
            red "      Контейнер мог остаться погашенным — у наблюдения это ячейка без тревог."
            FAILED=$((FAILED + 1))
            continue
        fi
    done <<EOF
$(printf '%s' "$CHEAP" | awk -F'\t' '!seen[$1]++ { print $1 "\t" $2 }')
EOF

    # Повторная сверка — по каждой паре, а не по команде: пересоздание одного
    # контейнера обязано донести ВСЕ его файлы.
    while IFS=$'\t' read -r step what; do
        [ -n "$what" ] || continue
        svc="${what%%:*}"
        target="${what#*:}"
        source=$(printf '%s\n' "$MOUNT_SOURCES" | awk -F'\t' -v s="$svc" -v t="$target" '$1==s && $2==t {print $3; exit}')
        [ -n "$source" ] || continue
        host=$(hash_stdin < "$source") || continue
        seen=$(seen_sha "$svc" "$target")
        if [ "$host" = "$seen" ]; then
            green "  ✓ применено: $what — в контейнере теперь та же редакция"
        else
            red "  ✗ ПРИМЕНЕНО И НЕ ПОДЕЙСТВОВАЛО: $what"
            red "      Команда отчиталась успехом, а в контейнере по-прежнему другая редакция."
            red '      Так ведёт себя `up -d` без --force-recreate: печатает «Running» и не делает ничего.'
            FAILED=$((FAILED + 1))
        fi
    done <<EOF
$CHEAP
EOF
}

apply_cron() {
    [ -n "$CRON_DIFFERS" ] || return 0
    printf '\n  → %s\n' "$CRON_SH"
    printf '     ради: расписание ячейки — привезённый состав задач\n'
    if do_step "$CRON_SH"; then
        # След спрашивается, а не выводится из кода возврата: у расписания
        # ровно для этого есть `--diff` с тремя исходами (0 совпадает,
        # 1 расходится, 2 не спросить). Без него «применено» означало бы
        # «команда дошла до конца» — то есть ту самую подмену, которой
        # оплачена 0152, и в единственном месте файла, где остальные шаги
        # перечитывают состояние у контейнера.
        if do_step "$CRON_SH --diff"; then
            green "  ✓ применено: расписание переустановлено и совпадает с привезённым"
            return 0
        fi
        red "  ✗ расписание переустановлено, а привезённой редакции в crontab НЕТ"
        red "      Спросите: $CRON_SH --diff (и --show — запустится ли стоящее)"
        FAILED=$((FAILED + 1))
        return 0
    fi
    # НЕ считается отказом применения намеренно, и это решение исполнителя.
    # Установка отказывается, когда журнал расписания некуда писать (0152), —
    # и тогда она НЕ ТРОГАЕТ crontab: расписание остаётся тем, что было,
    # то есть хуже не стало. Валить из-за этого выкладку значило бы держать
    # релизы заложником пути журнала; назвать — обязательно.
    red "  ✗ расписание переустановить не вышло — оно осталось ПРЕЖНИМ (привезённая редакция не действует)"
    red "      Выкладку это не останавливает: crontab не тронут, хуже не стало."
    red "      Чинить отдельно: $CRON_SH --show скажет, чего не хватает."
    HUMAN="$HUMAN$CRON_SH	расписание осталось прежним	расписание ячейки
"
    return 0
}

# ──────────────────────────────── вердикт ───────────────────────────────────
report() {
    local step price what

    if [ -n "$HUMAN" ]; then
        printf '\n'
        warn "ТРЕБУЕТ ПРИМЕНЕНИЯ, И ВЫКЛАДКА ЭТОГО НЕ ДЕЛАЕТ САМА:"
        while IFS=$'\t' read -r step price what; do
            [ -n "$step" ] || continue
            printf '  %s\n' "$what"
            printf '      цена: %s\n' "$price"
            printf '      команда: %s\n' "$step"
        done <<EOF
$HUMAN
EOF
        printf '  Почему не сама: дорогой шаг задевает клиента (простой базы, вход в ячейку),\n'
        printf '  а выкладка обещает, что простоя нет. Разрешать ли ей это — вопрос владельцу\n'
        printf '  продукта, названный в tasks/0216.\n'
    fi

    if [ "$BADLIST" != 0 ]; then
        printf '\n'
        red "МОНТИРОВАНИЙ БЕЗ ОПИСАННОГО ШАГА: $BADLIST — привезённая правка таких файлов не подействует молча"
    fi

    if [ "$FAILED" != 0 ]; then
        red "ПРИМЕНИТЬ НЕ УДАЛОСЬ: $FAILED"
        return 3
    fi
    if [ "$UNKNOWN" != 0 ]; then
        red "СВЕРКА НЕ ВЫПОЛНЕНА по $UNKNOWN монтированиям — это не «редакции совпадают» и не «разошлись»: ответа нет"
        return 2
    fi
    if [ -n "$HUMAN" ] || [ "$BADLIST" != 0 ]; then
        return 1
    fi
    return 0
}

# ─────────────────────────── проверка сторожа ───────────────────────────────
#
# Сторож, не краснеющий на дефекте, хуже отсутствующего, и установить это
# можно только попыткой. Ни ячейки, ни docker не нужно: монтирования,
# работающие контейнеры и «что видит контейнер» подменяются — ровно как
# у ops/image-state.sh. Последний случай — возврат дефекта: копия со снятой
# сверкой обязана валить самопроверку.
selftest() {
    local bad=0 out rc tmp seen do_file

    echo "Самопроверка ops/apply-config.sh"
    tmp="$TMP/st"
    mkdir -p "$tmp"

    # Настоящее дерево: у КАЖДОГО монтирования боевого compose обязан быть
    # описан шаг применения. Это и есть требование «восьмое монтирование нельзя
    # завести молча» — и проверяется он на настоящем compose, а не на списке
    # в этом файле. Контейнеров при этом нет (прогон CI), значит сверять нечего:
    # сторож обязан пройти молча и кодом 0.
    if [ -n "${APPLY_CONFIG_SELFTEST_FAKE:-}" ]; then
        printf '  ✓ дерево настоящее не сверяем — рекурсии нет\n'
    else
        printf 'stub\n' > "$tmp/telegram-token"
        sed -E 's/^([A-Z0-9_]+)=$/\1=ci-placeholder/' "$ROOT/.env.example" \
            | sed "s#^ALERT_TELEGRAM_TOKEN_FILE=.*#ALERT_TELEGRAM_TOKEN_FILE=$tmp/telegram-token#" \
            > "$tmp/env"
        : > "$tmp/ps-empty"
        printf '#!/bin/sh\nexit 0\n' > "$tmp/cron-quiet.sh"
        chmod +x "$tmp/cron-quiet.sh"
        out=$(ENV_FILE="$tmp/env" APPLY_CONFIG_PS="$tmp/ps-empty" \
              APPLY_CONFIG_CRON_SH="$tmp/cron-quiet.sh" bash "$SELF" 2>&1); rc=$?
        if [ "$rc" = 0 ] && ! grep -q 'шага применения для него не описано' <<< "$out"; then
            printf '  ✓ у каждого монтирования боевого compose описан шаг применения\n'
        else
            red "  ✗ настоящее дерево не проходит (код $rc): либо появилось монтирование без шага применения,"
            red "      либо сторож краснеет на исправной ячейке"
            printf '%s\n' "$out" | sed 's/^/      /' >&2
            bad=$((bad + 1))
        fi
    fi

    # Дальше — подделанные монтирования: настоящие трогать нельзя, рядом
    # работает ячейка. Два файла на хосте, два сервиса, и «что видит
    # контейнер» отвечает заглушка.
    printf 'СОДЕРЖИМОЕ ХОСТА, РЕДАКЦИЯ ВЕТКИ\n' > "$tmp/alerts.yml"
    printf 'СОДЕРЖИМОЕ ХОСТА, РЕДАКЦИЯ ВЕТКИ\n' > "$tmp/archive-wal.sh"
    printf 'prometheus\t/etc/prometheus/alerts.yml\t%s\npostgres\t/usr/local/bin/archive-wal.sh\t%s\n' \
        "$tmp/alerts.yml" "$tmp/archive-wal.sh" > "$tmp/mounts"
    printf 'prometheus\npostgres\n' > "$tmp/ps"
    do_file="$tmp/done"

    # Заглушка «что видит контейнер». Она же и модель реальности: пока шаг
    # пересоздания не выполнен, контейнер отдаёт ПРЕЖНЮЮ сумму, после —
    # ту же, что на хосте. Без этого случай «применено и подействовало»
    # ничего не утверждал бы.
    cat > "$tmp/seen.sh" <<'SH'
#!/usr/bin/env bash
# $1 — сервис, $2 — путь. Отвечает прежней суммой, пока в DONE не появится
# строка пересоздания этого сервиса.
svc="$1"
case "${SEEN_MODE:-drift}" in
    same)   printf 'РОВНО ТО ЖЕ\n' | { shasum -a 256 2>/dev/null || sha256sum; } | cut -d' ' -f1 ;;
    mute)   exit 1 ;;
    stuck)  printf 'ПРЕЖНЯЯ РЕДАКЦИЯ КОНТЕЙНЕРА\n' | { shasum -a 256 2>/dev/null || sha256sum; } | cut -d' ' -f1 ;;
    *)
        if [ -f "${DONE:-/dev/null}" ] && grep -q "force-recreate $svc" "${DONE}"; then
            cat "${HOSTFILE}" | { shasum -a 256 2>/dev/null || sha256sum; } | cut -d' ' -f1
        else
            printf 'ПРЕЖНЯЯ РЕДАКЦИЯ КОНТЕЙНЕРА\n' | { shasum -a 256 2>/dev/null || sha256sum; } | cut -d' ' -f1
        fi ;;
esac
SH
    chmod +x "$tmp/seen.sh"

    probe() {  # режим заглушки, аргументы сторожа…
        local mode="$1"; shift
        : > "$do_file"
        set +e
        out=$(APPLY_CONFIG_MOUNTS="$tmp/mounts" APPLY_CONFIG_PS="$tmp/ps" \
              APPLY_CONFIG_SEEN_SH="$tmp/seen.sh" APPLY_CONFIG_DO="$do_file" \
              APPLY_CONFIG_CRON_SH="$tmp/cron-quiet.sh" \
              SEEN_MODE="$mode" DONE="$do_file" HOSTFILE="$tmp/alerts.yml" \
              bash "$SELF" "$@" 2>&1); rc=$?
        set -e
    }

    # 1. Совпадает — сторож МОЛЧИТ. Обратный край, и он важнее половины
    #    остальных: сторож, краснеющий на исправной ячейке, будет отключён
    #    в первый же день вместе с защитой.
    printf 'РОВНО ТО ЖЕ\n' > "$tmp/alerts.yml"
    printf 'РОВНО ТО ЖЕ\n' > "$tmp/archive-wal.sh"
    probe same --apply
    if [ "$rc" = 0 ] && ! grep -q 'ТРЕБУЕТ ПРИМЕНЕНИЯ' <<< "$out" && [ ! -s "$do_file" ]; then
        printf '  ✓ редакции совпали — сторож молчит и НИЧЕГО не пересоздаёт\n'
    else
        red "  ✗ на совпавших редакциях сторож обязан молчать и не трогать контейнеров (код $rc)"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=$((bad + 1))
    fi

    # 2. Разошёлся ДЕШЁВЫЙ — выкладка применяет сама, и применённое проверяется
    #    повторным чтением контейнера.
    printf 'СОДЕРЖИМОЕ ХОСТА, РЕДАКЦИЯ ВЕТКИ\n' > "$tmp/alerts.yml"
    printf 'ПРЕЖНЯЯ РЕДАКЦИЯ КОНТЕЙНЕРА\n' > "$tmp/archive-wal.sh"
    probe drift --apply
    if [ "$rc" = 0 ] && grep -q 'force-recreate prometheus' "$do_file" \
       && grep -q 'применено: prometheus' <<< "$out"; then
        printf '  ✓ дешёвый шаг применяет сама выкладка, и применённое перечитано у контейнера\n'
    else
        red "  ✗ расхождение alerts.yml обязано пересоздать prometheus и подтвердиться чтением (код $rc)"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=$((bad + 1))
    fi

    # 3. Разошёлся ДОРОГОЙ — назван поимённо, С ЦЕНОЙ, и НЕ применён. Это
    #    возврат случая 19 сентября 2026 и прямой запрет задачи: пересоздавать
    #    postgres в порядке выкладки нельзя без решения владельца.
    printf 'РОВНО ТО ЖЕ\n' > "$tmp/alerts.yml"
    printf 'СОДЕРЖИМОЕ ХОСТА, РЕДАКЦИЯ ВЕТКИ\n' > "$tmp/archive-wal.sh"
    probe drift --apply
    if [ "$rc" = 1 ] && grep -q 'archive-wal.sh' <<< "$out" \
       && grep -q 'ПРОСТОЙ КЛИЕНТА' <<< "$out" \
       && grep -q 'force-recreate postgres' <<< "$out" \
       && ! grep -q 'postgres' "$do_file"; then
        printf '  ✓ дорогой шаг НАЗВАН с ценой и командой — и postgres не пересоздан\n'
    else
        red "  ✗ расхождение archive-wal.sh обязано быть названо ценой «простой клиента», кодом 1, и НЕ применено (код $rc)"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        printf '      сделано: %s\n' "$(tr '\n' '|' < "$do_file")" >&2
        bad=$((bad + 1))
    fi

    # 4. Спросить не удалось — третий исход, и он НЕ «сходится». Ровно та
    #    подмена, которой в этом проекте уже стоила пяти задач подряд
    #    (волна 0146–0151).
    probe mute --apply
    if [ "$rc" = 2 ] && grep -q 'СВЕРКА НЕ ВЫПОЛНЕНА' <<< "$out"; then
        printf '  ✓ «не прочитать внутри контейнера» — отдельный исход, а не «редакция совпадает»\n'
    else
        red "  ✗ нечитаемый контейнер обязан давать код 2 и слова «сверка не выполнена» (код $rc)"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=$((bad + 1))
    fi

    # 5. Применили — и не подействовало. `up -d` без флага ведёт себя ровно
    #    так: печатает «Running» и не делает ничего. Без этого случая сторож
    #    объявлял бы успехом свой собственный вызов.
    printf 'СОДЕРЖИМОЕ ХОСТА, РЕДАКЦИЯ ВЕТКИ\n' > "$tmp/alerts.yml"
    probe stuck --apply
    if [ "$rc" = 3 ] && grep -q 'ПРИМЕНЕНО И НЕ ПОДЕЙСТВОВАЛО' <<< "$out"; then
        printf '  ✓ шаг, отчитавшийся успехом и не сделавший дела, назван и краснеет кодом 3\n'
    else
        red "  ✗ «применено и не подействовало» обязано быть кодом 3 и своими словами (код $rc)"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=$((bad + 1))
    fi

    # 6. Монтирование, которого сторож не знает: завести восьмое молча нельзя.
    printf 'prometheus\t/etc/prometheus/novoe.yml\t%s\n' "$tmp/alerts.yml" > "$tmp/mounts"
    probe same
    if [ "$rc" = 1 ] && grep -q 'шага применения для него не описано' <<< "$out"; then
        printf '  ✓ незнакомое монтирование краснеет: восьмое нельзя завести молча\n'
    else
        red "  ✗ монтирование без описанного шага обязано валить сторожа словами (код $rc)"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=$((bad + 1))
    fi

    # 7. Сервис не запущен — это «применять нечего», а не «не спросить»:
    #    погашенная сборка стоит под профилем законно, и новую редакцию
    #    контейнер прочитает при старте сам.
    printf 'prometheus\t/etc/prometheus/alerts.yml\t%s\n' "$tmp/alerts.yml" > "$tmp/mounts"
    : > "$tmp/ps"
    probe mute --apply
    if [ "$rc" = 0 ] && grep -q 'не запущен' <<< "$out"; then
        printf '  ✓ погашенный сервис — «прочитает при старте», а не «сверка не выполнена»\n'
    else
        red "  ✗ погашенный сервис не должен ни краснеть, ни считаться неспрошенным (код $rc)"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=$((bad + 1))
    fi
    printf 'prometheus\n' > "$tmp/ps"

    # 8. Расписание разошлось — применяется САМО, и это тот случай, с которого
    #    завелась задача: восемь дней без прокрутки журнала.
    # Монтирования при этом обязаны СОВПАДАТЬ: случай про расписание, и чужое
    # расхождение в нём смешало бы два ответа в один.
    printf 'РОВНО ТО ЖЕ\n' > "$tmp/alerts.yml"
    printf '#!/bin/sh\n[ "$1" = --diff ] && { echo "прокрутки журнала в crontab нет"; exit 1; }\nexit 0\n' \
        > "$tmp/cron-differs.sh"
    chmod +x "$tmp/cron-differs.sh"
    : > "$do_file"
    set +e
    out=$(APPLY_CONFIG_MOUNTS="$tmp/mounts" APPLY_CONFIG_PS="$tmp/ps" \
          APPLY_CONFIG_SEEN_SH="$tmp/seen.sh" APPLY_CONFIG_DO="$do_file" \
          APPLY_CONFIG_CRON_SH="$tmp/cron-differs.sh" \
          SEEN_MODE=same DONE="$do_file" HOSTFILE="$tmp/alerts.yml" \
          bash "$SELF" --apply 2>&1); rc=$?
    set -e
    if [ "$rc" = 0 ] && grep -q 'РАСПИСАНИЕ РАСХОДИТСЯ' <<< "$out" \
       && grep -q 'cron-differs.sh' "$do_file"; then
        printf '  ✓ разошедшееся расписание названо и переустановлено самой выкладкой\n'
    else
        red "  ✗ разошедшееся расписание обязано быть названо и переустановлено (код $rc)"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=$((bad + 1))
    fi

    # 9. ВОЗВРАТ ДЕФЕКТА: копия сторожа, у которой сверка всегда отвечает
    #    «совпадает», обязана валить самопроверку. Без этого случая все восемь
    #    выше ничего не утверждали бы — краснеть могло что угодно, кроме самой
    #    проверки. Целость копии проверяется ДО запуска (`bash -n`): красное
    #    от сломанного синтаксиса и красное от снятой сверки — разные
    #    утверждения.
    if [ -n "${APPLY_CONFIG_SELFTEST_FAKE:-}" ]; then
        printf '  ✓ подделок не заводим — рекурсии нет\n'
    else
        local fake="$tmp/fake.sh"
        sed 's|^        if \[ "\$host" = "\$seen" \]; then$|        if true; then|' "$SELF" > "$fake"
        if ! grep -q '^        if true; then$' "$fake"; then
            red "  ✗ подделку негде поставить: строки сверки в файле нет"
            bad=$((bad + 1))
        elif ! bash -n "$fake" 2>/dev/null; then
            red "  ✗ подделка сломала синтаксис — её красное говорило бы не о том"
            bad=$((bad + 1))
        else
            set +e
            out=$(APPLY_CONFIG_SELFTEST_FAKE=yes bash "$fake" --selftest 2>&1); rc=$?
            set -e
            if [ "$rc" != 0 ]; then
                printf '  ✓ возврат дефекта: копия, у которой редакции «всегда совпадают», валит самопроверку\n'
            else
                red "  ✗ копия со СНЯТОЙ сверкой прошла самопроверку — значит сверка ничего не утверждает"
                printf '%s\n' "$out" | sed 's/^/      /' >&2
                bad=$((bad + 1))
            fi
        fi
    fi

    if [ "$bad" != 0 ]; then
        red "Самопроверка не прошла: $bad"
        return 1
    fi
    green "Самопроверка пройдена"
    return 0
}

