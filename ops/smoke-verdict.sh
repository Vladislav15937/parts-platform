#!/usr/bin/env sh
# Итог дымового прогона словами — ОДНО МЕСТО НА ДВА ЧИТАТЕЛЯ (задача 0255).
#
#   . ops/smoke-verdict.sh     # после cd в корень репозитория
#
# Сорсят ops/smoke-run.sh (печатает итог) и ops/deploy-checks.sh (узнаёт
# в выводе прогона частичный итог и доносит его до выкладки). Файл не зовут
# по пути, поэтому в индексе он 100644, как ops/env-file.sh и ops/moment.sh.
#
# ЗАЧЕМ ОБЩЕЕ МЕСТО. До 0255 у одного состояния было два слова и два цвета:
# прогон печатал «пройден ЧАСТИЧНО» ЗЕЛЁНЫМ, выкладка — «прошёл НЕ ЦЕЛИКОМ»
# жёлтым. Хуже разных слов было то, что выкладка узнавала состояние по слову,
# написанному у себя литералом: смени прогон слово — пятая самопроверка молча
# вернулась бы к «сценарий доезжает до конца», а её собственная самопроверка
# осталась бы зелёной, потому что кормила себя той же литеральной строкой.
# Теперь слово и фраза живут здесь, и самопроверка каждого из двух читателей
# сверяет свою поверхность с этим местом, а не с копией.

SMOKE_PARTIAL_WORD='ЧАСТИЧНО'

# Итоговая строка прогона: аргумент — непройденные шаги через запятую,
# пусто — сценарий исполнен целиком. Полный прогон говорит ровно одну строку
# и про пропуски молчит: постоянная приписка «всё исполнено» приучила бы
# итог не читать.
smoke_final_line() {
    if [ -n "$1" ]; then
        printf 'Дымовой прогон пройден %s: не исполнялись шаги — %s. Сценарий до конца НЕ доехал.' \
            "$SMOKE_PARTIAL_WORD" "$1"
    else
        printf 'Дымовой прогон пройден: сценарий доезжает до конца'
    fi
}
