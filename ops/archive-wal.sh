#!/bin/sh
# Архивация одного сегмента WAL. Зовёт её сам Postgres (archive_command),
# внутри контейнера базы, оболочкой образа:
#
#   archive-wal.sh %p %f
#
# Отдельным файлом, а не строкой в compose, и по трём причинам — каждая
# из них означает потерянную точку возврата, если сделать проще.
#
# 1. АТОМАРНОСТЬ. Сегмент, записанный в архив наполовину (кончилось место,
#    перезапустили машину), читается восстановлением как целый и обрывает
#    накат посередине — то есть даёт ровно то, чего задача 0083 и требует
#    не допускать: тихо восстановленное дырявое. Поэтому пишем во временный
#    файл рядом и переименовываем: mv внутри одного каталога атомарен.
#
# 2. ОТВЕТ НА ПОВТОР. Postgres зовёт команду снова после любого отказа,
#    поэтому «файл с таким именем уже есть» — обычное дело. Но честных
#    ответов на это ровно два: «тот же самый, считаем успехом» и «ДРУГОЙ
#    с тем же именем — остановись». Второе означает, что в один архив пишут
#    два кластера (например, поднятая рядом копия для разбора аварии),
#    и тихий успех здесь затирает чужую историю. Поэтому сверяем содержимое,
#    а не существование.
#
# 3. СЖАТИЕ. Сегмент всегда 16 МБ, сколько бы в нём ни было записей,
#    а archive_timeout переключает их каждые пять минут даже на спокойной
#    ячейке: 288 файлов в сутки, 4,5 ГиБ. Почти пустой сегмент жмётся
#    в десятки килобайт, и на диске в 96 ГБ разница между «архив живёт
#    неделями» и «диск кончился к пятнице». Восстановление разжимает
#    обратно — см. restore_command в ops/restore-pitr.sh.
set -eu

SRC="${1:?путь к сегменту (%p)}"
NAME="${2:?имя сегмента (%f)}"
DIR="${WAL_ARCHIVE:-/wal-archive}"

[ -d "$DIR" ] || { echo "архив WAL недоступен: $DIR нет" >&2; exit 1; }

DST="$DIR/$NAME.gz"

if [ -f "$DST" ]; then
    # Тот же сегмент — повтор архиватора после отказа, успех.
    if gzip -dc "$DST" 2>/dev/null | cmp -s - "$SRC"; then
        exit 0
    fi
    # Другой — в архив пишет кто-то ещё. Молчаливый успех затёр бы историю,
    # по которой восстанавливаются; пусть архиватор встанет и позовёт человека.
    echo "в архиве уже лежит ДРУГОЙ сегмент $NAME — в один архив пишут два кластера?" >&2
    exit 1
fi

TMP="$DIR/.$NAME.$$.tmp"
# Уборка за собой: недожатый временный файл иначе остаётся после каждого
# обрыва и копится в архиве до конца диска.
trap 'rm -f "$TMP"' EXIT

gzip -1 -c "$SRC" > "$TMP"
# -1, а не умолчание: архиватор работает на той же машине, что и база,
# и упираться в процессор ради лишних процентов сжатия нулей незачем.

# Сброс на диск до переименования: без него отказ машины оставляет в архиве
# имя без содержимого, и сегмент считается уехавшим, будучи пустым.
fsync "$TMP" 2>/dev/null || true
mv "$TMP" "$DST"
fsync "$DIR" 2>/dev/null || true
trap - EXIT
