#!/usr/bin/env bash
# Сторож канала тревог: уходят ли они вообще — и если нет, сказать об этом
# ВТОРЫМ путём, мимо самого канала.
#
#   ops/alert-channel-check.sh            # один проход (так его зовут руками)
#   ops/alert-channel-check.sh --loop     # проход раз в ALERT_CHANNEL_INTERVAL
#                                         # (так его держит контейнер alert-watch)
#   ops/alert-channel-check.sh --probe    # есть ли у диспетчера дорога до Telegram
#   ops/alert-channel-check.sh --selftest # проверка самого сторожа на подделках
#
# ЗАЧЕМ ОН ЕСТЬ. 19 сентября 2026 в 02:52 UTC доставка тревог боевой ячейки
# оборвалась, и до 20 сентября наружу не ушло НИ ОДНОГО сообщения: 2731 отказ
# в логе диспетчера, шесть горящих тревог, и ни одной строки человеку.
# Диспетчер честно писал о беде в свой лог — то есть сообщал о ней тому,
# кто и так смотрит в лог контейнера наблюдения, и молчал для всех, кто
# на наблюдение полагается. Сторож доставки, сообщающий через отказавший
# канал, бесполезен по построению: именно это и случилось.
#
# ПОЧЕМУ ВТОРОЙ ПУТЬ — ЭТО СЕТЬ ХОСТА, А НЕ ВТОРОЙ ПОЛУЧАТЕЛЬ. В тот день
# IPv4 к Telegram был закрыт, а IPv6 открыт — и с ХОСТА ячейки сообщение
# уходило (замер владельца: 302), а из контейнера диспетчера нет: сети docker
# по умолчанию без IPv6, и дорога у него оставалась одна и не та. Поэтому
# сторож ходит стеком хоста (`network_mode: host` у контейнера alert-watch),
# а диспетчер — своей сетью с IPv6. Дороги разные, и отказ одной не глушит
# другую. Второй получатель внутри того же диспетчера этого НЕ даёт: у него
# та же сеть, тот же процесс и тот же отказ.
#
# ЧЕГО ОН НЕ ЛОВИТ, И ЭТО НАДО ЗНАТЬ. Он видит «диспетчер не смог отправить»
# и «диспетчер не отвечает». Он НЕ видит «отправлено в чужой чат»: для
# Telegram это успех, и отличить его нечем, кроме как спросить человека.
# И он не спасёт, если Telegram недоступен с машины целиком — тогда молчат
# оба пути, и это свойство единственного канала, а не сторожа.
#
# ОКНО — ПЯТЬ МИНУТ, И ВОТ ПОЧЕМУ ИМЕННО ОНО. Диспетчер отменяет повторы
# после четырёх попыток (в логе ячейки: «notify retry canceled after
# 4 attempts»), то есть сообщение теряется НАВСЕГДА за минуты — ждать часами
# нечего. Обход каждые пять минут ловит первый же отказ; будит при этом
# не чаще раза в час (ALERT_CHANNEL_REPEAT), как и сам диспетчер повторяет
# тревогу раз в час: сторож, будящий каждые пять минут, будет отключён
# первым — вместе с защитой.
#
# ПОЧЕМУ НЕ CRON. Расписание ячейки с 10 сентября 2026 не отрабатывало вовсе
# (задача 0152): пять задач стояли в crontab и не запускались ни разу.
# Сторож доставки, поставленный в то же расписание, молчал бы вместе с ним —
# и молчал бы ровно те девять дней, когда он был нужен. Поэтому он держится
# контейнером ячейки со своим `restart: unless-stopped`, а не строкой cron.
#
# ЧТО УТВЕРЖДАЕТ КАЖДАЯ СТРОКА, И ЧЕТЫРЕ КОДА ВОЗВРАТА ВМЕСТО ТРЁХ (задача
# 0236; решение владельца продукта от 1 октября 2026 — варианты «б» и «в»
# вместе). До неё сторож печатал «Канал жив: новых отказов нет», а измерял
# ровно одно: прирост счётчика отказов диспетчера за окно. У канала, отбитого
# час назад, прирост тоже ноль — повторы диспетчер отменяет за минуты, — то
# есть зелёная строка обещала то, чего не мерила, и в самой аварии 19 сентября
# сторож был бы зелен, пока очередь тревог не начала расти.
#
#   0 — за окно диспетчер ОТПРАВЛЯЛ сообщения и ни одно не отказало;
#   1 — канал отбит, и об этом сказано вторым путём (либо намеренно
#       промолчали по выдержке);
#   2 — отбит и сказать НЕ УДАЛОСЬ ни одним путём;
#   3 — НЕ ПРОВЕРЯЛСЯ: измерить доставку было нечем — ни отправок, ни отказов
#       за окно; первый проход; непригодный файл состояния; перезапуск
#       диспетчера.
#
# Коды 2 и 3 — не украшение. «Не смогли сообщить», выданное за «сообщили»,
# повторяет саму поломку 0153; «проверять было нечем», выданное за «проверено
# и годно», повторяет дефект 0236. Четвёртое состояние НИКОГО НЕ БУДИТ: это
# не тревога, а честное «подтвердить нечем». И на спокойной ячейке оно станет
# обычным ответом — зелёного почти не будет, это принято сознательно и
# регрессом не считается.
#
# ЧЕГО И ЭТИ ЧЕТЫРЕ СОСТОЯНИЯ НЕ МЕРЯЮТ. Саму доставку меряет только активная
# проба — сторож шлёт сообщение сам и живым считает канал, когда оно дошло.
# Она отложена решением владельца до ответа, КУДА её слать (раз в пять минут
# в чат владельца — шум, который кончится заглушённым чатом), и по существу
# НЕ отклонена: появится служебный адрес — проба ляжет ПОВЕРХ этих состояний,
# не отменяя их.
set -uo pipefail
cd "$(dirname "$0")/.."

ENV_FILE="${ENV_FILE:-.env}"

# Разрешение пути к файлу окружения — ОДНО МЕСТО НА ПРОЕКТ (ops/env-file.sh,
# задача 0250). До неё проверка шла по непрефиксованному пути, а чтение —
# по пути с «./» впереди, при том что `cd` выше уже ушёл в корень репозитория:
# абсолютный ENV_FILE проверку ПРОХОДИЛ и источался как «.//srv/parts/.env».
# Здесь нет `set -e`, поэтому сторож продолжал работать на умолчаниях — имя
# ячейки, адрес диспетчера и номер чата брались не из файла, который человек
# назвал, а из встроенных значений, и сказано об этом не было ничем.
#
# ИЩЕТСЯ МОДУЛЬ ДВУМЯ ПУТЯМИ, и это не перестраховка: в контейнере сторожа
# (`curlimages/curl`, docker-compose.prod.yml) смонтирован РОВНО ОДИН файл —
# сам этот скрипт, — соседних рядом нет вовсе, а `cd` уводит в /usr/local.
# Второго монтирования не заведено намеренно: новый bind-mount означает
# у `ops/apply-config.sh` путь, которого ещё нет в работающем контейнере,
# то есть «сверка НЕ ВЫПОЛНЕНА» на КАЖДОЙ последующей выкладке, пока человек
# не пересоздаст контейнер руками (apply_cheap пересоздаёт только
# на расхождении, а не на неизвестном). Красное без дефекта каждую выкладку
# дороже того, что здесь лечится.
#
# Второй копии правила при этом не появляется: модуля нет — файл ячейки
# НЕ ЧИТАЕТСЯ, и это говорится словами ниже. Подставить умолчания молча
# значило бы ровно тот дефект, который задача и чинит.
ENV_MODULE=""
for kandidat in ops/env-file.sh "$(dirname "$0")/env-file.sh"; do
    if [ -r "$kandidat" ]; then
        # shellcheck source=/dev/null
        . "$kandidat"
        ENV_MODULE="$kandidat"
        break
    fi
done

MODE=проход
case "${1:-}" in
    --loop)     MODE=цикл ;;
    --probe)    MODE=проба ;;
    --selftest) MODE=самопроверка ;;
    -h|--help)  sed -n '2,50p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    "")         ;;
    *)          printf 'Непонятный аргумент: %s\n' "$1" >&2; exit 2 ;;
esac

red()   { printf '\033[1;31m%s\033[0m\n' "$1" >&2; }
green() { printf '\033[1;32m%s\033[0m\n' "$1"; }
warn()  { printf '\033[1;33m%s\033[0m\n' "$1"; }

# Окружение ячейки — оттуда имя ячейки, номер чата и путь к токену. Нет файла:
# значит сторожа нацелили переменными снаружи (контейнер, самопроверка), и это
# законно. Есть, а прочитать не удалось — отказ словами (задача 0250): сторож,
# работающий на умолчаниях вместо настроек ячейки, спрашивал бы не того
# диспетчера и говорил бы не в тот чат.
if [ "$MODE" != самопроверка ]; then
    if [ -n "$ENV_MODULE" ]; then
        env_file_source "$ENV_FILE" || exit 1
    elif [ "$ENV_FILE" != /dev/null ]; then
        # Модуля рядом нет, а файл ячейки назван — молчать нельзя: всё ниже
        # возьмётся из умолчаний, и это «настроек не читали», а не «их нет».
        # В контейнере сторожа этой строки не бывает: там ENV_FILE=/dev/null,
        # то есть файла ячейки не назначено вовсе.
        printf 'Рядом нет ops/env-file.sh — файл окружения %s НЕ ПРОЧИТАН.\n' "$ENV_FILE" >&2
        printf '    Имя ячейки, адрес диспетчера и номер чата берутся из умолчаний.\n' >&2
    fi
fi

CELL="${APP_CELL:-cell01}"
METRICS_URL="${ALERT_CHANNEL_METRICS_URL:-http://127.0.0.1:${ALERTMANAGER_PORT:-9093}/metrics}"
STATE="${ALERT_CHANNEL_STATE:-/var/lib/alert-channel/state}"
INTERVAL="${ALERT_CHANNEL_INTERVAL:-300}"
REPEAT="${ALERT_CHANNEL_REPEAT:-3600}"
TOKEN_FILE="${ALERT_CHANNEL_TOKEN_FILE:-${ALERT_TELEGRAM_TOKEN_FILE:-./ops/secrets/telegram-token}}"
CHAT_ID="${ALERT_TELEGRAM_CHAT_ID:-}"
PUSH_URL="${PUSHGATEWAY_URL:-http://localhost:9091}"
# Сеть с IPv6, которой диспетчер ходит наружу (docker-compose.prod.yml).
# Имя проекта у боевого compose — `partsflow-<ячейка>` (строка `name:` там же),
# docker приписывает его к имени сети. Умолчание собрано ровно по этому правилу:
# ошибись в нём — и проба скажет «сети нет» на исправной ячейке.
IPV6_NET="${ALERT_IPV6_NETWORK:-partsflow-${CELL}_alerts6}"
PROBE_IMAGE="${ALERT_PROBE_IMAGE:-curlimages/curl:8.11.1}"

# Швы для самопроверки: чем спросить метрики и чем отправить сообщение.
# Подменяются только ею — сторож, проверенный на своих же функциях, не
# проверен на том, что делает запуск.
FETCH_CMD="${ALERT_CHECK_FETCH:-}"
SEND_CMD="${ALERT_CHECK_SEND:-}"

now() { date -u +%s; }

# ─────────────────────────── чем спрашиваем диспетчера ───────────────────────
fetch_metrics() {
    if [ -n "$FETCH_CMD" ]; then
        $FETCH_CMD
        return $?
    fi
    curl -sf --max-time 10 "$METRICS_URL"
}

# Сумма отказов по всем причинам: диспетчер раскладывает их по reason
# (clientError, serverError, contextDeadlineExceeded, other), и на боевой
# ячейке отказ сети лёг в «other». Складывать надо все — сторож, смотрящий
# на одну причину, промолчит на следующей.
# LC_ALL=C у обоих sum_*: значение счётчика приезжает как «1.5e+06», и под
# русской локалью awk читает его как 1 (задача 0126) — отказы недосчитались бы.
sum_failed() {  # метрики на stdin
    LC_ALL=C awk '/^alertmanager_notifications_failed_total\{integration="telegram"/ {
             n = split($0, p, " "); s += p[n]
         }
         END { printf "%d", s + 0 }'
}

sum_total() {
    LC_ALL=C awk '/^alertmanager_notifications_total\{integration="telegram"/ {
             n = split($0, p, " "); s += p[n]
         }
         END { printf "%d", s + 0 }'
}

# ─────────────────────────── второй путь: прямо в Telegram ───────────────────
#
# Отдельным `curl` с хоста, а не через диспетчера: в этом вся задача. Токен
# читается из файла (в переменной он виден в `docker inspect` любому, кто
# дошёл до хоста) — тот же файл и тот же довод, что у alertmanager.
send_second_path() {  # текст сообщения
    local text="$1" token reply
    if [ -n "$SEND_CMD" ]; then
        printf '%s' "$text" | $SEND_CMD
        return $?
    fi
    [ -n "$CHAT_ID" ] || { red "  Некуда слать: ALERT_TELEGRAM_CHAT_ID пуст"; return 1; }
    [ -f "$TOKEN_FILE" ] || { red "  Нечем слать: нет файла токена ${TOKEN_FILE}"; return 1; }
    token=$(cat "$TOKEN_FILE") || return 1
    reply=$(curl -sS --max-time 20 \
        --data-urlencode "chat_id=${CHAT_ID}" \
        --data-urlencode "text=${text}" \
        "https://api.telegram.org/bot${token}/sendMessage" 2>&1) || {
        red "  Второй путь тоже молчит: ${reply}"
        return 1
    }
    case "$reply" in
        *'"ok":true'*) return 0 ;;
        *) red "  Telegram не принял сообщение: ${reply}"; return 1 ;;
    esac
}

# ─────────────────────────── отметки в наблюдение ────────────────────────────
#
# Чтобы отказ доставки был виден не только в логе диспетчера. Сам по себе
# push ничего не будит — будит второй путь выше; отметки отвечают на вопрос
# «что сторож в последний раз сумел измерить» тому, кто смотрит в наблюдение.
#
# ЧИСЕЛ ДВА, И ВТОРОЕ ЗАВЕДЕНО ЗАДАЧЕЙ 0236. `ok` НЕ значит «канал жив»:
# он значит «новых отказов за окно не было» — ровно то, что измерено. У канала,
# отбитого час назад с отменёнными повторами, новых отказов тоже нет, и `ok`
# у него единица. А было ли чем проверить доставку, говорит `checked`: ноль —
# за окно диспетчер не отправлял ничего либо сравнивать было не с чем. Правило
# тревоги, построенное на одном `ok`, повторило бы ту самую подмену, из-за
# которой зелёная строка сторожа обещала больше измеренного; «канал не
# проверялся сутками» спрашивается у `checked`, а не у `ok`.
mark() {  # $1 — ok (1 новых отказов нет, 0 отбит); $2 — checked (1 было чем проверить); $3 — отказов насчитали
    local ok="$1" checked="$2" failed="$3"
    printf '# TYPE partsflow_alert_channel_ok gauge
partsflow_alert_channel_ok %s
# TYPE partsflow_alert_channel_checked gauge
partsflow_alert_channel_checked %s
# TYPE partsflow_alert_channel_check_timestamp_seconds gauge
partsflow_alert_channel_check_timestamp_seconds %s
# TYPE partsflow_alert_notifications_failed_total gauge
partsflow_alert_notifications_failed_total %s
' "$ok" "$checked" "$(now)" "$failed" \
        | curl -sf --max-time 10 --data-binary @- "$PUSH_URL/metrics/job/alert-channel" >/dev/null \
        || warn "  Отметка в наблюдение не ушла — проверьте pushgateway"
}

# ─────────────────────────── состояние между проходами ───────────────────────
#
# STATE_BAD непустой означает: файл состояния есть, а пригодного прошлого
# в нём нет (обрезан, затёрт, мусор). Молча уйти с этим в ветку первого
# прохода нельзя — тогда непригодное состояние выглядело бы как свежий сторож,
# и каждая потеря файла читалась бы как законное «запомнили» (задача 0236).
# Прежняя редакция делала ровно это: `. "$STATE" 2>/dev/null || return 0`.
is_num() { case "${1:-}" in ''|*[!0-9]*) return 1 ;; *) return 0 ;; esac; }

read_state() {  # → PREV_FAILED PREV_TOTAL LAST_SHOUT STATE_BAD
    PREV_FAILED=""; PREV_TOTAL=""; LAST_SHOUT=0; STATE_BAD=""
    [ -f "$STATE" ] || return 0
    # shellcheck disable=SC1090
    . "$STATE" 2>/dev/null || STATE_BAD="файл состояния не читается"
    if [ -z "$STATE_BAD" ] && ! is_num "${PREV_FAILED:-}"; then
        STATE_BAD="в файле состояния нет числа отказов (PREV_FAILED=«${PREV_FAILED:-}»)"
    fi
    if [ -z "$STATE_BAD" ] && ! is_num "${PREV_TOTAL:-}"; then
        STATE_BAD="в файле состояния нет числа отправок (PREV_TOTAL=«${PREV_TOTAL:-}»)"
    fi
    # Выдержку чиним молча: на арифметике `$(( ))` нечисло валит весь проход
    # в dash, а «когда будили» — не то, ради чего сторож существует.
    is_num "${LAST_SHOUT:-}" || LAST_SHOUT=0
    [ -z "$STATE_BAD" ] || { PREV_FAILED=""; PREV_TOTAL=""; }
}

write_state() {  # $1 — отказов, $2 — отправок, $3 — когда будили
    mkdir -p "$(dirname "$STATE")" 2>/dev/null || true
    printf 'PREV_FAILED=%s\nPREV_TOTAL=%s\nLAST_SHOUT=%s\n' "$1" "$2" "$3" > "$STATE" \
        || warn "  Состояние не записать в ${STATE} — повтор будет будить каждый проход"
}

# Проверять было НЕЧЕМ. Не зелёное и не тревога — третье состояние на зелёной
# стороне (задача 0236): «ничего не пробовали» и «всё хорошо» до него давали
# одну и ту же зелёную строку, и различить их было нечем. Человека не будит —
# сообщать не о чем, — но и зелёным не выглядит: жёлтым, своими словами
# и своим кодом возврата.
unverified() {  # $1 — чего именно не узнали; $2 — счётчик отказов
    warn "Канал НЕ ПРОВЕРЯЛСЯ: $1"
    mark 1 0 "$2"
    return 3
}

# ─────────────────────────── один проход ─────────────────────────────────────
#
# Коды возврата — четыре, они перечислены в шапке файла: 0 отправки без
# отказов, 1 отбит и сказано, 2 отбит и сказать не удалось, 3 не проверялся.
pass() {
    local metrics failed total delta delta_total rc=0
    read_state

    if ! metrics=$(fetch_metrics); then
        broken "диспетчер тревог не отвечает (${METRICS_URL})" \
            "Alertmanager не отвечает на ${METRICS_URL}. Тревоги ячейки сейчас не уходят никому." \
            "${PREV_FAILED:-0}"
        return $?
    fi

    failed=$(printf '%s' "$metrics" | sum_failed)
    total=$(printf '%s' "$metrics" | sum_total)

    # Ответ не от диспетчера (не туда нацелили, чужой порт, страница-заглушка).
    # Без этой ветки сторож был бы вечно зелёным на пустом ответе — то есть
    # зелёным ровно тогда, когда смотреть перестал.
    case "$metrics" in
        *alertmanager_notifications_total*) ;;
        *) broken "ответ не похож на метрики диспетчера (${METRICS_URL})" \
               "Сторож канала не видит метрик Alertmanager по ${METRICS_URL} — проверить некому и нечем." \
               "${PREV_FAILED:-0}"
           return $? ;;
    esac

    if [ -n "$STATE_BAD" ]; then
        # Файл состояния есть, а прошлого в нём нет. Своим сообщением, а не
        # молча веткой первого прохода: иначе потеря состояния выглядела бы
        # законным «запомнили» — каждый раз и бесконечно.
        write_state "$failed" "$total" "${LAST_SHOUT:-0}"
        unverified "${STATE_BAD} (${STATE}) — сравнивать не с чем, запомнили заново (за жизнь диспетчера отправок ${total}, отказов ${failed})" "$failed"
        return $?
    fi

    if [ -z "${PREV_FAILED:-}" ]; then
        # Первый проход: отказы в счётчике — история (диспетчер считает их
        # за всю жизнь процесса). Разбудить на ней значит будить при каждом
        # перезапуске ячейки. Но и зелёным это не является: про канал здесь
        # не спрошено ничего — сравнивать не с чем.
        write_state "$failed" "$total" "${LAST_SHOUT:-0}"
        unverified "первый проход, сравнивать не с чем: запомнили историю диспетчера (отправок ${total}, отказов ${failed})" "$failed"
        return $?
    fi

    if [ "$failed" -lt "$PREV_FAILED" ]; then
        # Счётчик отказов уехал вниз — диспетчера перезапустили. Это не «стало
        # лучше» и не повод будить: просто начинаем считать заново. Про отправки
        # за это окно сказать нечего — их счёт начался с нуля.
        write_state "$failed" "$total" "${LAST_SHOUT:-0}"
        unverified "счётчики диспетчера сброшены (перезапуск) — считаем заново (отправок ${total}, отказов ${failed})" "$failed"
        return $?
    fi

    # Рост отказов проверяется РАНЬШЕ сброса отправок, и порядок здесь
    # содержательный: сторож, замолчавший из-за странного состояния счётчиков
    # при растущих отказах, повторил бы ровно тот дефект, который чинится
    # этой задачей, — только в сторону пропущенной аварии.
    delta=$((failed - PREV_FAILED))
    if [ "$delta" -gt 0 ]; then
        broken "диспетчер не доставил ${delta} сообщений за последние $((INTERVAL / 60)) мин" \
            "Тревоги ячейки НЕ УХОДЯТ: диспетчер не смог доставить ${delta} сообщений за последние $((INTERVAL / 60)) мин (отказов всего ${failed}). Повторы он отменяет после четырёх попыток — эти сообщения потеряны." \
            "$failed"
        rc=$?
        write_state "$failed" "$total" "$LAST_SHOUT_NEW"
        return $rc
    fi

    delta_total=$((total - PREV_TOTAL))
    write_state "$failed" "$total" "${LAST_SHOUT:-0}"
    if [ "$delta_total" -gt 0 ]; then
        mark 1 1 "$failed"
        # ОГОВОРКА про то, чего это число НЕ обещает. Отправку диспетчер считает
        # в НАЧАЛЕ попытки, а отказ — только когда отменит повторы (замер 0158:
        # 345 секунд). Значит сообщение, которое в эту минуту ещё повторяется,
        # здесь выглядит неотказавшим и станет отказом на одном из следующих
        # проходов. Поэтому строка говорит «ни одно не отказало», а не
        # «доставлено»: доставку меряет только активная проба (вариант «а»
        # задачи 0236, отложенный до ответа, куда её слать).
        green "Новых отказов нет: за последние $((INTERVAL / 60)) мин диспетчер отправлял ${delta_total} сообщений, ни одно не отказало (за жизнь диспетчера отправок ${total}, отказов ${failed})"
        return 0
    fi

    # Ни отправок, ни отказов: доставку в этом окне проверять было НЕЧЕМ.
    # Ровно это отдаёт канал, отбитый час назад, — и ровно здесь до задачи
    # 0236 печаталось «Канал жив».
    unverified "за последние $((INTERVAL / 60)) мин диспетчер не отправлял ничего: ни отправок, ни отказов — доставку подтвердить НЕЧЕМ (за жизнь диспетчера отправок ${total}, отказов ${failed})" "$failed"
    return $?
}

