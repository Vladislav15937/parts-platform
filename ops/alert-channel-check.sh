# ─────────────────────────── проба дороги ────────────────────────────────────
#
# Отвечает на вопрос, который нельзя вывести из конфигурации: дотягивается ли
# контейнер ДО Telegram по IPv6. Спрашивается это у самой сети — разовым
# контейнером в ней, — а не у хоста: у хоста IPv6 может работать при
# неработающем NAT66 в docker, и ровно на этой разнице стояла авария.
probe() {
    local code4 code6
    printf 'Проба дороги до Telegram (сеть %s)\n' "$IPV6_NET"

    if ! docker network inspect "$IPV6_NET" >/dev/null 2>&1; then
        red "  Сети ${IPV6_NET} нет — правка compose не применена (docker compose up -d alertmanager)"
        return 1
    fi
    case "$(docker network inspect -f '{{.EnableIPv6}}' "$IPV6_NET" 2>/dev/null)" in
        true) printf '  ✓ у сети %s включён IPv6\n' "$IPV6_NET" ;;
        *)    red "  ✗ у сети ${IPV6_NET} IPv6 ВЫКЛЮЧЕН — сеть создана до правки, пересоздайте её"; return 1 ;;
    esac

    code6=$(docker run --rm --network "$IPV6_NET" "$PROBE_IMAGE" \
        -6 -s -o /dev/null -w '%{http_code}' --max-time 10 https://api.telegram.org 2>/dev/null)
    code4=$(docker run --rm --network "$IPV6_NET" "$PROBE_IMAGE" \
        -4 -s -o /dev/null -w '%{http_code}' --max-time 10 https://api.telegram.org 2>/dev/null)

    printf '  IPv6 к api.telegram.org: %s\n' "${code6:-нет ответа}"
    printf '  IPv4 к api.telegram.org: %s (на боевой ячейке он закрыт — это норма)\n' "${code4:-нет ответа}"

    case "${code6:-000}" in
        000|"") red "  ✗ по IPv6 из этой сети до Telegram НЕ достучаться"
                red "    Если IPv6 работает с хоста (curl -6 https://api.telegram.org), значит docker не делает NAT66:"
                red "    смотрите ops/CLAUDE.md, «Если NAT66 на машине не работает» — там запасной путь без простоя"
                return 1 ;;
        *)      green "  ✓ дорога есть: диспетчеру из этой сети Telegram доступен" ;;
    esac
}

# ─────────────────────────── проверка самого сторожа ─────────────────────────
#
# Сторож, не краснеющий на дефекте, хуже отсутствующего, и установить это
# можно только попыткой. Ячейка, docker и сеть для этого не нужны: подменяются
# оба шва — чем спрашиваем диспетчера и чем шлём сообщение.
selftest() {
    local bad=0 out rc
    # Каталог НЕ локальный: уборка висит на EXIT, а тот срабатывает уже вне
    # функции — с локальной переменной трап падал бы «tmp: unbound variable»
    # под `set -u`, то есть сразу после зелёной самопроверки.
    tmp="$(mktemp -d)"
    trap 'rm -rf "$tmp"' EXIT
    echo "Самопроверка ops/alert-channel-check.sh"

    # Заглушка отправки: складывает сообщение в файл, чтобы проверить не только
    # «покраснел», но и «сказал ли и что именно».
    cat > "$tmp/send-ok" <<EOF
#!/bin/sh
cat >> "$tmp/sent.txt"
exit 0
EOF
    cat > "$tmp/send-fail" <<EOF
#!/bin/sh
cat >> "$tmp/sent.txt"
exit 1
EOF
    chmod +x "$tmp/send-ok" "$tmp/send-fail"

    metrics_file() {  # $1 — отказов, $2 — отправок
        printf 'alertmanager_notifications_total{integration="telegram"} %s\n' "$2" > "$tmp/metrics"
        printf 'alertmanager_notifications_failed_total{integration="telegram",reason="other"} %s\n' "$1" >> "$tmp/metrics"
        printf 'alertmanager_notifications_failed_total{integration="telegram",reason="serverError"} 0\n' >> "$tmp/metrics"
    }

    # Чем запускать себя же. В контейнере сторожа bash'а НЕТ (образ
    # curlimages/curl), и compose зовёт скрипт через /bin/sh — значит
    # самопроверка, намертво прибитая к bash, проверяла бы не тот
    # интерпретатор, под которым сторож работает у клиента. Поймано прогоном
    # самопроверки внутри самого образа: «bash: not found», девять случаев
    # из девяти.
    RUNNER="${ALERT_CHECK_SHELL:-$(command -v bash || command -v sh)}"

    run() {  # $1 — команда добычи метрик, $2 — отправщик
        : > "$tmp/sent.txt"
        set +e
        # ENV_FILE=/dev/null обязателен, и это не перестраховка. Скрипт
        # сорсит файл ячейки через `set -a`, то есть `.env` СТАРШЕ того,
        # что передал вызывающий, — и проба, запущенная там, где `.env`
        # лежит, меряет не сторожа, а чужой файл. Поймано красным CI:
        # задача «Развёртывание» шагом раньше пишет настоящий `.env`
        # (заглушки из `.env.example`), и его `ALERT_CHANNEL_REPEAT=3600`
        # отменял выдержку, заданную пробой, — у себя зелено, на раннере
        # красное. Тот же класс, что в задаче 0144.
        out=$(ALERT_CHECK_FETCH="$1" ALERT_CHECK_SEND="$2" \
              ALERT_CHANNEL_STATE="$tmp/state" ALERT_CHANNEL_REPEAT="${REPEAT_OVERRIDE:-3600}" \
              PUSHGATEWAY_URL="file:///dev/null" APP_CELL=cell01 ENV_FILE=/dev/null \
              "$RUNNER" "$SELF" 2>&1)
        rc=$?
        set -e
    }

    sent() { [ -s "$tmp/sent.txt" ]; }

    # Проверяем СЛОВА, а не только код возврата: подделка, вернувшая зелёную
    # строку и оставившая прежний код, прошла бы проверку кода насквозь
    # (урок 0147 и случая 8 ниже).
    says() {  # $1 — имя случая, $2 — слово, которое обязано быть в выводе
        case "$out" in
            *"$2"*) printf '  ✓ %s\n' "$1" ;;
            *) red "  ✗ ${1}: в выводе нет «${2}»"
               printf '%s\n' "$out" | sed 's/^/      /' >&2
               bad=1 ;;
        esac
    }

    says_not() {  # $1 — имя случая, $2 — слово, которого быть НЕ должно
        case "$out" in
            *"$2"*) red "  ✗ ${1}: в выводе есть «${2}», а его быть не должно"
                    printf '%s\n' "$out" | sed 's/^/      /' >&2
                    bad=1 ;;
            *) printf '  ✓ %s\n' "$1" ;;
        esac
    }

    check() {  # $1 — имя, $2 — ожидаемый код, $3 — ожидание про отправку (шлём|молчим), $4 — слово в сообщении
        local name="$1" want_rc="$2" want_send="$3" word="${4:-}"
        if [ "$rc" != "$want_rc" ]; then
            red "  ✗ ${name}: код ${rc}, ожидался ${want_rc}"
            printf '%s\n' "$out" | sed 's/^/      /' >&2
            bad=1; return
        fi
        if [ "$want_send" = шлём ]; then
            if ! sent; then
                red "  ✗ ${name}: сообщение вторым путём НЕ ушло"
                bad=1; return
            fi
            if [ -n "$word" ] && ! grep -q "$word" "$tmp/sent.txt"; then
                red "  ✗ ${name}: в сообщении нет «${word}»"
                sed 's/^/      /' "$tmp/sent.txt" >&2
                bad=1; return
            fi
        else
            if sent; then
                red "  ✗ ${name}: сторож разбудил человека там, где должен молчать"
                sed 's/^/      /' "$tmp/sent.txt" >&2
                bad=1; return
            fi
        fi
        printf '  ✓ %s\n' "$name"
    }

    # 1. Первый проход: отказы в счётчике — история за жизнь диспетчера.
    #    Разбудить на ней значит будить при каждом перезапуске ячейки. Но
    #    и зелёным это не является: про канал здесь не спрошено ничего.
    rm -f "$tmp/state"
    metrics_file 2731 5000
    run "cat $tmp/metrics" "$tmp/send-ok"
    check "первый проход на старых отказах — молчит и НЕ проверялся" 3 молчим
    says "первый проход назван первым проходом" "первый проход"
    says_not "первый проход не объявлен живым каналом" "Канал жив"

    # 2. ГЛАВНЫЙ случай задачи 0236: за окно диспетчер не отправлял ничего.
    #    Ровно это отдаёт канал, отбитый час назад (повторы отменены, прирост
    #    отказов нулевой), и ровно здесь прежняя редакция печатала «Канал жив».
    run "cat $tmp/metrics" "$tmp/send-ok"
    check "ни отправок, ни отказов — НЕ проверялся, молчит" 3 молчим
    says "сказано, что отправок за окно не было" "не отправлял ничего"
    says_not "молчание диспетчера не объявлено живым каналом" "Канал жив"

    # 2б. Отправки были и ни одна не отказала — единственное зелёное. Строка
    #     утверждает ровно измеренное: «новых отказов нет», а не «канал жив».
    metrics_file 2731 5003
    run "cat $tmp/metrics" "$tmp/send-ok"
    check "отправки есть, отказов нет — зелёное, молчит" 0 молчим
    says "названо число отправок за окно" "диспетчер отправлял 3 сообщений"
    says_not "зелёная строка не обещает живого канала" "Канал жив"

    # 3. Отказы растут — это и есть авария 19 сентября.
    metrics_file 2735 5000
    run "cat $tmp/metrics" "$tmp/send-ok"
    check "отказы растут — красное и сказано вторым путём" 1 шлём "ВТОРЫМ путём"

    # 4. Выдержка: будить каждые пять минут — значит быть отключённым.
    metrics_file 2740 5000
    run "cat $tmp/metrics" "$tmp/send-ok"
    check "повтор внутри часа — красное, но человека не будит" 1 молчим

    # 5. Час прошёл — будим снова.
    metrics_file 2750 5000
    REPEAT_OVERRIDE=0 run "cat $tmp/metrics" "$tmp/send-ok"
    check "выдержка вышла — будит снова" 1 шлём "НЕ УХОДЯТ"

    # 6. Диспетчер не отвечает вовсе.
    rm -f "$tmp/state"
    run "false" "$tmp/send-ok"
    check "первый проход, диспетчер молчит — красное" 1 шлём "не отвечает"

    # 7. Ответ не от диспетчера: не туда нацелили. Без этой ветки сторож был
    #    бы вечно зелёным на пустом ответе.
    rm -f "$tmp/state"
    printf 'какая-то страница\n' > "$tmp/chuzhoe"
    run "cat $tmp/chuzhoe" "$tmp/send-ok"
    check "ответ не похож на метрики — красное" 1 шлём "не видит метрик"

    # 8. Второй путь тоже отказал. «Сообщили» и «не смогли сообщить» — разные
    #    вещи, и выдать второе за первое значит повторить саму поломку.
    #
    #    Проверяются И код, И слова. Кода мало: подделка, убравшая строку
    #    «СООБЩИТЬ НЕ УДАЛОСЬ» и оставившая код 2, проходила эту пробу
    #    зелёной — то есть сторож молча переставал говорить человеку, что
    #    ячейка сейчас нема. Поймано возвратом дефекта, а не чтением.
    rm -f "$tmp/state"
    metrics_file 1 1
    run "cat $tmp/metrics" "$tmp/send-ok"     # первый проход — запомнили
    metrics_file 5 1
    run "cat $tmp/metrics" "$tmp/send-fail"
    check "второй путь отказал — код 2, а не «сообщено»" 2 шлём
    case "$out" in
        *"СООБЩИТЬ НЕ УДАЛОСЬ"*)
            printf '  ✓ и сказано словами: «ячейка сейчас нема»\n' ;;
        *)  red "  ✗ второй путь отказал, а сторож об этом не сказал — код есть, слов нет"
            printf '%s\n' "$out" | sed 's/^/      /' >&2
            bad=1 ;;
    esac

    # 8в. Локаль с запятой в дробях (задача 0126). Счётчик Prometheus
    #     приезжает как «1.5e+06»; под ru_RU awk читает его как 1, и отказов
    #     набегало бы меньше, чем было. Локаль берётся по разделителю, а не
    #     по имени; export обязателен. Нет такой локали — случай непроверен.
    zap=""
    for loc in $(locale -a 2>/dev/null | grep -iE '^(ru_RU|de_DE|fr_FR|pt_BR)\.(utf-?8)$'); do
        [ "$(LC_ALL="$loc" locale decimal_point 2>/dev/null)" = "," ] || continue
        zap="$loc"; break
    done
    if [ -n "$zap" ]; then
        got=$( export LC_ALL="$zap"
               printf 'alertmanager_notifications_failed_total{integration="telegram",reason="other"} 1.5e+06\n' | sum_failed )
        if [ "$got" = 1500000 ]; then
            printf '  ✓ под локалью с запятой (%s) счётчик 1.5e+06 читается целиком\n' "$zap"
        else
            red "  ✗ под ${zap} счётчик 1.5e+06 прочитан как «${got}» вместо 1500000"
            bad=1
        fi
    else
        printf '  · локали с запятой в дробях на этой машине нет — случай 8в не проверен\n'
    fi

    # 9. Счётчики уехали вниз — диспетчера перезапустили, а не «стало лучше».
    #    Будить не на чем, но и доставку проверить нечем: счёт начался заново.
    rm -f "$tmp/state"
    metrics_file 100 100
    run "cat $tmp/metrics" "$tmp/send-ok"
    metrics_file 3 5
    run "cat $tmp/metrics" "$tmp/send-ok"
    check "перезапуск диспетчера — молчит и НЕ проверялся" 3 молчим
    says "перезапуск назван перезапуском" "перезапуск"

    # 9б. Перезапуск виден и по ОТПРАВКАМ: отказов могло не быть вовсе, тогда
    #     вниз уезжает только второй счётчик. Без этой половины условия сторож
    #     считал бы прирост отправок по чужой истории.
    rm -f "$tmp/state"
    metrics_file 0 500
    run "cat $tmp/metrics" "$tmp/send-ok"
    metrics_file 0 7
    run "cat $tmp/metrics" "$tmp/send-ok"
    check "перезапуск виден по отправкам — молчит и НЕ проверялся" 3 молчим

    # 9в. Непригодный файл состояния — своим сообщением, а не молча веткой
    #     первого прохода: иначе каждая потеря состояния читалась бы как
    #     законное «запомнили». Мусор и обрезанный файл — два разных отказа.
    metrics_file 2731 5000
    printf 'мусор\n' > "$tmp/state"
    run "cat $tmp/metrics" "$tmp/send-ok"
    check "мусор в состоянии — НЕ проверялся, молчит" 3 молчим
    says "непригодное состояние названо своим сообщением" "состояния"
    says_not "мусор не выдан за первый проход" "первый проход"

    printf 'PREV_FAILED=7\n' > "$tmp/state"
    run "cat $tmp/metrics" "$tmp/send-ok"
    check "обрезанное состояние — НЕ проверялся, молчит" 3 молчим
    says "назван недостающий счётчик отправок" "нет числа отправок"

    # 9г. Обратный край: запомнив заново, следующий проход снова мерит —
    #     сторож, залипший на «не проверялся», был бы не лучше прежнего.
    metrics_file 2731 5004
    run "cat $tmp/metrics" "$tmp/send-ok"
    check "после непригодного состояния проход снова мерит" 0 молчим

    # 10. И сама проба не зависит от `.env`, лежащего рядом. Случай не
    #     умозрительный: ровно на нём покраснел CI — шаг «Боевой compose»
    #     пишет `.env` из заглушек, а `set -a; . ./.env` старше окружения,
    #     переданного пробой. Здесь это возвращается подделкой: рядом
    #     с копией сторожа кладётся `.env` с выдержкой в час, а проба
    #     требует, чтобы сторож всё равно разбудил — как ей и задано.
    #     Порядок шагов тут не случаен, и первая редакция случая была
    #     БЕСПОЛЕЗНА именно из-за него: пока сторож не будил ни разу,
    #     `LAST_SHOUT` равен нулю, ветка выдержки не выполняется вовсе —
    #     и подделка, вернувшая зависимость от `.env`, проходила зелёной.
    #     Значит будить надо ДВАЖДЫ: первый раз ставит отметку, и только
    #     второй проверяет, чья выдержка победила — файла или пробы.
    local tree="$tmp/derevo"
    mkdir -p "$tree/ops"
    cp "$SELF" "$tree/ops/alert-channel-check.sh"
    # Общее место разрешения пути (ops/env-file.sh, задача 0250) — иначе копия
    # работала бы в режиме «модуля рядом нет», которого в бою не бывает,
    # и случай проверял бы не то устройство, что уезжает на ячейку.
    cp ops/env-file.sh "$tree/ops/env-file.sh"
    printf 'ALERT_CHANNEL_REPEAT=3600\nALERT_CHANNEL_INTERVAL=300\n' > "$tree/.env"
    rm -f "$tmp/state"
    metrics_file 1 1
    SELF_SAVED="$SELF"; SELF="$tree/ops/alert-channel-check.sh"
    run "cat $tmp/metrics" "$tmp/send-ok"      # первый проход — запомнили
    metrics_file 5 1
    run "cat $tmp/metrics" "$tmp/send-ok"      # разбудили, отметка поставлена
    metrics_file 9 1
    REPEAT_OVERRIDE=0 run "cat $tmp/metrics" "$tmp/send-ok"
    SELF="$SELF_SAVED"
    check "«.env» рядом не отменяет выдержки, заданной пробой" 1 шлём "НЕ УХОДЯТ"

    # 10б. .env по АБСОЛЮТНОМУ пути читается (задача 0250). Сторожа человек
    #      зовёт руками на ячейке (`--probe`, docs/deployment.md), и файл там
    #      лежит абсолютным путём. До правки «.//srv/…» не открывался вовсе:
    #      `set -e` здесь нет, поэтому сторож молча работал на умолчаниях —
    #      спрашивал не того диспетчера и слал не в тот чат. Проверяется ПУТЬ
    #      ЗАПУСКА, а не функция (урок 0144): адрес диспетчера задаётся ТОЛЬКО
    #      файлом, и если он доехал, отказ называет именно его.
    local absenv0250="$tmp/env-abs-0250"
    printf 'ALERT_CHANNEL_METRICS_URL=http://127.0.0.1:9/metrics\n' > "$absenv0250"
    rm -f "$tmp/state"
    : > "$tmp/sent.txt"
    set +e
    out=$(ALERT_CHECK_SEND="$tmp/send-ok" ALERT_CHANNEL_STATE="$tmp/state" \
          PUSHGATEWAY_URL="file:///dev/null" ENV_FILE="$absenv0250" \
          "$RUNNER" "$SELF" 2>&1)
    rc=$?
    set -e
    says ".env по абсолютному пути прочитан: адрес диспетчера взят из файла" "127.0.0.1:9/metrics"
    says_not "«.//» в пути к файлу окружения не появляется" ".//"

    # 10в. ВОЗВРАТ ДЕФЕКТА 0250: «./» перед абсолютным путём вернулось.
    #      Подделывается общее место, а скрипт берётся настоящий — он сорсит
    #      подделанный модуль. `sed`, а не python3: самопроверка обязана быть
    #      зелёной В КОНТЕЙНЕРЕ сторожа (`curlimages/curl`), где python3 нет
    #      вовсе. Дерево с каталогом `ops` — урок 0151, целость до запуска —
    #      урок 0198, рекурсию обрывает переменная — урок 0195.
    if [ -z "${ALERT_CHECK_NO_FAKE:-}" ]; then
        local tree0250="$tmp/derevo-0250"
        mkdir -p "$tree0250/ops"
        cp "$SELF" "$tree0250/ops/alert-channel-check.sh"
        chmod +x "$tree0250/ops/alert-channel-check.sh"
        sed "s@^        /\\*) printf '%s@        /*) printf './%s@" \
            ops/env-file.sh > "$tree0250/ops/env-file.sh"
        if ! grep -q "printf './%s" "$tree0250/ops/env-file.sh"; then
            red "  ✗ возврат дефекта 0250: подделку негде поставить — образца нет в ops/env-file.sh"
            bad=1
        elif ! "$RUNNER" -n "$tree0250/ops/env-file.sh" 2>/dev/null; then
            red "  ✗ возврат дефекта 0250: подделка сломала синтаксис — её красное ничего не значило бы"
            bad=1
        else
            set +e
            fake_out=$(ALERT_CHECK_NO_FAKE=1 ENV_FILE=/dev/null \
                PUSHGATEWAY_URL="file:///dev/null" \
                "$RUNNER" "$tree0250/ops/alert-channel-check.sh" --selftest 2>&1)
            fake_rc=$?
            set -e
            case "$fake_rc" in
                0) red "  ✗ ВОЗВРАТ ДЕФЕКТА 0250: копия с «./» перед абсолютным путём ПРОШЛА самопроверку"
                   printf '%s\n' "$fake_out" | sed 's/^/      /' >&2
                   bad=1 ;;
                *) printf '  ✓ возврат дефекта: «./» перед абсолютным путём валит самопроверку\n' ;;
            esac
        fi
    fi

    # 11. ВОЗВРАТ ДЕФЕКТА. Подделка возвращает ровно то, что было до задачи
    #     0236: «не проверялся» снова печатается зелёным и отвечает нулём.
    #     Копия обязана ВАЛИТЬ самопроверку — без этого случая остальные
    #     не утверждают ничего: проверка, не краснеющая на дефекте, хуже
    #     отсутствующей. Копия лежит в своём дереве с каталогом `ops` (скрипт
    #     уходит в корень репозитория от своего каталога — урок 0151), целость
    #     её проверяется ДО запуска (урок 0198: красное от сломанного
    #     синтаксиса не говорит ни о чём), а рекурсию обрывает переменная.
    if [ -z "${ALERT_CHECK_NO_FAKE:-}" ]; then
        fake="$tmp/poddelka"
        mkdir -p "$fake/ops"
        sed -e 's/^    warn "Канал НЕ ПРОВЕРЯЛСЯ: \$1"$/    green "Канал жив: новых отказов нет"/' \
            -e 's/^    return 3$/    return 0/' \
            "$SELF" > "$fake/ops/alert-channel-check.sh"
        chmod +x "$fake/ops/alert-channel-check.sh"
        if cmp -s "$SELF" "$fake/ops/alert-channel-check.sh"; then
            red "  ✗ возврат дефекта: подделку негде поставить — образец не нашёлся в файле"
            bad=1
        elif ! "$RUNNER" -n "$fake/ops/alert-channel-check.sh" 2>/dev/null; then
            red "  ✗ возврат дефекта: подделка сломала синтаксис — её красное говорило бы не о дефекте"
            bad=1
        else
            set +e
            fake_out=$(ALERT_CHECK_NO_FAKE=1 ENV_FILE=/dev/null PUSHGATEWAY_URL="file:///dev/null" \
                "$RUNNER" "$fake/ops/alert-channel-check.sh" --selftest 2>&1)
            fake_rc=$?
            set -e
            case "$fake_rc" in
                0) red "  ✗ возврат дефекта: копия, объявляющая НЕПРОВЕРЕННОЕ зелёным, прошла самопроверку"
                   printf '%s\n' "$fake_out" | sed 's/^/      /' >&2
                   bad=1 ;;
                *) printf '  ✓ возврат дефекта: копия с зелёным «не проверялся» валит самопроверку\n' ;;
            esac
        fi
    fi

    [ $bad = 0 ] || { red "Самопроверка не прошла"; exit 1; }
    green "Самопроверка пройдена: разбор, отказы и непроверенное. Канал и ячейка не проверялись — их спрашивают без аргументов и --probe."
}

SELF="$(cd "$(dirname "$0")" && pwd)/$(basename "$0")"
LAST_SHOUT_NEW=0

case "$MODE" in
    самопроверка) selftest; exit 0 ;;
    проба)        probe; exit $? ;;
    проход)       pass; exit $? ;;
    цикл)
        # Контейнер alert-watch: проход, пауза, проход. Код возврата здесь
        # никого не интересует — сторож обязан пережить и отбитый канал,
        # и недоступного диспетчера, иначе `restart: unless-stopped`
        # превратит его в круг перезапусков.
        while :; do
            printf '\n[%s] проход сторожа канала\n' "$(date -u '+%Y-%m-%d %H:%M:%SZ')"
            pass || true
            sleep "$INTERVAL"
        done ;;
esac
