#!/usr/bin/env bash
# Работающий контейнер взят из того образа, что записан в настройках.
#
#   ops/image-state.sh             # спросить ячейку и сверить с настройками
#   ops/image-state.sh --selftest  # проверить самого сторожа на подделках
#
# ЗАЧЕМ ОН ЕСТЬ. 26 сентября 2026 зеркало образов в GHCR было сделано и слито
# (задача 0180), а на боевой ячейке хранилище продолжало работать с мёртвого
# `quay.io` — образа, репозитория которого в реестре больше нет. Применение
# выполняет человек готовой командой (агентам в ячейку нельзя), и подтвердить
# результат он мог единственной строкой:
#
#     docker compose exec minio minio --version
#
# А она НЕ РАЗЛИЧАЕТ ИСХОДОВ. Версия у зеркала та же самая — это условие
# самой 0180 («понижения формата данных нет», решение владельца от 18 сентября
# 2026 «не понижать»), — то есть строка печатает одно и то же до подмены
# и после. Замерено на обоих образах: «minio version RELEASE.2025-09-07T16-13-09Z
# (commit-id=07c3a429…)» буква в букву, при разных образах. Она доказывает,
# что хранилище живо, и не доказывает, откуда взят его бинарник.
#
# Спросить ячейку было нечем ничем: `tools/mirror-images.sh --проверить` про
# реестр, `tools/image-pin-guard.py` про исходники, `tools/alert-image-guard.py`
# про реестр, `ops/config-guard.sh` про монтируемые файлы, пять самопроверок
# выкладки про образы не спрашивают вовсе, и в четырнадцати правилах
# `ops/alerts.yml` про них нет ни одного (задача 0198).
#
# ПО ЧЕМУ СВЕРЯЕМ — ПО ТОМУ, ЧТО ПОДМЕНИТЬ НЕЛЬЗЯ. Не по версии внутри
# контейнера и не по имени образа, напечатанному самим контейнером, а по двум
# записям демона:
#
#   .Config.Image — адрес, которым контейнер БЫЛ СОЗДАН (слова человеку);
#   .Image        — сумма конфигурации того образа (признак).
#
# Сумма и есть неподменяемое: у зеркала и у источника версия совпадает
# по построению, а байты — нет (замерено: `sha256:14cea493…` против
# `sha256:267fc0f0…`). Сверяется она с суммой, в которую адрес из настроек
# разрешается на этой машине СЕЙЧАС, — поэтому ловится и случай, когда адрес
# не менялся, а под тегом лежат другие байты.
#
# ПОЧЕМУ ЗДЕСЬ DOCKER, А НЕ РЕЕСТР. Запрет «не проверять образ docker'ом там,
# где нужен реестр» (`tools/alert-image-guard.py`, `tools/mirror-images.sh`)
# про другой вопрос: при containerd-хранилище `docker manifest inspect`
# отвечает из локального индекса, то есть про нашу машину, — и потому
# «лежит ли образ в реестре» им спрашивать нельзя. Здесь вопрос ровно
# обратный: ЧТО РАБОТАЕТ НА ЭТОЙ МАШИНЕ. Про это, кроме её демона, не знает
# никто, и реестр тут был бы неверным инструментом.
#
# ЧИТАЮЩИЙ — он не пересоздаёт контейнеров, не тянет образов и не трогает
# ни одного файла. Всё, что меняет ячейку, остаётся человеку готовой командой:
# он её и печатает.
#
# ГДЕ ЕГО ЗОВУТ. `ops/config-guard.sh` — тот стоит первым шагом `ops/deploy.sh`,
# первой строкой раздела «Как поднять» в `docs/deployment.md` и шагом CI, то
# есть это место, куда человек и так заходит. Ещё один скрипт, который никто
# не зовёт, повторил бы нынешнее состояние: знание есть, спросить некому.
# Отдельно его запускает дежурный — этой командой.
#
#   COMPOSE_FILE=…              какой compose спрашивать (умолчание docker-compose.prod.yml)
#   ENV_FILE=…                  файл окружения ячейки (умолчание .env)
#   IMAGE_STATE_DOCKER=…        чем спрашивать демона (умолчание docker)
#   IMAGE_STATE_ROOT=…          корень дерева — только для самопроверки
#   IMAGE_STATE_DECLARED=файл   что «в настройках» (подмена для самопроверки)
#   IMAGE_STATE_RUNNING=файл    что «работает» (подмена для самопроверки)

set -uo pipefail

SELF="$(cd "$(dirname "$0")" && pwd)/$(basename "$0")"
ROOT="${IMAGE_STATE_ROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
cd "$ROOT" || exit 1

COMPOSE_FILE="${COMPOSE_FILE:-docker-compose.prod.yml}"
ENV_FILE="${ENV_FILE:-.env}"
DC="${DC:-docker compose}"
DOCKER="${IMAGE_STATE_DOCKER:-docker}"

red()   { printf '\033[1;31m%s\033[0m\n' "$1" >&2; }
green() { printf '\033[1;32m%s\033[0m\n' "$1"; }

# Как это чинят — одной строкой на весь скрипт: два написания разъехались бы,
# а цена ошибки здесь — человек, считающий смену образа состоявшейся.
# `--no-deps` не украшение: без него `up -d` сводит зависимости и пересоздаёт
# соседей (у minio это база), то есть перезапускает Postgres между делом.
kak_chinit() {  # сервис
    printf '      Пересоздать этот контейнер (и только его):\n'
    printf '        %s -f %s pull %s\n' "$DC" "$COMPOSE_FILE" "$1"
    printf '        %s -f %s up -d --no-deps %s\n' "$DC" "$COMPOSE_FILE" "$1"
    printf '      ПЕРЕСОЗДАНИЕ, а не restart: образ, как и окружение, читается\n'
    printf '      при создании контейнера — restart оставит прежний.\n'
}

# Короткая сумма человеку в глаза. Полная — в `docker inspect`; в отчёте она
# только шумит, а различать исходы хватает и двенадцати знаков.
short() { printf '%s' "${1#sha256:}" | cut -c1-12; }

# ─────────────────────── вердикт по одному сервису ───────────────────────────
#
# Разбор отделён от опроса намеренно, как у ops/deploy-checks.sh
# и ops/control-plane.sh: краснеть проверка обязана на дефекте, а проверить
# это можно только подсунув ей ответ.
verdict_service() {  # сервис, адрес в настройках, сумма настроек, контейнер, адрес у контейнера, сумма контейнера
    local svc="$1" want_ref="$2" want_id="$3" cname="$4" got_ref="$5" got_id="$6"

    if [ -z "$got_id" ]; then
        # Контейнера нет вовсе — сверять нечего. Законно: погашенная сборка
        # и `mc` стоят под профилями, и это норма, а не беда.
        return 0
    fi

    if [ -z "$want_id" ]; then
        # Адрес из настроек на этой машине не разрешается: образ не забирали.
        # Это и есть состояние боевой ячейки после слияния 0180 — настройки
        # приехали rsync'ом, образ не тянули, контейнер работает на прежнем.
        red "  ✗ ${svc}: образа из настроек на машине НЕТ ВОВСЕ — его не забирали"
        red "      в настройках: ${want_ref} (на машине отсутствует)"
        red "      у контейнера: ${got_ref} ($(short "$got_id")) — ${cname}"
        red "      Значит ячейка работает на прежнем образе, а новый не скачан."
        kak_chinit "$svc" >&2
        red "      Прежний образ живёт ТОЛЬКО в кэше этой машины: до проверки"
        red "      смены не запускайте уборку образов (docker image prune) —"
        red "      иначе дороги назад не останется вовсе (tasks/0180)."
        return 1
    fi

    if [ "$want_id" = "$got_id" ]; then
        printf '  ✓ %s: %s (%s)\n' "$svc" "$want_ref" "$(short "$want_id")"
        return 0
    fi

    if [ "$want_ref" = "$got_ref" ]; then
        # Адрес тот же, байты другие: под тегом лежит не то, чем создан
        # контейнер. Так выглядит переопубликованный тег — то, из-за чего
        # плавающий тег запрещён корневым CLAUDE.md.
        red "  ✗ ${svc}: адрес тот же, а ОБРАЗ ДРУГОЙ — под тегом другие байты"
        red "      в настройках: ${want_ref} ($(short "$want_id"))"
        red "      у контейнера: ${got_ref} ($(short "$got_id")) — ${cname}"
        red "      Тег переопубликован либо образ забрали заново после создания"
        red "      контейнера. Версия внутри контейнера этого не показывает."
        kak_chinit "$svc" >&2
        return 1
    fi

    # Главный случай задачи: настройки правлены, контейнер не пересоздан.
    red "  ✗ ${svc}: работает НЕ ТОТ образ, что записан в настройках"
    red "      в настройках: ${want_ref} ($(short "$want_id"))"
    red "      у контейнера: ${got_ref} ($(short "$got_id")) — ${cname}"
    red "      Настройки правлены, контейнер не пересоздан: адрес в compose"
    red "      сменился, а контейнер остался прежним со своим образом."
    red "      Версия внутри контейнера этого НЕ ПОКАЖЕТ — у зеркала"
    red "      и у источника она совпадает по построению (tasks/0180)."
    kak_chinit "$svc" >&2
    return 1
}

# ─────────────────────────── чем спрашиваем ──────────────────────────────────

# Что говорят настройки: сервис → адрес образа. Спрашиваем сам compose,
# а не читаем YAML глазами, — по тому же доводу, что у ops/config-guard.sh
# и ops/builds-guard.sh: какие сервисы есть и во что разворачиваются их адреса,
# считает он, по своим правилам интерполяции и `extends`. У minio и mc адрес
# приезжает из ops/images.yml именно так.
declared() {
    if [ -n "${IMAGE_STATE_DECLARED:-}" ]; then
        cat "$IMAGE_STATE_DECLARED"
        return $?
    fi
    # Сначала спрашиваем compose, ПОТОМ разбираем: в конвейере отказ compose
    # доезжал бы до python'а пустым вводом, и человек читал бы traceback разбора
    # вместо «нет файла окружения». Тот же класс, что «код возврата брать
    # до конвейера» (ops/CLAUDE.md, задача 0137) — поймано живым прогоном
    # на дереве без .env.
    $DC -f "$COMPOSE_FILE" --project-directory . --env-file "$ENV_FILE" \
        --profile blue --profile green --profile kafka --profile backup \
        config --format json >"$CFG" 2>"$ERR" || return 1
    python3 -c '
import json, sys
d = json.load(sys.stdin)
for name, svc in sorted((d.get("services") or {}).items()):
    ref = svc.get("image")
    if ref:
        print(name + "\t" + ref)
' <"$CFG" 2>>"$ERR" || return 1
}

# Что работает: сервис → контейнер, адрес при создании, сумма образа.
#
# Только РАБОТАЮЩИЕ контейнеры: погашенная сборка и разовый `mc` стоят
# под профилями законно, и краснеть на них значило бы краснеть на исправной
# ячейке. Сумму берём у демона (`.Image`), а не из метки `com.docker.compose.image`
# в выводе `ps`: метку ставит compose, и она про его версию, а запись демона —
# про то, из чего контейнер создан.
running() {
    if [ -n "${IMAGE_STATE_RUNNING:-}" ]; then
        cat "$IMAGE_STATE_RUNNING"
        return $?
    fi
    local list svc cname
    # Тем же порядком, что и declared(): спросить, проверить код, разобрать.
    $DC -f "$COMPOSE_FILE" --project-directory . --env-file "$ENV_FILE" \
        --profile blue --profile green --profile kafka --profile backup \
        ps --format json >"$PS" 2>"$ERR" || return 1
    list=$(python3 -c '
import json, sys
raw = sys.stdin.read().strip()
rows = []
if raw:
    try:
        # Compose v2 отдаёт массив, v5 — по объекту на строку. Обе формы живые:
        # у разработчика одна версия, на ячейке другая.
        doc = json.loads(raw)
        rows = doc if isinstance(doc, list) else [doc]
    except ValueError:
        for line in raw.splitlines():
            line = line.strip()
            if line:
                rows.append(json.loads(line))
for r in rows:
    if (r.get("State") or "") != "running":
        continue
    print((r.get("Service") or "") + "\t" + (r.get("Name") or ""))
' <"$PS" 2>>"$ERR") || return 1

    while IFS=$'\t' read -r svc cname; do
        [ -n "$svc" ] && [ -n "$cname" ] || continue
        local answer
        answer=$($DOCKER inspect "$cname" \
            --format '{{.Config.Image}}	{{.Image}}' 2>>"$ERR") || {
            # «Спросить нечем» — это не «всё сходится»: тихий успех здесь
            # означал бы проверку, не утверждающую ничего (урок 0151).
            printf '%s\t%s\t?\t?\n' "$svc" "$cname"
            continue
        }
        printf '%s\t%s\t%s\n' "$svc" "$cname" "$answer"
    done <<< "$list"
}

# Во что адрес из настроек разрешается на этой машине СЕЙЧАС.
resolve() {  # адрес → сумма конфигурации или пусто
    $DOCKER image inspect "$1" --format '{{.Id}}' 2>/dev/null | head -n1
}

# ──────────────────────────────── проверка ───────────────────────────────────
check_images() {
    # `unknown` отдельно от `bad` намеренно: «спросить не удалось» и «работает
    # не то» — разные ответы, и выдать первое за второе значило бы назвать
    # расхождение, которого не измеряли. Ровно этот класс волна 0146–0151
    # чинила пять задач подряд. Код возврата 2 означает «сверка не выполнена».
    local bad=0 unknown=0 seen=0 skipped=0 dec run svc ref cname got_ref got_id want_id

    if ! command -v python3 >/dev/null 2>&1; then
        red "  ✗ нечем разобрать ответ: нет python3"
        return 2
    fi

    dec=$(declared) || {
        red "Не удалось спросить compose про образы:"
        sed 's/^/    /' "$ERR" >&2
        return 2
    }
    if [ -z "$dec" ]; then
        red "  ✗ compose не называет ни одного образа — сверять нечего с чем"
        red "      Ждали сервисы с ключом image в ${COMPOSE_FILE}."
        return 2
    fi

    run=$(running) || {
        red "Не удалось спросить ячейку про контейнеры:"
        sed 's/^/    /' "$ERR" >&2
        return 2
    }
    if [ -z "$run" ]; then
        # Обычное состояние прогона CI и машины до подъёма ячейки. Молчим
        # и говорим, почему: «нечего сверять» и «всё сходится» — разные ответы.
        printf '  · контейнеров ячейки не запущено — сверять нечего\n'
        return 0
    fi

    while IFS=$'\t' read -r svc ref; do
        [ -n "$svc" ] || continue
        # Что работает под этим сервисом.
        cname=$(printf '%s\n' "$run" | awk -F'\t' -v s="$svc" '$1==s {print $2; exit}')
        got_ref=$(printf '%s\n' "$run" | awk -F'\t' -v s="$svc" '$1==s {print $3; exit}')
        got_id=$(printf '%s\n' "$run" | awk -F'\t' -v s="$svc" '$1==s {print $4; exit}')

        if [ -z "$cname" ]; then
            skipped=$((skipped + 1))
            continue
        fi
        seen=$((seen + 1))

        if [ "$got_id" = "?" ]; then
            red "  ✗ ${svc}: у контейнера ${cname} не спросить образ — демон не ответил"
            red "      Это НЕ «образ сходится»: ответа нет вовсе."
            sed 's/^/      /' "$ERR" >&2
            unknown=$((unknown + 1))
            continue
        fi

        want_id=$(resolve "$ref")
        verdict_service "$svc" "$ref" "$want_id" "$cname" "$got_ref" "$got_id" || bad=$((bad + 1))
    done <<< "$dec"

    if [ "$seen" = 0 ]; then
        printf '  · ни один работающий контейнер не сопоставлен сервису — сверять нечего\n'
        return 0
    fi
    printf '  · сверено сервисов: %s' "$seen"
    [ "$skipped" = 0 ] && printf '\n' || printf ' (не запущено: %s)\n' "$skipped"
    [ "$bad" != 0 ] && return 1
    [ "$unknown" != 0 ] && return 2
    return 0
}

# ───────────────────────────── самопроверка ──────────────────────────────────
#
# Сторож, не краснеющий на дефекте, хуже отсутствующего, и установить это можно
# только попыткой. Ни ячейки, ни docker для этого не нужно: вердикту
# подсовываются ответы, а пути запуска — подменённые слои.
#
# Последний случай — возврат дефекта: копия скрипта, объявляющая всё
# сходящимся, обязана валить самопроверку. Без него остальные не утверждали
# бы ничего.
selftest() {
    local bad=0 out rc tmp
    tmp="${TMPDIR:-/tmp}/image-state-selftest.$$"
    mkdir -p "$tmp" || return 1
    echo "Самопроверка ops/image-state.sh"

    # Адреса и суммы — из живого замера 27 сентября 2026: тот самый случай
    # боевой ячейки. Версия внутри контейнера у этих двух образов совпадает
    # буква в букву, а суммы разные — на этом всё и держится.
    local nash chuzhoy id_nash id_chuzhoy
    nash="ghcr.io/vladislav15937/parts-platform/minio:RELEASE.2025-09-07T16-13-09Z"
    chuzhoy="quay.io/minio/minio:RELEASE.2025-09-07T16-13-09Z"
    id_nash="sha256:267fc0f047442bcab892ce1717273a5ab7dd9e08d28aacae9ae1b6eddc83e73a"
    id_chuzhoy="sha256:14cea493d9a34af32f524e538b8346cf79f3321eff8e708c1e2960462bd8936e"

    probe() {  # имя, ожидаемый исход (ok|fail), затем шесть полей вердикта, затем слова
        local name="$1" want="$2"; shift 2
        local a="$1" b="$2" c="$3" d="$4" e="$5" f="$6"; shift 6
        set +e
        out=$(verdict_service "$a" "$b" "$c" "$d" "$e" "$f" 2>&1); rc=$?
        set -e
        if [ "$want" = ok ] && [ "$rc" != 0 ]; then
            red "  ✗ ${name}: ожидалось «молчит», а покраснело:"
            printf '%s\n' "$out" | sed 's/^/      /' >&2
            bad=$((bad + 1)); return
        fi
        if [ "$want" = fail ] && [ "$rc" = 0 ]; then
            red "  ✗ ${name}: ожидалось «краснеет», а промолчало:"
            printf '%s\n' "$out" | sed 's/^/      /' >&2
            bad=$((bad + 1)); return
        fi
        local word
        for word in "$@"; do
            case "$out" in
                *"$word"*) ;;
                *) red "  ✗ ${name}: в ответе нет «${word}»"
                   printf '%s\n' "$out" | sed 's/^/      /' >&2
                   bad=$((bad + 1)); return ;;
            esac
        done
        printf '  ✓ %s\n' "$name"
    }

    # 1. ГЛАВНЫЙ СЛУЧАЙ ЗАДАЧИ: настройки правлены, контейнер не пересоздан.
    #    Красное, и названы имя сервиса и ОБА адреса — этого требует пункт 1.
    probe "настройки правлены, контейнер не пересоздан — назван сервис и оба адреса" fail \
        minio "$nash" "$id_nash" cell01-minio-1 "$chuzhoy" "$id_chuzhoy" \
        minio "$nash" "$chuzhoy" cell01-minio-1 "не пересоздан" "up -d --no-deps" \
        "НЕ ПОКАЖЕТ"
    # 2. Пересоздали — обязано молчать. Без этого края сторож, красный всегда,
    #    отключат в первый же день вместе с защитой.
    probe "пересоздан — молчит" ok \
        minio "$nash" "$id_nash" cell01-minio-1 "$nash" "$id_nash"
    # 3. Сверка идёт по СУММЕ, а не по адресу: адрес совпал, байты разные.
    #    Проверка по строке адреса этот случай пропустила бы вовсе.
    probe "адрес тот же, байты другие — красное" fail \
        minio "$nash" "$id_nash" cell01-minio-1 "$nash" "$id_chuzhoy" \
        "ОБРАЗ ДРУГОЙ" "другие байты"
    # 4. И обратное: одна и та же сумма под разными адресами — не беда.
    #    Иначе сторож краснел бы на переименовании зеркала при тех же байтах.
    probe "разные адреса, одна сумма — молчит" ok \
        minio "$nash" "$id_chuzhoy" cell01-minio-1 "$chuzhoy" "$id_chuzhoy"
    # 5. Состояние боевой ячейки после слияния 0180: образ из настроек
    #    не забирали вовсе. Названы pull, пересоздание и запрет уборки образов.
    probe "образа настроек на машине нет — красное, назван pull и запрет уборки" fail \
        minio "$nash" "" cell01-minio-1 "$chuzhoy" "$id_chuzhoy" \
        "НЕТ ВОВСЕ" "pull minio" "docker image prune"
    # 6. Контейнера нет — сверять нечего (погашенная сборка, профиль backup).
    probe "контейнера нет — молчит" ok \
        mc "$nash" "$id_nash" "" "" ""

    # ── обвязка целиком, настоящим запуском скрипта ─────────────────────────
    #
    # Проба, зовущая только вердикт, не проверяет НАЦЕЛИВАНИЕ — то, чем
    # проверка отличается от заглушки (урок разбора PR #214 про
    # ops/deploy-checks.sh). Слои подменяются файлами, docker не нужен.
    local dec="$tmp/declared" run="$tmp/running" fake_docker="$tmp/docker"
    printf 'minio\t%s\npostgres\tsvoy/postgres:16\n' "$nash" > "$dec"
    printf 'minio\tcell01-minio-1\t%s\t%s\n' "$chuzhoy" "$id_chuzhoy" > "$run"
    # Поддельный демон: адрес зеркала разрешается в свою сумму, всё остальное —
    # «нет такого образа», как и настоящий docker.
    {
        printf '#!/bin/sh\n'
        printf 'if [ "$1" = image ] && [ "$3" = "%s" ]; then printf "%s\\n"; exit 0; fi\n' \
            "$nash" "$id_nash"
        printf 'echo "No such image" >&2; exit 1\n'
    } > "$fake_docker"
    chmod +x "$fake_docker"

    probe_run() {  # имя, ожидаемый исход, слова…
        local name="$1" want="$2"; shift 2
        set +e
        out=$(IMAGE_STATE_DECLARED="$dec" IMAGE_STATE_RUNNING="$run" \
              IMAGE_STATE_DOCKER="$fake_docker" bash "$SELF" 2>&1); rc=$?
        set -e
        if { [ "$want" = ok ] && [ "$rc" != 0 ]; } || { [ "$want" = fail ] && [ "$rc" = 0 ]; }; then
            red "  ✗ ${name}: исход не тот (код ${rc})"
            printf '%s\n' "$out" | sed 's/^/      /' >&2
            bad=$((bad + 1)); return
        fi
        local word
        for word in "$@"; do
            case "$out" in
                *"$word"*) ;;
                *) red "  ✗ ${name}: в ответе нет «${word}»"
                   printf '%s\n' "$out" | sed 's/^/      /' >&2
                   bad=$((bad + 1)); return ;;
            esac
        done
        printf '  ✓ %s\n' "$name"
    }

    # 7. Путь запуска: расхождение доезжает до человека и до кода возврата.
    probe_run "обвязка: расхождение названо и код возврата ненулевой" fail \
        minio "$nash" "$chuzhoy" "не пересоздан"
    # 8. Сервис без запущенного контейнера обвязку не красит и назван числом.
    case "$out" in
        *"не запущено: 1"*) printf '  ✓ обвязка: незапущенный сервис назван числом, а не красным\n' ;;
        *) red "  ✗ обвязка: про незапущенный сервис (postgres) ничего не сказано"
           printf '%s\n' "$out" | sed 's/^/      /' >&2
           bad=$((bad + 1)) ;;
    esac

    # 9. Пересоздали — обвязка молчит и выходит нулём.
    printf 'minio\tcell01-minio-1\t%s\t%s\n' "$nash" "$id_nash" > "$run"
    probe_run "обвязка: после пересоздания молчит и код 0" ok "$(short "$id_nash")"

    # 10. Контейнеров нет вовсе (прогон CI, машина до подъёма): код 0, и это
    #     сказано словами. «Нечего сверять» и «сходится» — разные ответы,
    #     и выдать первое за второе значило бы зеленеть, ничего не спросив.
    : > "$run"
    probe_run "обвязка: контейнеров нет — код 0 и сказано «сверять нечего»" ok \
        "сверять нечего"

    # 11. Демон не отвечает про работающий контейнер — это не «сходится»,
    #     но и не «работает не то»: сверка НЕ ВЫПОЛНЕНА, и слова обязаны быть
    #     свои.
    printf 'minio\tcell01-minio-1\t?\t?\n' > "$run"
    probe_run "обвязка: демон не ответил — «сверка не выполнена», а не «сходится»" fail \
        "не спросить образ" "НЕ «образ сходится»" "Сверка НЕ ВЫПОЛНЕНА"

    # 12. Настройки спросить не удалось (нет файла окружения, compose отказал).
    #     Два утверждения, и оба — живые находки этой ветки: прежняя редакция
    #     печатала здесь traceback разбора вместо причины И объявляла
    #     расхождение, которого не измеряла.
    set +e
    out=$(IMAGE_STATE_DECLARED="$tmp/net-takogo-fayla" IMAGE_STATE_RUNNING="$run" \
          IMAGE_STATE_DOCKER="$fake_docker" bash "$SELF" 2>&1); rc=$?
    set -e
    if [ "$rc" != 0 ] \
       && grep -q 'Сверка НЕ ВЫПОЛНЕНА' <<< "$out" \
       && ! grep -q 'Работает не то' <<< "$out" \
       && ! grep -q 'Traceback' <<< "$out"; then
        printf '  ✓ настройки не спросить — «сверка не выполнена», без traceback и без выдуманного расхождения\n'
    else
        red "  ✗ отказ compose обязан называться «сверка не выполнена» — без traceback и без «работает не то» (код ${rc})"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=$((bad + 1))
    fi

    # 13. ВОЗВРАТ ДЕФЕКТА. Копия со снятой проверкой (вердикт всегда «сходится»)
    #     обязана валить самопроверку. Копия кладётся в ops/, а не в /tmp:
    #     скрипт делает cd в корень репозитория от своего каталога, и копия
    #     в /tmp ушла бы в корень файловой системы (урок задачи 0151).
    local fake="$ROOT/ops/.image-state-bez-proverki.$$.sh"
    # Подделка снимает ровно проверку: вердикт всегда «сходится». Прежнее тело
    # остаётся ниже недостижимым — так копия остаётся СИНТАКСИЧЕСКИ ЦЕЛОЙ.
    #
    # Это не педантизм, а находка живого прогона этой ветки. Первая редакция
    # вставляла ещё одну открывающую скобку (`_nedostupno() {`, приём взят
    # из ops/control-plane.sh) — и копия падала с «syntax error: unexpected
    # end of file». Самопроверка при этом была ЗЕЛЁНОЙ: она смотрела только
    # на ненулевой код возврата, а его давал сломанный синтаксис, а не снятая
    # проверка. То есть случай «возврат дефекта» ничего не утверждал — ровно
    # тот обряд, ради исключения которого он и написан (урок задачи 0142:
    # пробу проверяют возвратом дефекта, а не тем, что она зелёная).
    #
    # Поэтому целость копии проверяется отдельно (`bash -n`) ДО запуска:
    # красное от сломанного синтаксиса и красное от снятой проверки — разные
    # утверждения, и путать их нельзя.
    python3 - "$SELF" "$fake" <<'PY'
import sys
src, dst = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()
head = ('verdict_service() {  # сервис, адрес в настройках, сумма настроек, '
        'контейнер, адрес у контейнера, сумма контейнера')
if head not in text:
    sys.exit("подделку негде поставить: заголовок verdict_service не найден")
text = text.replace(
    head,
    'verdict_service() {  # ПОДДЕЛКА: проверка снята\n'
    '    printf "  ✓ %s: образ сходится\\n" "$1"\n'
    '    return 0\n'
    '    # прежнее тело осталось ниже и недостижимо', 1)
open(dst, "w", encoding="utf-8").write(text)
PY
    if [ ! -s "$fake" ]; then
        red "  ✗ подделку негде поставить: копия не собралась"
        rm -f "$fake"
        bad=$((bad + 1))
    elif ! bash -n "$fake" 2>/dev/null; then
        red "  ✗ подделка сломала синтаксис — её красное говорило бы о сломанной копии,"
        red "      а не о снятой проверке. Случай «возврат дефекта» ничего не утверждал бы."
        rm -f "$fake"
        bad=$((bad + 1))
    else
        chmod +x "$fake"
        set +e
        out=$(bash "$fake" --selftest 2>&1); rc=$?
        set -e
        rm -f "$fake"
        if [ "$rc" != 0 ]; then
            printf '  ✓ возврат дефекта: целая копия со снятой проверкой валит самопроверку\n'
        else
            red "  ✗ копия со СНЯТОЙ проверкой прошла самопроверку — значит проверка ничего не утверждает"
            printf '%s\n' "$out" | sed 's/^/      /' >&2
            bad=$((bad + 1))
        fi
    fi

    rm -rf "$tmp"
    if [ "$bad" != 0 ]; then
        red "Самопроверка не прошла: $bad"
        return 1
    fi
    green "Самопроверка пройдена"
    return 0
}

