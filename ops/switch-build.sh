#!/usr/bin/env bash
# Перевод трафика ячейки на другую сборку — без простоя и без перезапуска
# терминатора.
#
#   ./switch-build.sh                 # какая сборка под трафиком сейчас
#   ./switch-build.sh --current       # то же, одним словом: app-blue
#   ./switch-build.sh --db app-green  # база, на которой работает эта сборка
#   ./switch-build.sh --current-db    # база сборки под трафиком — боевая база ячейки
#   ./switch-build.sh green           # перевести трафик на зелёную
#   ./switch-build.sh blue            # и обратно
#   ./switch-build.sh --selftest      # проверка самого скрипта, без docker
#
# Порядок выкладки владельца (12 сентября 2026): миграция, база, «само
# приложение встало штатно» — и только тогда убирать старую сборку. Значит
# новая поднимается РЯДОМ, а трафик переводится отдельным шагом. Этот шаг.
#
# Главное свойство: **сначала спросить готовность, потом переключать.**
# Сборка, которая не стала готовой (отставшая схема, незащищённые журналы,
# не отдающиеся метрики), трафик не получает вовсе — он остаётся на старой,
# а шаг выкладки краснеет. Обратный порядок означал бы, что неудачная
# выкладка кладёт ячейку, то есть ровно то, ради чего всё затеяно.
#
# Почему reload, а не перезапуск терминатора: `caddy reload` перечитывает
# конфигурацию в том же процессе — ответ, начатый до переключения,
# дочитывается целиком (замерено), — а контейнер держит сертификаты:
# перезапуск в худшем случае упрётся в недельный предел Let's Encrypt
# на выпуск, и упрётся в разгар неудачной выкладки. Простаивающее
# keep-alive соединение reload всё же закрывает; что это значит для
# человека и чем замерено — ops/CLAUDE.md.

set -euo pipefail
cd "$(dirname "$0")/.."

COMPOSE="${COMPOSE:-docker compose -f docker-compose.prod.yml}"
ACTIVE_FILE="${ACTIVE_FILE:-ops/active-build.caddy}"

# Сколько ждать готовности новой сборки. Ноль — «спросить один раз»: им
# пользуется проверка порядка (сначала сломать новую, потом переключаться)
# и шаг выкладки, который уже дождался healthy сам.
WAIT="${SWITCH_WAIT:-60}"

red()   { printf '\033[1;31m%s\033[0m\n' "$1" >&2; }
green() { printf '\033[1;32m%s\033[0m\n' "$1"; }
fail()  { red "$1"; exit 1; }

# Имя сборки под трафиком — из того самого файла, который читает терминатор.
# Второго источника нет намеренно: разойдясь, они отправили бы трафик
# в одну сборку, а миграции в другую.
current() {
    [ -f "$ACTIVE_FILE" ] || fail "Нет $ACTIVE_FILE — непонятно, какая сборка под трафиком"
    local name
    name=$(sed -n 's/^[[:space:]]*reverse_proxy[[:space:]]\{1,\}\(app-[a-z]\{1,\}\):8080[[:space:]]*$/\1/p' \
        "$ACTIVE_FILE" | tail -n1)
    [ -n "$name" ] || fail "В $ACTIVE_FILE не нашлось строки вида «reverse_proxy app-<сборка>:8080»"
    printf '%s\n' "$name"
}

# База сборки (задача 0112). У каждой сборки своя: выкладка снимает копию
# с базы работающей и поднимает новую уже на копии. Имя лежит в .env —
# APP_DB_BLUE / APP_DB_GREEN, — и читается ровно так, как его читает compose:
# переменная окружения оболочки старше файла, незаданное — «parts», база,
# с которой ячейка родилась. Разойдись это место с compose, бэкап снимал бы
# одну базу, а люди работали бы в другой, — и молча.
#
# Имя проверяется: оно уходит в SQL выкладки и бэкапа, и строка с кавычкой
# или пробелом в .env не должна становиться частью команды.
ENV_FILE="${ENV_FILE:-.env}"

db_of() {  # app-blue | app-green
    local key value
    case "$1" in
        app-blue)  key=APP_DB_BLUE ;;
        app-green) key=APP_DB_GREEN ;;
        *) fail "Неизвестная сборка: $1. Их две — app-blue и app-green." ;;
    esac
    if [ -n "${!key+задано}" ]; then
        value="${!key}"
    elif [ -f "$ENV_FILE" ]; then
        value=$(sed -n "s/^${key}=//p" "$ENV_FILE" | tail -n1)
    else
        value=""
    fi
    value="${value:-parts}"
    case "$value" in
        [a-z]*) ;;
        *) fail "Имя базы «${value}» в ${key} не годится: латиница в нижнем регистре, цифры и _" ;;
    esac
    case "$value" in
        *[!a-z0-9_]*) fail "Имя базы «${value}» в ${key} не годится: латиница в нижнем регистре, цифры и _" ;;
    esac
    [ "${#value}" -le 63 ] || fail "Имя базы «${value}» длиннее 63 символов — Postgres его обрежет"
    printf '%s\n' "$value"
}

usage() {
    cat >&2 <<'EOF'
Использование: ops/switch-build.sh [blue|green|--current|--selftest] [--force]

  blue | green   перевести трафик на эту сборку (с проверкой готовности)
  --current      напечатать имя сборки под трафиком (app-blue / app-green)
  --db СБОРКА    напечатать имя базы этой сборки (из .env, умолчание parts)
  --current-db   напечатать имя базы сборки под трафиком
  --force        перевести БЕЗ проверки готовности — только для ВОЗВРАТА
  без аргумента  то же, словами
EOF
    exit 2
}

# Переключить, не спросив готовности. Нужно ровно в одном месте — возврат
# трафика на сборку, которая обслуживала людей минуту назад, после неудачной
# выкладки (ops/deploy.sh). Там проверка готовности отвечает «нет» законно:
# при выкладке вниз схема уже опущена, и старшая сборка её не признаёт, —
# а оставить людей на сборке, только что не прошедшей самопроверки, хуже.
# Во всех остальных случаях это запрещённый путь: он и есть «перевести людей
# на приложение, которое не поднялось».
FORCE="${SWITCH_FORCE:-}"

# --- проверка самого скрипта ------------------------------------------------
#
# Без docker и без ячейки: проверяется разбор файла активной сборки
# и запись в него. Проверка, которая не краснеет на дефекте, хуже
# отсутствующей, поэтому каждый случай здесь — про свою ошибку.
selftest() {
    local dir ok=0
    dir=$(mktemp -d)
    trap 'rm -rf "$dir"' RETURN

    check() {  # имя, ожидание, факт
        if [ "$2" = "$3" ]; then
            printf '  ✓ %s\n' "$1"
        else
            red "  ✗ $1: ожидалось «$2», получено «$3»"
            ok=1
        fi
    }

    echo "Самопроверка ops/switch-build.sh"

    # 1. Обычный файл читается, и комментарии не сбивают разбор.
    printf '# комментарий\nreverse_proxy app-green:8080\n' > "$dir/a.caddy"
    check "имя активной сборки читается" "app-green" \
        "$(ACTIVE_FILE=$dir/a.caddy bash "$0" --current)"

    # 2. Файл без строки проксирования — это не «сборка blue по умолчанию»,
    #    а отказ: подставленное умолчание перевело бы трафик молча и не туда.
    printf '# ничего\n' > "$dir/b.caddy"
    if ACTIVE_FILE=$dir/b.caddy bash "$0" --current >/dev/null 2>&1; then
        red "  ✗ файл без reverse_proxy обязан быть отказом"; ok=1
    else
        printf '  ✓ файл без reverse_proxy — отказ\n'
    fi

    # 3. Отсутствующий файл — тоже отказ, а не пустая строка.
    if ACTIVE_FILE=$dir/нет.caddy bash "$0" --current >/dev/null 2>&1; then
        red "  ✗ пропавший файл обязан быть отказом"; ok=1
    else
        printf '  ✓ пропавший файл — отказ\n'
    fi

    # 4. Чужое имя сборки не принимается: опечатка в аргументе не должна
    #    превращаться в имя хоста, которого нет, — терминатор ответил бы
    #    502 всем, и это выглядело бы как упавшее приложение.
    if bash "$0" blau >/dev/null 2>&1; then
        red "  ✗ неизвестное имя сборки обязано быть отказом"; ok=1
    else
        printf '  ✓ неизвестное имя сборки — отказ\n'
    fi

    # 4б. Второй аргумент бывает только `--force`. Опечатка в нём не должна
    #     молча проглатываться: «переключить без проверки готовности» — это
    #     тот самый путь, которым неготовая сборка получает людей.
    if bash "$0" blue --форсаж >/dev/null 2>&1; then
        red "  ✗ непонятный второй аргумент обязан быть отказом"; ok=1
    else
        printf '  ✓ непонятный второй аргумент — отказ\n'
    fi

    # 5. Запись идёт НА МЕСТЕ, а не переименованием: у bind-mount'а одного
    #    файла подменённый inode контейнер больше не видит, и reload
    #    перечитал бы старое содержимое при верном файле на хосте.
    printf 'reverse_proxy app-blue:8080\n' > "$dir/c.caddy"
    local before after
    before=$(ls -i "$dir/c.caddy" | awk '{print $1}')
    ACTIVE_FILE=$dir/c.caddy write_active app-green
    after=$(ls -i "$dir/c.caddy" | awk '{print $1}')
    check "запись сохраняет inode" "$before" "$after"
    check "записанное читается обратно" "app-green" \
        "$(ACTIVE_FILE=$dir/c.caddy bash "$0" --current)"

    # 6. Запись обязана быть целым файлом конфигурации Caddy, а не только
    #    строкой: пустой импорт — это сайт без обработчика, то есть 200
    #    с пустым телом вместо приложения.
    grep -q '^reverse_proxy app-green:8080$' "$dir/c.caddy" \
        && printf '  ✓ записана строка проксирования\n' \
        || { red "  ✗ в файле нет строки «reverse_proxy app-green:8080»"; ok=1; }

    # 7. База сборки читается так же, как её читает compose: из .env,
    #    с умолчанием «parts», и переменная оболочки старше файла. Разойдись
    #    это с compose — бэкап и выкладка работали бы не с той базой,
    #    в которой люди.
    printf 'APP_DB_GREEN=parts_green_0123456789ab\n#APP_DB_BLUE=zakommentirovano\n' > "$dir/env"
    check "база сборки берётся из .env" "parts_green_0123456789ab" \
        "$(env -u APP_DB_GREEN ENV_FILE=$dir/env bash "$0" --db app-green)"
    check "незаданная база — parts, закомментированная не считается" "parts" \
        "$(env -u APP_DB_BLUE ENV_FILE=$dir/env bash "$0" --db app-blue)"
    check "переменная оболочки старше .env, как у compose" "iz_obolochki" \
        "$(APP_DB_GREEN=iz_obolochki ENV_FILE=$dir/env bash "$0" --db app-green)"
    printf 'reverse_proxy app-green:8080\n' > "$dir/d.caddy"
    check "база под трафиком — база активной сборки" "parts_green_0123456789ab" \
        "$(env -u APP_DB_GREEN ACTIVE_FILE=$dir/d.caddy ENV_FILE=$dir/env bash "$0" --current-db)"

    # 8. Имя, негодное для SQL, — отказ, а не подстановка в команду.
    printf 'APP_DB_BLUE=parts;DROP\n' > "$dir/bad.env"
    if env -u APP_DB_BLUE ENV_FILE=$dir/bad.env bash "$0" --db app-blue >/dev/null 2>&1; then
        red "  ✗ имя базы с «;» обязано быть отказом"; ok=1
    else
        printf '  ✓ имя базы с «;» — отказ\n'
    fi

    # 9. «Делать нечего» утверждает РОВНО ИЗМЕРЕННОЕ (задача 0239). Прежние
    #    слова «Трафик уже на app-green — делать нечего» звучали как ответ
    #    про живой трафик, а прочитан тут один факт: строка в файле. Разойдись
    #    файл с загруженной конфигурацией (правили руками, не прошёл reload) —
    #    и шаг говорил бы «делать нечего» при трафике на ДРУГОЙ сборке,
    #    а выкладка после этого гасит старую.
    #    Обратный край в том же случае: шаг обязан по-прежнему выходить нулём,
    #    иначе законный повтор выкладки стал бы отказом.
    printf 'reverse_proxy app-green:8080\n' > "$dir/e.caddy"
    local same_out
    if same_out=$(ACTIVE_FILE=$dir/e.caddy bash "$0" green 2>&1); then
        case "$same_out" in
            *"записано"*"не спрашивали"*)
                printf '  ✓ «делать нечего» сказано про ФАЙЛ, а не про живой трафик\n' ;;
            *) red "  ✗ «делать нечего» утверждает больше измеренного: ${same_out}"; ok=1 ;;
        esac
    else
        red "  ✗ трафик уже на цели — обязан быть выход нулём, а вышло: ${same_out}"; ok=1
    fi

    # 10. ВОЗВРАТ ДЕФЕКТА: вернув прежние слова, случай 9 обязан покраснеть —
    #     иначе он не утверждает ничего. Копия кладётся в ops/, а не в /tmp:
    #     скрипт уходит в корень репозитория от своего каталога (урок 0151);
    #     целость проверяется ДО запуска (урок 0198); рекурсию обрывает
    #     переменная (урок 0195).
    if [ -n "${SWITCH_SELFTEST_FAKE:-}" ]; then
        printf '  ✓ подделки своей копии не заводим — рекурсии нет\n'
    else
        local fake="ops/switch-build-fake-0239.sh"
        sed 's|^    green "В \$ACTIVE_FILE записано.*|    green "Трафик уже на $TARGET — делать нечего"|' \
            "$0" > "$fake"
        if ! grep -q 'Трафик уже на \$TARGET — делать нечего' "$fake"; then
            red "  ✗ подделку негде поставить — случай 9 ничего не утверждает"; ok=1
        elif ! bash -n "$fake" 2>/dev/null; then
            red "  ✗ подделка сломала синтаксис — её красное скажет не о том"; ok=1
        elif SWITCH_SELFTEST_FAKE=yes bash "$fake" --selftest >/dev/null 2>&1; then
            red "  ✗ ВОЗВРАТ ДЕФЕКТА: прежние слова про живой трафик самопроверку НЕ валят"; ok=1
        else
            printf '  ✓ возврат дефекта: прежние слова валят самопроверку\n'
        fi
        rm -f "$fake"
    fi

    # 11. ЧТО ТЕРМИНАТОР ЗАГРУЗИЛ — исходов три, и проверяются они ПРОГОНОМ
    #     ВСЕГО ШАГА (задача 0148), а не вызовом вердикта в одиночку: отказ
    #     запроса надо ещё донести до вердикта, а прежняя редакция глушила его
    #     на месте вызова (`2>/dev/null || true`). Проба, зовущая функцию,
    #     не проверяет того, что делает запуск (урок 0144).
    #
    #     Ни docker, ни ячейки не нужно: `$COMPOSE` подменяется заглушкой, она
    #     отвечает за готовность, validate, reload и admin API; заморозку базы
    #     шаг пропускает тем же признаком, которым её пропускает выкладка.
    local stub="$dir/compose"
    cat > "$stub" <<'STUB'
#!/bin/sh
# Заглушка `docker compose` для случая 11: отвечает по адресу запроса.
for a in "$@"; do
    case "$a" in
        */actuator/readiness) printf '{"ready":true}\n'; exit 0 ;;
        http://localhost:2019/config/)
            case "${STUB_API:-ok}" in
                ok)    printf '{"upstreams":[{"dial":"app-green:8080"}]}\n'; exit 0 ;;
                other) printf '{"upstreams":[{"dial":"app-blue:8080"}]}\n'; exit 0 ;;
                empty) exit 0 ;;
                down)  printf 'curl: (7) Failed to connect to localhost port 2019\n' >&2; exit 7 ;;
            esac ;;
    esac
done
exit 0
STUB
    chmod +x "$stub"

    switch_run() {  # STUB_API → вывод шага плюс строка «код=N»
        local out rc=0
        printf 'reverse_proxy app-blue:8080\n' > "$dir/sw.caddy"
        set +e
        out=$(STUB_API="$1" COMPOSE="$stub" ACTIVE_FILE="$dir/sw.caddy" \
              SWITCH_FROZEN_OK=yes SWITCH_WAIT=0 bash "$0" green 2>&1)
        rc=$?
        set -e
        printf '%s\nкод=%s\n' "$out" "$rc"
    }

    local run_out
    run_out=$(switch_run ok)
    case "$run_out" in
        *"перечитал конфигурацию"*"код=0"*)
            printf '  ✓ цель есть в загруженной конфигурации — переключение названо удавшимся\n' ;;
        *) red "  ✗ исправное переключение не названо удавшимся: ${run_out}"; ok=1 ;;
    esac

    #     Главный случай: admin API не ответил. Прежняя редакция печатала
    #     «в загруженной конфигурации нет app-green:8080» — то есть называла
    #     расхождение, которого не измеряла, и звала откатывать выкладку,
    #     трафик которой уже переключён.
    run_out=$(switch_run down)
    case "$run_out" in
        *"СПРОСИТЬ её не вышло"*"кодом 7"*)
            printf '  ✓ отказ запроса назван отказом запроса, и назван его код\n' ;;
        *) red "  ✗ отказ admin API не назван отказом: ${run_out}"; ok=1 ;;
    esac
    case "$run_out" in
        *"конфигурации нет app-green:8080"*)
            red "  ✗ НЕИЗМЕРЕННОЕ: отказ запроса назван отсутствием цели в конфигурации"; ok=1 ;;
    esac
    case "$run_out" in
        *"reload прошёл"*) ;;
        *) red "  ✗ не сказано, что reload прошёл, — человек пойдёт откатывать удавшееся"; ok=1 ;;
    esac
    case "$run_out" in
        *"код=0"*) red "  ✗ неотвеченный вопрос дал нулевой код возврата"; ok=1 ;;
    esac

    run_out=$(switch_run empty)
    case "$run_out" in
        *"ПУСТЫМ телом"*) printf '  ✓ пустой ответ назван пустым ответом, а не расхождением\n' ;;
        *) red "  ✗ пустой ответ admin API назван не тем: ${run_out}"; ok=1 ;;
    esac

    #     Обратный край: НАСТОЯЩЕЕ расхождение обязано по-прежнему краснеть
    #     прежними словами. Без него правка прошла бы и в виде «всегда зелено».
    run_out=$(switch_run other)
    case "$run_out" in
        *"ЗАГРУЖЕННОЙ конфигурации нет app-green:8080"*)
            printf '  ✓ непустая конфигурация без цели — по-прежнему расхождение\n' ;;
        *) red "  ✗ настоящее расхождение больше не называется: ${run_out}"; ok=1 ;;
    esac

    # 12. ВОЗВРАТ ДЕФЕКТА к случаю 11: вернув прежнее поведение (отказ запроса
    #     и пустой ответ читаются как «цели в конфигурации нет»), самопроверка
    #     обязана покраснеть. Копия лежит в `.scratch/` — она игнорируется git
    #     и при этом на той же глубине, что `ops/`, то есть корень репозитория
    #     разрешается туда же (уроки 0151 и 0248).
    if [ -n "${SWITCH_SELFTEST_FAKE:-}" ]; then
        printf '  ✓ подделки своей копии не заводим — рекурсии нет\n'
    else
        mkdir -p .scratch
        local fake2=".scratch/switch-build-loaded-fake-0148.sh"
        sed 's|^    local asked=yes$|    local asked=yes; rc=0; body="net-tseli"|' \
            "$0" > "$fake2"
        if ! grep -q 'body="net-tseli"' "$fake2"; then
            red "  ✗ подделку негде поставить — случай 11 ничего не утверждает"; ok=1
        elif ! bash -n "$fake2" 2>/dev/null; then
            red "  ✗ подделка сломала синтаксис — её красное скажет не о том"; ok=1
        elif SWITCH_SELFTEST_FAKE=yes bash "$fake2" --selftest >/dev/null 2>&1; then
            red "  ✗ ВОЗВРАТ ДЕФЕКТА: прежние слова про загруженную конфигурацию самопроверку НЕ валят"; ok=1
        else
            printf '  ✓ возврат дефекта: прежнее «цели в конфигурации нет» валит самопроверку\n'
        fi
        rm -f "$fake2"
    fi

    [ $ok = 0 ] || fail "Самопроверка не прошла"
    green "Самопроверка пройдена"
}

# Пишем на месте (`>`), а не через временный файл с переименованием:
# см. случай 5 самопроверки.
write_active() {
    local target="$1"
    {
        echo "# Активная сборка ячейки. Переписывает ops/switch-build.sh —"
        echo "# руками не править: трафик переводится только после проверки"
        echo "# готовности, иначе люди уедут на сборку, которая не поднялась."
        echo "reverse_proxy ${target}:8080"
    } > "$ACTIVE_FILE"
}

# --- разбор аргументов ------------------------------------------------------
case "${1:-}" in
    --current) current; exit 0 ;;
    --current-db) db_of "$(current)"; exit 0 ;;
    --db) db_of "${2:?назовите сборку: app-blue или app-green}"; exit 0 ;;
    --selftest) selftest; exit 0 ;;
    -h|--help) usage ;;
    "")
        printf 'Под трафиком: %s\n' "$(current)"
        exit 0 ;;
    blue|green) TARGET="app-$1" ;;
    app-blue|app-green) TARGET="$1" ;;
    *) red "Неизвестная сборка: ${1}. Их две — blue и green."; usage ;;
esac

case "${2:-}" in
    --force) FORCE=yes ;;
    "") ;;
    *) red "Непонятный аргумент: ${2}"; usage ;;
esac

CURRENT=$(current)

if [ "$TARGET" = "$CURRENT" ]; then
    # УТВЕРЖДЕНИЕ СУЖЕНО ДО ИЗМЕРЕННОГО (задача 0239). Прежнее «Трафик уже
    # на app-green — делать нечего» звучало как ответ про живой трафик,
    # а измерен тут ровно один факт: строка в ФАЙЛЕ ops/active-build.caddy.
    # Разойдись файл с загруженной конфигурацией (правили руками, не прошёл
    # reload) — и шаг говорил бы «делать нечего» при трафике на ДРУГОЙ сборке,
    # а выкладка после этого гасит старую.
    #
    # Загруженную конфигурацию здесь НЕ спрашиваем, и довод не в цене.
    # Второго источника ИМЕНИ активной сборки нет намеренно (см. current()
    # выше): его читают и накат схем, и выкладка, и разъехавшись, они
    # отправили бы трафик в одну сборку, а миграции в другую. Сверка «файл
    # против загруженного» второго источника не заводит и потому доводу
    # не противоречит — но запрос к admin API в этом файле уже есть (ниже,
    # «Что терминатор загрузил»), и его слова разбирает tasks/0148. Два места,
    # спрашивающих одно и то же, разъезжаются по построению (tasks/0177),
    # поэтому сверка оставлена тому, кто правит тот запрос, а здесь —
    # честные слова о том, что прочитано.
    green "В $ACTIVE_FILE записано, что трафик на $TARGET — делать нечего. У терминатора не спрашивали."
    exit 0
fi

# Что терминатор ЗАГРУЗИЛ — четыре исхода, а не два (задача 0148).
#
# Прежняя редакция глушила запрос целиком (`2>/dev/null || true`) и ПУСТОЙ
# ответ объявляла расхождением: «в загруженной конфигурации нет $TARGET:8080 —
# разбирайтесь руками». Пустым он становится не только от расхождения:
# admin API выключён в Caddyfile, curl'а в контейнере нет, запрос не успел
# за 10 секунд, демон не ответил — всё это даёт ту же пустоту и тот же
# красный вердикт, называющий причину, которой никто не проверял.
#
# Цена этой подмены выше, чем у соседей по классу, и вот почему: строку читают
# ПОСЛЕ `caddy reload`, то есть когда трафик, скорее всего, УЖЕ на цели,
# и по ней человек решает, откатывать ли. «В конфигурации нет цели» читается
# как «переключение не случилось» и зовёт откатывать удавшуюся выкладку.
#
# Поэтому: отказ запроса и пустой ответ — это «спросить не вышло» (и сказано,
# что reload при этом прошёл), а расхождением называется только непустая
# конфигурация без цели.
verdict_loaded() {   # код запроса, тело, первые строки отказа, цель
    local rc="$1" body="$2" err="$3" target="$4"
    # Признак «ответ получен и он непуст» стоит ОДНОЙ строкой намеренно: возврат
    # дефекта (случай 12 самопроверки) ставится ровно сюда, одной заменой, —
    # подделка, переписывающая два условия, легко ломает синтаксис, и тогда
    # её красное говорит о сломанной копии, а не о снятой проверке (урок 0198).
    local asked=yes
    { [ "$rc" = 0 ] && [ -n "$body" ]; } || asked=no
    if [ "$asked" = no ]; then
        if [ "$rc" != 0 ]; then
            red "Терминатор перечитал конфигурацию, а СПРОСИТЬ её не вышло: запрос"
            red "к admin API вышел кодом ${rc}${err:+ — }${err}"
        else
            red "Терминатор перечитал конфигурацию, а admin API ответил ПУСТЫМ телом —"
            red "сверять не с чем: цель в нём не искали."
        fi
        red "Это НЕ значит, что трафик не переключён: reload прошёл, в $ACTIVE_FILE стоит $target."
        red "Спросите снаружи, по домену ячейки: admin API смотрит только в петлю."
        return 1
    fi
    case "$body" in
        # «Перечитан», а не «соединения не тронуты»: замерено — ответ, начатый
        # до переключения, дочитывается целиком, а простаивающие keep-alive
        # соединения терминатор закрывает (браузер переоткроет сам).
        # Подробности и числа — ops/CLAUDE.md.
        *"$target:8080"*)
            green "Трафик на $target — терминатор перечитал конфигурацию, не перезапускаясь"
            return 0 ;;
    esac
    red "Терминатор перечитан, и в ЗАГРУЖЕННОЙ конфигурации нет $target:8080 — разбирайтесь руками"
    return 1
}

# --- готовность цели --------------------------------------------------------
#
# Спрашиваем из контейнера терминатора: у него есть curl, и он в той же сети,
# а порт сборки наружу не опубликован. Тот же адрес, что у healthcheck'а,
# и тот же ответ — «база отвечает, общая схема принята, схемы арендаторов
# не позади, журналы защищены, метрики отдаются».
#
# Без `-f` намеренно: на 503 он проглотил бы тело, а тело — это и есть
# список того, что не готово. Человеку, разбирающему неудачную выкладку,
# нужен именно он, а не «curl: (22) error 503».
probe() { $COMPOSE exec -T caddy curl -sS -m 10 "http://$TARGET:8080/actuator/readiness" 2>&1; }

# --- не на замороженную базу (задача 0112) ------------------------------------
#
# После выкладки прежняя база остаётся рядом замороженной: это слепок
# на момент переключения, а всё записанное людьми после него живёт только
# в базе новой сборки. Готовность такой сборки зелёная — только-чтение её
# не роняет, — поэтому «откат — обратное переключение» тихо перевёл бы людей
# на вчерашний склад: чтение показывает прошлое, запись отвечает «идёт
# обновление», а сегодняшняя работа пропадает из виду. Откат приложения
# после выкладки — это ops/deploy.sh --tag <прежний SHA> --migrate-with none.
#
# Проходят сюда двое, и оба называют себя: выкладка на своём прямом
# переключении (копия заморожена намеренно, до конца самопроверок —
# SWITCH_FROZEN_OK=yes) и возврат при неудаче (--force, прежняя база ещё
# заморожена и откроется следующим шагом).
if [ -z "$FORCE" ] && [ "${SWITCH_FROZEN_OK:-}" != yes ]; then
    TARGET_DB=$(db_of "$TARGET")
    PG_USER="${DB_USER:-$(sed -n 's/^DB_USER=//p' "$ENV_FILE" 2>/dev/null | tail -n1)}"
    FROZEN=$($COMPOSE exec -T postgres psql -U "${PG_USER:?не узнать DB_USER — владельца базы}" -d postgres -tAc \
        "SELECT count(*) FROM pg_db_role_setting s JOIN pg_database d ON d.oid = s.setdatabase,
                unnest(s.setconfig) c
          WHERE d.datname = '$TARGET_DB' AND s.setrole = 0
            AND c = 'default_transaction_read_only=on'" 2>&1) \
        || fail "Не спросить, заморожена ли база $TARGET_DB: $FROZEN — трафик ОСТАЁТСЯ на $CURRENT"
    if [ "$FROZEN" != 0 ]; then
        red "База сборки $TARGET ($TARGET_DB) заморожена: это прежняя база, слепок на момент"
        red "выкладки. Записанное людьми после неё живёт в базе $CURRENT ($(db_of "$CURRENT"))."
        red "Переключение туда показало бы людям вчерашний склад — трафик ОСТАЁТСЯ на $CURRENT."
        fail "Откат приложения после выкладки: ops/deploy.sh --tag <прежний SHA> --migrate-with none"
    fi
fi

if [ -n "$FORCE" ]; then
    # Говорится вслух и в лог выкладки: принуждение — это ровно тот путь,
    # которым сюда попадает неготовая сборка, и он обязан быть виден тому,
    # кто потом разбирается, почему люди уехали не туда.
    red "ПРИНУДИТЕЛЬНО: готовность $TARGET не спрашиваем (--force)."
    red "Годится только для ВОЗВРАТА на сборку, которая только что работала."
else

echo "==> Готова ли $TARGET"
DEADLINE=$(( $(date +%s) + WAIT ))
while :; do
    ANSWER=$(probe) && case "$ANSWER" in *'"ready":true'*) break ;; esac
    [ "$(date +%s)" -lt "$DEADLINE" ] || break
    sleep 3
done

case "${ANSWER:-}" in
    *'"ready":true'*) ;;
    *)
        red "Сборка $TARGET не готова — трафик ОСТАЁТСЯ на $CURRENT."
        red "Ответ готовности: ${ANSWER:-нет ответа}"
        fail "Переключение отменено. Разберитесь с причиной и повторите; ячейка всё это время работает."
        ;;
esac
green "  $TARGET готова"

fi

# --- переключение -----------------------------------------------------------
BACKUP=$(cat "$ACTIVE_FILE")
restore() { printf '%s\n' "$BACKUP" > "$ACTIVE_FILE"; }

echo "==> Переводим трафик $CURRENT → $TARGET"
write_active "$TARGET"

# Сначала разбор конфигурации, потом перечитывание. Caddy на битой
# конфигурации оставляет работать прежнюю — но сказать об этом должен
# скрипт, а не лог контейнера, иначе выкладка зеленеет, ничего не переключив.
if ! $COMPOSE exec -T caddy caddy validate --config /etc/caddy/Caddyfile >/dev/null 2>&1; then
    restore
    fail "Конфигурация терминатора с $TARGET не разбирается — трафик остался на $CURRENT"
fi

# Не прошло — значит терминатор работает на прежней конфигурации (reload
# у Caddy либо загружает целиком, либо не трогает загруженное), и вернуть
# надо только файл.
if ! $COMPOSE exec -T caddy caddy reload --config /etc/caddy/Caddyfile; then
    restore
    fail "caddy reload не прошёл — трафик остался на $CURRENT"
fi

# Спрашиваем РАБОТАЮЩУЮ конфигурацию, а не файл: файл мы только что написали
# сами, и сверка с ним доказывала бы лишь то, что запись удалась.
#
# Отказ запроса НЕ глушится (задача 0148): его код и его stderr — это и есть
# разница между «цели в конфигурации нет» и «спросить не вышло».
echo "==> Что терминатор загрузил"
LOADED_ERR_FILE="$(mktemp)"
LOADED=""
LOADED_RC=0
LOADED=$($COMPOSE exec -T caddy curl -fsS -m 10 http://localhost:2019/config/ \
    2>"$LOADED_ERR_FILE") || LOADED_RC=$?
# Первые две строки отказа, склеенные в одну: `cut -c` на не-ASCII режет байты
# на Linux и символы на macOS (урок 0085), а сообщения docker и curl бывают
# и русскими.
LOADED_ERR=$(sed -n '1,2p' "$LOADED_ERR_FILE" | tr '\n' ' ')
rm -f "$LOADED_ERR_FILE"
verdict_loaded "$LOADED_RC" "$LOADED" "$LOADED_ERR" "$TARGET" || exit 1

printf 'Старая сборка %s ещё работает. Убедитесь, что всё в порядке, и гасите её:\n' "$CURRENT"
printf '    docker compose -f docker-compose.prod.yml stop %s\n' "$CURRENT"
