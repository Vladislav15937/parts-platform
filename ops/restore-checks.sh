#!/usr/bin/env bash
# Проверки по СЛЕДУ для восстановления (задача 0238): ops/restore-cell.sh,
# ops/restore-tenant.sh и — список расширений — ops/verify-backup.sh.
#
# Этот файл только сорсят — у него нет своего запуска (поэтому в индексе
# 100644, как у ops/backup-checks.sh и ops/backup-aggregates.sh):
#
#   . ops/restore-checks.sh
#
# ЗАЧЕМ. Пути возврата доказывали результат кодом возврата и числом, которое
# ни с чем не сравнивалось: «pg_trgm, ltree, pgcrypto» печаталось жёстко
# вписанным текстом после psql, вывод которого уходил в /dev/null, а «Снимков
# возвращено: N» считалось по каталогу-источнику на хосте — то есть называло,
# что СОБИРАЛИСЬ отправить. Правило то же, что у 0157, 0235 и 0237: у операции
# спрашивают не «вышла ли без ошибки», а «что от неё осталось» — и спрашивают
# у той стороны, куда она писала.
#
# Здесь только вопросы, без побочных действий: функция возвращает 0 или 1 и
# кладёт причину в одну переменную, а решает зовущий. Так их можно прогнать
# самопроверкой на подложенных ответах без docker.

# --- Расширения: спросить у базы, а не напечатать список ---------------------
#
# Список расширений — один на восстановление ячейки, восстановление одного
# клиента и еженедельную проверку бэкапа. Почему их ставит восстанавливающий,
# а не дамп и не приложение, — в самом файле.
EXT_SQL="ops/restore-extensions.sql"

# Запрос к pg_extension в проекте ОДИН (задача 0238): им проверка бэкапа
# сверяет список с живой базой, а восстановление — что расширения встали.
# Две копии запроса разошлись бы молча (болезнь задачи 0177).
EXT_QUERY="SELECT extname FROM pg_extension ORDER BY extname"

# Расширения, которые ставит восстанавливающий.
ours_extensions() {
    grep -oE 'CREATE EXTENSION IF NOT EXISTS [a-z_0-9]+' "$EXT_SQL" \
        | awk '{print $NF}' | sort
}

# Встали ли в базе все расширения из списка. Нулевой код psql — это «команды
# выполнились», а не «расширения есть»: ответ берётся у самой базы, и каждое
# недостающее называется по имени. Именно на них 0157 падал «на первой же
# таблице», уводя разбор на полчаса, — а скрипт печатал три имени, которых
# не спрашивал.
EXT_WHY=""
EXT_FOUND=""
extensions_present_check() {   # $1 — ответ базы (имя на строку), $2 — наш список
    local installed ours="$2" missing
    EXT_WHY=""
    EXT_FOUND=""
    installed="$(printf '%s\n' "$1" | sed 's/[[:space:]]//g' | grep -v '^$' | sort || true)"
    if [ -z "$installed" ]; then
        EXT_WHY="база не ответила, какие расширения в ней стоят, — встали ли они, не установлено"
        return 1
    fi
    missing="$(comm -13 <(printf '%s\n' "$installed") \
        <(printf '%s\n' "$ours" | sed 's/[[:space:]]//g' | grep -v '^$' | sort) || true)"
    if [ -n "$missing" ]; then
        EXT_WHY="в базе нет расширений: $(printf '%s' "$missing" | tr '\n' ' ')— psql отработал, а их нет"
        return 1
    fi
    EXT_FOUND="$(comm -12 <(printf '%s\n' "$installed") \
        <(printf '%s\n' "$ours" | sed 's/[[:space:]]//g' | grep -v '^$' | sort) | tr '\n' ' ')"
    return 0
}

# --- Снимки: считать на той стороне, куда их вернули -------------------------
#
# Сколько файлов лежало в копии (отправляли) и сколько объектов у арендатора
# стало в хранилище ПОСЛЕ зеркала. Хранилище не может оказаться меньше копии:
# зеркало идёт без --remove и только пополняет, а снимки, появившиеся после
# снятия набора, лишь добавляют объектов. Ноль при пустой копии — законный
# клиент без снимков; ноль при непустой — бакет не тот, нет прав или хранилище
# не поднялось, и прежний счёт по хосту печатал на этом месте зелёное число.
PHOTOS_BACK_WHY=""
photos_back_check() {   # $1 — файлов в копии, $2 — объектов арендатора в хранилище
    local sent="$1" got="$2"
    PHOTOS_BACK_WHY=""
    case "$got" in
        ''|*[!0-9]*)
            PHOTOS_BACK_WHY="хранилище не ответило, сколько в нём снимков клиента (получено «${got}») — вернулись ли они, не установлено"
            return 1 ;;
    esac
    case "$sent" in
        ''|*[!0-9]*)
            PHOTOS_BACK_WHY="число файлов в копии не прочитано (получено «${sent}»)"
            return 1 ;;
    esac
    if [ "$got" -lt "$sent" ]; then
        PHOTOS_BACK_WHY="в хранилище у клиента $got объектов, а из копии отправляли $sent — вернулись не все"
        return 1
    fi
    return 0
}

# --- Заглушка docker для самопроверок восстановления -------------------------
#
# Самопроверка гоняет ВЕСЬ путь скрипта, а не одни функции (урок 0144: проба,
# зовущая функцию, не проверяет того, что делает запуск), — значит ей нужен
# docker, отвечающий как ячейка. Заглушка кладётся первой в PATH и читает
# сценарий из каталога $STUB:
#
#   answers      — «SQL<TAB>ответ», сравнение SQL целиком; ответ `!ERR` —
#                  отказ psql (таблицы нет), `\n` в ответе — перевод строки;
#                  незнакомый SQL (DROP SCHEMA, CREATE DATABASE) — пусто и ноль;
#   ls           — что отвечает `mc ls --recursive` (объект на строку);
#   ls_fail      — хранилище недоступно: `mc ls` отказывает;
#   mirror_fail  — `mc mirror` отказывает;
#   calls        — сюда пишется каждый вызов: по нему видно, ЧТО скрипт сделал.
restore_stub_docker() {   # $1 — каталог, куда положить исполняемый docker
    mkdir -p "$1"
    cat > "$1/docker" <<'STUB'
#!/usr/bin/env bash
all="$*"
last="${*: -1}"
printf '%s\n' "$all" >> "$STUB/calls"
case "$all" in
    *pg_restore*)
        cat > /dev/null; exit 0 ;;
    *"mc mirror"*)
        [ ! -e "$STUB/mirror_fail" ] || { echo 'mc: <ERROR> Unable to connect to cell' >&2; exit 1; }
        exit 0 ;;
    *" mc ls "*)
        [ ! -e "$STUB/ls_fail" ] || { echo 'mc: <ERROR> Access Denied.' >&2; exit 1; }
        cat "$STUB/ls" 2>/dev/null; exit 0 ;;
    *"-f /dev/stdin"*)
        cat > /dev/null; exit 0 ;;
    *psql*)
        ans="$(Q="$last" awk -F'\t' 'BEGIN { q = ENVIRON["Q"] } $1 == q { print $2; exit }' "$STUB/answers")"
        case "$ans" in
            '!ERR') printf 'ERROR:  relation does not exist\n' >&2; exit 1 ;;
            '') exit 0 ;;
        esac
        printf '%b\n' "$ans"; exit 0 ;;
esac
exit 0
STUB
    chmod +x "$1/docker"
}
