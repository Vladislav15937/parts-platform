-- Расширения Postgres, без которых схему клиента не развернуть.
--
-- Ставит их ТОТ, КТО ВОССТАНАВЛИВАЕТ, и вот почему (задача 0157, замерено):
--
--   1. В дампах их нет и быть не может. `pg_dump --schema=…` выгружает схемы,
--      а расширения принадлежат базе: в наборе их нет ни в `shared.dump`,
--      ни в дампе арендатора.
--
--   2. Приложение их уже не поставит. Расширения заводит changeset
--      `catalog/001-extensions`, а он отмечается в `public.databasechangelog`,
--      который лежит ВНУТРИ `shared.dump`. Развернув набор в голую базу,
--      получаем отметку «catalog-001-extensions применён» при НУЛЕ расширений:
--      Liquibase пропустит его, и никто их не создаст никогда. Проверено
--      прогоном — отметка на месте, расширений ноль.
--
-- Что ломается без них (оба отказа воспроизведены на живой базе):
--   • `function public.gen_random_bytes(integer) does not exist` — на ПЕРВОЙ
--     же таблице арендатора: `public_code` выдаётся умолчанием колонки
--     через pgcrypto;
--   • `operator class "public.gin_trgm_ops" does not exist` — на индексах
--     поиска (pg_trgm), и это уже в общих схемах: без ltree и pg_trgm
--     `catalog.part_category` не создаётся вовсе, а индексов в `catalog`
--     выходит 31 вместо 37.
--
-- Список живёт в `ops/`, а не берётся из `db/changelog`, намеренно: на машине
-- ячейки есть `ops/` и `docker-compose.prod.yml` (их кладёт выкладка
-- `rsync`'ом), а каталога `db/` может не быть вовсе. Цена такого решения —
-- список способен разойтись с тем, что на самом деле нужно схемам; поэтому
-- `ops/verify-backup.sh` каждую неделю сверяет его с расширениями ЖИВОЙ базы
-- и краснеет, если там появилось незнакомое. Дрейф обязан всплыть на проверке,
-- а не в день аварии.
--
-- IF NOT EXISTS: файл проигрывают и на живой базе, где они уже стоят.

CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS ltree;
CREATE EXTENSION IF NOT EXISTS pgcrypto;
