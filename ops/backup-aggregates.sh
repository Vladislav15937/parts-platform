#!/usr/bin/env bash
# Числа набора: пять агрегатов, снятых ВМЕСТЕ с дампом.
#
# Этот файл только сорсят — у него нет своего запуска:
#
#   . ops/backup-aggregates.sh
#
# ЗАЧЕМ ОН ЕСТЬ (задача 0244). `ops/verify-backup.sh` сверял пять агрегатов
# развёрнутой копии с ЖИВОЙ базой, строгим `!=` и без всякого допуска. Живая
# база — движущаяся цель: ночной дамп идёт в 03:00, проверка в 05:00
# по понедельникам, и любая законная запись в эти два часа красила проверку
# на совершенно годной копии.
#
# Это ОБРАТНЫЙ класс к обычному: не зелёное без следа, а красное без дефекта,
# и цена у него та же, только приходит с другой стороны. На ложную тревогу
# натыкаются каждую неделю, а кончается это тем, что проверку отключают или
# перестают читать, — после чего она молчит и про настоящую беду. Ровно это
# здесь уже случалось в задаче 0157: «бэкап проверен» выносилось еженедельно,
# при том что разворот падал на первой же таблице.
#
# ОТКУДА БЕРЁТСЯ ОЖИДАЕМОЕ. Числа снимает тот, кто снимает дамп
# (`ops/backup.sh`), и кладёт их в опись набора. Сверять «что было на момент
# снятия» больше не с чем: живая база этого уже не помнит, а дамп сам о себе
# таких чисел не рассказывает. Значит оракул обязан родиться вместе с набором
# и уехать вместе с ним — в том числе в офсайт, где никакой живой базы рядом
# нет вовсе.
#
# ПОЧЕМУ ЧИСЛА ДВА, А НЕ ОДНО. Снимок берётся ДО и ПОСЛЕ дампа схемы, и в описи
# стоят оба. Один замер рядом с дампом не равен состоянию внутри дампа: pg_dump
# держит свой снимок, а запись, прошедшая между замером и снимком, снова дала бы
# ложное красное — та же болезнь, только окно уже не два часа, а секунды дампа.
# Пара замеров это окно ОГРАНИЧИВАЕТ и измеряет: годным считается любое число
# между ними. На спокойной ячейке в 03:00 замеры равны, и сравнение выходит
# строгим, без всякого допуска; разошлись — значит в эти секунды писали, и
# разница в описи видна числами.
#
# ЭТО НЕ ДОПУСК «ПЛЮС-МИНУС СКОЛЬКО-НИБУДЬ». Допуска с выдуманным числом здесь
# нет: границы не назначены, а ИЗМЕРЕНЫ на живой базе вокруг самого дампа.
# Разница в одну сделку и разница в тысячу означают разное — и обе будут красить
# проверку, если в дампе их не окажется.
#
# ЧЕГО НЕ ВЫБРАЛИ И ПОЧЕМУ. Точный путь — один снимок на оба дела:
# `pg_export_snapshot()` в открытой транзакции плюс `pg_dump --snapshot=…`.
# Тогда числа и дамп видят ровно одно состояние. Отвергнуто ценой: держать
# транзакцию живой на время дампа — это psql на фоне через FIFO внутри
# `docker compose exec`, то есть новый способ подвесить НОЧНОЙ БЭКАП, самое
# дорогое, что есть у ячейки. Пара коротких запросов такого риска не несёт.
# Возвращаться к снимку — если окно между замерами начнёт расходиться
# настолько, что проверка станет пропускать настоящую недостачу.
#
# ПОЧЕМУ СПИСОК ОДИН НА ДВА ФАЙЛА. Его читают и тот, кто пишет числа
# (`ops/backup.sh`), и тот, кто по ним сверяет (`ops/verify-backup.sh`).
# Две копии одного списка разошлись бы молча: проверка искала бы в описи
# строки, которых бэкап не пишет, и «сверено» означало бы «не нашли, чего
# сверять». Та же причина, по которой адрес образа записан один раз
# (ops/images.yml).

# Слово-метка строки описи. Строки стоят ПОСЛЕ строк реестра: первые три
# строки описи печатает человеку ops/restore-cell.sh, а «арендаторов: N»
# он же читает sed'ом — формат этих строк трогать нельзя.
AGG_MARK="агрегат"

# Пять агрегатов — то, что клиент заметит первым: сколько позиций, сколько
# лежит на складе, сколько записей в журнале движений, сколько сделок
# и сколько сотрудников. Совпадение числа строк без совпадения остатка ничего
# не значит: остаток — агрегат журнала, и разъехаться он может независимо.
#
# Имена — ключ строки описи. Переименование имени означает, что набор, снятый
# прежней сборкой, перестаёт читаться (и честно скажет «не сверено»), поэтому
# менять их задним числом нельзя: только добавлять новые.
agg_names() {
    printf '%s\n' part part_stock_qty stock_movement deal tenant_member
}

# SQL одного агрегата. Один и тот же запрос задаётся живой базе при снятии
# набора и развёрнутой копии при проверке: разные запросы сравнивали бы
# разные величины и расходились бы молча.
agg_sql() {   # $1 — метрика, $2 — схема
    case "$1" in
        part)           printf 'SELECT count(*) FROM %s.part' "$2" ;;
        part_stock_qty) printf 'SELECT COALESCE(sum(qty), 0) FROM %s.part_stock' "$2" ;;
        stock_movement) printf 'SELECT count(*) FROM %s.stock_movement' "$2" ;;
        deal)           printf 'SELECT count(*) FROM %s.deal' "$2" ;;
        tenant_member)  printf 'SELECT count(*) FROM %s.tenant_member' "$2" ;;
        *) return 1 ;;
    esac
}

# Как называть агрегат человеку. Красную строку читают в аварию, и «part» там
# объясняет меньше, чем «позиций».
agg_title() {
    case "$1" in
        part)           printf 'позиций' ;;
        part_stock_qty) printf 'на складе (сумма qty)' ;;
        stock_movement) printf 'записей в журнале движений' ;;
        deal)           printf 'сделок' ;;
        tenant_member)  printf 'сотрудников' ;;
        *) printf '%s' "$1" ;;
    esac
}

# Строка описи набора.
agg_line() {   # схема метрика до после
    printf '%s %s %s %s %s\n' "$AGG_MARK" "$1" "$2" "$3" "$4"
}

# Пара замеров из описи: «до после», либо ПУСТО, если числа не записаны.
# Пусто — это законное состояние: набор, снятый сборкой до задачи 0244,
# таких строк не имеет, и проверка обязана сказать об этом словами,
# а не считать, что сверила.
agg_pair() {   # файл-описи схема метрика
    [ -r "$1" ] || return 0
    awk -v m="$AGG_MARK" -v s="$2" -v n="$3" \
        '$1 == m && $2 == s && $3 == n && NF >= 5 { print $4, $5; exit }' "$1"
}

# Число ли это вообще. Сумма qty приезжает numeric(12,3), то есть «12.000»;
# пустая строка и слова в описи означают, что сверять нечем.
agg_numeric() {
    case "$1" in
        ''|*[!0-9.]*) return 1 ;;
        *) return 0 ;;
    esac
}

# Попадает ли значение в измеренные границы. Сравнение числами, а не строками:
# bash «12.000» и «12» не сравнивает вовсе, а `-ge` на них падает.
# LC_ALL=C (задача 0126): под русской локалью разбор «12.500» зависит от awk —
# одни читают 12, дробную часть ища после ЗАПЯТОЙ. Значения тут идут через -v,
# и на macOS awk их читает верно, но на ячейке awk другой, а проверка, всегда
# говорящая «да», хуже отсутствующей: локаль закреплена, не надеясь на разбор.
agg_in_range() {   # значение замер1 замер2
    LC_ALL=C awk -v v="$1" -v a="$2" -v b="$3" 'BEGIN {
        lo = (a + 0 <= b + 0) ? a + 0 : b + 0
        hi = (a + 0 <= b + 0) ? b + 0 : a + 0
        exit !(v + 0 >= lo && v + 0 <= hi)
    }'
}
