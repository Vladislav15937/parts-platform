#!/usr/bin/env bash
# Накат миграций на схемы уже заведённых арендаторов ячейки.
#
#   ./migrate-tenants.sh                 # проверить, кто отстал (читающий прогон)
#   ./migrate-tenants.sh --check         # то же, названное словом
#   ./migrate-tenants.sh --apply         # накатить
#   ./migrate-tenants.sh --selftest      # проверка самого скрипта, без docker и ячейки
#
# Шаг развёртывания, а не старт приложения: пятьсот схем на подъёме — это
# минуты недоступности всей ячейки, и падение одной миграции не дало бы
# подняться остальным клиентам.
#
# ВЫКЛАДКОЙ ТЕПЕРЬ ЗАНИМАЕТСЯ ops/schema-sync.sh, а не этот скрипт.
# Причина: changelog лежит внутри jar, значит новые changeset'ы умеет накатить
# только новый артефакт — тот, который уже подменил работающий. Этот скрипт
# стучится в РАБОТАЮЩЕЕ приложение, то есть накатывает changeset'ы прежней
# сборки, и порядок ниже одним артефактом выполнить было нельзя вовсе:
# он инвертировался, оставляя окно, где новый код работает на старых схемах.
#
# Этот путь не отменён и остаётся тем, чем удобно спросить «кто отстал»
# у работающей ячейки, не поднимая контейнера. Чего он не умеет: накатить то,
# чего нет в работающем приложении, и опустить схему вниз.
#
# И ЗОВУЩИХ У НЕГО БОЛЬШЕ НЕТ — НИ ОДНОГО (задача 0202, 27 сентября 2026).
# Третья самопроверка выкладки (ops/deploy-checks.sh) спрашивала «кто отстал»
# этим скриптом, то есть через управляющий контур — а секрет провижининга
# docs/onboarding.md (раздел 2) велит выключать сразу после подключения.
# Выполненное правило красило СЛЕДУЮЩУЮ выкладку: скрипт падает на пустом
# APP_PROVISIONING_TOKEN раньше, чем успевает что-нибудь спросить, а проверка
# объявляла это словами «схемы отстали». 27 сентября это остановило выкладку
# на ПРОМ и продержало запись замороженной 37 секунд у живого клиента, при
# схемах, которые были на версии.
#
# Теперь та проверка спрашивает готовность работающей сборки (schemas
# в /actuator/readiness, по отметке schema_version в реестре), а ГЛУБОКИЙ
# вопрос — «что скажет про каждую схему сам Liquibase» — задаёт
# ops/schema-sync.sh без --apply: ему секрет не нужен, он сверяет на равенство
# с версией образа, называет по имени и схему ВПЕРЕДИ, и стоит шагом 3 той же
# выкладки. Значит глубокая проверка из выкладки не ушла — она стоит раньше,
# до подъёма новой сборки.
#
# Остался этот скрипт ровно одним: способом спросить работающую ячейку
# и НАКАТИТЬ (--apply) руками, не поднимая контейнера. Платится за это
# включённым управляющим контуром — то есть на ячейке, выполнившей правило
# подключения, он не работает вовсе, и это не поломка, а цена пути. Нужен
# ответ без секрета — ops/schema-sync.sh. Нужен накат — он же, с --apply,
# образом выкладываемой сборки.
#
# ЖИВ ЛИ ЭТОТ ПУТЬ — отвечено задачей 0243 (1 октября 2026), и ответ «жив,
# но не путь выкладки». Автоматических зовущих у скрипта нет ни одного,
# а человека к нему посылают четыре живых места: docs/deployment.md («прежний
# путь остался и не отменён» — им спрашивают работающую ячейку, не поднимая
# контейнера, и он единственный, когда образа под рукой нет),
# docs/pilot-server.md (повседневные команды пилота), docs/domain-model.md
# и .claude/agents/migrator.md. Поэтому скрипт НЕ УДАЛЁН: удаление — решение
# задачи 0163 (её критерий 2), и сделанное здесь оно оставило бы четыре
# висящие ссылки. Обе поломки задачи 0243 при этом починены: пока файл
# запускается, молчаливый зелёный на опечатке остаётся ловушкой независимо
# от того, кто его зовёт.
#
# Стоит ли его после этого держать, разбирает tasks/0163 (критерий 2): здесь
# снят его последний автоматический потребитель, а не сам скрипт.
#
# Порядок выкладки — expand/contract, и он важнее самого скрипта:
#   1. миграция, совместимая со старым кодом (добавить колонку, не удалять)
#   2. ops/schema-sync.sh --apply образом новой сборки
#   3. проверка: ops/schema-sync.sh — код возврата ноль
#   4. и только теперь поднять сам образ, который на новую схему рассчитывает
# Обратный порядок оставляет окно, в котором новый код ходит в старую схему.

set -euo pipefail
cd "$(dirname "$0")/.."

SELF="ops/$(basename "$0")"

red()   { printf '\033[1;31m%s\033[0m\n' "$1" >&2; }
green() { printf '\033[1;32m%s\033[0m\n' "$1"; }
fail()  { red "$1"; exit 1; }

# ─────────────────────────── разбор аргументов ───────────────────────────────
#
# Блока разбора у скрипта не было ВОВСЕ (задача 0243): стояло `APPLY="${1:-}"`,
# и единственное сравнение `[ "$APPLY" = "--apply" ]` решало, накатывать ли.
# Ни else, ни проверки неизвестного аргумента. Значит `--aply`, `--appply`,
# `-apply` и `apply` молча пропускали накат, выполняли только читающую часть
# и кончались зелёным «Все схемы на поставляемой версии» с кодом 0 — то есть
# отчётом о работе, которой не было, после которого человек идёт дальше
# по порядку выкладки. Образцы отбивания чужого аргумента стояли в обоих
# соседях по области (ops/schema-sync.sh, ops/switch-build.sh), здесь их
# не было.
#
# Печатает режим, а не выставляет глобальную переменную: так его проверяет
# самопроверка — у неё иначе нет способа спросить «как ты понял аргумент».
parse_args() {
    local mode=check
    while [ $# -gt 0 ]; do
        case "$1" in
            --apply)    mode=apply;    shift ;;
            --check)    mode=check;    shift ;;
            --selftest) mode=selftest; shift ;;
            -h|--help)  mode=help;     shift ;;
            *)
                red "Непонятный аргумент: $1"
                red "  Их два: --apply (накатить) и --check (только спросить, умолчание)."
                red "  Плюс --selftest и --help."
                red "  Опечатка в --apply читающего прогона НЕ делает: накат, о котором"
                red "  отчитались, обязан случиться. До задачи 0243 делала, и молча."
                return 2 ;;
        esac
    done
    printf '%s\n' "$mode"
}

# ──────────────────── файл окружения: путь и три состояния ───────────────────
#
# ДЕФЕКТ, который здесь починен (задача 0243). Проверка шла по
# НЕПРЕФИКСОВАННОМУ пути (`[ -f "$ENV_FILE" ]`), а чтение — по пути с «./»
# впереди (`. "./$ENV_FILE"`), при том что скрипт выше уже сделал cd в корень
# репозитория. Поэтому ENV_FILE=/srv/parts/.env — то есть ровно так, как файл
# лежит на ячейке, — проверку ПРОХОДИЛ и источался как «.//srv/parts/.env»,
# от текущего каталога. Под set -e это шумное падение «No such file
# or directory»; молча получалось в другом случае — относительный путь,
# заданный из другого каталога: файл не читался, PROVISIONING_TOKEN оставался
# пустым, и `:?` требовал секрет из файла, который существует и в котором
# секрет записан. Человек смотрит в файл, видит секрет и не понимает ответа.
#
# Относительный путь по-прежнему разрешается ОТ КОРНЯ РЕПОЗИТОРИЯ, а не
# от каталога, где стоял человек, и это не оплошность: умолчание «.env» —
# это файл ячейки рядом с docker-compose.prod.yml, и запуск из ops/ обязан
# находить его, как находил раньше. Сменить точку отсчёта значило бы сломать
# работающий путь ради неработающего.
resolve_env_file() {
    case "$1" in
        /*) printf '%s\n' "$1" ;;
        *)  printf './%s\n' "$1" ;;
    esac
}

# Три состояния, и сводить их нельзя: «файла нет», «файл есть, а прочитать
# не удалось» и «файл прочитан». Прежняя редакция сводила первые два
# к третьему с пустым токеном, и человек читал «нужен секрет» про файл,
# в котором секрет записан. То же различение, которого не хватало
# ops/control-plane.sh до задачи 0197.
env_file_state() {
    local src
    src=$(resolve_env_file "$1")
    if [ ! -e "$src" ]; then printf 'нет\n';         return 0; fi
    if [ ! -r "$src" ]; then printf 'не-читается\n'; return 0; fi
    printf 'годен\n'
}

# ───────────────────────────── итоговая строка ───────────────────────────────
#
# Зелёная строка обязана утверждать ровно то, что сделано. До задачи 0243
# читающий прогон кончался словами «Все схемы на поставляемой версии»,
# неотличимыми от итога наката, — и на опечатке в --apply человек читал их
# как «накатил», после чего шёл дальше по порядку выкладки.
final_line() {   # режим
    case "$1" in
        apply)
            green "Накат выполнен. Все схемы на поставляемой версии" ;;
        *)
            green "Все схемы на поставляемой версии — ЧИТАЮЩИЙ прогон, ничего не накатывали"
            printf '    Накатить: %s --apply\n' "$SELF" ;;
    esac
}

# ─────────────────────────────── самопроверка ────────────────────────────────
#
# Без docker, без ячейки и без сети: разбор аргументов, разрешение пути
# к файлу окружения и итоговая строка — чистые функции, а путь запуска
# проходится целиком с подложенным ответом приложения (MIGRATE_STUB).
# Последние случаи — возврат дефекта: копия скрипта с вернувшейся поломкой
# обязана валить самопроверку. Без них остальные не утверждали бы ничего.
selftest() {
    local bad=0 tmp out rc got
    tmp="${TMPDIR:-/tmp}/migrate-tenants-selftest.$$"
    mkdir -p "$tmp"
    echo "Самопроверка $SELF"

    # ── 1. разбор аргументов ────────────────────────────────────────────────
    mode_is() {  # имя, ожидаемый режим, аргументы…
        local name="$1" want="$2"; shift 2
        local seen
        set +e
        seen=$(parse_args "$@" 2>/dev/null); rc=$?
        set -e
        if [ "$rc" != 0 ] || [ "$seen" != "$want" ]; then
            red "  ✗ ${name}: ожидался режим «${want}», вышло «${seen}» (код ${rc})"
            bad=$((bad + 1)); return
        fi
        printf '  ✓ %s\n' "$name"
    }

    refuses() {  # имя, аргумент
        local name="$1" arg="$2"
        set +e
        out=$(parse_args "$arg" 2>&1); rc=$?
        set -e
        if [ "$rc" = 0 ]; then
            red "  ✗ ${name}: «${arg}» принят молча (режим «${out}») — это и есть дефект 0243"
            bad=$((bad + 1)); return
        fi
        case "$out" in
            *"Непонятный аргумент"*) printf '  ✓ %s\n' "$name" ;;
            *) red "  ✗ ${name}: отказ не называет непонятный аргумент: ${out}"
               bad=$((bad + 1)) ;;
        esac
    }

    mode_is "без аргументов — читающий прогон" check
    mode_is "--check — читающий прогон" check --check
    mode_is "--apply — накат" apply --apply
    mode_is "--selftest не съедается разбором" selftest --selftest
    # Ровно четыре написания, названные задачей 0243: каждое молча давало
    # читающий прогон и зелёный итог с кодом 0.
    refuses "опечатка --aply отбита словами" --aply
    refuses "опечатка --appply отбита словами" --appply
    refuses "опечатка -apply отбита словами" -apply
    refuses "опечатка apply (без тире) отбита словами" apply

    # ── 2. путь к файлу окружения ───────────────────────────────────────────
    got=$(resolve_env_file /srv/parts/.env)
    if [ "$got" = /srv/parts/.env ]; then
        printf '  ✓ абсолютный путь не префиксуется (было «.//srv/parts/.env»)\n'
    else
        red "  ✗ абсолютный путь искажён: ${got}"
        bad=$((bad + 1))
    fi
    case "$got" in
        .//*) red "  ✗ в пути осталось «.//» — это и есть поломка 0243"
              bad=$((bad + 1)) ;;
    esac
    got=$(resolve_env_file .env)
    if [ "$got" = ./.env ]; then
        printf '  ✓ относительный путь по-прежнему от корня репозитория\n'
    else
        red "  ✗ относительный путь искажён: ${got}"
        bad=$((bad + 1))
    fi

    # ── 3. три состояния файла, и отказ называет СВОЮ причину ───────────────
    printf 'APP_PROVISIONING_TOKEN=tok\n' > "$tmp/env"
    got=$(env_file_state "$tmp/env")
    if [ "$got" = годен ]; then
        printf '  ✓ существующий файл назван годным\n'
    else
        red "  ✗ существующий файл назван «${got}»"; bad=$((bad + 1))
    fi
    got=$(env_file_state "$tmp/net-takogo-fayla")
    if [ "$got" = нет ]; then
        printf '  ✓ отсутствующий файл назван отсутствующим\n'
    else
        red "  ✗ отсутствующий файл назван «${got}»"; bad=$((bad + 1))
    fi
    # Нечитаемый файл: под root права не спрашивают, и случай честно
    # пропускается — сторож, красный там, где прав всегда хватает, был бы
    # отключён первым.
    printf 'APP_PROVISIONING_TOKEN=tok\n' > "$tmp/zakrytyy"
    chmod 000 "$tmp/zakrytyy" 2>/dev/null || true
    if [ -r "$tmp/zakrytyy" ]; then
        printf '  ~ нечитаемый файл НЕ ПРОВЕРЕН: под этим пользователем права не спрашивают\n'
    else
        got=$(env_file_state "$tmp/zakrytyy")
        if [ "$got" = не-читается ]; then
            printf '  ✓ нечитаемый файл отличён от отсутствующего\n'
        else
            red "  ✗ нечитаемый файл назван «${got}» — человек прочтёт «секрет не задан»"
            bad=$((bad + 1))
        fi
    fi
    chmod 644 "$tmp/zakrytyy" 2>/dev/null || true

    # ── 4. итоговая строка утверждает ровно сделанное ───────────────────────
    out=$(final_line check)
    case "$out" in
        *ЧИТАЮЩИЙ*) printf '  ✓ итог читающего прогона называет себя читающим\n' ;;
        *) red "  ✗ итог читающего прогона неотличим от наката: ${out}"
           bad=$((bad + 1)) ;;
    esac
    out=$(final_line apply)
    case "$out" in
        *ЧИТАЮЩИЙ*) red "  ✗ итог наката назван читающим прогоном: ${out}"
                    bad=$((bad + 1)) ;;
        *Накат*)    printf '  ✓ итог наката говорит про накат\n' ;;
        *) red "  ✗ итог наката не называет накат: ${out}"
           bad=$((bad + 1)) ;;
    esac

    # ── 5. ОБВЯЗКА: путь запуска читает файл окружения ──────────────────────
    #
    # Проба, зовущая только функции, не проверяет ПУТЬ ЗАПУСКА — а именно он
    # читает .env (урок задачи 0144). Ответ приложения подкладывается файлом,
    # поэтому ни docker, ни сети не нужно.
    printf '{"behind":[],"failures":[]}\n200\n' > "$tmp/stub"
    local absenv="$tmp/env-abs"
    printf 'APP_PROVISIONING_TOKEN=sekret-iz-absolyutnogo-puti\n' > "$absenv"

    run_it() {  # аргументы скрипта…
        set +e
        out=$(ENV_FILE="$absenv" APP_URL=http://stend MIGRATE_STUB="$tmp/stub" \
              bash "$SELF" "$@" 2>&1); rc=$?
        set -e
    }

    # 5а. АБСОЛЮТНЫЙ путь к .env — главный критерий задачи: секрет обязан
    #     доехать. До правки здесь было «.//…: No such file or directory».
    run_it
    if [ "$rc" = 0 ] && [ -z "${out##*ЧИТАЮЩИЙ*}" ]; then
        printf '  ✓ обвязка: .env по абсолютному пути прочитан, секрет доехал, прогон читающий\n'
    else
        red "  ✗ обвязка: .env по абсолютному пути не доехал (код ${rc})"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=$((bad + 1))
    fi
    case "$out" in
        *sekret-iz-absolyutnogo-puti*)
            red "  ✗ СЕКРЕТ НАПЕЧАТАН в выводе — этого нельзя ни в каком виде"
            bad=$((bad + 1)) ;;
        *) printf '  ✓ обвязка: секрет в вывод не попал\n' ;;
    esac

    # 5б. Обратный край: --apply по-прежнему накатывает.
    run_it --apply
    if [ "$rc" = 0 ] && [ -z "${out##*Накат выполнен*}" ] && [ -n "${out##*ЧИТАЮЩИЙ*}" ]; then
        printf '  ✓ обвязка: --apply накатывает и говорит про накат\n'
    else
        red "  ✗ обвязка: --apply не накатил либо назвался читающим (код ${rc})"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=$((bad + 1))
    fi

    # 5в. Опечатка останавливает прогон, а не делает читающий молча.
    run_it --aply
    if [ "$rc" != 0 ] && [ -z "${out##*Непонятный аргумент*}" ]; then
        printf '  ✓ обвязка: --aply останавливает прогон ненулевым кодом\n'
    else
        red "  ✗ обвязка: --aply прошёл (код ${rc}) — молчаливый читающий прогон вернулся"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=$((bad + 1))
    fi

    # 5г. Файл прочитан, а секрет в нём пуст — отказ обязан говорить про
    #     ПУСТОЙ СЕКРЕТ, а не про отсутствующий файл.
    printf 'APP_PROVISIONING_TOKEN=\n' > "$tmp/env-pusto"
    set +e
    out=$(ENV_FILE="$tmp/env-pusto" APP_URL=http://stend MIGRATE_STUB="$tmp/stub" \
          bash "$SELF" 2>&1); rc=$?
    set -e
    if [ "$rc" != 0 ] && [ -z "${out##*файл прочитан*}" ] && [ -n "${out##*Нет файла*}" ]; then
        printf '  ✓ обвязка: пустой секрет назван пустым, а не отсутствующим файлом\n'
    else
        red "  ✗ обвязка: пустой секрет назван не своей причиной (код ${rc})"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=$((bad + 1))
    fi

    # 5д. Файла нет вовсе — отказ называет путь и точку отсчёта, а не секрет.
    set +e
    out=$(ENV_FILE="$tmp/net-takogo-fayla" APP_URL=http://stend MIGRATE_STUB="$tmp/stub" \
          bash "$SELF" 2>&1); rc=$?
    set -e
    if [ "$rc" != 0 ] && [ -z "${out##*Нет файла окружения*}" ]; then
        printf '  ✓ обвязка: отсутствующий файл назван файлом, а не «секрет не задан»\n'
    else
        red "  ✗ обвязка: отсутствующий файл назван не своей причиной (код ${rc})"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=$((bad + 1))
    fi

    # ── 6. ВОЗВРАТ ДЕФЕКТА ──────────────────────────────────────────────────
    #
    # Две копии, каждая возвращает ровно одну половину поломки 0243, и каждая
    # обязана валить самопроверку. Целость копии проверяется ДО запуска
    # (bash -n): красное от сломанного синтаксиса не говорило бы ни о чём
    # (урок задачи 0198). Копия кладётся в ops/, а не в /tmp: скрипт делает
    # cd в корень репозитория от своего каталога, и копия в /tmp ушла бы
    # в корень файловой системы (урок задачи 0151).
    forgery() {  # имя, программа подделки для python
        local name="$1" program="$2"
        local fake="ops/.migrate-tenants-podelka.$$.sh"
        if ! printf '%s' "$program" | python3 - "$SELF" "$fake"; then
            red "  ✗ ${name}: подделку негде поставить — образец не нашёлся"
            bad=$((bad + 1)); rm -f "$fake"; return
        fi
        chmod +x "$fake"
        if ! bash -n "$fake" 2>/dev/null; then
            red "  ✗ ${name}: подделка сломала синтаксис — её красное ничего не значило бы"
            bad=$((bad + 1)); rm -f "$fake"; return
        fi
        set +e
        out=$(MIGRATE_SELFTEST_FAKE=1 bash "$fake" --selftest 2>&1); rc=$?
        set -e
        rm -f "$fake"
        if [ "$rc" != 0 ]; then
            printf '  ✓ возврат дефекта: %s валит самопроверку\n' "$name"
        else
            red "  ✗ ${name}: копия с вернувшейся поломкой ПРОШЛА самопроверку"
            printf '%s\n' "$out" | sed 's/^/      /' >&2
            bad=$((bad + 1))
        fi
    }

    # Рекурсию обрывает MIGRATE_SELFTEST_FAKE: иначе подделка заводила бы
    # подделку себя.
    if [ -z "${MIGRATE_SELFTEST_FAKE:-}" ]; then
        # 6а. Снят `*)` — неизвестный аргумент снова молча даёт читающий прогон.
        forgery "неизвестный аргумент снова проходит молча" '
import sys
src, dst = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()
obrazec = """            *)
                red "Непонятный аргумент: $1"
"""
assert obrazec in text, "образец ветки отказа не найден"
text = text.replace(obrazec, """            *)
                shift; continue
                red "Непонятный аргумент: $1"
""", 1)
open(dst, "w", encoding="utf-8").write(text)
'
        # 6б. Вернулся «./» перед абсолютным путём — секрет из файла ячейки
        #     снова не доезжает.
        forgery "«./» перед абсолютным путём вернулось" '
import sys
src, dst = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()
obrazec = """        /*) printf \x27%s\\n\x27 "$1" ;;"""
assert obrazec in text, "образец ветки абсолютного пути не найден"
text = text.replace(obrazec, """        /*) printf \x27./%s\\n\x27 "$1" ;;""", 1)
open(dst, "w", encoding="utf-8").write(text)
'
    fi

    rm -rf "$tmp"
    if [ "$bad" != 0 ]; then
        red "Самопроверка не прошла: $bad"
        return 1
    fi
    green "Самопроверка пройдена: разбор аргументов, путь к .env, три состояния файла и итоговая строка."
    printf '    Схемы при этом не спрашивались — для этого запуск без аргументов.\n'
    return 0
}

