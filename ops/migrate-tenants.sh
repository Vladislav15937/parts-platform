# Секрет берётся из файла окружения ячейки, как у бэкапа и заведения ролей.
# Пока он требовался переменной с другим именем (PROVISIONING_TOKEN против
# APP_PROVISIONING_TOKEN в .env), шаг развёртывания начинался с ручного
# экспорта — а забытый экспорт роняет накат ровно в день выкладки.
#
# Сорсится файл в ТЕКУЩУЮ оболочку, как и раньше: кроме секрета, оттуда
# законно приезжает APP_URL («оператор знает, куда»), и подоболочка, читающая
# только токен, отменила бы это молча — ровно тот класс, который задача 0243
# и чинит.
ENV_FILE="${ENV_FILE:-.env}"
ENV_PATH=$(resolve_env_file "$ENV_FILE")

if [ -z "${PROVISIONING_TOKEN:-}" ]; then
    case "$(env_file_state "$ENV_FILE")" in
        годен)
            set -a
            # shellcheck source=/dev/null
            . "$ENV_PATH" || fail "Файл окружения $ENV_PATH есть, а прочитать его не удалось.
    Это НЕ «секрет не задан»: проверьте сам файл (кавычки, перевод строки)."
            set +a
            PROVISIONING_TOKEN="${APP_PROVISIONING_TOKEN:-}"
            ;;
        не-читается)
            fail "Файл окружения есть, а прочитать его нечем: $ENV_PATH — нет прав на чтение.
    Это НЕ «секрет не задан» — секрет там может быть записан, его просто не видно.
    Кем читать: тем пользователем, которому принадлежит ячейка (.env лежит с правами 600)."
            ;;
        нет)
            fail "Нет файла окружения: $ENV_PATH
    Относительный путь разрешается от корня репозитория ($(pwd)), а не от каталога,
    где вы стоите; абсолютный берётся как есть. Назовите файл явно:
      ENV_FILE=/путь/к/.env $SELF
    либо задайте секрет переменной: PROVISIONING_TOKEN=… $SELF"
            ;;
    esac
fi

: "${PROVISIONING_TOKEN:?пуст APP_PROVISIONING_TOKEN (файл прочитан).
    Управляющий контур, похоже, выключен — правило подключения велит выключать
