#!/usr/bin/env bash
# Прокрутка журнала расписания ячейки.
#
#   ops/rotate-log.sh [ЖУРНАЛ]   # прокрутить, если перерос предел
#   ops/rotate-log.sh --limit    # назвать предел и глубину хранения числами
#   ops/rotate-log.sh --selftest # проверить самого себя на подделках
#
# ЗАЧЕМ (задача 0154). В журнал пишут все пять задач расписания, а задача
# архива WAL идёт КАЖДЫЕ ПЯТЬ МИНУТ — 288 запусков в сутки, и каждый что-то
# пишет. Пока расписание стояло мёртвым (0152), это ничего не значило: файла
# не существовало вовсе. Починка 0152 включила запись — и с 20 сентября 2026,
# 06:28 UTC, журнал боевой ячейки растёт, а ротации нет никакой: правил
# logrotate про него не заведено ни одного, и системный logrotate до каталога
# ячейки не дотягивается по построению (0152 выбрала этот каталог как раз
# затем, чтобы не зависеть от прав на `/var/log`).
#
# Цена не в мусоре на диске: заполненный диск ячейки останавливает Postgres,
# а вместе с ним и архив WAL — то есть растущий журнал ломает точку возврата,
# ради которой всё и заведено.
#
# ПОЧЕМУ СВОЙ СКРИПТ, А НЕ logrotate. Три довода, и первый решающий:
#   1) настройка обязана ехать в репозитории (критерий задачи), а правило
#      logrotate — это либо файл в `/etc/logrotate.d` (root и состояние машины:
#      следующая ячейка поднимется без него, и узнают об этом через месяцы),
#      либо свой конфиг плюс своё состояние плюс своя строка в crontab — то
#      есть та же строка в расписании, только с чужим бинарником посередине;
#   2) logrotate есть не везде (на машине разработчика и в образах CI его нет),
#      значит «ротация доказана прогоном» доказывалась бы не тем, что поедет
#      в бой;
#   3) нам нужна ровно одна операция из всего logrotate — переименование
#      с созданием нового файла; остальное его поведение (copytruncate,
#      su, dateext) нам не просто не нужно, а опасно, см. ниже.
# Цена решения названа: своя прокрутка — свой код, и держится он на
# самопроверке ниже, а не на чужой репутации.
#
# ПОЧЕМУ ПЕРЕИМЕНОВАНИЕ, А НЕ ОБРЕЗКА. Задачи пишут в журнал через `>> ЖУРНАЛ`,
# то есть шелл открывает файл ОДИН РАЗ, до запуска команды, и держит
# дескриптор всё время работы задачи (ночной дамп идёт минутами). Переименовав
# файл, мы не трогаем этот дескриптор: идущая задача продолжает писать
# в переименованный — вывод не теряется и задача не падает. `copytruncate`
# (скопировать и обрезать) потерял бы всё, что записано между копией
# и обрезкой, а запись с O_APPEND после обрезки легла бы с нулевого смещения,
# оставив в файле дыру. Это и есть критерий «ни одна задача не теряет вывод».
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$(pwd)"

# ПРЕДЕЛ — РАЗМЕРОМ, А НЕ СРОКОМ, и это довод, а не вкус. Сроком («хранить
# 30 дней») занимаемое место зависит от того, насколько разговорчивы задачи:
# один цикл отказов архиватора пишет по десятку строк каждые пять минут,
# и месячный журнал раздувается непредсказуемо.
#
# ЧЕГО ЭТОТ ПРЕДЕЛ НЕ ДАЁТ, и это надо знать до того, как на него сошлются.
# Прокрутка режет журнал В МОМЕНТ СВОЕГО ЗАПУСКА и потоком записи
# не управляет: сколько задача выльет между часовыми прокрутками — столько
# и будет лежать. Замерено: 50 МиБ, записанные одним куском, дают копию `.1`
# ровно в 50 МиБ при пределе 5. Значит «не больше 30 МиБ» — это правда
# ПРО СЕГОДНЯШНЕЕ ПОВЕДЕНИЕ пяти задач (ни одна не пишет в неограниченном
# цикле: у `restore-pitr.sh` цикл ожидания печатает только на выходе,
# у остальных циклы идут по готовым спискам), а не свойство самой прокрутки.
# Бюджет между проверками не ограничен ничем — это цена периодической
# ротации, любой, включая logrotate.
#
# 5 МиБ выбраны замером: здоровый прогон `ops/wal-archive.sh` пишет 850 байт
# (пять шагов — цепочка, архиватор, офсайт, место на диске, состав баз;
# считано по самим строкам скрипта), 288 прогонов в сутки дают ~239 КиБ в день
# и ~7,0 МиБ в месяц; остальные четыре задачи на этом фоне пренебрежимы
# (ночной дамп — единицы килобайт, недельные проверки — десятки). То есть
# прокрутка случается примерно раз в 21 день, а пять хранимых копий держат
# около трёх с половиной месяцев истории — ровно то, за чем в этот журнал
# и заходят («когда это сломалось в последний раз»).
#
# Было 569 байт и ~4,7 МиБ в месяц, пока шагов было три: четвёртый добавила
# задача 0089 (место на диске числом в наблюдение) — 193 байта, стало 762,
# прокрутка раз в 24 дня и четыре месяца истории; пятый — задача 0229
# (состав баз) — ещё 88 байт. Цена названа здесь нарочно: каждый шаг сдвигает
# и частоту прокрутки, и глубину истории, и запись, обещающая прежнее, стала
# бы неправдой.
LIMIT="${ROTATE_LIMIT_BYTES:-5242880}"   # 5 МиБ
KEEP="${ROTATE_KEEP:-5}"                 # сколько прокрученных копий хранить

# Файл окружения ячейки здесь НЕ читается, и это намеренно. `.env` старше
# переданного окружения (`set -a; . .env`), поэтому скрипт, сорсящий его,
# меряет не себя, а чужой файл — и меряет по-разному на разных машинах.
# Так уже обожглись дважды: список тестовых компаний в 0144 и выдержка
# сторожа тревог в 0153. Прокрутке из `.env` ничего не нужно: путь журнала
# приходит аргументом из той же строки расписания, что и перенаправление.
LOG="${1:-${BACKUP_LOG:-$ROOT/logs/parts-backup.log}}"

red()   { printf '\033[1;31m%s\033[0m\n' "$1" >&2; }
green() { printf '\033[1;32m%s\033[0m\n' "$1"; }

# Размер — `wc -c`, а не `stat`. У `stat` формат разный на GNU и BSD, и порядок
# отката уже стоил проекту круга (задача 0140: на Linux `stat -f` — это
# `--file-system`, он печатает простыню про блоки и ВЫХОДИТ НУЛЁМ, то есть
# откат по `||` не срабатывает). `wc -c` одинаков везде.
size_of() { if [ -f "$1" ]; then wc -c < "$1" | tr -d ' '; else printf '0'; fi; }

# Режим файла нужен, чтобы новый журнал родился с теми же правами, что старый:
# журнал ячейки — это вывод задач, которые ходят в базу, и расширять к нему
# доступ прокруткой нельзя. Здесь `stat` нужен по-настоящему, и порядок
# обязан быть GNU → BSD (см. выше про 0140).
#
# Третьей ветки «или напечатать 600» здесь БОЛЬШЕ НЕТ (задача 0240). Она
# выдумывала режим при отказе обеих форм `stat`, `chmod "$mode"` ниже ставил
# его успешно, `mode_failed` оставался нулём, и прокрутка возвращала 0 —
# журнал, бывший 640, мог родиться 600 (или наоборот, шире), и сказать об этом
# было некому. Невозможность узнать права — это отказ прокрутки, а не повод
# назначить их самим.
mode_of() { stat -c '%a' "$1" 2>/dev/null || stat -f '%Lp' "$1" 2>/dev/null; }

mib() { printf '%s' "$(( ( $1 + 524288 ) / 1048576 ))"; }

# --- след в наблюдении (задача 0240) ----------------------------------------
#
# У прокрутки не было отметки ни в одном наблюдении: отказ был виден лишь
# красным в том самом журнале, который она не смогла прокрутить, а ячейка
# узнавала о нём с заполненным диском (он останавливает Postgres, а с ним
# архив WAL). Отметка — время последнего ПРОХОДА, закончившегося нулём: и «под
# пределом, трогать нечего», и «прокручено». Ставится после всех шагов, как у
# соседей по расписанию: поставленная раньше, она значила бы «запускался».
# Тревога — `ПрокруткаЖурналаНеХодит` в ops/alerts.yml: absent() ловит
# «задачи нет в crontab», возраст — «стоит, но отказывает».
#
# Недоступное наблюдение прокрутку не валит: журнал-то прокручен, и ронять
# работу ради метрики значит терять данные ради числа (так же у backup.sh).
send_mark() {
    local url="${PUSHGATEWAY_URL:-http://localhost:9091}"
    if ! printf '# TYPE partsflow_log_rotate_success_timestamp_seconds gauge\npartsflow_log_rotate_success_timestamp_seconds %s\n' \
            "$(date -u +%s)" \
        | curl -sf --max-time 10 --data-binary @- "$url/metrics/job/logrotate" > /dev/null
    then
        printf '%s  отметка прокрутки в наблюдение не ушла — проверьте pushgateway\n' \
            "$(date -u '+%Y-%m-%d %H:%M:%S UTC')"
    fi
}

# --- прокрутка --------------------------------------------------------------

rotate() {
    local log="$1" dir size mode i lock mode_failed=0
    dir=$(dirname "$log")

    if [ ! -f "$log" ]; then
        # Не отказ: до первой записи файла нет вовсе, а задача в расписании
        # стоит с первого дня. Красное на свежей ячейке отключили бы вместе
        # с прокруткой.
        printf 'журнала нет — прокручивать нечего: %s\n' "$log"
        return 0
    fi

    size=$(size_of "$log")
    if [ "$size" -lt "$LIMIT" ]; then
        return 0   # тихо: задача идёт каждый час, и строка «ещё не пора»
                   # засорила бы тот самый журнал, размер которого мы бережём
    fi

    if [ ! -w "$dir" ]; then
        red "✗ журнал перерос предел, а прокрутить его нечем: $log"
        red "    нет права записи в $dir ($(ls -ld "$dir" 2>/dev/null | awk '{print $1, $3, $4}' || true))"
        red "    журнал продолжит расти; заполненный диск ячейки останавливает Postgres"
        return 1
    fi

    # Замок: задача стоит в расписании, и две прокрутки разом переставляли бы
    # копии друг у друга из-под ног. `mkdir`, а не `flock`, — по тому же
    # доводу, что и в ops/wal-archive.sh: он есть и на хосте ячейки,
    # и на машине разработчика.
    lock="${TMPDIR:-/tmp}/partsflow-rotate-$(printf '%s' "$log" | tr -c 'A-Za-z0-9' '-').lock"
    if ! mkdir "$lock" 2>/dev/null; then
        printf 'прошлая прокрутка ещё идёт (%s) — пропускаю\n' "$lock"
        return 0
    fi
    # shellcheck disable=SC2064
    trap "rmdir '$lock' 2>/dev/null || true" RETURN

    # Права узнаются ДО того, как что-либо сдвинуто: отказ тут не должен
    # оставить после себя наполовину переставленные копии. Ответ, не похожий
    # на восьмеричное число, — тоже «не узнали» (на Linux `stat -f` без
    # `--file-system` печатает простыню и выходит нулём — урок 0140).
    if ! mode=$(mode_of "$log") || [ -z "$mode" ] || [[ $mode == *[!0-7]* ]]; then
        red "✗ права журнала узнать не удалось (stat не ответил числом ни в одной форме): $log"
        red "    придумывать их нельзя: новый журнал мог бы родиться шире прежнего (в нём вывод задач, ходящих в базу)"
        red "    журнал не тронут, прокрутка не сделана, он продолжит расти"
        return 1
    fi

    # 1. Самая старая копия уходит.
    rm -f "$log.$KEEP.gz"
    # 2. Сжатые копии сдвигаются на одну вниз.
    i=$(( KEEP - 1 ))
    while [ "$i" -ge 2 ]; do
        [ -f "$log.$i.gz" ] && mv "$log.$i.gz" "$log.$(( i + 1 )).gz"
        i=$(( i - 1 ))
    done
    # 3. Прошлая прокрутка (несжатая `.1`) сжимается только СЕЙЧАС, а не
    #    в момент своего появления. Это `delaycompress` logrotate, и причина
    #    у него та же, что у переименования: в `.1` могла дописывать задача,
    #    которая шла в момент прокрутки и держала дескриптор. Сжав файл сразу,
    #    мы потеряли бы её хвост. К следующей прокрутке (по замеру — через
    #    месяц) её давно нет.
    if [ -f "$log.1" ]; then
        # ОТКАЗ `gzip` ЗДЕСЬ НЕ ОСТАНАВЛИВАЛ СКРИПТ, и это стоило поколения
        # журнала. Команда стояла НЕФИНАЛЬНОЙ в `&&`-списке, а `set -e`
        # такие списки не судит: `mv` пропускался, `rm -f "$log.1"` сносил
        # несжатую копию всё равно, `.2.gz` не появлялось — и итог печатал
        # зелёное «журнал прокручен». Отказывает `gzip` ровно на кончившемся
        # диске, то есть в том самом случае, ради которого прокрутка заведена.
        #
        # Поэтому отказ называется словами, несжатая копия остаётся на месте,
        # а прокрутка этого цикла не делается вовсе: потерять поколение хуже,
        # чем не прокрутить — журнал за час не вырастет так, как стоит история,
        # которую в нём ищут.
        if ! gzip -c "$log.1" > "$log.2.gz.tmp" 2>/dev/null; then
            rm -f "$log.2.gz.tmp"
            red "✗ прошлую копию журнала не сжать: $log.1"
            red "    поколение журнала не тронуто, прокрутка не сделана"
            red "    скорее всего на диске нет места; заполненный диск ячейки останавливает Postgres"
            return 1
        fi
        # СОДЕРЖИМОЕ КОПИИ ПРОВЕРЯЕТСЯ ДО УДАЛЕНИЯ ИСХОДНИКА (задача 0240).
        # Код возврата `gzip` говорит, что он отработал, а не что получилось
        # то, что можно разжать: усечённая запись на кончающемся диске, подмена
        # утилиты, обрыв посередине — и `rm -f "$log.1"` ниже сносил единственный
        # экземпляр поколения, а итог печатал «прокручен». Сверяется разжатое
        # с оригиналом, а не «gzip -t»: тот же самый `gzip` отвечал бы и здесь,
        # и подменённый на `exit 0` пропустил бы проверку вместе с копией.
        if [ ! -s "$log.2.gz.tmp" ] || ! gzip -dc "$log.2.gz.tmp" 2>/dev/null | cmp -s - "$log.1"; then
            rm -f "$log.2.gz.tmp"
            red "✗ сжатая копия не совпала с оригиналом: $log.2.gz не разжимается в $log.1"
            red "    поколение журнала не тронуто, прокрутка не сделана"
            return 1
        fi
        mv "$log.2.gz.tmp" "$log.2.gz"
        rm -f "$log.1"
    fi
    # 4. Текущий журнал — переименованием. Дескрипторы идущих задач остаются
    #    на нём: их вывод доедет в `.1`, а не пропадёт.
    mv "$log" "$log.1"
    # 5. Новый журнал с прежними правами. Создаём сами, а не ждём первой
    #    задачи: `>>` создаст файл по umask, и права разъехались бы с прежними.
    : > "$log"
    # Отказ `chmod` глушился целиком (`|| true`), а случай 5 самопроверки
    # объявляет прежние права инвариантом: «журнал ячейки открывать шире
    # прокрутка не вправе». Молча не выполненный инвариант — это обещание,
    # которое перестало действовать, и узнать об этом было нечем.
    if ! chmod "$mode" "$log" 2>/dev/null; then
        red "✗ права нового журнала не выставлены (ждали $mode): $log"
        red "    в журнале вывод задач, ходящих в базу, — шире прежних открывать его нельзя"
        mode_failed=1
    fi

    # Запись о прокрутке идёт в НОВЫЙ журнал явным перенаправлением, а не
    # в stdout. Из расписания stdout уже перенаправлен в старый файл (шелл
    # открыл его до запуска команды), то есть след прокрутки лёг бы
    # в прокрученную копию — туда, где его никто не ищет.
    printf '%s  журнал прокручен: было %s МиБ, копий хранится %s (ops/rotate-log.sh)\n' \
        "$(date -u '+%Y-%m-%d %H:%M:%S UTC')" "$(mib "$size")" "$KEEP" >> "$log"

    green "журнал прокручен: $log ($(mib "$size") МиБ → $log.1), копий хранится $KEEP"

    # Сторож на случай, когда прокрутка «прошла», а размер не упал: так
    # выглядит любая тихая поломка этого места. «Правило лежит» и «правило
    # отработало» — разные утверждения, и вся цена 0152 заплачена за их подмену.
    size=$(size_of "$log")
    if [ "$size" -ge "$LIMIT" ]; then
        red "✗ прокрутка прошла, а журнал по-прежнему $(mib "$size") МиБ при пределе $(mib "$LIMIT") МиБ"
        return 1
    fi
    # Права не выставились — прокрутка состоялась, но названный инвариант нет.
    # Зелёная строка выше правдива (журнал прокручен), а код возврата обязан
    # быть ненулевым: иначе несделанное уезжает под успехом.
    [ "$mode_failed" = 0 ] || return 1
    return 0
}

# --- проверка самого себя ---------------------------------------------------
#
# Случаи — ровно те, которыми эта защита перестаёт работать: журнал под
# пределом трогать нельзя; переросший обязан прокрутиться; идущая задача
# не должна ни потерять вывод, ни упасть; глубина хранения обязана быть
# конечной; права не должны разъехаться; отсутствие прав — отказ словами.
# Последним — возврат дефекта: копия скрипта со снятой прокруткой обязана
# молча дать журналу расти, иначе краснеет не прокрутка, а что-то соседнее.
selftest() {
    local bad=0 tmp out rc log SELF n n_under n_rot
    SELF="$(cd "$(dirname "$0")" && pwd)/$(basename "$0")"
    echo "Самопроверка ops/rotate-log.sh"

    tmp=$(mktemp -d)
    # shellcheck disable=SC2064
    trap "rm -rf '$tmp'" EXIT
    log="$tmp/parts-backup.log"

    # Заглушка `curl` на ВЕСЬ прогон: настоящий pushgateway тут трогать нельзя,
    # а отметку надо видеть — что и куда ушло. Адрес — последний аргумент,
    # тело — со стандартного входа.
    mkdir -p "$tmp/stub"
    cat > "$tmp/stub/curl" <<'STUB'
#!/bin/sh
for a; do last=$a; done
body=$(cat)
printf '%s %s\n' "$last" "$(printf '%s' "$body" | tr '\n' ' ')" >> "$CURL_LOG"
exit "${CURL_RC:-0}"
STUB
    chmod +x "$tmp/stub/curl"
    export CURL_LOG="$tmp/curl.log"
    : > "$CURL_LOG"
    export PATH="$tmp/stub:$PATH"

    # Строка, похожая на настоящий вывод расписания, — чтобы и размеры,
    # и сжатие мерились на том, что действительно пишут задачи.
    fill() {  # $1 — файл, $2 — сколько байт примерно
        local f="$1" want="$2"
        : > "$f"
        while [ "$(size_of "$f")" -lt "$want" ]; do
            printf '\033[1;32m    в очереди 0, отказов за жизнь базы 0 — %s\033[0m\n' \
                "$(date -u '+%Y-%m-%d %H:%M:%S')" >> "$f"
        done
    }
    run() {  # $1 — какой скрипт гнать; вывод в out, код в rc
        set +e
        out=$(ROTATE_LIMIT_BYTES=8192 ROTATE_KEEP=3 bash "$1" "$log" 2>&1); rc=$?
        set -e
    }

    # Случай 1: под пределом — не трогать вовсе. Прокрутка, режущая журнал
    # каждый час, потеряла бы историю, ради которой журнал и ведут.
    fill "$log" 1000
    run "$SELF"
    if [ "$rc" = 0 ] && [ ! -f "$log.1" ] && [ "$(size_of "$log")" -gt 900 ]; then
        printf '  ✓ под пределом журнал не тронут\n'
    else
        red "  ✗ журнал под пределом обязан остаться нетронутым (код $rc)"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=1
    fi

    # Случай 2: над пределом — прокручен, содержимое уехало в копию,
    # новый журнал начат и несёт запись о прокрутке.
    fill "$log" 9000
    printf 'МЕТКА-СОДЕРЖИМОГО\n' >> "$log"
    run "$SELF"
    if [ "$rc" = 0 ] && [ -f "$log.1" ] \
       && grep -q 'МЕТКА-СОДЕРЖИМОГО' "$log.1" \
       && [ "$(size_of "$log")" -lt 8192 ] \
       && grep -q 'журнал прокручен' "$log"; then
        printf '  ✓ над пределом — прокручен: старое в копии, новый журнал начат и подписан\n'
    else
        red "  ✗ переросший журнал обязан прокручиваться (код $rc)"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=1
    fi

    # Случай 3 — главный: идущая задача не теряет вывод и не падает.
    # Дескриптор открывается ровно так же, как его открывает шелл crontab
    # для `>> ЖУРНАЛ`, — ДО прокрутки, и пишет ПОСЛЕ неё.
    rm -f "$log".[0-9]* ; fill "$log" 9000
    set +e
    (
        exec 9>>"$log"                       # так открывает файл шелл cron
        # Предел обязан приехать и сюда: без него 9 КиБ журнала не дотягивают
        # до умолчания в 5 МиБ, прокрутки не случается вовсе — и случай
        # зеленеет, ничего не проверив. Ровно так он и был написан сначала.
        ROTATE_LIMIT_BYTES=8192 ROTATE_KEEP=3 \
            bash "$SELF" "$log" >/dev/null 2>&1  # прокрутка под идущей задачей
        printf 'ХВОСТ-ИДУЩЕЙ-ЗАДАЧИ\n' >&9  # задача дописывает свой вывод
        exec 9>&-
    ) 2>/dev/null; rc=$?
    set -e
    if [ "$rc" = 0 ] && [ -f "$log" ] \
       && grep -q 'ХВОСТ-ИДУЩЕЙ-ЗАДАЧИ' "$log.1" 2>/dev/null \
       && ! grep -q 'ХВОСТ-ИДУЩЕЙ-ЗАДАЧИ' "$log" 2>/dev/null; then
        printf '  ✓ идущая задача не упала, и её вывод доехал в прокрученную копию\n'
    else
        red "  ✗ вывод идущей задачи обязан сохраниться, а сама задача не падать (код $rc)"
        red "      это и есть запрет на copytruncate: там хвост задачи теряется"
        bad=1
    fi

    # Случай 4: глубина хранения конечна, старое уходит, копии сжимаются —
    # кроме свежей (delaycompress, случай 3 объясняет почему).
    rm -f "$log".[0-9]*
    n=1
    while [ "$n" -le 5 ]; do
        fill "$log" 9000
        printf 'ПРОКРУТКА-%s\n' "$n" >> "$log"
        run "$SELF"
        n=$(( n + 1 ))
    done
    if [ -f "$log.1" ] && [ -f "$log.2.gz" ] && [ -f "$log.3.gz" ] \
       && [ ! -e "$log.4.gz" ] && [ ! -e "$log.4" ] \
       && grep -q 'ПРОКРУТКА-5' "$log.1" \
       && gzip -cd "$log.2.gz" | grep -q 'ПРОКРУТКА-4'; then
        printf '  ✓ хранится ровно 3 копии, старое уходит, несвежие сжаты\n'
    else
        red "  ✗ глубина хранения обязана быть конечной, а копии — сжатыми"
        ls -1 "$tmp" | sed 's/^/      /' >&2
        bad=1
    fi

    # Случай 5: права нового журнала — прежние. Журнал ячейки открывать шире,
    # чем он был, прокрутка не вправе: в нём вывод задач, ходящих в базу.
    rm -f "$log".[0-9]*
    fill "$log" 9000
    chmod 640 "$log"
    run "$SELF"
    if [ "$(mode_of "$log")" = 640 ]; then
        printf '  ✓ новый журнал родился с прежними правами (640)\n'
    else
        red "  ✗ права нового журнала разъехались с прежними: $(mode_of "$log") вместо 640"
        bad=1
    fi

    # Случай 6: прокрутить нечем — отказ СЛОВАМИ и ненулевым кодом, а не
    # тихий ноль. Под root биты прав не спрашивают, и случай честно
    # пропускается: молчаливое «зелено» здесь было бы хуже пропуска.
    if [ "$(id -u)" = 0 ]; then
        printf '  · случай «каталог без права записи» пропущен: под root права не спрашивают\n'
    else
        mkdir -p "$tmp/tolko-chtenie"
        fill "$tmp/tolko-chtenie/parts-backup.log" 9000
        chmod 500 "$tmp/tolko-chtenie"
        set +e
        out=$(ROTATE_LIMIT_BYTES=8192 ROTATE_KEEP=3 bash "$SELF" \
              "$tmp/tolko-chtenie/parts-backup.log" 2>&1); rc=$?
        set -e
        chmod 700 "$tmp/tolko-chtenie"
        if [ "$rc" != 0 ] && grep -q 'прокрутить его нечем' <<<"$out"; then
            printf '  ✓ нет прав на каталог — отказ словами и ненулевой код\n'
        else
            red "  ✗ невозможность прокрутки обязана называться, а не молчать (код $rc)"
            printf '%s\n' "$out" | sed 's/^/      /' >&2
            bad=1
        fi
    fi

    # Случай 7: сжать прошлую копию нечем — так выглядит кончившийся диск,
    # то есть ровно та беда, ради которой прокрутка и заведена. Поколение
    # журнала обязано остаться на месте, прокрутка — не состояться, отказ —
    # назваться словами. Прежняя редакция здесь печатала ЗЕЛЁНОЕ «журнал
    # прокручен», потеряв `.1` и не создав `.2.gz`.
    rm -f "$log".[0-9]*
    fill "$log" 9000
    run "$SELF"                                   # первая прокрутка: появилась .1
    printf 'МЕТКА-ПОКОЛЕНИЯ\n' >> "$log.1"
    fill "$log" 9000
    mkdir -p "$tmp/bez-gzip"
    printf '#!/usr/bin/env bash\nexit 1\n' > "$tmp/bez-gzip/gzip"
    chmod +x "$tmp/bez-gzip/gzip"
    set +e
    out=$(PATH="$tmp/bez-gzip:$PATH" ROTATE_LIMIT_BYTES=8192 ROTATE_KEEP=3 \
          bash "$SELF" "$log" 2>&1); rc=$?
    set -e
    if [ "$rc" != 0 ] && grep -q 'не сжать' <<<"$out" \
       && grep -q 'МЕТКА-ПОКОЛЕНИЯ' "$log.1" 2>/dev/null \
       && [ ! -e "$log.2.gz" ] && [ ! -e "$log.2.gz.tmp" ]; then
        printf '  ✓ сжать нечем — поколение журнала цело, отказ назван, код ненулевой\n'
    else
        red "  ✗ отказ gzip обязан сохранить поколение и назваться, а не печатать «прокручен» (код $rc)"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=1
    fi

    # Случай 8: права нового журнала не выставились. Прокрутка при этом
    # состоялась — и зелёная строка про неё правдива, — а вот инвариант
    # случая 5 («шире прежних открывать нельзя») нет. Значит красное и
    # ненулевой код, а не тихий ноль под зелёной строкой.
    rm -f "$log".[0-9]*
    fill "$log" 9000
    mkdir -p "$tmp/bez-chmod"
    printf '#!/usr/bin/env bash\nexit 1\n' > "$tmp/bez-chmod/chmod"
    chmod +x "$tmp/bez-chmod/chmod"
    set +e
    out=$(PATH="$tmp/bez-chmod:$PATH" ROTATE_LIMIT_BYTES=8192 ROTATE_KEEP=3 \
          bash "$SELF" "$log" 2>&1); rc=$?
    set -e
    if [ "$rc" != 0 ] && grep -q 'права нового журнала не выставлены' <<<"$out"; then
        printf '  ✓ права не выставились — сказано словами и код ненулевой\n'
    else
        red "  ✗ невыставленные права обязаны называться и менять код возврата (код $rc)"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=1
    fi

    # ── Отчёт говорит о результате, а не о запуске (задача 0240) ──────────────
    # Подготовка второго поколения: после неё на диске есть `.1`, который
    # следующая прокрутка сожмёт, — на этом пути и стоит проверка содержимого.
    second_generation() {
        rm -f "$log".[0-9]*
        fill "$log" 9000
        run "$SELF"                      # первая прокрутка: появилась .1
        printf 'МЕТКА-ПОКОЛЕНИЯ\n' >> "$log.1"
        fill "$log" 9000
    }

    # Случай 10: отметка. Здоровые проходы — и «трогать нечего», и «прокручен» —
    # кладут её в нужное место; отказные не кладут вовсе.
    rm -f "$log".[0-9]*; fill "$log" 1000; : > "$CURL_LOG"
    run "$SELF"
    n_under=$(grep -c 'metrics/job/logrotate .*partsflow_log_rotate_success_timestamp_seconds' "$CURL_LOG" || true)
    rm -f "$log".[0-9]*; fill "$log" 9000; : > "$CURL_LOG"
    run "$SELF"
    n_rot=$(grep -c 'metrics/job/logrotate .*partsflow_log_rotate_success_timestamp_seconds' "$CURL_LOG" || true)
    if [ "$n_under" = 1 ] && [ "$n_rot" = 1 ]; then
        printf '  ✓ отметка ставится на здоровом проходе: и когда трогать нечего, и после прокрутки\n'
    else
        red "  ✗ отметка обязана уйти ровно раз на каждом здоровом проходе (под пределом: ${n_under:-0}, после прокрутки: ${n_rot:-0})"
        bad=1
    fi

    # Случай 11: pushgateway не ответил — прокрутка состоялась, код нулевой,
    # но об отметке сказано словами.
    rm -f "$log".[0-9]*; fill "$log" 9000
    CURL_RC=1 run "$SELF"
    if [ "$rc" = 0 ] && [ -f "$log.1" ] && grep -q 'отметка прокрутки в наблюдение не ушла' <<<"$out"; then
        printf '  ✓ наблюдение молчит — журнал прокручен, об отметке сказано, код нулевой\n'
    else
        red "  ✗ недоступный pushgateway не должен ронять прокрутку и не должен молчать (код $rc)"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=1
    fi

    # Случай 12: `gzip` отвечает кодом 0 и ничего не пишет (кончающийся диск,
    # подмена утилиты). Прежняя редакция снесла `.1` — единственный экземпляр
    # поколения — и напечатала «прокручен». Теперь: красное, поколение на месте,
    # отметки нет.
    second_generation
    mkdir -p "$tmp/gzip-nol"
    printf '#!/usr/bin/env bash\nexit 0\n' > "$tmp/gzip-nol/gzip"
    chmod +x "$tmp/gzip-nol/gzip"
    : > "$CURL_LOG"
    set +e
    out=$(PATH="$tmp/gzip-nol:$PATH" ROTATE_LIMIT_BYTES=8192 ROTATE_KEEP=3 \
          bash "$SELF" "$log" 2>&1); rc=$?
    set -e
    if [ "$rc" != 0 ] && grep -q 'не совпала с оригиналом' <<<"$out" \
       && grep -q 'МЕТКА-ПОКОЛЕНИЯ' "$log.1" 2>/dev/null \
       && [ ! -e "$log.2.gz" ] && [ ! -e "$log.2.gz.tmp" ] && [ ! -s "$CURL_LOG" ]; then
        printf '  ✓ gzip «успешно» ничего не записал — поколение цело, копия не принята, отметки нет\n'
    else
        red "  ✗ неразжимаемая копия обязана остановить прокрутку до удаления исходника (код $rc)"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=1
    fi

    # Случай 13: `stat` не отвечает ни в одной форме. Режим не выдумывается:
    # красное словами, журнал не тронут, отметки нет.
    rm -f "$log".[0-9]*; fill "$log" 9000
    mkdir -p "$tmp/stat-nol"
    printf '#!/usr/bin/env bash\nexit 1\n' > "$tmp/stat-nol/stat"
    chmod +x "$tmp/stat-nol/stat"
    : > "$CURL_LOG"
    set +e
    out=$(PATH="$tmp/stat-nol:$PATH" ROTATE_LIMIT_BYTES=8192 ROTATE_KEEP=3 \
          bash "$SELF" "$log" 2>&1); rc=$?
    set -e
    if [ "$rc" != 0 ] && grep -q 'права журнала узнать не удалось' <<<"$out" \
       && [ ! -e "$log.1" ] && [ "$(size_of "$log")" -ge 8192 ] && [ ! -s "$CURL_LOG" ]; then
        printf '  ✓ stat не ответил — права не выдуманы: отказ словами, журнал не тронут, отметки нет\n'
    else
        red "  ✗ при отказе обоих stat режим выдумывать нельзя (код $rc)"
        printf '%s\n' "$out" | sed 's/^/      /' >&2
        bad=1
    fi

    # Случай 14: отказные пути прежних случаев (нет права на каталог, gzip
    # отказал, chmod отказал) отметки не ставят — она означает «получилось».
    rm -f "$log".[0-9]*; fill "$log" 9000
    : > "$CURL_LOG"
    set +e
    out=$(PATH="$tmp/bez-chmod:$PATH" ROTATE_LIMIT_BYTES=8192 ROTATE_KEEP=3 \
          bash "$SELF" "$log" 2>&1); rc=$?
    set -e
    if [ "$rc" != 0 ] && [ ! -s "$CURL_LOG" ]; then
        printf '  ✓ прокрутка с невыставленными правами отметки не ставит\n'
    else
        red "  ✗ красный проход не вправе ставить отметку «получилось» (код $rc)"
        bad=1
    fi

    # Возвраты дефекта по трём новым защитам. Каждая подделка меняет ОДНУ
    # строку по якорю; `cmp` ловит промах якоря, `bash -n` — сломанную копию:
    # красное от сломанной копии и красное от снятой проверки — разные вещи.
    fake_run() {  # $1 — копия; вывод в out, код в rc
        set +e
        out=$(ROTATE_LIMIT_BYTES=8192 ROTATE_KEEP=3 bash "$1" "$log" 2>&1); rc=$?
        set -e
    }
    mkfake() {  # $1 — выражение sed, $2 — файл копии
        sed "$1" "$SELF" > "$2"
        if cmp -s "$SELF" "$2"; then
            red "  ✗ подделку собрать не удалось — якорь в скрипте изменился: $1"; bad=1; return 1
        fi
        if ! bash -n "$2" 2>/dev/null; then
            red "  ✗ подделка сломала синтаксис — её красное говорило бы не о том: $1"; bad=1; return 1
        fi
    }
    # Содержимое копии не проверяется → копия гзипа-нулевика молча сносит поколение.
    if mkfake 's#^        if \[ ! -s "\$log.2.gz.tmp" \] .*; then$#        if false; then#' "$tmp/bez-sverki.sh"; then
        second_generation
        set +e
        out=$(PATH="$tmp/gzip-nol:$PATH" ROTATE_LIMIT_BYTES=8192 ROTATE_KEEP=3 \
              bash "$tmp/bez-sverki.sh" "$log" 2>&1); rc=$?
        set -e
        if ! grep -q 'МЕТКА-ПОКОЛЕНИЯ' "$log.1" 2>/dev/null \
           && ! gzip -dc "$log.2.gz" 2>/dev/null | grep -q 'МЕТКА-ПОКОЛЕНИЯ'; then
            printf '  ✓ возврат дефекта: без сверки содержимого поколение журнала теряется молча\n'
        else
            red "  ✗ без сверки содержимого поколение обязано потеряться — иначе случай 12 ничего не стережёт"
            bad=1
        fi
    fi
    # Режим выдумывается → отказ stat проходит с кодом 0.
    if mkfake "s#^mode_of() { stat -c '%a' \"\$1\" 2>/dev/null || stat -f '%Lp' \"\$1\" 2>/dev/null; }\$#mode_of() { stat -c '%a' \"\$1\" 2>/dev/null || stat -f '%Lp' \"\$1\" 2>/dev/null || printf '600'; }#" "$tmp/s-vydumkoy.sh"; then
        rm -f "$log".[0-9]*; fill "$log" 9000
        set +e
        out=$(PATH="$tmp/stat-nol:$PATH" ROTATE_LIMIT_BYTES=8192 ROTATE_KEEP=3 \
              bash "$tmp/s-vydumkoy.sh" "$log" 2>&1); rc=$?
        set -e
        if [ "$rc" = 0 ] && [ -f "$log.1" ]; then
            printf '  ✓ возврат дефекта: с выдуманным режимом отказ stat проходит под нулевым кодом\n'
        else
            red "  ✗ с выдуманным режимом отказ stat обязан пройти молча — иначе случай 13 ничего не стережёт (код $rc)"
            bad=1
        fi
    fi
    # Отметка не ставится вовсе → случай 10 краснеет.
    if mkfake 's#^        send_mark$#        : отметки нет#' "$tmp/bez-otmetki.sh"; then
        rm -f "$log".[0-9]*; fill "$log" 9000; : > "$CURL_LOG"
        fake_run "$tmp/bez-otmetki.sh"
        if [ ! -s "$CURL_LOG" ]; then
            printf '  ✓ возврат дефекта: без вызова send_mark наблюдение остаётся пустым\n'
        else
            red "  ✗ копия без вызова отметки обязана оставить наблюдение пустым"
            bad=1
        fi
    fi

    # Случай 9 — возврат дефекта: копия скрипта со снятой прокруткой обязана
    # МОЛЧА дать журналу расти. Без этого случая нельзя утверждать, что
    # зелёные строки выше краснеют именно из-за прокрутки, а не из-за
    # чего-нибудь соседнего.
    #
    # Подделка снимает ВЫЗОВ прокрутки целиком, а не одну её строку, — и это
    # не лень, а точность: снятое `mv` оставило бы `: > "$log"`, то есть
    # журнал не «рос бы дальше», а обнулялся. Это другой дефект, и притом
    # худший. Снятый вызов воспроизводит ровно сегодняшнее состояние `main`:
    # прокрутки нет вовсе, журнал растёт.
    rm -f "$log".[0-9]*
    sed 's|^        rotate "\$LOG"$|        : прокрутки нет|' "$SELF" > "$tmp/bez-rotatsii.sh"
    if cmp -s "$SELF" "$tmp/bez-rotatsii.sh"; then
        red "  ✗ подделку собрать не удалось — строка прокрутки в скрипте изменилась"
        bad=1
    else
        fill "$log" 9000
        set +e
        out=$(ROTATE_LIMIT_BYTES=8192 ROTATE_KEEP=3 bash "$tmp/bez-rotatsii.sh" "$log" 2>&1); rc=$?
        set -e
        if [ "$(size_of "$log")" -ge 8192 ] && [ ! -f "$log.1" ]; then
            printf '  ✓ со снятой прокруткой журнал растёт дальше — краснеет именно прокрутка\n'
        else
            red "  ✗ без прокрутки журнал обязан остаться переросшим: иначе случай 2 зелен не из-за неё"
            printf '%s\n' "$out" | sed 's/^/      /' >&2
            bad=1
        fi
    fi

    [ $bad = 0 ] || { red "Самопроверка не прошла"; exit 1; }
    green "Самопроверка пройдена: прокрутка, глубина, права, отказы. Журнал ячейки не тронут."
}

case "${1:-}" in
    --selftest)
        selftest
        ;;
