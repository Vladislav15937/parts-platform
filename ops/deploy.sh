other_of() {  # app-blue → app-green
    case "$1" in
        app-blue) printf 'app-green\n' ;;
        app-green) printf 'app-blue\n' ;;
        *) return 1 ;;
    esac
}

# База сборки — у ops/switch-build.sh, и только у него: он читает её так же,
# как compose. Второе место, знающее, где искать имя базы, однажды разъехалось
# бы с первым, и выкладка заморозила бы не ту базу, в которой люди.
db_of() { "$SWITCH" --db "$1"; }

# ─────────────────────────────── операции с базой ────────────────────────────
#
# Все идут владельцем схем в служебную базу postgres: в замороженную базу
# ходить нельзя (там всё только на чтение), а базу, с которой снимают копию,
# Postgres требует оставить без единого соединения.
pg() {
    $COMPOSE exec -T postgres psql -U "${PG_USER:?}" -d postgres -v ON_ERROR_STOP=1 -tAq "$@"
}

pg_in() {  # база, SQL — спросить внутри самой базы
    $COMPOSE exec -T postgres psql -U "${PG_USER:?}" -d "$1" -v ON_ERROR_STOP=1 -tAqc "$2"
}

# Оборвать соединения базы, открытые раньше момента. «Раньше момента»,
# а не «все»: пул приложения переоткрывает соединения сразу после обрыва,
# и новые — уже с нужным умолчанием. Требовать нуля значило бы ждать вечно.
kick_db() {  # база, момент по часам сервера
    local db="$1" since="$2" left deadline
    deadline=$(( $(date +%s) + KICK_WAIT ))
    while :; do
        left=$(pg -c "SELECT count(pg_terminate_backend(pid)) FROM pg_stat_activity
                       WHERE datname = '$db' AND pid <> pg_backend_pid()
                         AND backend_start < '$since'::timestamptz") || return 1
        [ "$left" = 0 ] && return 0
        [ "$(date +%s)" -lt "$deadline" ] || {
            red "  $db: соединения, открытые до заморозки, не уходят за ${KICK_WAIT}с ($left)"
            return 1
        }
        sleep 1
    done
}

# Заморозить запись. Умолчание сессии — только для новых соединений, поэтому
# прежние обрываются, а результат проверяется попыткой: свежее соединение
# обязано ответить «только чтение». Верить команде без проверки нельзя —
# настройка роли старше настройки базы и отменила бы заморозку молча.
# Настройка роли старше настройки базы: заданное роли «read_only=off» молча
# отменило бы заморозку для рабочей роли, а проверка заморозки идёт владельцем,
# у которого своей настройки нет, — и ответила бы «заморожено». Спрашивается
# дважды: до метки (отказ там никого не задевает) и в самой заморозке.
freezable() {  # база
    local overrides
    overrides=$(pg -c "SELECT string_agg(DISTINCT pg_get_userbyid(s.setrole), ', ')
                         FROM pg_db_role_setting s, unnest(s.setconfig) c
                        WHERE s.setrole <> 0
                          AND c LIKE 'default\_transaction\_read\_only=%'
                          AND (s.setdatabase = 0
                               OR s.setdatabase = (SELECT oid FROM pg_database WHERE datname = '$1'))") || return 1
    if [ -n "$overrides" ]; then
        red "  $1: у ролей ($overrides) своя настройка default_transaction_read_only — она старше"
        red "  настройки базы и отменила бы заморозку. Снимите: ALTER ROLE … RESET default_transaction_read_only"
        return 1
    fi
}

freeze_db() {  # база
    local db="$1" since ro
    freezable "$db" || return 1
    pg -c "ALTER DATABASE \"$db\" SET default_transaction_read_only = on" >/dev/null || return 1
    since=$(pg -c "SELECT clock_timestamp()") || return 1
    kick_db "$db" "$since" || return 1
    ro=$(pg_in "$db" "SHOW transaction_read_only") || return 1
    if [ "$ro" != on ]; then
        red "  $db: заморозка поставлена, а новое соединение пишет (transaction_read_only=$ro)"
        return 1
    fi
    printf '  %s: запись заморожена — новые соединения только на чтение, прежние оборваны\n' "$db"
}

# Открыть запись. Тоже с обрывом: соединение, открытое во время заморозки,
# так и осталось бы «только на чтение» до конца своей жизни в пуле.
unfreeze_db() {  # база
    local db="$1" since ro
    pg -c "ALTER DATABASE \"$db\" ALLOW_CONNECTIONS true" >/dev/null || return 1
    pg -c "ALTER DATABASE \"$db\" RESET default_transaction_read_only" >/dev/null || return 1
    since=$(pg -c "SELECT clock_timestamp()") || return 1
    kick_db "$db" "$since" || return 1
    ro=$(pg_in "$db" "SHOW transaction_read_only") || return 1
    if [ "$ro" != off ]; then
        red "  $db: заморозка снята, а новое соединение всё ещё только на чтение ($ro)"
        return 1
    fi
    printf '  %s: запись открыта\n' "$db"
}

unfreeze_if_frozen() {  # база
    local db="$1" frozen allowed
    frozen=$(pg -c "SELECT count(*) FROM pg_db_role_setting s
                      JOIN pg_database d ON d.oid = s.setdatabase, unnest(s.setconfig) c
                     WHERE d.datname = '$db' AND s.setrole = 0
                       AND c = 'default_transaction_read_only=on'") || return 1
    allowed=$(pg -c "SELECT datallowconn FROM pg_database WHERE datname = '$db'") || return 1
    if [ "$frozen" = 0 ] && [ "$allowed" = t ]; then
        printf '  %s: не заморожена — делать нечего\n' "$db"
        return 0
    fi
    unfreeze_db "$db"
}

# Хватит ли места и не помешает ли что-нибудь — ДО заморозки: отказ здесь
# никого не задевает, отказ посреди копии задевает всех.
check_copy_room() {  # источник, копия
    local src="$1" dst="$2" exists dumps size free need
    exists=$(pg -c "SELECT count(*) FROM pg_database WHERE datname = '$src'") || return 1
    [ "$exists" = 1 ] || { red "  Базы $src нет — непонятно, с чего снимать копию"; return 1; }
    exists=$(pg -c "SELECT count(*) FROM pg_database WHERE datname = '$dst'") || return 1
    [ "$exists" = 0 ] || {
        red "  База $dst уже есть — копию прошлой выкладки не убрали. ops/deploy.sh --abort"
        return 1
    }
    # Копия требует базу без единого соединения, то есть оборвала бы идущий
    # дамп — ночной бэкап отчитался бы провалом, а утром никто не понял бы почему.
    dumps=$(pg -c "SELECT count(*) FROM pg_stat_activity
                    WHERE datname = '$src' AND application_name IN ('pg_dump', 'pg_restore')") || return 1
    [ "$dumps" = 0 ] || { red "  С базы $src сейчас снимают дамп ($dumps) — копия его оборвала бы. Повторите после бэкапа"; return 1; }
    freezable "$src" || return 1
    size=$(pg -c "SELECT pg_database_size('$src')") || return 1
    free=$($COMPOSE exec -T postgres df -Pk /var/lib/postgresql/data | awk 'NR == 2 { printf "%.0f", $4 * 1024 }') || return 1
    # Пятая часть сверху — под WAL, который пишется рядом всё время выкладки,
    # и под новые changeset'ы на копии.
    need=$(( size + size / 5 ))
    if [ "${free:-0}" -lt "$need" ]; then
        red "  Места под копию нет: база $src — $(( size / 1048576 )) МБ, нужно $(( need / 1048576 )) МБ, свободно $(( ${free:-0} / 1048576 )) МБ"
        return 1
    fi
    printf '  база %s — %s МБ, свободно %s МБ\n' "$src" "$(( size / 1048576 ))" "$(( free / 1048576 ))"
}

# Снять копию. Шаблоном, а не дампом: физическая копия файлов переносит всё —
# схемы, права, последовательности на их нынешнем значении, — и не зависит
# от того, всё ли умеет разворот. Цена — источник на время копирования
# остаётся без соединений (чтение ждёт секунды), поэтому снимается она
# с уже замороженной базы, и отказ на любом месте открывает соединения обратно.
# FILE_COPY, а не WAL_LOG: второй пишет всю базу в журнал, то есть в архив
# точки возврата на каждой выкладке.
copy_db() {  # источник, копия
    local src="$1" dst="$2" owner rc=0 started kill_all
    owner=$(pg -c "SELECT pg_get_userbyid(datdba) FROM pg_database WHERE datname = '$src'") || return 1
    [ -n "$owner" ] || { red "  Базы $src нет"; return 1; }
    started=$(date +%s)
    pg -c "ALTER DATABASE \"$src\" ALLOW_CONNECTIONS false" >/dev/null || return 1
    kill_all=$(pg -c "SELECT clock_timestamp() + interval '1 day'") || rc=1
    [ "$rc" = 0 ] && { kick_db "$src" "$kill_all" || rc=1; }
    if [ "$rc" = 0 ]; then
        pg -c "CREATE DATABASE \"$dst\" WITH TEMPLATE \"$src\" OWNER \"$owner\" STRATEGY FILE_COPY" >/dev/null || rc=1
    fi
    pg -c "ALTER DATABASE \"$src\" ALLOW_CONNECTIONS true" >/dev/null || {
        red "  $src: соединения обратно не открылись — ячейка не читает. ops/deploy.sh --abort"
        rc=1
    }
    [ "$rc" = 0 ] || return 1

    # Права на базу и её настройки не едут с шаблоном — они живут в общем
    # каталоге кластера. Без права CONNECT рабочая роль не вошла бы в копию
    # вовсе. Заморозку источника не переносим: копия замораживается сама,
    # своим шагом.
    $COMPOSE exec -T postgres psql -U "$PG_USER" -d postgres -v ON_ERROR_STOP=1 -q \
        -v src="$src" -v dst="$dst" >/dev/null <<'SQL' || return 1
SELECT format('REVOKE ALL ON DATABASE %I FROM PUBLIC', :'dst') \gexec
SELECT format('GRANT %s ON DATABASE %I TO %s', a.privilege_type, :'dst',
              CASE WHEN a.grantee = 0 THEN 'PUBLIC' ELSE quote_ident(pg_get_userbyid(a.grantee)) END)
  FROM pg_database d, aclexplode(COALESCE(d.datacl, acldefault('d', d.datdba))) a
 WHERE d.datname = :'src' AND a.grantee <> d.datdba \gexec
SELECT CASE WHEN s.setrole = 0
            THEN format('ALTER DATABASE %I SET %s', :'dst', c)
            ELSE format('ALTER ROLE %I IN DATABASE %I SET %s', pg_get_userbyid(s.setrole), :'dst', c)
       END
  FROM pg_db_role_setting s JOIN pg_database d ON d.oid = s.setdatabase, unnest(s.setconfig) AS c
 WHERE d.datname = :'src' AND c NOT LIKE 'default\_transaction\_read\_only=%' \gexec
SQL
    printf '  %s → %s за %s с, соединения источника открыты\n' "$src" "$dst" "$(( $(date +%s) - started ))"
}

# Удалять выкладка вправе только не свою рабочую базу. Проверка отдельной
# функцией — её самопроверка зовёт напрямую, без docker.
drop_guard() {  # база, база под трафиком
    if [ "$1" = "$2" ]; then
        red "  ОТКАЗ: $1 — база сборки под трафиком, в ней люди. Удалять её выкладка не вправе"
        return 1
    fi
}

drop_db() {  # база
    local db="$1" active
    active=$("$SWITCH" --current-db) || { red "  Не узнать базу под трафиком — ничего не удаляю"; return 1; }
    drop_guard "$db" "$active" || return 1
    pg -c "DROP DATABASE IF EXISTS \"$db\" WITH (FORCE)" >/dev/null || return 1
    printf '  %s удалена\n' "$db"
}

# «Базы нет» и «не спросить» — разные ответы, и второй не повод молча решить,
# что удалять нечего.
db_exists() {  # база: 0 — есть, 1 — нет, 2 — не спросить
    local n
    n=$(pg -c "SELECT count(*) FROM pg_database WHERE datname = '$1'") || return 2
    [ "$n" = 1 ]
}

# ──────────────── отметки бэкапа: снялся ли он по НОВОЙ базе ─────────────────
#
# Решение владельца от 15 сентября 2026 (задача 0117): прежнюю базу удаляем
# после самопроверок выкладки И после того, как по сменившей её базе снялся
# бэкап — ночной дамп и базовая копия для точки возврата (так звучало само
# решение; чем считается «бэкап» у ворот удаления с 28 сентября 2026 — абзацем
# ниже). Спрашиваем у самих
# отметок, а не у расписания: «задача стоит в cron» и «бэкап по ЭТОЙ базе
# снялся» — разные утверждения, и вторым отвечает только отметка. Имя базы
# в отметку ночного дампа кладёт ops/backup.sh — без него «бэкап снят»
# означало бы в том числе бэкап позавчерашней базы, снятый до выкладки.
#
# С 28 сентября 2026 (задача 0214, вариант Б) ворота удаления спрашивают ОДНО:
# снялся ли ночной дамп по базе-сменщице. Базовая копия рядом НАЗЫВАЕТСЯ —
# её время видно человеку, — но ворот не держит: она про точку возврата,
# и точку возврата эти ворота не охраняют по построению (довод — в шапке
# файла, «БЭКАПОМ ЗДЕСЬ СЧИТАЕТСЯ НОЧНОЙ ДАМП»).
pushgateway_url() {
    local url port
    url="${PUSHGATEWAY_URL:-$(read_env PUSHGATEWAY_URL)}"
    if [ -z "$url" ]; then
        port=$(read_env PUSHGATEWAY_PORT)
        url="http://localhost:${port:-9091}"
    fi
    printf '%s' "$url"
}

marks() { curl -sf --max-time 10 "$(pushgateway_url)/metrics"; }

# Значение приезжает числом с плавающей точкой: 1757894400 pushgateway отдаёт
# как «1.7578944e+09», и сравнение таких строк оболочкой дало бы «бэкапа нет»
# при снятом бэкапе. Приводит awk.
#
# LC_ALL=C у awk — не аккуратность, а починка настоящего отказа. В локали
# с запятой в дробях (ru_RU.UTF-8 на русском сервере — обычное дело) strtod
# читает «1.757e+09» как 1: оба времени становятся единицами, сравнение
# «базовая копия старше дампа» даёт ложь, и прежняя база удаляется при
# бэкапе, которого нет. Поймано прогоном самопроверки под ru_RU.UTF-8;
# в локали по умолчанию всё зелено.
# Берётся САМАЯ СВЕЖАЯ отметка, а не последняя напечатанная. Сегодня под каждое
# выражение подходит ровно одна строка — у дампа выражение пришпилено
# к db="…", у базовой копии метка одна на всю ячейку, — но это свойство
# ДАННЫХ, а не проверки: появится вторая строка того же семейства, и tail -n1
# ответит «последняя в выводе» вместо «самая новая». Ответ при этом уедет
# в любую сторону, в том числе в опасную (задача 0214, пункт 6).
mark_ts() {  # текст отметок, регулярное выражение строки
    printf '%s\n' "$1" | grep -v '^#' | grep -E -- "$2" \
        | LC_ALL=C awk '{ v = $NF + 0; if (v > max) max = v } END { if (max > 0) printf "%.0f\n", max }'
}

when() {  # время в секундах — человеку
    date -r "$1" '+%d.%m %H:%M' 2>/dev/null || date -d "@$1" '+%d.%m %H:%M' 2>/dev/null || printf '%s' "$1"
}

# ВОРОТА УДАЛЕНИЯ прежней базы — и только они. Вопрос, на который отвечает эта
# функция, один: есть ли полная копия данных на момент переключения где-нибудь,
# кроме самой прежней базы. Отвечает на него ночной дамп по её сменщице —
# копия снята с прежней побайтово (CREATE DATABASE … TEMPLATE), то есть всё,
# что лежало в прежней базе, лежит и в сменщице, а дамп по сменщице этим
# и покрыт. Точку возврата эта функция не охраняет и охранять не может.
#
# Кто её зовёт — перебирает самопроверка (covers_callers), а не список
# в чьей-то памяти: вариант Б задачи 0214 снял требование базовой копии ТОЛЬКО
# у ворот удаления, и появившийся третий зовущий получил бы это ослабление
# молча вместе с именем функции.
backup_covers() {  # база-сменщица: 0 — прежнюю можно удалять, 1 — нельзя
    local db="$1" text dump base
    text=$(marks) || {
        red "  Отметок бэкапа не спросить ($(pushgateway_url)/metrics) — считаю, что бэкапа нет"
        return 1
    }
    dump=$(mark_ts "$text" "^partsflow_backup_success_timestamp_seconds[{][^}]*db=\"${db}\"")
    if [ -z "$dump" ]; then
        red "  Ночного дампа ПО БАЗЕ $db в отметках нет: ops/backup.sh либо не отработал"
        red "  после переключения на неё, либо на ячейке стоит его редакция без имени базы"
        # Чей дамп в отметках всё-таки есть — числами: обычно это база ДО
        # выкладки, и тогда вопрос не «сломан ли бэкап», а «отработал ли он
        # хоть раз после переключения». Без этих строк «дампа нет» не говорит,
        # сколько ждать (задача 0195).
        local others odb ots
        # Имя базы и значение берутся РАЗНЫМИ разборами: значение — последнее
        # поле строки, имя — из db="…". Первая редакция делила строку
        # по `db="`, и тогда «последним полем» оказывалось имя базы вместе
        # с хвостом метки: %.0f печатал 0, а `when` показывал 01.01 07:00 —
        # то есть время дампа приезжало человеку неправдой. Поймано живым
        # прогоном на стенде.
        others=$(printf '%s\n' "$text" | grep -v '^#' \
            | grep -E '^partsflow_backup_success_timestamp_seconds[{][^}]*db="' \
            | LC_ALL=C awk '{ value = $NF; split($0, a, "db=\""); split(a[2], b, "\"");
                              printf "%s %.0f\n", b[1], value }')
        if [ -n "$others" ]; then
            printf '%s\n' "$others" | while read -r odb ots; do
                red "  в отметках есть дамп по базе $odb — $(when "$ots")"
            done
        else
            red "  дампов ни по одной базе в отметках нет вовсе — ops/backup.sh не отрабатывал"
        fi
        return 1
    fi
    printf '  бэкап по %s снят: ночной дамп %s\n' "$db" "$(when "$dump")"
    # Базовая копия физическая и про базы не знает вовсе, поэтому «содержит
    # новую базу» устанавливалось бы только временем. Ворот она больше
    # не держит (решение владельца от 28 сентября 2026, задача 0214), но
    # НАЗЫВАЕТСЯ: её время — это то, чем человек отвечает себе на вопрос про
    # точку возврата, и молчать о ней значило бы прятать вторую половину
    # состояния бэкапа.
    base=$(mark_ts "$text" "^partsflow_basebackup_success_timestamp_seconds[{ ]")
    if [ -z "$base" ]; then
        red "  Базовой копии кластера не снимали вовсе (ops/basebackup.sh): архив WAL"
        red "  накатывать не на что, то есть точки возврата у ячейки нет. Удаления прежней"
        red "  базы это не держит — её данные покрыты дампом выше, — но чинить надо:"
        red "  об этом же говорит тревога БазоваяКопияНеСнималась."
    elif [ "$base" -lt "$dump" ]; then
        printf '  базовая копия (%s) старше этого дампа — на удаление это не влияет:\n' "$(when "$base")"
        printf '  старой копии плюс архив WAL хватает, чтобы воссоздать базу, появившуюся\n'
        printf '  после неё (замер 28 сентября 2026, задача 0214)\n'
    else
        printf '  базовая копия %s — свежее дампа\n' "$(when "$base")"
    fi
    return 0
}

# Кто зовёт ворота удаления — спрашивается у самого файла. Перебором, а не
# списком: список стареет молча, и ровно молча получил бы ослабление варианта Б
# новый зовущий (задача 0214, пункт 9 приёмки). Имя функции передаётся
# аргументом, а не пишется здесь литералом: литерал в этом теле сделал бы саму
# проверку своим же зовущим. Самопроверка (случай 17) сверяет ответ с названным
# перечнем, у каждого — причина «оно про удаление или про точку возврата».
#
# ТЕЛО САМОПРОВЕРКИ ПРОПУСКАЕТСЯ, А НЕ ОБРЫВАЕТ РАЗБОР, и это не оформление.
# Первая редакция делала на заголовке `selftest()` `exit`, то есть не видела
# ничего, что стоит НИЖЕ её тела, — а там верхнеуровневый диспетчер
# (`if [ -n "$DROP_PREV" ]; then drop_previous_now …`). Зовущий, дописанный
# туда, проходил самопроверку молча: разбор PR #319 поставил его попыткой
# и получил зелёное, включая случай «ВОРОТА УДАЛЕНИЯ ЗОВУТ ТОЛЬКО НАЗВАННЫЕ».
# Пропускать тело при этом всё равно надо — внутри лежат имена случаев
# и программы подделок, то есть литералы, от которых самопроверка стала бы
# своим же зовущим. Поэтому разбор возобновляется на закрывающей скобке
# функции (строка ровно «}», как у всех функций этого файла), а код вне
# функций числится «(верхний-уровень)» и в перечень законных зовущих
# не входит — то есть ловится.
#
# ЦЕНА ПРИЁМА: «}» в нулевой колонке ВНУТРИ тела selftest() ломает
# возобновление, и самопроверка краснеет составом зовущих на здоровом файле.
# Предупреждение об этом стоит первой строкой самого selftest() — там, где
# работает тот, кто вставляет в него heredoc или JSON; сюда он не заглянет,
# а правило нужно ему, а не читателю сторожа.
covers_callers() {  # файл, имя функции ворот → имена зовущих функций
    awk -v pat="$2" '
        BEGIN              { fn = "(верхний-уровень)" }
        /^selftest\(\) \{/ { skip = 1; next }
        skip && /^\}$/     { skip = 0; fn = "(верхний-уровень)"; next }
        skip               { next }
        /^[a-z_]+\(\) \{/  { fn = $1; sub(/\(\).*/, "", fn) }
        /^\}$/             { fn = "(верхний-уровень)"; next }
        $0 ~ pat           { if ($0 !~ /^[[:space:]]*#/) print fn }
    ' "$1" | sort -u
}

# ───────────── какие базы лежат в ячейке и кто они (задача 0195) ─────────────
#
# ЗАЧЕМ. Инструменты ячейки знают ровно две базы — названные в .env
# (APP_DB_BLUE, APP_DB_GREEN): бэкап и его проверка берут базу сборки под
# трафиком (ops/switch-build.sh --current-db), выкладка получает ОДНОГО
# кандидата на удаление (db_of выкладываемой сборки), а перечисления баз
# не делал никто. То, что не названо ключом, для ячейки не существовало
# вовсе — ни в одном скрипте, ни в метриках, ни в тревогах.
#
# Наблюдение на боевой ячейке 26 сентября 2026: рядом с живой базой лежат ДВЕ
# замороженные, и одну из них назвать нельзя ничем — она не база под трафиком,
# не база второй сборки и не копия идущей выкладки. Занимает она столько же,
# сколько живая, а кончившийся диск останавливает Postgres, а с ним архив WAL
# и точку возврата ВСЕХ арендаторов ячейки. Вторая сторона тише и хуже:
# посторонняя замороженная база выглядит как данные, и тот, кто придёт
# разбираться в аварию, будет решать, какая из трёх настоящая, — а ответ живёт
# в .env и в deploy-history.log, не в самой базе.
#
# КАК БАЗА СТАНОВИТСЯ ПОСТОРОННЕЙ — видно в самой выкладке, и это не догадка.
# Шаг 2 переписывает ключ .env выкладываемой сборки на копию, а шаг 11 удаляет
# прежнюю базу той же сборки ТОЛЬКО если по её сменщице снялся ночной дамп
# (условие 0117). До задачи 0214 требовалась ещё базовая копия свежее этого
# дампа, и тогда условие не выполнялось почти никогда — базовая копия
# недельная, а дамп обновляется каждую ночь; так и появились посторонние базы,
# по одной на выкладку. Значит ровно в ту минуту, когда база остаётся лежать,
# её перестаёт называть что-либо: имя живёт в переменной этой выкладки
# и никуда больше не пишется, а следующая выкладка назовёт прежней базой уже
# другую. Поэтому шаг 11 говорит об этом вслух, а перечень ниже отвечает
# на вопрос «что вообще лежит в ячейке» в любую другую минуту.
#
# ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО. Удаления посторонней базы: «дать признак и имя,
# а не автоматическое удаление» — задача 0195 дословно; ночная задача,
# удаляющая базы, по-прежнему заводится решением оператора с открытыми глазами
# (docs/deployment.md). И счёта места с порогом тревоги: это задача 0089.

# Рабочая база недельной проверки бэкапа лежит в ячейке МЕЖДУ прогонами —
# ops/verify-backup.sh пересоздаёт её в начале своей работы, — и объявить её
# посторонней значило бы кричать «волк» каждую неделю. Ложная тревога здесь
# дороже пропуска: на неё натыкаются при каждой выкладке, а кончается это тем,
# что перечень перестают читать. Имя берётся из самого скрипта, чтобы второго
# места с этим именем не появилось; не прочиталось — оставшаяся база честно
# назовётся посторонней, и это лучше, чем считать своей любую незнакомую.
verify_check_db() {
    sed -n 's/^CHECK_DB="\{0,1\}\([A-Za-z0-9_]\{1,\}\)"\{0,1\}$/\1/p' ops/verify-backup.sh 2>/dev/null | head -n1
}

# С какого числа база не принимает работу. У Postgres этого не спросить —
# времени создания базы он не хранит вовсе, — а в журнале выкладок оно есть:
# запись несёт поле «база: <источник> → <копия>», и выкладка, снявшая копию
# С ЭТОЙ базы, и есть та минута, когда работа ушла в другую. Табуляция в конце
# образца обязательна: без неё «→ parts_green_abc» совпало бы и со строкой
# про parts_green_abc_2.
history_when() {  # имя базы → когда с неё сняли копию
    [ -f "$HISTORY" ] || return 0
    grep -F "база: $1 →" "$HISTORY" | tail -n1 | cut -f1
}

history_born() {  # имя базы → когда её завели копией
    [ -f "$HISTORY" ] || return 0
    grep -F "$(printf '→ %s\t' "$1")" "$HISTORY" | tail -n1 | cut -f1
}

# Выдуманная дата хуже отсутствующей: «остаётся до бэкапа» без числа
# не отвечает на вопрос «это неделя или месяц», а неверное число отвечает
# на него неправдой.
since_words() {  # имя базы
    local left born
    left=$(history_when "$1")
    born=$(history_born "$1")
    if [ -n "$left" ]; then
        printf 'Работу она не принимает с %s — с той выкладки, что сняла с неё копию (%s).' "$left" "$HISTORY"
    elif [ -n "$born" ]; then
        printf 'Заведена копией выкладки %s; записи о выводе из работы в %s нет.' "$born" "$HISTORY"
    else
        printf 'С какого числа она не в работе — в %s записи нет, сказать нечем.' "$HISTORY"
    fi
}

# Сырой перечень баз кластера. Отдельно от разбора намеренно: «кто есть кто» —
# это логика, и проверяется она самопроверкой на подложенной таблице, без
# docker и без ячейки.
db_list_raw() {
    pg -c "SELECT d.datname,
                  pg_database_size(d.oid),
                  (SELECT count(*) FROM pg_db_role_setting s, unnest(s.setconfig) c
                    WHERE s.setdatabase = d.oid AND s.setrole = 0
                      AND c = 'default_transaction_read_only=on'),
                  d.datallowconn,
                  (SELECT count(*) FROM pg_stat_activity a WHERE a.datname = d.datname)
             FROM pg_database d
            WHERE NOT d.datistemplate AND d.datname <> 'postgres'
            ORDER BY d.datname"
}

# 0 — посторонних нет, 1 — есть, 2 — перечня нет вовсе.
db_inventory_report() {  # таблица, база под трафиком, база второй сборки, копия идущей выкладки
    local text="$1" heir="$2" other="$3" copy="$4"
    local verify strangers=0 stranger_mb=0 name size frozen allowed conns state role mb
    verify=$(verify_check_db)
    printf 'Базы ячейки (служебные — postgres, template0, template1 — не перечисляются):\n'
    if [ -z "$text" ]; then
        red "  Ни одной базы не нашлось — это не ячейка"
        return 2
    fi
    while IFS='|' read -r name size frozen allowed conns; do
        [ -n "$name" ] || continue
        mb=$(( ${size:-0} / 1048576 ))
        if [ "${frozen:-0}" != 0 ]; then
            state=заморожена
        elif [ "${allowed:-t}" = f ]; then
            state="закрыта для соединений"
        else
            state=пишется
        fi
        if [ "$name" = "$heir" ]; then
            role="под трафиком — в ней люди"
        elif [ -n "$copy" ] && [ "$name" = "$copy" ]; then
            role="копия идущей выкладки"
        elif [ "$name" = "$other" ]; then
            role="база второй сборки"
        elif [ -n "$verify" ] && [ "$name" = "$verify" ]; then
            role="рабочая база проверки бэкапа (ops/verify-backup.sh) — так и должно быть"
        else  # ← эту строку целиком снимает подделка самопроверки (случай 15г)
            role="ПОСТОРОННЯЯ: не названа ни APP_DB_BLUE, ни APP_DB_GREEN"; strangers=$((strangers + 1)); stranger_mb=$(( stranger_mb + mb ))
        fi
        # Столбцами пробелами не выравниваем: printf считает БАЙТЫ, а не буквы,
        # и на «заморожена» столбец разъезжается — читается это как поломка
        # вывода. Поймано живым прогоном, а не рассуждением.
        printf '  %s — %s\n' "$name" "$role"
        printf '      %s МБ, %s, соединений %s\n' "$mb" "$state" "${conns:-?}"
        case "$role" in
            "под трафиком"*)
                [ "${frozen:-0}" = 0 ] || red "      запись заморожена, а в базе люди: идёт выкладка либо она оборвалась (ops/deploy.sh --abort)" ;;
            "база второй сборки")
                if [ "${frozen:-0}" != 0 ]; then
                    printf '      прежняя база — слепок на момент прошлого переключения\n'
                    printf '      %s\n' "$(since_words "$name")"
                    printf '      удалит выкладка или ops/deploy.sh --drop-previous, и только после ночного дампа по %s (задача 0117)\n' "$heir"
                fi ;;
            ПОСТОРОННЯЯ*)
                red "      её не видит ни один инструмент ячейки: бэкап берёт базу сборки под трафиком,"
                red "      выкладка — базу второй сборки, а этой нет ни в одном ключе .env"
                printf '      %s\n' "$(since_words "$name")"
                printf '      Похоже на прежнюю базу выкладки, которую не убрали. Удаляется руками и глазами:\n'
                printf '      сверьте %s и %s — автоматически её не удаляет никто (задача 0195)\n' "$HISTORY" "$ENV_FILE" ;;
        esac
    done <<EOF
$text
EOF
    if [ "$strangers" = 0 ]; then
        printf '  Посторонних баз нет: каждую называет ключ .env или инструмент ячейки.\n'
        return 0
    fi
    red "  Посторонних баз: ${strangers}, всего ${stranger_mb} МБ — их не видит ни один инструмент ячейки."
    return 1
}

db_inventory() {  # база под трафиком, база второй сборки, копия идущей выкладки
    local text
    text=$(db_list_raw) || {
        red "  Перечня баз не спросить у Postgres — что лежит в ячейке, неизвестно"
        return 2
    }
    db_inventory_report "$text" "$1" "$2" "$3"
}

# Перечислить базы, ничего не трогая. Красным и ненулевым кодом отвечает
# только эта команда: у неё одна работа — назвать то, чего не видит никто,
# — а перечень в конце выкладки и в --drop-previous сообщает, не делая
# их красными: удавшуюся работу посторонняя база не отменяет.
databases_now() {
    local active other heir prev copy rc=0
    PG_USER="${DB_USER:-$(read_env DB_USER)}"
    active=$(active_build) || fail "Не удалось узнать сборку под трафиком"
    other=$(other_of "$active") || fail "Непонятное имя активной сборки: $active"
    heir=$(db_of "$active") || fail "Не узнать базу сборки $active"
    prev=$(db_of "$other") || fail "Не узнать базу сборки $other"
    copy=$(read_env DEPLOY_COPY_DB)
    printf 'Под трафиком:  %s (база %s)\n' "$active" "$heir"
    printf 'Вторая сборка: %s (база %s)\n' "$other" "$prev"
    [ -z "$copy" ] || printf 'Идёт выкладка: копия %s (метка DEPLOY_COPY_DB в %s)\n' "$copy" "$ENV_FILE"
    printf '\n'
    db_inventory "$heir" "$prev" "$copy" || rc=$?
    # Условие 0117 — числами, и спрашивается тем же кодом, которым спрашивает
    # удаление: второе место, знающее условие, разошлось бы с первым.
    if [ -n "$prev" ] && [ "$prev" != "$heir" ] && [ "$prev" != "$copy" ]; then
        step "Условие 0117: снялся ли ночной дамп по базе под трафиком $heir"
        if backup_covers "$heir"; then
            printf '  Значит прежнюю базу %s уже можно убрать: ops/deploy.sh --drop-previous\n' "$prev"
        else
            printf '  Пока не снялся — прежняя база %s остаётся (задача 0117).\n' "$prev"
        fi
    fi
    return $rc
}

# Прежняя база — замороженный слепок, оставшийся от прошлой выкладки в эту же
# сборку. Её сменщица — база, которая с того переключения принимает работу
# людей; бэкап по ней и есть то условие, после которого слепок перестаёт быть
# единственной полной копией данных на момент переключения.
#
# Код возврата: 0 — удалена, удалять было нечего или удалить не вышло;
# 2 — осталась лежать по условию 0117. Второе важно звавшему: с этой минуты
# базу может не называть ни один ключ .env (см. раздел выше).
drop_previous() {  # прежняя база, её сменщица
    local prev="$1" heir="$2"
    if [ -z "$prev" ] || [ "$prev" = "$heir" ]; then
        printf '  %s — это база, с которой работают: не трогаем\n' "${prev:-—}"
        return 0
    fi
    run db_exists "$prev"
    case "$?" in
        0) ;;
        1) printf '  %s уже нет — удалять нечего\n' "$prev"; return 0 ;;
        *) red "  Не спросить, есть ли база $prev — ничего не трогаю"; return 0 ;;
    esac
    if ! run backup_covers "$heir"; then
        printf '  %s остаётся до ночного дампа по новой базе — так решено 15 сентября 2026\n' "$prev"
        printf '  (задача 0117) и уточнено 28 сентября (задача 0214: базовой копии ворота\n'
        printf '  удаления больше не требуют — она про точку возврата).\n'
        # «Остаётся до бэкапа» без даты не отвечает на вопрос «это неделя или
        # месяц» — а ответ на него и решает, ждать или снимать базовую копию
        # руками (задача 0195).
        printf '  %s\n' "$(since_words "$prev")"
        printf '  Удалит её следующая выкладка или ops/deploy.sh --drop-previous.\n'
        return 2
    fi
    run drop_db "$prev" || red "  $prev удалить не вышло; на саму выкладку это не влияет"
}

# Убрать прежнюю базу, ничего не выкладывая. Нужна эта команда для случая,
# когда условие в минуту выкладки ещё не выполнено: по новой базе дампа нет
# до ближайших трёх часов ночи, значит вторая выкладка за день оставит слепок
# лежать. Без команды он дожил бы до следующей выкладки.
#
# До задачи 0214 условие не выполнялось в минуту выкладки ПОЧТИ НИКОГДА
# (требовалась базовая копия свежее дампа, а она недельная), и эта команда была
# единственным способом освободить место вообще.
drop_previous_now() {
    local active other heir prev
    PG_USER="${DB_USER:-$(read_env DB_USER)}"
    [ -z "$(read_env DEPLOY_COPY_DB)" ] \
        || fail "Идёт выкладка (метка DEPLOY_COPY_DB в $ENV_FILE) — прежнюю базу не трогаю"
    active=$(active_build) || fail "Не удалось узнать сборку под трафиком"
    other=$(other_of "$active") || fail "Непонятное имя активной сборки: $active"
    heir=$(db_of "$active") || fail "Не узнать базу сборки $active"
    prev=$(db_of "$other") || fail "Не узнать базу сборки $other"
    step "Прежняя база сборки $other (под трафиком $active на $heir)"
    drop_previous "$prev" "$heir"
    # И перечень: эта команда — то место, куда человек приходит разбираться
    # с лишними базами, а прежняя база сборки далеко не единственная лишняя
    # (задача 0195). Красным перечень здесь не отвечает: своя работа удалась.
    step "Базы ячейки"
    run db_inventory "$heir" "$prev" ""
    [ "$?" -lt 2 ] || red "  Перечень баз не получился: ops/deploy.sh --databases"
}

# ─────────────────────────── откат до точки невозврата ───────────────────────
#
# Порядок не случайный. Трафик возвращается первым — людей обслуживает
# старая сборка, и остальное делается уже без них. Копия удаляется только
# после того, как трафик ушёл: проверка «не база ли это под трафиком» стоит
# в drop_db и отказывает, если возврат не удался. Запись в старой базе
# открывается последней, а метка «выкладка не закончена» снимается только
# после всех шагов — упавший откат повторяет ops/deploy.sh --abort.
undo_copy() {
    local bad=0
    step "Откатываем: трафик и запись возвращаются на $SOURCE_DB"
    if ! run env SWITCH_FORCE=yes "$SWITCH" "$ACTIVE_COLOR"; then
        red "Вернуть трафик на $ACTIVE не вышло. Копию не трогаю: люди могут быть на ней."
        red "Разберитесь с терминатором и повторите: ops/deploy.sh --abort"
        return 1
    fi
    run $COMPOSE stop "$TARGET" || bad=1
    run drop_db "$COPY_DB" || bad=1
    run set_env "APP_DB_$(upper "$COLOR")" "$PREV_TARGET_DB" || bad=1
    # Профили — обратно на одну сборку. Оставленные «blue,green», они
    # подняли бы неудавшуюся сборку первым же `up -d` без имени сервиса.
    run set_env COMPOSE_PROFILES "$ACTIVE_COLOR" || bad=1
    run unfreeze_db "$SOURCE_DB" || bad=1
    if [ "$bad" != 0 ]; then
        red "Откат прошёл не целиком — метку незаконченной выкладки оставляю: ops/deploy.sh --abort"
        return 1
    fi
    clear_marker
}

set_marker() {
    run set_env DEPLOY_COPY_DB "$COPY_DB" &&
    run set_env DEPLOY_COPY_FROM "$SOURCE_DB" &&
    run set_env DEPLOY_COPY_BUILD "$TARGET" &&
    run set_env DEPLOY_COPY_PREV "$PREV_TARGET_DB"
}

clear_marker() {
    run set_env DEPLOY_COPY_DB "" &&
    run set_env DEPLOY_COPY_FROM "" &&
    run set_env DEPLOY_COPY_BUILD "" &&
    run set_env DEPLOY_COPY_PREV ""
}

# Отказ после заморозки: всё назад, запись в историю, красный код.
abandon() {  # причина
    red "$1"
    if undo_copy; then
        freeze_report
        record "выкладка" "$1; откат: трафик и база прежние"
        fail "Выкладка красная. Ячейка на прежней сборке и прежней базе, запись открыта"
    fi
    record "выкладка" "$1; откат НЕ закончен"
    fail "Выкладка красная, и откат не закончен — ops/deploy.sh --abort"
}

freeze_report() {
    [ -n "${FROZEN_AT:-}" ] || return 0
    printf 'Запись была заморожена %s с\n' "$(( $(date +%s) - FROZEN_AT ))"
}

# ──────── не то же ли это, что уже под трафиком (задача 0223) ────────────────
#
# 29 сентября 2026 владелец нажал кнопку, считая, что везёт свежий `main`,
# и выложил коммит, который на ячейке УЖЕ СТОЯЛ. Выкладка прошла целиком:
# самопроверки зелёные, трафик переведён, в отчёте «успех». Заплачено при этом
# полной ценой — окно заморозки записи (32–33 с по замеру 0112, когда продавец
# не может записать), ещё одна копия базы и прежняя, вылетевшая из обоих ключей
# .env (задача 0195), — а привезено НИЧЕГО: починка, за которой выкладку
# и звали, осталась в реестре.
#
# Сравнения не делал никто. Форма тега проверялась (сорок знаков,
# шестнадцатеричные), а «не то же ли это, что уже работает» не спрашивалось
# ни здесь, ни в кнопке. Оба значения при этом в отчёте кнопки УЖЕ были —
# соседними строками одной таблицы, «Версия» и «Было», — и ровно на них никто
# не посмотрел: сверять сорок шестнадцатеричных знаков глазами человек
# не станет, пока ему не сказали, что их надо сверить. Поэтому здесь
# называется ИСХОД, а не печатаются два значения рядом: ещё одна пара строк
# вырождается в то же самое состояние.
#
# РЕШЕНИЕ ВЛАДЕЛЬЦА от 29 сентября 2026, дословно: «не красим, только
# словами». Значит выкладка СООБЩАЕТ И ПРОДОЛЖАЕТ — код возврата тот же, шаг
# не останавливается, поля «продолжить всё равно» нет. Рекомендация
# останавливать её до заморозки с явным способом продолжить ОТКЛОНЕНА, и это
# названный размен: заморозка и посторонняя база остаются платой за повтор,
# зато на законном пути не появляется преграды, которую учатся обходить, —
# та же причина, по которой у нас «ложная тревога дороже пропуска».
#
# СРАВНИВАЕТСЯ APP_IMAGE_TAG — версия ПОД ТРАФИКОМ, а не ключ второй сборки.
# Иначе окликался бы откат приложения: «выложили A в зелёную, B в синюю,
# возвращаемся к A» кладёт в зелёную тот же образ второй раз, и совпадение
# с APP_IMAGE_TAG_GREEN там законно.
#
# ТРИ ИСХОДА, А НЕ ДВА (образец — tools/head-green.sh, задача 0194): «повтор»,
# «новое» и «сравнить не с чем» — последнее у ячейки, в .env которой тега нет
# вовсе (первая выкладка). Третий обязан отличаться от «сходится»: пустое
# значение, молча попавшее в «новое», — ровно то умолчание, из-за которого
# «неизвестно» читают как «всё в порядке».
verdict_key() {  # выкладываемый SHA, SHA под трафиком → повтор|новое|неизвестно
    if [ -z "$2" ]; then
        printf 'неизвестно\n'
    elif [ "$1" = "$2" ]; then
        printf 'повтор\n'
    else
        printf 'новое\n'
    fi
}

# Громкая строка — ОДНА на две поверхности: её печатает и выкладка на ячейке,
# и кнопка (шагом --verdict, в предупреждение прогона). Второй редакции текста
# не существует намеренно — разъехавшись, они сообщали бы человеку разное
# об одном и том же.
verdict_line() {  # ключ → строка человеку; у «нового» её нет намеренно
    case "$1" in
        повтор)     printf 'ПОВТОР: этот коммит уже под трафиком — выкладка не привезёт нового\n' ;;
        неизвестно) printf 'СРАВНИТЬ НЕ С ЧЕМ: что стоит под трафиком, ячейка не называет — в .env нет APP_IMAGE_TAG\n' ;;
        новое)      ;;
    esac
}

# То же в одну клетку — для таблицы отчёта прогона и для строки
# deploy-history.log: «эта выкладка что-нибудь привезла?» обязано отвечаться
# без сверки сорока знаков глазами.
verdict_brought() {  # ключ → что выкладка привезла
    case "$1" in
        повтор)     printf 'ничего: тот же коммит уже был под трафиком\n' ;;
        новое)      printf 'новую версию\n' ;;
        неизвестно) printf 'неизвестно: под трафиком версия не названа\n' ;;
    esac
}

same_commit_verdict() {  # выкладываемый SHA, SHA под трафиком
    local key line
    key=$(verdict_key "$1" "$2")
    # Ключ — в журнал выкладок (record): строка истории обязана отвечать
    # на «привезла ли эта выкладка что-нибудь» сама, без соседних строк.
    VERDICT_KEY="$key"
    line=$(verdict_line "$key")
    # «Новое» МОЛЧИТ, и это половина правки. Законный путь не окликают:
    # проверка, говорящая что-нибудь на каждой выкладке, через неделю
    # перестаёт читаться — и тогда на повторе её тоже не прочитают.
    [ -n "$line" ] || return 0
    printf '\n%s\n' "$line"
    case "$key" in
        повтор)
            printf '  Выкладываемый и стоящий коммит — один и тот же: %s\n' "$1"
            printf '  Цена повтора при этом полная: окно заморозки записи (около полуминуты,\n'
            printf '  продавец не может записать), ещё одна копия базы и прежняя база, которая\n'
            printf '  останется лежать. Привезено не будет ничего.\n'
            printf '  Собирались привезти свежую версию — выкладка идёт НЕ ТУДА: сверьте SHA\n'
            printf '  в поле кнопки, свежий берётся из зелёного прогона main.\n'
            printf '  Это откат приложения, повтор после обрыва или пересборка ячейки — тогда\n'
            printf '  всё верно: выкладка продолжается, останавливать её здесь нечем и не нужно.\n' ;;
        неизвестно)
            printf '  Повтор того же коммита в эту минуту не отличить от новой версии, поэтому\n'
            printf '  сказано «не с чем», а не «сходится»: второе было бы неправдой.\n'
            printf '  Так выглядит первая выкладка ячейки — тега в %s ещё нет, и всё верно.\n' "$ENV_FILE" ;;
    esac
    return 0
}

# Вердикт отдельной командой — им спрашивает кнопка ДО первого изменения
# стенда: на раннере .env ячейки нет вовсе, и версия под трафиком приезжает
# туда своим шагом по ssh (--current). Код возврата ВСЕГДА 0: «не красим,
# только словами», а шаг, падающий на повторе, красил бы выкладку, которой
# владелец решил дать пройти.
verdict_now() {
    local current key line
    [ -n "$TAG" ] || fail "Нужен --tag: SHA, который собираются выкладывать"
    if [ -n "${CURRENT_GIVEN:-}" ]; then
        current="$CURRENT_TAG"
    else
        current=$(read_env APP_IMAGE_TAG)
    fi
    same_commit_verdict "$TAG" "$current"
    key=$(verdict_key "$TAG" "$current")
    line=$(verdict_line "$key")
    if [ -n "${GH_OUTPUT:-}" ]; then
        # Предупреждение прогона — чтобы исход был виден на странице кнопки,
        # а не только в логе шага. Выкладку оно не красит (у ::warning::
        # такого свойства нет), и у «нового» его нет вовсе.
        [ -z "$line" ] || printf '::warning::%s\n' "$line"
        if [ -n "${GITHUB_OUTPUT:-}" ]; then
            {
                printf 'verdict=%s\n' "$key"
                printf 'verdict_line=%s\n' "$line"
                printf 'verdict_brought=%s\n' "$(verdict_brought "$key")"
            } >> "$GITHUB_OUTPUT"
        fi
    fi
    return 0
}

# ─────────────────────────────── сама выкладка ───────────────────────────────
deploy() {
    [ -n "$TAG" ] || fail "Нужен --tag: полный SHA коммита, собранного CI (сорок символов)"
    case "$TAG" in
        *[!0-9a-f]*|"") fail "Тег «${TAG}» не похож на SHA: в реестре лежат полные SHA, сорок символов" ;;
    esac
    [ "${#TAG}" = 40 ] || fail "Тег «${TAG}» длиной ${#TAG}: короткого SHA в реестре нет, pull ответит manifest unknown"

    # ── тот же ли это коммит, что уже под трафиком (задача 0223) ───────────
    #
    # ПЕРВЫМ ДЕЛОМ, и это всё, что отличает эту правку от отсутствующей: вся
    # цена дефекта — заморозка записи, копия базы и прежняя база, оставшаяся
    # лежать, — платится ниже, а сказанное после них не спасает ничего.
    # Поэтому вердикт стоит раньше data_gate, раньше config-guard.sh и раньше
    # первой записи в .env, то есть до единого изменения чего бы то ни было.
    #
    # «Только миграции» пропускается намеренно: там нет ни копии,
    # ни переключения, ни заморозки — схема приводится на месте у работающей
    # базы, и тем же коммитом это законная починка, у которой цены повтора
    # нет вовсе. Окликать её значило бы завести ложную тревогу на пути,
    # которым чинят.
    if [ "$MIGRATIONS" != only ]; then
        same_commit_verdict "$TAG" "$(read_env APP_IMAGE_TAG)"
    fi

    data_gate
    transport_gate

    if [ -n "$(read_env DEPLOY_COPY_DB)" ]; then
        red "Прошлая выкладка не закончена: в $ENV_FILE стоит DEPLOY_COPY_DB=$(read_env DEPLOY_COPY_DB)."
        red "Запись в базе, возможно, ещё заморожена, а копия не убрана."
        fail "Сначала доделайте откат: ops/deploy.sh --abort. Выкладка остановлена ДО единого изменения."
    fi

    ACTIVE=$(active_build) || fail "Не удалось узнать сборку под трафиком (ops/active-build.caddy)"
    TARGET=$(other_of "$ACTIVE") || fail "Непонятное имя активной сборки: $ACTIVE"
    COLOR="${TARGET#app-}"
    ACTIVE_COLOR="${ACTIVE#app-}"
    SOURCE_DB=$(db_of "$ACTIVE") || fail "Не узнать базу сборки $ACTIVE"
    PREV_TARGET_DB=$(db_of "$TARGET") || fail "Не узнать базу сборки $TARGET"
    # Имя копии называет сборку и версию: «какой сборке эта база» читается
    # в списке баз без расспросов. Цвет в имени — от повторной выкладки
    # того же SHA: в сборку другого цвета, то есть в другую базу.
    COPY_DB="parts_${COLOR}_$(printf '%s' "$TAG" | cut -c1-12)"
    # Тот же образ в ту же сборку второй раз — это и есть откат приложения:
    # выложили A в зелёную, B в синюю, возвращаемся к A. Имя копии тогда
    # совпало бы с прежней базой зелёной, а её мы с задачи 0117 удаляем ПОСЛЕ
    # выкладки, не перед, — и занятое имя остановило бы откат словами «копию
    # прошлой выкладки не убрали», то есть ровно в ту минуту, когда он нужен.
    [ "$COPY_DB" = "$PREV_TARGET_DB" ] && COPY_DB="${COPY_DB}_2"
    PG_USER="${DB_USER:-$(read_env DB_USER)}"

    printf 'Стенд:        %s\n' "$STAND"
    printf 'Выкладываем:  %s\n' "$TAG"
    printf 'Сборка:       %s (сейчас под трафиком %s)\n' "$TARGET" "$ACTIVE"
    if [ "$MIGRATIONS" = only ]; then
        printf 'База:         %s — на месте, без копии\n' "$SOURCE_DB"
    else
        printf 'База:         %s → копия %s\n' "$SOURCE_DB" "$COPY_DB"
    fi
    printf 'Миграции:     %s%s\n' "$(migrations_word)" \
        "$([ "$MIGRATE_WITH" = none ] && printf ' — база новее образа, схему не трогаем')"
    printf 'Данные:       %s\n' "$DATA"
    printf 'Нажал:        %s\n' "$WHO"

    # Настройки ячейки — ДО первой правки чего бы то ни было. Пропавший файл
    # из ops/ docker подменяет пустым каталогом молча (задача 0101), и хуже
    # всего это у наблюдения: ячейка, у которой нет alerts.yml, не сможет
    # сообщить об этом тревогой — сообщать будет нечем. Выкладка приезжает
    # rsync'ом, то есть ровно тем способом, которым файл и теряется.
    step "Настройки ячейки на месте (файл, а не каталог)"
    run ops/config-guard.sh \
        || fail "Настройки ячейки неполны — docker подставит пустые каталоги молча. Выкладка остановлена до единого изменения"

    # ── привезённое начинает ДЕЙСТВОВАТЬ, а не просто лежать ───────────────
    #
    # Решение владельца от 28 сентября 2026, дословно: «расхождение красит,
    # выкладка применяет». Вторая половина — этот шаг (задача 0216). До него
    # выкладка клала ops/ целиком и не применяла НИЧЕГО: bind-mount одного
    # файла разрешается в inode при старте контейнера, а rsync подменяет файл
    # новым — то есть привезённая правка archive-wal.sh, alerts.yml или
    # alert-channel-check.sh лежала на хосте, пока контейнер исполнял прежнюю.
    # 19 сентября 2026 так пропала точка возврата при здоровой с виду базе.
    #
    # ЗДЕСЬ, А НЕ ВНУТРИ ОКНА: пересоздание контейнеров наблюдения не касается
    # ни трафика, ни базы, и делать его после заморозки значило бы удлинять
    # окно без нужды. А шагом позже config-guard.sh потому, что это разные
    # вопросы: тот про «файл на месте», этот про «та ли редакция действует».
    #
    # ЧТО ОН ДЕЛАЕТ САМ, А ЧТО НАЗЫВАЕТ — решение ИСПОЛНИТЕЛЯ, ждущее
    # владельца (довод и цена — в ops/apply-config.sh и tasks/0216). Сам:
    # наблюдение и расписание, 0,5–0,8 с на контейнер, клиента не видно.
    # Называет: postgres и caddy — простой базы и вход в ячейку; выкладка
    # обещает, что простоя нет, и вносить его молча в выкладку, которая этих
    # файлов не касалась, нельзя.
    step "Привезённые настройки начинают действовать"
    APPLY_RC=0
    run ops/apply-config.sh --apply || APPLY_RC=$?
    case "$APPLY_RC" in
        0) ;;
        3) # Дешёвый шаг отказал или НЕ ПОДЕЙСТВОВАЛ. Останавливаемся здесь:
           # ячейка ещё не тронута выкладкой, запись не заморожена, люди
           # работают как работали, — а пересоздание наблюдения, оборвавшееся
           # на полпути, означает ячейку без тревог, и выкладывать поверх неё
           # нельзя.
           fail "Привезённую настройку применить не вышло — выкладка остановлена ДО заморозки записи. Разбирайтесь: ops/apply-config.sh" ;;
        2) red "Сверка привезённых настроек НЕ ВЫПОЛНЕНА — неизвестно, та ли редакция действует в контейнерах."
           red "Выкладку это не останавливает: ячейка не тронута. Спросить отдельно: ops/apply-config.sh" ;;
        *) red "Часть привезённого НЕ ДЕЙСТВУЕТ — названа выше поимённо, вместе с ценой и командой."
           red "Выкладку это не красит (решение исполнителя, вопрос владельцу — tasks/0216): дорогой шаг"
           red "задевает клиента, и выкладка, которая этого файла не касалась, простоя не вносит." ;;
    esac

    # Тег новой сборки — в .env ДО всего остального: и pull, и одноразовый
    # контейнер миграции берут образ оттуда же, откуда его возьмёт compose.
    step "Записываем тег выкладываемой сборки"
    run set_env "APP_IMAGE_TAG_$(upper "$COLOR")" "$TAG"
    # Обе сборки обязаны быть подняты одновременно — иначе «рядом» не выйдет.
    run set_env COMPOSE_PROFILES "blue,green"

    step "Забираем образ из реестра"
    run $COMPOSE --profile "$COLOR" pull "$TARGET" \
        || fail "Образа $TAG в реестре нет (или реестр недоступен). Ячейка ничего не собирает — выкладывать нечего"

    # ── «только миграции»: на месте, без копии ─────────────────────────────
    #
    # Поле формы названо владельцем: «привести схему и выйти». Сборку при
    # этом не выкладывают, значит и копии, на которую переключиться, нет —
    # схема приводится у работающей базы. Годится это только для расширяющих
    # миграций (старый код на новой схеме работает, сторож — 0116), и не даёт
    # «всё или ничего»: сорвавшийся changeset оставит схему на полпути.
    if [ "$MIGRATIONS" = only ]; then
        if [ "$MIGRATE_WITH" = none ]; then
            green "База новее выкладываемого образа — приводить нечего. Схему не трогали."
            record "только миграции" "успех: база новее образа"
            return 0
        fi
        step "Приводим схему НА МЕСТЕ — у базы $SOURCE_DB, под работающей сборкой"
        printf 'Без копии: это расширяющий шаг, старая сборка обязана работать на новой схеме.\n'
        run env "APP_DB_$(upper "$COLOR")=$SOURCE_DB" ops/schema-sync.sh --apply "$COLOR" \
            || fail "Схему привести не вышло — сборку не поднимали, трафик на $ACTIVE"
        green "Схема приведена. Сборку не поднимали и трафик не трогали — выбрано «только миграции»."
        record "только миграции" "успех"
        return 0
    fi

    # ── первая выкладка копией на этой ячейке ───────────────────────────────
    #
    # Обе сборки смотрят в одну базу — значит копией здесь ещё не выкладывали,
    # а значит работающая сборка может не знать про заморозку записи.
    if [ "$PREV_TARGET_DB" = "$SOURCE_DB" ]; then
        step "Первая выкладка копией на этой ячейке"
        printf '  Обе сборки смотрят в одну базу (%s) — копией здесь ещё не выкладывали.\n' "$SOURCE_DB"
        printf '  Работающая сборка про заморозку записи может не знать: если её код\n'
        printf '  старше 15 сентября 2026, продавец увидит «Внутренняя ошибка» вместо\n'
        printf '  «Идёт обновление» — около полуминуты. Данные при этом целы: заморожена\n'
        printf '  база, а не приложение.\n'
        printf '  Поэтому первое такое обновление боевой ячейки делают В НЕРАБОЧЕЕ ВРЕМЯ\n'
        printf '  и предупредив клиента заранее (docs/deployment.md, «Первое обновление\n'
        printf '  боевой ячейки»). Со второй выкладки сборки про заморозку уже знают.\n'
    fi

    # Прежняя база выкладываемой сборки — замороженный слепок прошлой выкладки
    # в этот цвет — здесь не трогается вовсе. До задачи 0117 её сносили прямо
    # тут, перед заморозкой: единственная полная копия данных на момент
    # прошлого переключения исчезала раньше, чем появлялся первый бэкап её
    # сменщицы. Теперь это последний шаг выкладки и с условием (шаг 10).

    step "Место под копию"
    run check_copy_room "$SOURCE_DB" "$COPY_DB" \
        || fail "Копию снимать нельзя — выкладка остановлена ДО заморозки, люди работают как работали"

    # Метка — до заморозки: если выкладку оборвут посреди, --abort по ней
    # узнает, какую базу открыть и какую копию удалить.
    set_marker || fail "Не записать метку выкладки в $ENV_FILE — останавливаюсь до заморозки"

    # ── 0. вход дымового прогона — ДО заморозки ────────────────────────────
    #
    # Вход заводит серверную сессию (public.spring_session, задача 0080),
    # то есть ПИШЕТ. Внутри окна заморозки запись отбита, и вход отвечает
    # 503 — значит пятая самопроверка не могла пройти там никогда. Первая же
    # выкладка кнопкой на ПРОМ упала именно так (задача 0142).
    #
    # Поэтому входим заранее: сессия ложится в исходную базу, копия снимается
    # следом и уносит её с собой, а банка cookie остаётся в контейнере
    # терминатора — он при переключении не пересоздаётся, только перечитывает
    # конфигурацию. Сборка, поднятая на копии, видит ту же сессию.
    #
    # Отказ здесь НЕ валит выкладку: ячейка ещё не тронута, а проверки внутри
    # окна честно покраснеют и всё вернут. Молчать об этом нельзя — иначе
    # «сессия не получена» выяснится только пятой проверкой, и причина
    # будет выглядеть как поломка продажи.
    #
    # ЧЕМ ЭТО ДЕРЖИТСЯ, КРОМЕ ПОРЯДКА ШАГОВ. Готовой сессии мало: Spring
    # Session пишет отметку последнего обращения на КАЖДОМ запросе вошедшего,
    # то есть внутри окна каждое чтение било бы в замороженную базу. Спасают
    # два места, и без них вариант несостоятелен:
    # FreezeTolerantSessions (platform/session) глотает ровно 25006 и только
    # при сохранении сессии, и SessionTrackingFilter.markSeen ловит свой отказ
    # отдельно. Найдено разбором PR #256 — в первой редакции этой правки они
    # не были названы, и «почему оно вообще работает» осталось бы догадкой.
    #
    # НОВЫЙ РЕЖИМ ОТКАЗА, названный вслух. Банка cookie лежит в /tmp
    # КОНТЕЙНЕРА ТЕРМИНАТОРА (весь curl прогона идёт через `compose exec
    # caddy`). Переключение трафика его не пересоздаёт — только `caddy
    # reload`, — поэтому банка переживает окно. Но перезапуск терминатора
    # между этим шагом и самопроверками унесёт её, и тогда ИСПРАВНАЯ выкладка
    # откатится на 503: прогон войти уже не сможет. Перезапускать caddy
    # посреди выкладки нельзя.
    SMOKE_JAR="${SMOKE_JAR:-/tmp/partsflow-smoke-$(printf '%s' "$TAG" | cut -c1-12)}"
    export SMOKE_JAR
    SESSION_READY=""
    step "Вход дымового прогона — до заморозки"
    if run env SMOKE_JAR="$SMOKE_JAR" ops/smoke-run.sh --login-only; then
        SESSION_READY=yes
    else
        red "Вход до заморозки не получен — пятая самопроверка войти внутри окна не сможет"
    fi

    # ── 1–2. заморозка и копия ─────────────────────────────────────────────
    step "Замораживаем запись в $SOURCE_DB"
    FROZEN_AT=$(date +%s)
    run freeze_db "$SOURCE_DB" || abandon "Заморозить запись в $SOURCE_DB не вышло"

    step "Снимаем копию $SOURCE_DB → $COPY_DB"
    run copy_db "$SOURCE_DB" "$COPY_DB" || abandon "Копия $COPY_DB не снялась"

    # Сборка настроена на копию ДО того, как её поднимут, и тем более до
    # трафика. Базу работающей сборки не трогает ни одна строка ниже: старая
    # на копию не смотрит никогда.
    run set_env "APP_DB_$(upper "$COLOR")" "$COPY_DB" || abandon "Не записать базу сборки $TARGET в $ENV_FILE"

    # ── 3. схема копии ──────────────────────────────────────────────────────
    if [ "$MIGRATE_WITH" = none ]; then
        step "Схему не трогаем: база новее образа"
        printf 'Откатывается только приложение, база чинится вперёд (задача 0112).\n'
        printf 'Готовность новой сборки покраснеет сама, если схема окажется ПОЗАДИ неё.\n'
    elif [ "$MIGRATIONS" = skip ]; then
        step "Схему не трогаем (выбрано «не трогать»)"
        printf 'Пара «код и схема» при этом может не совпасть — готовность новой сборки\n'
        printf 'покраснеет сама, если схема окажется ПОЗАДИ неё.\n'
    else
        step "Приводим схему КОПИИ к версии образа"
        run ops/schema-sync.sh --apply "$COLOR" \
            || abandon "Схему копии привести не вышло"
    fi

    # ── 4–5. новая сборка рядом, на копии ──────────────────────────────────
    step "Поднимаем $TARGET РЯДОМ со старой — на копии $COPY_DB"
    run $COMPOSE --profile blue --profile green up -d "$TARGET" \
        || abandon "Не поднялась $TARGET"

    step "Ждём готовности $TARGET (до ${HEALTH_WAIT} с — всё это время запись заморожена)"
    run wait_healthy "$TARGET" || abandon "Сборка $TARGET не стала здоровой за ${HEALTH_WAIT}с"

    # ── 6. дымовая продажа — по копии, ДО трафика и ДО заморозки ───────────
    #
    # ЗДЕСЬ, А НЕ В САМОПРОВЕРКАХ, и вот почему (задача 0145). Сценарий
    # прогона кончается деньгами — приёмка, сделка с резервом, оплата,
    # выдача, уборка, — то есть пишет. Самопроверки идут внутри окна, где
    # копия заморожена шагом 7, а заморозка ставится на БАЗУ ЦЕЛИКОМ
    # и схем не различает: подтверждено живым прогоном на боевой ячейке —
    # insert в тестовую компанию и в кабинет клиента отбиты одинаково.
    # Значит пишущие шаги внутри окна не могли пройти никогда.
    #
    # Это окно — единственное подходящее: копия уже поднята под новой
    # сборкой и ещё открыта на запись (схему на неё накатывали шагом 3 тем
    # же порядком), а записать в неё, кроме самой выкладки, некому — трафик
    # на старой сборке, её база заморожена.
    #
    # И оно ДО ТОЧКИ НЕВОЗВРАТА: упади продажа — копию удаляют вместе со
    # всем, что прогон успел записать, трафик не двигается вовсе, старая
    # база не менялась. Атомарность из 0112 («всё новое или ничего») этим
    # не тронута; цена выбора — окно заморозки длиннее на время сценария.
    #
    # ЧЕРЕЗ ИМЯ СБОРКИ, А НЕ ЧЕРЕЗ ТЕРМИНАТОР: в эту минуту терминатор ведёт
    # на СТАРУЮ сборку, и прогон проверил бы не ту версию, которую
    # выкладывают. Стенд при этом считается по публичному адресу, а не по
    # «app-green» (STAND_BASE в ops/smoke-run.sh): иначе метка «prom»
    # пропала бы, а с ней и правило «хост сильнее переменной».
    #
    # БАНКА COOKIE СВОЯ, и это не мелочь: `curl -c` переписывает файл
    # целиком, то есть общая банка унесла бы сессию, добытую шагом 0 для
    # самопроверок, — и ИСПРАВНАЯ выкладка покраснела бы внутри окна на 503.
    step "Дымовая продажа на $TARGET — по копии, до трафика и до заморозки"
    run env SMOKE_BUILD="$TARGET" SMOKE_JAR="${SMOKE_JAR}-sale" ops/smoke-run.sh \
        || abandon "Дымовой прогон на $TARGET не прошёл"

    # ── 7. копия замораживается на время переключения ─────────────────────
    #
    # До точки невозврата в копию не должна лечь ни одна запись людей: упади
    # самопроверки — копию удалят, и записанное туда исчезло бы. Так же
    # делает эталон (blue/green у Amazon RDS): при переключении запись
    # заблокирована на обеих базах.
    step "Замораживаем и копию — до конца самопроверок"
    run freeze_db "$COPY_DB" || abandon "Заморозить копию $COPY_DB не вышло"

    # ── 8. трафик ───────────────────────────────────────────────────────────
    step "Переводим трафик на $TARGET"
    # Копия заморожена намеренно (шаг 6), и переключатель на замороженную
    # базу без разрешения не пускает: там обычно лежит вчерашний слепок.
    run env SWITCH_FROZEN_OK=yes "$SWITCH" "$COLOR" || abandon "Переключение не прошло"

    # ── 9. самопроверки ─────────────────────────────────────────────────────
    step "Шесть самопроверок на переключённой сборке"
    # Банка cookie и признак готовой сессии едут сюда: вход случился до
    # заморозки (шаг 0), и внутри окна повторять его нельзя — запись отбита.
    # Признак пуст, если вход не удался: тогда прогон войдёт сам и честно
    # покраснеет на 503, вместо того чтобы молча притвориться прошедшим.
    #
    # DEPLOY_WRITE_FROZEN говорит проверкам, что запись сейчас заморожена:
    # пятая идёт только на чтение, а продажу уже прогнали шагом 6 (0145).
    # Без этого она пошла бы писать в замороженную копию и покраснела бы
    # на полностью исправной сборке.
    #
    # DEPLOY_EXPECT_VERSION — то, что выкладываем, для шестой проверки
    # (задача 0130): она спрашивает у поднятой сборки, какой SHA она несёт,
    # и сверяет с этим. Ожидание берётся ОТСЮДА, а не из .env: файл к этой
    # минуте уже переписан самой выкладкой, и проверка пересказывала бы
    # собственную запись — «в файле написано» и «в памяти работает»
    # расходятся ровно тогда, когда .env правили руками.
    run env DEPLOY_BUILD="$TARGET" SMOKE_JAR="$SMOKE_JAR" \
        SMOKE_SESSION_READY="$SESSION_READY" DEPLOY_WRITE_FROZEN=yes \
        DEPLOY_EXPECT_VERSION="$TAG" ops/deploy-checks.sh \
        || abandon "Самопроверки не прошли"

    # ── 10. точка невозврата ───────────────────────────────────────────────
    #
    # Метка снимается ДО того, как открывается запись: оборвись выкладка
    # между двумя шагами, --abort без метки не удалит копию, в которую уже
    # пишут, а только снимет с неё заморозку.
    step "Точка невозврата: открываем запись в $COPY_DB"
    clear_marker || fail "Не снять метку выкладки в $ENV_FILE — трафик на $TARGET, запись заморожена. ops/deploy.sh --abort"
    run unfreeze_db "$COPY_DB" || {
        record "выкладка" "трафик на новой сборке, запись в копии не открылась"
        fail "Трафик на $TARGET, но запись в $COPY_DB не открылась — ops/deploy.sh --abort снимет заморозку"
    }
    freeze_report

    step "Гасим старую сборку $ACTIVE"
    # Не погасла — выкладка всё равно состоялась (трафик и запись уже
    # на новой), но сказать надо: старая так и работает на замороженном
    # слепке, и её готовность зелёная. Переключатель на неё людей
    # не переведёт, а фоновые обходы будут сыпать отказами записи.
    run $COMPOSE stop "$ACTIVE" || {
        red "Старая сборка $ACTIVE не погасла — она работает на замороженной $SOURCE_DB."
        red "Погасите руками: $COMPOSE stop $ACTIVE"
        record "выкладка" "успех; старая сборка не погасла"
    }

    # Тег ячейки переносим после успеха: до него «версия ячейки» — прежняя,
    # и это верно, потому что вернуться можно было в любую минуту.
    run set_env APP_IMAGE_TAG "$TAG"
    run set_env COMPOSE_PROFILES "$COLOR"
    # След спрашивается, а не выводится из кода возврата: оба ключа
    # перечитываются из файла. Отказ записи (сломанный python3, `.env` без права
    # записи) не читал НИКТО — `run set_env` стоял без `||` вовсе, — и «Готово.
    # Под трафиком …, версия $TAG» печаталось при ПРЕЖНЕМ `APP_IMAGE_TAG`.
    # Это то самое «в файле написано ≠ в памяти работает», против которого
    # заведена шестая самопроверка (0130), и цена у него двойная: перезапуск
    # ячейки поднимет прежний образ, а следующая выкладка сравнит свой тег
    # с устаревшим и назовёт повтор новой версией (0223).
    #
    # При `--dry-run` сверка не идёт: там `run` только печатает, ничего
    # не записывая, — спрашивать след у напечатанного значило бы краснеть
    # на исправном показе шагов (поймано своей же самопроверкой: шесть
    # случаев, идущих через `--dry-run`, покраснели разом).
    VERSION_RECORDED=yes
    if [ -z "${DRY:-}" ]; then
        [ "$(read_env APP_IMAGE_TAG)" = "$TAG" ] || VERSION_RECORDED=""
        [ "$(read_env COMPOSE_PROFILES)" = "$COLOR" ] || VERSION_RECORDED=""
    fi
    if [ -z "$VERSION_RECORDED" ]; then
        red "Версия ячейки НЕ записана в $ENV_FILE (APP_IMAGE_TAG=$(read_env APP_IMAGE_TAG), COMPOSE_PROFILES=$(read_env COMPOSE_PROFILES))."
        red "Трафик, запись и схема — новые, а файл называет прежнюю версию."
        red "Впишите руками: APP_IMAGE_TAG=$TAG и COMPOSE_PROFILES=$COLOR — иначе"
        red "перезапуск ячейки поднимет прежний образ, а следующая выкладка сочтёт этот SHA новым."
    fi

    # ── 11. прежняя база прошлой выкладки ──────────────────────────────────
    #
    # Последним шагом и с условием (задача 0117). Выкладка к этой минуте уже
    # состоялась: что бы здесь ни случилось, трафик, запись и версия — новые.
    step "Прежняя база сборки $TARGET"
    drop_previous "$PREV_TARGET_DB" "$SOURCE_DB"
    # Осталась лежать — значит с этой минуты её не называет ничто: ключ .env
    # этой сборки переписан на копию ещё шагом 2, а имя прежней базы жило
    # в переменной этой выкладки. Так и появились на боевой ячейке две
    # замороженные базы рядом с живой (задача 0195).
    if [ "$?" = 2 ]; then
        printf '  И назвать её с этой минуты не сможет ни один ключ %s: APP_DB_%s указывает\n' "$ENV_FILE" "$(upper "$COLOR")"
        printf '  на копию, APP_DB_%s — на прежнюю базу. Ни бэкап, ни следующая выкладка\n' "$(upper "$ACTIVE_COLOR")"
        printf '  этой базы не увидят — искать её по имени: ops/deploy.sh --databases.\n'
    fi

    # Перечень баз — последним шагом и только сообщением: посторонняя база
    # не отменяет удавшейся выкладки, а молчать о ней нельзя. Отказ перечня
    # выкладку тоже не красит: трафик, запись и версия к этой минуте новые.
    step "Базы ячейки"
    run db_inventory "$COPY_DB" "$SOURCE_DB" ""
    # Код 1 — «нашлась посторонняя база», и это не отказ перечня: она уже
    # названа выше. Жаловаться на неё здесь значило бы сказать человеку, что
    # не получилось ровно то, что получилось. Отказом считается только 2 —
    # «перечня не спросить».
    [ "$?" -lt 2 ] || red "  Перечень баз не получился — на саму выкладку это не влияет: ops/deploy.sh --databases"

    # Журнал выкладок называет и незаписанную версию: по нему сверяют, что
    # в ячейке стоит (0116, 0223), и «успех» без оговорки увёл бы следующего.
    if [ -n "$VERSION_RECORDED" ]; then
        record "выкладка" "успех"
    else
        record "выкладка" "успех; версия ячейки в $ENV_FILE не записана"
    fi
    green "Готово. Под трафиком $TARGET, версия $TAG, база $COPY_DB"
    printf 'Прежняя база %s оставлена замороженной — инструмент первых минут, а не отмена\n' "$SOURCE_DB"
    printf 'релиза: всё записанное с этой минуты живёт только в %s. Удалит её следующая\n' "$COPY_DB"
    printf 'выкладка в сборку %s или ops/deploy.sh --drop-previous — и только после того,\n' "$ACTIVE"
    printf 'как по %s снимется ночной дамп (задача 0214: базовой копии ворота удаления\n' "$COPY_DB"
    printf 'больше не требуют — она про точку возврата, и за ней следят тревога и репетиция).\n'
    # Версия ячейки не записалась — выкладка состоялась, а файл называет прежнюю.
    # Зелёная строка выше правдива, но код возврата обязан быть ненулевым:
    # несделанное не уезжает под успехом. Откат этим не запускается — точка
    # невозврата пройдена, а скрипт кончается вызовом `deploy`, то есть код
    # функции и есть код процесса.
    [ -n "$VERSION_RECORDED" ] || return 1
    return 0
}

# ───────────────────────── доделать откат оборвавшейся ──────────────────────
#
# Выкладка, оборванная посреди (упал ssh, перезагрузили машину), оставляет
# ячейку с замороженной записью. По метке в .env видно, что откатывать: пока
# метка стоит, точки невозврата не было — трафик возвращается на прежнюю
# сборку, копия удаляется, запись открывается. Метки нет — выкладка либо
# не начиналась, либо прошла точку невозврата; тогда снимается только
# заморозка с базы под трафиком, если она осталась.
abort() {
    PG_USER="${DB_USER:-$(read_env DB_USER)}"
    COPY_DB=$(read_env DEPLOY_COPY_DB)
    if [ -z "$COPY_DB" ]; then
        ACTIVE=$(active_build) || fail "Не удалось узнать сборку под трафиком"
        SOURCE_DB=$(db_of "$ACTIVE") || fail "Не узнать базу сборки $ACTIVE"
        step "Незаконченной выкладки нет — снимаем заморозку с $SOURCE_DB, если осталась"
        run unfreeze_if_frozen "$SOURCE_DB" || fail "Заморозку снять не вышло"
        green "Запись в базе под трафиком открыта"
        return 0
    fi
    SOURCE_DB=$(read_env DEPLOY_COPY_FROM)
    TARGET=$(read_env DEPLOY_COPY_BUILD)
    PREV_TARGET_DB=$(read_env DEPLOY_COPY_PREV)
    ACTIVE=$(other_of "$TARGET") || fail "В метке выкладки непонятная сборка: «${TARGET}»"
    COLOR="${TARGET#app-}"
    ACTIVE_COLOR="${ACTIVE#app-}"
    TAG=$(read_env "APP_IMAGE_TAG_$(upper "$COLOR")")
    [ -n "$SOURCE_DB" ] && [ -n "$PREV_TARGET_DB" ] || fail "Метка выкладки неполная — разбирайтесь руками по $ENV_FILE"
    printf 'Незаконченная выкладка: сборка %s на копии %s, прежняя база %s\n' "$TARGET" "$COPY_DB" "$SOURCE_DB"
    undo_copy || fail "Откат не закончен — причина выше; повторите ops/deploy.sh --abort"
    record "откат оборвавшейся выкладки" "успех"
    green "Откат доделан: трафик на $ACTIVE, база $SOURCE_DB, запись открыта"
}

wait_healthy() {  # имя сервиса
    local name="$1" id status deadline
    deadline=$(( $(date +%s) + HEALTH_WAIT ))
    while :; do
        id=$($COMPOSE ps -q "$name" 2>/dev/null | tail -n1)
        if [ -n "$id" ]; then
            # Нет healthcheck'а — нет и ответа: пустую строку принимать
            # за здоровье нельзя, иначе выкладка переключит трафик
            # на не поднявшееся приложение.
            status=$(docker inspect --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}нет проверки{{end}}' \
                "$id" 2>/dev/null)
            case "$status" in
                healthy) printf '  %s: healthy\n' "$name"; return 0 ;;
                "нет проверки") red "У $name нет healthcheck'а — ждать нечего"; return 1 ;;
            esac
        fi
        [ "$(date +%s)" -lt "$deadline" ] || { red "  $name: ${status:-не поднялась}"; return 1; }
        sleep 5
    done
}

# ───────────────────────── запись о выкладке ─────────────────────────────────
#
# «Что сейчас на ПСИ» обязано отвечаться без расспросов. Строка остаётся
# и у неудачной выкладки: разбираются как раз с ними.
record() {  # что делали, чем кончилось
    local line
    # Базы — в строке истории: имя боевой базы меняется с каждой выкладкой,
    # и возврат к моменту времени обязан знать, КАК база называлась тогда
    # (ops/restore-pitr.sh --db). Спросить это потом больше не у кого.
    # «Привезла» — отдельным полем, а не догадкой по соседним строкам (задача
    # 0223): повтор того же коммита виден в истории как таковой, и «эта
    # выкладка что-нибудь привезла?» не требует сверки сорока знаков глазами.
    # Поля нет у тех записей, где вердикт не считался (--abort, «только
    # миграции»): пустая графа честнее подставленной.
    line=$(printf '%s\t%s\t%s\t%s\t%s\t%s\t%s%s\t%s' \
        "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$STAND" "${TAG:-—}" "$WHO" \
        "$1" "миграции: $MIGRATIONS$([ "$MIGRATE_WITH" = none ] && printf ', база новее образа')" \
        "база: ${SOURCE_DB:-—}$([ -n "${COPY_DB:-}" ] && [ "$MIGRATIONS" != only ] && printf ' → %s' "$COPY_DB")" \
        "$([ -n "${VERDICT_KEY:-}" ] && printf '\tпривезла: %s' "$(verdict_brought "$VERDICT_KEY")")" "$2")
    if [ -n "$DRY" ]; then
        printf 'ЗАПИСЬ: %s\n' "$line"
    else
        printf '%s\n' "$line" >> "$HISTORY"
    fi
}

# ────────────────────────────── самопроверка ─────────────────────────────────
#
# Без ячейки и без docker. Проверяется то единственное, ради чего эта выкладка
# и написана: ПОРЯДОК ШАГОВ и ОТКАТ. Запись замораживается раньше копии,
# новая сборка смотрит на копию раньше трафика, старая на копию не смотрит
# никогда, копия открывается на запись только после самопроверок, а любой
# отказ до этого возвращает всё — и не открывает запись в копии, которую
# удаляет.
selftest() {
    # ЗДЕСЬ НЕЛЬЗЯ СТАВИТЬ «}» В НУЛЕВОЙ КОЛОНКЕ — ни heredoc'ом, ни
    # многострочной строкой, ни образцом JSON. На такой строке covers_callers
    # возобновляет разбор файла: тело самопроверки он пропускает намеренно
    # (внутри лежат имена случаев и программы подделок, то есть литералы,
    # от которых сторож стал бы своим же зовущим), а возвращается к разбору
    # на закрывающей скобке функции. «}» посреди тела он прочитает как её
    # конец — и остаток тела станет для него кодом вне функций.
    #
    # Чем это обойдётся вставившему: самопроверка покраснеет случаем «у ворот
    # удаления другой состав зовущих» НА ЗДОРОВОМ ФАЙЛЕ — подделок нет,
    # bash -n чист, — и красное будет говорить не о том, о чём кажется: не
    # «кто-то дописал зовущего к воротам удаления», а «сторож дочитал не до
    # того места». Замерено вставкой шести строк с JSON в начало этого тела
    # (задача 0214): bash -n = 0, самопроверка — код 1 и строка про
    # «(верхний-уровень)».
    #
    # Нужен многострочный литерал — отступите его «}» хотя бы одним пробелом.
    local bad=0 dir plan code
    dir=$(mktemp -d)
    trap 'rm -rf "$dir"' RETURN

    local sha=b1b1b1b1b1b1b1b1b1b1b1b1b1b1b1b1b1b1b1b1
    local copy=parts_green_b1b1b1b1b1b1
    local blue_db=parts_blue_cccccccccccc
    local green_db=parts_green_dddddddddddd

    fresh_env() {  # ячейка, выкладывавшаяся копией: у обеих сборок свои базы
        printf 'COMPOSE_PROFILES=blue\nAPP_IMAGE_TAG=%s\n#APP_IMAGE_TAG_GREEN=\nDB_USER=partsflow\nAPP_DB_BLUE=%s\nAPP_DB_GREEN=%s\n' \
            "$(printf 'a%.0s' $(seq 40))" "$blue_db" "$green_db" > "$dir/env"
    }

    say()  { printf '  ✓ %s\n' "$1"; }
    nope() { red "  ✗ $1"; bad=$((bad + 1)); }

    # Чем обделено окружение — сказать надо ДО того, как случаи покраснеют
    # по чужой причине. Отметки бэкапа читает curl (в пробах — по file://),
    # а в python:3.12-slim его нет вовсе. До задачи 0214 это было незаметно
    # и потому опасно: все случаи про отметки ждали ОТКАЗА, и «curl: command
    # not found» давал ровно ожидаемое «нет» — то есть в окружении без curl
    # они были зелёными, не проверив ничего. Теперь половина их ждёт удаления,
    # и подмена причины видна сразу. Годится образ, где есть и bash, и python3,
    # и curl (python:3.12; slim и bash:5 не годятся).
    local have_curl=yes
    command -v curl >/dev/null 2>&1 || have_curl=""

    # Номер первой строки плана с образцом. Образец, начинающийся с «=», —
    # это ШАГ целиком: «снять метку» (set_env DEPLOY_COPY_DB с пустым
    # значением) иначе совпал бы с «поставить метку», стоящей раньше.
    line_of() {  # образец
        case "$1" in
            =*) printf '%s\n' "$plan" | grep -n -x -F -- "ШАГ: ${1#=}" | head -n1 | cut -d: -f1 ;;
            *)  printf '%s\n' "$plan" | grep -n -F -- "$1" | head -n1 | cut -d: -f1 ;;
        esac
    }

    # План выкладки: переменные оболочки про базы снимаются — у compose они
    # старше .env, и случайно заданная на машине испортила бы проверку.
    plan_of() {  # активная сборка, аргументы…
        local active="$1"; shift
        plan=$(env -u APP_DB_BLUE -u APP_DB_GREEN -u DB_USER ENV_FILE="$dir/env" \
            DEPLOY_ACTIVE="$active" DEPLOY_HISTORY="$dir/h" bash "$0" "$@" --dry-run 2>&1)
        code=$?
    }

    # Порядок в плане: шаг A обязан стоять РАНЬШЕ шага B.
    before() {  # имя случая, образец A, образец B
        local a b
        a=$(line_of "$2")
        b=$(line_of "$3")
        if [ -z "$a" ]; then nope "$1: в плане нет «$2»"; return; fi
        if [ -z "$b" ]; then nope "$1: в плане нет «$3»"; return; fi
        if [ "$a" -lt "$b" ]; then say "$1"; else nope "$1: «$2» стоит после «$3»"; fi
    }

    absent() {  # имя случая, образец
        if [ -n "$(line_of "$2")" ]; then nope "$1: в плане есть «$2»"; else say "$1"; fi
    }

    present() {  # имя случая, образец
        if [ -n "$(line_of "$2")" ]; then say "$1"; else nope "$1: в плане нет «$2»"; fi
    }

    refused_before_changes() {  # имя случая
        if [ "$code" = 0 ]; then
            nope "$1: обязано быть отказом"
        else
            absent "$1: остановлено до единого изменения" "ШАГ:"
        fi
    }

    echo "Самопроверка ops/deploy.sh"

    # 1. Обычная выкладка: заморозка → копия → схема копии → подъём →
    #    готовность → заморозка копии → трафик → самопроверки → точка
    #    невозврата → старая гаснет последней.
    fresh_env
    plan_of app-blue --tag "$sha"
    [ "$code" = 0 ] && say "обычная выкладка проходит" || nope "обычная выкладка упала: $plan"
    # Прежняя база зелёной — замороженный слепок прошлой выкладки. До задачи
    # 0117 она удалялась ПЕРЕД заморозкой, то есть до того, как её сменщицу
    # успевали забэкапить; теперь это последний шаг и с условием.
    before "ПРЕЖНЯЯ БАЗА УДАЛЯЕТСЯ ПОСЛЕ САМОПРОВЕРОК" "deploy-checks.sh" "drop_db $green_db"
    before "прежняя база удаляется после заморозки, а не до неё" "freeze_db $blue_db" "drop_db $green_db"
    before "прежняя база удаляется после открытия записи в копии" "unfreeze_db $copy" "drop_db $green_db"
    before "у прежней базы сперва спрашивают, есть ли она" "db_exists $green_db" "backup_covers $blue_db"
    before "БЭКАП НОВОЙ БАЗЫ СПРАШИВАЕТСЯ ДО УДАЛЕНИЯ ПРЕЖНЕЙ" "backup_covers $blue_db" "drop_db $green_db"
    absent "обычная выкладка про первое обновление не предупреждает" "В НЕРАБОЧЕЕ ВРЕМЯ"
    # Настройки ячейки проверяются раньше, чем тронут хоть что-нибудь: отказ
    # на полпути означал бы ячейку с записанным тегом и без части настроек.
    before "НАСТРОЙКИ ЯЧЕЙКИ ПРОВЕРЯЮТСЯ ДО ПЕРВОЙ ПРАВКИ" "config-guard.sh" "set_env APP_IMAGE_TAG_GREEN"
    # Привезённое обязано начать действовать, а не просто лечь на диск
    # (задача 0216). Порядок: состав настроек проверяется раньше применения —
    # это разные вопросы, — а применение идёт ДО заморозки записи, потому что
    # пересоздание наблюдения не касается ни базы, ни трафика, и внутри окна
    # оно только удлиняло бы простой записи.
    present "ПРИВЕЗЁННОЕ ПРИМЕНЯЕТСЯ, А НЕ ТОЛЬКО ДОСТАВЛЯЕТСЯ" "apply-config.sh --apply"
    before "состав настроек проверяется раньше их применения" "config-guard.sh" "apply-config.sh --apply"
    before "ПРИВЕЗЁННОЕ ПРИМЕНЯЕТСЯ ДО ЗАМОРОЗКИ ЗАПИСИ" "apply-config.sh --apply" "freeze_db $blue_db"
    before "применение раньше подъёма новой сборки" "apply-config.sh --apply" "up -d app-green"
    present "сказано, сколько ждём готовности" "до 120 с"
    # Вход дымового прогона обязан случиться, пока запись ещё открыта: внутри
    # окна он отвечает 503 (сессия — это запись), и пятая самопроверка
    # не проходила там никогда. Первая выкладка кнопкой на ПРОМ упала ровно
    # так (0142), поэтому порядок стережётся, а не помнится.
    before "ВХОД ДЫМОВОГО ПРОГОНА РАНЬШЕ ЗАМОРОЗКИ" "smoke-run.sh --login-only" "freeze_db $blue_db"
    # Порядка мало: вход, случившийся заранее, бесполезен, если признак
    # и банка не доехали до проверок. Каждая из трёх проб ниже возвращает
    # дефект 0142 целиком, а первая редакция самопроверки все три молчала —
    # проверяла только то, что шаг стоит на месте.
    present "признак готовой сессии уезжает в самопроверки" "SMOKE_SESSION_READY=yes"
    # Банка сверяется ВНУТРИ плана, а не с переменной этого процесса: её здесь
    # нет вовсе — план строит отдельный запуск, — и под `set -u` обращение
    # к ней обрывало самопроверку прямо на этой строке. Остаток проб при этом
    # не выполнялся, а вывод выглядел как «всё зелёное до конца».
    # Банка берётся ИЗ НУЖНОЙ СТРОКИ, а не из соседства образцов. Первая
    # редакция требовала, чтобы `SMOKE_JAR=` стоял вплотную к имени скрипта,
    # и краснела на ВЕРНОМ коде, стоило переставить переменные местами или
    # вставить между ними третью (разбор PR #256). Ложная тревога здесь дороже
    # пропуска: на неё натыкается каждый прогон, и кончается это тем, что
    # проверку отключают — вместе с настоящей защитой.
    jar_of() {  # образец строки плана → значение SMOKE_JAR в ней
        printf '%s\n' "$plan" | grep -F "$1" | head -1 \
            | sed -n 's/.*SMOKE_JAR=\([^ ]*\).*/\1/p'
    }
    jar_login=$(jar_of "ops/smoke-run.sh --login-only")
    jar_checks=$(jar_of "ops/deploy-checks.sh")
    if [ -z "$jar_login" ]; then
        nope "у шага входа нет банки cookie"
    elif [ -z "$jar_checks" ]; then
        # Отдельная ветка, а не «разные»: сообщение обязано говорить правду
        # о том, что случилось, иначе чинить будут не то.
        nope "у самопроверок нет банки cookie — сессию не найдут"
    elif [ "$jar_login" = "$jar_checks" ]; then
        say "банка cookie у входа и у самопроверок ОДНА"
    else
        # Фигурные скобки обязательны: bash 3.2 захватывает первый байт
        # кириллической «ёлочки» в имя переменной, и под set -u эта строка
        # обрывала самопроверку молча — на исправном коде ветка не
        # исполняется, поэтому дефект был виден только на подделке.
        nope "банка разная: вход «${jar_login}», проверки «${jar_checks}» — сессию не найдут"
    fi
    # А у дымовой продажи (шаг 6, задача 0145) банка обязана быть СВОЯ.
    # `curl -c` переписывает файл целиком, поэтому общая банка унесла бы
    # сессию, добытую до заморозки, — и самопроверки внутри окна покраснели
    # бы на 503 при полностью исправной сборке. Проба нужна именно потому,
    # что «сэкономить на банке» выглядит безобидно.
    jar_sale=$(jar_of "SMOKE_BUILD=app-green")
    if [ -z "$jar_sale" ]; then
        nope "у дымовой продажи нет банки cookie"
    elif [ "$jar_sale" = "$jar_login" ]; then
        nope "банка продажи та же, что у входа («${jar_sale}»): curl -c перепишет файл, и сессия для самопроверок пропадёт"
    else
        say "банка дымовой продажи ОТДЕЛЬНАЯ от банки входа"
    fi
    # Третья дыра, найденная разбором PR #256: неудачный вход, объявленный
    # удавшимся. Тогда проверки внутри окна пойдут с признаком «сессия есть»,
    # войти не смогут и покраснеют на 503 — то есть дефект 0142 вернётся
    # целиком, а выкладка будет выглядеть исправной до самого конца.
    fresh_env
    plan=$(env -u APP_DB_BLUE -u APP_DB_GREEN -u DB_USER ENV_FILE="$dir/env" DEPLOY_ACTIVE=app-blue \
        DEPLOY_HISTORY="$dir/h" DEPLOY_DRY_FAIL="smoke-run.sh --login-only" \
        bash "$0" --tag "$sha" --dry-run 2>&1)
    case "$plan" in
        *"SMOKE_SESSION_READY=yes"*)
            nope "провалившийся вход объявлен удавшимся — проверки пойдут с чужим признаком" ;;
        *) say "провалившийся вход не объявляется удавшимся" ;;
    esac
    fresh_env
    plan_of app-blue --tag "$sha"

    before "место под копию проверяется ДО заморозки" "check_copy_room $blue_db $copy" "freeze_db $blue_db"
    before "метка выкладки ставится ДО заморозки" "set_env DEPLOY_COPY_DB $copy" "freeze_db $blue_db"
    before "ЗАПИСЬ ЗАМОРОЖЕНА РАНЬШЕ КОПИИ" "freeze_db $blue_db" "copy_db $blue_db $copy"
    before "новая сборка настроена на копию раньше наката" "set_env APP_DB_GREEN $copy" "schema-sync.sh --apply green"
    before "схема приводится на копии раньше подъёма" "schema-sync.sh --apply green" "up -d app-green"
    before "новая сборка настроена на копию раньше подъёма" "set_env APP_DB_GREEN $copy" "up -d app-green"
    before "подъём раньше готовности" "up -d app-green" "wait_healthy app-green"
    before "готовность раньше заморозки копии" "wait_healthy app-green" "freeze_db $copy"
    # Дымовая продажа (задача 0145) идёт по копии, пока та ещё открыта
    # на запись и пока трафик на старой сборке. Обе пробы возвращают дефект
    # целиком: переставь шаг за заморозку копии или за переключение — и он
    # снова окажется там, где запись отбита у всех одинаково.
    before "ДЫМОВАЯ ПРОДАЖА — ПОКА КОПИЯ ОТКРЫТА НА ЗАПИСЬ" "SMOKE_BUILD=app-green" "freeze_db $copy"
    before "ДЫМОВАЯ ПРОДАЖА — ДО ПЕРЕКЛЮЧЕНИЯ ТРАФИКА" "SMOKE_BUILD=app-green" "switch-build.sh green"
    before "продажа идёт после наката схемы копии" "schema-sync.sh --apply green" "SMOKE_BUILD=app-green"
    before "продажа идёт после готовности сборки" "wait_healthy app-green" "SMOKE_BUILD=app-green"
    # Проверяется ВЫКЛАДЫВАЕМАЯ сборка, а не работающая: через терминатор
    # в эту минуту отвечает старая, и прогон по нему проверил бы прежнюю
    # версию — молча и с зелёным исходом.
    absent "продажа не идёт в сборку под трафиком" "SMOKE_BUILD=app-blue"
    # Порядка мало: продажа, вынесенная из окна, бесполезна, если проверки
    # внутри окна всё равно пойдут писать. Признак обязан уехать в них —
    # иначе пятая самопроверка снова упрётся в замороженную копию,
    # и покраснеет ИСПРАВНАЯ сборка. Пробу видно только отсюда:
    # ops/deploy-checks.sh знает, что делать с признаком, но не знает,
    # передаёт ли его кто-нибудь.
    present "ВНУТРИ ОКНА ПРОВЕРКАМ СКАЗАНО, ЧТО ЗАПИСЬ ЗАМОРОЖЕНА" "DEPLOY_WRITE_FROZEN=yes"
    # Шестая проверка сверяет версию поднятой сборки с выкладываемой, и ожидание
    # ей передаёт только этот шаг (задача 0130). Не передали — она сверяет
    # неизвестное с неизвестным и краснеет на ИСПРАВНОЙ выкладке, потому что
    # .env к этой минуте переписан самой выкладкой. Видно это только отсюда:
    # ops/deploy-checks.sh знает, что делать с ожиданием, но не знает,
