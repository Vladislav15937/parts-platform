    present "ОЖИДАЕМАЯ ВЕРСИЯ УЕЗЖАЕТ В САМОПРОВЕРКИ" "DEPLOY_EXPECT_VERSION=$sha"
    before "КОПИЯ ЗАМОРОЖЕНА РАНЬШЕ ТРАФИКА" "freeze_db $copy" "switch-build.sh green"
    before "трафик раньше самопроверок" "switch-build.sh green" "deploy-checks.sh"
    before "метка снимается после самопроверок" "deploy-checks.sh" "=set_env DEPLOY_COPY_DB "
    before "метка снимается ДО открытия записи в копии" "=set_env DEPLOY_COPY_DB " "unfreeze_db $copy"
    before "ЗАПИСЬ В КОПИИ ОТКРЫВАЕТСЯ ТОЛЬКО ПОСЛЕ САМОПРОВЕРОК" "deploy-checks.sh" "unfreeze_db $copy"
    before "СТАРАЯ ГАСНЕТ ПОСЛЕДНЕЙ: после открытия записи" "unfreeze_db $copy" "stop app-blue"
    before "тег ячейки переносится после остановки старой" "stop app-blue" "set_env APP_IMAGE_TAG $sha"
    absent "СТАРАЯ СБОРКА НА КОПИЮ НЕ СМОТРИТ: её база не переписывается" "set_env APP_DB_BLUE"
    absent "старая сборка не перезапускается" "up -d app-blue"
    absent "старая база остаётся замороженной — возврат первых минут" "unfreeze_db $blue_db"
    absent "удачная выкладка копию не удаляет" "drop_db $copy"
    case "$plan" in
        *"ЗАПИСЬ:"*) say "выкладка оставляет запись" ;;
        *) nope "выкладка не оставляет записи" ;;
    esac

    # 2. Любой отказ между заморозкой и точкой невозврата возвращает ВСЁ:
    #    трафик, запись в прежней базе, копию — удаляет. Запись в копии,
    #    которую удаляют, не открывается никогда: иначе люди успели бы
    #    записать туда то, что исчезнет.
    for broken in "copy_db" "schema-sync.sh" "up -d app-green" "wait_healthy" "SMOKE_BUILD=app-green" \
                  "freeze_db $copy" "switch-build.sh green" "deploy-checks.sh"; do
        fresh_env
        plan=$(env -u APP_DB_BLUE -u APP_DB_GREEN -u DB_USER ENV_FILE="$dir/env" DEPLOY_ACTIVE=app-blue \
            DEPLOY_HISTORY="$dir/h" DEPLOY_DRY_FAIL="$broken" bash "$0" --tag "$sha" --dry-run 2>&1)
        code=$?
        [ "$code" != 0 ] && say "отказ на «${broken}» красит выкладку" || nope "отказ на «${broken}» не красит выкладку"
        before "отказ на «${broken}»: трафик возвращается раньше удаления копии" \
            "switch-build.sh blue" "drop_db $copy"
        before "отказ на «${broken}»: новая сборка гаснет раньше удаления копии" \
            "stop app-green" "drop_db $copy"
        before "отказ на «${broken}»: копия удаляется раньше открытия записи в прежней базе" \
            "drop_db $copy" "unfreeze_db $blue_db"
        before "отказ на «${broken}»: метка снимается последней" \
            "unfreeze_db $blue_db" "=set_env DEPLOY_COPY_DB "
        present "отказ на «${broken}»: зелёной возвращается прежняя база" "set_env APP_DB_GREEN $green_db"
        before "отказ на «${broken}»: профили возвращаются на одну сборку" \
            "drop_db $copy" "=set_env COMPOSE_PROFILES blue"
        absent "отказ на «${broken}»: ЗАПИСЬ В УДАЛЯЕМОЙ КОПИИ НЕ ОТКРЫВАЕТСЯ" "unfreeze_db $copy"
        absent "отказ на «${broken}»: старая сборка не гаснет" "stop app-blue"
        absent "отказ на «${broken}»: прежняя база не удаляется" "drop_db $green_db"
        absent "отказ на «${broken}»: тег ячейки не переносится" "set_env APP_IMAGE_TAG $sha"
    done

    # 2б. Отказ дымовой продажи — особый случай, и ради него выбрано место
    #     шага 6: он наступает ДО ТРАФИКА. Люди остаются на старой сборке
    #     и даже не узнают о выкладке, а всё, что прогон записал в копию,
    #     уходит вместе с ней. Этим и куплено право проверять продажу
    #     на выкладываемой сборке, не отменяя атомарности 0112.
    fresh_env
    plan=$(env -u APP_DB_BLUE -u APP_DB_GREEN -u DB_USER ENV_FILE="$dir/env" DEPLOY_ACTIVE=app-blue \
        DEPLOY_HISTORY="$dir/h" DEPLOY_DRY_FAIL="SMOKE_BUILD=app-green" \
        bash "$0" --tag "$sha" --dry-run 2>&1)
    code=$?
    [ "$code" != 0 ] && say "отказ дымовой продажи красит выкладку" || nope "отказ дымовой продажи не красит выкладку"
    absent "отказ продажи: ТРАФИК НА НОВУЮ СБОРКУ НЕ ПЕРЕВОДИЛСЯ" "switch-build.sh green"
    absent "отказ продажи: самопроверки не гонялись" "deploy-checks.sh"
    absent "отказ продажи: копия даже не замораживалась" "freeze_db $copy"
    present "отказ продажи: копия удаляется вместе с записанным в неё" "drop_db $copy"
    present "отказ продажи: запись в прежней базе открывается" "unfreeze_db $blue_db"
    fresh_env
    plan_of app-blue --tag "$sha"

    # 3. Отказ ДО заморозки ничего не замораживает и ничего не откатывает.
    fresh_env
    plan=$(env -u APP_DB_BLUE -u APP_DB_GREEN -u DB_USER ENV_FILE="$dir/env" DEPLOY_ACTIVE=app-blue \
        DEPLOY_HISTORY="$dir/h" DEPLOY_DRY_FAIL="check_copy_room" bash "$0" --tag "$sha" --dry-run 2>&1)
    code=$?
    [ "$code" != 0 ] && say "нет места под копию — отказ" || nope "нет места под копию — не отказ"
    absent "нет места под копию: запись не замораживается" "freeze_db"
    absent "нет места под копию: метка не ставится" "set_env DEPLOY_COPY_DB $copy"

    # 4. Прежняя база выкладываемой сборки, совпадающая с базой под трафиком
    #    (ячейка, не выкладывавшаяся копией: обе на «parts»), не удаляется.
    printf 'COMPOSE_PROFILES=blue\nAPP_IMAGE_TAG=%s\nDB_USER=partsflow\n' "$(printf 'a%.0s' $(seq 40))" > "$dir/env"
    plan_of app-blue --tag "$sha"
    absent "первая выкладка копией: общая «parts» не удаляется" "drop_db parts"
    present "первая выкладка копией: копия снимается с «parts»" "copy_db parts $copy"
    # Первая выкладка копией на боевой ячейке пройдёт со сборкой, которая
    # про заморозку не знает: продавец увидит «Внутреннюю ошибку». Решение
    # владельца от 15 сентября 2026 — нерабочее время и предупреждённый
    # клиент, — и сказать об этом обязана сама выкладка, а не память.
    present "первая выкладка копией предупреждает про нерабочее время" "В НЕРАБОЧЕЕ ВРЕМЯ"

    # 5. Под трафиком зелёная — выкладываем в синюю, копию снимаем с базы зелёной.
    fresh_env
    plan_of app-green --tag "$sha"
    present "под трафиком зелёная — копия снимается с её базы" "copy_db $green_db parts_blue_b1b1b1b1b1b1"
    before "под трафиком зелёная — выкладываем в синюю" "up -d app-blue" "stop app-green"
    absent "под трафиком зелёная — её база не переписывается" "set_env APP_DB_GREEN"

    # 6. «Не трогать» и «база новее образа» не зовут миграцию, но копию и трафик ведут.
    fresh_env
    plan_of app-blue --tag "$sha" --migrations "не трогать"
    absent "не трогать: миграции не зовутся" "schema-sync.sh"
    present "не трогать: копия всё равно снимается" "copy_db $blue_db $copy"
    present "не трогать: код всё же выкладывается" "switch-build.sh green"
    fresh_env
    plan_of app-blue --tag "$sha" --migrate-with none
    absent "откат приложения: схема не опускается и не накатывается" "schema-sync.sh"
    present "откат приложения: тем же путём копии" "copy_db $blue_db $copy"

    # 7. «Только миграции» — на месте: без заморозки, без копии, без трафика,
    #    и образом выкладываемой сборки поверх базы работающей.
    fresh_env
    plan_of app-blue --tag "$sha" --migrations "только миграции"
    present "только миграции: схема базы под трафиком, образом выкладываемой" \
        "env APP_DB_GREEN=$blue_db ops/schema-sync.sh --apply green"
    absent "только миграции: запись не замораживается" "freeze_db"
    absent "только миграции: копии нет" "copy_db"
    absent "только миграции: прежняя база не трогается" "drop_db"
    absent "только миграции: трафик не трогается" "switch-build.sh green"
    absent "только миграции: старая не гаснет" "stop app-blue"

    # 8. Отказы до единого изменения.
    for choice in "обезличенный слепок прома" "эталонный набор"; do
        fresh_env
        plan_of app-blue --tag "$sha" --data "$choice"
        refused_before_changes "«${choice}»"
    done
    fresh_env
    printf 'SPRING_PROFILES=kafka\n' >> "$dir/env"
    plan_of app-blue --tag "$sha"
    refused_before_changes "транспорт Kafka"
    fresh_env
    printf 'DEPLOY_COPY_DB=%s\n' "$copy" >> "$dir/env"
    plan_of app-blue --tag "$sha"
    refused_before_changes "незаконченная прошлая выкладка"

    # 9. Мусор в аргументах — отказ, а не умолчание. Опечатка в «не трогать»
    #    не должна тихо превращаться в накат схемы, а упразднённый откат вниз —
    #    молча выполняться прежним путём.
    for args in "--tag $sha --migrations нетрогать" "--tag короткий" "--tag $sha --migrate-with чужой" \
                "--tag $sha --migrate-with current" "--tag $sha --to 134" "--tag $sha --data чужое"; do
        fresh_env
        # shellcheck disable=SC2086
        if env -u APP_DB_BLUE -u APP_DB_GREEN ENV_FILE="$dir/env" DEPLOY_ACTIVE=app-blue DEPLOY_HISTORY="$dir/h" \
            bash "$0" $args --dry-run >/dev/null 2>&1; then
            nope "«${args}» обязано быть отказом"
        else
            say "«${args}» — отказ"
        fi
    done

    # 10. --abort по метке доделывает откат; без метки — только снимает заморозку.
    fresh_env
    printf 'DEPLOY_COPY_DB=%s\nDEPLOY_COPY_FROM=%s\nDEPLOY_COPY_BUILD=app-green\nDEPLOY_COPY_PREV=%s\n' \
        "$copy" "$blue_db" "$green_db" >> "$dir/env"
    plan_of app-blue --abort
    [ "$code" = 0 ] && say "--abort по метке проходит" || nope "--abort по метке упал: $plan"
    before "--abort: трафик возвращается раньше удаления копии" "switch-build.sh blue" "drop_db $copy"
    before "--abort: копия удаляется раньше открытия записи" "drop_db $copy" "unfreeze_db $blue_db"
    absent "--abort: запись в копии не открывается" "unfreeze_db $copy"
    fresh_env
    plan_of app-blue --abort
    present "--abort без метки: снимается заморозка с базы под трафиком" "unfreeze_if_frozen $blue_db"
    absent "--abort без метки: ничего не удаляется" "drop_db"

    # 11. Удалять базу под трафиком выкладка не вправе — проверка сама по себе.
    if drop_guard parts_x parts_x 2>/dev/null; then
        nope "удаление базы под трафиком обязано быть отказом"
    else
        say "удаление базы под трафиком — отказ"
    fi
    drop_guard parts_x parts_y && say "удаление чужой базы — разрешено" || nope "удаление не своей базы запрещено зря"

    # 12. Правка .env: на месте, с раскомментированием и без потери соседей.
    fresh_env
    ENV_FILE="$dir/env" set_env APP_IMAGE_TAG_GREEN "$sha"
    ENV_FILE="$dir/env" set_env DEPLOY_NEW "значение"
    ENV_FILE="$dir/env" set_env DEPLOY_COPY_DB ""
    if grep -q "^APP_IMAGE_TAG_GREEN=$sha$" "$dir/env" \
        && grep -q "^COMPOSE_PROFILES=blue$" "$dir/env" \
        && grep -q "^DEPLOY_NEW=значение$" "$dir/env" \
        && grep -q "^DEPLOY_COPY_DB=$" "$dir/env" \
        && [ "$(grep -c APP_IMAGE_TAG_GREEN "$dir/env")" = 1 ]; then
        say ".env правится на месте: закомментированный ключ раскрыт, соседи целы, пустое значение пишется"
    else
        nope ".env поправлен неверно: $(tr '\n' '|' < "$dir/env")"
    fi

    # 13. Условие удаления прежней базы спрашивается у ОТМЕТОК бэкапа, а не
    #     подразумевается. Без ячейки и без pushgateway: отметки подкладываются
    #     файлом, а читает их тот же код, что ходит в ячейку, — curl по file://.
    local pgdir="$dir/pg"
    mkdir -p "$pgdir"
    marks_are() { printf '%s\n' "$@" > "$pgdir/metrics"; }
    covers_says() {  # имя случая, база, ожидание (да|нет)
        local got
        if ( PUSHGATEWAY_URL="file://$pgdir"; backup_covers "$2" >/dev/null 2>&1 ); then
            got=да
        else
            got=нет
        fi
        # Скобки у ${got} и ${3} не украшение: bash 3.2 на macOS прихватывает
        # байты кавычки-ёлочки в имя переменной, и при set -u ветка отказа
        # падала бы с «got»: unbound variable» — то есть проверка краснела бы,
        # не назвав случай. Поймано подделкой, а не чтением.
        [ "$got" = "$3" ] && say "$1" || nope "$1: ожидалось «${3}», вышло «${got}»"
    }
    # Слова ворот, а не только их вердикт: базовая копия ворот больше не держит,
    # но обязана НАЗЫВАТЬСЯ — иначе вторая половина состояния бэкапа исчезает
    # с глаз, и «удаляем» звучит как «с точкой возврата всё в порядке».
    covers_words() {  # имя случая, база, образец в выводе
        local out
        out=$( PUSHGATEWAY_URL="file://$pgdir"; backup_covers "$2" 2>&1 )
        case "$out" in
            *"$3"*) say "$1" ;;
            *) nope "$1: в выводе ворот нет «${3}» — вышло «$(printf '%s' "$out" | tr '\n' ' ')»" ;;
        esac
    }
    local dump_new="partsflow_backup_success_timestamp_seconds{db=\"$blue_db\",instance=\"\",job=\"backup\"} 1.7578944e+09"
    local base_after="partsflow_basebackup_success_timestamp_seconds{instance=\"\",job=\"backup\"} 1.7579e+09"
    local base_before="partsflow_basebackup_success_timestamp_seconds{instance=\"\",job=\"backup\"} 1.757e+09"

    if [ -z "$have_curl" ]; then
        say "curl в этом окружении нет — случаи про отметки бэкапа НЕ ПРОВЕРЕНЫ (нужен образ с bash, python3 И curl)"
    else
    marks_are ""
    covers_says "отметок бэкапа нет вовсе — прежнюю базу не трогаем" "$blue_db" нет

    marks_are "partsflow_backup_success_timestamp_seconds{db=\"parts_blue_pozavchera\",instance=\"\",job=\"backup\"} 1.7578944e+09" \
              "$base_after"
    covers_says "ДАМП СНЯТ ПО ЧУЖОЙ БАЗЕ — не считается" "$blue_db" нет

    marks_are "$dump_new"
    covers_says "дамп есть, базовой копии не было вовсе — удаление проходит по дампу" "$blue_db" да
    covers_words "и про отсутствие точки возврата сказано словами" "$blue_db" "точки возврата у ячейки нет"

    # ВАРИАНТ Б (задача 0214, решение владельца от 28 сентября 2026). Это
    # состояние ячейки шесть суток из семи: ночной дамп обновляется каждую ночь
    # и снова оказывается свежее недельной базовой копии. Прежняя редакция
    # отвечала здесь «нет» — то есть самоочистка не работала ВОВСЕ, и каждая
    # выкладка оставляла замороженную базу, которую больше не называл ни один
    # ключ .env (четыре таких на боевой ячейке, 86 МБ).
    marks_are "$dump_new" "$base_before"
    covers_says "БУДНИ: базовая копия старше ночного дампа — удаление ПРОХОДИТ" "$blue_db" да
    covers_words "БУДНИ: базовая копия названа, но ворот не держит" "$blue_db" "на удаление это не влияет"

    marks_are "# TYPE partsflow_backup_success_timestamp_seconds gauge" \
              "partsflow_photo_backup_success_timestamp_seconds{instance=\"\",job=\"backup\"} 1.7578944e+09" \
              "$dump_new" "$base_after"
    covers_says "дамп по этой базе и базовая копия свежее него — удаляем" "$blue_db" да

    if ( PUSHGATEWAY_URL="http://127.0.0.1:1"; backup_covers "$blue_db" >/dev/null 2>&1 ); then
        nope "отметок не спросить — обязано быть отказом"
    else
        say "отметок не спросить — прежнюю базу не трогаем"
    fi
    fi

    # Локаль с запятой в дробях. Без LC_ALL=C у awk «1.7578944e+09» читается
    # как 1 — и с варианта Б (0214) это видно уже не по вердикту, а по времени:
    # человеку печатается «дамп 01.01 07:00» вместо настоящей ночи, а из двух
    # отметок «самой свежей» становится любая. Поэтому проверяется само
    # прочитанное время. Локали может не быть на машине — тогда случай честно
    # называется непроверенным, а не молча засчитывается.
    # Локаль берётся не по имени, а по тому, что она на самом деле говорит
    # про дробный разделитель: имя в списке ещё не значит, что запятая там
    # есть, и случай молча выродился бы в проверку ни о чём. И LC_ALL надо
    # ЭКСПОРТИРОВАТЬ: без export это переменная оболочки, awk её не видит —
    # на этом проверка сначала и осталась зелёной на сломанном коде.
    local zapiataya loc
    zapiataya=""
    for loc in $(locale -a 2>/dev/null | grep -iE '^(ru_RU|de_DE|fr_FR|pt_BR)\.(utf-?8)$'); do
        [ "$(LC_ALL="$loc" locale decimal_point 2>/dev/null)" = "," ] || continue
        zapiataya="$loc"
        break
    done
    if [ -n "$zapiataya" ]; then
        local loc_got
        loc_got=$( export LC_ALL="$zapiataya"; mark_ts "$dump_new" "^partsflow_backup_success_timestamp_seconds" )
        if [ "$loc_got" = 1757894400 ]; then
            say "локаль с запятой в дробях (${zapiataya}) время отметки не ломает"
        else
            nope "локаль ${zapiataya}: время отметки прочитано как «${loc_got}» вместо 1757894400"
        fi
    else
        say "локали с запятой в дробях на этой машине нет — случай не проверен"
    fi

    # 14. Тот же образ в ту же сборку (откат приложения): имя копии совпало бы
    #     с прежней базой этой сборки, а она теперь живёт до конца выкладки.
    printf 'COMPOSE_PROFILES=blue\nAPP_IMAGE_TAG=%s\nDB_USER=partsflow\nAPP_DB_BLUE=%s\nAPP_DB_GREEN=%s\n' \
        "$(printf 'a%.0s' $(seq 40))" "$blue_db" "$copy" > "$dir/env"
    plan_of app-blue --tag "$sha"
    [ "$code" = 0 ] && say "повторная выкладка того же образа проходит" || nope "повторная выкладка упала: $plan"
    present "повторный тот же образ: копия берёт свободное имя" "copy_db $blue_db ${copy}_2"
    before "повторный тот же образ: прежняя база удаляется в конце" "deploy-checks.sh" "drop_db $copy"

    # 15. Перечень баз ячейки (задача 0195). Дефектов было два, и закрывать надо
    #     оба: прежнюю базу, которую инструмент назвать МОЖЕТ, никто
    #     не напоминал удалить; а базу, не названную ни APP_DB_BLUE,
    #     ни APP_DB_GREEN, не видел вообще никто — ни бэкап, ни выкладка,
    #     ни одна тревога. Разбор кормится подложенной таблицей той же формы,
    #     что отдаёт Postgres, поэтому «кто есть кто» проверяется без docker
    #     и без ячейки.
    local strange=parts verify_db out inv_code table
    verify_db=$(verify_check_db)
    if [ -n "$verify_db" ]; then
        say "имя рабочей базы проверки бэкапа читается из ops/verify-backup.sh (${verify_db})"
    else
        nope "имя рабочей базы проверки бэкапа в ops/verify-backup.sh не нашлось — перечень будет звать её посторонней каждую неделю"
    fi

    row_of() {  # имя базы → её строки перечня (их две: кто она и чем живёт)
        # Обе строки, а не первая: размер, заморожённость и число соединений
        # стоят второй строкой, и проба по одной первой молча перестала бы
        # проверять заморожённость — это случилось при первой же правке
        # вывода (столбцы пробелами разъезжались на кириллице).
        printf '%s\n' "$out" | grep -A1 -E "^  $1( |$)" | head -n2
    }
    says() {  # имя случая, текст, образец
        case "$2" in *"$3"*) say "$1" ;; *) nope "$1: в выводе нет «$3»" ;; esac
    }
    says_not() {  # имя случая, текст, образец
        case "$2" in *"$3"*) nope "$1: в выводе есть «$3»" ;; *) say "$1" ;; esac
    }

    # Журнал выкладок — единственное место, где записано, с какого числа база
    # не в работе: у Postgres времени создания базы не спросить вовсе.
    HISTORY="$dir/hist"
    printf '2026-09-19T21:03:11Z\tprom\t%s\tvladislav\tвыкладка\tмиграции: apply\tбаза: %s → %s\tуспех\n' \
        "$sha" "$strange" "$green_db" > "$HISTORY"

    table=$(printf '%s|432013312|0|t|7\n%s|398458880|1|t|0\n%s|390070272|1|t|0\n%s|8388608|0|t|0\n' \
        "$blue_db" "$green_db" "$strange" "${verify_db:-parts_verify}")
    out=$(db_inventory_report "$table" "$blue_db" "$green_db" "" 2>&1)
    inv_code=$?

    says "ПОСТОРОННЯЯ БАЗА НАЗВАНА ПОСТОРОННЕЙ" "$(row_of "$strange")" "ПОСТОРОННЯЯ"
    [ "$inv_code" = 1 ] && say "перечень с посторонней базой отвечает ненулевым кодом" \
        || nope "перечень с посторонней базой ответил кодом ${inv_code}, а не 1"
    says "сказано, что посторонней базы не видит ни один инструмент" "$out" "не видит ни один инструмент"
    says "посторонняя база сама не удаляется — сказано словами" "$out" "руками и глазами"
    says "база под трафиком названа своим делом" "$(row_of "$blue_db")" "под трафиком"
    says_not "БАЗА ПОД ТРАФИКОМ НЕ ОБЪЯВЛЕНА ПОСТОРОННЕЙ" "$(row_of "$blue_db")" "ПОСТОРОННЯЯ"
    says "база второй сборки названа базой второй сборки" "$(row_of "$green_db")" "база второй сборки"
    says_not "база второй сборки не объявлена посторонней" "$(row_of "$green_db")" "ПОСТОРОННЯЯ"
    says "ЗАМОРОЖЕННОСТЬ НАЗЫВАЕТСЯ ТОЖЕ" "$(row_of "$green_db")" "заморожена"
    says "работающая база названа пишущей" "$(row_of "$blue_db")" "пишется"
    # Ложная тревога здесь дороже пропуска: рабочая база недельной проверки
    # бэкапа лежит в ячейке между прогонами, и перечень, кричащий на неё
    # «волк», перестанут читать.
    says_not "рабочая база проверки бэкапа не объявлена посторонней" \
        "$(row_of "${verify_db:-parts_verify}")" "ПОСТОРОННЯЯ"
    says "С КАКОГО ЧИСЛА БАЗА НЕ В РАБОТЕ — НАЗВАНО ЧИСЛОМ" "$out" "2026-09-19T21:03:11Z"
    says "у прежней базы названо условие, по которому её удалят" "$out" "задача 0117"
    says "сказано, сколько занимают посторонние базы" "$out" "Посторонних баз: 1"

    # 15б. Обратный край: посторонних нет — перечень зелёный и говорит об этом.
    #      Сторож, красный на исправной ячейке, отключат первым — вместе
    #      с защитой.
    out=$(db_inventory_report "$(printf '%s|432013312|0|t|7\n%s|398458880|1|t|0\n' "$blue_db" "$green_db")" \
        "$blue_db" "$green_db" "" 2>&1)
    inv_code=$?
    [ "$inv_code" = 0 ] && say "перечень без посторонних баз — зелёный" \
        || nope "перечень без посторонних баз ответил кодом ${inv_code}"
    says "перечень без посторонних говорит об этом словами" "$out" "Посторонних баз нет"

    # 15в. Копия идущей выкладки — не посторонняя: во время выкладки ключ .env
    #      уже указывает на неё, и обругать её значило бы краснеть каждый раз,
    #      когда кто-то смотрит перечень в окне выкладки.
    out=$(db_inventory_report "$(printf '%s|432013312|0|t|7\n%s|398458880|1|t|0\n' "$blue_db" "$copy")" \
        "$blue_db" "$copy" "$copy" 2>&1)
    inv_code=$?
    says "копия идущей выкладки названа копией" "$(row_of "$copy")" "копия идущей выкладки"
    [ "$inv_code" = 0 ] && say "копия идущей выкладки перечень не краснит" \
        || nope "копия идущей выкладки покрасила перечень (код ${inv_code})"

    # 15г. Перечень доезжает до человека сам, а не только по отдельной команде:
    #      в конце выкладки и в --drop-previous. Без этого дефект 1 остаётся —
    #      прежнюю базу никто не напоминает убрать.
    fresh_env
    plan_of app-blue --tag "$sha"
    present "ПЕРЕЧЕНЬ БАЗ ПЕЧАТАЕТСЯ ШАГОМ ВЫКЛАДКИ" "db_inventory $copy $blue_db"
    before "перечень печатается после разбора с прежней базой" "drop_db $green_db" "db_inventory"
    before "перечень печатается после точки невозврата" "unfreeze_db $copy" "db_inventory"
    fresh_env
    plan_of app-blue --drop-previous
    [ "$code" = 0 ] && say "--drop-previous проходит" || nope "--drop-previous упал: $plan"
    present "--DROP-PREVIOUS ПЕРЕЧИСЛЯЕТ БАЗЫ ЯЧЕЙКИ" "db_inventory $blue_db $green_db"
    before "--drop-previous: перечень после разбора с прежней базой" "drop_db $green_db" "db_inventory"

    # Посторонняя база не отменяет удавшейся выкладки: отказ перечня её
    # не красит. Обратное означало бы красную выкладку за то, что человеку
    # всего лишь сообщили.
    fresh_env
    plan=$(env -u APP_DB_BLUE -u APP_DB_GREEN -u DB_USER ENV_FILE="$dir/env" DEPLOY_ACTIVE=app-blue \
        DEPLOY_HISTORY="$dir/h" DEPLOY_DRY_FAIL="db_inventory" bash "$0" --tag "$sha" --dry-run 2>&1)
    code=$?
    [ "$code" = 0 ] && say "отказ перечня баз выкладку не красит" || nope "отказ перечня баз покрасил выкладку"

    # Бэкапа по новой базе нет — прежняя остаётся (условие 0117, оно обязано
    # остаться зелёным), выкладка зелёная, и оставшаяся база НАЗВАНА вместе
    # с тем, чем её потом искать: ровно этого и не было до задачи 0195.
    fresh_env
    plan=$(env -u APP_DB_BLUE -u APP_DB_GREEN -u DB_USER ENV_FILE="$dir/env" DEPLOY_ACTIVE=app-blue \
        DEPLOY_HISTORY="$dir/h" DEPLOY_DRY_FAIL="backup_covers" bash "$0" --tag "$sha" --dry-run 2>&1)
    code=$?
    [ "$code" = 0 ] && say "бэкапа новой базы нет — выкладка всё равно зелёная" \
        || nope "бэкапа новой базы нет — выкладка покраснела"
    case "$plan" in
        *"drop_db $green_db"*) nope "УСЛОВИЕ 0117: прежняя база удалена без бэкапа новой" ;;
        *) say "УСЛОВИЕ 0117: без бэкапа новой базы прежняя не удаляется" ;;
    esac
    says "оставшаяся база: сказано, чем её потом найти" "$plan" "--databases"
    says "оставшаяся база: сказано, что называть её больше некому" "$plan" "не сможет ни один ключ"
    fresh_env
    plan_of app-blue --tag "$sha"

    # 15д. ВОЗВРАТ ДЕФЕКТА. Копия скрипта, в которой перечень не отличает
    #      постороннюю базу от своей (а в нынешней main перечня нет вовсе),
    #      обязана валить ЭТУ САМУЮ самопроверку — и валить именно на признаке
    #      посторонней базы. Без этого случая все пробы выше ничего
    #      не утверждают: зелёная проба не доказывает, что краснеет сторож.
    #      Копия кладётся в ops/, а не в /tmp: скрипт делает cd в корень
    #      репозитория от своего каталога, и копия из /tmp ушла бы в корень
    #      файловой системы (урок задачи 0151).
    if [ -n "${DEPLOY_SELFTEST_FAKE:-}" ]; then
        say "подделка своей копии не заводит — рекурсии нет"
    else
        local fake fake_out fake_code
        fake=$(mktemp ops/.deploy-0195-XXXXXX 2>/dev/null) || fake=""
        if [ -z "$fake" ]; then
            nope "подделку некуда положить — возврат дефекта не проверен"
        else
            sed 's/^ *role="ПОСТОРОННЯЯ.*$/            role="база ячейки"/' "$0" > "$fake"
            # Проверяется, что подделанная строка ПОЯВИЛАСЬ, а не что прежняя
            # исчезла: «role="ПОСТОРОННЯЯ» встречается и в самих пробах выше
            # (в образце этого же sed), поэтому поиск исчезновения находил бы
            # свой собственный текст и объявлял подделку непоставленной —
            # на исправном коде. Проверка, которая краснеет не тем местом,
            # хуже отсутствующей.
            if ! grep -q '^ *role="база ячейки"$' "$fake"; then
                nope "подделку негде поставить: строки, которой перечень отличает постороннюю базу, не нашлось"
            else
                fake_out=$(DEPLOY_SELFTEST_FAKE=yes bash "$fake" --selftest 2>&1)
                fake_code=$?
                if [ "$fake_code" = 0 ]; then
                    nope "ВОЗВРАТ ДЕФЕКТА: перечень, не отличающий постороннюю базу, самопроверку ПРОШЁЛ"
                else
                    case "$fake_out" in
                        *ПОСТОРОННЯЯ*) say "ВОЗВРАТ ДЕФЕКТА: подделка валит самопроверку, и валит на признаке посторонней базы" ;;
                        *) nope "подделка покраснела не тем местом: $(printf '%s\n' "$fake_out" | grep '✗' | head -2 | tr '\n' ' ')" ;;
                    esac
                fi
            fi
            rm -f "$fake"
        fi
    fi

    # 16. Отметка берётся САМАЯ СВЕЖАЯ, а не последняя напечатанная (задача 0214,
    #     пункт 6). Живого дефекта сегодня нет — под выражение подходит ровно
    #     одна строка, — но это свойство ДАННЫХ, а не проверки: pushgateway
    #     переотдаёт отметки, и вторая строка того же семейства ответ уводит.
    local two_marks freshest one_mark
    one_mark="partsflow_backup_success_timestamp_seconds{db=\"$blue_db\"}"
    two_marks=$(printf '%s 1.7579e+09\n%s 1.757e+09\n' "$one_mark" "$one_mark")
    freshest=$(mark_ts "$two_marks" "^partsflow_backup_success_timestamp_seconds")
    [ "$freshest" = 1757900000 ] \
        && say "ОТМЕТКА БЕРЁТСЯ САМАЯ СВЕЖАЯ, а не последняя в выводе" \
        || nope "из двух отметок взята «${freshest}», а не самая свежая 1757900000"

    # 17. КТО ЗОВЁТ ВОРОТА УДАЛЕНИЯ — перебором по файлу, а не списком из задачи
    #     (пункт 9 приёмки 0214). Вариант Б снял требование базовой копии ТОЛЬКО
    #     у ворот удаления; то же условие, позванное откуда-то ещё, охраняло бы
    #     точку возврата, а там ослаблять его владелец не разрешал. Поэтому
    #     каждый зовущий назван вместе с ответом «про удаление он или про точку
    #     возврата»:
    #       backup_covers — сами ворота (определение);
    #       drop_previous — УДАЛЕНИЕ: решает, снести ли прежнюю базу;
    #       databases_now — тот же вопрос человеку («уже можно убрать» / «пока
    #                       не снялся»), и он обязан звать ТО ЖЕ место: второе,
    #                       знающее условие, разошлось бы с первым (пункт 2).
    #     Про точку возврата ворота не спрашивает никто — за ней следят
    #     ops/alerts.yml (БазоваяКопияНеСнималась) и недельная репетиция
    #     ops/restore-pitr.sh --verify, и они этой правкой не тронуты.
    local callers known
    callers=$(covers_callers "$0" backup_covers | tr '\n' ' ')
    known="backup_covers databases_now drop_previous "
    if [ "$callers" = "$known" ]; then
        say "ВОРОТА УДАЛЕНИЯ ЗОВУТ ТОЛЬКО НАЗВАННЫЕ: ${callers}"
    else
        nope "у ворот удаления другой состав зовущих: названы «${known}», в файле «${callers}» — нового назовите и скажите, про удаление он или про точку возврата (задача 0214)"
    fi

    # 18. ВОЗВРАТ ДЕФЕКТА — две подделки, каждая возвращает свою половину правки
    #     и обязана валить ЭТУ САМУЮ самопроверку, причём своим случаем. Зелёная
    #     проба сама по себе не доказывает ничего (урок 0142). Копия кладётся
    #     в ops/, а не в /tmp: скрипт уходит в корень репозитория от своего
    #     каталога, и копия из /tmp ушла бы в корень файловой системы (урок
    #     0151). Целость копии проверяется ДО запуска: красное от сломанного
    #     синтаксиса не говорило бы ни о чём (урок 0198).
    if [ -n "${DEPLOY_SELFTEST_FAKE:-}" ]; then
        say "подделок ворот удаления не заводим — рекурсии нет"
    else
        returns_defect() {  # имя случая, программа sed, образец подделки, образец красного
            local f out rc
            f=$(mktemp ops/.deploy-0214-XXXXXX 2>/dev/null) || f=""
            if [ -z "$f" ]; then nope "$1: подделку некуда положить — возврат дефекта не проверен"; return; fi
            sed "$2" "$0" > "$f"
            if ! grep -q -- "$3" "$f"; then
                nope "$1: подделку негде поставить — строки, которую она правит, в файле нет"
                rm -f "$f"; return
            fi
            if ! bash -n "$f" 2>/dev/null; then
                nope "$1: подделка синтаксически сломана — её красное говорило бы не о том"
                rm -f "$f"; return
            fi
            out=$(DEPLOY_SELFTEST_FAKE=yes bash "$f" --selftest 2>&1)
            rc=$?
            rm -f "$f"
            if [ "$rc" = 0 ]; then
                nope "ВОЗВРАТ ДЕФЕКТА, $1: подделка самопроверку ПРОШЛА"
                return
            fi
            case "$out" in
                *"$4"*) say "ВОЗВРАТ ДЕФЕКТА, $1: подделка валит самопроверку — и валит на «$4»" ;;
                *) nope "ВОЗВРАТ ДЕФЕКТА, $1: подделка покраснела не тем местом: $(printf '%s\n' "$out" | grep '✗' | head -2 | tr '\n' ' ')" ;;
            esac
        }
        # 18а. Прежнее условие обратно: базовая копия старше дампа снова запирает
        #      удаление. Это состояние ячейки шесть суток из семи — то есть
        #      подделка возвращает ровно тот дефект, из-за которого на боевой
        #      ячейке лежали четыре посторонние базы.
        if [ -n "$have_curl" ]; then
            returns_defect "требование базовой копии вернули к воротам удаления" \
                's/^\( *\)elif \[ "$base" -lt "$dump" \]; then$/\1elif [ "$base" -lt "$dump" ]; then return 1/' \
                'then return 1' "БУДНИ"
        else
            say "curl'а нет — возврат дефекта по базовой копии НЕ ПРОВЕРЕН: ему нужен случай БУДНИ"
        fi
        # 18б. Третий зовущий, появившийся молча: он получил бы ослабление вместе
        #      с именем функции, и перебор обязан назвать это.
        returns_defect "у ворот удаления появился незаявленный зовущий" \
            's|^    step "Прежняя база сборки .*|    backup_covers "$heir" >/dev/null 2>\&1 \|\| true|' \
            'backup_covers "$heir" >/dev/null' "состав зовущих"
        # 18в. Тот же зовущий, дописанный НЕ в функцию, а в верхнеуровневый
        #      диспетчер. Первая редакция сторожа обрывала разбор на заголовке
        #      selftest() и до этих строк не доходила вовсе — такая подделка
        #      проходила молча (нашёл разбор PR #319 попыткой; чинится здесь
        #      решением владельца «продолжай волну — чини здесь»). Ветка
        #      --databases выбрана потому, что самопроверка её не запускает:
        #      подделку обязан поймать перебор, а не случайное исполнение.
        returns_defect "зовущий дописан в верхнеуровневый диспетчер, мимо функций" \
            's|^    databases_now$|    backup_covers "${SNEAKY_WIPE:-x}" >/dev/null 2>\&1 \|\| true; databases_now|' \
            'backup_covers "${SNEAKY_WIPE:-x}"' "состав зовущих"
    fi

    # 19. ПОВТОР ТОГО ЖЕ КОММИТА НАЗЫВАЕТСЯ СЛОВАМИ, И ДО ЕДИНОГО ИЗМЕНЕНИЯ
    #     (задача 0223). Три исхода проверяются все три, и два из них —
    #     МОЛЧАНИЕМ: проверка, окликающая законный путь, хуже отсутствующей,
    #     а «не красим, только словами» означает, что краснеть не будет ничто —
    #     значит доказывать надо слова и молчание, а не цвет.
    local live out vcode gho wf nv nr
    live=$(printf 'a%.0s' $(seq 40))   # тег, который fresh_env ставит под трафик
    fresh_env
    plan_of app-blue --tag "$live"
    [ "$code" = 0 ] && say "ПОВТОР ВЫКЛАДКУ НЕ ОСТАНАВЛИВАЕТ: сообщает и продолжает" \
        || nope "повтор остановил выкладку, а решение владельца — «не красим, только словами»: $plan"
    present "ПОВТОР НАЗВАН СЛОВАМИ" "уже под трафиком"
    # Назван ИСХОД, а не два значения рядом: два значения в отчёте кнопки были
    # и 29 сентября — соседними строками «Версия» и «Было», — и именно на них
    # никто не посмотрел.
    present "НАЗВАН ИСХОД, А НЕ ДВА ЗНАЧЕНИЯ РЯДОМ" "не привезёт нового"
    before "ПОВТОР НАЗВАН ДО ПЕРВОЙ ПРАВКИ ЯЧЕЙКИ" "уже под трафиком" "config-guard.sh"
    before "повтор назван до заморозки записи" "уже под трафиком" "freeze_db $blue_db"
    before "повтор назван до копии базы" "уже под трафиком" "copy_db $blue_db"
    present "ПОВТОР ВИДЕН В ЖУРНАЛЕ ВЫКЛАДОК" "привезла: ничего"

    # Другой коммит — самый частый и совершенно законный путь: ни слова.
    fresh_env
    plan_of app-blue --tag "$sha"
    absent "ДРУГОЙ КОММИТ: ПРО ПОВТОР НИ СЛОВА" "уже под трафиком"
    absent "другой коммит: и «сравнить не с чем» не говорится" "СРАВНИТЬ НЕ С ЧЕМ"
    present "журнал выкладок называет, что привезли" "привезла: новую версию"

    # Откат приложения: под трафиком B, в свободный цвет возвращают прежний A.
    # Ключ ВТОРОЙ сборки при этом совпадает с выкладываемым законно — потому
    # и сравнивается APP_IMAGE_TAG, версия под трафиком, а не он.
    printf 'COMPOSE_PROFILES=blue,green\nAPP_IMAGE_TAG=%s\nAPP_IMAGE_TAG_GREEN=%s\nDB_USER=partsflow\nAPP_DB_BLUE=%s\nAPP_DB_GREEN=%s\n' \
        "$live" "$sha" "$blue_db" "$green_db" > "$dir/env"
    plan_of app-blue --tag "$sha"
    absent "ОТКАТ ПРИЛОЖЕНИЯ МОЛЧИТ: тот же SHA во второй сборке, под трафиком другой" "уже под трафиком"

    # «Только миграции» тем же коммитом — законная починка схемы на месте:
    # ни копии, ни переключения, ни заморозки, то есть цены повтора нет вовсе.
    fresh_env
    plan_of app-blue --tag "$live" --migrations "только миграции"
    [ "$code" = 0 ] && say "«только миграции» тем же коммитом проходит" \
        || nope "«только миграции» тем же коммитом упало: $plan"
    absent "«ТОЛЬКО МИГРАЦИИ» ТЕМ ЖЕ КОММИТОМ МОЛЧИТ" "уже под трафиком"
    # Настройки приезжают тем же rsync'ом и на этом пути: применять их надо
    # и здесь, иначе «только миграции» оставляли бы привезённое лежать.
    present "«ТОЛЬКО МИГРАЦИИ» ТОЖЕ ПРИМЕНЯЕТ ПРИВЕЗЁННОЕ" "apply-config.sh --apply"

    # Третий исход: тега в .env нет вовсе — сравнивать не с чем, и это НЕ
    # «сходится» (три исхода вместо двух — образец tools/head-green.sh).
    printf 'COMPOSE_PROFILES=blue\nDB_USER=partsflow\nAPP_DB_BLUE=%s\nAPP_DB_GREEN=%s\n' \
        "$blue_db" "$green_db" > "$dir/env"
    plan_of app-blue --tag "$sha"
    [ "$code" = 0 ] && say "«сравнивать не с чем» — не отказ" \
        || nope "ячейка без APP_IMAGE_TAG получила отказ: $plan"
    present "ТРЕТИЙ ИСХОД НАЗВАН СВОИМИ СЛОВАМИ" "СРАВНИТЬ НЕ С ЧЕМ"
    absent "третий исход не выдан за повтор" "уже под трафиком"
    present "журнал выкладок не выдаёт третий исход за поставку" "привезла: неизвестно"

    # 20. ВТОРАЯ ПОВЕРХНОСТЬ: тот же вердикт отдельной командой. Им спрашивает
    #     кнопка — у неё .env ячейки нет вовсе, версия под трафиком приезжает
    #     отдельным шагом по ssh. Одна поверхность без другой — это заведённый
    #     своими руками класс 2 «две поверхности отвечают по-разному».
    verdict_out() {  # выкладываемый, под трафиком → вывод команды
        ENV_FILE="$dir/env" bash "$0" --verdict --tag "$1" --current "$2" 2>&1
    }
    out=$(verdict_out "$live" "$live"); vcode=$?
    if [ "$vcode" != 0 ]; then
        nope "--verdict на повторе отдал код ${vcode} — шаг кнопки покраснел бы, а решено «не красим»"
    else
        case "$out" in
            *"уже под трафиком"*) say "--VERDICT НА ПОВТОРЕ ГОВОРИТ ТО ЖЕ, ЧТО ВЫКЛАДКА" ;;
            *) nope "--verdict на повторе молчит: «$(printf '%s' "$out" | tr '\n' ' ')»" ;;
        esac
    fi
    out=$(verdict_out "$sha" "$live")
    if [ -z "$out" ]; then
        say "--verdict на другом коммите МОЛЧИТ"
    else
        nope "--verdict окликает законный путь: «$(printf '%s' "$out" | tr '\n' ' ')»"
    fi
    out=$(verdict_out "$sha" "")
    case "$out" in
        *"СРАВНИТЬ НЕ С ЧЕМ"*) say "--verdict: версия под трафиком не названа — третий исход" ;;
        *) nope "--verdict принял пустую версию под трафиком за «сходится»: «$(printf '%s' "$out" | tr '\n' ' ')»" ;;
    esac
    # Клетка отчёта прогона — оттуда же, а не сочинённая в кнопке второй раз.
    gho="$dir/gho"
    : > "$gho"
    ( ENV_FILE="$dir/env"; GITHUB_OUTPUT="$gho"; export GITHUB_OUTPUT
      bash "$0" --verdict --tag "$live" --current "$live" --github-output >/dev/null 2>&1 )
    if grep -q '^verdict=повтор$' "$gho" && grep -q '^verdict_brought=ничего' "$gho"; then
        say "КНОПКЕ ОТДАЮТСЯ ИСХОД И СЛОВА ДЛЯ ОТЧЁТА"
    else
        nope "кнопке нечего поставить в отчёт: «$(tr '\n' '|' < "$gho")»"
    fi

    # 21. КНОПКА ЗОВЁТ ВЕРДИКТ, И ДО ПЕРВОГО ИЗМЕНЕНИЯ СТЕНДА. Руками
    #     выкладывают ровно тогда, когда кнопка недоступна, поэтому ответ нужен
    #     обеим поверхностям. На самой ячейке .github рядом нет — там случай
    #     пропускается СЛОВАМИ, а не молча.
    wf=.github/workflows/deploy.yml
    if [ ! -f "$wf" ]; then
        say "кнопки рядом нет (так выглядит ячейка) — её порядок проверяет прогон"
    else
        nv=$(grep -n -- '--verdict' "$wf" | head -n1 | cut -d: -f1)
        nr=$(grep -n 'rsync -az --delete' "$wf" | head -n1 | cut -d: -f1)
        if [ -z "$nv" ]; then
            nope "КНОПКА ВЕРДИКТ НЕ ЗОВЁТ: в ${wf} нет ops/deploy.sh --verdict — вторая поверхность без ответа"
        elif [ -z "$nr" ]; then
            nope "в ${wf} не найден rsync настроек — не с чем сверить порядок"
        elif [ "$nv" -lt "$nr" ]; then
            say "КНОПКА СПРАШИВАЕТ ВЕРДИКТ ДО ПЕРВОГО ИЗМЕНЕНИЯ СТЕНДА"
        else
            nope "кнопка спрашивает вердикт ПОСЛЕ rsync'а настроек — сказанное после изменения ничего не спасает"
        fi
    fi

    # 22. ВОЗВРАТ ДЕФЕКТА 0223 — четыре подделки, и каждая обязана валить
    #     СВОЙ случай: снятый вердикт, сравнение не с тем ключом, третий исход,
    #     сведённый к «сходится», и вердикт, окликающий законный путь.
    if [ -n "${DEPLOY_SELFTEST_FAKE:-}" ]; then
        say "подделок вердикта не заводим — рекурсии нет"
    else
        returns_defect "вердикт сняли вовсе — вернулась выкладка 29 сентября" \
            's|^        same_commit_verdict "$TAG" .*|        VERDIKT_SNYAT=yes|' \
            'VERDIKT_SNYAT=yes' "ПОВТОР НАЗВАН СЛОВАМИ"
        returns_defect "сравнение ушло на ключ второй сборки, а не на версию под трафиком" \
            's|read_env APP_IMAGE_TAG)|read_env APP_IMAGE_TAG_GREEN)|' \
            'read_env APP_IMAGE_TAG_GREEN)' "ОТКАТ ПРИЛОЖЕНИЯ МОЛЧИТ"
        returns_defect "третий исход сведён к «сходится»" \
            's|^    if \[ -z "$2" \]; then$|    if false; then|' \
            '    if false; then' "ТРЕТИЙ ИСХОД НАЗВАН СВОИМИ СЛОВАМИ"
        returns_defect "вердикт стал окликать законный путь" \
            's|^    elif \[ "$1" = "$2" \]; then$|    elif true; then|' \
            '    elif true; then' "ДРУГОЙ КОММИТ: ПРО ПОВТОР НИ СЛОВА"
        # 23. ВОЗВРАТ ДЕФЕКТА 0216: шаг применения сняли — и выкладка снова
        #     только доставляет настройки. Это ровно то состояние, в котором
        #     ячейка прожила случаи 19 и 20 сентября 2026.
        returns_defect "шаг применения сняли — привезённое снова только лежит" \
            's|^    run ops/apply-config.sh --apply .*|    PRIMENENIE_SNYATO=yes|' \
            'PRIMENENIE_SNYATO=yes' "ПРИВЕЗЁННОЕ ПРИМЕНЯЕТСЯ"
    fi

    if [ "$bad" != 0 ]; then
        red "Самопроверка не прошла: $bad"
        return 1
    fi
    green "Самопроверка пройдена"
    return 0
}

