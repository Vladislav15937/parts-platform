#!/usr/bin/env bash
# Выкладка на стенд одной командой: база едет вместе со сборкой — всё новое
# или ничего.
#
#   ops/deploy.sh --tag <SHA>                          обычная выкладка
#   ops/deploy.sh --tag <SHA> --migrations не-трогать  копия без наката схемы
#   ops/deploy.sh --tag <SHA> --migrations только      привести схему НА МЕСТЕ и выйти
#   ops/deploy.sh --tag <SHA> --migrate-with none      база новее образа (откат приложения)
#   ops/deploy.sh --abort                              доделать откат оборвавшейся выкладки
#   ops/deploy.sh --drop-previous                      убрать прежнюю базу, когда по новой снялся дамп
#   ops/deploy.sh --databases                          какие базы лежат в ячейке и кто они
#   ops/deploy.sh --verdict --tag <SHA>                не то же ли это, что уже под трафиком
#   ops/deploy.sh --tag <SHA> --dry-run                напечатать шаги, ничего не делая
#   ops/deploy.sh --selftest                           проверка самого порядка шагов
#
# Зовут её кнопкой в браузере (.github/workflows/deploy.yml) — сюда она
# приезжает по ssh с уже посчитанным планом. Руками на стенде работает так же.
#
# РЕШЕНИЕ ВЛАДЕЛЬЦА от 14 сентября 2026 (задача 0112), дословно: «база всегда
# соответствует сборке которая едет на деплой, а если что то пошло не так
# то всё откатывается. То есть у нас должна быть атомарность по принципу всё
# катим новое или ничего». И уточнение того же дня: откатывается только
# приложение, база чинится вперёд. Отсюда шаги:
#
# ШАПКА ОТСТАВАЛА ОТ КОДА НА ШЕСТЬ ШАГОВ, и читают её перед выкладкой на ПРОМ.
# Объявлено было одиннадцать, и все одиннадцать действительно исполняются —
# а вот шесть исполняемых шагов не были названы вовсе, включая два, которые
# правят `.env` и применяют привезённые настройки. Нумерация 1–11 ниже
# НЕ СДВИНУТА намеренно: на эти номера ссылаются и комментарии этого файла
# («копия уже заморожена (шаг 7)»), и `ops/CLAUDE.md` («шагом 3 выкладки»), —
# сдвинув их, я починил бы одну поверхность, соврав в двух других. Поэтому
# шаги до заморозки названы своими номерами 0а–0е, как этот файл уже называет
# вход дымового прогона («── 0.» ниже по тексту).
#
#   0а. проверить состав монтируемых настроек        ops/config-guard.sh
#   0б. применить привезённые настройки              ops/apply-config.sh (0216)
#   0в. записать тег выкладываемой сборки в .env
#   0г. забрать образ из реестра
#   0д. проверить место под копию базы
#   0е. вход дымового прогона — ДО заморозки         ops/smoke-run.sh --login-only (0142)
#   1. заморозить запись в базе работающей сборки   (default_transaction_read_only)
#   2. снять с неё копию                              CREATE DATABASE … TEMPLATE
#   3. привести схему копии к версии образа           ops/schema-sync.sh
#   4. поднять новую сборку РЯДОМ, уже на копии
#   5. дождаться готовности                           /actuator/readiness
#   6. дымовая продажа по копии, прямо в сборку       ops/smoke-run.sh
#   7. заморозить и копию — на время переключения
#   8. перевести трафик                               ops/switch-build.sh
#   9. шесть самопроверок                             ops/deploy-checks.sh
#  10. ТОЧКА НЕВОЗВРАТА: открыть запись в копии, погасить старую сборку
#  11. прежнюю базу прошлой выкладки — удалить, и только если по сменившей
#      её базе уже снялся ночной дамп (задача 0117, уточнение 0214);
#      не удалили — назвать её и перечислить базы ячейки (задача 0195)
#
# ПОЧЕМУ ПРОДАЖА СТОИТ ШЕСТЫМ, А НЕ В САМОПРОВЕРКАХ (задача 0145). Пятая
# самопроверка доводит сценарий до денег — то есть ПИШЕТ, — а идут
# самопроверки внутри окна, где копия уже заморожена (шаг 7). Заморозка
# ставится на базу целиком и схем не различает, поэтому своя тестовая
# компания прогона (0144) от неё не спасает ничем: пишущие шаги не могли
# пройти там никогда, ровно как вход до 0142. Шаг 6 — единственное окно,
# где копия и поднята под новой сборкой, и ещё открыта на запись (схему
# на неё накатывали тем же порядком), а людей в ней нет: трафик на старой
# сборке, её база заморожена. И это ДО точки невозврата — упавшая продажа
# удаляется вместе с копией, трафик не двигается вовсе.
#
# Упавший шаг 2–9 возвращает всё: трафик — на старую сборку, копию — удаляет,
# запись в старой базе — открывает. Старая база за это время не менялась
# вовсе: запись в неё заморожена, а схему накатывали на копию.
#
# ЗАМОРОЗКА — ЦЕНА «НИЧЕГО НЕ ПОТЕРЯНО». Копию снимают в момент T, а старая
# сборка продолжает принимать работу: переключись мы на копию без заморозки,
# всё записанное после T исчезло бы молча — база цела, сходится сама с собой,
# просто в ней нет вечера. Поэтому с шага 1 запись не принимает никто: чтение
# работает, запись отвечает 503 «идёт обновление», офлайн-очередь приёмки
# повторяет сама. Копия замораживается тоже (шаг 6) — затем, чтобы запись
# не легла в базу, которую самопроверки ещё могут велеть удалить.
# Замораживает база, а не приложение: забытый в коде путь записи заморозку
# не обходит, а громко падает.
#
# ОТКАТ ПОСЛЕ ТОЧКИ НЕВОЗВРАТА — это выкладка прежнего образа тем же путём,
# без изменения схемы (--migrate-with none: база новее приложения — нормальное
# состояние, совместимость держит сторож 0116). Миграции вниз в выкладке нет:
# она уносит записанное людьми. Возврат к старой замороженной базе —
# инструмент первых минут, а не способ отменить релиз.
#
# КОГДА УДАЛЯЕТСЯ ПРЕЖНЯЯ БАЗА — решение владельца от 15 сентября 2026
# (задача 0117): после самопроверок выкладки И после того, как по сменившей
# её базе снялся бэкап. До первого бэкапа новой базы прежняя остаётся
# единственной полной копией данных на момент переключения, снятой вне
# архива WAL. Условие спрашивается у ОТМЕТОК бэкапа, а не подразумевается:
# «бэкап по расписанию стоит» и «бэкап по этой базе снялся» — разные
# утверждения. Не выполнено — база остаётся, и об этом сказано словами;
# убрать её потом, ничего не выкладывая, умеет ops/deploy.sh --drop-previous.
#
# БЭКАПОМ ЗДЕСЬ СЧИТАЕТСЯ НОЧНОЙ ДАМП, а не «дамп плюс базовая копия свежее
# него» — решение владельца от 28 сентября 2026 (задача 0214, вариант Б,
# дословно «давай б»). Прежнее условие при нынешнем расписании
# (ops/install-cron.sh: базовая копия «0 1 * * 0», дамп «0 3 * * *»)
# не выполнялось ВОВСЕ: отметку дампа ops/backup.sh обновляет каждую ночь,
# и она снова оказывается свежее недельной копии — то есть окно было два
# часа в неделю, и выкладка должна была попасть ровно в них. Каждая выкладка
# оставляла поэтому ровно одну замороженную базу, которую с этой минуты
# не называл ни один ключ .env (на боевой ячейке 28 сентября 2026 таких
# нашлось четыре, 86 МБ, — по одной на выкладку).
#
# Требование базовой копии снято ТОЛЬКО у ворот удаления. Точку возврата
# оно охраняет по-прежнему, и там не тронуто: за ней следят тревога
# БазоваяКопияНеСнималась (ops/alerts.yml) и недельная репетиция
# ops/restore-pitr.sh --verify. Основание — замер 28 сентября 2026: базовой
# копии, снятой ДО появления новой базы, плюс архива WAL хватает, чтобы
# воссоздать её накатом (CREATE DATABASE … STRATEGY FILE_COPY в журнал едет
# записью «скопировать каталог», и накат копирует каталог заново).
#
# ЧЕГО ЗДЕСЬ НЕТ. Репликации: копия — снимок, и запись стоит всё время
# подготовки (минуты), а не секунды переключения. Это шаг первый из двух,
# шаг второй назван в задаче 0112 вместе с пятью условиями надёжности.

